def _разбор(файл: Path) -> tuple[str, tuple | None]:
    """(вид файла из ВИДЫ, (картинка, маска, рамка, голова) — только у выреза). Одно место, где
    файл разбирается на приметы: им пользуются и `силуэт()`, и `что_видно()`, чтобы скрипт и
    его объяснение человеку не разошлись."""
    try:
        картинка = _открыть(Path(файл))
    except (OSError, ValueError):   # svg-заглушка витрины, битый файл — это не поломка, а ответ «не картинка»
        return "не-картинка", None
    маска = _альфа(картинка)
    if маска is None:
        return "фотография", None
    край = маска.getbbox()
    if not край:
        return "пусто", None
    if (край[2] - край[0]) > картинка.width * ДОЛЯ_СИЛУЭТА:
        return "мягкий-край", None
    г = голова(картинка, маска, край)
    return ("вырез-человека" if г else "вырез-без-головы"), (картинка, маска, край, г)


def силуэт(файл: Path) -> tuple | None:
    """(картинка, маска, рамка, голова) для настоящего выреза; фотография — None. Вырез узнаём по двум
    приметам сразу: прозрачные поля по краям (фигура уже кадра) и найденная голова. Фотография с мягким
    краем (`картинка--край` растворяет низ прямо в файле) прозрачные пиксели тоже имеет, но занимает
    почти весь кадр — её мы за вырез не принимаем и в рамку не тащим."""
    return _разбор(файл)[1]


def что_видно(файл: Path) -> str:
    """Одной фразой: что система увидела в файле. Фикс-раунд Ж, дело 3: вырез предмета, животного или
    знака голову по силуэту не даёт, рамка к нему не применяется — и раньше это проходило молча.
    Теперь скрипт называет увиденное словами, а схемы с вырезом добавляют, чего они ждали."""
    return ВИДЫ[_разбор(файл)[0]]


def фокус(файл: Path) -> tuple[int, int]:
    """Точка лица в процентах от картинки: у выреза с найденной головой — её середина по ширине и глаза
    (45 % высоты головы от макушки); у выреза без головы — старая прикидка по фигуре; у фото — ФОКУС_ФОТО.
    Значение идёт в data-лицо (слот {{ЛИЦО}}). У приведённого в рамку выреза оно всегда одно и то же —
    в этом и смысл приведения."""
    свой = силуэт(файл)
    if свой is None:
        return ФОКУС_ФОТО
    картинка, _, (л, в, п, н), г = свой
    if г:
        return (round(г["центр"] / картинка.width * 100),
                round((г["макушка"] + г["высота"] * ЛИЦО_В_ГОЛОВЕ) / картинка.height * 100))
    return (round((л + п) / 2 / картинка.width * 100), round((в + (н - в) * ДОЛЯ_ГОЛОВЫ) / картинка.height * 100))


def замеры_рамки(файл: Path) -> dict | None:
    """Что у этого выреза с рамкой: доли головы, макушки и лица в кадре и расхождение с контрактом.
    Не вырез или голова не нашлась — None (приводить нечего, мерить не по чему)."""
    свой = силуэт(файл)
    if свой is None or свой[3] is None:
        return None
    картинка, _, _, г = свой
    ш, в = картинка.size
    доли = {"голова": г["высота"] / в, "макушка": г["макушка"] / в, "лицо_x": г["центр"] / ш,
            "кадр": ш / в, "ширина_головы": г["ширина"] / ш}
    # всё расхождение меряем в одних единицах — долях самого кадра, поэтому и допуск один на все четыре
    доли["расхождение"] = max(abs(доли["голова"] - ГОЛОВА_В_РАМКЕ), abs(доли["макушка"] - МАКУШКА_В_РАМКЕ),
                              abs(доли["лицо_x"] - .5), abs(доли["кадр"] - РАМКА_ВЫРЕЗА[0] / РАМКА_ВЫРЕЗА[1]))
    доли["в_рамке"] = доли["расхождение"] <= ДОПУСК_РАМКИ
    return доли


def подбородок_в_кадре(файл: Path) -> float | None:
    """Доля высоты кадра, на которой кончается подбородок; голову по силуэту не видно — None.
    Это единственная мерка, которая говорит, наедет ли плашка «имя · опора» на подбородок:
    важна не сама голова, а то, как низко в кадре она кончается (ПОРОГ_ПОДБОРОДКА)."""
    свой = силуэт(файл)
    if свой is None or свой[3] is None:
        return None
    картинка, _, _, г = свой
    return г["подбородок"] / картинка.height


def доля_прозрачного(файл: Path) -> float:
    """Какую долю кадра занимает сквозная прозрачность. У фотографии альфы нет вовсе — 0; у выреза
    это фон вокруг фигуры; у фотографии с растворённым краем прозрачны только кромки."""
    try:
        картинка = _открыть(Path(файл))
    except (OSError, ValueError):
        return 0.0
    маска = _альфа(картинка)
    if маска is None:
        return 0.0
    точки = маска.tobytes()
    return sum(1 for в in точки if в < ПОРОГ_АЛЬФЫ) / len(точки)


def светлота_под_текстом(файл: Path) -> float | None:
    """Светлота полосы кадра, которая попадает под текст, — от 0 (чёрное) до 1 (белое).
    Кадр ужимаем до клеток (СЕТКА_СВЕТЛОТЫ) и берём среднее по полосе: одна клетка — это примерно
    буква заголовка, поэтому мелкий блик не перевешивает, а светлая стена за человеком — да.
    Файл не открывается картинкой — None (мерить не по чему)."""
    try:
        картинка = _открыть(Path(файл)).convert("L")
    except (OSError, ValueError):
        return None
    ш, в = картинка.size
    л, п, верх, низ = ПОЛОСА_ТЕКСТА
    полоса = картинка.crop((int(ш * л), int(в * верх), max(int(ш * л) + 1, int(ш * п)), max(int(в * верх) + 1, int(в * низ))))
    высота = max(1, round(СЕТКА_СВЕТЛОТЫ * полоса.height / полоса.width))
    клетки = полоса.resize((СЕТКА_СВЕТЛОТЫ, высота), Image.Resampling.BOX).tobytes()
    return sum(клетки) / len(клетки) / 255


def добор_затемнения(файл: Path) -> float:
    """Насколько плотнее макетного должно быть затемнение на этом кадре — число для css-переменной
    `--добор-затемнения` (слот `{{ДОБОР_ЗАТЕМНЕНИЯ}}`). Кадр не светлее макетного — 0, и схема
    встаёт ровно на макетных остановках; светлее — сверху ложится сплошная вуаль на долю добора."""
    светло = светлота_под_текстом(файл)
    if светло is None:
        return 0.0
    return round(min(ПРЕДЕЛ_ДОБОРА, max(0.0, (светло - СВЕТЛОТА_МАКЕТА) * ДОБОР_НА_СВЕТЛОТУ)), 2)


def крупность(файл: Path, умолчание: tuple[float, float] | None = None) -> tuple[float, float]:
    """(доля головы, доля макушки) в высоте кадра — два числа, от которых схемы с вырезом считают
    крупность фигуры (слоты `{{ГОЛОВА_В_КАДРЕ}}` и `{{МАКУШКА_В_КАДРЕ}}`, фикс-раунд Ж, дело 1).
    Голову по силуэту не видно (фотография, вырез предмета, заглушка) — отдаём `умолчание`: контракт
    рамки выреза или, у живого портрета, кадр его собственного макета. Стиль всё равно должен на
    что-то опереться, и опереться он должен на эталон схемы, а не на случайное число."""
    try:
        з = замеры_рамки(файл)
    except (OSError, ValueError):
        з = None
    return (з["голова"], з["макушка"]) if з else (умолчание or (ГОЛОВА_В_РАМКЕ, МАКУШКА_В_РАМКЕ))


def слоты_крупности(файл: Path) -> str:
    """Строка для человека и для того, кто верстает экран: что вписать в слоты крупности."""
    голова_доля, макушка_доля = крупность(файл)
    return (f"Крупность: голова {голова_доля:.3f}, макушка {макушка_доля:.3f} — это значения слотов "
            "{{ГОЛОВА_В_КАДРЕ}} и {{МАКУШКА_В_КАДРЕ}} (орбита, центр, живой портрет считают от них "
            "высоту кадра в схеме; ядро/блоки.md § 3)")


def близкий_кадр(файл: Path) -> str:
    """Фикс-раунд Ж, дело 2. Схемы с плашкой под лицом («разворот») требуют кадра с запасом над
    головой. У выреза это измеримо — говорим замером; у обычной фотографии силуэта нет и голову
    система не видит — тогда честно просим человека проверить кадр самому, а не молчим.
    Пустая строка — измерили и всё в порядке."""
    низ = подбородок_в_кадре(файл)
    if низ is None:
        return f"крупность головы я здесь не вижу ({что_видно(файл)}). Проверьте кадр сами: {ЗАПАС_НАД_ГОЛОВОЙ}"
    if низ > ПОРОГ_ПОДБОРОДКА:
        return (f"кадр слишком близкий: подбородок на {round(низ * 100)} % высоты кадра "
                f"(дальше {round(ПОРОГ_ПОДБОРОДКА * 100)} % плашка с именем встаёт на него) — "
                "дайте снимок с запасом над головой")
    return ""


СХЕМЫ_ПЛАШКИ = ("разворот", "разворот-слева")   # плашка «имя · опора» (`чип--автор`) встаёт под лицом
СХЕМЫ_ВЫРЕЗА = ("вырез", "живой-портрет")       # значения data-картинка, где схема считает крупность от головы
# Фикс-раунд И, замечание 4: обратная примета. Этим схемам нужна ФОТОГРАФИЯ с фоном — прямоугольный
# кадр, который они растворяют по краям виньеткой. Вырез на прозрачном фоне в них читается наклейкой:
# растворять нечего, человек висит в пустоте. Правило владелицы: фон подбирают, а не вырезают, и
# вырез остаётся только там, где схема без него не работает (орбита, центр, живой портрет).
# Ловим именно дырку в кадре, а не «вырез» из `ВИДЫ`: наш собственный старый `portret-3x4.webp`
# силуэтом не считался (фигура шире ДОЛЯ_СИЛУЭТА, вид — «мягкий-край»), а прозрачного фона в нём
# треть кадра. У настоящей фотографии альфы нет вовсе, у фотографии с растворённым краем прозрачны
# только кромки — десятой части кадра там не набирается.
СХЕМЫ_ФОТО = ("фото", "сцена", "видео", "видео-с-голосом", "товар", "мозаика")
ПОРОГ_ПРОЗРАЧНОГО = .10


def находки_кадра(схема: str, тип: str, файл: Path, кадр_телефона: Path | None = None,
                  наш_пример: bool = False) -> list[dict]:
    """Что не так с этим кадром под эту схему — словами человека, одной формулировкой на оба пути.

    Фикс-раунд Ж (дела 2 и 3). Живёт здесь, а не в витрине обложек, потому что говорить об этом
    надо в обоих местах: и когда человек выбирает схему на витрине, и когда собирает сайт напрямую
    (`собрать.py`) — витрина нужна только чтобы выбрать, а зовут потом сборку. Формулировка одна,
    чтобы человек не гадал, одно это предупреждение или два разных.

    • дело 3 — схемам с вырезом (орбита, центр, живой портрет) нужен вырез ЧЕЛОВЕКА: крупность
      фигуры в них считается от головы; вырез предмета или обычное фото встанет случайной величины;
    • дело 2 — схемам с плашкой «имя · опора» (развороты) нужен кадр с запасом над головой.
      На вырезе это измеримо, на обычной фотографии силуэта нет — тогда честно просим человека
      проверить кадр самому — и на витрине обложек, и на обычной сборке. Не просим только у
      нашего примера в каталоге (`наш_пример`): там кадр наш, а не чья-то работа.
    """
    файл = Path(файл)
    найденное: list[dict] = []
    if not файл.is_file():
        return найденное
    if тип in СХЕМЫ_ВЫРЕЗА:
        if рамка_выреза(файл)["вид"] != "вырез-человека":   # без «куда» — только меряет, файла не пишет
            найденное.append(находка(
                ПОПРАВИТЬ, f"Схеме «{схема}» нужен вырез человека",
                [f"{файл.name}: {что_видно(файл)}"],
                "крупность фигуры эта схема считает от головы — головы нет, и кадр встанет случайной "
                "величины: дайте вырез человека (PNG с прозрачностью) или выберите схему без выреза"))
    if тип in СХЕМЫ_ФОТО and доля_прозрачного(файл) > ПОРОГ_ПРОЗРАЧНОГО:
        найденное.append(находка(
            ПОПРАВИТЬ, f"Схеме «{схема}» нужна фотография, а не вырез",
            [f"{файл.name}: прозрачный фон занимает {round(доля_прозрачного(файл) * 100)} % кадра"],
            "эта схема показывает прямоугольный кадр и сама растворяет его края — у выреза "
            "растворять нечего, фигура повиснет в пустоте: дайте обычный снимок с фоном "
            "(фон подбирают, а не вырезают) или выберите схему, которая строится вокруг выреза "
            "(орбита, центр, живой портрет)"))
    if схема in СХЕМЫ_ПЛАШКИ:
        # меряем тот кадр, который увидит телефон: у разворота это `-telefon`, если он уже сделан
        кадр = Path(кадр_телефона) if кадр_телефона and Path(кадр_телефона).is_file() else файл
        близко = близкий_кадр(кадр)
        измеримо = подбородок_в_кадре(кадр) is not None
        if близко and (измеримо or not наш_пример):
            найденное.append(находка(
                ПОПРАВИТЬ if измеримо else К_СВЕДЕНИЮ, f"Кадр для схемы «{схема}» может быть слишком близким",
                [f"{кадр.name}: {близко}"],
                "плашка с именем стоит под лицом; кадр «голова и плечи во весь кадр» подводит её к "
                "подбородку — возьмите снимок пошире или схему без плашки (сцена, бенто, орбита)"))
    return найденное


def _растворить_низ(картинка: Image.Image, маска: Image.Image, рамка: tuple) -> Image.Image:
    """Вырез, обрезанный по пояс или по грудь, кончается ровной чертой — в схеме она читается обрубком.
    Если нижний ряд фигуры широкий (это срез, а не ноги), гасим альфу линейно на РАСТВОР_НИЗА её высоты."""
    л, в, п, н = рамка
    низ = маска.crop((0, н - 1, маска.width, н)).getbbox()
    if not низ or (низ[2] - низ[0]) < (п - л) * .6:
        return картинка
    высота = max(2, int((н - в) * РАСТВОР_НИЗА))
    альфа = картинка.getchannel("A")
    градиент = Image.linear_gradient("L").resize((картинка.width, высота))   # 0 сверху → 255 снизу
    кусок = ImageChops.multiply(альфа.crop((0, н - высота, картинка.width, н)),
                                градиент.transpose(Image.Transpose.FLIP_TOP_BOTTOM))
    альфа.paste(кусок, (0, н - высота))
    картинка.putalpha(альфа)
    return картинка


def рамка_выреза(файл: Path, куда: Path | None = None) -> dict:
    """Любой вырез — к одной рамке: обрезать прозрачные поля, смерить голову, увеличить или уменьшить так,
    чтобы голова заняла ГОЛОВА_В_РАМКЕ высоты кадра, и поставить макушку на МАКУШКА_В_РАМКЕ, а лицо —
    посередине по ширине. Отдаёт {'путь', 'приведено', 'замеры', 'предупреждение'}; `куда` не задана —
    только меряет, файла не пишет. Голову не нашли или это фотография — приводить нечего, `приведено` False."""
    файл = Path(файл)
    вид, свой = _разбор(файл)
    замеры = замеры_рамки(файл)
    if свой is None or свой[3] is None:
        # Фикс-раунд Ж, дело 3: раньше здесь на все три случая была одна глухая строка «не вырез или
        # голову не видно». Теперь говорим, что именно увидели и чего ждали, — иначе вырез предмета
        # уходит в схему с нетронутой рамкой и человек узнаёт об этом только по готовому сайту.
        ждали = ("Схемы «орбита», «центр» и «живой портрет» строятся вокруг человека: крупность фигуры "
                 "в них считается от головы. Головы нет — крупность выйдет случайной: возьмите вырез "
                 "человека или выберите схему, которой вырез не нужен (разворот, сцена, товар крупно).")
        return {"путь": файл, "приведено": False, "замеры": замеры, "вид": вид,
                "предупреждение": f"{ВИДЫ[вид]}. Рамку не трогаю. {ждали}"}
    if замеры and замеры["в_рамке"]:
        return {"путь": файл, "приведено": False, "замеры": замеры, "вид": вид, "предупреждение": ""}
    картинка, маска, край, г = свой
    картинка = _растворить_низ(картинка.copy(), маска, край)
    ширина_рамки, высота_рамки = ШИРИНА_РАМКИ, round(ШИРИНА_РАМКИ * РАМКА_ВЫРЕЗА[1] / РАМКА_ВЫРЕЗА[0])
    масштаб = ГОЛОВА_В_РАМКЕ * высота_рамки / г["высота"]
    предупреждение = ""
    предел = ширина_рамки * (1 - 2 * ПОЛЯ_РАМКИ) / (край[2] - край[0])
    if масштаб > предел:      # фигура развела руки шире рамки — уменьшаем, иначе схема «центр» срежет кисти
        предупреждение = (f"фигура шире рамки: уменьшил ещё на {round((1 - предел / масштаб) * 100)} % — "
                          "голова вышла мельче эталона; лучше прислать вырез, где руки ближе к телу")
        масштаб = предел
    новый = картинка.resize((max(1, round(картинка.width * масштаб)), max(1, round(картинка.height * масштаб))),
                            Image.Resampling.LANCZOS)
    холст = Image.new("RGBA", (ширина_рамки, высота_рамки), (0, 0, 0, 0))
    сдвиг_x = round(ширина_рамки * .5 - г["центр"] * масштаб)
    сдвиг_y = round(высота_рамки * МАКУШКА_В_РАМКЕ - г["макушка"] * масштаб)
    холст.alpha_composite(новый, dest=(max(0, сдвиг_x), max(0, сдвиг_y)),
                          source=(max(0, -сдвиг_x), max(0, -сдвиг_y)))
    if куда is None:
        return {"путь": файл, "приведено": True, "замеры": замеры, "вид": вид, "предупреждение": предупреждение}
    куда = Path(куда)
    куда.mkdir(parents=True, exist_ok=True)
    основа = имя_латиницей(файл.stem)
    путь = куда / ((основа if основа.endswith("-vyrez") else основа + "-vyrez") + ".png")
    холст.save(путь, "PNG")
    return {"путь": путь, "приведено": True, "замеры": замеры_рамки(путь), "вид": вид, "предупреждение": предупреждение}


def кроп_телефон(файл: Path, куда: Path, точка: tuple[int, int] | None = None) -> Path:
    """Кроп 9:16 под телефон: лицо на 28 % высоты окна, ширина ≤ 900 → <имя>-telefon.webp (слот {{ФОТО_ТЕЛЕФОН}})."""
    файл, куда = Path(файл), Path(куда)
    картинка = _открыть(файл)
    x, y = точка or фокус(файл)
    ш, в = картинка.size
    пш, пв = ПРОПОРЦИЯ_ТЕЛЕФОНА
    окно_ш, окно_в = (ш, ш * пв / пш) if ш / в < пш / пв else (в * пш / пв, в)
    лево = min(max(x / 100 * ш - ЛИЦО_В_ОКНЕ[0] / 100 * окно_ш, 0), ш - окно_ш)
    верх = min(max(y / 100 * в - ЛИЦО_В_ОКНЕ[1] / 100 * окно_в, 0), в - окно_в)
    центр = (лево / (ш - окно_ш) if ш > окно_ш else .5, верх / (в - окно_в) if в > окно_в else .5)
    итог_ш = min(ШИРИНА_ТЕЛЕФОНА, int(окно_ш))
    итог = ImageOps.fit(картинка, (итог_ш, int(итог_ш * пв / пш)), centering=центр, method=Image.Resampling.LANCZOS)
    куда.mkdir(parents=True, exist_ok=True)
    путь = куда / f"{имя_латиницей(файл.stem)}-telefon.webp"
    итог.save(путь, "WEBP", quality=КАЧЕСТВО, method=6)
    return путь


def касается_краёв(файл: Path, порог: int = 8) -> list[str]:
    """Схема «центр»: фигура не должна упираться в левый, верхний и правый края (низ — можно и нужно).
    Не вырез — ["не вырез"]. У приведённого в рамку выреза список всегда пуст: поля держит ПОЛЯ_РАМКИ."""
    свой = силуэт(файл)
    if свой is None:
        return ["не вырез"]
    картинка, _, рамка, _ = свой
    л, в, п, _ = рамка
    return [имя for имя, беда in (("слева", л < порог), ("сверху", в < порог), ("справа", п > картинка.width - порог)) if беда]


def вырез(файл: Path, куда: Path) -> Path | None:
    """Фон долой через rembg (необязательная зависимость) → <имя>-vyrez.png; без rembg — None."""
