def _альфа(картинка: Image.Image):
    """Маска непрозрачного (альфа выше порога); у картинки без альфы — None, полностью непрозрачная RGBA — тоже фото."""
    if картинка.mode != "RGBA":
        return None
    альфа = картинка.getchannel("A")
    if альфа.getextrema()[0] > ПОРОГ_АЛЬФЫ:   # ни одного прозрачного пикселя: PNG из Preview, Figma, скриншот
        return None
    return альфа.point(lambda а: 255 if а > ПОРОГ_АЛЬФЫ else 0)


def _рамка(файл: Path) -> tuple[Image.Image, tuple | None]:
    картинка = _открыть(Path(файл))
    маска = _альфа(картинка)
    return картинка, (маска.getbbox() if маска is not None else None)


def _полосы(маска: Image.Image, рамка: tuple) -> list[tuple | None]:
    """По строке на каждый ряд фигуры: (левая кромка, правая) или None у пустого ряда."""
    полосы = []
    for y in range(рамка[1], рамка[3]):
        край = маска.crop((0, y, маска.width, y + 1)).getbbox()
        полосы.append((край[0], край[2]) if край else None)
    return полосы


def голова(картинка: Image.Image, маска: Image.Image, рамка: tuple) -> dict | None:
    """Голова по силуэту: сверху вниз ширина растёт (череп), сужается на шее и снова растёт на плечах.
    Возвращает макушку, подбородок (он же шея), высоту головы и её середину по ширине — или None,
    когда впадины-шеи нет (силуэт без головы: коробка-заглушка, товар, кадр с мягким краем)."""
    полосы = _полосы(маска, рамка)
    ширины = [(п[1] - п[0]) if п else 0 for п in полосы]
    if len(ширины) < 20:
        return None
    пик = пик_i = 0
    for i, ш in enumerate(ширины):
        if ш > пик:
            пик, пик_i = ш, i
        elif пик >= 8 and ш <= пик * .88:          # началось сужение — ищем дно впадины (шею)
            дно, дно_i = ш, i
            for j in range(i + 1, len(ширины)):
                if ширины[j] <= дно:
                    дно, дно_i = ширины[j], j
                elif ширины[j] > дно * 1.15:       # снова расширяется — это плечи, шея позади
                    полоса = полосы[пик_i]
                    return {"макушка": рамка[1], "подбородок": рамка[1] + дно_i, "высота": дно_i,
                            "ширина": пик, "центр": (полоса[0] + полоса[1]) // 2}
            return None
    return None


