def разобрать_регион(запись: str | None) -> tuple[int | None, str]:
    """«Москва» → (213, «Москва»), «все» → (None, «все регионы»), «213» → (213, «регион 213»)."""
    текст = (запись or "все").strip()
    ключ = текст.lower().replace("ё", "е")
    if ключ.isdigit():
        return int(ключ), f"регион {ключ}"
    if ключ in РЕГИОНЫ:
        код = РЕГИОНЫ[ключ]
        return код, ("все регионы" if код is None else текст)
    известные = ", ".join(sorted(к for к in РЕГИОНЫ if " " not in к))
    raise кисть.БедаВвода(
        f"не знаю регион «{текст}». Знаю: {известные} — или задайте код региона Яндекса числом "
        "(его видно в адресе страницы Вордстата после выбора региона: region=…).")


def адрес_запроса(запрос: str, регион: int | None) -> str:
    части = {"view": "table", "words": запрос}
    if регион is not None:
        части = {"region": str(регион), **части}
    return ВОРДСТАТ + "?" + urllib.parse.urlencode(части, quote_via=urllib.parse.quote)


# ── чистый разбор страницы: текст или HTML → числа ───────────────────────────
ЧИСЛО = r"\d{1,3}(?:[    ]\d{3})+|\d+"
СТРОКА_ТАБОМ = re.compile(r"^(?P<фраза>[^\t]*\S)\t+(?:[^\t]*\t+)*(?P<число>" + ЧИСЛО + r")$")
СТРОКА_ПРОБЕЛОМ = re.compile(r"^(?P<фраза>.*?\S)\s+(?P<число>" + ЧИСЛО + r")$")
ТОЛЬКО_ЧИСЛО = re.compile(r"^(?:" + ЧИСЛО + r")$")
ВСЕГО_В_СТРОКЕ = re.compile(
    r"(?:(?:общ\w*\s+)?(?:число|количество|частота)(?:\s+(?:запросов|показов))?|"
    r"(?:показ\w*|запрос\w*)\s+в\s+месяц)\s*[:—–-]?\s*(?P<число>" + ЧИСЛО + r")?\s*$", re.I)
ЧИСЛО_В_МЕСЯЦ = re.compile(r"(?P<число>" + ЧИСЛО + r")\s*(?:показ\w*|запрос\w*)\s+в\s+месяц", re.I)
ЗАГОЛОВОК_ПОХОЖИХ = re.compile(r"похож", re.I)
ЗАГОЛОВОК_С_ФРАЗОЙ = re.compile(r"популярн|со\s*слов|запросы\s+со$|с\s+фраз|содерж|включа|все\s+запросы", re.I)
КОНЕЦ_ТАБЛИЦЫ = re.compile(r"^при\s+использовании\s+материалов", re.I)
# Живая страница (проверено 03.10.2026): общая цифра стоит строкой «за 31.08.2026 – 29.09.2026: 424»
# над таблицей. Для запроса в кавычках это и есть точная частота, а первая строка таблицы под ней
# всё равно показывает широкую — поэтому эта строка главнее таблицы.
ЗА_ПЕРИОД = re.compile(r"^за\s+\d{1,2}\.\d{1,2}\.\d{4}\s*[–—-]\s*\d{1,2}\.\d{1,2}\.\d{4}\s*:\s*(?P<число>"
                       + ЧИСЛО + r")$", re.I)
НЕТ_ДАННЫХ = re.compile(r"нет\s+данных|ничего\s+не\s+найден|не\s+найдено\s+запросов|"
                        r"недостаточно\s+данных", re.I)
КАПЧА_ТЕКСТ = re.compile(r"я\s+не\s+робот|вы\s+не\s+робот|подтвердите,?\s+что\s+запросы\s+"
                         r"отправляли\s+вы|smartcaptcha|showcaptcha", re.I)
ПРОСЯТ_ВОЙТИ = re.compile(r"войдите,?\s+чтобы|войдите\s+в\s+(?:аккаунт|яндекс)|"
                          r"авторизуйтесь|войти\s+(?:с|через)\s+яндекс\s*id", re.I)


def число(запись: str) -> int:
    return int(re.sub(r"\D", "", запись))


def вид_фразы(фраза: str) -> str:
    """Фраза для сравнения: без регистра, ё = е, без операторов Вордстата и лишних пробелов."""
    текст = (фраза or "").lower().replace("ё", "е")
    текст = re.sub(r"[\"«»“”„!+\[\]()|]", " ", текст)
    return " ".join(текст.split())


def html_в_текст(разметка: str) -> str:
    """HTML → текст, как его видит человек: ячейки через таб, строки и блоки с новой строки."""
    текст = re.sub(r"(?is)<(script|style|noscript)\b.*?</\1>", " ", разметка)
    текст = re.sub(r"(?i)</t[dh]\s*>", "\t", текст)
    текст = re.sub(r"(?i)<br\s*/?>|</(?:tr|p|div|li|h[1-6]|section|header|thead|tbody|table|ul|ol)\s*>",
                   "\n", текст)
    текст = re.sub(r"(?s)<[^>]+>", "", текст)
    текст = html.unescape(текст)
    строки = [re.sub(r"[  ]*\t[  \t]*", "\t", с).strip("  \t") for с in текст.splitlines()]
    return "\n".join(строки)


def _строка_с_числом(строка: str) -> tuple[str, int] | None:
    for образец in (СТРОКА_ТАБОМ, СТРОКА_ПРОБЕЛОМ):
        найдено = образец.match(строка)
        if найдено and re.search(r"[^\W\d_]", найдено.group("фраза")):
            return найдено.group("фраза").strip(), число(найдено.group("число"))
    return None


def разобрать_выдачу(страница: str, фраза: str, похожих: int = ПОХОЖИХ) -> dict:
    """Текст страницы Вордстата (или её HTML) → числа. Чистая функция, без браузера.

    Опирается на текст и устройство таблицы, а не на имена классов: классы у Яндекса
    сгенерированные и меняются с каждой выкладкой, а слова и порядок «фраза — число» живут годами.

    Возвращает {"всего": int | None, "с_фразой": [(фраза, число)], "похожие": [(фраза, число)],
    "нет_данных": bool}. «всего» — сколько раз в месяц ищут фразу: либо из строки «Число
    запросов …», либо из строки таблицы, где стоит сама фраза. Не нашлось — None, а не догадка.
    """
    текст = html_в_текст(страница) if re.search(r"<(?:html|body|div|table|tr|td)\b", страница or "", re.I) \
        else (страница or "")
    строки = [re.sub(r" ?\t[ \t]*", "\t", re.sub(r"[ \u00a0]+", " ", с)).strip(" \t")
              for с in текст.splitlines()]
    строки = [с for с in строки if с]
    искомая = вид_фразы(фраза)
    всего: int | None = None
    раздел: str | None = None
    с_фразой: list[tuple[str, int]] = []
    похожие: list[tuple[str, int]] = []
    без_раздела: list[tuple[str, int]] = []
    ждём_число_всего = False
    i = 0
    while i < len(строки):
        строка = строки[i]
        следующая = строки[i + 1] if i + 1 < len(строки) else ""
        if ждём_число_всего:
            ждём_число_всего = False
            if ТОЛЬКО_ЧИСЛО.match(строка) and всего is None:
                всего = число(строка)
                i += 1
                continue
        if КОНЕЦ_ТАБЛИЦЫ.match(строка):
            break                  # дальше подвал Яндекса: «Напишите нам», справка — не запросы
        за_период = ЗА_ПЕРИОД.match(строка)
        if за_период:
            всего = число(за_период.group("число"))
            раздел = "с_фразой"    # выше — вкладки-меню; под строкой идёт «Запросы со словами»
            i += 1
            continue
        в_месяц = ЧИСЛО_В_МЕСЯЦ.search(строка)
        if в_месяц and всего is None and "\t" not in строка:
            всего = число(в_месяц.group("число"))
            i += 1
            continue
        найдено_всего = ВСЕГО_В_СТРОКЕ.search(строка)
        if найдено_всего and "\t" not in строка:
            if найдено_всего.group("число"):
                всего = всего if всего is not None else число(найдено_всего.group("число"))
            else:
                ждём_число_всего = True
            i += 1
            continue
        пара = _строка_с_числом(строка)
        if пара is None and not ТОЛЬКО_ЧИСЛО.match(строка) and ТОЛЬКО_ЧИСЛО.match(следующая) \
                and re.search(r"[^\W\d_]", строка) and not (ЗАГОЛОВОК_ПОХОЖИХ.search(строка)
                                                         or ЗАГОЛОВОК_С_ФРАЗОЙ.search(строка)):
            пара = (строка, число(следующая))       # фраза и число — в соседних строках
            i += 1
        if пара is None:
            # Заголовок раздела: строка без числа. Подпись вкладки («Похожие») заголовком не
            # считаем, если сразу за ней снова заголовок, а не строка таблицы.
            if ЗАГОЛОВОК_ПОХОЖИХ.search(строка) and len(строка) < 80:
                раздел = "похожие"
            elif ЗАГОЛОВОК_С_ФРАЗОЙ.search(строка) and len(строка) < 80:
                раздел = "с_фразой"
            i += 1
            continue
        if всего is None and вид_фразы(пара[0]) == искомая:
            всего = пара[1]
        if раздел == "похожие":
            куда = похожие
        elif раздел == "с_фразой":
            куда = с_фразой
        else:
            куда = без_раздела
        if all(вид_фразы(п[0]) != вид_фразы(пара[0]) for п in куда):
            куда.append(пара)
        i += 1
    # Заголовков не нашлось вовсе — делим по смыслу: строки с ВСЕМИ словами фразы — «с фразой»,
    # остальные — похожие. Грубее заголовков, но лучше, чем свалить всё в одну кучу.
    if без_раздела:
        слова = искомая.split()
        for пара in без_раздела:
            вид = вид_фразы(пара[0])
            if вид == искомая:
                continue
            (с_фразой if all(с in вид.split() for с in слова) else похожие).append(пара)
    с_фразой = [п for п in с_фразой if вид_фразы(п[0]) != искомая]
    return {"всего": всего, "с_фразой": с_фразой[:похожих], "похожие": похожие[:похожих],
            "нет_данных": всего is None and bool(НЕТ_ДАННЫХ.search(текст))}

ШАПКА_ПОХОЖИХ = re.compile(r"запросы,?\s+похожие\s+на", re.I)


def разобрать_похожие(страница: str, похожих: int = ПОХОЖИХ) -> list[tuple[str, int]]:
    """Текст вкладки «Похожие» → [(запрос, число)]. Чистая функция, без браузера.

    Вкладка (проверено живьём 03.10.2026) не живёт в адресе: `view=associations` Вордстат
    игнорирует, она открывается только щелчком. На ней нет строки «за …: N», а шапка —
    «Запросы, похожие на <фраза>, за период …». Строки до шапки — меню, после неё — таблица
    «запрос — число» до подвала Яндекса. Шапки нет — пусто, а не догадка.
    """
    текст = html_в_текст(страница) if re.search(r"<(?:html|body|div|table|tr|td)\b", страница or "", re.I) \
        else (страница or "")
    строки = [re.sub(r" ?\t[ \t]*", "\t", re.sub(r"[ \u00a0]+", " ", с)).strip(" \t")
              for с in текст.splitlines()]
    строки = [с for с in строки if с]
    начало = next((i for i, с in enumerate(строки) if ШАПКА_ПОХОЖИХ.search(с)), None)
    if начало is None:
        return []
    итог: list[tuple[str, int]] = []
    for строка in строки[начало + 1:]:
        if КОНЕЦ_ТАБЛИЦЫ.match(строка):
            break
        пара = _строка_с_числом(строка)
        if пара is not None and all(вид_фразы(п[0]) != вид_фразы(пара[0]) for п in итог):
            итог.append(пара)
    return итог[:похожих]


# ── что на странице: решение ─────────────────────────────────────────────────
КАПЧА = "капча"
НЕ_ВОШЛИ = "не вошли"
РЕЗУЛЬТАТ = "результат"
ПУСТО = "нет данных"
ЖДЁМ = "ждём"


def что_на_странице(адрес: str, текст: str, фраза: str) -> str:
    """Капча, не вошли, результат, «нет данных» или ещё грузится — по адресу и тексту страницы.

    Капча старше всего: на её странице нет ни чисел, ни входа, и спутать её с «вошли, но пусто»
    значило бы записать человеку «не снялось» там, где нужно его одно нажатие.
    """
    адрес = (адрес or "").lower()
    текст = текст or ""
    if "showcaptcha" in адрес or "/captcha" in адрес or КАПЧА_ТЕКСТ.search(текст):
        return КАПЧА
    хост = urllib.parse.urlparse(адрес).hostname or ""
    if хост.startswith("passport."):
        return НЕ_ВОШЛИ
    разбор = разобрать_выдачу(текст, фраза)
    if разбор["всего"] is not None:
        return РЕЗУЛЬТАТ
    if ПРОСЯТ_ВОЙТИ.search(текст):
        return НЕ_ВОШЛИ
    if разбор["нет_данных"]:
        return ПУСТО
    return ЖДЁМ


