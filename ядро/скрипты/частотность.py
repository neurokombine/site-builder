ЭПОХА_CHROME = 11_644_473_600          # секунд между 1601-01-01 и 1970-01-01


def кука_яндекса(профиль: Path = кисть.ПРОФИЛЬ, сейчас: float | None = None) -> str | None:
    """Есть ли в профиле кука входа Яндекса: «жива» · «истекла» · «нет» · None (не прочитать).

    Имена кук и сроки в базе Chrome лежат открыто (зашифрованы только значения), поэтому
    вопрос «входили ли в Яндекс» решается без окна. Базу копируем во временную папку: живой
    Chrome держит её занятой.
    """
    сейчас_chrome = ((сейчас if сейчас is not None else time.time()) + ЭПОХА_CHROME) * 1_000_000
    for база in (профиль / "Default" / "Network" / "Cookies", профиль / "Default" / "Cookies"):
        if not база.exists():
            continue
        try:
            with tempfile.TemporaryDirectory() as врем:
                копия = Path(врем) / "Cookies"
                shutil.copy2(база, копия)
                for хвост in ("-wal", "-journal"):
                    рядом = база.with_name(база.name + хвост)
                    if рядом.exists():
                        shutil.copy2(рядом, копия.with_name(копия.name + хвост))
                связь = sqlite3.connect(f"file:{копия}?mode=ro", uri=True)
                try:
                    ряды = связь.execute(
                        "select expires_utc, has_expires from cookies "
                        "where name = ? and host_key like '%yandex.%'", (КУКА_ВХОДА,)).fetchall()
                finally:
                    связь.close()
        except (OSError, sqlite3.Error):
            return None
        if not ряды:
            return "нет"
        return "жива" if any(not есть_срок or срок > сейчас_chrome for срок, есть_срок in ряды) \
            else "истекла"
    return "нет"


def метка_входа(журнал: Path = ЖУРНАЛ) -> bool:
    try:
        return журнал.exists() and МЕТКА_ВХОДА in журнал.read_text(encoding="utf-8")
    except OSError:
        return False


def яндекс_по_следам(профиль: Path = кисть.ПРОФИЛЬ, журнал: Path = ЖУРНАЛ, кука=None) -> str:
    кука = кука_яндекса if кука is None else кука
    что = кука(профиль)
    был = метка_входа(журнал)
    if что == "жива":
        return ЯНДЕКС_ГОТОВ
    if что == "истекла":
        return ЯНДЕКС_ВХОД_УМЕР
    if что is None:                       # базу не прочитать — верим своей метке
        return ЯНДЕКС_ГОТОВ if был else ЯНДЕКС_НЕ_ВХОДИЛИ
    return ЯНДЕКС_ВХОД_УМЕР if был else ЯНДЕКС_НЕ_ВХОДИЛИ


def состояние_канала(найти=None, профиль: Path = кисть.ПРОФИЛЬ, журнал: Path = ЖУРНАЛ,
                     замок: Path = кисть.ЗАМОК, кука=None) -> str:
    """Что с каналом для Вордстата — по диску, без окна.

    Браузер и замок — общие с кистью, и спрашиваем их у кисти (`кисть.состояние_канала`):
    логика одна. Вход в ChatGPT Вордстату не нужен, поэтому дальше вместо него смотрим вход в
    Яндекс — по куке Яндекс ID в том же профиле и по своей метке удавшегося `--вход`.
    """
    общее = кисть.состояние_канала(найти=найти, профиль=профиль, замок=замок)
    if общее in (кисть.НЕТ_БРАУЗЕРА, кисть.ПУТЬ_МИМО, кисть.ЗАНЯТО):
        return общее
    return яндекс_по_следам(профиль, журнал, кука)


