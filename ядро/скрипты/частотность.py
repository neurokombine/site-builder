def команда_проверь(порт: int | None) -> int:
    if not кисть.занять_замок():
        печатать(кисть.ЗАНЯТО)
        return КОД_БЕДА
    try:
        живой = кисть.порт_браузера(порт)
        with кисть.подключение(живой) as контекст:
            страница = открыть_вордстат(контекст)
            try:
                страница.wait_for_timeout(3000)
                что = вошли_живьём(страница, контекст)
                if что == "есть":
                    print(f"✅ вход в Яндекс на месте — система может снимать частотность (порт {живой})")
                    return 0
                if что == "капча":
                    печатать(КАПЧА)
                    return КОД_КАПЧА
                if что == "нет":
                    print(str(беда_входа()))
                    return КОД_НУЖЕН_ВХОД
                печатать(кисть.СЕТЬ)
                return КОД_НЕ_ГОТОВО
            finally:
                страница.close()
    finally:
        кисть.отпустить_замок()


def команда_вход(минут: int, порт: int | None) -> int:
    """Открыть окно на Вордстате и ждать. Пароль система не видит — вход только руками."""
    if not кисть.занять_замок():
        печатать(кисть.ЗАНЯТО)
        return КОД_БЕДА
    try:
        живой = кисть.порт_браузера(порт)
        with кисть.подключение(живой) as контекст:
            страница = открыть_вордстат(контекст)
            print(f"🖥  окно Chrome открыто на Вордстате (порт {живой}). Войдите в Яндекс своими руками —")
            print("    логин и пароль система не видит и не подставляет. Окно не закрывайте.")
            # Строка поиска видна и без входа — человек решает, что входить не надо. Вход Вордстат
            # просит только на первом запросе (проверено живьём 03.10.2026), поэтому говорим это прямо.
            print("    Строка поиска открывается и без входа — наберите в ней любое слово и нажмите поиск:")
            print("    тогда Яндекс попросит войти. Без входа цифр Вордстат не показывает.")
            print(f"    Жду до {минут} мин, проверяю раз в 10 с.")
            край = time.monotonic() + минут * 60
            while time.monotonic() < край:
                if вошли_живьём(страница, контекст) == "есть":
                    кисть.записать_журнал({"вход в Яндекс": "выполнен руками"}, журнал=ЖУРНАЛ)
                    print(f"✅ вход в Яндекс выполнен, он сохранён в окне системы ({кисть.ПРОФИЛЬ.name})")
                    страница.close()
                    return 0
                time.sleep(10)
            print(f"⏰ время вышло, вход не завершён. Окно оставляю открытым — войдите и "
                  f"запустите проверку: {ПРОВЕРИТЬ_ВХОД}")
            страница.close()
            return КОД_НУЖЕН_ВХОД
    finally:
        кисть.отпустить_замок()


def команда_фразы(фразы: list[str], регион: str | None, работа: str | None, точная: bool,
                  порт: int | None) -> int:
    фразы = проверить_фразы(фразы)
    код_региона, подпись = разобрать_регион(регион)
    папка = проверить_работу(работа)
    print(f"снимаю {len(фразы)} фраз(ы), {подпись}; пауза между запросами 2–4 с…")
    try:
        итоги = снять(фразы, код_региона, точная=точная, порт=порт)
        код = 0
    except Капча as беда:
        итоги = getattr(беда, "итоги", [])
        код = КОД_КАПЧА
    когда = datetime.now(МСК)
    if итоги:
        print()
        print(таблица(итоги, подпись, когда))
    снято = sum(1 for с in итоги if с["всего"] is not None or с["точно"] is not None)
    if папка is not None and снято:
        поиск = дописать_в_поиск(папка, итоги, подпись, когда)
        дописать_в_журнал(папка, итоги, подпись, когда)
        print(f"\n→ записано в {поиск} и строка в журнал.md")
    if код == КОД_КАПЧА:
        print()
        печатать(КАПЧА)
        return КОД_КАПЧА
    if not снято:
        print("\n⚠️ Ни одной цифры не снялось: страница открылась, а чисел система на ней не узнала.")
        print(f"   Образцы страниц — в {показ_пути(ОБРАЗЦЫ)}: по ним чинят разбор.")
        print("   Пока так — цифры можно посмотреть руками на wordstat.yandex.ru.")
        return КОД_НЕ_УЗНАЛ
    return 0


def main(argv: list[str] | None = None) -> int:
    вывод_в_utf8()
    разбор = argparse.ArgumentParser(
        description="Частотность: снять в Яндекс Вордстате, как часто ищут фразы (живой браузер, без API)")
    группа = разбор.add_mutually_exclusive_group(required=True)
    группа.add_argument("--канал", action="store_true",
                        help="что с каналом: Chrome, замок, вход в Яндекс (окно не открывается)")
    группа.add_argument("--проверь", action="store_true", help="жив ли вход в Яндекс прямо сейчас")
    группа.add_argument("--вход", action="store_true", help="открыть окно на Вордстате для входа руками")
    группа.add_argument("--фразы", nargs="+", metavar="ФРАЗА", help="какие фразы снять (до 15)")
    разбор.add_argument("--регион", default="все", help="Москва, Санкт-Петербург, Россия, все — или код")
    разбор.add_argument("--работа", default=None, help="сайты/<имя>: дописать итог в поиск.md и журнал")
    разбор.add_argument("--без-точной", action="store_true",
                        help="не снимать точную частоту (фразу в кавычках) — вдвое меньше запросов")
    разбор.add_argument("--порт", type=int, default=None, help="отладочный порт Chrome")
    разбор.add_argument("--минут", type=int, default=15, help="сколько ждать входа")
    аргументы = разбор.parse_args(argv)
    try:
        if аргументы.канал:
            return команда_канал()
        if аргументы.проверь:
            return команда_проверь(аргументы.порт)
        if аргументы.вход:
            return команда_вход(аргументы.минут, аргументы.порт)
        return команда_фразы(аргументы.фразы, аргументы.регион, аргументы.работа,
                             not аргументы.без_точной, аргументы.порт)
    except кисть.СессияУмерла as беда:
        print(str(беда))
        return КОД_НУЖЕН_ВХОД
    except Капча:
        печатать(КАПЧА)
        return КОД_КАПЧА
    except кисть.ОкноНеПоднялось as беда:
        печатать(кисть.НЕ_ПОДНЯЛСЯ)
        print(f"   Что именно не сложилось: {беда}")
        return КОД_НЕ_ГОТОВО
    except кисть.НеГотово as беда:
        печатать(кисть.СЕТЬ)
        print(f"   Что именно не сложилось: {беда}")
        return КОД_НЕ_ГОТОВО
    except кисть.ПутьМимоБраузера:
        печатать(кисть.ПУТЬ_МИМО)
        return КОД_БЕДА
    except кисть.БедаКисти as беда:
        print(f"❌ {беда}")
        return КОД_БЕДА
    except KeyboardInterrupt:
        print("\n⏹ Остановлено. Окно системы осталось открытым, вход цел.")
        return кисть.КОД_ОСТАНОВЛЕНО
    except Exception as беда:  # noqa: BLE001 — трассировок наружу не выпускаем, как у кисти
        for строка in кисть.слова_прочей_беды(беда)[0]:
            print(строка)
        return КОД_БЕДА


if __name__ == "__main__":
    sys.exit(main())
