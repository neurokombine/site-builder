# ── работа со страницей ──────────────────────────────────────────────────────
JS_ТЕКСТ = "() => (document.body && document.body.innerText) || ''"


def снимок(страница) -> tuple[str, str]:
    try:
        return страница.url, страница.evaluate(JS_ТЕКСТ)
    except Exception:
        return страница.url, ""


def вошли_живьём(страница, контекст) -> str:
    """Живой вопрос: «есть» · «нет» · «капча» · «непонятно». Кука Яндекс ID плюс адрес страницы."""
    адрес, текст = снимок(страница)
    что = что_на_странице(адрес, текст, "")
    if что == КАПЧА:
        return "капча"
    if что == НЕ_ВОШЛИ:
        return "нет"
    try:
        куки = контекст.cookies(["https://wordstat.yandex.ru", "https://passport.yandex.ru"])
    except Exception:
        куки = []
    if any(к.get("name") == КУКА_ВХОДА for к in куки) and "wordstat.yandex" in адрес:
        return "есть"
    return "непонятно"


def открыть_вордстат(контекст, адрес: str = ВОРДСТАТ):
    """Новая вкладка в окне системы. Вкладки человека не трогаем."""
    страница = контекст.new_page()
    перейти(страница, адрес)
    return страница


def перейти(страница, адрес: str) -> None:
    try:
        ответ = страница.goto(адрес, timeout=ЗАГРУЗКА_МС, wait_until="domcontentloaded")
    except Exception as беда:
        raise кисть.НеГотово(f"Вордстат не открылся: {type(беда).__name__}") from беда
    if ответ is not None and ответ.status >= 500:
        raise кисть.НеГотово(f"Вордстат ответил HTTP {ответ.status}")


def беда_входа() -> кисть.СессияУмерла:
    """Не вошли: первый это раз или вход умер — решают следы на диске."""
    был = яндекс_по_следам() != ЯНДЕКС_НЕ_ВХОДИЛИ or метка_входа()
    return кисть.СессияУмерла("\n".join(слова(ЯНДЕКС_ВХОД_УМЕР if был else ЯНДЕКС_НЕ_ВХОДИЛИ)))


def ждать_выдачу(страница, запрос: str, было: str | None = None, ждать_с: int = ВЫДАЧА_С,
                 пауза=None) -> dict:
    """Ждём, пока на странице встанут числа по запросу. Два одинаковых замера подряд — готово.

    `было` — текст страницы до запроса: если он не изменился, это старая выдача, а не наша.
    """
    пауза = пауза or (lambda: страница.wait_for_timeout(1000))
    прежний = None
    for _ in range(ждать_с):
        адрес, текст = снимок(страница)
        что = что_на_странице(адрес, текст, запрос)
        if что == КАПЧА:
            raise Капча("проверка «я не робот»")
        if что == НЕ_ВОШЛИ:
            raise беда_входа()
        if что in (РЕЗУЛЬТАТ, ПУСТО) and (было is None or текст != было):
            разбор = разобрать_выдачу(текст, запрос)
            ключ = (что, разбор["всего"], len(разбор["похожие"]), len(разбор["с_фразой"]))
            if ключ == прежний:
                return {"что": что, **разбор, "текст": текст}
            прежний = ключ
        пауза()
    адрес, текст = снимок(страница)
    return {"что": ЖДЁМ, "всего": None, "с_фразой": [], "похожие": [], "нет_данных": False,
            "текст": текст}


def ввести_в_поле(страница, запрос: str) -> bool:
    """Запасной путь, если адрес с фразой выдачу не показал: напечатать в поле и нажать Enter."""
    for выбор in ("input[type='search']:visible", "input[type='text']:visible",
                  "input:not([type]):visible", "textarea:visible"):
        поле = страница.locator(выбор).first
        try:
            if поле.count():
                поле.click(timeout=5000)
                поле.fill("")
                поле.type(запрос, delay=60)
                страница.keyboard.press("Enter")
                return True
        except Exception:
            continue
    return False


def снять_запрос(страница, запрос: str, регион: int | None) -> dict:
    перейти(страница, адрес_запроса(запрос, регион))
    итог = ждать_выдачу(страница, запрос)
    if итог["что"] == ЖДЁМ:
        _, было = снимок(страница)
        if ввести_в_поле(страница, запрос):
            итог = ждать_выдачу(страница, запрос, было=было)
    return итог


def снять_похожие(страница, запрос: str, пауза=None) -> list[tuple[str, int]]:
    """Вкладка «Похожие» на уже открытой выдаче этой фразы: щелчок и разбор. Не снялось — пусто.

    Один щелчок без перехода по адресу: вкладка работает на странице, а не в адресе. Радиокнопка
    в Вордстате перекрыта своей подписью, поэтому отмечаем её без проверки перекрытия.
    """
    пауза = пауза or (lambda: страница.wait_for_timeout(1000))
    try:
        страница.locator("#associations").check(force=True, timeout=10_000)
    except Exception:
        return []
    for _ in range(ВЫДАЧА_С):
        адрес, текст = снимок(страница)
        if КАПЧА_ТЕКСТ.search(текст) or "showcaptcha" in адрес.lower():
            raise Капча("проверка «я не робот»")
        найдено = разобрать_похожие(текст)
        if найдено:
            return найдено
        пауза()
    return []


def показ_пути(путь: Path) -> str:
    путь = Path(путь)
    return str(путь.relative_to(КОРЕНЬ)) if путь.is_relative_to(КОРЕНЬ) else str(путь)


def сохранить_образец(текст: str, запрос: str, папка: Path | None = None) -> Path:
    папка = ОБРАЗЦЫ if папка is None else папка
    папка.mkdir(parents=True, exist_ok=True)
    имя = datetime.now(МСК).strftime("%Y-%m-%d_%H-%M-%S")
    путь = папка / f"{имя}.txt"
    путь.write_text(f"запрос: {запрос}\n\n{текст}", encoding="utf-8")
    return путь


def точный_запрос(фраза: str) -> str | None:
    """Фраза в кавычках — «ищут ровно эти слова, без хвостов». Уже с операторами — не трогаем."""
    if re.search(r"[\"«»!\[\]+]", фраза):
        return None
    return f"\"{фраза}\""


def проверить_фразы(фразы: list[str]) -> list[str]:
    чистые: list[str] = []
    for ф in фразы or []:
        ф = " ".join((ф or "").split())
        if ф and вид_фразы(ф) not in {вид_фразы(ч) for ч in чистые}:
            чистые.append(ф)
    if not чистые:
        raise кисть.БедаВвода("фраз нет — скажите, что снимать: --фразы \"курсы английского\".")
    if len(чистые) > МАКС_ФРАЗ:
        raise кисть.БедаВвода(
            f"фраз {len(чистые)}, а за один прогон система снимает не больше {МАКС_ФРАЗ}: "
            "Вордстат быстро замечает частые запросы и просит доказать, что вы не робот. "
            "Разбейте на два прогона.")
    return чистые


def проверить_работу(работа: str | None) -> Path | None:
    if not работа:
        return None
    путь = Path(работа)
    if not путь.is_absolute():
        путь = (КОРЕНЬ / путь) if not путь.exists() else путь.resolve()
    if not путь.is_dir():
        raise кисть.БедаВвода(f"нет папки работы «{работа}» — укажите так: --работа сайты/<имя>.")
    return путь


def снять(фразы: list[str], регион: int | None, точная: bool = True, порт: int | None = None,
          печать=print, спать=None) -> list[dict]:
    """Снять частотность по фразам. Возвращает по строке на фразу; числа — только снятые."""
    спать = спать or (lambda: time.sleep(random.uniform(*ПАУЗА_С)))
    итоги: list[dict] = [{"фраза": ф, "всего": None, "точно": None, "похожие": [], "с_фразой": [],
                          "заметка": НЕ_СНЯЛОСЬ} for ф in фразы]
    if not кисть.занять_замок():
        raise кисть.БедаКисти("\n".join(слова(кисть.ЗАНЯТО)))
    try:
        живой = кисть.порт_браузера(порт)
        with кисть.подключение(живой) as контекст:
            страница = открыть_вордстат(контекст)
            try:
                первый = True
                for строка in итоги:
                    for вид, запрос in (("всего", строка["фраза"]),
                                        ("точно", точный_запрос(строка["фраза"]) if точная else None)):
                        if запрос is None:
                            continue
                        if not первый:
                            спать()
                        первый = False
                        try:
                            итог = снять_запрос(страница, запрос, регион)
                        except Капча:
                            строка["заметка"] = "не снялось: проверка «я не робот»"
                            raise
                        if итог["что"] == РЕЗУЛЬТАТ:
                            строка[вид] = итог["всего"]
                            if вид == "всего":
                                строка["с_фразой"] = итог["с_фразой"]
                                спать()          # вкладка «Похожие» — ещё один запрос, тот же темп
                                try:
                                    строка["похожие"] = снять_похожие(страница, запрос)
                                except Капча:
                                    строка["заметка"] = "не снялось: проверка «я не робот»"
                                    raise
                            строка["заметка"] = ""
                        elif итог["что"] == ПУСТО and вид == "всего":
                            строка["заметка"] = "нет данных: Вордстат чисел не показал"
                        elif итог["что"] == ЖДЁМ:
                            образец = сохранить_образец(итог.get("текст", ""), запрос)
                            печать(f"⚠️ «{запрос}»: чисел на странице не узнал, образец — "
                                   f"{показ_пути(образец)}")
                    печать(f"   · {строка['фраза']}: {формат(строка['всего'])}"
                           + (f" / точно {формат(строка['точно'])}" if точная else ""))
            finally:
                try:
                    страница.close()
                except Exception:
                    pass
    except Капча as беда:
        беда.итоги = итоги      # снятое до проверки не теряем
        raise
    finally:
        кисть.отпустить_замок()
    кисть.записать_журнал({"частотность": f"фраз {len(итоги)}, снято "
                                          f"{sum(1 for с in итоги if с['всего'] is not None)}"},
                          журнал=ЖУРНАЛ)
    return итоги


# ── вывод и запись ───────────────────────────────────────────────────────────
def формат(значение: int | None) -> str:
    if значение is None:
        return НЕ_СНЯЛОСЬ
    return f"{значение:,}".replace(",", " ")


def таблица(итоги: list[dict], регион: str, когда: datetime) -> str:
    строки = [f"Частотность в Вордстате · {регион} · снято {когда:%d.%m.%Y %H:%M} МСК",
              "показов в месяц: всего (с любыми хвостами) / точно («фраза в кавычках»)", ""]
    ширина = max([len(с["фраза"]) for с in итоги] + [5])
    for с in итоги:
        строки.append(f"{с['фраза']:<{ширина}}  {формат(с['всего']):>12}  {формат(с['точно']):>12}"
                      + (f"   ({с['заметка']})" if с["заметка"] and с["всего"] is None else ""))
        if с["с_фразой"]:
            строки.append("    с этой фразой: " + " · ".join(
                f"{т} — {формат(ч)}" for т, ч in с["с_фразой"][:5]))
        if с["похожие"]:
            строки.append("    похожие (вкладка «Похожие»): " + " · ".join(
                f"{т} — {формат(ч)}" for т, ч in с["похожие"]))
    return "\n".join(строки)


def раздел_частотности(итоги: list[dict], регион: str, когда: datetime) -> str:
    """Раздел для `поиск.md`. Строк вида «Поле: значение» нет нарочно: `собрать.py` читает
    поля контракта Б по такому образцу, и чужая строка не должна подменить настоящее поле."""
    строки = [f"## Частотность (снято {когда.astimezone(МСК):%d.%m.%Y} МСК, регион {регион})", "",
              "Сняла система в Яндекс Вордстате, в окне со входом владельца. Показов в месяц —",
              "всего (с любыми хвостами) и точно (фраза в кавычках). Числа только снятые.", "",
              "| Фраза | Всего | Точно |", "|---|---|---|"]
    for с in итоги:
        всего = формат(с["всего"]) if с["всего"] is not None else (с["заметка"] or НЕ_СНЯЛОСЬ)
        строки.append(f"| {с['фраза']} | {всего} | {формат(с['точно'])} |")
    for с in итоги:
        if с["с_фразой"] or с["похожие"]:
            строки += ["", f"**{с['фраза']}**", ""]
            for т, ч in с["с_фразой"]:
                строки.append(f"- с фразой · {т} — {формат(ч)}")
            if с["похожие"]:
                строки += ["", "Вкладка «Похожие» (до 10; цифры тут общие по Вордстату, не сужены до фразы):", ""]
            for т, ч in с["похожие"]:
                строки.append(f"- похожий · {т} — {формат(ч)}")
    return "\n".join(строки) + "\n"


def дописать_в_поиск(работа: Path, итоги: list[dict], регион: str, когда: datetime) -> Path:
    файл = работа / "поиск.md"
    было = файл.read_text(encoding="utf-8") if файл.exists() else f"# Как нас находят: {работа.name}\n"
    файл.write_text(было.rstrip("\n") + "\n\n" + раздел_частотности(итоги, регион, когда),
                    encoding="utf-8")
    return файл


def дописать_в_журнал(работа: Path, итоги: list[dict], регион: str, когда: datetime) -> Path:
    журнал = работа / "журнал.md"
    было = журнал.read_text(encoding="utf-8") if журнал.exists() else "# Журнал\n"
    снято = sum(1 for с in итоги if с["всего"] is not None)
    строка = (f"\n\n## {когда.astimezone(МСК):%d.%m.%Y %H:%M} МСК — частотность в Вордстате: "
              f"снято {снято} из {len(итоги)} фраз, {регион}; таблица — в поиск.md\n")
    журнал.write_text(было.rstrip("\n") + строка, encoding="utf-8")
    return журнал


