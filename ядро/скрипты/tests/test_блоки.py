class ЭкранВидео(unittest.TestCase):
    """Семнадцатый тип — экран, где доводом работает живая запись.

    Макета у него нет: он собран из уже принятых деталей (левая шапка и список галок «что
    получите», окно `мокап` витрины работ) — поэтому сторожим не пиксели, а ровно то, что легко
    потерять при следующей правке: три формы окна по одной образцовой копии, пропорцию 16 : 9
    у всех трёх, отсутствие автоплея и субтитров и то, что ролик на экране ровно один.
    """

    РЕЦЕПТЫ = {н: (БЛОКИ / н / "04-видео.html").read_text(encoding="utf-8")
               for н in ("лендинг", "визитка")}
    СТИЛИ = (ROOT / "ядро/блоки/стили-страницы.css").read_text(encoding="utf-8")
    ФИКСТУРА = ROOT / "ядро/скрипты/tests/фикстуры/экраны-все"

    def test_окно_держит_три_формы_по_одной_образцовой_копии(self):
        """Адрес плеера · свой файл · заглушка — все три стоят в рецепте, верстальщик оставляет
        одну. Пропадёт форма — человек с таким материалом станет верстать её сам, с нуля."""
        for набор, текст in self.РЕЦЕПТЫ.items():
            with self.subTest(набор=набор):
                self.assertEqual(текст.count('<figure class="мокап видео__плеер">'), 3)
                self.assertEqual(текст.count("<iframe "), 1)
                self.assertEqual(текст.count("<video "), 1)
                self.assertEqual(текст.count('<div class="заглушка-картинки">заглушка</div>'), 1)
                self.assertIn("{{ВИДЕО_АДРЕС}}", текст)
                self.assertIn("video/{{ВИДЕО}}.mp4", текст)
                self.assertIn("poster=\"video/{{ПОСТЕР}}\"", текст)

    def test_ролик_не_стартует_сам_и_не_несёт_субтитров(self):
        """Звук приходит с нажатием человека: автоплей на экране-обращении был бы разговором,
        который начался без спроса. Субтитров не бывает нигде (GC 25)."""
        for набор, текст in self.РЕЦЕПТЫ.items():
            with self.subTest(набор=набор):
                тег = re.search(r"<video [^>]*>", текст).group(0)
                self.assertIn("controls", тег)
                self.assertIn('preload="none"', тег)
                self.assertIn("playsinline", тег)
                self.assertNotIn("autoplay", тег)
                self.assertNotIn("<track", текст)

    def test_пропорция_шестнадцать_к_девяти_у_всех_трёх_начинок(self):
        """У плеера площадки её держит база (`.мокап iframe`), а свой файл и заглушка её не знают:
        у видео пропорция своя, у заглушки книжная 3 : 4 — и окно на месте ненайденного ролика
        было бы вдвое выше того, что придёт ему на смену."""
        база = (ROOT / "ядро/блоки/стили-база.css").read_text(encoding="utf-8")
        self.assertRegex(база, r"\.мокап iframe \{[^}]*aspect-ratio: 16 / 9")
        self.assertRegex(self.СТИЛИ, r"\.видео__плеер video \{[^}]*aspect-ratio: 16 / 9")
        self.assertRegex(self.СТИЛИ, r"\.видео__плеер \.заглушка-картинки \{[^}]*aspect-ratio: 16 / 9")

    def test_окно_шире_текста_и_на_телефоне_стоит_первым(self):
        """Ролик здесь довод, а не украшение: на компьютере колонка под него шире (1.15fr к 1fr),
        а в разметке он идёт ПЕРЕД текстом — значит, на телефоне кадр сам оказывается над словами
        о нём, и переставлять ничего не нужно."""
        self.assertRegex(self.СТИЛИ, r"\.видео__сетка \{ grid-template-columns: 1\.15fr 1fr")
        for набор, текст in self.РЕЦЕПТЫ.items():
            with self.subTest(набор=набор):
                self.assertLess(текст.index('class="мокап видео__плеер"'),
                                текст.index('class="видео__текст"'))

    def test_список_той_же_формы_что_и_у_что_получите(self):
        """Эталон приёмки у экрана без макета — уже принятые экраны. Список «что увидите» набран
        ровно так же, как список «что получите»: кружок-галка (а не контурная иконка из набора
        шестидесяти), заголовок пункта и пояснение с тире ВНУТРИ того же span."""
        образец = (БЛОКИ / "лендинг" / "02-что-получите.html").read_text(encoding="utf-8")
        self.assertIn('<li><i class="галка"></i><span><b>{{ПОЛУЧИТЕ_1}}</b>', образец)
        for набор, текст in self.РЕЦЕПТЫ.items():
            with self.subTest(набор=набор):
                self.assertIn('<ul class="список-иконок видео__список">', текст)
                self.assertEqual(текст.count('<i class="галка"></i>'), 3)
                self.assertIn('<span><b>{{ПУНКТ_1}}</b><span> — {{ПОЯСНЕНИЕ_1}}</span></span>', текст)
                self.assertNotIn("{{ИКОНКА:галочка}}", текст)

    def test_на_экране_один_ролик_и_ни_одной_кнопки(self):
        """Связи у экрана нет вовсе — шаг человек делает на соседнем, как на «условиях». И плеер
        один: витрина многих роликов — это соседний тип `работы`, а не этот."""
        for набор, текст in self.РЕЦЕПТЫ.items():
            with self.subTest(набор=набор):
                self.assertNotIn("{{СВЯЗЬ:", текст)
                self.assertNotIn("кнопка", текст)
