"""Блоки-рецепты: контракт секции, слоты только из блоки.md, нет hex, лимиты, картинки в обёртках."""
import re
import sys
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "ядро" / "скрипты"))
sys.path.insert(0, str(Path(__file__).resolve().parent))
import собрать  # noqa: E402

БЛОКИ = ROOT / "ядро" / "блоки"
СЕКЦИЯ = re.compile(r'^<section class="блок блок--([а-яё-]+)((?: [а-яё-]+--[а-яё-]+)*) '
                    r'(светлый(?: второй)?|тёмный)( фон--(?:пятна|сетка|зерно))?" '
                    r'id="экран-\{\{НОМЕР\}\}" data-тип="\1"')
СХЕМЫ_НАБОРА = {"визитка": ("разворот", "орбита", "сцена", "живая-сцена", "товар-крупно", "бенто", "центр", "живой-портрет"),
                "лендинг": собрать.СХЕМЫ}
# Состав наборов живёт в ядре (`собрать.ТИПЫ_НАБОРА`), а не в тесте: схемы первого экрана плюс типы
# экранов ниже — визитка 8 + 8 = 16, лендинг 11 + 15 = 26, всего 42 файла.
ОЖИДАЕМ = {набор: len(СХЕМЫ_НАБОРА[набор]) + len(типы) for набор, типы in собрать.ТИПЫ_НАБОРА.items()}
ВСЕГО_БЛОКОВ = sum(ОЖИДАЕМ.values())
# После class у обёртки может стоять `style="--…"` — объявление своей переменной (фикс-раунд Е, ниже).
ОБЁРТКА = re.compile(r'<figure class="(?:фото|мокап|картинка)[^"]*"[^>]*>.*?</figure>', re.S)
ФАЙЛЫ = [ф for набор in ОЖИДАЕМ for ф in sorted((БЛОКИ / набор).glob("*.html"))]


class Блоки(unittest.TestCase):
    карта = (ROOT / "ядро" / "блоки.md").read_text(encoding="utf-8")

    def test_в_комментариях_нет_слотов(self):
        for ф in ФАЙЛЫ:   # сборщик подставляет и в инструкцию: слот в комментарии = 🔴 у человека, стёршего абзац
            for к in re.findall(r"<!--.*?-->", ф.read_text(encoding="utf-8"), re.S):
                self.assertNotIn("{{", к, ф.name)

    def test_состав_наборов(self):
        for набор, сколько in ОЖИДАЕМ.items():
            имена = sorted(ф.name for ф in (БЛОКИ / набор).glob("*.html"))
            self.assertEqual(len(имена), сколько, имена)
            self.assertEqual(sorted(ф.stem.split("01-первый-экран-", 1)[1] for ф in (БЛОКИ / набор).glob("01-*.html")), sorted(СХЕМЫ_НАБОРА[набор]))
            # Тип из состава набора обязан лежать файлом: имя рецепта кончается на `-<тип>.html`.
            типы = {ф.stem.split("-", 1)[1] for ф in (БЛОКИ / набор).glob("*.html") if not ф.name.startswith("01-")}
            self.assertEqual(типы, set(собрать.ТИПЫ_НАБОРА[набор]), набор)
        self.assertLessEqual(len((БЛОКИ / "таймер.js").read_text(encoding="utf-8").splitlines()), 25)

    def test_каждый_тип_назван_в_карте(self):
        """Новый тип без строки в `блоки.md` — рецепт, о котором `screen-builder` не узнает.
        § 2 называет файл (`02-что-получите.html`), § 3 — строку слотов (`| что-получите |`)."""
        for набор, типы in собрать.ТИПЫ_НАБОРА.items():
            for тип in типы:
                файл, = (БЛОКИ / набор).glob(f"*-{тип}.html")
                with self.subTest(набор=набор, тип=тип):
                    self.assertIn(f"`{файл.name}`", self.карта, f"§ 2 не называет файл {файл.name}")
                    self.assertRegex(self.карта, re.compile(rf"^\| {re.escape(тип)} \|", re.M),
                                     f"§ 3 не знает слотов типа «{тип}»")

    def test_каждый_блок_по_контракту(self):
        for ф in ФАЙЛЫ:
            текст = ф.read_text(encoding="utf-8")
            with self.subTest(файл=ф.name):
                self.assertRegex(текст.splitlines()[0], СЕКЦИЯ)
                self.assertEqual(текст.count("<section"), 1)
                self.assertIn('<div class="блок__внутри">', текст)
                if ф.name.startswith("01-"):
                    схема = ф.stem.split("01-первый-экран-", 1)[1]
                    self.assertIn(схема, СХЕМЫ_НАБОРА[ф.parent.name])
                    self.assertIn(f'data-схема="{схема}"', текст)
                    # Фикс-раунд Л, замечание 1: рецепт несёт ключ СВОЕГО макета, чтобы стили
                    # знали, где светлый ключ — родной (разворот, товар крупно, бенто: макет плоский
                    # и таким задуман), а где он перекрашен из тёмного и обязан взять ту же глубину.
                    ключ = собрать.РОДНОЙ_КЛЮЧ[схема]
                    self.assertIn(f'data-ключ-макета="{ключ}"', текст,
                                  f"{ф.name}: ключ макета разошёлся с собрать.РОДНОЙ_КЛЮЧ")
                    self.assertRegex(текст, r'data-картинка="(?:фото|вырез|видео|видео-с-голосом|живой-портрет|мозаика|мокап|товар)"')
                    if 'data-картинка="видео-с-голосом"' in текст:
                        for кусок in ('<button class="звук"', 'class="звук__почему', 'preload="auto"'):
                            self.assertIn(кусок, текст)
                    self.assertNotIn("<track", текст)
                    self.assertIn(f"первый-экран--{схема}", текст)
                    self.assertIn('первый-экран__картинка"', текст)            # GC 21: картинка обязательна
                    self.assertRegex(текст, r'<(?:img|video) [^>]*data-лицо="\{\{ЛИЦО\}\}"')
                    self.assertNotIn("data-концепция", текст)
                self.assertNotRegex(текст, r"#[0-9a-fA-F]{3,8}\b")
                # Инлайн-стиль в блоке по-прежнему запрещён — с одной узкой оговоркой (фикс-раунд Е):
                # ОБЪЯВЛЕНИЕ СОБСТВЕННОЙ ПЕРЕМЕННОЙ разметкой. Это не оформление, а замер, которого
                # стиль сам сделать не может: `--лицо-в-кадре` — доля высоты картинки, на которой стоит
                # лицо ИМЕННО ЭТОГО человека. Оформление остаётся в css-файле, здесь только число.
                for м in re.finditer(r'style="([^"]*)"', текст):
                    self.assertRegex(м.group(1).strip(), r"^(?:--[\w-]+:[^;]+;?\s*)+$",
                                     "инлайн-стиль в блоке — только объявление своей переменной")
                self.assertNotIn("object-fit", текст)
                self.assertLessEqual(len(текст.splitlines()), 140 if ф.name.startswith("01-") else 110)
                self.assertLessEqual(текст.count("{{СВЯЗЬ:"), 1)
                self.assertNotIn("кнопка--главная", текст)   # главную ставит только начинка_связи
                обёртки = [м.span() for м in ОБЁРТКА.finditer(текст)]
                for м in re.finditer(r"<img [^>]*>", текст):
                    if 'class="аватар"' not in м.group(0):
                        self.assertTrue(any(а <= м.start() < б for а, б in обёртки), "img вне .фото/.мокап/.картинка/.аватар")
                for м in re.finditer(r"<video [^>]*>", текст):
                    self.assertTrue(all(с in м.group(0) for с in ("muted", "playsinline", "poster=")), м.group(0))
                for с in собрать.ПЛЕЙСХОЛДЕР.finditer(текст):
                    if с.group(1) not in ("СВЯЗЬ", "ИКОНКА", "НОМЕР"):
                        self.assertIn(f"`{{{{{с.group(1)}}}}}`", self.карта, f"слота {с.group(1)} нет в блоки.md § 3")

    def test_фикстура_экраны_все_из_всех_рецептов(self):
        фикстура = sorted((ROOT / "ядро/скрипты/tests/фикстуры/экраны-все").glob("*.html"))
        self.assertEqual(len(фикстура), ВСЕГО_БЛОКОВ)
        for ф in фикстура:
            текст = ф.read_text(encoding="utf-8")
            # Решение контроллёра 3: {{СВЯЗЬ:…}} и {{ИКОНКА:…}} в фикстуре остаются — их подставляет собрать.py
            лишние = [с.group(1) for с in собрать.ПЛЕЙСХОЛДЕР.finditer(текст) if с.group(1) not in ("ИКОНКА", "СВЯЗЬ")]
            self.assertEqual(лишние, [], ф.name)
            self.assertRegex(текст, r'id="экран-\d+"')
        self.assertEqual(sorted(ф.stem for ф in фикстура if ф.name.startswith("01-")),
                         sorted(f"01-первый-экран-{с}-{н}" for н, сс in СХЕМЫ_НАБОРА.items() for с in сс))

    def test_фикстура_первых_экранов_не_отстала_от_рецептов(self):
        """Фикс-раунд Г, долг трёх раундов: фикстуру `экраны-все` правили рецепты, а её саму — нет,
        и браузерный гейт `test_флаги_дизайна` мерил вчерашние экраны, оставаясь зелёным. Теперь
        первые экраны фикстуры собираются тем же кодом, что и настоящий сайт, и этот тест каждый
        раз пересобирает их в памяти: разошлись — падаем и называем команду, а не молчим."""
        import пересобрать_фикстуру
        self.assertEqual(пересобрать_фикстуру.разошлись(), [],
                         "фикстура отстала от рецептов — пересобери: "
                         ".venv/bin/python ядро/скрипты/tests/пересобрать_фикстуру.py")



class БлокиРассказа(unittest.TestCase):
    """Экраны рассказа стоят по макету полной страницы: «Для кого» — плитки-роли на фактуре и без
    иконок, «Об авторе» — разворот с рядом цифр вместо стеклянных карточек-фактов."""

    def test_для_кого_плитки_роли_без_иконок(self):
        текст = (БЛОКИ / "лендинг" / "02-боль.html").read_text(encoding="utf-8")
        for кусок in ("блок--тихо блок--текстура", 'class="сетка-текстура"',
                      'class="текстура__список', '<div class="роль">'):
            self.assertIn(кусок, текст)
        # Адресата держит золотая строка его имени, а не картинка рядом с ней: иконок макет здесь
        # не рисует вовсе, и карточек с иконкой — тоже.
        self.assertNotIn("{{ИКОНКА:", текст)
        self.assertNotIn('class="карточки"', текст)

    def test_об_авторе_ряд_цифр_вместо_карточек_фактов(self):
        for набор, зеркало in (("лендинг", True), ("визитка", False)):
            текст = (БЛОКИ / набор / "02-о-себе.html").read_text(encoding="utf-8")
            with self.subTest(набор=набор):
                self.assertIn('class="разворот__сетка', текст)
                # Зеркало (фото слева) — только на лендинге: на визитке это третий экран, и
                # зеркальная раскладка ломала бы ритм с первым.
                self.assertEqual("разворот__сетка--лево" in текст, зеркало)
                self.assertIn('class="хвост-акцент"', текст)
                self.assertEqual(текст.count('class="цифра"'), 4)
                self.assertNotIn("{{ФАКТ_", текст)
                self.assertNotIn("карточка--стекло", текст)

    def test_что_получите_разворот_с_галками_врезкой_и_парящим_кадром(self):
        текст = (БЛОКИ / "лендинг" / "02-что-получите.html").read_text(encoding="utf-8")
        for кусок in ('class="разворот__сетка"', 'class="список-иконок"', '<i class="галка">',
                      '<div class="врезка">', 'class="фото парит"',
                      '<figcaption class="плашка фото__подпись">'):
            self.assertIn(кусок, текст)
        # Маркер списка — мелкая золотая галка из базы, а не контурная иконка из набора шестидесяти:
        # она стоит рядом со строчными буквами, а не спорит с кнопкой размером.
        self.assertNotIn("{{ИКОНКА:", текст)
        # Черты в шапке нет: в макете полной страницы её не стоит ни на одном экране.
        self.assertNotIn('class="черта"', текст)
        # Фикс-раунд 1: длинное тире между половинами пункта видно человеку — он читает ту же фразу,
        # которую написал в прототипе. И живёт тире ВНУТРИ элемента пояснения, первым в нём: стёр
        # пояснение — тире ушло вместе с ним, а не повисло после жирного заголовка.
        for н in (1, 2, 3):
            self.assertIn(f"<b>{{{{ПОЛУЧИТЕ_{н}}}}}</b><span> — {{{{ПОЯСНЕНИЕ_{н}}}}}</span>", текст,
                          "разделитель пункта потерялся или вынесен из элемента пояснения")

    def test_как_работаем_лента_без_кнопки(self):
        """«Решение» — единственный экран страницы без связи: главная кнопка живёт на первом экране,
        в тарифах и в финале, а лента шагов — дорога, которую ещё смотрят (макет, `#как-работаем`)."""
        текст = (БЛОКИ / "лендинг" / "03-решение.html").read_text(encoding="utf-8")
        for кусок in ("блок--тихо блок--текстура", 'class="сетка-текстура"',
                      'class="секция__шапка секция__шапка--центр"', 'class="лента', '<div class="шаг">'):
            self.assertIn(кусок, текст)
        self.assertNotIn("{{СВЯЗЬ:", текст)
        self.assertNotIn('class="пара', текст)   # пара «заголовок и кнопка | шаги» ушла вместе с кнопкой
        self.assertNotIn('class="шаги"', текст)  # вертикальные шаги базы — не лента макета
        self.assertEqual(текст.count('<div class="шаг">'), 3)

    def test_программа_аккордеон_по_частям_без_скрипта(self):
        """«Программа» — части, внутри них модули, и раскрывает их сам `details`: ни строки своего
        скрипта, ни класса-переключателя. Вертикальные шаги базы ушли вместе со старой формой."""
        текст = (БЛОКИ / "лендинг" / "05-программа.html").read_text(encoding="utf-8")
        for кусок in ('class="части-программы секция__тело"', '<div class="часть">',
                      'class="часть__шапка"', 'class="часть__имя"', 'class="часть__метка"',
                      '<div class="модули">', 'class="модуль__номер"', 'class="модуль__мета"',
                      'class="модуль__шеврон"', 'class="модуль__тело"', '<span class="тег">',
                      'class="модуль__результат"', '<div class="врезка">'):
            self.assertIn(кусок, текст)
        self.assertNotIn('class="шаги"', текст)     # вертикальные шаги базы — не аккордеон макета
        self.assertNotIn("<script", текст)
        self.assertNotIn("onclick", текст)
        # 🔴 Открыт по умолчанию РОВНО ОДИН модуль — первый: на телефоне три раскрытых подряд
        # вытягивают экран на несколько метров, и человек не видит, сколько в программе частей.
        self.assertEqual(текст.count("<details"), 2, "образцовых модуля два: открытый и его копия")
        self.assertEqual(текст.count('<details class="модуль" open>'), 1)
        self.assertLess(текст.index('<details class="модуль" open>'), текст.index('<details class="модуль">'))

    def test_условия_строки_с_тире_и_без_висячего_разделителя(self):
        """Тире-маркер строке рисуют стили, а тире-разделитель между половинами человек видит и
        читает — тот же приём, что в списке «что получите»: разделитель живёт внутри элемента
        пояснения, первым в нём, и стирается вместе с ним."""
        текст = (БЛОКИ / "лендинг" / "06-условия.html").read_text(encoding="utf-8")
        for кусок in ("блок--тихо блок--текстура", 'class="сетка-текстура"',
                      'class="условия секция__тело"'):
            self.assertIn(кусок, текст)
        self.assertNotIn('class="черта"', текст)   # черты в макете нет ни на одном экране
        self.assertNotIn("{{СВЯЗЬ:", текст)        # шаг человек делает на соседнем экране
        for н in (1, 2, 3):
            self.assertIn(f"<b>{{{{УСЛОВИЕ_{н}}}}}</b><span> — {{{{ПОЯСНЕНИЕ_{н}}}}}</span>", текст,
                          "разделитель строки потерялся или вынесен из элемента пояснения")


if __name__ == "__main__":
    unittest.main()
