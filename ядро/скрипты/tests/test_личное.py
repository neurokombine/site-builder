"""Сторож личного на всё ядро: ни имени владелицы системы, ни её школы, ни её цифр.

Зачем отдельный файл. Сторожа «в модуле нет личного» стояли по одному на модуль
(`test_заказ.py`, `test_портрет.py`, `test_приёмка.py`, `test_стили.py`) — три питоновских файла
и один CSS из полутора сотен текстовых файлов ядра. Всё остальное — рецепты блоков, документы,
шпаргалки, комментарии в стилях — не охранял никто, и личное там жило: лицензия школы примером
в прототипе, её длинное название примером в CSS-комментарии. Система отчуждаемая: её берёт
человек, у которого своё дело, и ничьё чужое имя в его копии стоять не должно.

Список слов — одной константой ЛИЧНЫЕ_СЛОВА: модульные сторожа ссылаются на неё же и добавляют
только своё (ниша, гардероб, шрифты). Пополнять список — здесь, в одном месте.

Исключений четыре, и у каждого своя причина. Два первых названы в `ядро/картинки.md` § 8:
`ядро/обложки/пример-студия/` (материалы автора системы, разрешение 10.09.2026) и собранный из них
каталог схем `ядро/обложки/каталог/`. Два вторых — полки галереи, где лежат снимки НАСТОЯЩИХ
страниц: `ядро/галерея/примеры/страница-целиком/` (три цветовые партитуры одной живой страницы) и
`ядро/галерея/бренд/` (чужие живые сайты как планка). Снимок живой страницы без имён и цифр на нём
бессмысленен, а копировать оттуда нечего: галерея — для глаз (`ядро/галерея.md`). Примеры экранов
(`ядро/галерея/примеры/<тип>/<набор>/`) исключением НЕ являются: они собираются из образцовых
текстов, и личного в них нет, как не было в рецептах. Плюс сам этот файл — в нём слова живут по делу.
"""
import unittest
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[3]

# Личное владелицы системы: имя, школа, её документы и её цифры. Регистр не важен.
ЛИЧНЫЕ_СЛОВА = ("Натэл", "Зубченко", "Л035", "01053865", "34 900", "34900",
                "ТЭФИ", "НейроВидео", "Риторикс", "ritoriks")

РАСШИРЕНИЯ = {".md", ".py", ".css", ".js", ".html", ".json", ".sh", ".txt"}
# Что обходим: всё ядро и документы, которые уезжают вместе с системой.
ОБХОДИМ = ("ядро", ".claude")
ОТДЕЛЬНЫЕ_ФАЙЛЫ = ("CLAUDE.md", "README.md", "ЕСЛИ-СЛОМАЛОСЬ.md")
ИСКЛЮЧЕНИЯ = ("ядро/обложки/пример-студия", "ядро/обложки/каталог",
              "ядро/галерея/примеры/страница-целиком", "ядро/галерея/бренд")


def личное_в_строке(строка: str) -> list[str]:
    """Какие из личных слов есть в строке (регистронезависимо)."""
    низ = строка.lower()
    return [слово for слово in ЛИЧНЫЕ_СЛОВА if слово.lower() in низ]


def текстовые_файлы() -> list[Path]:
    """Все текстовые файлы ядра и уезжающих с ним документов, кроме папок-исключений
    и самого этого файла."""
    этот = Path(__file__).resolve()
    найденные: list[Path] = []
    for папка in ОБХОДИМ:
        найденные += sorted((КОРЕНЬ / папка).rglob("*"))
    найденные += [КОРЕНЬ / имя for имя in ОТДЕЛЬНЫЕ_ФАЙЛЫ]
    итог = []
    for файл in найденные:
        if not файл.is_file() or файл.suffix.lower() not in РАСШИРЕНИЯ:
            continue
        путь = файл.resolve().relative_to(КОРЕНЬ).as_posix()
        if путь.startswith(ИСКЛЮЧЕНИЯ) or "__pycache__" in путь or файл.resolve() == этот:
            continue
        итог.append(файл)
    return итог


class ЛичногоВЯдреНет(unittest.TestCase):
    def test_ни_в_одном_файле_ядра_нет_личного(self):
        находки = []
        for файл in текстовые_файлы():
            путь = файл.resolve().relative_to(КОРЕНЬ).as_posix()
            текст = файл.read_text(encoding="utf-8-sig", errors="replace")
            for номер, строка in enumerate(текст.splitlines(), 1):
                for слово in личное_в_строке(строка):
                    находки.append(f"{путь}:{номер}: «{слово}» — {строка.strip()[:100]}")
        self.assertEqual(находки, [], "личное в ядре:\n" + "\n".join(находки))

    def test_обход_добирается_до_ядра(self):
        """Сторож, который ничего не обошёл, не сторож: файлов должно быть много, и среди них —
        документы, рецепты блоков, стили и скрипты."""
        файлы = текстовые_файлы()
        пути = {ф.resolve().relative_to(КОРЕНЬ).as_posix() for ф in файлы}
        self.assertGreater(len(файлы), 100, "обход ядра опустел — сторож мерит не то")
        for обязательный in ("ядро/картинки.md", "ядро/блоки/стили-база.css",
                             "ядро/скрипты/собрать.py", "README.md",
                             "ядро/блоки/лендинг/01-первый-экран-орбита.html"):
            self.assertIn(обязательный, пути, обязательный)
        self.assertFalse([п for п in пути if п.startswith(ИСКЛЮЧЕНИЯ)],
                         "в обход не идут четыре разрешённых места: пример-студия, каталог схем, "
                         "страницы целиком и полка бренда")
        # Сторож исключений: галерея целиком из-под проверки не выпадает — примеры экранов
        # проверяются наравне с рецептами, иначе личное въехало бы в ядро через полку примеров.
        self.assertIn("ядро/галерея.md", пути)
        self.assertIn("ядро/галерея/примеры/боль/лендинг/о-примере.md", пути)

    def test_сторож_ловит_подсунутое(self):
        """Проверка самого сторожа: слова ловятся в любом регистре, а безобидная строка молчит."""
        self.assertEqual(личное_в_строке("а тут у нас НАТЭЛА и Ritoriks"), ["Натэл", "ritoriks"])
        self.assertEqual(личное_в_строке("Лицензия № л035-01261-30/01053865"), ["Л035", "01053865"])
        self.assertEqual(личное_в_строке("обычная строка про первый экран"), [])


if __name__ == "__main__":
    unittest.main()
