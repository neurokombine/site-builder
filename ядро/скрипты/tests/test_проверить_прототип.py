# Задача 2: пять новых слотов первого экрана (кикер, верхняя строка, регалии, чипы, подписи
# роликов) — рецепты вёрстки просили их давно, в прототипе не было ни одного, и сборка
# сочиняла текст сама. Каждому полю — своя пара тестов: требуется там, где схема его просит,
# и не требуется там, где не просит (`ядро/прототип-поля-первого-экрана.md`).

ВЕРХНЯЯ_СТРОКА_ЧИСТОГО = ("- Верхняя строка:\n"
                          "  - знак: Логопед для дошкольников\n"
                          "  - доверие: Отвечаю на сообщения в течение дня\n")
КИКЕР_ЧИСТОГО = "- Кикер: Ставим звуки до школы\n"


def _со_схемой(схема: str | None = None, *, регалии: list[str] | None = None,
              чипы: list[str] | None = None, подписи: list[str] | None = None,
              замена: tuple[str, str] | None = None):
    """Прототип-чистый с заданной схемой первого экрана и, по желанию, новыми полями."""
    текст = (ФИКСТУРЫ / "прототип-чистый.md").read_text(encoding="utf-8")
    if замена:
        было, стало = замена
        assert было in текст, было
        текст = текст.replace(было, стало, 1)
    if схема is not None:
        текст = текст.replace("- Схема: не выбрана", f"- Схема: {схема}", 1)
    вставка = []
    for имя_слота, значения in (("Регалии", регалии), ("Чипы", чипы), ("Подписи роликов", подписи)):
        if значения is not None:
            вставка.append(f"- {имя_слота}:")
            вставка += [f"  - {строка}" for строка in значения]
    if вставка:
        якорь = f"- Схема: {схема}" if схема is not None else "- Схема: не выбрана"
        текст = текст.replace(якорь, якорь + "\n" + "\n".join(вставка), 1)
    [п] = пп.разобрать(текст)
    return п


