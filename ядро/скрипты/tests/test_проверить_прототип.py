class НадёжностьЧтенияТесты(unittest.TestCase):
    """Раунд правок 1: rsplit по стрелке, кодировка, BOM, разные сообщения профиля."""

    def test_декоративная_стрелка_в_кнопке_не_путает_действие(self):
        [п] = пп.разобрать(ПРОТОТИП_СО_СТРЕЛКОЙ)
        н = пп.проверить_прототип(п, нельзя_говорить=[], тип_из_профиля=None)
        self.assertNotIn("ведут в разные места", тексты(н))

    def test_файл_не_в_utf8_даёт_код_2_без_traceback(self):
        with tempfile.TemporaryDirectory() as врем:
            путь = Path(врем) / "прототип.md"
            путь.write_bytes("# Прототип: тест\nпривет".encode("cp1251"))
            р = subprocess.run([sys.executable, str(СКРИПТЫ / "проверить_прототип.py"),
                                str(путь), "--без-профиля"], capture_output=True, text=True)
        self.assertEqual(р.returncode, 2, р.stdout + р.stderr)
        self.assertNotIn("Traceback", р.stderr)
        self.assertIn("UTF-8", р.stdout)

    def test_bom_не_ломает_разбор_чистого_прототипа(self):
        with tempfile.TemporaryDirectory() as врем:
            путь = Path(врем) / "прототип.md"
            текст = (ФИКСТУРЫ / "прототип-чистый.md").read_text(encoding="utf-8")
            путь.write_bytes(текст.encode("utf-8-sig"))
            р = subprocess.run([sys.executable, str(СКРИПТЫ / "проверить_прототип.py"),
                                str(путь), "--без-профиля"], capture_output=True, text=True)
        self.assertEqual(р.returncode, 0, р.stdout + р.stderr)
        self.assertNotIn(пп.ФОРМАТ_НЕ_РАСПОЗНАН, р.stdout)

    def test_профиль_битый_json_отличается_от_не_найден(self):
        with tempfile.TemporaryDirectory() as врем:
            профили = Path(врем) / "профили"
            (профили / "битый").mkdir(parents=True)
            (профили / "битый" / "profile.json").write_text("{не json", encoding="utf-8")
            старый = пп.профиль.ПРОФИЛИ
            пп.профиль.ПРОФИЛИ = профили
            try:
                # четвёртым возвращаются сами данные профиля: по ним задача 4 спрашивает про
                # недобранную палитру; у обеих бед их нет — читать было нечего
                *_, беда_нет, данные_нет = пп._прочитать_профиль("отсутствует")
                *_, беда_битый, данные_битый = пп._прочитать_профиль("битый")
                self.assertIsNone(данные_нет)
                self.assertIsNone(данные_битый)
            finally:
                пп.профиль.ПРОФИЛИ = старый
        self.assertNotEqual(беда_нет, беда_битый)
        self.assertIn("не найден", беда_нет)
        self.assertIn("profile.json", беда_битый)


