class ВидеоТесты(unittest.TestCase):
    """Поле `Видео` экрана видео-доказательства: адрес плеера, свой файл или честное «нет».

    Запрет здесь один и он про безопасность — адрес без `https://` браузер на защищённой странице
    просто не покажет. Остальное не запреты, а вопросы к человеку: незнакомая площадка чаще всего
    значит, что в поле попала ссылка на СТРАНИЦУ с роликом вместо адреса самого плеера, а «нет»
    значит серую заглушку на месте единственного довода экрана — и знать об этом надо до вёрстки.
    """

    def _с_видео(self, строка: str):
        п = _чистый((СПИСОК_УСЛУГ_ЧИСТОГО, СПИСОК_УСЛУГ_ЧИСТОГО + f"\n- Видео: {строка}"))
        return пп.проверить_прототип(п, нельзя_говорить=[])

    def test_адрес_известного_плеера_молчит(self):
        for адрес in ("https://kinescope.io/embed/abc123", "https://vk.com/video_ext.php?oid=1",
                      "https://www.youtube.com/embed/abc", "https://rutube.ru/play/embed/12345"):
            with self.subTest(адрес=адрес):
                н = self._с_видео(адрес)
                self.assertNotIn("площадка", тексты(н))
                self.assertNotIn("https", тексты(н))

    def test_имя_своего_файла_молчит(self):
        н = self._с_видео("obrashchenie.mp4")
        self.assertEqual(без_заметки_о_схеме(н), [], тексты(н))

    def test_без_https_это_жёлтое(self):
        н = self._с_видео("http://kinescope.io/embed/abc123")
        self.assertIn("не с «https://»", тексты(н))
        self.assertNotIn(пп.ЧИНИТЬ, уровни(н))

    def test_незнакомая_площадка_это_жёлтое_со_списком(self):
        н = self._с_видео("https://moi-sait.ru/video/1")
        т = тексты(н)
        self.assertIn("незнакомая площадка «moi-sait.ru»", т)
        self.assertIn("kinescope.io", т)
        self.assertNotIn(пп.ЧИНИТЬ, уровни(н))

    def test_нет_ролика_это_жёлтое_про_заглушку(self):
        н = self._с_видео("нет")
        self.assertIn("экран видео без ролика", тексты(н))
        self.assertNotIn(пп.ЧИНИТЬ, уровни(н))

    def test_подпись_и_длительность_проверяются_как_страничные(self):
        п = _чистый((СПИСОК_УСЛУГ_ЧИСТОГО, СПИСОК_УСЛУГ_ЧИСТОГО
                     + "\n- Подпись видео: СРОЧНО смотрите"
                     + "\n- Длительность: гарантирую четыре минуты"))
        т = тексты(пп.проверить_прототип(п, нельзя_говорить=[]))
        self.assertIn("капс: «СРОЧНО»", т)
        self.assertIn("стоп-слово «гарантиру»", т)

    def test_обычная_длительность_не_считается_цифрой_без_источника(self):
        н = self._с_видео("https://kinescope.io/embed/abc123")
        self.assertNotIn("цифра без источника", тексты(н))
        п = _чистый((СПИСОК_УСЛУГ_ЧИСТОГО, СПИСОК_УСЛУГ_ЧИСТОГО + "\n- Длительность: 4 минуты"))
        self.assertNotIn("цифра без источника", тексты(пп.проверить_прототип(п, нельзя_говорить=[])))


