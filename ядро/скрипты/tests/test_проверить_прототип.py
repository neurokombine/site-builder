class ПрофильВПроверкеТесты(unittest.TestCase):
    """Путь, ради которого проверка вообще ходит в профиль: имя в шапке → файл → находка."""

    def _положить_профиль(self, корень: Path, имя: str, нельзя: list, тип: str):
        папка = корень / имя
        папка.mkdir(parents=True)
        (папка / "profile.json").write_text(
            json.dumps({"сайт": {"тип": тип, "нельзя_говорить": нельзя}}, ensure_ascii=False),
            encoding="utf-8")

    def _прототип(self, папка: Path, имя_профиля: str) -> Path:
        текст = (ФИКСТУРЫ / "прототип-чистый.md").read_text(encoding="utf-8")
        текст = текст.replace("- Профиль: логопед-тест", f"- Профиль: {имя_профиля}")
        текст = текст.replace(ПОДЗАГОЛОВОК_ЧИСТОГО,
                              "- Подзаголовок: Гарантия результата после первого занятия")
        путь = папка / "прототип.md"
        путь.write_text(текст, encoding="utf-8")
        return путь

    def _прогнать(self, аргументы: list[str], профили: Path) -> tuple[int, str]:
        старый_argv, старые_профили = sys.argv, пп.профиль.ПРОФИЛИ
        sys.argv = ["проверить_прототип.py"] + аргументы
        пп.профиль.ПРОФИЛИ = профили
        вывод = io.StringIO()
        try:
            with contextlib.redirect_stdout(вывод):
                код = пп.main()
        finally:
            sys.argv, пп.профиль.ПРОФИЛИ = старый_argv, старые_профили
        return код, вывод.getvalue()

    def test_имя_из_шапки_ведёт_к_файлу_профиля(self):
        with tempfile.TemporaryDirectory() as врем:
            врем = Path(врем)
            профили = врем / "профили"
            self._положить_профиль(профили, "моё-дело", ["гарантия результата"], "лендинг")
            файл = self._прототип(врем, "моё-дело")
            код, вывод = self._прогнать([str(файл)], профили)
        self.assertEqual(код, 1, вывод)
        self.assertIn("нельзя говорить", вывод)
        self.assertIn("тип из профиля", вывод)
        self.assertNotIn("не найден", вывод)

    def test_флаг_профиль_переопределяет_шапку(self):
        with tempfile.TemporaryDirectory() as врем:
            врем = Path(врем)
            профили = врем / "профили"
            self._положить_профиль(профили, "мягкое", [], "визитка")
            self._положить_профиль(профили, "строгое", ["гарантия результата"], "визитка")
            файл = self._прототип(врем, "мягкое")
            без_флага = self._прогнать([str(файл)], профили)
            с_флагом = self._прогнать([str(файл), "--профиль", "строгое"], профили)
        self.assertNotIn("нельзя говорить", без_флага[1])
        self.assertIn("нельзя говорить", с_флагом[1])

    def test_без_профиля_отключает_чтение(self):
        with tempfile.TemporaryDirectory() as врем:
            врем = Path(врем)
            профили = врем / "профили"
            self._положить_профиль(профили, "моё-дело", ["гарантия результата"], "лендинг")
            файл = self._прототип(врем, "моё-дело")
            код, вывод = self._прогнать([str(файл), "--без-профиля"], профили)
        self.assertEqual(код, 0, вывод)
