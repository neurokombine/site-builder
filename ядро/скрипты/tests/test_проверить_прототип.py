def без_заметки_о_схеме(находки):
    """«Чистая» фикстура на шаге 4 схему ещё не выбрала — это одна ожидаемая ℹ️, а не брак.

    Три теста ниже проверяют, что служебные слоты не дают ЛОЖНЫХ находок; заметка про схему
    к делу не относится и должна остаться в списке единственной, если вообще есть.
    """
    return [н for н in находки if н["что"] != СХЕМА_НЕ_ВЫБРАНА_ТЕКСТ]


