#!/usr/bin/env python3
"""Пересобрать первые экраны фикстуры `экраны-все` из нынешних рецептов.

Зачем это отдельный файл. Фикстура `ядро/скрипты/tests/фикстуры/экраны-все/` изображает уже
собранный сайт: её читает браузерный гейт `test_флаги_дизайна` и самопроверка `selftest.py`. Пока
рецепты `ядро/блоки/**` правились, а фикстура — нет, гейт три фикс-раунда подряд мерил вчерашние
экраны и оставался зелёным: проверка сторожила не то, что собирается.

Как теперь не разойтись молча: первые экраны фикстуры собираются ровно тем же кодом, что и
настоящий сайт (`витрина.заполнить_первый_экран` на текстах образцового прототипа), а тест
`test_блоки.test_фикстура_первых_экранов_не_отстала_от_рецептов` каждый раз собирает их заново в
памяти и сверяет с тем, что лежит на диске. Разошлись — тест падает и называет команду:

    .venv/bin/python ядро/скрипты/tests/пересобрать_фикстуру.py

Остальные 19 блоков фикстуры (02–09) писаны руками и здесь не трогаются: их разметка от правок
первого экрана не зависит, а переписывать их генератором значило бы выбросить их тексты.

Две тонкости, из-за которых это не просто «подставь значения»:
1. `{{СВЯЗЬ:…}}` в фикстуре ОСТАЁТСЯ — кнопку связи ставит `собрать.py` уже из профиля работы;
   если подставить её здесь, фикстура унесёт с собой чужой адрес. Прячем слот на время заполнения.
2. Номер экрана у каждого файла свой (в фикстуре все 38 блоков живут на одной странице, и `id`
   обязаны быть разными) — берём его из файла, который пересобираем, а не выдаём заново.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

СКРИПТЫ = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(СКРИПТЫ))

import витрина  # noqa: E402
import собрать  # noqa: E402

ФИКСТУРЫ = Path(__file__).resolve().parent / "фикстуры"
ЭКРАНЫ = ФИКСТУРЫ / "экраны-все"
ОБРАЗЕЦ = ФИКСТУРЫ / "работа-образец"
ЗАМОК_СВЯЗИ = "@@СВЯЗЬ@@"   # слот связи прячем от подстановки: его ставит собрать.py из профиля
НОМЕР_ЭКРАНА = re.compile(r'id="экран-(\d+)"')


def первые_экраны() -> dict[Path, str]:
    """{файл фикстуры: как он должен выглядеть по нынешним рецептам}. Тексты — из образцового
    прототипа: ровно те, что увидит `собрать.py` на настоящей работе."""
    тексты = витрина.тексты_первого_экрана(ОБРАЗЕЦ)
    if not тексты:
        raise SystemExit(f"не читается прототип образца: {ОБРАЗЕЦ / 'прототип.md'}")
    итог: dict[Path, str] = {}
    for файл in sorted(ЭКРАНЫ.glob("01-первый-экран-*.html")):
        схема, набор = файл.stem.split("01-первый-экран-", 1)[1].rsplit("-", 1)
        рецепт = собрать.БЛОКИ / набор / f"01-первый-экран-{схема}.html"
        номер = НОМЕР_ЭКРАНА.search(файл.read_text(encoding="utf-8"))
        шаблон = рецепт.read_text(encoding="utf-8").replace("{{СВЯЗЬ:", ЗАМОК_СВЯЗИ)
        готово = витрина.заполнить_первый_экран(шаблон, {**тексты, "пресет": набор}, None, None)
        итог[файл] = готово.replace(ЗАМОК_СВЯЗИ, "{{СВЯЗЬ:").replace(
            'id="экран-1"', f'id="экран-{номер.group(1) if номер else 1}"')
    return итог


def разошлись() -> list[str]:
    """Имена файлов, которые на диске отстали от рецептов. Пусто — фикстура свежая."""
    return [файл.name for файл, надо in первые_экраны().items()
            if файл.read_text(encoding="utf-8") != надо]


if __name__ == "__main__":
    сколько = 0
    for файл, надо in первые_экраны().items():
        if файл.read_text(encoding="utf-8") != надо:
            файл.write_text(надо, encoding="utf-8")
            print(f"пересобран: {файл.name}")
            сколько += 1
    print(f"Готово: пересобрано {сколько}; фикстура снова совпадает с рецептами." if сколько
          else "Фикстура и так совпадает с рецептами — пересобирать нечего.")
