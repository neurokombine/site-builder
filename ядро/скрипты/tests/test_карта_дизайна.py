"""Задача 12: сироты и битые ссылки после дробления `дизайн-система.md` на `ядро/дизайн/`.

`test_карта.py` смотрит только на файлы прямо в `ядро/*.md` (`ЯДРО.glob("*.md")` не рекурсивный) —
поддиректория `ядро/дизайн/` проходит мимо него насквозь. Ровно это место ломается молча при
дроблении: задача 12 развела `дизайн-система.md` на пять файлов (карта + `палитра-и-токены.md`,
`детали.md`, `схемы-обложек.md`, `ритм-и-громкость.md`), и это главная поломка такого рефакторинга —
без отдельного теста через два-три следующих этапа половина правил потеряется из карты незамеченной:
файл переименовали или убрали, а ссылка на него осталась, или новый файл завели, а в CLAUDE.md
забыли назвать.

Две проверки:
1. **Сирота** — каждый `ядро/дизайн/*.md` должен быть назван (бэктиками, голым именем) в CLAUDE.md,
   как уже принято для файлов прямо в `ядро/`.
2. **Битая ссылка** — каждая ссылка вида `` `ядро/…/имя.md` `` (полный путь от корня, начинается на
   «ядро/») в любом документе ядра или в CLAUDE.md обязана вести на файл, который реально лежит по
   этому пути. Проверяются и `.py`, чтобы заодно ловить опечатки в путях к скриптам.
"""
import re
import unittest
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[3]
ЯДРО = КОРЕНЬ / "ядро"
ДИЗАЙН = ЯДРО / "дизайн"

# Ссылка с явным путём от корня, начинающимся на «ядро/»: `ядро/дизайн/детали.md`, `ядро/блоки.md`,
# `ядро/скрипты/tests/test_карта.py`. Путь целиком — одна группа, чтобы проверить именно тот файл,
# что назван, а не какой-нибудь файл с таким же голым именем в другом месте.
ССЫЛКА_С_ПУТЁМ_ЯДРА = re.compile(r"`(ядро/[\w\-]+(?:/[\w\-]+)*\.(?:md|py))`")

# Документы, где такие ссылки на дизайн-систему (и вообще на файлы ядра) встречаются или могут
# появиться: сама карта плюс все правила ядра верхнего уровня и всё, что уже лежит в ядро/дизайн/.
ДОКУМЕНТЫ = sorted([КОРЕНЬ / "CLAUDE.md", *ЯДРО.glob("*.md"), *ДИЗАЙН.glob("*.md")])


class КартаДизайнаТесты(unittest.TestCase):
    def test_каждый_файл_дизайн_папки_назван_в_карте(self):
        карта = (КОРЕНЬ / "CLAUDE.md").read_text(encoding="utf-8")
        файлы = sorted(ДИЗАЙН.glob("*.md"))
        self.assertTrue(файлы, "ядро/дизайн/ пуст или не существует — сверь путь в этом тесте")
        for файл in файлы:
            with self.subTest(файл=файл.name):
                self.assertIn(f"`{файл.name}`", карта,
                              f"{файл.name} лежит в ядро/дизайн/, но CLAUDE.md о нём молчит")

    def test_ссылки_с_путём_ядра_не_битые(self):
        найдено = 0
        for документ in ДОКУМЕНТЫ:
            текст = документ.read_text(encoding="utf-8")
            for путь in ССЫЛКА_С_ПУТЁМ_ЯДРА.findall(текст):
                найдено += 1
                with self.subTest(документ=str(документ.relative_to(КОРЕНЬ)), ссылка=путь):
                    self.assertTrue(
                        (КОРЕНЬ / путь).exists(),
                        f"{документ.relative_to(КОРЕНЬ)} ссылается на `{путь}`, а такого файла нет")
        # Регулярка сломалась (например, из-за правки формата ссылок) — самих ссылок наберётся
        # намного меньше сорока; порог — сигнал «проверь тест», а не число, высеченное в камне.
        self.assertGreater(найдено, 40,
                            "ссылок с путём «ядро/…» нашлось подозрительно мало — проверь регулярку")


if __name__ == "__main__":
    unittest.main()
