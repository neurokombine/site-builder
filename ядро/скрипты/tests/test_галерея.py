"""Галерея: у каждого примера есть снимок и описание, и каждый тип экрана чем-то показан.

Галерея — не ядро вёрстки. Сборка её не читает (это сторожит `test_не_импортируется_ядром`):
файлы в `ядро/галерея/**` смотрят глазами человек и нейросеть перед тем, как верстать свой экран.
Отсюда и предмет проверки — не разметка, а комплектность полки:

* **четыре файла у каждого примера** — сам экран, два снимка и описание. Снимка нет — пример
  никто не откроет (кто станет собирать страницу, чтобы посмотреть, как выглядит чужой экран);
  описания нет — по снимку не понять, что в нём хорошего и почему он тут лежит.
* **описание по формату** — пять строк, одинаковых у всех: тип, откуда взят, ключ, что хорошо,
  какие детали. Разнобой описаний превращает полку в свалку: глазами её листают подряд.
* **тип из словаря типов** (`собрать.ТИПЫ_НАБОРА`) — выдуманный тип уводит в экран, которого
  система не знает, и в инструкцию, которой нет.
* **у каждого типа ниже обложки есть пример** — иначе верстальщик открывает `ядро/экраны/<тип>.md`,
  идёт по ссылке «компоновки» и упирается в пустую папку.
* **каталог знает каждый пример** — `каталог.html` и есть вход в галерею; не назвал пример —
  пример не существует.
"""
import re
import subprocess
import sys
import unittest
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(КОРЕНЬ / "ядро" / "скрипты"))
import собрать  # noqa: E402

ЯДРО = КОРЕНЬ / "ядро"
ГАЛЕРЕЯ = ЯДРО / "галерея"
ПРИМЕРЫ = ГАЛЕРЕЯ / "примеры"
СТРАНИЦА_ЦЕЛИКОМ = ПРИМЕРЫ / "страница-целиком"
БРЕНД = ГАЛЕРЕЯ / "бренд"
КАТАЛОГ = ГАЛЕРЕЯ / "каталог.html"
ДОКУМЕНТ = ЯДРО / "галерея.md"
СКРИПТ = ЯДРО / "скрипты" / "галерея.py"

ЧЕТЫРЕ_ФАЙЛА = {"экран.html", "компьютер.png", "телефон.png", "о-примере.md"}
ПОЛЯ_ПРИМЕРА = ("- Тип:", "- Откуда:", "- Ключ:", "- Что хорошо:", "- Детали:")
ПОЛЯ_РЕФЕРЕНСА = ("- Что это:", "- Что берём:", "- Что не берём:")
КЛЮЧИ = {"светлый", "тёмный"}
ТИПЫ = sorted({т for типы in собрать.ТИПЫ_НАБОРА.values() for т in типы})
ПОТОЛОК_ДОКУМЕНТА = 100
# Всё, без чего `галерея.py --снять` не соберёт пример. Каждый файл обязан ехать вместе с системой:
# на машине человека есть только то, что лежит в хранилище версий.
ПОД_ВЕРСИЕЙ = [Path("ядро/скрипты/tests/фикстуры/профиль-образец/profile.json"),
               Path("ядро/галерея/образец/прототип.md"), Path("ядро/галерея/образец/дизайн.md"),
               Path("ядро/галерея/образец/поиск.md"), Path("ядро/галерея/образец/тексты.json")]


def папки_примеров() -> list[Path]:
    """Полка рецептов: `примеры/<тип>/<набор>/`. Полка страниц целиком устроена иначе — она
    показывает не экран, а цветовую партитуру всей страницы, и лежит отдельно."""
    итог = []
    for тип in sorted(п for п in ПРИМЕРЫ.iterdir() if п.is_dir() and п.name != "страница-целиком"):
        итог += sorted(п for п in тип.iterdir() if п.is_dir())
    return итог


def поля(файл: Path, имена: tuple[str, ...]) -> dict[str, str]:
    """Описание примера → {поле: значение}. Значение бывает многострочным — до следующего поля."""
    текст = файл.read_text(encoding="utf-8")
    итог, ключ = {}, None
    for строка in текст.splitlines():
        начало = next((и for и in имена if строка.startswith(и)), None)
        if начало:
            ключ = начало
            итог[ключ] = строка[len(начало):].strip()
        elif ключ and строка.strip():
            итог[ключ] += " " + строка.strip()
        elif not строка.strip():
            ключ = None
    return итог


class ПолкаПримеров(unittest.TestCase):
    def test_у_каждого_примера_четыре_файла(self):
        """Экран, два снимка и описание — меньше нельзя, лишнего в папке примера не держим."""
        папки = папки_примеров()
        self.assertGreaterEqual(len(папки), len(ТИПЫ), "примеров меньше, чем типов экранов")
        for папка in папки:
            with self.subTest(пример=папка.relative_to(ПРИМЕРЫ).as_posix()):
                self.assertEqual({ф.name for ф in папка.iterdir() if ф.is_file()}, ЧЕТЫРЕ_ФАЙЛА)
                for снимок in ("компьютер.png", "телефон.png"):
                    self.assertGreater((папка / снимок).stat().st_size, 1000,
                                       f"{снимок} подозрительно пустой")

    def test_описание_примера_по_формату(self):
        """Пять полей, все непустые: полку листают глазами, и разнобой в описаниях её ломает."""
        for папка in папки_примеров():
            значения = поля(папка / "о-примере.md", ПОЛЯ_ПРИМЕРА)
            with self.subTest(пример=папка.relative_to(ПРИМЕРЫ).as_posix()):
                self.assertEqual(sorted(значения), sorted(ПОЛЯ_ПРИМЕРА), "не все поля на месте")
                for поле, значение in значения.items():
                    self.assertTrue(значение.strip(), f"поле «{поле}» пустое")
                self.assertIn(значения["- Ключ:"].strip(), КЛЮЧИ)
                self.assertGreaterEqual(len(значения["- Что хорошо:"].split()), 8,
                                        "«Что хорошо» в одно слово ничего не объясняет")

    def test_тип_примера_из_словаря_типов(self):
        """Тип берётся не из головы, а из состава наборов (`собрать.ТИПЫ_НАБОРА`)."""
        for папка in папки_примеров():
            тип, набор = папка.parent.name, папка.name
            значения = поля(папка / "о-примере.md", ПОЛЯ_ПРИМЕРА)
            with self.subTest(пример=папка.relative_to(ПРИМЕРЫ).as_posix()):
                self.assertIn(тип, ТИПЫ, "такого типа экрана нет ни в одном наборе")
                self.assertIn(набор, собрать.ТИПЫ_НАБОРА, "папка примера названа не набором")
                self.assertIn(тип, собрать.ТИПЫ_НАБОРА[набор], "в этом наборе такого экрана нет")
                self.assertEqual(значения["- Тип:"].strip(), тип, "в описании другой тип")

    def test_у_каждого_типа_ниже_обложки_есть_пример(self):
        """Ссылка «компоновки» из инструкции обязана привести к живому примеру, а не к пустой папке."""
        показаны = {папка.parent.name for папка in папки_примеров()}
        for тип in ТИПЫ:
            with self.subTest(тип=тип):
                self.assertIn(тип, показаны, f"тип «{тип}» не показан ни одним примером")

    def test_каталог_упоминает_каждый_пример(self):
        """Каталог — вход в галерею: снимок каждого примера в нём, и путь к нему написан словами."""
        self.assertTrue(КАТАЛОГ.is_file(), "нет ядро/галерея/каталог.html — собери `галерея.py --каталог`")
        текст = КАТАЛОГ.read_text(encoding="utf-8")
        for папка in папки_примеров():
            путь = папка.relative_to(ГАЛЕРЕЯ).as_posix()
            with self.subTest(пример=путь):
                self.assertIn(f"{путь}/компьютер.png", текст, "в каталоге нет снимка примера")
                self.assertIn(f"{путь}/телефон.png", текст, "в каталоге нет телефонного снимка")
        for папка in sorted(п for п in СТРАНИЦА_ЦЕЛИКОМ.iterdir() if п.is_dir()):
            путь = папка.relative_to(ГАЛЕРЕЯ).as_posix()
            with self.subTest(страница=путь):
                self.assertIn(путь, текст, "в каталоге нет цветового варианта")

    def test_снимки_каталога_лежат_на_месте(self):
        """Пути в каталоге относительные, от `ядро/галерея/`: каталог открывают файлом, не сервером."""
        текст = КАТАЛОГ.read_text(encoding="utf-8")
        адреса = set(re.findall(r'(?:src|href)="([^":]+)"', текст))
        self.assertGreater(len(адреса), 10, "в каталоге почти нет ссылок — проверять нечего")
        for адрес in sorted(адреса):
            if адрес.startswith("#"):
                continue
            with self.subTest(адрес=адрес):
                self.assertFalse(адрес.startswith("/"), "путь от корня диска в каталоге не откроется")
                self.assertTrue((ГАЛЕРЕЯ / адрес).exists(), f"каталог ссылается на {адрес}, а его нет")


class ПолкаСтраницЦеликом(unittest.TestCase):
    def test_три_цветовых_варианта_со_снимками_и_описанием(self):
        папки = sorted(п for п in СТРАНИЦА_ЦЕЛИКОМ.iterdir() if п.is_dir())
        self.assertEqual(len(папки), 3, "цветовых вариантов страницы должно быть три")
        for папка in папки:
            with self.subTest(вариант=папка.name):
                self.assertTrue((папка / "страница.html").is_file(), "нет страница.html")
                self.assertTrue((папка / "о-примере.md").is_file(), "нет о-примере.md")
                снимки = sorted(ф.name for ф in папка.glob("*.png"))
                self.assertGreaterEqual(len(снимки), 8, f"снимков по экранам мало: {снимки}")
                self.assertIn("телефон.png", снимки)

    def test_описание_варианта_называет_партитуру_и_выбор(self):
        for папка in sorted(п for п in СТРАНИЦА_ЦЕЛИКОМ.iterdir() if п.is_dir()):
            текст = (папка / "о-примере.md").read_text(encoding="utf-8")
            with self.subTest(вариант=папка.name):
                self.assertIn("- Выбор владелицы:", текст)
                self.assertLessEqual(len(текст.splitlines()), 20, "описание варианта — до 15 строк")


class ПолкаБренда(unittest.TestCase):
    def test_у_каждого_референса_снимки_и_описание(self):
        папки = sorted(п for п in БРЕНД.iterdir() if п.is_dir())
        self.assertGreaterEqual(len(папки), 2, "на полке бренда меньше двух референсов")
        for папка in папки:
            with self.subTest(референс=папка.name):
                self.assertTrue((папка / "о-референсе.md").is_file(), "нет о-референсе.md")
                self.assertTrue(sorted(папка.glob("*.png")), "нет ни одного снимка")
                значения = поля(папка / "о-референсе.md", ПОЛЯ_РЕФЕРЕНСА)
                self.assertEqual(sorted(значения), sorted(ПОЛЯ_РЕФЕРЕНСА))
                for поле, значение in значения.items():
                    self.assertGreaterEqual(len(значение.split()), 5, f"поле «{поле}» в два слова")


class ГалереяНеЯдроВёрстки(unittest.TestCase):
    def test_образец_для_сборки_примеров_едет_вместе_с_системой(self):
        """Снять свой пример должен уметь человек, у которого система только что скачана.

        Папки `сайты/*` в хранилище версий не входят — их на его машине нет вовсе. Возьми скрипт
        профиль оттуда, и первый же шаг «как добавить свой пример» упал бы трассировкой на файле,
        которого никто не удалял: его там и не было.
        """
        текст = СКРИПТ.read_text(encoding="utf-8")
        self.assertNotIn("сайты/профиль-образец", текст)
        self.assertNotIn('"сайты" / "профиль-образец"', текст)
        под_версией = subprocess.run(["git", "ls-files", "--error-unmatch"] + [п.as_posix() for п in ПОД_ВЕРСИЕЙ],
                                     cwd=КОРЕНЬ, capture_output=True, text=True)
        self.assertEqual(под_версией.returncode, 0,
                         f"образец сборки примеров не под версией: {под_версией.stderr.strip()}")

    def test_не_импортируется_ядром_сборки(self):
        """Сборка и проверка галерею не читают: она для глаз, а не для подстановки в страницу."""
        self.assertTrue(СКРИПТ.is_file(), "нет ядро/скрипты/галерея.py")
        for имя in ("собрать.py", "проверить.py"):
            текст = (ЯДРО / "скрипты" / имя).read_text(encoding="utf-8")
            with self.subTest(файл=имя):
                self.assertNotIn("import галерея", текст, f"{имя} импортирует галерею")

    def test_документ_есть_и_не_растёт(self):
        self.assertTrue(ДОКУМЕНТ.is_file(), "нет ядро/галерея.md")
        строк = len(ДОКУМЕНТ.read_text(encoding="utf-8").splitlines())
        self.assertLessEqual(строк, ПОТОЛОК_ДОКУМЕНТА, f"галерея.md: {строк} строк")

    def test_разбор_описания_собирает_многострочное_поле(self):
        """Проверка самого сторожа: «Что хорошо» пишут в две-три строки, и они одно поле."""
        образец = ("- Тип: боль\n- Откуда: рецепт лендинг\n- Ключ: тёмный\n"
                   "- Что хорошо: тихая секция без картинки,\n  плитки-роли под шапкой\n"
                   "- Детали: секция__шапка, роль\n")
        файл = Path(__file__).parent / "фикстуры" / "_о-примере-образец.md"
        файл.write_text(образец, encoding="utf-8")
        try:
            значения = поля(файл, ПОЛЯ_ПРИМЕРА)
            self.assertEqual(значения["- Тип:"], "боль")
            self.assertIn("плитки-роли", значения["- Что хорошо:"])
        finally:
            файл.unlink()


if __name__ == "__main__":
    unittest.main()
