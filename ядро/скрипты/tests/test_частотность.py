class СледыВходаВЯндекс(unittest.TestCase):
    СЕЙЧАС = 1_790_000_000.0

    def setUp(self):
        self.папка = Path(tempfile.mkdtemp())
        self.профиль = self.папка / "профиль"
        self.журнал = self.папка / "частотность.txt"
        self.замок = self.папка / ".замок"

    def кука(self):
        return lambda профиль: ч.кука_яндекса(профиль, сейчас=self.СЕЙЧАС)

    def test_кука_жива(self):
        база_кук(self.профиль, [(".yandex.ru", "Session_id", по_chrome(self.СЕЙЧАС + 86400), 1)])
        self.assertEqual(ч.кука_яндекса(self.профиль, сейчас=self.СЕЙЧАС), "жива")

    def test_кука_истекла(self):
        база_кук(self.профиль, [(".yandex.ru", "Session_id", по_chrome(self.СЕЙЧАС - 86400), 1)])
        self.assertEqual(ч.кука_яндекса(self.профиль, сейчас=self.СЕЙЧАС), "истекла")

    def test_чужие_куки_не_в_счёт(self):
        база_кук(self.профиль, [(".chatgpt.com", "Session_id", по_chrome(self.СЕЙЧАС + 9e5), 1),
                                (".yandex.ru", "yandexuid", по_chrome(self.СЕЙЧАС + 9e5), 1)])
        self.assertEqual(ч.кука_яндекса(self.профиль, сейчас=self.СЕЙЧАС), "нет")

    def test_нет_базы_и_битая_база(self):
        self.assertEqual(ч.кука_яндекса(self.профиль), "нет")
        путь = self.профиль / "Default" / "Network" / "Cookies"
        путь.parent.mkdir(parents=True)
        путь.write_bytes(b"not a database at all" * 100)
        self.assertIsNone(ч.кука_яндекса(self.профиль))

    def test_решение_по_следам(self):
        случаи = [("жива", False, ч.ЯНДЕКС_ГОТОВ), ("истекла", False, ч.ЯНДЕКС_ВХОД_УМЕР),
                  ("нет", False, ч.ЯНДЕКС_НЕ_ВХОДИЛИ), ("нет", True, ч.ЯНДЕКС_ВХОД_УМЕР),
                  (None, True, ч.ЯНДЕКС_ГОТОВ), (None, False, ч.ЯНДЕКС_НЕ_ВХОДИЛИ)]
        for кука, метка, ждём in случаи:
            with self.subTest(кука=кука, метка=метка):
                self.журнал.write_text(ч.МЕТКА_ВХОДА + " руками\n" if метка else "", encoding="utf-8")
                self.assertEqual(ч.яндекс_по_следам(self.профиль, self.журнал, lambda п: кука), ждём)

