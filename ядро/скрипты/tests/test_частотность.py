def база_кук(профиль: Path, ряды):
    путь = профиль / "Default" / "Network" / "Cookies"
    путь.parent.mkdir(parents=True)
    связь = sqlite3.connect(путь)
    связь.execute("create table cookies (host_key text, name text, expires_utc integer, "
                  "has_expires integer)")
    связь.executemany("insert into cookies values (?,?,?,?)", ряды)
    связь.commit()
    связь.close()


