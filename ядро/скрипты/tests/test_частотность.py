@contextmanager
def фальшивое_подключение(порт):
    class Страница:
        def close(self):
            pass

    class Контекст:
        def new_page(self):
            return Страница()
    yield Контекст()


class Прогон(unittest.TestCase):
    """`снять` и `команда_фразы` с подменённым окном: браузер не поднимается."""

    def setUp(self):
        self.папка = Path(tempfile.mkdtemp())
        self.работа = self.папка / "сайт-x"
        self.работа.mkdir()
        self.стек = contextlib.ExitStack()
        for имя, значение in (("занять_замок", lambda *а: True), ("отпустить_замок", lambda *а: None),
                              ("порт_браузера", lambda *а: 9500),
                              ("подключение", фальшивое_подключение)):
            self.стек.enter_context(patch.object(кисть, имя, значение))
        self.стек.enter_context(patch.object(ч, "перейти", lambda *а: None))
        self.стек.enter_context(patch.object(ч, "ЖУРНАЛ", self.папка / "частотность.txt"))
        self.стек.enter_context(patch.object(ч, "ОБРАЗЦЫ", self.папка / "образцы"))
        self.стек.enter_context(patch.object(ч.time, "sleep", lambda с: None))
        self.запросы = []
        self.вкладка_похожих = 0
        def снять_похожие(страница, запрос, *а):
            self.вкладка_похожих += 1
            return [("похожий", 10)]
        self.стек.enter_context(patch.object(ч, "снять_похожие", снять_похожие))

    def tearDown(self):
        self.стек.close()

    def ответы(self, по_запросу):
        def снять_запрос(страница, запрос, регион):
            self.запросы.append((запрос, регион))
            ответ = по_запросу(запрос)
            if isinstance(ответ, BaseException):
                raise ответ
            return ответ
        self.стек.enter_context(patch.object(ч, "снять_запрос", снять_запрос))

