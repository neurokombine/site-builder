class ФальшиваяСтраница:
    def __init__(self, кадры):
        self.кадры = list(кадры)
        self.и = 0

    @property
    def url(self):
        return self.кадры[min(self.и, len(self.кадры) - 1)][0]

    def evaluate(self, *_):
        return self.кадры[min(self.и, len(self.кадры) - 1)][1]

    def дальше(self):
        self.и += 1


