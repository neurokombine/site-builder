def вырез_с_каймой(путь: Path, фон_съёмки=(20, 20, 20), альфа=128, размер=(400, 600)) -> Path:
    """Вырез, как его отдаёт нейросеть: фигура, а по контуру полоска, где кисточка захватила
    студийный фон. В кромке лежит смесь `край × α + фон × (1 − α)` — ровно то, что мерит `фон_съёмки`."""
    край, фигура = (160, 150, 140), (100, 120, 300, 560)
    к = Image.new("RGBA", размер, (0, 0, 0, 0))
    к.paste(край + (255,), фигура)
    д = обложка.ШИРИНА_КАЙМЫ
    смесь = tuple(round(к_ * альфа / 255 + ф * (1 - альфа / 255)) for к_, ф in zip(край, фон_съёмки))
    л, в, п_, н = фигура
    for i in range(д):                     # рамка в ШИРИНА_КАЙМЫ пикселей внутрь от границы фигуры
        для_рамки = Image.new("RGBA", (п_ - л - 2 * i, н - в - 2 * i), смесь + (альфа,))
        к.paste(для_рамки, (л + i, в + i))
    к.paste(Image.new("RGBA", (п_ - л - 2 * д, н - в - 2 * д), край + (255,)), (л + д, в + д))
    к.save(путь)
    return путь


