# Настоящая фотография примера — на ней проверяем фотографию и растворённый край, а не синтетику.
ПРИМЕР_ФОТО = ROOT / "ядро" / "обложки" / "пример-студия" / "img" / "portret-3x4.webp"


def с_растворённым_низом(путь: Path) -> Path:
    """Настоящая фотография примера, у которой низ растворён тем же `_растворить_низ`, каким его
    растворяет система: прозрачные пиксели в файле есть, а вырезом он от этого не стал."""
    with Image.open(ПРИМЕР_ФОТО) as файл:
        кадр = файл.convert("RGBA")
    обложка._растворить_низ(кадр, Image.new("L", кадр.size, 255), (0, 0) + кадр.size).save(путь)
    return путь


def вырез_png(путь: Path, рамка=(100, 60, 300, 560), размер=(400, 600)) -> Path:
    к = Image.new("RGBA", размер, (0, 0, 0, 0))
    к.paste((120, 90, 60, 255), рамка)
    к.save(путь)
    return путь


