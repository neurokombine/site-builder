def фигура_png(путь: Path, кадр=(1024, 1536), макушка=97, голова=210, ширина_головы=272,
               низ=1469, плечи=1.9, центр=512) -> Path:
    """Грубый человек-силуэт: голова кругом, ниже — шея, плечи и корпус. Ровно то, по чему `голова()`
    ищет впадину-шею, и ничего лишнего: тесту нужна геометрия, а не фотография."""
    from PIL import ImageDraw
    к = Image.new("RGBA", кадр, (0, 0, 0, 0))
    р = ImageDraw.Draw(к)
    р.ellipse((центр - ширина_головы // 2, макушка, центр + ширина_головы // 2, макушка + голова), fill=(120, 90, 60, 255))
    шея = макушка + голова
    р.rectangle((центр - ширина_головы // 5, шея - голова // 8, центр + ширина_головы // 5, шея + голова // 10), fill=(120, 90, 60, 255))
    корпус = int(ширина_головы * плечи)
    р.rectangle((центр - корпус // 2, шея + голова // 10, центр + корпус // 2, низ), fill=(120, 90, 60, 255))
    к.save(путь)
    return путь


class РамкаВыреза(unittest.TestCase):
    """Дело фикс-раунда Е: числа кропа в стилях сняты с выреза в полный рост. Ученик принесёт кадр по
    грудь — и схема увеличит его вдвое сильнее нужного. Рамку держит скрипт, а не стиль."""

    def test_три_кадра_одного_человека_встают_одинаково(self):
        with tempfile.TemporaryDirectory() as д:
            д = Path(д)
            рост = фигура_png(д / "rost.png")
            with Image.open(рост) as к:
                по_пояс = к.crop((0, 0, к.width, 850))
                по_грудь = к.crop((120, 40, к.width - 90, 620))
            по_пояс.save(д / "poyas.png")
            по_грудь.save(д / "grud.png")
            до = {имя: обложка.замеры_рамки(д / f"{имя}.png") for имя in ("rost", "poyas", "grud")}
            self.assertGreater(до["grud"]["голова"], до["poyas"]["голова"])      # чем ближе кадр, тем крупнее голова
            self.assertGreater(до["poyas"]["голова"], до["rost"]["голова"])
            после, пути = {}, {}
            for имя in ("rost", "poyas", "grud"):
                итог = обложка.рамка_выреза(д / f"{имя}.png", д / "out" / имя)
                пути[имя] = итог["путь"]
                после[имя] = обложка.замеры_рамки(итог["путь"])
                with Image.open(итог["путь"]) as к:
                    self.assertEqual(к.size, (обложка.ШИРИНА_РАМКИ, обложка.ШИРИНА_РАМКИ * 3 // 2))
                self.assertEqual(обложка.касается_краёв(итог["путь"]), [])       # схема «центр» примет любой из трёх
            for имя, з in после.items():
                self.assertAlmostEqual(з["голова"], обложка.ГОЛОВА_В_РАМКЕ, delta=обложка.ДОПУСК_РАМКИ, msg=имя)
                self.assertAlmostEqual(з["макушка"], обложка.МАКУШКА_В_РАМКЕ, delta=обложка.ДОПУСК_РАМКИ, msg=имя)
                self.assertAlmostEqual(з["лицо_x"], .5, delta=обложка.ДОПУСК_РАМКИ, msg=имя)
                self.assertTrue(з["в_рамке"], имя)
            self.assertEqual(len({обложка.фокус(п) for п in пути.values()}), 1)   # одна точка лица на все три кадра

    def test_кадр_в_рамке_не_трогаем(self):
        with tempfile.TemporaryDirectory() as д:
            рост = фигура_png(Path(д) / "rost.png")
            итог = обложка.рамка_выреза(рост, Path(д) / "out")
            self.assertFalse(итог["приведено"])
            self.assertEqual(итог["путь"], рост)              # лишнего пережатия чужого файла не делаем

    def test_фотография_с_мягким_краем_не_вырез(self):
        """`картинка--край` растворяет низ фото прямо в файле — прозрачные пиксели есть, а вырезом это не стало.

        Задача 7: растворённый низ делаем тем же `_растворить_низ`, которым его делает система, и на
        настоящем кадре примера, а не градиентом во весь файл. Синтетика гасила альфу от макушки до
        пят и оставляла сквозной прозрачности восьмую часть кадра — столько не растворяет ни одна
        схема, и проверялся на ней не «мягкий край», а небывалый файл."""
        with tempfile.TemporaryDirectory() as д:
            фото = с_растворённым_низом(Path(д) / "portret.png")
            self.assertGreater(обложка.доля_прозрачного(фото), 0, "низ не растворился — проверять нечего")
            self.assertLess(обложка.доля_прозрачного(фото), обложка.ПОРОГ_ПРОЗРАЧНОГО,
                            "растворённая кромка не должна дотягивать до порога выреза")
            self.assertEqual(обложка._разбор(фото)[0], "мягкий-край")
            self.assertIsNone(обложка.силуэт(фото))
            self.assertIsNone(обложка.замеры_рамки(фото))
            self.assertEqual(обложка.фокус(фото), обложка.ФОКУС_ФОТО)
            self.assertFalse(обложка.рамка_выреза(фото, Path(д) / "out")["приведено"])

    def test_пример_ядра_лежит_ровно_в_рамке(self):
        """Контракт: макеты рисовались на этом вырезе, и он же — эталон рамки. Разъедется — разъедутся и числа стилей."""
        з = обложка.замеры_рамки(ROOT / "ядро/обложки/пример-студия/img/portret-vyrez.webp")
        self.assertIsNotNone(з)
        self.assertTrue(з["в_рамке"], з)

    def test_широкую_фигуру_ужимаем_и_говорим(self):
        with tempfile.TemporaryDirectory() as д:
            широкий = фигура_png(Path(д) / "shirokiy.png", кадр=(1200, 900), макушка=20, голова=90,
                                 ширина_головы=110, низ=880, плечи=9, центр=600)
            итог = обложка.рамка_выреза(широкий, Path(д) / "out")
            self.assertTrue(итог["приведено"])
            self.assertIn("шире рамки", итог["предупреждение"])
            self.assertEqual(обложка.касается_краёв(итог["путь"]), [])


ЦЕНТР_У_ЩИТКА = 700     # человек стоит не по центру кадра, а сбоку — как на живом кадре электрика


def фигура_с_рукой(путь: Path, центр: int = ЦЕНТР_У_ЩИТКА, **ещё) -> Path:
    """Та же фигура, но с рукой, вытянутой в сторону: кисть висит отдельным пятном на высоте головы.
    Так снят живой кадр электрика — и именно на нём две мерки системы разошлись."""
    from PIL import ImageDraw

    фигура_png(путь, центр=центр, **ещё)
    with Image.open(путь) as к:
        к = к.convert("RGBA")
    р = ImageDraw.Draw(к)
    р.rectangle((30, 150, 420, 260), fill=(120, 90, 60, 255))       # рука к щитку: отдельное пятно на высоте головы
    к.save(путь)
    return путь


class ОднаМеркаВыреза(unittest.TestCase):
    """Задача 7: «это вырез» в системе означает одно и то же везде.

    Мерок было две — площадь сквозной прозрачности (`доля_прозрачного` против ПОРОГ_ПРОЗРАЧНОГО) и
    ширина рамки фигуры внутри `_разбор`. На фигуре с вытянутой рукой они давали противоположные
    ответы: «вырез» в находках кадра и «фотография с растворённым краем» в разборе, из-за чего
    голову — главный замер заказанного кадра — не искали вовсе."""

    def test_широкий_вырез_остаётся_вырезом_и_голову_видно(self):
        with tempfile.TemporaryDirectory() as д:
            д = Path(д)
            свой = фигура_с_рукой(д / "s_rukoy.png")
            картинка = Image.open(свой)
            рамка = обложка._альфа(картинка).getbbox()
            self.assertGreater((рамка[2] - рамка[0]) / картинка.width, .9,
                               "рука должна развести рамку фигуры шире девяти десятых кадра — иначе случай не тот")
            self.assertGreater(обложка.доля_прозрачного(свой), обложка.ПОРОГ_ПРОЗРАЧНОГО)
            self.assertEqual(обложка._разбор(свой)[0], "вырез-человека")
            self.assertIsNotNone(обложка.замеры_рамки(свой))

    def test_рука_в_стороне_не_меняет_замер_головы(self):
        """Голову ведём одним пятном от макушки: отдельная кисть на высоте головы в замер не входит."""
        with tempfile.TemporaryDirectory() as д:
            д = Path(д)
            без_руки = обложка.замеры_рамки(фигура_png(д / "bez.png", центр=ЦЕНТР_У_ЩИТКА))
            с_рукой = обложка.замеры_рамки(фигура_с_рукой(д / "s_rukoy.png"))
            self.assertAlmostEqual(с_рукой["голова"], без_руки["голова"], delta=.005)
            self.assertAlmostEqual(с_рукой["лицо_x"], без_руки["лицо_x"], delta=.005)
            self.assertAlmostEqual(обложка.подбородок_в_кадре(д / "s_rukoy.png"),
                                   обложка.подбородок_в_кадре(д / "bez.png"), delta=.005)

    def test_воротник_с_одной_стороны_не_обрезает_голову_по_губам(self):
        """Круг 1: голова наклонена, воротник подходит к бороде сбоку на уровне рта. Ширина вырастает на
        15 % — раньше здесь объявлялись плечи, и голова выходила обрезанной по губам. Вторая сторона
        ещё сужается — голова продолжается до места, где развернулась и она.

        Кадр рисованный, а не настоящий: у фото-вырезов репозитория шея под таким воротником сужается
        с другой стороны меньше допуска (эталон — на 16 px при допуске 17), и случай на них не
        воспроизводится; живой кадр электрика — временный файл, в репозиторий он не кладётся."""
        with tempfile.TemporaryDirectory() as д:
            д = Path(д)
            без = обложка.замеры_рамки(фигура_png(д / "bez.png"))
            с_воротником = фигура_png(д / "vorotnik.png")
            with Image.open(с_воротником) as к:
                к = к.convert("RGBA")
            from PIL import ImageDraw
            # фигура_png: макушка 97, голова 210, центр 512, корпус до x = 770 с y = 328; сужение
            # головы начинается на y ≈ 252, воротник встаёт справа на y = 265 и срастается с плечом
            ImageDraw.Draw(к).rectangle((612, 265, 770, 340), fill=(120, 90, 60, 255))
            к.save(с_воротником)
            с = обложка.замеры_рамки(с_воротником)
            self.assertIsNotNone(с, "голова с воротником не нашлась вовсе")
            self.assertAlmostEqual(с["голова"], без["голова"], delta=.005,
                                   msg="воротник сбоку обрезал голову — шея нашлась на уровне рта")

    def test_неправдоподобная_голова_не_даёт_числа(self):
        """Сторож формы: «голова» втрое выше своей ширины — это не голова, а шея, найденная не там.
        Честное «не вижу» лучше числа, которому поверят."""
        with tempfile.TemporaryDirectory() as д:
            вытянутая = фигура_png(Path(д) / "vytyanutaya.png", голова=700, ширина_головы=200, низ=1500)
            self.assertIsNone(обложка.замеры_рамки(вытянутая))
            self.assertEqual(обложка._разбор(вытянутая)[0], "вырез-без-головы")

    def test_обе_мерки_говорят_об_одном(self):
        """Разбор файла на вид и находки кадра считают вырезом ровно одно и то же — иначе система
        одним голосом просит вырез, а другим отказывается его видеть."""
        with tempfile.TemporaryDirectory() as д:
            д = Path(д)
            фото = д / "foto.jpg"
            Image.new("RGB", (800, 1067), (190, 180, 170)).save(фото)
            файлы = [фото, с_растворённым_низом(д / "s_krayem.png"), фигура_png(д / "rost.png"), фигура_с_рукой(д / "s_rukoy.png"),
                     вырез_png(д / "korobka.png"), ПРИМЕР_ВЫРЕЗА, ПРИМЕР_ФОТО]
            for ф in файлы:
                с_дыркой = обложка.доля_прозрачного(ф) > обложка.ПОРОГ_ПРОЗРАЧНОГО
                self.assertEqual(обложка._разбор(ф)[0].startswith("вырез"), с_дыркой, ф.name)


class КрупностьИВид(unittest.TestCase):
    """Фикс-раунд Ж. Дело 1: два замера кадра уезжают в стиль переменными, а не процентами, снятыми
    с нашего файла. Дело 2: близкий кадр подводит плашку «имя · опора» к подбородку — об этом надо
    предупредить до сборки. Дело 3: вырез не человека рамку не получает — и об этом надо сказать
    словами, а не промолчать."""

    def test_крупность_меряет_кадр_а_без_замера_отдаёт_эталон(self):
        with tempfile.TemporaryDirectory() as д:
            д = Path(д)
            рост = фигура_png(д / "rost.png")
            голова_доля, макушка_доля = обложка.крупность(рост)
            self.assertAlmostEqual(голова_доля, обложка.ГОЛОВА_В_РАМКЕ, delta=обложка.ДОПУСК_РАМКИ)
            self.assertAlmostEqual(макушка_доля, обложка.МАКУШКА_В_РАМКЕ, delta=обложка.ДОПУСК_РАМКИ)
            with Image.open(рост) as к:
                к.crop((120, 40, к.width - 90, 620)).save(д / "grud.png")
            крупнее = обложка.крупность(д / "grud.png")[0]
            self.assertGreater(крупнее, голова_доля * 1.5)      # тот же человек ближе — голова крупнее, и стиль об этом узнает
            фото = д / "foto.jpg"
            Image.new("RGB", (800, 1200), (200, 180, 160)).save(фото)
