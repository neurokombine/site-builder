"""Критик однородности: шесть правил на словарях и две страницы-фикстуры в браузере.

Правила — чистые функции над замером, поэтому большая часть тестов браузера не просит: словарь
секции описывает то же, что отдаёт `ЗАМЕР_JS`. Браузерных всего два — они сторожат сам замер:
`ровная.html` не должна дать ни одной находки, `разнобой.html` — ровно четыре.

Запуск из корня репозитория:
    .venv/bin/python -m unittest discover -s ядро/скрипты/tests -t .
"""
import shutil
import sys
import tempfile
import unittest
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(КОРЕНЬ / "ядро" / "скрипты"))

import глаза  # noqa: E402
import находки as дом_находок  # noqa: E402
import однородность  # noqa: E402
import проверить  # noqa: E402
import флаги_дизайна  # noqa: E402

ФИКСТУРЫ = Path(__file__).resolve().parent / "фикстуры" / "однородность"

# Палитра образца: те же цвета, что в `:root` фикстур и в профиле-образце тестов сборки.
ПАЛИТРА = {"--цвет-фон": "#FFFFFF", "--цвет-фон-2": "#F2F0EB", "--цвет-фон-карточки": "#FFFFFF",
           "--цвет-текст": "#1F2328", "--цвет-текст-мягкий": "#565D66",
           "--цвет-акцент": "#2C5C8A", "--цвет-акцент-тёмный": "#1D3F60",
           "--цвет-на-акценте": "#FFFFFF", "--цвет-линия": "#DAD6CE",
           "--цвет-тёмный-фон": "#1B2430", "--цвет-тёмный-текст": "#F3F1EC"}


def карточка(радиус=18, тень=True, фон="#ffffff", класс="карточка", вид=None):
    return {"класс": класс, "фон": фон, "радиус": радиус, "тень": тень,
            "вид": класс.split()[0] if вид is None else вид}


def кнопка(высота=56, радиус=999, главная=True, класс="кнопка кнопка--главная"):
    return {"класс": класс, "фон": "#2c5c8a", "радиус": радиус, "высота": высота, "главная": главная}


def цвет(значение, альфа=1.0, что="фон", класс="карточка"):
    return {"цвет": значение, "альфа": альфа, "что": что, "класс": класс}


def секция(номер=2, тип="боль", фон="#ffffff", шрифты=("Tahoma", "system-ui"),
           h2=44, p=18, карточки=None, кнопки=None, цвета=None):
    кегли = {}
    if h2:
        кегли["h2"] = h2
    if p:
        кегли["p"] = p
    return {"id": f"экран-{номер:02d}", "тип": тип, "своя": True, "фон": фон,
            "шрифты": list(шрифты), "кегли": кегли,
            "карточки": list(карточки if карточки is not None else [карточка()]),
            "кнопки": list(кнопки if кнопки is not None else [кнопка()]),
            "цвета": list(цвета or [])}


РОВНО = [секция(2, "боль"), секция(3, "решение", фон="#f2f0eb"), секция(4, "условия")]


class Правила(unittest.TestCase):
    """Шесть кодов, каждый — «есть» и «нет»."""

    def что(self, секции, палитра=None):
        return [н["что"] for н in однородность.находки(секции, ПАЛИТРА if палитра is None else палитра)]

    def test_ровная_страница_молчит(self):
        self.assertEqual(self.что(РОВНО), [])
        self.assertEqual(однородность.находки([], ПАЛИТРА), [])

    def test_шрифт(self):
        третья = секция(4, "условия", шрифты=("Tahoma", "system-ui", "Georgia"))
        self.assertEqual(self.что([секция(2), секция(3), третья]), ["Шрифтов больше двух"])
        self.assertEqual(self.что([секция(2), секция(3, шрифты=("system-ui",))]), [])

    def test_кегль(self):
        сбитый = [секция(2), секция(3, h2=30), секция(4)]
        self.assertEqual(self.что(сбитый), ["Кегль заголовка или текста выбивается из шкалы"])
        строки = однородность.находки(сбитый, ПАЛИТРА)[0]["строки"]
        self.assertEqual(строки, ["экран 3 («боль»): заголовок 30 px при 44 на остальных"])
        self.assertEqual(self.что([секция(2), секция(3, h2=45), секция(4)]), [])   # 1 px — не разнобой
        self.assertEqual(self.что([секция(2), секция(3, p=15), секция(4)]),
                         ["Кегль заголовка или текста выбивается из шкалы"])

    def test_кегль_первого_экрана_и_подвала_вне_шкалы(self):
        края = [секция(1, "первый-экран", h2=72, p=24), секция(2), секция(3), секция(4),
                секция(5, "подвал", h2=None, p=14)]
        self.assertEqual(self.что(края), [])

    def test_радиус(self):
        разные = [секция(2), секция(3, карточки=[карточка(радиус=8)]),
                  секция(4, карточки=[карточка(радиус=26)])]
        self.assertEqual(self.что(разные), ["Скругления карточек или кнопок разные"])
        # Скругление кнопки считается по всем кнопкам страницы, а не только по главным:
        # кнопка-контур с другим скруглением — тот же разнобой в языке форм.
        кнопки = [секция(2), секция(3, кнопки=[кнопка(радиус=4, главная=False,
                                                      класс="кнопка кнопка--контур")]), секция(4)]
        self.assertEqual(self.что(кнопки), ["Скругления карточек или кнопок разные"])

    def test_радиус_разные_виды_карточек_не_спорят(self):
        """Система сама раздаёт видам разные токены: `--радиус-карточки` 18, `--радиус-плитки` 22,
        `--радиус-модуля` у работы. Страница из трёх видов карточек — замысел, а не разнобой."""
        виды = [секция(2, карточки=[карточка(радиус=18, вид="карточка")]),
                секция(3, карточки=[карточка(радиус=22, класс="плитка", вид="плитка")]),
                секция(4, карточки=[карточка(радиус=12, класс="работа", вид="работа")])]
        self.assertEqual(self.что(виды), [])

    def test_радиус_внутри_вида_считается(self):
        """Зато два скругления у ОДНОГО вида — разнобой, и находка называет вид словом."""
        свой = [секция(2, карточки=[карточка(радиус=18, вид="карточка")]),
                секция(3, карточки=[карточка(радиус=22, класс="плитка", вид="плитка")]),
                секция(4, карточки=[карточка(радиус=22, класс="плитка", вид="плитка"),
                                    карточка(радиус=18, класс="плитка", вид="плитка")])]
        найденное = однородность.находки(свой, ПАЛИТРА)
        self.assertEqual([н["что"] for н in найденное], ["Скругления карточек или кнопок разные"])
        self.assertEqual(найденное[0]["строки"],
                         ["экран 4 («боль»): скругление плиток 18 при 22 на остальных"])

    def test_тень(self):
        одна_светлота = [секция(2, фон="#ffffff"),
                         секция(3, фон="#ffffff", карточки=[карточка(тень=False)])]
        self.assertEqual(self.что(одна_светлота), ["Тени у карточек то есть, то нет"])
        разная_светлота = [секция(2, фон="#ffffff"),
                           секция(3, фон="#1b2430", карточки=[карточка(тень=False)])]
        self.assertEqual(self.что(разная_светлота), [])   # на тёмном тени не видно вовсе

    def test_цвет(self):
        чужой = [секция(2, цвета=[цвет("#1e88e5")]), секция(3), секция(4)]
        self.assertEqual(self.что(чужой), ["Цвет не из палитры профиля"])
        находка, = однородность.находки(чужой, ПАЛИТРА)
        self.assertEqual(находка["уровень"], дом_находок.ЧИНИТЬ)
        self.assertIn("#1e88e5", находка["строки"][0])
        близкий = [секция(2, цвета=[цвет("#2c5c8b"), цвет("#1f2328", что="текст")]), секция(3)]
        self.assertEqual(self.что(близкий), [])          # допуск на округление браузера
        прозрачный = [секция(2, цвета=[цвет("#1e88e5", альфа=0.05)]), секция(3)]
        self.assertEqual(self.что(прозрачный), [])       # 5 % чужого цвета поверх фона глазу не видны
        без_палитры = [секция(2, цвета=[цвет("#1e88e5")]), секция(3)]
        self.assertEqual(self.что(без_палитры, палитра={}), [])   # палитры нет — находок не выдумываем

    def test_кнопка(self):
        разные = [секция(2), секция(3, кнопки=[кнопка(высота=72)]), секция(4)]
        self.assertEqual(self.что(разные), ["Главные кнопки разной формы"])
        self.assertEqual(self.что([секция(2), секция(3, кнопки=[кнопка(высота=60)])]), [])
        не_главная = [секция(2), секция(3, кнопки=[кнопка(высота=72, главная=False,
                                                         класс="кнопка кнопка--контур")])]
        self.assertEqual(self.что(не_главная), [])       # вторая кнопка экрана форму главной не держит

    def test_уровни_и_порядок(self):
        всё = [секция(2, шрифты=("Tahoma", "system-ui", "Georgia"), цвета=[цвет("#1e88e5")]),
               секция(3, h2=30, карточки=[карточка(радиус=8, тень=False)]),
               секция(4, карточки=[карточка(радиус=26)], кнопки=[кнопка(высота=72)])]
        найденное = однородность.находки(всё, ПАЛИТРА)
        self.assertEqual([н["что"] for н in найденное],
                         ["Шрифтов больше двух", "Кегль заголовка или текста выбивается из шкалы",
                          "Скругления карточек или кнопок разные", "Тени у карточек то есть, то нет",
                          "Цвет не из палитры профиля", "Главные кнопки разной формы"])
        for н in найденное:
            self.assertIn(н["уровень"], дом_находок.УРОВНИ)
            self.assertTrue(н["строки"] and н["чем_грозит"], н["что"])
        self.assertEqual([н["уровень"] for н in найденное if н["что"] == "Цвет не из палитры профиля"],
                         [дом_находок.ЧИНИТЬ])

    def test_сводка_говорит_числами(self):
        строки = однородность.сводка(РОВНО)
        self.assertTrue(any("экранов" in с for с in строки), строки)


class ВБраузере(unittest.TestCase):
    """Две фикстуры одним сервером: замер снимается тем же `снять`, что зовёт `проверить.py`."""

    @classmethod
    def setUpClass(cls):
        from playwright.sync_api import sync_playwright

        cls._playwright = sync_playwright().start()
        cls.браузер = глаза.запустить_браузер(cls._playwright)
        cls._сервер = проверить.локальный_сервер(ФИКСТУРЫ)
        cls.адрес = cls._сервер.__enter__()

    @classmethod
    def tearDownClass(cls):
        cls._сервер.__exit__(None, None, None)
        cls.браузер.close()
        cls._playwright.stop()

    def находки_фикстуры(self, имя: str):
        секции = однородность.снять(self.браузер, self.адрес + имя)
        self.assertEqual(len(секции), 5, f"{имя}: замер увидел не все секции")
        палитра = флаги_дизайна._цвета_root((ФИКСТУРЫ / имя).read_text(encoding="utf-8"))
        self.assertIn("--цвет-акцент", палитра, f"{имя}: палитра `:root` не прочиталась")
        return однородность.находки(секции, палитра)

    def test_ровная_страница_без_находок(self):
        self.assertEqual([н["что"] for н in self.находки_фикстуры("ровная.html")], [])

    def test_разнобой_даёт_ровно_четыре(self):
        найденное = self.находки_фикстуры("разнобой.html")
        self.assertEqual([н["что"] for н in найденное],
                         ["Кегль заголовка или текста выбивается из шкалы",
                          "Скругления карточек или кнопок разные",
                          "Тени у карточек то есть, то нет",
                          "Цвет не из палитры профиля"])
        цветная, = [н for н in найденное if н["что"] == "Цвет не из палитры профиля"]
        self.assertTrue(any("#1e88e5" in с for с in цветная["строки"]), цветная["строки"])


class СловарьКарточек(unittest.TestCase):
    """Что такое карточка, знает один модуль — `находки.py`; второго списка в системе нет."""

    def test_кортеж_и_селектор_общие(self):
        self.assertIs(однородность.КАРТОЧКИ, дом_находок.КАРТОЧКИ)
        self.assertIs(проверить.КАРТОЧКИ, дом_находок.КАРТОЧКИ)
        self.assertEqual(однородность.КАРТОЧКИ_СЕЛЕКТОР, дом_находок.КАРТОЧКИ_СЕЛЕКТОР)
        self.assertEqual(проверить.КАРТОЧКИ_СЕЛЕКТОР, дом_находок.КАРТОЧКИ_СЕЛЕКТОР)

    def test_в_кортеже_все_карточки_системы(self):
        """Расходились они как раз по составу: отзыв не видел один, работу — другой."""
        for класс in ("карточка", "тариф", "плитка", "врезка", "модуль", "работа",
                      "отзыв", "отзыв-заглушка"):
            self.assertIn(класс, дом_находок.КАРТОЧКИ, класс)
            if класс != дом_находок.КАРТОЧКИ[0]:
                self.assertIn(f".{класс}", дом_находок.КАРТОЧКИ_СЕЛЕКТОР, класс)
        корень = дом_находок.КАРТОЧКИ[0][:-1]
        self.assertIn(f'[class*="{корень}"]', дом_находок.КАРТОЧКИ_СЕЛЕКТОР)

    def test_виды_это_семьи_а_не_классы(self):
        """`отзыв-заглушка` — тот же отзыв: в видах его нет, иначе он спорил бы сам с собой."""
        self.assertEqual(дом_находок.ВИДЫ_КАРТОЧЕК,
                         ("карточка", "тариф", "плитка", "врезка", "модуль", "работа", "отзыв"))

    def test_своих_копий_у_модулей_не_осталось(self):
        for модуль in (однородность, проверить):
            текст = Path(модуль.__file__).read_text(encoding="utf-8")
            self.assertNotIn('КАРТОЧКИ = ("', текст, модуль.__name__)

    def test_селектор_и_виды_уехали_в_замер(self):
        self.assertIn(f"КАРТОЧКИ_СЕЛЕКТОР = '{дом_находок.КАРТОЧКИ_СЕЛЕКТОР}'", однородность.ЗАМЕР_JS)
        self.assertIn(f"КАРТОЧКИ_СЕЛЕКТОР = '{дом_находок.КАРТОЧКИ_СЕЛЕКТОР}'", проверить.РАЗБОР_JS)
        for вид in дом_находок.ВИДЫ_КАРТОЧЕК:
            self.assertIn(f"'{вид}'", однородность.ЗАМЕР_JS, вид)


class ГейтВПроверить(unittest.TestCase):
    """Сквозной путь целиком: признак `своих_экранов` в `РАЗБОР_JS` → вызов критика в
    `собрать_находки`. Без этого теста переименование ключа выключило бы критика молча."""

    ЗАГОЛОВКИ = {что for _, _, что, _ in однородность.ПРАВИЛА}

    @classmethod
    def setUpClass(cls):
        from playwright.sync_api import sync_playwright

        cls._playwright = sync_playwright().start()
        cls.браузер = глаза.запустить_браузер(cls._playwright)
        cls._временная = tempfile.TemporaryDirectory()
        cls.папка = Path(cls._временная.name)
        shutil.copyfile(ФИКСТУРЫ / "разнобой.html", cls.папка / "index.html")
        cls._сервер = проверить.локальный_сервер(cls.папка)
        cls.адрес = cls._сервер.__enter__()
        контекст = глаза.контекст(cls.браузер, "компьютер")
        страница = контекст.new_page()
        try:
            страница.goto(cls.адрес, wait_until="load", timeout=глаза.ТАЙМАУТ_ЗАГРУЗКИ_МС)
            cls.разметка = страница.evaluate(проверить.РАЗБОР_JS)
        finally:
            контекст.close()
        cls.замеры = {"устройства": {}, "однородность": однородность.снять(cls.браузер, cls.адрес)}

    @classmethod
    def tearDownClass(cls):
        cls._сервер.__exit__(None, None, None)
        cls.браузер.close()
        cls._playwright.stop()
        cls._временная.cleanup()

    def test_разбор_считает_свои_экраны(self):
        self.assertEqual(self.разметка.get("своих_экранов"), 3)

    def test_замер_снялся(self):
        self.assertEqual(len(self.замеры["однородность"]), 5)

    def test_находки_критика_доезжают_до_общего_списка(self):
        найденное = проверить.собрать_находки(self.замеры, self.разметка, self.папка)
        свои = [н["что"] for н in найденное if н["что"] in self.ЗАГОЛОВКИ]
        self.assertTrue(свои, [н["что"] for н in найденное])

    def test_без_своих_экранов_критик_молчит(self):
        разметка = dict(self.разметка, своих_экранов=0)
        найденное = проверить.собрать_находки(self.замеры, разметка, self.папка)
        self.assertEqual([н["что"] for н in найденное if н["что"] in self.ЗАГОЛОВКИ], [])


if __name__ == "__main__":
    unittest.main()
