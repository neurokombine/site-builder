class Рисовалка:
    """Подделка кисти: отдаёт заранее приготовленные файлы по одному на попытку и помнит промты.
    Живого браузера здесь нет и быть не может — это и есть цена правила «Chrome в тестах не поднимаем»."""

    def __init__(self, файлы, беды=()):
        self.файлы = list(файлы)
        self.беды = list(беды)
        self.промты: list[str] = []

    def __call__(self, промт, куда, имя="kadr", рефы=(), пропорция=None):
        self.промты.append(промт)
        номер = len(self.промты) - 1
        if номер < len(self.беды) and self.беды[номер] is not None:
            raise self.беды[номер]
        файл = Path(self.файлы[min(номер, len(self.файлы) - 1)])
        return {"файл": файл, "размер": (1200, 1600), "пропорция": .75, "заказана": .75,
                "совпала": True, "режим_картинки": True, "режим_ответа": "проба", "порт": 0}


def мерилка(наборы):
    """Подделка замеров: по одному готовому словарю на попытку. Считает, сколько раз её звали."""
    вызовы = {"счёт": 0}

    def мерит(файл, заказ, **_):
        набор = наборы[min(вызовы["счёт"], len(наборы) - 1)]
        вызовы["счёт"] += 1
        return {**набор, "файл": str(файл), "схема": заказ.get("схема", ""),
                "тип": заказ.get("тип", ""), "ключ": заказ.get("ключ", "")}

    мерит.вызовы = вызовы
    return мерит


