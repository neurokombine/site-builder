# ── замеры по настоящему файлу ───────────────────────────────────────────────
class Померить(unittest.TestCase):
    """Числа берутся у `обложка.py`, а не считаются заново, и крупность считается первой."""

    def setUp(self):
        self._в = tempfile.TemporaryDirectory()
        self.д = Path(self._в.name)
        self.addCleanup(self._в.cleanup)

    def test_крупность_первым_ключом(self):
        файл = фигура_png(self.д / "figura.png")
        итог = приёмка.померить(файл, заказ_на("разворот"))
        self.assertEqual(list(итог)[0], "крупность", "крупность считается первой — она промахивается чаще всего")
        self.assertEqual(приёмка.ПОРЯДОК[0], "крупность")

    def test_доля_головы_та_же_что_у_обложки(self):
        файл = фигура_png(self.д / "figura.png")
        итог = приёмка.померить(файл, заказ_на("разворот"))
        self.assertAlmostEqual(итог["крупность"]["доля"], обложка.замеры_рамки(файл)["голова"])
        self.assertEqual(итог["крупность"]["вилка"], заказы.вилка_головы("разворот", "фото"))

    def test_воздух_над_макушкой_меряется_даже_без_найденной_головы(self):
        # широкие плечи во весь кадр: голову по силуэту не разобрать, а верхняя кромка видна всегда —
        # именно на этом споткнулись оба живых прогона
        широкий = фигура_png(self.д / "shirokiy.png", плечи=3.6)
        итог = приёмка.померить(широкий, заказ_на("разворот"))
        self.assertIsNotNone(итог["посадка"]["макушка"])
        self.assertAlmostEqual(итог["посадка"]["макушка"], 97 / 1536, places=3)

    def test_каждый_замер_говорит_чем_мерили(self):
        файл = фигура_png(self.д / "figura.png")
        итог = приёмка.померить(файл, заказ_на("разворот"))
        for бук in приёмка.ПОРЯДОК:
            self.assertTrue(итог[бук]["чем"].strip(), f"{бук} не сказал, чем мерили")

    def test_фотографию_режет_черновым_вырезом_и_в_работу_его_не_кладёт(self):
        снимок = фото(self.д / "kadr.png")
        готовый = фигура_png(self.д / "готовый.png")

        def подделка_выреза(файл, куда, отмывать=True):
            Path(куда).mkdir(parents=True, exist_ok=True)
            путь = Path(куда) / "kadr-vyrez.png"
            путь.write_bytes(Path(готовый).read_bytes())
            return путь

        with patch.object(обложка, "вырез", подделка_выреза):
            итог = приёмка.померить(снимок, заказ_на("разворот"))
        self.assertIsNotNone(итог["крупность"]["доля"], "по черновому вырезу голова видна")
        self.assertIn(приёмка.ЧЕРНОВИКИ, итог["силуэт_файл"])
        self.assertTrue((self.д / приёмка.ЧЕРНОВИКИ).is_dir())

    def test_без_rembg_говорим_словами_а_не_молчим(self):
        снимок = фото(self.д / "kadr.png")
        with patch.object(обложка, "вырез", lambda *а, **к: None):
            итог = приёмка.померить(снимок, заказ_на("разворот"))
        self.assertIsNone(итог["крупность"]["доля"])
        self.assertIn("rembg", итог["откуда_силуэт"])
        найдено = приёмка.промахи(итог, заказ_на("разворот"))
        self.assertIn("Крупность головы здесь не измерима", [п["что"] for п in найдено])


# ── порядок промахов ─────────────────────────────────────────────────────────
class ПорядокПромахов(unittest.TestCase):
    """Порядок снят с живых прогонов: крупность → посадка → фон и кайма → светлота → вид кадра."""

    def test_всё_сразу_идёт_в_порядке_важности(self):
        найдено = приёмка.промахи(
            замеры(доля=.22, макушка=.02, кайма="вырез снят на тёмном фоне", светлота=.95,
                   добор=обложка.ПРЕДЕЛ_ДОБОРА, нужен_текст=True, совпала=False),
            заказ_на("сцена", "тёмный"))
        буки = [п["бук"] for п in найдено]
        self.assertEqual(буки, sorted(буки, key=приёмка.ПОРЯДОК.index))
        self.assertEqual(буки[0], "крупность")
        self.assertEqual(буки[-1], "вид")

    def test_кадр_в_вилке_и_на_месте_промахов_не_даёт(self):
        чисто = замеры(доля=.33, макушка=.08, подбородок=.40)
        self.assertEqual(приёмка.промахи(чисто, заказ_на("разворот")), [])

    def test_голова_мельче_вилки_и_крупнее_вилки(self):
        мелко = приёмка.промахи(замеры(доля=.22), заказ_на("разворот"))[0]
        крупно = приёмка.промахи(замеры(доля=.55), заказ_на("разворот"))[0]
        self.assertIn("22 %", мелко["поправка"])
        self.assertIn("ближе", мелко["поправка"])
        self.assertIn("пошире", крупно["поправка"])

    def test_вилка_разворота_ниже_общей_нормы(self):
        # плашка «имя · опора» садится под лицо: у схем с плашкой верхняя кромка опущена
        self.assertLess(заказы.вилка_головы("разворот", "фото")[1], обложка.НОРМА_ГОЛОВЫ_НА_ТЕЛЕФОНЕ[1])
        найдено = приёмка.промахи(замеры(доля=.42), заказ_на("разворот"))
        self.assertEqual([п["бук"] for п in найдено], ["крупность"])

    def test_поля_по_краям_просят_только_у_схемы_с_вырезом(self):
        """Задача 7, круг 1: фотографию кромка режет всегда — просить отодвинуть человека от краёв
        значит портить годный кадр. Схеме с вырезом срезанная кромка — промах."""
        у_краёв = замеры(доля=.33, макушка=.08, подбородок=.40, поля=("слева", "справа"))
        self.assertEqual(заказ_на("разворот")["тип"], "фото")
        self.assertEqual(приёмка.промахи(у_краёв, заказ_на("разворот")), [])
        вырез = заказ_на("центр")
        self.assertIn(вырез["тип"], обложка.СХЕМЫ_ВЫРЕЗА)
        self.assertIn("Фигура упирается в край кадра", [п["что"] for п in приёмка.промахи(у_краёв, вырез)])

    def test_форма_находки_общая_для_системы(self):
        for п in приёмка.промахи(замеры(доля=.22, макушка=.02), заказ_на("разворот")):
            self.assertEqual(set(п) >= {"уровень", "что", "строки", "чем_грозит"}, True)
            self.assertIn(п["уровень"], (ЧИНИТЬ, ПОПРАВИТЬ, К_СВЕДЕНИЮ))

    def test_вес_считает_и_уровень_и_важность(self):
        крупность = приёмка.промахи(замеры(доля=.22), заказ_на("разворот"))
        формат = приёмка.промахи(замеры(доля=.33, совпала=False), заказ_на("разворот"))
        self.assertGreater(приёмка.цена(крупность), приёмка.цена(формат),
                           "промах крупности весит больше промаха формата")


# ── поправка ─────────────────────────────────────────────────────────────────
class Поправка(unittest.TestCase):
    """«Сделай лучше» генератору бесполезно: поправка говорит число, вилку и сторону."""

    def test_говорит_числа_и_вилку(self):
        текст = приёмка.поправка(приёмка.промахи(замеры(доля=.29), заказ_на("разворот")))
        self.assertIn("30–37 %", текст)
        self.assertIn("29 %", текст)
        for пусто in ("сделай лучше", "получше", "покрасивее"):
            self.assertNotIn(пусто, текст.lower())

    def test_макушка_просит_измеримое(self):
        текст = приёмка.поправка(приёмка.промахи(замеры(доля=.33, макушка=.046), заказ_на("разворот")))
        self.assertIn("над макушкой", текст)
        self.assertIn("6 %", текст)
        self.assertIn("5 %", текст)

    def test_правит_одно_два_верхних_а_не_всё(self):
        найдено = приёмка.промахи(
            замеры(доля=.22, макушка=.02, кайма="кайма", светлота=.95,
                   добор=обложка.ПРЕДЕЛ_ДОБОРА, нужен_текст=True, совпала=False),
            заказ_на("сцена", "тёмный"))
        self.assertGreaterEqual(len(найдено), 4)
        текст = приёмка.поправка(найдено).lower()
        for свой in найдено[:приёмка.ПРАВИМ_ЗА_РАЗ]:
            self.assertIn(свой["поправка"].rstrip(".").lower(), текст)
        for чужой in найдено[приёмка.ПРАВИМ_ЗА_РАЗ:]:
            self.assertNotIn(чужой["поправка"].rstrip(".").lower(), текст)
        self.assertEqual(приёмка.ПРАВИМ_ЗА_РАЗ, 2)

    def test_велит_остальное_не_трогать(self):
        текст = приёмка.поправка(приёмка.промахи(замеры(доля=.22), заказ_на("разворот")))
        self.assertIn("оставь как есть", текст)

    def test_неизмеримое_в_поправку_не_идёт(self):
        найдено = приёмка.промахи(замеры(доля=None), заказ_на("разворот"))
        self.assertTrue(найдено)
        self.assertEqual(приёмка.поправка(найдено), "", "генератору нечего сказать — молчим")

    def test_пусто_на_пустом(self):
        self.assertEqual(приёмка.поправка([]), "")


