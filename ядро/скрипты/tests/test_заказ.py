def промт(схема="орбита", ключ="светлый", **ещё):
    ещё.setdefault("что_в_кадре", "мастер за верстаком")
    ещё.setdefault("палитра", ПАЛИТРА)
    return заказ.собрать_промт(схема, ключ, **ещё)


class ТипИПропорция(unittest.TestCase):
    """Схема решает, что за кадр, — и решает рецептом, а не таблицей в голове."""

    def test_тип_читается_из_рецепта(self):
        self.assertEqual(заказ.тип_кадра("орбита"), "вырез")
        self.assertEqual(заказ.тип_кадра("центр"), "вырез")
        self.assertEqual(заказ.тип_кадра("разворот"), "фото")
        self.assertEqual(заказ.тип_кадра("товар-крупно"), "товар")
        self.assertEqual(заказ.тип_кадра("афиша-с-экраном"), "мокап")

    def test_разворот_слева_читает_рецепт_разворота(self):
        self.assertEqual(заказ.тип_кадра("разворот-слева"), заказ.тип_кадра("разворот"))

    def test_незнакомая_схема_не_угадывается(self):
        self.assertEqual(заказ.тип_кадра("чего-нибудь-этакое"), "")

    def test_пропорция_выреза_из_рамки(self):
        ш, в = обложка.РАМКА_ВЫРЕЗА
        self.assertEqual(заказ.пропорция_схемы("орбита", "вырез"), f"{ш}:{в}")
        self.assertEqual(заказ.пропорция_схемы("центр", "вырез"), f"{ш}:{в}")

    def test_пропорция_фото_из_контракта_имён(self):
        self.assertEqual(заказ.пропорция_схемы("разворот", "фото"), "3:4")
        self.assertEqual(заказ.пропорция_схемы("сцена", "фото"), "16:9")
        self.assertEqual(заказ.пропорция_схемы("бенто", "фото"), "4:3")
        self.assertEqual(заказ.пропорция_схемы("товар-крупно", "товар"), "9:16")

    def test_пропорция_попадает_в_промт_и_в_кисть(self):
        з = промт("орбита", "светлый")
        self.assertIn(f"Соотношение сторон кадра: {з['пропорция']}.", з["промт"])
        # кисть понимает эту запись и не дописывает вторую такую же строку
        self.assertAlmostEqual(кисть.разобрать_пропорцию(з["пропорция"]), 2 / 3)
        self.assertEqual(кисть.промт_с_пропорцией(з["промт"], з["пропорция"]), з["промт"])

    def test_пропорция_сцены_понятна_кисти(self):
        з = промт("сцена", "тёмный")
        self.assertAlmostEqual(кисть.разобрать_пропорцию(з["пропорция"]), 16 / 9)


class КлючРешаетФон(unittest.TestCase):
    """Главное правило задачи: «для светлого ключа — кадр на светлом фоне» стало строкой промта."""

    def test_светлый_ключ_просит_светлый_фон(self):
        строка = промт("орбита", "светлый")["промт"]
        self.assertIn("Фон: ровный однотонный светлый", строка)
        self.assertNotIn("однотонный тёмный", строка)

    def test_тёмный_ключ_просит_тёмный_фон(self):
        строка = промт("орбита", "тёмный")["промт"]
        self.assertIn("Фон: ровный однотонный тёмный", строка)

    def test_светлый_ключ_просит_ещё_и_светлую_кромку(self):
        # § 7-ter: ниже порога каймы на светлом ключе уходит только вырез со светлой кромкой
        self.assertIn("светлые волосы", промт("центр", "светлый")["промт"])
        self.assertNotIn("светлые волосы", промт("центр", "тёмный")["промт"])

    def test_фон_объяснён_порогом_каймы(self):
        откуда = " ".join(с["откуда"] for с in промт("орбита", "светлый")["строки"])
        self.assertIn("ПОРОГ_КАЙМЫ", откуда)
        self.assertIn(str(обложка.ПОРОГ_КАЙМЫ), откуда)

    def test_фотосхеме_фон_выреза_не_просят(self):
        строка = промт("разворот", "светлый")["промт"]
        self.assertNotIn("будет вырезана фигура", строка)

    def test_текст_на_кадре_просит_полосу_нужной_светлоты(self):
        тёмный = промт("сцена", "тёмный")["промт"]
        светлый = промт("сцена", "светлый")["промт"]
        лево, право, _, _ = обложка.ПОЛОСА_ТЕКСТА
        self.assertIn(f"от {round(лево * 100)} %", тёмный)
        self.assertIn(f"до {round(право * 100)} %", тёмный)
        self.assertIn("спокойный тёмный участок", тёмный)
        self.assertIn("спокойный светлый участок", светлый)

    def test_полоса_только_там_где_текст_лежит_на_кадре(self):
        self.assertTrue(заказ.текст_на_кадре("сцена"))
        self.assertFalse(заказ.текст_на_кадре("разворот"))
        self.assertNotIn("ляжет заголовок", промт("разворот", "тёмный")["промт"])

    def test_неизвестный_ключ_считаем_тёмным(self):
        self.assertEqual(промт("орбита", "полосатый")["ключ"], "тёмный")


class Крупность(unittest.TestCase):
    """Числа крупности — те же, которыми готовый кадр потом меряют."""

    def test_вилка_из_нормы_телефона(self):
        низ, верх = заказ.вилка_головы("сцена", "фото")
        self.assertEqual((низ, верх), обложка.НОРМА_ГОЛОВЫ_НА_ТЕЛЕФОНЕ)

    def test_у_схемы_с_плашкой_верхняя_кромка_ниже(self):
        _, верх = заказ.вилка_головы("разворот", "фото")
        self.assertAlmostEqual(верх, обложка.ПОРОГ_ПОДБОРОДКА - обложка.МАКУШКА_В_РАМКЕ)
        self.assertLess(верх, обложка.НОРМА_ГОЛОВЫ_НА_ТЕЛЕФОНЕ[1])

    def test_подбородок_остаётся_выше_порога(self):
        # воздух над макушкой + голова = подбородок; он обязан быть выше ПОРОГ_ПОДБОРОДКА
        _, верх = заказ.вилка_головы("разворот", "фото")
        self.assertLessEqual(обложка.МАКУШКА_В_РАМКЕ + верх, обложка.ПОРОГ_ПОДБОРОДКА)

    def test_вилка_попала_в_промт_числами(self):
        строка = промт("разворот", "светлый")["промт"]
        низ, верх = заказ.вилка_головы("разворот", "фото")
        self.assertIn(f"от {round(низ * 100)} % до {round(верх * 100)} % высоты кадра", строка)

    def test_у_выреза_крупность_головы_не_просят(self):
        # её всё равно выставит рамка выреза — просить значит спорить со своим же скриптом
        self.assertIsNone(заказ.вилка_головы("орбита", "вырез"))
        строка = промт("орбита", "тёмный")["промт"]
        self.assertNotIn("голова занимает", строка)
        self.assertIn(f"не меньше {round(обложка.ПОЛЯ_РАМКИ * 100)} % ширины", строка)

    def test_у_бенто_человека_не_требуем(self):
        self.assertFalse(заказ.человек_в_кадре("бенто", "фото"))
        self.assertIsNone(заказ.вилка_головы("бенто", "фото"))
        self.assertNotIn("Крупность:", промт("бенто", "светлый")["промт"])

    def test_товару_просят_предмет_целиком(self):
        self.assertIn("предмет целиком", промт("товар-крупно", "светлый")["промт"])

    def test_взгляд_от_стороны(self):
        self.assertIn("чуть влево", промт("разворот", "светлый", сторона="справа")["промт"])
        self.assertIn("чуть вправо", промт("разворот", "светлый", сторона="слева")["промт"])
        self.assertIn("Взгляд: в камеру.", промт("разворот", "светлый", сторона="центр")["промт"])

    def test_сцене_человек_необязателен(self):
        # «сцена» — про атмосферу: помещение, процесс, город тоже законны
        self.assertFalse(заказ.лицо_обязательно("сцена", "фото"))
        строка = промт("сцена", "тёмный")["промт"]
        self.assertIn("Крупность: если в кадре человек", строка)
        self.assertIn("Взгляд человека, если он в кадре", строка)

    def test_вырезу_и_плашке_человек_обязателен(self):
        self.assertTrue(заказ.лицо_обязательно("орбита", "вырез"))
        self.assertTrue(заказ.лицо_обязательно("центр", "вырез"))
        self.assertTrue(заказ.лицо_обязательно("разворот", "фото"))
        self.assertIn("Крупность: человек по грудь", промт("разворот", "светлый")["промт"])

    def test_у_кадра_без_человека_взгляда_нет(self):
        self.assertNotIn("Взгляд:", промт("товар-крупно", "светлый")["промт"])


class ЦветаСловами(unittest.TestCase):
    def test_считается_из_цвета_а_не_по_таблице(self):
        self.assertEqual(заказ.цвет_словами("#2C4A63"), "тёмный приглушённый синий")
        self.assertEqual(заказ.цвет_словами("#C62828"), "насыщенный красный")
        self.assertEqual(заказ.цвет_словами("#4CAF50"), "зелёный")

    def test_почти_белое_не_становится_оранжевым(self):
        # ловушка HLS: у #FAF8F5 разница каналов в два уровня даёт s = .33
        self.assertEqual(заказ.цвет_словами("#FAF8F5"), "почти белый")
        self.assertEqual(заказ.цвет_словами("#000000"), "почти чёрный")

    def test_тёплый_приглушённый_называется_бежевым(self):
        self.assertEqual(заказ.цвет_словами("#C8A97E"), "светлый бежевый")

    def test_не_цвет_возвращает_пусто(self):
        for мусор in ("", "нет", "#GGGGGG", "rgb(1,2,3)", None):
            self.assertEqual(заказ.цвет_словами(мусор), "")

    def test_палитра_берёт_фон_своего_ключа(self):
        светлая = заказ.палитра_словами(ПАЛИТРА, "светлый")
        тёмная = заказ.палитра_словами(ПАЛИТРА, "тёмный")
        self.assertIn("фон страницы — почти белый", светлая)
        self.assertIn("фон страницы — очень тёмный", тёмная)

    def test_светлота_ключа_меряется_той_же_линейкой(self):
        # это же число сборка отдаёт в обложка.находки_кадра, когда приёмка мерит кайму
        self.assertEqual(заказ.светлота_ключа(ПАЛИТРА, "светлый"), обложка.светлота_цвета("#FAF8F5"))
        self.assertEqual(заказ.светлота_ключа(ПАЛИТРА, "тёмный"), обложка.светлота_цвета("#0D1B2A"))
        self.assertIsNone(заказ.светлота_ключа(None, "светлый"))

    def test_нет_палитры_нет_строки(self):
        self.assertEqual(заказ.палитра_словами(None, "светлый"), "")
        self.assertNotIn("Палитра кадра", промт("орбита", "светлый", палитра=None)["промт"])

    def test_в_промте_нет_ни_одного_hex(self):
        for схема in ("орбита", "разворот", "сцена", "товар-крупно", "бенто"):
            строка = промт(схема, "светлый")["промт"]
            self.assertIsNone(re.search(r"#[0-9a-fA-F]{3,8}", строка), схема)
            self.assertNotIn("rgb(", строка)


