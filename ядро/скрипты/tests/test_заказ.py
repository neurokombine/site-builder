class ГнездоВнешности(unittest.TestCase):
    """Стык для канонов портрета: этот модуль лицо не сочиняет, а держит для него место."""

    def test_блок_встаёт_после_сюжета_и_до_фона(self):
        з = промт("орбита", "светлый", внешность="Женщина 45 лет, тёмные волосы до плеч")
        место = заказ.место_внешности(з)
        self.assertEqual(место, 1)          # 0 — «Фотография: …», роли в этом вызове нет
        строки = [с["строка"] for с in з["строки"]]
        self.assertTrue(строки[место].startswith("Женщина 45 лет"))
        self.assertTrue(any(с.startswith("Фон:") for с in строки[место + 1:]))

    def test_роль_блок_не_сдвигает_фон(self):
        з = промт("орбита", "светлый", роль="столяр", внешность="Мужчина, седая борода")
        строки = [с["строка"] for с in з["строки"]]
        self.assertEqual(заказ.место_внешности(з), 2)
        self.assertTrue(any(с.startswith("Фон:") for с in строки[3:]))

    def test_блока_нет_и_место_минус_один(self):
        self.assertEqual(заказ.место_внешности(промт("орбита", "светлый")), -1)

    def test_без_блока_но_с_образцами_лицо_берётся_с_них(self):
        з = промт("орбита", "светлый", рефы=["селфи-1.jpg", "селфи-2.jpg"])
        self.assertIn("строго по приложенным фотографиям", з["промт"])
        self.assertEqual(з["рефы"], ["селфи-1.jpg", "селфи-2.jpg"])

    def test_блок_старше_образцов(self):
        # пришли каноны портрета — говорим их словами, а не своей запасной строкой
        з = промт("орбита", "светлый", внешность="Женщина, каре", рефы=["селфи.jpg"])
        self.assertNotIn("строго по приложенным фотографиям", з["промт"])
        self.assertIn("Женщина, каре.", з["промт"])

    def test_кадру_без_человека_внешность_не_нужна(self):
        self.assertFalse(заказ.человек_в_кадре("товар-крупно", "товар"))
        з = промт("товар-крупно", "светлый", рефы=["селфи.jpg"])
        self.assertNotIn("приложенным фотографиям", з["промт"])

    def test_точка_в_конце_блока_не_двоится(self):
        з = промт("орбита", "светлый", внешность="Женщина, каре.")
        self.assertIn("Женщина, каре.", з["промт"])
        self.assertNotIn("каре..", з["промт"])


