class Команда(unittest.TestCase):
    """CLI: та же сборка, но глазами человека — и журнал пишется сам."""

    def setUp(self):
        self._в = tempfile.TemporaryDirectory()
        self.папка = Path(self._в.name)
        self.addCleanup(self._в.cleanup)
        (self.папка / "прототип.md").write_text(
            "# Прототип: проба\n\n- Пресет: визитка\n\n"
            "## Экран 1 · Первый экран · статус: принят\n"
            "Задача экрана: показать мастера\n"
            "- Заголовок: Столярная мастерская\n  - или: Мебель на заказ\n"
            "- Подзаголовок: Дуб и ясень\n- Кнопка: Написать\n"
            "- Картинка: мастер у верстака\n"
            "- Почему этот экран: доверие\n- Не делаем: стоковых улыбок\n", encoding="utf-8")
        (self.папка / "дизайн.md").write_text(
            "# Дизайн-система: проба\n\n## Решения\n- Схема первого экрана: сцена\n"
            "- Доминанта: тёмная\n- Сторона: справа\n", encoding="utf-8")

    def _прогон(self, *аргументы):
        вывод = io.StringIO()
        with contextlib.redirect_stdout(вывод):
            код = заказ.main_с_аргументами([str(self.папка), *аргументы])
        return код, вывод.getvalue()

    def test_печатает_промт_и_пишет_журнал(self):
        код, вывод = self._прогон()
        self.assertEqual(код, 0)
        self.assertIn("Фотография: мастер у верстака.", вывод)
        self.assertIn("Почему каждая строка:", вывод)
        self.assertIn("Соотношение сторон кадра: 16:9.", (self.папка / "журнал.md").read_text(encoding="utf-8"))

    def test_без_журнала_ничего_не_пишет(self):
        код, _ = self._прогон("--без-журнала")
        self.assertEqual(код, 0)
        self.assertFalse((self.папка / "журнал.md").exists())

    def test_нет_папки_работы(self):
        вывод = io.StringIO()
        with contextlib.redirect_stdout(вывод):
            код = заказ.main_с_аргументами([str(self.папка / "нет-такой")])
        self.assertEqual(код, 1)

    def test_роликовой_схеме_говорит_что_не_рисует(self):
        код, вывод = self._прогон("--схема", "живая-обложка", "--без-журнала", "--нарисуй")
        self.assertEqual(код, 0)
        self.assertIn("Не рисую:", вывод)
        self.assertNotIn("Фотография:", вывод)

    def test_красная_находка_даёт_код_1(self):
        (self.папка / "дизайн.md").write_text("# Дизайн-система: проба\n", encoding="utf-8")
        код, вывод = self._прогон("--без-журнала")
        self.assertEqual(код, 1)
        self.assertIn("Схема первого экрана не выбрана", вывод)


