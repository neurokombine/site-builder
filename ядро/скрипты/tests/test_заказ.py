class Журнал(unittest.TestCase):
    def setUp(self):
        self._в = tempfile.TemporaryDirectory()
        self.папка = Path(self._в.name)
        self.addCleanup(self._в.cleanup)

    def test_запись_несёт_промт_и_таблицу(self):
        з = промт("орбита", "светлый")
        текст = заказ.запись_журнала(з, datetime(2026, 9, 13, 21, 40, tzinfo=заказ.МСК))
        self.assertIn("## 13.09.2026 21:40 МСК — промт кадра: схема «орбита», светлый ключ", текст)
        self.assertIn("```text", текст)
        self.assertIn(з["промт"], текст)
        self.assertIn("| Строка промта | Откуда |", текст)

    def test_время_московское(self):
        # полночь по Москве — это ещё «13.09» для того, кто живёт западнее
        текст = заказ.запись_журнала(промт(), datetime(2026, 9, 13, 23, 30, tzinfo=заказ.МСК))
        self.assertIn("13.09.2026 23:30 МСК", текст)

    def test_журнал_заводится_и_дописывается(self):
        путь = заказ.в_журнал(self.папка, промт("орбита", "светлый"))
        первый = путь.read_text(encoding="utf-8")
        self.assertTrue(первый.startswith(f"# Журнал работы «{self.папка.name}»"))
        заказ.в_журнал(self.папка, промт("сцена", "тёмный"))
        второй = путь.read_text(encoding="utf-8")
        self.assertTrue(второй.startswith(первый.rstrip("\n")))
        self.assertEqual(второй.count("## "), 2)

    def test_палки_в_таблице_не_ломают_разметку(self):
        з = промт("орбита", "светлый", что_в_кадре="мастер | у станка")
        строка = [с for с in заказ.запись_журнала(з).splitlines() if "мастер" in с and с.startswith("|")][0]
        self.assertEqual(строка.count("|"), 3)


