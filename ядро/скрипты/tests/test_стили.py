    def test_заливка_кнопки_идёт_через_свой_токен(self):
        """Правило владелицы «кнопка с СТА всегда контрастная» держится подменой одной только
        заливки: прямой `var(--цвет-акцент)` в фоне кнопки означал бы, что подменить её можно
        только перекрасив всю страницу."""
        for правило in re.findall(r"^\.[^\n{]*кнопка[^\n{]*\{[^}]*\}", self.тело, re.M):
            if "background:" not in правило or "--кнопка-радиус" in правило:
                continue
            фон = re.search(r"background:\s*([^;}]+)", правило).group(1)
            if "transparent" in фон or "currentColor" in фон:
                continue   # кнопка-контур: у неё заливки нет вовсе
            self.assertNotRegex(фон, r"var\(--цвет-акцент[-\w]*\)\s*$",
                                f"заливка кнопки мимо своего токена: {правило[:80]}")

