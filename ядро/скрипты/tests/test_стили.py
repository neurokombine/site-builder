def клэмп_или_плоское(css: str, токен: str) -> tuple:
    """Возвращает (нижний, верхний) для `токен: clamp(A, ..vw, B)`, для плоского `токен: Xpx`, или —
    фикс-раунд 1 системного блока — для токена, разведённого на телефон/компьютер ДВУМЯ отдельными
    объявлениями (`--кегль-h1`, палитра-и-токены.md § 3): значение, объявленное ПЕРВЫМ по тексту
    (плоское или clamp — не важно, какая форма) — нижний (телефонный) конец; если тот же токен
    объявлен снова дальше по тексту (внутри `@media (min-width: …)`), его значение (верх clamp или
    само плоское число) — верхний (компьютерный) конец. Искать сперва clamp() `re.search`-ем по
    всему тексту нельзя: он находит ЛЮБОЕ вхождение независимо от порядка и может отдать
    компьютерный конец за телефонный, если тот записан вилкой, а телефонный — плоским числом раньше
    по тексту (ровно этот случай у `--кегль-h1`)."""
    клэмп = rf"{re.escape(токен)}:\s*clamp\(([\d.]+)px[^,]*,[^,]*,\s*([\d.]+)px\)"
    плоское = rf"{re.escape(токен)}:\s*([\d.]+)px\s*;"
    первый = re.compile(rf"(?:{клэмп})|(?:{плоское})")
    м = первый.search(css)
    if not м:
        raise AssertionError(f"{токен} не найден ни в clamp(), ни как плоское значение")
    if м.group(1) is not None:   # первое вхождение — clamp(): нижний/верхний конец вилки
        нижний, верх_по_умолчанию = float(м.group(1)), float(м.group(2))
    else:   # первое вхождение — плоское число: это и есть нижний (телефонный) конец
        нижний, верх_по_умолчанию = float(м.group(3)), float(м.group(3))
    хвост = css[м.end():]
    м2 = первый.search(хвост)
    if not м2:
        return нижний, верх_по_умолчанию
    return нижний, float(м2.group(2)) if м2.group(1) is not None else float(м2.group(3))


def светимость_rgb(строка_цвета: str) -> float:
    """Относительная светимость WCAG из computed style — Chromium отдаёт результат color-mix()
    не как `rgb()`, а как `color(srgb r g b / a)` (0..1 на канал); поддерживаем оба вида. Формула —
    та же, что и `собрать._светимость`, только вход не hex, а браузерный цвет."""
    м = re.match(r"color\(srgb ([\d.]+) ([\d.]+) ([\d.]+)", строка_цвета)
    if м:
        r, g, b = (float(x) * 255 for x in м.groups())
    else:
        r, g, b = (int(x) for x in re.match(r"rgba?\((\d+),\s*(\d+),\s*(\d+)", строка_цвета).groups())

    def канал(c: float) -> float:
        c /= 255
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4

    return 0.2126 * канал(r) + 0.7152 * канал(g) + 0.0722 * канал(b)


def светимость_поверх(цвет: str, подложка: str) -> float:
    """Светимость краски, ПОЛОЖЕННОЙ на подложку: словарь красит подписи полупрозрачным
    `color-mix(… , transparent)`, и `светимость_rgb` считает такую краску непрозрачной — контраст
    выходит завышенным. Складываем каналы по альфе, как это делает браузер, и только потом меряем."""
    м = re.match(r"color\(srgb ([\d.]+) ([\d.]+) ([\d.]+)(?:\s*/\s*([\d.]+))?", цвет)
    if м:
        r, g, b = (float(x) * 255 for x in м.groups()[:3])
        альфа = float(м.group(4)) if м.group(4) is not None else 1.0
    else:
        части = re.match(r"rgba?\((\d+),\s*(\d+),\s*(\d+)(?:,\s*([\d.]+))?", цвет)
        r, g, b = (int(x) for x in части.groups()[:3])
        альфа = float(части.group(4)) if части.group(4) is not None else 1.0
    if альфа >= 1:
        return светимость_rgb(цвет)
    ф = re.match(r"color\(srgb ([\d.]+) ([\d.]+) ([\d.]+)", подложка)
    if ф:
        фr, фg, фb = (float(x) * 255 for x in ф.groups())
    else:
        фr, фg, фb = (int(x) for x in re.match(r"rgba?\((\d+),\s*(\d+),\s*(\d+)", подложка).groups())
    смесь = tuple(к * альфа + ф * (1 - альфа) for к, ф in ((r, фr), (g, фg), (b, фb)))
    return светимость_rgb("rgb(%d, %d, %d)" % tuple(round(x) for x in смесь))


def отрезать_блок(css: str, начало: int) -> tuple:
    """Кусок текста от `начало` до закрывающей скобки этого блока и позиция сразу за ним."""
    глубина, i = 0, css.index("{", начало)
    while i < len(css):
        глубина += 1 if css[i] == "{" else -1 if css[i] == "}" else 0
        if глубина == 0:
            return css[начало:i + 1], i + 1
        i += 1
    return css[начало:], len(css)


def без_комментариев(css: str) -> str:
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    return re.sub(r"@media[^{]*\{", "{", css)   # прелюдия медиазапроса — не свойство


