class КрупностьНаТелефоне(unittest.TestCase):
    """Фикс-раунд Л, замечание 3 — вилка, а не число.

    Маятник: фикс-раунд Д чинил «фигура выглядывает снизу» и увёл кадр в «одну голову»; исправь
    сейчас одно число обратно — и через раунд качнёт в третий раз. Поэтому норма задана вилкой
    (`обложка.НОРМА_ГОЛОВЫ_НА_ТЕЛЕФОНЕ`), а этот тест держит обе её кромки: каждая доля головы,
    зашитая в телефонные правила схем с вырезом, обязана лежать внутри вилки. Числитель в
    `--кадр-выреза: calc(X% / var(--голова-в-кадре, …))` — это и есть доля головы в высоте
    телефонной рамки: высота кадра множится на долю головы в самом кадре и даёт ровно X %.
    """

    @classmethod
    def setUpClass(cls):
        sys.path.insert(0, str(ROOT / "ядро" / "скрипты"))
        import обложка
        cls.обложка = обложка
        cls.вырез = (ROOT / "ядро" / "блоки" / "стили-первый-экран-вырез.css").read_text(encoding="utf-8")

    def _телефонный_кусок(self) -> str:
        """Все медиазапросы телефона файла выреза подряд: их там два — орбита с живым портретом и центр."""
        куски = []
        место = 0
        while True:
            начало = self.вырез.find("@media (max-width: 899px)", место)
            if начало < 0:
                return "\n".join(куски)
            глубина, конец = 0, начало
            for i in range(начало, len(self.вырез)):
                if self.вырез[i] == "{":
                    глубина += 1
                elif self.вырез[i] == "}":
                    глубина -= 1
                    if глубина == 0:
                        конец = i
                        break
            куски.append(self.вырез[начало:конец])
            место = конец + 1

    def test_доля_головы_на_телефоне_внутри_вилки(self):
        низ, верх = self.обложка.НОРМА_ГОЛОВЫ_НА_ТЕЛЕФОНЕ
        доли = [float(ч) / 100 for ч in re.findall(r"--кадр-выреза: calc\(([\d.]+)% /", self._телефонный_кусок())]
        self.assertGreaterEqual(len(доли), 3, "телефонные правила крупности пропали из файла выреза")
        for доля in доли:
            self.assertGreaterEqual(доля, низ, f"{доля}: голова мельче нижней кромки вилки — фигура выглянет снизу")
            self.assertLessEqual(доля, верх, f"{доля}: голова крупнее верхней кромки вилки — в кадре останется одна голова")

    def test_вилка_двусторонняя_и_не_вырожденная(self):
        низ, верх = self.обложка.НОРМА_ГОЛОВЫ_НА_ТЕЛЕФОНЕ
        self.assertLess(низ, верх)
        self.assertGreater(верх - низ, .05, "вилка схлопнулась в число — маятник качнётся снова")


