    def test_на_тёмном_акцент_три_состояния(self):
        # Задача 7, фикс-раунд 1: правило задачи 6 («на тёмном акцент — золото у всех») было неверным —
        # проверка всех двенадцати макетов показала пять тёмных схем с ярко-красным (акцент-яркий) и
        # только четыре с золотом (тёплый). Тест — на три состояния: 1) дефолт без схемного класса
        # (и на примере орбиты) — акцент-яркий; 2) сцена (принята с золотом в задаче 6, не ломаем) —
        # тёплый; 3) кнопка и кикер — свои правила, не смешиваются ни с тем, ни с другим. Розового
        # тут не будет: solid var() поверх тёмного фона, не смешение с белым (см. РОЗОВОЕ).
        стр = self.браузер.new_page()
        стр.goto(self.путь.as_uri())
        яркий = стр.evaluate("s => getComputedStyle(document.querySelector('#акцент-яркий')).color")
        тёплый = стр.evaluate("s => getComputedStyle(document.querySelector('#тёплый')).color")
        self.assertNotEqual(яркий, тёплый, "акцент-яркий и тёплый — разные цвета, состояния не должны схлопнуться")
        # 1) общий тёмный без схемного класса и схема без золотого модификатора (орбита) — яркий.
        self.assertEqual(стр.evaluate("s => getComputedStyle(document.querySelector('.акцент')).color"), яркий)
        self.assertEqual(стр.evaluate("s => getComputedStyle(document.querySelector('#акцент-дефолт')).color"), яркий)
        # 2) сцена — золото, отдельным модификатором, не общим правилом.
        self.assertEqual(стр.evaluate("s => getComputedStyle(document.querySelector('#акцент-сцена')).color"), тёплый)
        # 3) кнопка и кикер — свои цвета, не спутаны с акцентом h1.
        self.assertEqual(стр.evaluate("s => getComputedStyle(document.querySelector('.кнопка--главная')).backgroundColor"),
                         стр.evaluate("s => getComputedStyle(document.querySelector('#акцент')).color"))
        self.assertEqual(стр.evaluate("s => getComputedStyle(document.querySelector('.кикер')).color"), тёплый)
        стр.close()

    def test_карточка_стекло_темнее_фона_не_светлее(self):
        # Фикс-раунд 2 задачи 5: `--цвет-стекло` был светлым 8% — на тёмном плита оказывалась СВЕТЛЕЕ
        # фона (обратный знак, не оттенок мимо). Подстрока тут бесполезна — сравниваем яркость.
        стр = self.браузер.new_page()
