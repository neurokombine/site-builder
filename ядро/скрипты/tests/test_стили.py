                    стр.wait_for_timeout(300)
                    з = стр.evaluate(замер)
                    низ_подбородка = з["верх"] + подбородок * з["высота_кадра"]
                    self.assertGreater(з["плашка_верх"], низ_подбородка,
                                       f"{имя}: плашка «имя · опора» села на подбородок")
                    self.assertGreaterEqual(з["плашка_верх"] - низ_подбородка, з["плашка_высота"] * .5,
                                            f"{имя}: плашка подошла к подбородку вплотную")
                    self.assertLess(з["плашка_низ"], з["низ_окна"], f"{имя}: плашка вылезла из картинки")
                    # …и не уехала вниз: она должна стоять на непрозрачной части фотографии, а не на
                    # растворённом хвосте. Верхнюю границу даёт другая строка стиля — маска картинки,
