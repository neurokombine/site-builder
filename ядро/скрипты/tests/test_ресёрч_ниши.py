"""Ресёрч ниши: несколько чужих сайтов за один проход и сводка по измеримому.

Сводка считается чистыми функциями — их гоняем на выдуманных замерах без браузера.
Браузерный прогон один на класс, по учебным страницам через file://, без интернета.
"""
