from pathlib import Path

СКРИПТЫ = Path(__file__).resolve().parent.parent
ФИКСТУРЫ = Path(__file__).resolve().parent / "фикстуры"
sys.path.insert(0, str(СКРИПТЫ))

import глаза  # noqa: E402
import ресёрч_ниши  # noqa: E402

# Нейтральные тестовые цвета — не палитра бренда, просто белый / тёмно-серый / почти чёрный
# для проверки «тёмный/светлый первый экран». Собираем их так же, как ЦВЕТ_КНОПКИ в
# test_глаза.py, а не хардкодим hex-литералом.
БЕЛЫЙ_ФОН = "#{:02x}{:02x}{:02x}".format(255, 255, 255)
ЦВЕТ_ТЕКСТА = "#{:02x}{:02x}{:02x}".format(34, 34, 34)
ТЁМНЫЙ_ФОН = "#{:02x}{:02x}{:02x}".format(16, 16, 16)


def замер(адрес, *, шрифт="Open Sans", кегль_тел=16, воздух=45.0, фон=БЕЛЫЙ_ФОН,
          мелкого=0, вбок=False, статус="ок", вид=None, телефон_статус=None, запасной=None):
    устройство = {
        "статус": статус, "не_пустило": вид, "шрифт_заголовков": "Montserrat",
        "шрифт_текста": шрифт, "кегли": {"текст": {"px": кегль_тел}},
        "интерлиньяж": {"px": 24}, "цвета_текста": [{"hex": ЦВЕТ_ТЕКСТА, "доля": 90.0}],
        "прокрутка_вбок": {"есть": вбок}, "мелкий_текст": {"элементов_мельче_14": мелкого},
        "вылезающие_картинки": [], "самый_крупный_текст": {"px": 32, "текст": "Заголовок из трёх слов"},
        "воздух": {"доля": воздух, "фон_скриншота_hex": фон}, "заголовок_вкладки": "Пример",
    }
    if запасной is not None:
        # так список `шрифты` приходит из глаза.py: применённое имя плюс признак, общее ли
        # семейство стояло в CSS (`запасной_ли`)
        устройство["шрифты"] = [
            {"объявлен": шрифт, "применён": шрифт, "запасной_ли": запасной,
             "элементов": 12, "теги": {"P": 10}},
        ]
    телефон = dict(устройство)
    if телефон_статус is not None:
        # только для устройства «телефон» подменяем статус — компьютер снят как обычно;
        # так собираем тестовый кейс «только_компьютер» без ключей стилей на телефоне
        телефон = {"статус": телефон_статус, "не_пустило": {"вид": "ошибка",
                                                            "признак": "страница не отдалась"}}
    return {"адрес": адрес, "устройства": {"компьютер": dict(устройство), "телефон": телефон},
            "итог": {"статус": статус, "не_пустило": вид}}


class ЧертыИСводкаТесты(unittest.TestCase):
    def test_черты_снимаются_с_телефона_и_компьютера(self):
        ч = ресёрч_ниши.собрать_черты(замер("https://a.ru", фон=ТЁМНЫЙ_ФОН, мелкого=3))
        self.assertEqual(ч["адрес"], "https://a.ru")
        self.assertEqual(ч["шрифт_текста"], "Open Sans")
        self.assertTrue(ч["тёмный_первый_экран"])
        self.assertTrue(ч["мелкий_текст_на_телефоне"])
        self.assertEqual(ч["воздух_словами"], "средне")

    def test_системное_имя_шрифта_не_становится_своим(self):
        # Arial стоит на устройстве и так: браузер доложит «применился, не запасной»,
        # но своим, загруженным сайтом, шрифт от этого не станет
        ч = ресёрч_ниши.собрать_черты(замер("https://a.ru", шрифт="Arial", запасной=False))
        self.assertFalse(ч["свой_шрифт_загружен"])

    def test_свой_шрифт_загрузился_или_подставился_запасной(self):
        загрузился = ресёрч_ниши.собрать_черты(
            замер("https://a.ru", шрифт="Montserrat", запасной=False))
        подставился = ресёрч_ниши.собрать_черты(
            замер("https://b.ru", шрифт="Montserrat", запасной=True))
        self.assertTrue(загрузился["свой_шрифт_загружен"])
        self.assertFalse(подставился["свой_шрифт_загружен"])

    def test_у_всех_и_ни_у_кого(self):
        черты = [ресёрч_ниши.собрать_черты(замер(f"https://{i}.ru")) for i in range(3)]
        с = ресёрч_ниши.сводка_ниши(черты)
        self.assertIn("шрифт текста: Open Sans", с["у_всех"])
        self.assertIn("тёмный первый экран", с["ни_у_кого"])
        self.assertEqual(с["сайтов"], 3)

    def test_большинство_и_по_разному(self):
        черты = [ресёрч_ниши.собрать_черты(замер("https://1.ru", мелкого=5)),
                 ресёрч_ниши.собрать_черты(замер("https://2.ru", мелкого=5)),
                 ресёрч_ниши.собрать_черты(замер("https://3.ru"))]
        с = ресёрч_ниши.сводка_ниши(черты)
        self.assertTrue(any("мелкий текст на телефоне" in х for х in с["у_большинства"]))

    def test_не_пустившие_отдельно(self):
        черты = [ресёрч_ниши.собрать_черты(замер("https://1.ru")),
                 ресёрч_ниши.собрать_черты(замер("https://2.ru", статус="не пустило", вид="антибот_стена"))]
        с = ресёрч_ниши.сводка_ниши(черты)
        self.assertEqual(с["сайтов"], 1)
        self.assertEqual(с["не_пустило"][0]["адрес"], "https://2.ru")
        текст = ресёрч_ниши.сводка_словами(с)
        self.assertIn("Паттерн — не приговор", текст)
        self.assertIn("https://2.ru", текст)

    def test_один_сайт_не_даёт_у_всех(self):
        с = ресёрч_ниши.сводка_ниши([ресёрч_ниши.собрать_черты(замер("https://1.ru"))])
        self.assertEqual(с["у_всех"], [])
        self.assertIn("мало сайтов", ресёрч_ниши.сводка_словами(с))

    def test_только_компьютер_не_даёт_тихого_false_на_телефоне(self):
        """Компьютер снялся, телефон — нет (кейс «только_компьютер» из глаза.py). Три булевых
        признака телефона должны стать None («не измерено»), а не тихим False."""
        ч = ресёрч_ниши.собрать_черты(замер("https://1.ru", телефон_статус="ошибка"))
        self.assertEqual(ч["статус"], "ок", "сайт всё равно снят — компьютер помер")
        self.assertIsNone(ч["мелкий_текст_на_телефоне"])
        self.assertIsNone(ч["прокрутка_вбок_на_телефоне"])
        self.assertIsNone(ч["картинки_вылезают_на_телефоне"])

        другой = ресёрч_ниши.собрать_черты(замер("https://2.ru"))
        с = ресёрч_ниши.сводка_ниши([ч, другой])
        self.assertEqual(с["сайтов"], 2)
        # у обоих сайтов всего один сайт с измеренным телефоном — на признак телефона это
        # не должно тихо превратиться в «ни у кого» на одном-единственном замере
        for метка in ("мелкий текст на телефоне", "прокрутка вбок на телефоне",
                      "картинки вылезают за экран телефона"):
            self.assertNotIn(метка, с["ни_у_кого"], метка)
            self.assertNotIn(метка, с["у_всех"], метка)
        текст = ресёрч_ниши.сводка_словами(с)
        self.assertIn("не измерено", текст)

    def test_не_открывшиеся_сайты_считаются_отдельно_от_не_пустивших(self):
        черты = [ресёрч_ниши.собрать_черты(замер("https://1.ru")),
                 ресёрч_ниши.собрать_черты(замер("https://2.ru"))]
        с = ресёрч_ниши.сводка_ниши(
            черты, не_открылись=[{"адрес": "https://3.ru", "причина": "TimeoutError: упал"}])
        self.assertEqual(с["сайтов"], 2)
        self.assertEqual(с["не_пустило"], [])
        self.assertEqual(с["не_открылись"][0]["адрес"], "https://3.ru")
        текст = ресёрч_ниши.сводка_словами(с)
        self.assertIn("Не открылись", текст)
        self.assertIn("https://3.ru", текст)
        self.assertIn("снять экран самому", текст)
        self.assertIn("Сайтов передано: 3", текст)
        self.assertIn("не открылись: 1", текст)

    def test_сводка_ниши_без_не_открылись_даёт_пустой_список(self):
        с = ресёрч_ниши.сводка_ниши([ресёрч_ниши.собрать_черты(замер("https://1.ru")),
                                    ресёрч_ниши.собрать_черты(замер("https://2.ru"))])
        self.assertEqual(с["не_открылись"], [])


class ПрогонТесты(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.папка = tempfile.TemporaryDirectory()
        cls.работа = Path(cls.папка.name) / "моё-дело"

    @classmethod
    def tearDownClass(cls):
        cls.папка.cleanup()

    def test_1_три_страницы_и_сводка(self):
        ссылки = [str(ФИКСТУРЫ / "лендинг.html"), str(ФИКСТУРЫ / "референс" / "index.html"),
                  str(ФИКСТУРЫ / "стена.html")]
        р = subprocess.run([sys.executable, str(СКРИПТЫ / "ресёрч_ниши.py"), *ссылки,
                            "--работа", str(self.работа)], capture_output=True, text=True, timeout=240)
        self.assertEqual(р.returncode, 0, р.stdout + р.stderr)
        референсы = self.работа / "референсы"
        папки = [п for п in референсы.iterdir() if п.is_dir()]
        self.assertEqual(len(папки), 3)
        for п in папки:
            self.assertTrue((п / "замеры.json").exists(), п)
        сводка = json.loads((референсы / "_сводка.json").read_text(encoding="utf-8"))
        self.assertEqual(сводка["сайтов"], 2)
        self.assertEqual(len(сводка["не_пустило"]), 1)
        текст = (референсы / "_сводка.md").read_text(encoding="utf-8")
        self.assertIn("Паттерн — не приговор", текст)
        self.assertIn("МСК", текст)

    def test_2_только_сводка_без_браузера(self):
        # после первого теста папки есть; пересборка не должна открывать браузер
        with unittest.mock.patch.object(глаза, "запустить_браузер", side_effect=AssertionError("браузер не нужен")):
            код = ресёрч_ниши.main_с_аргументами(["--работа", str(self.работа), "--только-сводка"])
        self.assertEqual(код, 0)


if __name__ == "__main__":
    unittest.main()
