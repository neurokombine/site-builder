class ЗащитаСнятияСекцийТесты(unittest.TestCase):
    """Беда внутри снятия секций не должна уносить с собой весь проход и сводку.

    Свой браузер этот класс не держит: `main_с_аргументами` поднимает его сам, а два живых
    синхронных Playwright в одном потоке не уживаются.
    """

    @classmethod
    def setUpClass(cls):
        sys.path.insert(0, str(СКРИПТЫ))
        import проверить  # noqa: PLC0415

        cls._сервер = проверить.локальный_сервер(ФИКСТУРЫ / "ниша")
        корень = cls._сервер.__enter__()
        cls.адреса = [корень + "чужой-сайт.html", корень + "чужой-сайт-обёртки.html"]

    @classmethod
    def tearDownClass(cls):
        cls._сервер.__exit__(None, None, None)

    def test_сломанный_js_не_роняет_прогон(self):
        # беда ровно внутри снятия секций: сайт открылся, а отбор секций упал
        временная = tempfile.TemporaryDirectory()
        self.addCleanup(временная.cleanup)
        работа = Path(временная.name) / "сломанный-js"
        с_ошибкой = "() => { throw new Error('бах'); }"
        with unittest.mock.patch.object(ресёрч_ниши, "ОТБОР_СЕКЦИЙ_JS", с_ошибкой), \
             unittest.mock.patch.object(ресёрч_ниши, "ЗАПАСНОЙ_ОТБОР_JS", с_ошибкой):
            код = ресёрч_ниши.main_с_аргументами(
                ["--дизайн", "--работа", str(работа), *self.адреса])
        self.assertEqual(код, 0, "падение отбора секций утащило за собой весь проход")
        сводка = json.loads(
            (работа / "референсы" / "_сводка.json").read_text(encoding="utf-8"))
        self.assertEqual(сводка["сайтов"], 2, "второй сайт не доехал до сводки")
        self.assertEqual(сводка["решения_по_экранам"], [])
        self.assertTrue((работа / "референсы" / "_сводка.md").is_file(), "сводки нет вовсе")


