class БеруТесты(unittest.TestCase):
    ЖИВОЙ = ("# Референсы — ниша\n\n## Пять ответов\n- Есть у всех: фото\n\n"
             "## Что берём\n- Цену «от» у кнопки\n\n## Что не берём\n- Чужие тексты\n")

    def работа(self, текст=None):
        папка = Path(self.временная.name) / "моё-дело"
        папка.mkdir(parents=True, exist_ok=True)
        if текст is not None:
            (папка / "референсы.md").write_text(текст, encoding="utf-8")
        return папка

    def setUp(self):
        self.временная = tempfile.TemporaryDirectory()
        self.addCleanup(self.временная.cleanup)
        self.черты = [ресёрч_ниши.собрать_черты(замер_с_секциями(
            "https://один.ru", секции_по_типам("услуги-и-цены", "отзывы"), папка="один-ru"))]

    def test_раздел_беру_с_чекбоксами_появляется(self):
        работа = self.работа(self.ЖИВОЙ)
        путь, добавлено = ресёрч_ниши.дописать_беру(работа, self.черты)
        текст = путь.read_text(encoding="utf-8")
        self.assertEqual(добавлено, 2)
        self.assertIn("## Беру", текст)
        self.assertIn("- [ ] услуги-и-цены — один.ru — ", текст)
        self.assertIn("референсы/один-ru/секции/02-отзывы.png", текст)

    def test_живые_разделы_не_затираются(self):
        работа = self.работа(self.ЖИВОЙ)
        ресёрч_ниши.дописать_беру(работа, self.черты)
        текст = (работа / "референсы.md").read_text(encoding="utf-8")
        for кусок in ("## Пять ответов", "## Что берём", "- Цену «от» у кнопки",
                      "## Что не берём", "- Чужие тексты"):
            with self.subTest(кусок=кусок):
                self.assertIn(кусок, текст)

    def test_повторный_прогон_не_дублирует(self):
        работа = self.работа(self.ЖИВОЙ)
        ресёрч_ниши.дописать_беру(работа, self.черты)
        путь, добавлено = ресёрч_ниши.дописать_беру(работа, self.черты)
        self.assertEqual(добавлено, 0)
        текст = путь.read_text(encoding="utf-8")
        self.assertEqual(текст.count("- [ ] отзывы — один.ru"), 1)

    def test_отметка_человека_переживает_повторный_прогон(self):
        работа = self.работа(self.ЖИВОЙ)
        ресёрч_ниши.дописать_беру(работа, self.черты)
        файл = работа / "референсы.md"
        файл.write_text(файл.read_text(encoding="utf-8").replace("- [ ] отзывы", "- [x] отзывы"),
                        encoding="utf-8")
        ресёрч_ниши.дописать_беру(работа, self.черты)
        текст = файл.read_text(encoding="utf-8")
