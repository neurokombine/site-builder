def сырая_секция(заголовок, текст="", *, высота=420, светлота=240.0, карточек=0, строк=0,
                 кнопок=0, картинок=0):
    """Одна секция чужой страницы так, как её отдаёт замер разметки в браузере."""
    return {"заголовок": заголовок, "текст": текст, "высота": высота, "светлота": светлота,
            "карточек": карточек, "строк": строк, "кнопок": кнопок, "картинок": картинок}


def замер_с_секциями(адрес, секции, *, папка=None, всего=None, **прочее):
    """Замер сайта плюс уже снятые секции — так `--дизайн` кладёт их в замеры.json.

    `всего` — сколько секций на странице: больше снятых, когда сработал предел в 14.
    """
    з = замер(адрес, **прочее)
    з["секции"] = секции
    з["секций_всего"] = len(секции) if всего is None else всего
    з["папка"] = папка or глаза.слаг_из(адрес)
    return з


def секции_по_типам(*типы):
    """Готовые секции работы по типам — для сводки и «Беру», без браузера."""
    return [{"тип": т, "заголовок": т.capitalize(), "снимок": f"секции/{н:02d}-{т}.png",
             "светлота": 240.0, "карточек": 3, "кнопок": 1, "строк": 0, "картинок": 0,
             "приём": "карточки"}
            for н, т in enumerate(типы, start=1)]


