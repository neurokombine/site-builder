class СтенаНеСчитаетсяСайтом(unittest.TestCase):
    """Задача 5: антибот-стена приезжала в сводку полноправным сайтом.

    Живой случай 14.09.2026: страница «Подтвердите, что вы человек · Я не робот · Антибот Клауд»
    была посчитана сайтом «без замечаний, кегль 18, воздух 97,6 %» — и сводка «у всех / ни у
    кого» перекосилась вся: белый лист это, конечно, «просторно» и «системный шрифт».
    `глаза.МАРКЕРЫ_СТЕНЫ` этих слов не знает, а трогать `глаза.py` в этой линии нельзя — значит,
    стену дочитывает сам ресёрч, по тому тексту, что доехал до `замеры.json`.

    ⛔ Живых сайтов здесь не открываем: замеры выдуманные, как во всём этом файле.
    """

    СТЕНА = "Подтвердите, что вы человек:"

    def test_страница_со_стеной_становится_не_пустившей(self):
        ч = ресёрч_ниши.собрать_черты(замер("https://стена.ru", крупный_текст=self.СТЕНА))
        self.assertEqual(ч["статус"], "не_пустило")
        self.assertEqual(ч["не_пустило"], ресёрч_ниши.ВИД_СТЕНЫ)

    def test_каждый_маркер_ловится_и_в_крупном_тексте_и_в_заголовке_вкладки(self):
        for маркер in ресёрч_ниши.МАРКЕРЫ_ПРОВЕРКИ_НА_РОБОТОВ:
            with self.subTest(маркер=маркер, где="крупный текст"):
                ч = ресёрч_ниши.собрать_черты(
                    замер("https://a.ru", крупный_текст=маркер.upper()))
                self.assertEqual(ч["не_пустило"], ресёрч_ниши.ВИД_СТЕНЫ)
            with self.subTest(маркер=маркер, где="заголовок вкладки"):
                ч = ресёрч_ниши.собрать_черты(замер("https://a.ru", вкладка=маркер.title()))
                self.assertEqual(ч["не_пустило"], ресёрч_ниши.ВИД_СТЕНЫ)

    def test_стена_не_попадает_в_у_всех_и_ни_у_кого(self):
        черты = [ресёрч_ниши.собрать_черты(замер("https://1.ru")),
                 ресёрч_ниши.собрать_черты(замер("https://2.ru")),
                 # стена: белый лист, системный шрифт, «просторно» — ровно то, что перекашивало
                 ресёрч_ниши.собрать_черты(замер("https://стена.ru", крупный_текст=self.СТЕНА,
                                                 шрифт="system-ui", воздух=97.6, кегль_тел=18))]
        с = ресёрч_ниши.сводка_ниши(черты)
        self.assertEqual(с["сайтов"], 2, "стена посчиталась снятым сайтом")
        self.assertEqual([з["адрес"] for з in с["не_пустило"]], ["https://стена.ru"])
        self.assertIn("шрифт текста: Open Sans", с["у_всех"], "стена испортила «у всех»")
        текст = ресёрч_ниши.сводка_словами(с)
        self.assertIn("проверка на роботов", текст)
        self.assertIn("скриншот сами", текст)
        # таблица снятых сайтов — только о живых двух
        self.assertNotIn("https://стена.ru |", текст)

    def test_обычная_страница_как_раньше(self):
        ч = ресёрч_ниши.собрать_черты(замер("https://обычный.ru"))
        self.assertEqual(ч["статус"], "ок")
        self.assertIsNone(ч["не_пустило"])
        с = ресёрч_ниши.сводка_ниши([ч, ресёрч_ниши.собрать_черты(замер("https://2.ru"))])
        self.assertEqual(с["сайтов"], 2)
        self.assertEqual(с["не_пустило"], [])

    def test_403_без_стены_это_доступ_запрещён_а_не_проверка_на_роботов(self):
        # так 403 приезжает из глаза.py: вид «антибот_стена», признак — слово из его же списка
        ч = ресёрч_ниши.собрать_черты(замер(
            "https://закрыт.ru", статус="не_пустило", крупный_текст="403 Forbidden",
            вид={"вид": "антибот_стена", "признак": "403 forbidden"}))
        self.assertEqual(ч["не_пустило"], ресёрч_ниши.ВИД_ДОСТУПА)
        текст = ресёрч_ниши.сводка_словами(ресёрч_ниши.сводка_ниши([ч]))
        # вид сайта в списке «Не пустило» — именно наш, а не чужой
        self.assertIn("https://закрыт.ru — доступ запрещён.", текст)
        self.assertNotIn("— проверка на роботов.", текст)
        self.assertIn("снимок экрана самому", текст)

    def test_стена_важнее_403_если_видны_её_слова(self):
        ч = ресёрч_ниши.собрать_черты(замер(
            "https://и_то_и_то.ru", статус="не_пустило", крупный_текст="Я не робот",
            вкладка="403 Forbidden",
            вид={"вид": "антибот_стена", "признак": "403 forbidden"}))
        self.assertEqual(ч["не_пустило"], ресёрч_ниши.ВИД_СТЕНЫ)

    def test_название_и_подсказка_есть_у_обоих_видов(self):
        for вид in (ресёрч_ниши.ВИД_СТЕНЫ, ресёрч_ниши.ВИД_ДОСТУПА):
            with self.subTest(вид=вид):
                self.assertNotEqual(ресёрч_ниши.название_вида(вид), вид)
                # ход у всех видов один (CLAUDE.md § 7) — снять экран самому; слова у глаза.py
                # («скриншот сами») и у нашего вида («снимок экрана самому») чуть разные
                подсказка = ресёрч_ниши.подсказка_по_виду(вид)
                self.assertTrue(any(с in подсказка for с in ("скриншот сами", "экрана самому")),
                                подсказка)


class ПрогонТесты(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.папка = tempfile.TemporaryDirectory()
        cls.работа = Path(cls.папка.name) / "моё-дело"

    @classmethod
    def tearDownClass(cls):
        cls.папка.cleanup()

    def test_1_три_страницы_и_сводка(self):
        ссылки = [str(ФИКСТУРЫ / "лендинг.html"), str(ФИКСТУРЫ / "референс" / "index.html"),
                  str(ФИКСТУРЫ / "стена.html")]
        р = subprocess.run([sys.executable, str(СКРИПТЫ / "ресёрч_ниши.py"), *ссылки,
                            "--работа", str(self.работа)], capture_output=True, text=True, timeout=240)
        self.assertEqual(р.returncode, 0, р.stdout + р.stderr)
        референсы = self.работа / "референсы"
        папки = [п for п in референсы.iterdir() if п.is_dir()]
        self.assertEqual(len(папки), 3)
        for п in папки:
            self.assertTrue((п / "замеры.json").exists(), п)
        сводка = json.loads((референсы / "_сводка.json").read_text(encoding="utf-8"))
        self.assertEqual(сводка["сайтов"], 2)
        self.assertEqual(len(сводка["не_пустило"]), 1)
        текст = (референсы / "_сводка.md").read_text(encoding="utf-8")
        self.assertIn("Паттерн — не приговор", текст)
        self.assertIn("МСК", текст)

    def test_2_только_сводка_без_браузера(self):
        # после первого теста папки есть; пересборка не должна открывать браузер
        with unittest.mock.patch.object(глаза, "запустить_браузер", side_effect=AssertionError("браузер не нужен")):
            код = ресёрч_ниши.main_с_аргументами(["--работа", str(self.работа), "--только-сводка"])
        self.assertEqual(код, 0)


if __name__ == "__main__":
    unittest.main()
