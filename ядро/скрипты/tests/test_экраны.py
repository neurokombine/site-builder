"""Каталог экранов: инструкция на каждый тип, семь разделов, настоящие поля, живые ссылки.

Экран ниже обложки больше не рецепт: нейросеть верстает его свободно, а что на нём обязано
быть, говорит инструкция `ядро/экраны/<тип>.md`. Инструкция — единственное, что осталось от
рецепта, и три вещи в ней держит этот сторож:

* **файл на каждый тип обоих наборов** (`собрать.ТИПЫ_НАБОРА` плюс обложка) — иначе верстальщик
  открывает каталог и не находит того экрана, который стоит у него в прототипе;
* **семь разделов ровно в том порядке**, в каком инструкцию читают: зачем → что обязано быть →
  чем доказываем → из каких полей → какая роль в ритме → какие компоновки → чего нельзя;
* **поля и ссылки настоящие** — имя поля сверяется с форматом прототипа (`прототип.md` § 2 и
  `прототип-поля-экранов.md` § 9), ссылка на пример — с папкой галереи. Придуманное поле уводит
  человека писать в прототип строку, которой система не знает, а ссылка в никуда читается как
  сломанная система.
"""
import re
import sys
import unittest
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(КОРЕНЬ / "ядро" / "скрипты"))
import собрать  # noqa: E402

ЯДРО = КОРЕНЬ / "ядро"
ЭКРАНЫ = ЯДРО / "экраны"
ИНДЕКС = ЯДРО / "экраны.md"
ПРИМЕРЫ = ЯДРО / "галерея" / "примеры"
# Обложка каталогом типов не описана (её схемы живут в `блоки.md`), но инструкция у неё своя —
# короткая, со ссылками туда же. Отсюда «плюс первый экран».
ТИПЫ = ["первый-экран"] + sorted({т for типы in собрать.ТИПЫ_НАБОРА.values() for т in типы})
РАЗДЕЛЫ = ["## Зачем", "## Обязательно", "## Доказательство", "## Поля прототипа",
           "## Роль в ритме", "## Компоновки", "## Нельзя"]
ПОТОЛОК_ИНСТРУКЦИИ = 80
ПОТОЛОК_ИНДЕКСА = 120
ПОТОЛОК_БЛОКОВ = 150
ССЫЛКА_НА_ПРИМЕР = re.compile(r"`(ядро/галерея/примеры/[^`]+)`")
ИМЯ_ПОЛЯ = re.compile(r"^[А-ЯЁ·][А-Яа-яЁё ·:]*$")


def строки_таблицы(текст: str, раздел: str) -> list[str]:
    """Строки markdown-таблицы внутри раздела — без шапки и без разделительной строки."""
    кусок = текст.split(раздел, 1)[1].split("\n## ", 1)[0]
    строки = [с.strip() for с in кусок.splitlines() if с.strip().startswith("|")]
    return [с for с in строки[2:] if с.count("|") >= 3]


def поля_раздела(текст: str) -> list[str]:
    """Имена полей прототипа из первой колонки таблицы `## Поля прототипа`.

    Берём только то, что похоже на имя поля: `Заголовок`, `· срок:`. Слот вёрстки (`{{ЦЕНА_1}}`)
    в первой колонке тоже встречается — у экранов, которые система заполняет сама, — и полем
    прототипа не считается.
    """
    имена = []
    for строка in строки_таблицы(текст, "## Поля прототипа"):
        первая = строка.split("|")[1]
        for имя in re.findall(r"`([^`]+)`", первая):
            if not имя.startswith("{{") and ИМЯ_ПОЛЯ.match(имя):
                имена.append(имя)
    return имена


def поля_формата() -> set[str]:
    """Все имена полей, которые знает формат прототипа: базовые и поля экранов ниже первого."""
    формат = (ЯДРО / "прототип.md").read_text(encoding="utf-8")
    кусок = формат.split("## 2 · Формат", 1)[1].split("\n## 3 ", 1)[0]
    кусок = re.sub(r"```.*?```", "", кусок, flags=re.S)   # образец прототипа — не список полей
    базовые = {и for и in re.findall(r"`([^`]+)`", кусок) if ИМЯ_ПОЛЯ.match(и)}
    таблица = (ЯДРО / "прототип-поля-экранов.md").read_text(encoding="utf-8")
    ниже = set()
    for строка in строки_таблицы(таблица, "## 9 · Таблица целиком"):
        найдено = re.search(r"`([^`]+)`", строка.split("|")[1])
        if найдено:
            ниже.add(найдено.group(1))
    return базовые | ниже


class КаталогЭкранов(unittest.TestCase):
    def test_на_каждый_тип_обоих_наборов_есть_инструкция(self):
        """Тип из состава набора без инструкции — экран, который верстают наугад."""
        for тип in ТИПЫ:
            with self.subTest(тип=тип):
                self.assertTrue((ЭКРАНЫ / f"{тип}.md").is_file(),
                                f"нет инструкции `ядро/экраны/{тип}.md`")
        лишние = sorted(ф.stem for ф in ЭКРАНЫ.glob("*.md") if ф.stem not in ТИПЫ)
        self.assertEqual(лишние, [], "в каталоге лежит тип, которого нет ни в одном наборе")
        self.assertEqual(len(list(ЭКРАНЫ.glob("*.md"))), 17)

    def test_семь_разделов_в_нужном_порядке(self):
        """Порядок — это порядок чтения перед вёрсткой; переставленный раздел его ломает."""
        for тип in ТИПЫ:
            текст = (ЭКРАНЫ / f"{тип}.md").read_text(encoding="utf-8")
            with self.subTest(тип=тип):
                self.assertEqual(re.findall(r"^## .*$", текст, re.M), РАЗДЕЛЫ)

    def test_поля_прототипа_существуют_в_формате(self):
        """Поле, которого формат прототипа не знает, — строка, которую человек напишет зря."""
        известные = поля_формата()
        self.assertIn("Заголовок", известные)      # сторож, который ничего не набрал, не сторож
        self.assertIn("Вид цены", известные)
        self.assertGreater(len(известные), 25, "разбор формата прототипа опустел")
        собрано = 0
        for тип in ТИПЫ:
            текст = (ЭКРАНЫ / f"{тип}.md").read_text(encoding="utf-8")
            имена = поля_раздела(текст)
            собрано += len(имена)
            for имя in имена:
                with self.subTest(тип=тип, поле=имя):
                    self.assertIn(имя, известные,
                                  f"поля «{имя}» нет ни в `прототип.md` § 2, ни в "
                                  "`прототип-поля-экранов.md` § 9")
        self.assertGreater(собрано, 40, "таблицы полей почти пусты — проверять нечего")

    def test_каждая_инструкция_называет_поля_и_компоновки(self):
        """Раздел без таблицы полей и без ссылки на пример — половина инструкции."""
        for тип in ТИПЫ:
            текст = (ЭКРАНЫ / f"{тип}.md").read_text(encoding="utf-8")
            with self.subTest(тип=тип):
                self.assertTrue(строки_таблицы(текст, "## Поля прототипа"),
                                "в `## Поля прототипа` нет таблицы")
                компоновки = текст.split("## Компоновки", 1)[1].split("\n## ", 1)[0]
                self.assertTrue(ССЫЛКА_НА_ПРИМЕР.search(компоновки) or тип == "первый-экран",
                                "в `## Компоновки` нет ни одной ссылки на пример галереи")

    def test_ссылки_на_примеры_ведут_в_существующие_папки(self):
        """Ссылка в никуда читается как сломанная система: человек открывает — а там пусто."""
        файлы = [ИНДЕКС] + [ЭКРАНЫ / f"{тип}.md" for тип in ТИПЫ]
        найдено = 0
        for файл in файлы:
            текст = файл.read_text(encoding="utf-8")
            for путь in ССЫЛКА_НА_ПРИМЕР.findall(текст):
                найдено += 1
                with self.subTest(файл=файл.name, путь=путь):
                    self.assertTrue((КОРЕНЬ / путь.rstrip("/")).exists(),
                                    f"{файл.name} ссылается на {путь}, а его нет")
        self.assertGreater(найдено, 20, "ссылок на примеры почти нет — проверять нечего")

    def test_индекс_знает_все_семнадцать(self):
        """Индекс — вход в каталог: не назвал тип, значит его никто не найдёт."""
        индекс = ИНДЕКС.read_text(encoding="utf-8")
        for тип in ТИПЫ:
            with self.subTest(тип=тип):
                self.assertIn(f"`экраны/{тип}.md`", индекс)
                self.assertRegex(индекс, re.compile(rf"\|\s*{re.escape(тип)}\s*\|"))

    def test_документы_не_растут(self):
        """Потолок строк — то самое правило «документы ядра дробятся, а не растут»."""
        for тип in ТИПЫ:
            строк = len((ЭКРАНЫ / f"{тип}.md").read_text(encoding="utf-8").splitlines())
            with self.subTest(тип=тип):
                self.assertLessEqual(строк, ПОТОЛОК_ИНСТРУКЦИИ, f"{тип}.md: {строк} строк")
        self.assertLessEqual(len(ИНДЕКС.read_text(encoding="utf-8").splitlines()), ПОТОЛОК_ИНДЕКСА)
        блоки = (ЯДРО / "блоки.md").read_text(encoding="utf-8").splitlines()
        self.assertLessEqual(len(блоки), ПОТОЛОК_БЛОКОВ, f"блоки.md: {len(блоки)} строк")

    def test_разбор_таблицы_и_имён_полей(self):
        """Проверка самого сторожа: он читает первую колонку и отличает поле от слота."""
        образец = ("## Поля прототипа\n\n| Поле | Куда встаёт |\n|---|---|\n"
                   "| `Заголовок` | шапка секции, `{{ЗАГОЛОВОК}}` |\n"
                   "| `· срок:` у пункта | бейдж шага |\n"
                   "| `{{ГОД}}` — из профиля | нижняя полоса |\n\n## Нельзя\n")
        self.assertEqual(поля_раздела(образец), ["Заголовок", "· срок:"])
        self.assertEqual(len(строки_таблицы(образец, "## Поля прототипа")), 3)


if __name__ == "__main__":
    unittest.main()
