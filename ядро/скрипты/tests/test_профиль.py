"""Тесты профиля: --новый, --взять, --проверить, --соседи.

Запуск из корня репозитория:
    .venv/bin/python -m unittest discover -s ядро/скрипты/tests -t .
"""
import contextlib
import io
import json
import shutil
import sys
import tempfile
import unittest
from pathlib import Path

СКРИПТЫ = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(СКРИПТЫ))

import профиль  # noqa: E402

КОРЕНЬ_РЕАЛЬНЫЙ = СКРИПТЫ.parent.parent
РЕАЛЬНЫЙ_ШАБЛОН = КОРЕНЬ_РЕАЛЬНЫЙ / "профили" / "_шаблон" / "profile.json"


def _фейковый_профиль(**правки) -> dict:
    """Копия настоящего шаблона (валидная сама по себе), с точечными правками для теста."""
    данные = json.loads(РЕАЛЬНЫЙ_ШАБЛОН.read_text(encoding="utf-8"))
    for путь, значение in правки.items():
        *голова, хвост = путь.split(".")
        узел = данные
        for часть in голова:
            узел = узел[часть]
        узел[хвост] = значение
    return данные


class ФейковыйКореньТесты(unittest.TestCase):
    """Общий фикстур: временный корень со своим профили/_шаблон/profile.json."""

    def setUp(self):
        self._временная = tempfile.TemporaryDirectory()
        self.addCleanup(self._временная.cleanup)
        self.контейнер = Path(self._временная.name)
        self.корень = self.контейнер / "site-builder"
        self.профили = self.корень / "профили"
        self.шаблон_папка = self.профили / "_шаблон"
        self.шаблон_папка.mkdir(parents=True)
        shutil.copy(РЕАЛЬНЫЙ_ШАБЛОН, self.шаблон_папка / "profile.json")
        self.шаблон = self.шаблон_папка / "profile.json"


class НовыйПрофильТесты(ФейковыйКореньТесты):
    def test_новый_создаёт_профиль_и_делает_активным(self):
        успех, сообщение = профиль.новый_профиль(
            "проба", папка_профилей=self.профили, шаблон=self.шаблон,
        )
        self.assertTrue(успех, сообщение)

        файл = self.профили / "проба" / "profile.json"
        self.assertTrue(файл.exists())
        данные = json.loads(файл.read_text(encoding="utf-8"))
        self.assertEqual(данные["профиль"], "проба")
        self.assertIn("сайт", данные)
        self.assertEqual(
            профиль.прочитать_активного(папка_профилей=self.профили), "проба",
        )

    def test_новый_не_перезаписывает_существующий(self):
        профиль.новый_профиль("проба", папка_профилей=self.профили, шаблон=self.шаблон)
        файл = self.профили / "проба" / "profile.json"
        файл.write_text('{"метка": "не трогать"}', encoding="utf-8")

        успех, сообщение = профиль.новый_профиль(
            "проба", папка_профилей=self.профили, шаблон=self.шаблон,
        )

        self.assertFalse(успех)
        self.assertIn("уже есть", сообщение)
        self.assertEqual(файл.read_text(encoding="utf-8"), '{"метка": "не трогать"}')


class ИмяПрофиляТесты(ФейковыйКореньТесты):
    """Имя профиля — это имя папки. Что нельзя пускать в имя папки, туда и не попадает."""

    ПЛОХИЕ = [
        "клиент/иванов",     # профиль уезжает в подпапку, а --список его не покажет
        "..\\побег",         # и вовсе за пределы папки профилей
        "../побег",          # туда не достаёт .gitignore — контакты клиента уедут наружу
        "_шаблон",           # образец, из которого заводятся все остальные
        "_активный",         # служебный указатель
        "",                  # имени нет вовсе
        "   ",
    ]

    def test_плохое_имя_отклоняется_с_объяснением(self):
        for имя in self.ПЛОХИЕ:
            with self.subTest(имя=имя):
                self.assertIsNotNone(профиль.имя_допустимо(имя))

    def test_человеческое_имя_проходит(self):
        for имя in ("Салон Ирина", "иванов", "мастерская-2", "ООО Ромашка"):
            with self.subTest(имя=имя):
                self.assertIsNone(профиль.имя_допустимо(имя), имя)

    def test_новый_профиль_с_плохим_именем_ничего_не_создаёт(self):
        for имя in self.ПЛОХИЕ:
            with self.subTest(имя=имя):
                успех, сообщение = профиль.новый_профиль(
                    имя, папка_профилей=self.профили, шаблон=self.шаблон)
                self.assertFalse(успех, имя)
                self.assertIn("имени профиля", сообщение.lower())
        # ⛔ главное: наружу папки профилей ничего не легло
        self.assertFalse((self.корень / "побег").exists())
        self.assertFalse((self.контейнер / "побег").exists())
        self.assertEqual(профиль.список_профилей(self.профили), [])

    def test_новый_профиль_с_человеческим_именем_создаётся(self):
        успех, сообщение = профиль.новый_профиль(
            "Салон Ирина", папка_профилей=self.профили, шаблон=self.шаблон)
        self.assertTrue(успех, сообщение)
        self.assertTrue((self.профили / "Салон Ирина" / "profile.json").exists())
        self.assertEqual(профиль.список_профилей(self.профили), ["Салон Ирина"])

    def test_как_с_плохим_именем_не_копирует(self):
        сосед = self.контейнер / "сосед" / "профили" / "мастер"
        сосед.mkdir(parents=True)
        (сосед / "profile.json").write_text(
            json.dumps(_фейковый_профиль(), ensure_ascii=False), encoding="utf-8")

        успех, сообщение = профиль.взять_профиль(
            сосед, имя="../побег", папка_профилей=self.профили, шаблон=self.шаблон)

        self.assertFalse(успех)
        self.assertIn("имени профиля", сообщение.lower())
        self.assertFalse((self.корень / "побег").exists())
        self.assertFalse((self.контейнер / "побег").exists())


class ВзятьПрофильТесты(ФейковыйКореньТесты):
    def _фейковый_сосед(self, **поля) -> Path:
        временная = tempfile.TemporaryDirectory()
        self.addCleanup(временная.cleanup)
        папка = Path(временная.name) / "профили" / "клиент-1"
        папка.mkdir(parents=True)
        данные = {
            "профиль": "клиент-1",
            "название": "Дело клиента",
            "автор": {"имя": "Иван Иванов", "роль": "Мастер"},
            "контакты": [{"название": "Телеграм", "адрес": "@ivan"}],
            "палитра": {"акцент": "оставить-как-было"},
            "шрифты": {"заголовки": "Montserrat", "текст": "Open Sans"},
            "активы": {"логотип_на_тёмном": "", "логотип_на_светлом": "", "фото_автора": ""},
            "подпись_в_подвале": "",
        }
        данные.update(поля)
        (папка / "profile.json").write_text(
            json.dumps(данные, ensure_ascii=False, indent=2), encoding="utf-8",
        )
        return папка

    def test_взять_копирует_добавляет_сайт_не_трогая_старые_поля(self):
        сосед = self._фейковый_сосед()

        успех, сообщение = профиль.взять_профиль(
            сосед, папка_профилей=self.профили, шаблон=self.шаблон,
        )

        self.assertTrue(успех, сообщение)
        файл = self.профили / "клиент-1" / "profile.json"
        self.assertTrue(файл.exists())
        данные = json.loads(файл.read_text(encoding="utf-8"))

        # старые поля источника не тронуты
        self.assertEqual(данные["автор"]["имя"], "Иван Иванов")
        self.assertEqual(данные["палитра"]["акцент"], "оставить-как-было")

        # секция «сайт» и служебные ключи добавлены из шаблона
        self.assertIn("сайт", данные)
        self.assertEqual(данные["сайт"]["тип"], "")
        self.assertIn("_как_заполнять_сайт", данные)
        self.assertEqual(данные["унаследован_из"], str(сосед.resolve()))

        # профиль стал активным
        self.assertEqual(
            профиль.прочитать_активного(папка_профилей=self.профили), "клиент-1",
        )

    def test_взять_копирует_активы(self):
        сосед = self._фейковый_сосед()
        (сосед / "активы").mkdir()
        (сосед / "активы" / "лого.png").write_bytes(b"PNG")

        профиль.взять_профиль(сосед, папка_профилей=self.профили, шаблон=self.шаблон)

        self.assertTrue((self.профили / "клиент-1" / "активы" / "лого.png").exists())

    def test_взять_не_перезаписывает_существующий(self):
        сосед = self._фейковый_сосед()
        профиль.взять_профиль(сосед, папка_профилей=self.профили, шаблон=self.шаблон)

        успех, сообщение = профиль.взять_профиль(
            сосед, папка_профилей=self.профили, шаблон=self.шаблон,
        )

        self.assertFalse(успех)
        self.assertIn("уже есть", сообщение)

    def test_взять_с_флагом_как(self):
        сосед = self._фейковый_сосед()

        успех, _ = профиль.взять_профиль(
            сосед, имя="моё-дело", папка_профилей=self.профили, шаблон=self.шаблон,
        )

        self.assertTrue(успех)
        self.assertTrue((self.профили / "моё-дело" / "profile.json").exists())


class ВалидацияТесты(unittest.TestCase):
    def test_валидный_шаблон_без_ошибок(self):
        данные = _фейковый_профиль()
        ошибки, предупреждения = профиль.валидировать(данные)
        self.assertEqual(ошибки, [])
        # шаблон пуст: пустые автор.имя, сайт.тип и связь.адрес — честные предупреждения
        self.assertTrue(предупреждения)

    def test_ловит_плохой_hex(self):
        данные = _фейковый_профиль(**{"палитра.акцент": "2C4A63"})
        ошибки, _ = профиль.валидировать(данные)
        self.assertTrue(
            any("акцент" in о and "#RRGGBB" in о for о in ошибки),
            ошибки,
        )

    def test_ловит_неверный_тип_сайта(self):
        данные = _фейковый_профиль(**{"сайт.тип": "квиз"})
        ошибки, _ = профиль.валидировать(данные)
        self.assertTrue(any("сайт.тип" in о for о in ошибки), ошибки)

    def test_ловит_неверный_способ_связи(self):
        данные = _фейковый_профиль()
        данные["сайт"]["связь"]["способ"] = "почта"
        ошибки, _ = профиль.валидировать(данные)
        self.assertTrue(any("связь.способ" in о for о in ошибки), ошибки)

    def test_ловит_неверный_статус_юрлица(self):
        данные = _фейковый_профиль()
        данные["сайт"]["юр_блок"]["статус"] = "ООО"
        ошибки, _ = профиль.валидировать(данные)
        self.assertTrue(any("юр_блок.статус" in о for о in ошибки), ошибки)

    def test_недостающий_ключ_это_ошибка(self):
        данные = _фейковый_профиль()
        del данные["палитра"]
        ошибки, _ = профиль.валидировать(данные)
        self.assertTrue(any("палитра" in о for о in ошибки), ошибки)


class СоседиТесты(unittest.TestCase):
    def setUp(self):
        self._временная = tempfile.TemporaryDirectory()
        self.addCleanup(self._временная.cleanup)
        self.контейнер = Path(self._временная.name)
        self.корень = self.контейнер / "site-builder"
        self.корень.mkdir()

    def _положить_профиль(self, куда: Path, имя: str, **поля):
        папка = куда / "профили" / имя
        папка.mkdir(parents=True)
        данные = {"профиль": имя, "автор": {"имя": "Тестовый Автор", "роль": "Тестовая роль"}}
        данные.update(поля)
        (папка / "profile.json").write_text(
            json.dumps(данные, ensure_ascii=False), encoding="utf-8",
        )

    def test_находит_соседа_рядом(self):
        сосед = self.контейнер / "docs-builder"
        self._положить_профиль(сосед, "моё-дело")

        находки = профиль.найти_соседей(корень=self.корень)

        self.assertEqual(len(находки), 1)
        self.assertEqual(находки[0]["имя"], "моё-дело")
        self.assertEqual(находки[0]["путь"], сосед / "профили" / "моё-дело")
        self.assertEqual(находки[0]["автор_имя"], "Тестовый Автор")

    def test_находит_соседа_во_вложенной_папке(self):
        сосед = self.контейнер / "инструменты" / "docs-builder"
        self._положить_профиль(сосед, "клиент-х")

        находки = профиль.найти_соседей(корень=self.корень)

        self.assertEqual(len(находки), 1)
        self.assertEqual(находки[0]["имя"], "клиент-х")

    def test_не_находит_себя(self):
        self._положить_профиль(self.корень, "проба")
        находки = профиль.найти_соседей(корень=self.корень)
        self.assertEqual(находки, [])

    def test_не_находит_шаблон(self):
        сосед = self.контейнер / "docs-builder"
        (сосед / "профили" / "_шаблон").mkdir(parents=True)
        (сосед / "профили" / "_шаблон" / "profile.json").write_text("{}", encoding="utf-8")

        находки = профиль.найти_соседей(корень=self.корень)

        self.assertEqual(находки, [])

    def test_ничего_нет_рядом(self):
        находки = профиль.найти_соседей(корень=self.корень)
        self.assertEqual(находки, [])


class СделатьАктивнымТесты(ФейковыйКореньТесты):
    def test_переключает_на_существующий(self):
        профиль.новый_профиль("проба", папка_профилей=self.профили, шаблон=self.шаблон)
        профиль.новый_профиль("другой", папка_профилей=self.профили, шаблон=self.шаблон)

        успех, сообщение = профиль.сделать_активным("проба", папка_профилей=self.профили)

        self.assertTrue(успех, сообщение)
        self.assertEqual(
            профиль.прочитать_активного(папка_профилей=self.профили), "проба",
        )

    def test_несуществующий_профиль_не_переключает(self):
        успех, сообщение = профиль.сделать_активным("нет-такого", папка_профилей=self.профили)
        self.assertFalse(успех)
        self.assertIn("нет-такого", сообщение)

    def test_указатель_на_удалённую_папку_не_ломает_работу(self):
        """Профиль переименовали или удалили руками — считаем, что активного нет, и говорим об этом."""
        профиль.новый_профиль("проба", папка_профилей=self.профили, шаблон=self.шаблон)
        shutil.rmtree(self.профили / "проба")

        со_словами = io.StringIO()
        with contextlib.redirect_stdout(со_словами):
            активный = профиль.прочитать_активного(папка_профилей=self.профили)

        self.assertIsNone(активный)
        self.assertIn("проба", со_словами.getvalue())
        self.assertIn("его папки больше нет", со_словами.getvalue())
        self.assertTrue((self.профили / "_активный").exists(), "указатель не трогаем")


if __name__ == "__main__":
    unittest.main()
