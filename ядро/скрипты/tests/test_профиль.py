    def test_роли_считаются_смесью_двух_цветов_профиля(self):
        """Не «примерно темнее», а ровно смесь в srgb — те же числа, что у `color-mix` в стилях."""
        полная = профиль.добрать_палитру(ПАЛИТРА_ОБРАЗЦА)["полная"]
