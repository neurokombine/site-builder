    def test_акцент_уже_тёплый_тёплый_не_выводится_а_спрашивается(self):
        # акцент сам стоит в тёплом секторе — выводить «свой же» тёплый бессмысленно,
        # это решает вкус, а не формула (задача 11, «выбор неоднозначен»)
        середина_сектора = sum(профиль.ТЁПЛЫЙ_СЕКТОР) / 2 / 360
        золотистый_акцент = профиль._из_hls(середина_сектора, 0.35, 0.5)
        рез = профиль.добрать_палитру({"акцент": золотистый_акцент})
        спросить_ключи = {с["ключ"] for с in рез["нужно_спросить"]}
        self.assertIn("тёплый", спросить_ключи)
        self.assertNotIn("тёплый", {в["ключ"] for в in рез["выведено"]})
        # И буквально золото школы (36°) — тот же случай: сектор его накрывает.
        школьное = профиль.добрать_палитру({"акцент": профиль._из_hls(36 / 360, 0.35, 0.5)})
        self.assertIn("тёплый", {с["ключ"] for с in школьное["нужно_спросить"]})

