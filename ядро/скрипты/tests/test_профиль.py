    def test_тёплый_выводится_из_оттенка_акцента_а_не_из_золота_школы(self):
        """Решение владелицы 14.09.2026 (№ 9): тёплый — из акцента профиля, не из зашитого 36°.

        Оттенок 36° — золото ОДНОЙ палитры; в чужой оно читается как чужой бренд: у зелёного
        электрика галки и опоры регалий выходили золотыми. Теперь оттенок акцента поворачивается
        к ближней кромке тёплого сектора — зелёное дело получает оливково-золотой, красное янтарный."""
        зелёный = профиль.добрать_палитру({"акцент": "#2C7A5B"})
        [запись] = [в for в in зелёный["выведено"] if в["ключ"] == "тёплый"]
        self.assertEqual(запись["из"], "акцент")
        h, l, _ = профиль._hls(зелёный["полная"]["тёплый"])
        self.assertAlmostEqual(l, профиль.ТЁПЛЫЙ_СВЕТЛОТА, delta=0.01)
        self.assertFalse(30 <= h * 360 <= 45,
                         f"на зелёном акценте тёплый снова сел в золото школы: {h * 360:.1f}°")
        низ, верх = профиль.ТЁПЛЫЙ_СЕКТОР
        self.assertTrue(низ <= h * 360 <= верх, f"тёплый вышел из тёплого сектора: {h * 360:.1f}°")
        # Красное дело подходит к сектору с другой стороны — и кромка у него другая.
        красный = профиль.добрать_палитру({"акцент": "#6B1520"})
        h_к, _, _ = профиль._hls(красный["полная"]["тёплый"])
        self.assertNotAlmostEqual(h_к * 360, h * 360, delta=1,
                                  msg="у красного и зелёного акцента тёплый вышел одинаковым — оттенок снова зашит")

