class ОдинВердиктОНеполномПрофиле(unittest.TestCase):
    """Задача 4 отчуждаемости: неполный профиль останавливает в начале пути, а не в конце.

    До этого 🔴 «Профиль не укомплектован» говорил только `проверить.py` — последний шаг, когда
    сайт уже собран и показан. Четыре шага между профилем и проверкой (`проверить_прототип.py`,
    `витрина.py`, `обложки.py`, `собрать.py`) молчали, и человек подставлял цвет наугад. Теперь
    вердикт один на всю систему, живёт в `профиль.находки_по_комплекту`, и его говорят все
    четверо — тем же текстом.

    ⛔ Ни один тест здесь не открывает браузер: работа нарочно собрана недоделанной (нет
    `дизайн.md`, нет экранов), поэтому витрина и обложки упираются в своё же 🔴 и выходят до
    съёмки — а нам важно только, названа ли к этому моменту неполнота профиля.
    """

    # Бедная палитра — ровно та, что лежит в тестовом профиле «электрик»: тёмного фона нет, и
    # вывести его не из чего. Полная — настоящий шаблон системы.
    БЕДНАЯ = {"акцент": "#2C7A5B", "текст": "#20241F", "светлый_фон_1": "#FAF7F2"}

    def setUp(self):
        self._в = tempfile.TemporaryDirectory()
        self.addCleanup(self._в.cleanup)
        self.д = Path(self._в.name)
        self.профили = self.д / "профили"
        self.профили.mkdir()
        self.работа = self.д / "сайты" / "моё-дело"
        self.работа.mkdir(parents=True)

    def _профиль(self, имя: str, палитра: dict) -> None:
        папка = self.профили / имя
        папка.mkdir()
        (папка / "profile.json").write_text(
            json.dumps({"палитра": палитра}, ensure_ascii=False), encoding="utf-8")

    def _прототип(self, имя_профиля: str) -> Path:
        исходный = (СКРИПТЫ / "tests" / "фикстуры" / "прототип-чистый.md").read_text(encoding="utf-8")
        текст = исходный.replace("- Профиль: логопед-тест", f"- Профиль: {имя_профиля}")
        файл = self.работа / "прототип.md"
        файл.write_text(текст, encoding="utf-8")
        return файл

    def _находки_четырёх(self, имя_профиля: str) -> dict[str, list[dict]]:
        """Находки всех четырёх скриптов на одной и той же работе — по имени скрипта."""
        import витрина, обложки, проверить_прототип, собрать   # noqa: E401

        файл = self._прототип(имя_профиля)
        итог: dict[str, list[dict]] = {}
        with patch.object(профиль, "ПРОФИЛИ", self.профили):
            поток = io.StringIO()
            аргв = ["проверить_прототип.py", str(файл), "--профиль", имя_профиля]
            with contextlib.redirect_stdout(поток), patch.object(sys, "argv", аргв):
                код = проверить_прототип.main()
            итог["проверить_прототип"] = список_находок_из(поток.getvalue())
            итог["проверить_прототип_код"] = код
            _, итог["витрина"] = витрина.витрина(self.работа)
            _, итог["обложки"] = обложки.обложки(self.работа, снимки=False)
            _, итог["собрать"] = собрать.собрать(self.работа)
        return итог

    def test_бедный_профиль_останавливает_все_четыре_одним_текстом(self):
        self._профиль("бедный", self.БЕДНАЯ)
        итог = self._находки_четырёх("бедный")

        self.assertEqual(итог["проверить_прототип_код"], 1,
                         "проверить_прототип на неполном профиле обязан выйти кодом 🔴")
        self.assertIn(профиль.СЛОВА_НЕУКОМПЛЕКТОВАН, итог["проверить_прототип"])
        for имя in ("витрина", "обложки", "собрать"):
            свои = [н for н in итог[имя] if н["что"] == профиль.СЛОВА_НЕУКОМПЛЕКТОВАН]
            self.assertEqual(len(свои), 1, f"{имя}: вердикта о неполном профиле нет или он задвоен")
            н = свои[0]
            with self.subTest(скрипт=имя):
                self.assertEqual(н["уровень"], профиль.ЧИНИТЬ)
                self.assertIn("бедный", н["чем_грозит"])
                self.assertTrue(any("тёмный_фон_1" in с for с in н["строки"]), н["строки"])

    def test_текст_вердикта_у_всех_дословно_один(self):
        self._профиль("бедный", self.БЕДНАЯ)
        итог = self._находки_четырёх("бедный")
        свои = [[н for н in итог[имя] if н["что"] == профиль.СЛОВА_НЕУКОМПЛЕКТОВАН][0]
                for имя in ("витрина", "обложки", "собрать")]
        эталон = профиль.находки_по_комплекту({"палитра": self.БЕДНАЯ}, "бедный")[0]
        for н in свои:
            self.assertEqual(н, эталон)

    def test_полный_профиль_молчат_все_четыре(self):
        полная = json.loads(РЕАЛЬНЫЙ_ШАБЛОН.read_text(encoding="utf-8"))["палитра"]
        self._профиль("полный", полная)
        итог = self._находки_четырёх("полный")
        self.assertNotIn(профиль.СЛОВА_НЕУКОМПЛЕКТОВАН, итог["проверить_прототип"])
        for имя in ("витрина", "обложки", "собрать"):
            self.assertEqual([н for н in итог[имя] if н["что"] == профиль.СЛОВА_НЕУКОМПЛЕКТОВАН], [],
                             f"{имя} остановил на укомплектованном профиле")

    def test_недостающее_выводится_само_и_никто_не_останавливает(self):
        """Четыре опоры есть — остальные восемь система считает сама; останавливать не за что."""
        четыре_опоры = dict(self.БЕДНАЯ, **{"тёмный_фон_1": "#181C20"})
        self.assertTrue(профиль.добрать_палитру(четыре_опоры)["выведено"],
                        "фикстура выбрана неверно: системе тут нечего выводить")
        self._профиль("четыре-опоры", четыре_опоры)
        итог = self._находки_четырёх("четыре-опоры")
        self.assertNotIn(профиль.СЛОВА_НЕУКОМПЛЕКТОВАН, итог["проверить_прототип"])
        for имя in ("витрина", "обложки", "собрать"):
            self.assertEqual([н for н in итог[имя] if н["что"] == профиль.СЛОВА_НЕУКОМПЛЕКТОВАН], [],
                             f"{имя} остановил там, где цвет выводится сам")


def список_находок_из(вывод: str) -> list[str]:
    """Заголовки находок из отчёта `проверить_прототип.py` — он печатает их строками «- что»."""
    return [строка[2:].strip() for строка in вывод.splitlines() if строка.startswith("- ")]


