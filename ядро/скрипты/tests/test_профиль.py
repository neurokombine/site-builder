class АктивыТесты(unittest.TestCase):
    """Задача 11, пункт «шире цвета»: пустое фото/логотип — предложить, не смолчать."""

    def test_пустые_активы_предупреждают(self):
        данные = _фейковый_профиль()
        _, предупреждения = профиль.валидировать(данные)
        self.assertTrue(any("активы.фото_автора" in п for п in предупреждения), предупреждения)
        self.assertTrue(any("активы.логотип_на_светлом" in п for п in предупреждения), предупреждения)
        self.assertTrue(any("активы.логотип_на_тёмном" in п for п in предупреждения), предупреждения)

    def test_заполненные_активы_не_предупреждают_о_пустоте(self):
        данные = _фейковый_профиль(**{"активы.фото_автора": "активы/я.jpg"})
        _, предупреждения = профиль.валидировать(данные)
        self.assertFalse(any("активы.фото_автора не заполнено" in п for п in предупреждения))

    def test_путь_на_несуществующий_файл_предупреждает(self):
        with tempfile.TemporaryDirectory() as д:
            путь = Path(д) / "profile.json"
            данные = _фейковый_профиль(**{"активы.фото_автора": "активы/я.jpg"})
            путь.write_text(json.dumps(данные, ensure_ascii=False), encoding="utf-8")
            _, предупреждения = профиль.проверить_файл(путь)
            self.assertTrue(any("активы/я.jpg" in п and "нет на диске" in п for п in предупреждения),
                             предупреждения)
            (Path(д) / "активы").mkdir()
            (Path(д) / "активы" / "я.jpg").write_bytes(b"jpg")
            _, предупреждения = профиль.проверить_файл(путь)
            self.assertFalse(any("нет на диске" in п for п in предупреждения), предупреждения)


