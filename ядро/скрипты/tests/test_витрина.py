"""Витрина: первый экран из прототипа в каждом варианте дизайн-системы — три композиции, в двух видах."""
import re, subprocess, sys, tempfile, unittest, shutil
from pathlib import Path
СКРИПТЫ = Path(__file__).resolve().parent.parent
ФИКСТУРЫ = Path(__file__).resolve().parent / "фикстуры"
sys.path.insert(0, str(СКРИПТЫ))
import витрина, глаза, находки, собрать  # noqa: E402


def _скопировать_образец(д: Path) -> Path:
    """Копия работа-образец в д/работа и профиль-образец рядом — как selftest._прогнать_сборку:
    так слот связи получает настоящую кнопку, а не запасную с 🟡."""
    shutil.copytree(ФИКСТУРЫ / "работа-образец", д / "работа")
    shutil.copytree(ФИКСТУРЫ / "профиль-образец", д / "профиль-образец")
    return д / "работа"


class ВитринаТесты(unittest.TestCase):
    def test_варианты_и_перекраска(self):
        д = собрать.прочитать_дизайн(ФИКСТУРЫ / "работа-образец" / "дизайн.md")
        в = витрина.варианты_из(д)
        self.assertEqual(len(в), 2)
        html = "<html><head><style>\n:root{--а:1}\n</style></head><body></body></html>"
        self.assertIn("--цвет-акцент", витрина.перекрасить(html, в[1]["css"]))
        self.assertNotIn("--а:1", витрина.перекрасить(html, в[1]["css"]))

    def test_1_витрина_двух_вариантов(self):
        with tempfile.TemporaryDirectory() as д:
            shutil.copytree(ФИКСТУРЫ / "работа-образец", Path(д) / "работа")
            путь, н = витрина.витрина(Path(д) / "работа")
            self.assertNotIn(находки.ЧИНИТЬ, [x["уровень"] for x in н], н)
            for n in (1, 2):
                папка = Path(д) / "работа" / "витрина" / f"вариант-{n}"
                self.assertTrue((папка / "index.html").exists())
                self.assertTrue((папка / "компьютер.png").exists())
                self.assertTrue((папка / "телефон.png").exists())
            текст = путь.read_text(encoding="utf-8")
            self.assertIn("Вариант 1", текст)
            self.assertIn("Вариант 2", текст)
            self.assertIn("тот же прототип стал другой страницей", текст)

    def test_2_один_вариант_красный(self):
        with tempfile.TemporaryDirectory() as д:
            shutil.copytree(ФИКСТУРЫ / "работа-образец", Path(д) / "работа")
            дизайн = Path(д) / "работа" / "дизайн.md"
            текст = дизайн.read_text(encoding="utf-8")
            дизайн.write_text(текст[:текст.index("## Вариант 2")] + текст[текст.index("## Решения"):], encoding="utf-8")
            р = subprocess.run([sys.executable, str(СКРИПТЫ / "витрина.py"), str(Path(д) / "работа"), "--без-показа"],
                               capture_output=True, text=True, timeout=120)
            self.assertEqual(р.returncode, 1, р.stdout)
            self.assertIn("две-три на выбор", р.stdout)


class ЧемОтличаетсяТесты(unittest.TestCase):
    """Строка «Чем отличается» доезжает из дизайн.md до витрины: без неё человек сравнивает вслепую."""

    def test_строка_из_дизайна_попадает_на_витрину(self):
        д = собрать.прочитать_дизайн(ФИКСТУРЫ / "работа-образец" / "дизайн.md")
        self.assertEqual(д["варианты"][0]["чем_отличается"],
                         "белый лист и один синий акцент — как чистая страница в тетради")
        текст = витрина._страница_витрины("проба", витрина.варианты_из(д))
        self.assertIn("Чем отличается: белый лист и один синий акцент", текст)
        self.assertIn("Композиция: сцена · тёмная · пятна · иконки плотные", текст)
        self.assertIn("вариант-2/телефон.png", текст)
        self.assertIn("Снято", текст)

    def test_композиция_словами_при_пустых_полях(self):
        # ревью, minor 5: показываем то, что реально взято, а не сырые поля
        пустой = {"номер": 1, "имя": "", "css": "x", "чем_отличается": "", "схема": "коллаж"}
        self.assertIn("Композиция: разворот (взят по умолчанию) · как в рецепте · как в рецепте · иконки обычные",
                      витрина._страница_витрины("проба", [пустой]))
        # схема не из набора пресета подписывается тем, что реально показано (ревью T2, quality 2)
        мозаика = {**пустой, "схема": "мозаика-роликов"}
        self.assertIn("Композиция: разворот (взят по умолчанию)", витрина._страница_витрины("проба", [мозаика], "визитка"))
        self.assertIn("Композиция: мозаика-роликов", витрина._страница_витрины("проба", [мозаика], "лендинг"))


class ТекстыПрототипаТесты(unittest.TestCase):
    """Чистый разбор прототипа и заполнение рецепта — без браузера."""

    def test_тексты_первого_экрана_из_прототипа(self):
        т = витрина.тексты_первого_экрана(ФИКСТУРЫ / "работа-образец")
        self.assertEqual((т["пресет"], т["заголовок"], т["акцент"]), ("визитка", "Математика без паники за три", "месяца"))
        self.assertEqual((len(т["пункты"]), т["кнопка"], т["фото"]), (3, "Написать про занятия", "пример.svg"))
        self.assertEqual(т["цифры"], [("6", "лет занятий"), ("40", "учеников закончили год без троек")])
        self.assertEqual(т["кикер"], "родитель восьмиклассника")   # до первой запятой, а не первые шесть слов

    def test_русские_числа_в_доказательстве(self):
        # ревью, important 1: «5 000» и «4,9» — одно число, запятая внутри числа пункт не делит
        with tempfile.TemporaryDirectory() as д:
            работа = _скопировать_образец(Path(д))
            прототип = работа / "прототип.md"
            прототип.write_text(прототип.read_text(encoding="utf-8").replace(
                "6 лет занятий, 40 учеников закончили год без троек",
                "5 000 учеников, 4,9 балла в отзывах · 12 лет"), encoding="utf-8")
            т = витрина.тексты_первого_экрана(работа)
            self.assertEqual(т["цифры"], [("5 000", "учеников"), ("4,9", "балла в отзывах"), ("12", "лет")])

    def test_заполнение_рецепта(self):
        т = витрина.тексты_первого_экрана(ФИКСТУРЫ / "работа-образец")
        разворот = (собрать.БЛОКИ / "визитка" / "01-первый-экран-разворот.html").read_text(encoding="utf-8")
        html = витрина.заполнить_первый_экран(разворот, т, None, None)
        self.assertIn('<ul class="цифры">', html)                       # две цифры — список остаётся…
        self.assertEqual(html.count('<li class="цифра">'), 2)           # …без третьего <li>
        self.assertIn('<b class="цифра__значение">6</b><span class="цифра__подпись">лет занятий</span>', html)
        self.assertNotIn("{{", html.replace("{{ИКОНКА:", ""))            # иконки подставляет страница_варианта
        одна = витрина.заполнить_первый_экран(разворот, {**т, "цифры": т["цифры"][:1]}, None, None)
        self.assertNotIn('<ul class="цифры">', одна)                     # одна цифра — списка нет
        одно_слово = витрина.заполнить_первый_экран(разворот, {**т, "заголовок": "Математика", "акцент": ""}, None, None)
        self.assertIn("<h1>Математика</h1>", одно_слово)                # ревью, minor 6: пустого <em> нет
        self.assertNotIn('<em class="акцент">', одно_слово)
        орбита = (собрать.БЛОКИ / "визитка" / "01-первый-экран-орбита.html").read_text(encoding="utf-8")
        спутники = витрина.заполнить_первый_экран(орбита, т, None, None)
        # R24/F2: спутник — только короткое доказательство: цифры прототипа, потом строка доверия; без доказательства спутник убирается
        self.assertIn("<b>6</b><span>лет занятий</span>", спутники)
        self.assertIn("<b>40</b><span>учеников закончили год без троек</span>", спутники)
        self.assertIn(f"<b>{витрина.ДОВЕРИЕ_ПО_УМОЛЧАНИЮ}</b></div>", спутники)
        self.assertEqual(спутники.count("орбита__спутник"), 3)
        self.assertNotIn("<span></span>", спутники)
        пусто = витрина.заполнить_первый_экран(орбита, {**т, "цифры": [], "пункты": []}, None, None)
        self.assertEqual(пусто.count(f"<b>{витрина.ДОВЕРИЕ_ПО_УМОЛЧАНИЮ}</b>"), 1)   # одно доказательство — один спутник
        self.assertEqual(пусто.count("орбита__спутник"), 1)

    def test_пункт_списка_не_попадает_в_спутник_и_бейдж(self):
        """Ревью T6: длинный пункт списка никогда не становится подписью спутника или бейджа — туда идут цифры и строка доверия."""
        т = витрина.тексты_первого_экрана(ФИКСТУРЫ / "работа-образец")
        длинный = "Не «оживление картинок» — полный цикл видеопроизводства: сценарий → кадр → герой → анимация → озвучка → монтаж → деньги"
        своё = {**т, "цифры": т["цифры"][:1], "пункты": [длинный, "второй пункт", "третий пункт"]}
        for набор, файл in (("визитка", "орбита"), ("лендинг", "живой-портрет"), ("лендинг", "товар-крупно")):
            html = витрина.заполнить_первый_экран((собрать.БЛОКИ / набор / f"01-первый-экран-{файл}.html").read_text(encoding="utf-8"), своё, None, None)
            артефакты = re.findall(r'class="(?:орбита__спутник|бейдж картинка__бейдж)[^"]*">(.*?)</(?:div|span)>', html)
            self.assertEqual(len(артефакты), 2, html)                                     # одна цифра + доверие; остальные убраны
            for а in артефакты:
                self.assertNotIn(длинный, а)
                self.assertNotIn("пункт", а)
            self.assertTrue(any("6" in а and "лет занятий" in а for а in артефакты), артефакты)

    def test_картинки_и_заглушка(self):
        with tempfile.TemporaryDirectory() as д:
            работа = _скопировать_образец(Path(д))
            к = витрина._картинки(работа)
            self.assertEqual((к["фото"], к["видео"], к["постер"]), ("пример.svg", "пример", "пример-poster.jpg"))
            (работа / "img" / "пример-telefon.webp").write_bytes(b"")
            self.assertEqual(витрина._картинки(работа)["фото_телефон"], "пример-telefon.webp")
            (работа / "video" / "a-poster.jpg").write_bytes(b"")   # чужой постер первым по алфавиту — постер берётся у своего ролика
            self.assertEqual(витрина._картинки(работа)["постер"], "пример-poster.jpg")
            shutil.rmtree(работа / "img"); shutil.rmtree(работа / "video")
            т = витрина.тексты_первого_экрана(работа)
            self.assertEqual((т["фото"], т["фото_телефон"], т["видео"], т["постер"]), ("", "", "", ""))
            разворот = (собрать.БЛОКИ / "визитка" / "01-первый-экран-разворот.html").read_text(encoding="utf-8")
            html = витрина.заполнить_первый_экран(разворот, т, None, None)
            self.assertIn('src="img/силуэт.svg"', html)                   # без картинки — силуэт, фигура не вырезается
            self.assertIn('data-лицо="50,22"', html)

    def test_страница_варианта_с_видео_несёт_скрипты_обложки(self):
        # ревью T4: «открыть живьём» из витрины — с обложка.js (телефонный ролик, reduced-motion) и звук.js
        with tempfile.TemporaryDirectory() as д:
            работа = _скопировать_образец(Path(д))
            т, поиск = витрина.тексты_первого_экрана(работа), собрать.прочитать_поиск(работа / "поиск.md")
            css = собрать.прочитать_дизайн(работа / "дизайн.md")["варианты"][0]["css"]
            живая = витрина.страница_варианта(работа, {"номер": 3, "css": css, "схема": "живая-сцена"}, т, поиск)
            self.assertIn("картинка--постер", живая.split("<script>")[1])   # тот же признак обложка.js, что в test_собрать
            self.assertIn("visibilitychange", живая)                          # звук.js — кнопка звука есть
            self.assertEqual(живая.count("<script>"), 2)
            self.assertNotIn("<script>", витрина.страница_варианта(работа, {"номер": 1, "css": css, "схема": "разворот"}, т, поиск))


