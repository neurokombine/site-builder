class ТекстыПрототипаТесты(unittest.TestCase):
    """Чистый разбор прототипа и заполнение рецепта — без браузера."""

    def test_тексты_первого_экрана_из_прототипа(self):
        т = витрина.тексты_первого_экрана(ФИКСТУРЫ / "работа-образец")
        self.assertEqual((т["пресет"], т["заголовок"], т["акцент"]), ("визитка", "Математика без паники за три", "месяца"))
        self.assertEqual((len(т["пункты"]), т["кнопка"], т["фото"]), (3, "Написать про занятия", "пример.svg"))
        self.assertEqual(т["цифры"], [("6", "лет занятий"), ("40", "учеников закончили год без троек")])
        self.assertEqual(т["кикер"], "родитель восьмиклассника")   # до первой запятой, а не первые шесть слов

    def test_русские_числа_в_доказательстве(self):
        # ревью, important 1: «5 000» и «4,9» — одно число, запятая внутри числа пункт не делит
        with tempfile.TemporaryDirectory() as д:
            работа = _скопировать_образец(Path(д))
            прототип = работа / "прототип.md"
            прототип.write_text(прототип.read_text(encoding="utf-8").replace(
                "6 лет занятий, 40 учеников закончили год без троек",
                "5 000 учеников, 4,9 балла в отзывах · 12 лет"), encoding="utf-8")
            т = витрина.тексты_первого_экрана(работа)
            self.assertEqual(т["цифры"], [("5 000", "учеников"), ("4,9", "балла в отзывах"), ("12", "лет")])

    def test_заполнение_рецепта(self):
        т = витрина.тексты_первого_экрана(ФИКСТУРЫ / "работа-образец")
        разворот = (собрать.БЛОКИ / "визитка" / "01-первый-экран-разворот.html").read_text(encoding="utf-8")
        html = витрина.заполнить_первый_экран(разворот, т, None, None)
        self.assertIn('<ul class="цифры">', html)                       # две цифры — список остаётся…
        self.assertEqual(html.count('<li class="цифра">'), 2)           # …без третьего <li>
        self.assertIn('<b class="цифра__значение">6</b><span class="цифра__подпись">лет занятий</span>', html)
        self.assertNotIn("{{", html.replace("{{ИКОНКА:", ""))            # иконки подставляет страница_варианта
        одна = витрина.заполнить_первый_экран(разворот, {**т, "цифры": т["цифры"][:1]}, None, None)
        self.assertNotIn('<ul class="цифры">', одна)                     # одна цифра — списка нет
        одно_слово = витрина.заполнить_первый_экран(разворот, {**т, "заголовок": "Математика", "акцент": ""}, None, None)
        self.assertIn("<h1>Математика</h1>", одно_слово)                # ревью, minor 6: пустого <em> нет
        self.assertNotIn('<em class="акцент">', одно_слово)
        орбита = (собрать.БЛОКИ / "визитка" / "01-первый-экран-орбита.html").read_text(encoding="utf-8")
        спутники = витрина.заполнить_первый_экран(орбита, т, None, None)
        # Ruling 18: сначала цифры прототипа, потом пункты целиком, фразу не режем
        self.assertIn("<b>6</b><span>лет занятий</span>", спутники)
        self.assertIn("<b>40</b><span>учеников закончили год без троек</span>", спутники)
        self.assertIn("<b>разбираем пробелы, а не гоняем по всему учебнику</b></div>", спутники)
        self.assertIn("<b>готовим к контрольным и экзаменам по школьной программе</b></div>", спутники)
        self.assertNotIn("<span></span>", спутники)
        пусто = витрина.заполнить_первый_экран(орбита, {**т, "цифры": [], "пункты": []}, None, None)
        self.assertEqual(пусто.count(f"<b>{витрина.ДОВЕРИЕ_ПО_УМОЛЧАНИЮ}</b>"), 5)   # центр + четыре добора


