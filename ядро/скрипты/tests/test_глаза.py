    def test_стена_html_через_лестницу_без_сети(self):
        """Реальная фикстура стены, браузер настоящий, архив и видимое окно — моки."""
        from playwright.sync_api import sync_playwright
        with sync_playwright() as дв, tempfile.TemporaryDirectory() as куда:
            бр = глаза.запустить_браузер(дв)
            try:
                замеры = глаза.посмотреть(
                    глаза.адрес_из(ФИКСТУРЫ / "стена.html"), куда, размеры=("компьютер",),
                    ждать_сек=0.1, браузер=бр, движок=дв, лестница=False)
                self.assertEqual(замеры["итог"]["не_пустило"]["вид"], "антибот_стена")
                лендинг = глаза.адрес_из(ФИКСТУРЫ / "лендинг.html")
                настоящий = глаза.снять_размер

                def подмена(браузер_, адрес, размер, папка, ждать, **кв):
                    # «копия архива» — это наш исправный лендинг
                    return настоящий(браузер_, лендинг, размер, папка, ждать)
                with unittest.mock.patch.object(глаза, "снять_размер", подмена), \
                        unittest.mock.patch.object(
                            глаза, "_запустить_видимый",
                            side_effect=RuntimeError("нет окна")):
                    глаза.подняться(
                        замеры, глаза.адрес_из(ФИКСТУРЫ / "стена.html"), куда,
                        ("компьютер",), 0.1, бр, дв,
                        получить=lambda url: ОТВЕТ_АРХИВА, сказать=lambda т: None)
            finally:
                бр.close()
        self.assertEqual(замеры["итог"]["статус"], "ок")
        self.assertEqual(замеры["итог"]["копия_архива"]["дата"], "12.05.2026")


