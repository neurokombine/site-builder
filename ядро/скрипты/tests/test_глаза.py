            скриншоты = self.референс["устройства"][размер]["скриншоты"]
            self.assertTrue(Path(скриншоты["экран"]).exists(), f"{размер}: первый экран")
            self.assertTrue(Path(скриншоты["вся_страница"]).exists(), f"{размер}: вся страница")

