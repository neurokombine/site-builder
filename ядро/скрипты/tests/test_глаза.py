class ЛестницаПриБлокировке(unittest.TestCase):
    """Лестница «окно → архив → человек» — без сети и без браузера: всё за моками."""

    def setUp(self):
        self.речь = []

    def _идти(self, итоги_снятия, получить=None, движок=object(), размер="компьютер",
              вид=None, окно=None, **доп):
        """Прогнать лестницу; снять_размер отвечает по очереди из `итоги_снятия`."""
        очередь = [и if isinstance(и, Exception) else dict(и) for и in итоги_снятия]
        вызовы = []

        def снять(браузер, адрес, размер_, папка, ждать, **кв):
            вызовы.append((адрес, кв))
            ответ = очередь.pop(0)
            if isinstance(ответ, Exception):
                raise ответ
            return ответ

        with unittest.mock.patch.object(глаза, "снять_размер", снять), \
                unittest.mock.patch.object(
                    глаза, "_запустить_видимый",
                    окно or (lambda дв: unittest.mock.Mock())):
            итог = глаза.подняться_для_размера(
                размер, dict(СТЕНА), "https://example.org/", Path("."), 0, "браузер", движок,
                получить=получить or (lambda url: ОТВЕТ_АРХИВА),
                сказать=self.речь.append, **доп)
        return итог, вызовы

    def test_порядок_ступеней(self):
        self.assertEqual(глаза.выбрать_ступени("таймаут"), ["повтор", "окно", "архив"])
        self.assertEqual(глаза.выбрать_ступени("антибот_стена"), ["окно", "архив"])
        self.assertEqual(глаза.выбрать_ступени("сертификат"), ["архив"])
        self.assertEqual(глаза.выбрать_ступени("ошибка"), [])
        self.assertEqual(глаза.выбрать_ступени("ошибка", другой_размер_ок=True), ["окно", "архив"])

    def test_сертификат_не_обходим_и_окна_нет(self):
        итог, вызовы = self._идти([ХОРОШИЙ], принудительно_вид="сертификат")
        self.assertEqual(итог["ступень"], "архив")
        self.assertTrue(all("web.archive.org" in а for а, _ in вызовы))
        self.assertFalse(any(к.get("доп_контекст") for _, к in вызовы))

    def test_окно_сработало_архив_не_трогаем(self):
        итог, вызовы = self._идти([ХОРОШИЙ])
