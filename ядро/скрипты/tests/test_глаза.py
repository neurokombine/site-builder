"""Тесты браузера-глаз: замеры по учебным страницам, лежащим рядом.

В интернет отсюда не ходим — живые сайты проверяются руками, не тестами. Браузер поднимается
один раз на класс: на каждый тест по разу — долго.

Запуск из корня репозитория:
    .venv/bin/python -m unittest discover -s ядро/скрипты/tests -t .
"""
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

СКРИПТЫ = Path(__file__).resolve().parent.parent
ФИКСТУРЫ = Path(__file__).resolve().parent / "фикстуры"
sys.path.insert(0, str(СКРИПТЫ))

import глаза  # noqa: E402

# Цвет кнопки на учебной странице — тот же, что в её стилях: rgb(200, 30, 40)
ЦВЕТ_КНОПКИ = "#{:02x}{:02x}{:02x}".format(200, 30, 40)


class ЗамерыТесты(unittest.TestCase):
    """Одна учебная страница, снятая обоими размерами, — и всё, что мы обещали померить."""

    @classmethod
    def setUpClass(cls):
        from playwright.sync_api import sync_playwright

        cls._playwright = sync_playwright().start()
        cls.браузер = глаза.запустить_браузер(cls._playwright)
        cls._временная = tempfile.TemporaryDirectory()
        куда = Path(cls._временная.name)
        cls.референс = глаза.посмотреть(
            глаза.адрес_из(ФИКСТУРЫ / "референс"), куда / "референс",
            ждать_сек=0.2, браузер=cls.браузер,
        )
        cls.стена = глаза.посмотреть(
            глаза.адрес_из(ФИКСТУРЫ / "стена.html"), куда / "стена",
            ждать_сек=0.2, браузер=cls.браузер,
        )
        cls.лендинг = глаза.посмотреть(
            глаза.адрес_из(ФИКСТУРЫ / "лендинг.html"), куда / "лендинг",
            ждать_сек=0.2, браузер=cls.браузер,
        )

    @classmethod
    def tearDownClass(cls):
        cls.браузер.close()
        cls._playwright.stop()
        cls._временная.cleanup()

    def test_оба_размера_открылись(self):
        for размер in ("компьютер", "телефон"):
            self.assertEqual(self.референс["устройства"][размер]["статус"], "ок", размер)
        self.assertEqual(self.референс["итог"]["статус"], "ок")
        self.assertIsNone(self.референс["итог"]["не_пустило"])

    def test_экраны_снялись(self):
        for размер in ("компьютер", "телефон"):
            скриншоты = self.референс["устройства"][размер]["скриншоты"]
            self.assertTrue(Path(скриншоты["экран"]).exists(), f"{размер}: первый экран")
            self.assertTrue(Path(скриншоты["вся_страница"]).exists(), f"{размер}: вся страница")

    def test_нашёлся_мелкий_текст(self):
        мелкий = self.референс["устройства"]["компьютер"]["мелкий_текст"]
        self.assertEqual(мелкий["минимум_px"], 12)
        self.assertEqual(мелкий["элементов_мельче_14"], 1)

    def test_картинка_вылезает_только_на_телефоне(self):
        self.assertTrue(self.референс["устройства"]["телефон"]["вылезающие_картинки"],
                        "на телефоне картинка шире экрана — должна попасть в список")
        self.assertEqual(self.референс["устройства"]["компьютер"]["вылезающие_картинки"], [],
                         "на компьютере та же картинка помещается")

    def test_палитра_помнит_цвет_кнопки(self):
        фоны = [ц["hex"] for ц in self.референс["устройства"]["компьютер"]["фон_по_разметке"]]
        self.assertIn(ЦВЕТ_КНОПКИ, фоны)
        self.assertTrue(all(0 < ц["доля"] <= 100
                            for ц in self.референс["устройства"]["компьютер"]["фон_по_разметке"]))

    def test_шрифт_заголовка_померен(self):
        устройство = self.референс["устройства"]["компьютер"]
        self.assertTrue(any("Georgia" in (ш["объявлен"] or "") for ш in устройство["шрифты"]))
        self.assertIsNotNone(устройство["шрифт_заголовков"])
        self.assertEqual(устройство["кегли"]["h1"]["px"], 48)

    def test_воздух_посчитан(self):
        воздух = self.референс["устройства"]["компьютер"]["воздух"]
        self.assertTrue(0 <= воздух["доля"] <= 100)
        self.assertTrue(воздух["фон_скриншота_hex"].startswith("#"))

    def test_стена_узнаётся(self):
        self.assertEqual(self.стена["итог"]["не_пустило"]["вид"], "антибот_стена")
        self.assertEqual(self.стена["итог"]["статус"], "не_пустило")
        self.assertTrue(self.стена["итог"]["не_пустило"]["подсказка"])
        self.assertEqual(
            self.стена["устройства"]["компьютер"]["не_пустило"]["вид"], "антибот_стена")

    def test_лендинг_с_капчей_в_форме_это_не_стена(self):
        """Капча в разметке формы заявки — примета обычного сайта, а не стены."""
        for размер in ("компьютер", "телефон"):
            устройство = self.лендинг["устройства"][размер]
            self.assertEqual(устройство["статус"], "ок", размер)
            self.assertIsNone(устройство["не_пустило"], размер)
        self.assertEqual(self.лендинг["итог"]["статус"], "ок")
        self.assertIsNone(self.лендинг["итог"]["не_пустило"])
        self.assertNotIn("Не пустило", глаза.сводка(self.лендинг))

    def test_коды_выхода_у_командной_строки(self):
        """Исправный сайт — 0, стена — 2. Один размер, чтобы не гонять браузер дважды."""
        скрипт = str(СКРИПТЫ / "посмотреть_сайт.py")
        with tempfile.TemporaryDirectory() as куда:
            for фикстура, ожидаемый in (("лендинг.html", 0), ("стена.html", 2)):
                готово = subprocess.run(
                    [sys.executable, скрипт, str(ФИКСТУРЫ / фикстура),
                     "--куда", str(Path(куда) / фикстура), "--только", "компьютер"],
                    capture_output=True, text=True,
                )
                self.assertEqual(готово.returncode, ожидаемый, f"{фикстура}: {готово.stdout[-400:]}")

    def test_сводка_говорит_чего_не_меряет(self):
        текст = глаза.сводка(self.референс)
        self.assertIn("Что не меряется", текст)
        self.assertIn("скриншот всегда рядом с цифрами", текст)
        self.assertIn("Воздух:", текст)
        self.assertIn("Адаптивность:", текст)

    def test_замеры_легли_рядом_с_экранами(self):
        папка = Path(self.референс["устройства"]["компьютер"]["скриншоты"]["экран"]).parent
        self.assertTrue((папка / "замеры.md").exists())
        self.assertTrue((папка / "замеры.json").exists())
        self.assertIn("Что не меряется", (папка / "замеры.md").read_text(encoding="utf-8"))


class АдресаТесты(unittest.TestCase):
    def test_папка_превращается_в_файл(self):
        адрес = глаза.адрес_из(ФИКСТУРЫ / "референс")
        self.assertTrue(адрес.startswith("file://"))
        self.assertTrue(адрес.endswith("index.html"))

    def test_папка_без_индекса_говорит_об_этом(self):
        with tempfile.TemporaryDirectory() as пустая:
            with self.assertRaises(ValueError):
                глаза.адрес_из(пустая)

    def test_голый_домен_получает_протокол(self):
        self.assertEqual(глаза.адрес_из("example.com"), "https://example.com")
        self.assertEqual(глаза.адрес_из(" https://example.com/цены "), "https://example.com/цены")

    def test_слаг_из_домена(self):
        self.assertEqual(глаза.слаг_из("https://www.example.com/цены"), "example-com")

    def test_слаг_из_локальной_папки_читаемый(self):
        # путь приходит процентно-закодированным — слаг всё равно должен быть узнаваемым
        self.assertEqual(глаза.слаг_из(глаза.адрес_из(ФИКСТУРЫ / "референс")), "референс")


class ИтогТесты(unittest.TestCase):
    """Классификация «не пустило» — без браузера, на готовых состояниях устройств."""

    ОБА = ("компьютер", "телефон")

    def test_только_компьютер(self):
        итог = глаза.подвести_итог({
            "компьютер": {"статус": "ок", "не_пустило": None},
            "телефон": {"статус": "ошибка",
                        "не_пустило": {"вид": "ошибка", "признак": "страница не отдалась"}},
        }, self.ОБА)
        self.assertEqual(итог["не_пустило"]["вид"], "только_компьютер")
        self.assertEqual(итог["не_пустило"]["где"], ["телефон"])
        self.assertEqual(итог["статус"], "ок", "компьютер померен — значит работа не встала")

    def test_сертификат_важнее_прочего(self):
        итог = глаза.подвести_итог({
            "компьютер": {"статус": "не_пустило",
                          "не_пустило": {"вид": "сертификат", "признак": "ERR_CERT_INVALID"}},
            "телефон": {"статус": "таймаут",
                        "не_пустило": {"вид": "таймаут", "признак": "не загрузилась"}},
        }, self.ОБА)
        self.assertEqual(итог["не_пустило"]["вид"], "сертификат")
        self.assertEqual(итог["статус"], "не_пустило")

    def test_маркеры_ищутся_в_видимом_тексте(self):
        """Разметка сюда не попадает: капча в форме заявки не должна становиться стеной."""
        не_стена = [
            ("Наше агентство делает сайты. Оставьте заявку", "Агентство"),
            ("Что-то не так, попробуйте позже", "Салон красоты"),
        ]
        for текст, заголовок in не_стена:
            self.assertIsNone(глаза.маркер_стены(текст, заголовок), текст)
        self.assertEqual(глаза.маркер_стены("Проверяем браузер", "Магазин"), "проверяем браузер")
        self.assertEqual(глаза.маркер_стены("", "Проверка браузера — captcha"), "captcha")

    def test_у_каждого_вида_есть_подсказка(self):
        for вид in ("антибот_стена", "только_компьютер", "сертификат", "таймаут", "ошибка"):
            self.assertTrue(глаза.подсказка_по_виду(вид), вид)
            self.assertIn(вид, глаза.НАЗВАНИЯ_ВИДОВ)


if __name__ == "__main__":
    unittest.main()
