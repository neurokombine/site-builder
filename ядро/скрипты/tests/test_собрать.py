        итог, найденное = собрать.раздать_светлоту(html, "светлый")
        self.assertEqual(self.классы(итог), [["блок", "блок--отзывы", "тёмный"],
                                             ["блок", "блок--финал", "светлый"]])
        self.assertEqual([н["что"] for н in найденное], ["Два акцентных экрана подряд"])
        # Вторая строка — НБ-1: сборка перевернула КЛЮЧ экрана (тёмный → светлый), и краски ядра
