        self.assertEqual(стр.count('class="стык'), 4)     # два стыка по две половинки; без светлоты — мимо
        первый, второй, третий = (стр.split(f'id="экран-{н}"')[1].split("</section>")[0] for н in ("1", "02", "03"))
        self.assertIn('стык--низ" aria-hidden="true" style="--стык-сосед: var(--цвет-фон)"', первый)
        self.assertIn("стык--верх", второй)
        self.assertIn("--стык-сосед: var(--цвет-тёмный-фон)", второй)
        self.assertIn("--стык-сосед: var(--цвет-фон-2", второй)          # светлый → светлый второй
