        """Копии экранов в работе человека сделаны до этой задачи и несут светлоту в себе.
        Переписывать их сборка права не имеет — но в ритме они участвуют наравне со всеми."""
        старый = '<section class="блок блок--боль светлый" id="экран-1" data-тип="боль"></section>'
