def _наложить(верх: str, низ: str, доля: float) -> str:
    """Цвет `верх` с прозрачностью `доля` поверх непрозрачного `низ` — то же, что делает
    `color-mix(in srgb, верх X%, transparent)` на фоне секции (карточка тарифа в тёмном ключе)."""
    канал = lambda ц, i: int(ц[1 + 2 * i:3 + 2 * i], 16)
    return "#" + "".join(f"{round(канал(верх, i) * доля + канал(низ, i) * (1 - доля)):02X}" for i in range(3))


