class КонтрастВОбоихКлючах(unittest.TestCase):
    """Слой ключа обязан держать пороги на КАЖДОЙ палитре, а где не держит — система должна
    сказать словами, а не отдать нечитаемую страницу молча."""

    def _ключи(self, добор: dict) -> dict[str, dict]:
        """Что слой ключа выдаст на этой палитре: фон, текст и золото каждого ключа.
        Соответствие «поле палитры → токен» — `ядро/дизайн/палитра-и-токены.md` § 1 и § 1-ter.

        Опоры ключа в палитре может и не быть (у электрика нарочно нет тёмного фона). Тогда ключ
        не собирается — и это не провал, а правило системы: мало дали — спросить, а не собирать
        молча. Такой ключ возвращается как `None`, и тест проверяет, что вопрос задан словами."""
        полная = добор["полная"]
        просят = {х["ключ"] for х in добор["нужно_спросить"]}
        светлый_фон = полная.get("светлый_фон_1")
        тёплый = полная.get("тёплый") or полная.get("акцент")
        тёмный = ({"фон": полная["тёмный_фон_1"], "текст": светлый_фон, "тёплый": тёплый}
                  if "тёмный_фон_1" in полная else None)
        светлый = ({"фон": светлый_фон, "текст": полная["текст"],
                    "тёплый": собрать.тёплый_тёмная_ступень(тёплый, светлый_фон,
                                                            полная.get("тёплый_тёмный"))}
                   if светлый_фон and полная.get("текст") else None)
        if тёмный is None:
            self.assertTrue({"тёмный_фон_1"} & просят, "тёмный ключ не собрать, а система не спросила")
        if светлый is None:
            self.assertTrue({"светлый_фон_1", "текст"} & просят,
                            "светлый ключ не собрать, а система не спросила")
        return {"тёмный": тёмный, "светлый": светлый}

    def test_текст_и_золото_держат_пороги_в_обоих_ключах(self):
        for имя, сырьё in _палитры_для_проверки().items():
            for ключ, слой in self._ключи(профиль_модуль.добрать_палитру(сырьё)).items():
                if слой is None:
                    continue   # ключ не собрать из этой палитры — система уже спросила, см. _ключи
                with self.subTest(палитра=имя, ключ=ключ):
                    self.assertGreaterEqual(round(собрать.контраст(слой["текст"], слой["фон"]), 2),
                                            собрать.ПОРОГ_ПОДПИСИ,
                                            f"{имя}/{ключ}: текст ключа не читается на его фоне")
                    self.assertGreaterEqual(round(собрать.контраст(слой["тёплый"], слой["фон"]), 2),
                                            собрать.ПОРОГ_КНОПКИ,
                                            f"{имя}/{ключ}: золото ключа не видно на его фоне")

    def test_кнопка_контрастна_в_обоих_ключах_или_система_говорит_словами(self):
        # Жёсткое правило владелицы: кнопка целевого действия контрастна всегда. Не дотянул
        # акцент — сборка сама берёт краску из палитры; не из чего взять — это находка
        # «Кнопку не из чего перекрасить», а не молчаливая невидимая кнопка.
        for имя, сырьё in _палитры_для_проверки().items():
            добор = профиль_модуль.добрать_палитру(сырьё)
            полная = добор["полная"]
            акцент, на_акценте = полная["акцент"], полная["светлый_фон_1"]
            for ключ, слой in self._ключи(добор).items():
                if слой is None:
                    continue
                with self.subTest(палитра=имя, ключ=ключ):
                    выбор = собрать.подобрать_кнопку(акцент, на_акценте, слой["фон"], полная)
                    if выбор is None:   # сам акцент дотянул
                        self.assertGreaterEqual(round(собрать.контраст(акцент, слой["фон"]), 2),
                                                собрать.ПОРОГ_КНОПКИ)
                        continue
                    if выбор.get("заливка"):
                        self.assertGreaterEqual(round(выбор["к_фону"], 2), собрать.ПОРОГ_КНОПКИ)
                        self.assertGreaterEqual(round(выбор["к_подписи"], 2), собрать.ПОРОГ_ПОДПИСИ)
                        continue
                    # Не из чего перекрасить — значит система обязана сказать это словами.
                    токены = (":root {\n  --цвет-акцент: %s;\n  --цвет-на-акценте: %s;\n"
                              "  --цвет-фон: %s;\n  --цвет-тёмный-фон: %s;\n}\n"
                              % (акцент, на_акценте, полная["светлый_фон_1"],
                                 полная.get("тёмный_фон_1", полная["светлый_фон_1"])))
                    _, найдено = собрать._цвет_кнопки(токены, {"палитра": полная})
                    self.assertTrue(any(н["уровень"] == находки.ПОПРАВИТЬ for н in найдено),
                                    f"{имя}/{ключ}: кнопку не из чего перекрасить, а система молчит")


ЛИЧНОЕ_В_КОММЕНТАРИЯХ = ("владелиц", "фикс-раунд", "фикс М ", "НейроВидео", "Натэла", "Зубченко")


def _правила_css(текст: str) -> int:
    """Сколько `{` в стилях НЕ считая комментариев и строк — свой разбор посимвольно, нарочно не
    тот, которым чистит сборка: если оба ошибутся одинаково, тест ничего не поймает."""
    счёт, i, n, кавычка = 0, 0, len(текст), None
    while i < n:
        с = текст[i]
        if кавычка:
            if с == "\\":
                i += 2
                continue
            if с == кавычка:
                кавычка = None
        elif с in "\"'":
            кавычка = с
        elif текст[i:i + 2] == "/*":
            конец = текст.find("*/", i + 2)
            i = n if конец < 0 else конец + 2
            continue
        elif с == "{":
            счёт += 1
        i += 1
    return счёт


