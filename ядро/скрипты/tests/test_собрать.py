    def test_сборка_образца_чистая(self):
        with tempfile.TemporaryDirectory() as д:
            путь, н = собрать.собрать(ФИКСТУРЫ / "работа-образец", куда=Path(д))
            html = путь.read_text(encoding="utf-8")
