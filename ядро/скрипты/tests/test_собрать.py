    def test_роль_встаёт_на_своё_место_в_строке_классов(self):
        """Порядок классов — часть контракта секции: атмосфера идёт последней и после светлоты."""
        html = self.секция("финал", собрать.АКЦЕНТ, ещё=" блок--громко") .replace(
            f'{собрать.АКЦЕНТ}"', f'{собрать.АКЦЕНТ} фон--пятна"')
        итог, _ = собрать.раздать_светлоту(html, "светлый")
