class ТриСтиля(Стенд):
    """Стили выводятся из решений и палитры, а не берутся списком «стилей вообще»."""

    def стили(self):
        return разговор.три_стиля(заказ.решения(self.папка), ПАЛИТРА,
                                  "столяр, мебель из массива на заказ")

    def test_их_ровно_три_и_они_разные(self):
        стили = self.стили()
        self.assertEqual(len(стили), 3)
        имена = [с["имя"] for с in стили]
        self.assertEqual(len(set(имена)), 3)
        for поле in ("описание", "свет", "почему"):
            значения = [str(с[поле]) for с in стили]
            self.assertEqual(len(set(значения)), 3, поле)

    def test_первый_идёт_от_выбранного_варианта(self):
        self.assertEqual(self.стили()[0]["имя"], "Светлая мастерская")

    def test_каждый_несёт_цвета_палитры(self):
        словами = заказ.цвет_словами(ПАЛИТРА["акцент"])
        for стиль in self.стили():
            self.assertTrue(стиль["цвета"].strip(), стиль["имя"])
        # цвет акцента назван словами хотя бы в двух из трёх, и ни в одном нет hex
        текст = " ".join(с["цвета"] for с in self.стили())
        self.assertIn(словами, текст)
        self.assertNotIn("#", текст)

    def test_на_чужой_палитре_выходят_другие_слова(self):
        чужая = {"светлый_фон_1": "#F2EFEA", "тёмный_фон_1": "#101418",
                 "акцент": "#7A4E2D", "тёплый": "#D9B382"}
        своё = [с["цвета"] for с in self.стили()]
        чужое = [с["цвета"] for с in разговор.три_стиля(заказ.решения(self.папка), чужая, "кофейня")]
        self.assertNotEqual(своё, чужое)

    def test_почему_подходит_говорит_про_это_дело(self):
        for стиль in self.стили():
            self.assertIn("столяр", стиль["почему"])


