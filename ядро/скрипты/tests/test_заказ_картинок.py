class Стенд(unittest.TestCase):
    """Пробный сайт: тексты стоят, картинок нет, в профиле нет опорных снимков."""

    ВНЕШНОСТЬ = {"селфи": [], "телосложение": "плотный, среднего роста"}

    def setUp(self):
        self._в = tempfile.TemporaryDirectory()
        корень = Path(self._в.name)
        self.addCleanup(self._в.cleanup)
        self.папка = корень / "проба"
        (self.папка / "экраны").mkdir(parents=True)
        профиль = корень / "проба-картинки"
        профиль.mkdir()
        (профиль / "profile.json").write_text(json.dumps({
            "автор": {"роль": "столяр, мебель из массива на заказ"},
            "палитра": ПАЛИТРА,
            "внешность": self.ВНЕШНОСТЬ,
        }, ensure_ascii=False), encoding="utf-8")
        (self.папка / "прототип.md").write_text(ПРОТОТИП, encoding="utf-8")
        (self.папка / "дизайн.md").write_text(ДИЗАЙН, encoding="utf-8")
        for имя, текст in (("01-первый-экран", ПЕРВЫЙ_ЭКРАН), ("02-о-себе", О_СЕБЕ),
                           ("03-работы", РАБОТЫ), ("04-видео", ВИДЕО), ("05-контакты", КОНТАКТЫ)):
            (self.папка / "экраны" / f"{имя}.html").write_text(текст, encoding="utf-8")

    def прогон(self, *аргументы):
        вывод = io.StringIO()
        with contextlib.redirect_stdout(вывод):
            код = заказ.main_с_аргументами([str(self.папка), "--картинки", *аргументы])
        return код, вывод.getvalue()

    def файл(self) -> str:
        return (self.папка / разговор.ФАЙЛ_РАЗГОВОРА).read_text(encoding="utf-8")

    def ответить(self, **ответы):
        """Заполнить «Решения» так, как их заполнил бы человек: без палок и без образца."""
        текст = re.sub(r"^- Стиль: .*$", f"- Стиль: {ответы.pop('стиль', '1')}", self.файл(),
                       flags=re.M)
        текст = re.sub(r"^- Свои файлы: .*$",
                       ответы.pop("файлы", "- Свои файлы: экран-3 → kuhnya.jpg"), текст, flags=re.M)
        for ключ, ответ in ответы.items():
            ключ = ключ.replace("_", "-")
            текст = re.sub(rf"^- {ключ} · ([^:]+): .*$", rf"- {ключ} · \1: {ответ}", текст,
                           flags=re.M)
        (self.папка / разговор.ФАЙЛ_РАЗГОВОРА).write_text(текст, encoding="utf-8")


