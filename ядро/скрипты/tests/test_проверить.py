class ВесИЗаглушкиТесты(unittest.TestCase):
    """Вес картинок и забытые слова шаблона — без браузера."""

    def test_тяжёлая_картинка_красная_а_средняя_жёлтая(self):
        with tempfile.TemporaryDirectory() as папка:
            папка = Path(папка)
            (папка / "тяжёлая.png").write_bytes(b"0" * (проверить.КАРТИНКА_ТЯЖЁЛАЯ + 1024))
            (папка / "средняя.png").write_bytes(b"0" * (проверить.КАРТИНКА_ТЯЖЕЛОВАТА + 1024))
            находки = проверить.находки_по_весу(
                [{"тег": "img", "сырой": "тяжёлая.png"}, {"тег": "img", "сырой": "средняя.png"}],
                папка, 2048)
        уровни = {н["что"]: н["уровень"] for н in находки}
        self.assertEqual(уровни["Тяжёлые картинки"], проверить.ЧИНИТЬ)
        self.assertEqual(уровни["Картинки, которые стоит сжать"], проверить.ПОПРАВИТЬ)

    def test_вся_страница_тяжёлая_это_жёлтое(self):
        with tempfile.TemporaryDirectory() as папка:
            папка = Path(папка)
            for номер in range(4):
                (папка / f"кадр-{номер}.png").write_bytes(b"0" * (900 * 1024))
            находки = проверить.находки_по_весу(
                [{"тег": "img", "сырой": f"кадр-{н}.png"} for н in range(4)], папка, 4096)
        тяжёлая_страница = [н for н in находки if н["что"] == "Страница весит много"]
        self.assertEqual(len(тяжёлая_страница), 1)
        self.assertEqual(тяжёлая_страница[0]["уровень"], проверить.ПОПРАВИТЬ)

    def test_файл_по_ссылке_в_вес_страницы_не_идёт(self):
        """Прайс в PDF рядом со страницей никто не грузит при открытии — и в вес он не идёт."""
        with tempfile.TemporaryDirectory() as папка:
            папка = Path(папка)
            (папка / "прайс.pdf").write_bytes(b"0" * (4 * 1024 * 1024))
            находки = проверить.находки_по_весу([{"тег": "a", "сырой": "прайс.pdf"}], папка, 2048)
        self.assertEqual(находки, [])

    def test_один_файл_считается_один_раз(self):
        """Одна картинка, названная в двух тегах, весит столько же, сколько одна."""
        with tempfile.TemporaryDirectory() as папка:
            папка = Path(папка)
            (папка / "фон.png").write_bytes(b"0" * (2 * 1024 * 1024))
            находки = проверить.находки_по_весу(
                [{"тег": "img", "сырой": "фон.png"}, {"тег": "link", "сырой": "./фон.png"}],
                папка, 1024)
        тяжёлые = [н for н in находки if н["что"] == "Тяжёлые картинки"]
        self.assertEqual(len(тяжёлые[0]["строки"]), 1, тяжёлые[0]["строки"])
        self.assertEqual([н for н in находки if н["что"] == "Страница весит много"], [],
                         "посчитанные дважды 2 МБ дали бы ложное «страница весит много»")

    def test_вес_словами_читается_человеком(self):
        self.assertEqual(проверить.вес_словами(1024 * 300), "300 КБ")
        self.assertEqual(проверить.вес_словами(int(1024 * 1024 * 1.4)), "1,4 МБ")

    def test_заглушки_ищутся_независимо_от_регистра(self):
        найденные = проверить.найти_заглушки(
            "Первый абзац. LOREM ipsum dolor. Позвоните: +7 (000) 000-00-00.", "Главная")
