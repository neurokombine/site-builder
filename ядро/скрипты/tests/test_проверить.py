class СсылкиТесты(unittest.TestCase):
    """Ссылки разбираются без браузера — на готовом списке, наружу не ходим."""

    def ссылка(self, сырой, тег="a"):
        return {"тег": тег, "сырой": сырой, "адрес": сырой, "подпись": "ссылка"}

    def test_внешняя_не_открылась_это_жёлтое(self):
        with patch.object(проверить, "открывается_ли", return_value=(False, "код 404")) as поход:
            находки = проверить.находки_по_ссылкам(
                [self.ссылка("https://пример.рф/цены")], [], None)
        поход.assert_called_once()
        self.assertEqual(len(находки), 1)
        self.assertEqual(находки[0]["уровень"], проверить.ПОПРАВИТЬ)
        self.assertIn("не открылась", находки[0]["строки"][0])
        self.assertIn("защита от роботов", находки[0]["строки"][0])

    def test_внешняя_открылась_молчим(self):
        with patch.object(проверить, "открывается_ли", return_value=(True, "код 200")):
            находки = проверить.находки_по_ссылкам(
                [self.ссылка("https://пример.рф/цены")], [], None)
        self.assertEqual(находки, [])

    def test_к_мессенджерам_не_ходим(self):
        with patch.object(проверить, "открывается_ли",
                          side_effect=AssertionError("к мессенджеру ходить не надо")):
            хорошие = проверить.находки_по_ссылкам(
                [self.ссылка("https://t.me/имя_мастера"),
                 self.ссылка("https://wa.me/" + УЧЕБНЫЙ_НОМЕР.lstrip("+"))], [], None)
            пустая = проверить.находки_по_ссылкам([self.ссылка("https://t.me/")], [], None)
        self.assertEqual(хорошие, [])
        self.assertEqual(пустая[0]["уровень"], проверить.ЧИНИТЬ)
        self.assertIn("без имени или номера", пустая[0]["строки"][0])

    def test_служебные_link_не_проверяем(self):
        # п. 2: preconnect к fonts.googleapis.com/gstatic.com — подсказка браузеру, а корни этих
        # доменов отвечают 404: каждый сайт с веб-шрифтом получал два ложных 🟡.
        def link(сырой, rel):
            return {"тег": "link", "сырой": сырой, "адрес": сырой, "подпись": "", "rel": rel}
        with patch.object(проверить, "открывается_ли", return_value=(False, "код 404")) as поход:
            находки = проверить.находки_по_ссылкам(
                [link("https://fonts.googleapis.com", "preconnect"),
                 link("https://fonts.gstatic.com", "preconnect"),
                 link("https://пример.рф/шрифт.woff2", "preload")], [], None)
        поход.assert_not_called()
        self.assertEqual(находки, [])
        # а обычный stylesheet по-прежнему проверяется
        with patch.object(проверить, "открывается_ли", return_value=(True, "код 200")) as поход:
            проверить.находки_по_ссылкам([link("https://fonts.googleapis.com/css2?family=X", "stylesheet")], [], None)
        поход.assert_called_once()

    def test_хост_не_откусывается(self):
        """`wa.me` начинается с «w» — домен должен остаться целым."""
        self.assertEqual(проверить.хост_из("https://wa.me/70000000000"), "wa.me")
        self.assertEqual(проверить.хост_из("https://www.t.me/имя"), "t.me")

    def test_почта_и_телефон_по_форме(self):
        self.assertIsNone(проверить.проверить_адрес_связи("mailto:мастер@пример.рф"))
        self.assertIsNone(проверить.проверить_адрес_связи("tel:" + УЧЕБНЫЙ_НОМЕР))
        self.assertIn("почты", проверить.проверить_адрес_связи("mailto:мастер-пример.рф"))
        self.assertIn("цифр", проверить.проверить_адрес_связи("tel:звоните"))

    def test_разделители_в_номере_это_не_ошибка(self):
        """Скобки, пробелы и дефисы в номере пишут все, и телефон по ним набирается."""
        как_пишут = "tel:+1 (000) 000-00-00"
        self.assertIsNone(проверить.проверить_адрес_связи(как_пишут), как_пишут)
        находки = проверить.находки_по_ссылкам([self.ссылка(как_пишут)], [], None)
        self.assertEqual(находки, [], "красное здесь запретило бы показывать готовый сайт")
        self.assertIsNone(проверить.проверить_адрес_связи("tel:" + УЧЕБНЫЙ_НОМЕР.replace("+", "")))
        self.assertIsNotNone(проверить.проверить_адрес_связи("tel:"))

    def test_якорь_наверх_не_ругается(self):
        находки = проверить.находки_по_ссылкам(
            [self.ссылка("#"), self.ссылка("#top"), self.ссылка("#цены")], ["цены"], None)
        self.assertEqual(находки, [])

    def test_соседняя_папка_с_похожим_именем_это_не_своя(self):
        # Ложноотрицательный ответ из ревью: путь сравнивался строками, и для папки «сайт»
        # соседняя «сайт-старый» тоже «начиналась с» неё. Файл на диске есть, находки нет —
        # а на хостинге соседней папки не будет и на месте фотографии останется пустота.
        with tempfile.TemporaryDirectory() as временная:
            корень = Path(временная)
            свой = корень / "сайт"
            свой.mkdir()
            соседняя = корень / "сайт-старый"
            соседняя.mkdir()
            (соседняя / "фото.jpg").write_text("тут была фотография", encoding="utf-8")

            находки = проверить.находки_по_ссылкам(
                [self.ссылка("../сайт-старый/фото.jpg", тег="img")], [], свой)

        self.assertEqual(len(находки), 1)
        self.assertEqual(находки[0]["уровень"], проверить.ЧИНИТЬ)
        self.assertIn("за пределы папки сайта", находки[0]["строки"][0])

    def test_внешних_ссылок_проверяем_первые_сорок(self):
        # Каждая ссылка — до двух походов по восемь секунд: без потолка подвал с сотней
        # ссылок проверялся бы четверть часа при обещанной «около минуты».
        ссылки = [self.ссылка(f"https://пример-{номер}.рф/") for номер in range(45)]
        with patch.object(проверить, "открывается_ли", return_value=(True, "код 200")) as поход, \
                contextlib.redirect_stderr(io.StringIO()) as прогресс:
            находки = проверить.находки_по_ссылкам(ссылки, [], None)

        self.assertIn("Проверяю ссылки: 10 из 40", прогресс.getvalue(),
                      "человек у экрана должен видеть, что работа идёт, а не зависла")

        self.assertEqual(поход.call_count, проверить.ЛИМИТ_ВНЕШНИХ_ССЫЛОК)
        сказано = [н for н in находки if н["уровень"] == проверить.К_СВЕДЕНИЮ]
        self.assertEqual(len(сказано), 1, "про непроверенные ссылки надо сказать вслух")
        self.assertIn("остальные 5", сказано[0]["строки"][0])

    def test_сорока_ссылок_хватило_и_говорить_не_о_чем(self):
        ссылки = [self.ссылка(f"https://пример-{номер}.рф/") for номер in range(40)]
        with patch.object(проверить, "открывается_ли", return_value=(True, "код 200")), \
                contextlib.redirect_stderr(io.StringIO()):
            self.assertEqual(проверить.находки_по_ссылкам(ссылки, [], None), [])


class ПоходПоСсылкеТесты(unittest.TestCase):
    """Настоящий поход по ссылке — но не наружу, а к своему же локальному серверу."""

    def test_живая_страница_и_битая(self):
        with проверить.локальный_сервер(ФИКСТУРЫ / "сайт-чистый") as адрес:
            открылась, почему = проверить.открывается_ли(адрес + "index.html")
            self.assertTrue(открылась, почему)
            открылась, почему = проверить.открывается_ли(адрес + "нет-такой-страницы.html")
        self.assertFalse(открылась)
        self.assertIn("404", почему)

    def test_отказ_на_head_переспрашиваем_get_ом(self):
        """Сервер, который не понимает HEAD, отдаёт ту же страницу по GET — ссылка живая."""

        class НеЛюбитHead(http.server.BaseHTTPRequestHandler):
            def do_HEAD(self):
                self.send_error(501)

            def do_GET(self):
                тело = "живая страница".encode("utf-8")
                self.send_response(200)
                self.send_header("Content-Length", str(len(тело)))
                self.end_headers()
                self.wfile.write(тело)

            def log_message(self, формат, *аргументы):
                pass

        сервер = http.server.ThreadingHTTPServer(("127.0.0.1", 0), НеЛюбитHead)
        поток = threading.Thread(target=сервер.serve_forever, daemon=True)
        поток.start()
        try:
            открылась, почему = проверить.открывается_ли(
                f"http://127.0.0.1:{сервер.server_port}/цены")
        finally:
            сервер.shutdown()
            сервер.server_close()
        self.assertTrue(открылась, почему)
        self.assertEqual(почему, "код 200")

