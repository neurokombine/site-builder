    def test_запрос_в_заголовке_подряд_и_с_предлогами(self):
        в = проверить.запрос_в_тексте
        self.assertTrue(в("репетитор по математике", "Репетитор математики онлайн — Имя", первых_слов=12))
        self.assertTrue(в("курсы вязания", "Курсы для вязания спицами"))
        self.assertFalse(в("курсы вязания", "Вязание и курсы"))     # порядок важен
        self.assertFalse(в("курсы вязания", "Курсы Имя Вязание"))

