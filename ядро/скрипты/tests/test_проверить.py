def строки_находок(итог) -> str:
    """Все находки одним текстом — по нему тесты и ищут."""
    куски = []
    for н in итог["находки"]:
        куски.append(f"{н['уровень']} {н['что']} {н.get('чем_грозит', '')}")
        куски += [f"{н['уровень']} {с}" for с in н["строки"]]
    return "\n".join(куски)


def уровень(итог, кусок: str) -> str | None:
    """С каким значком нашлось место, где встречается этот кусок текста."""
    for строка in строки_находок(итог).split("\n"):
        if кусок in строка:
            return строка.split(" ", 1)[0]
    return None


