    def находки(self, **разметка):
        открыт = разметка.pop("открыт", True)
        живой = разметка.pop("живой", "")
        папка = разметка.pop("папка", None)
        return проверить.находки_для_поиска(разметка, открыт_поиску=открыт,
                                            адрес_живой=живой, папка=папка)

    def по_имени(self, находки, имя):
        return next((н for н in находки if н["что"] == имя), None)

    def h(self, *уровни):
        return [{"у": у, "т": f"Заголовок {i}"} for i, у in enumerate(уровни)]

    def test_без_ключей_разбора_молчим(self):
        self.assertEqual(self.находки(), [])

    def test_h1_нет_это_красное(self):
        н = self.по_имени(self.находки(заголовки=self.h(2, 3)), "Главных заголовков не один")
        self.assertEqual(н["уровень"], проверить.ЧИНИТЬ)

    def test_два_h1_это_красное(self):
        н = self.по_имени(self.находки(заголовки=self.h(1, 2, 1)), "Главных заголовков не один")
        self.assertEqual(н["уровень"], проверить.ЧИНИТЬ)
