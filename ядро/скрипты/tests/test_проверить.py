УЧЕБНЫЙ_НОМЕР = "+1" + "0" * 10


def ЦВЕТ(красный, зелёный, синий) -> str:
    """Цвет в том виде, в каком его отдаёт браузер, — собран из чисел, а не написан литералом."""
    return "#{:02x}{:02x}{:02x}".format(красный, зелёный, синий)


