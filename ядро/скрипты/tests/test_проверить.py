class КрупныйТекстМеритсяТремяТесты(unittest.TestCase):
    """Решение владелицы 14.09.2026 (№ 6): акцентное слово заголовка на телефоне в тёмном ключе
    чинится не цветом, а размером — «крупнее хвост заголовка».

    Смысл правки: WCAG меряет крупный текст (от 24 px, или от 18,66 px при 700) нормой 3:1, а не
    4,5. Акцент студии — #D32F2F на #0D1B2A — даёт 3,49: мелким он не проходит, крупным проходит.
    Здесь проверяется именно эта развилка, на одних и тех же двух цветах: меняется только кегль.
    И третий случай — палитра, где не выходит даже 3:1: там сторож обязан заговорить и на крупном,
    иначе «сделай крупнее» превратилось бы в способ заглушить любую находку."""

    ФОН = "#0D1B2A"          # тёмный_фон_1 студии
    ЯРКИЙ = "#D32F2F"        # акцент_яркий студии: 3,49 к фону
    ТУСКЛЫЙ = "#6B1520"      # акцент_тёмный студии: 1,45 к фону — не тянет и на 3:1

    @classmethod
    def setUpClass(cls):
        from playwright.sync_api import sync_playwright

        cls._playwright = sync_playwright().start()
        cls.браузер = проверить.глаза.запустить_браузер(cls._playwright)
        cls._временная = tempfile.TemporaryDirectory()

    @classmethod
    def tearDownClass(cls):
        cls.браузер.close()
        cls._playwright.stop()
        cls._временная.cleanup()

    def _проверить(self, имя: str, цвет: str, кегль: int) -> dict:
        корень = Path(self._временная.name) / имя
        (корень / "сайт").mkdir(parents=True)
        (корень / "сайт" / "index.html").write_text(
            '<!DOCTYPE html><html lang="ru"><head><meta charset="utf-8">'
            '<meta name="viewport" content="width=device-width, initial-scale=1">'
            "<title>Проба крупного текста</title></head>"
            f'<body style="margin:0;background:{self.ФОН}">'
            f'<h1 style="color:#FAF8F5;font-size:33px;padding:24px">Дело мастера'
            f'<span style="display:block;font-size:{кегль}px;font-weight:600">'
            f'вы научитесь делать <em style="font-style:normal;color:{цвет}">видео из ничего</em>'
            "</span></h1></body></html>", encoding="utf-8")
        return проверить.проверить(корень / "сайт", корень / "отчёт",
                                   браузер=self.браузер, ждать_сек=0.2)

    def test_мелким_кеглем_акцент_это_находка(self):
        итог = self._проверить("мелким", self.ЯРКИЙ, 21)
        self.assertEqual(уровень(итог, "при норме 4,5"), проверить.ПОПРАВИТЬ,
                         "акцент 3,49 при мелком кегле обязан быть находкой")

    def test_крупным_кеглем_тот_же_цвет_молчит(self):
        итог = self._проверить("крупным", self.ЯРКИЙ, 24)
        self.assertIsNone(уровень(итог, "видео из ничего"),
                          "с 24 px норма 3:1, и 3,49 её держит — сторож обязан молчать")

    def test_где_и_трёх_не_выходит_говорит_и_на_крупном(self):
        итог = self._проверить("совсем-тускло", self.ТУСКЛЫЙ, 24)
        self.assertEqual(уровень(итог, "при норме 3"), проверить.ПОПРАВИТЬ,
                         "1,45 не тянет даже на крупном — «сделай крупнее» не глушит находку")


