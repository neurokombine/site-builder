class КонтрастПоПикселямТесты(unittest.TestCase):
    """Фон под кнопкой и под текстом берётся с экрана, а не из разметки.

    Сторож на самом жёстком правиле владелицы («кнопка целевого действия всегда контрастная»)
    обязан молчать на честной кнопке и кричать на серой. Оба случая проверяются на собранной
    странице, а не на выдуманном словаре: страница поднимается локальным сервером, снимается
    браузером, и находки считаются так же, как у человека.
    """

    @classmethod
    def setUpClass(cls):
        from playwright.sync_api import sync_playwright

        cls._playwright = sync_playwright().start()
        cls.браузер = проверить.глаза.запустить_браузер(cls._playwright)
        cls._временная = tempfile.TemporaryDirectory()
        корень = Path(cls._временная.name)
        папка = корень / "сайт"
        папка.mkdir()
        (папка / "index.html").write_text(СТРАНИЦА_С_ГРАДИЕНТАМИ, encoding="utf-8")
        cls.итог = проверить.проверить(папка, корень / "проверка",
                                       браузер=cls.браузер, ждать_сек=0.2)
        # Отдельный, не тронутый находками разбор — им тесты показывают, что было бы БЕЗ экрана.
        with проверить.локальный_сервер(папка) as адрес:
            cls.разметка = json.loads(json.dumps(
                проверить.снять_разметку(cls.браузер, адрес)))

    @classmethod
    def tearDownClass(cls):
        cls.браузер.close()
        cls._playwright.stop()
        cls._временная.cleanup()

    def _свежие(self, ключ):
        return json.loads(json.dumps(self.разметка[ключ]))

    def test_разметка_читает_градиент_и_честную_кнопку_не_обвиняет(self):
        """Н2: секция задана шорткатом `background: linear-gradient(…)`, и `background-color`
        у неё прозрачный. Раньше обход предков проходил секцию насквозь и приносил цвет body —
        честная кнопка на тёмном экране отчитывалась контрастом 2,79 к светлому фону страницы.
        Теперь фон берётся с первого непрозрачного стопа градиента, и находки нет уже по
        разметке. Сторож при этом не выключен: серая кнопка по-прежнему названа."""
        н, = проверить.находки_по_кнопкам(self._свежие("кнопки"), None)
        строки = "\n".join(н["строки"])
        self.assertNotIn("Оставить заявку", строки)
        self.assertIn("Записаться на разбор", строки)
        self.assertIn(проверить.БЕЗ_ЭКРАНА, строки)

    def test_кнопка_на_градиенте_с_честным_контрастом_молчит(self):
        """Та же кнопка на собранной странице: фон снят с экрана (#16202b), 5,65 — находки нет."""
        self.assertNotIn("Оставить заявку", строки_находок(self.итог))

    def test_серая_кнопка_на_близком_фоне_находится(self):
        """И наоборот: серая заливка на светлом градиенте остаётся находкой — сторож не выключен."""
        self.assertEqual(уровень(self.итог, "Записаться на разбор"), проверить.ПОПРАВИТЬ)
        [строка] = [с for с in строки_находок(self.итог).split("\n")
                    if "Записаться на разбор" in с]
        self.assertIn("при норме 3", строка)
        self.assertIn("фон снят с экрана", строка, "фон должен быть взят по пикселям, а не по body")

    def test_текст_на_полупрозрачной_карточке_молчит(self):
        """Сосед той же природы: белая строка на тёмном стекле поверх светлой секции."""
        по_разметке, = проверить.находки_по_контрасту(self._свежие("контраст"), None)
        self.assertIn("Белая строка на тёмной карточке", "\n".join(по_разметке["строки"]))
        self.assertNotIn("Белая строка на тёмной карточке", строки_находок(self.итог))

    def test_бледный_текст_на_градиенте_находится(self):
        """А настоящее слияние текста с фоном остаётся находкой и после пересчёта по пикселям."""
        self.assertEqual(уровень(self.итог, "Бледный абзац"), проверить.ПОПРАВИТЬ)
        [строка] = [с for с in строки_находок(self.итог).split("\n") if "Бледный абзац" in с]
        self.assertIn("фон снят с экрана", строка)


class ПорогПересчётаКнопкиТесты(unittest.TestCase):
    """НЭ-7: фактура секции (`фон--пятна|сетка|зерно`) лежит поверх фона слоем с прозрачностью
    .12 и сдвигает настоящий пиксель, а подбор цвета кнопки при сборке об этом слое не знает.
    Живой случай: 3,06 по токену и 2,71 по пикселям — по разметке «норма». Поэтому по снимку
    перемеряется всё, что ближе 3,5 к норме, а не только провалившееся."""

    def _кнопка(self, к_фону):
        return {"текст": "Оставить заявку", "заливка": "#a6957b", "подпись": "#16202b",
                "фон": "#16202b", "к_фону": к_фону, "к_подписи": 5.6,
                "коробка": {"x": 0, "y": 0, "ш": 10, "в": 10}}

    def test_пограничный_контраст_перемеряется_по_снимку(self):
        кнопка = self._кнопка(3.06)
        with patch.object(проверить, "фон_вокруг", return_value="#6b6155"):
            находки = проверить.находки_по_кнопкам([кнопка], ("картинка", 1))
        self.assertTrue(кнопка.get("фон_с_экрана"), "пограничная кнопка не перемерена по снимку")
        self.assertTrue(находки, "после пересчёта контраст ниже нормы — находка обязана быть")

    def test_кнопка_с_запасом_остаётся_на_разметке(self):
        кнопка = self._кнопка(5.65)
        with patch.object(проверить, "фон_вокруг", return_value="#2a2a2a"):
            self.assertEqual(проверить.находки_по_кнопкам([кнопка], ("картинка", 1)), [])
        self.assertNotIn("фон_с_экрана", кнопка)


class ЭкранСтраницыТесты(unittest.TestCase):
    """Снимок и разбор должны говорить об одном и том же месте — иначе мерить по снимку нельзя."""

    def test_без_снимка_молчит(self):
        self.assertIsNone(проверить.экран_страницы({}, {"окно": {"ширина": 1440, "высота": 900}}))

    def test_разошлись_по_высоте_страницы_молчит(self):
        with tempfile.TemporaryDirectory() as временная:
            from PIL import Image

            снимок = Path(временная) / "вся-страница.png"
            Image.new("RGB", (1440, 5000), (255, 255, 255)).save(снимок)
            замеры = {"устройства": {"компьютер": {"скриншоты": {"вся_страница": str(снимок)}}}}
            self.assertIsNone(проверить.экран_страницы(
                замеры, {"окно": {"ширина": 1440, "высота": 900}}))
            картинка, масштаб = проверить.экран_страницы(
                замеры, {"окно": {"ширина": 720, "высота": 2500}})
            self.assertEqual(масштаб, 2.0, "у телефона снимок крупнее страницы — масштаб считаем сами")
            self.assertEqual(картинка.size, (1440, 5000))


