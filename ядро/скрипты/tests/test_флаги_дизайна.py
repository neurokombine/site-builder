# ── Задача 13, статические находки: палитра, видео, предлоги, иконки — без браузера ────────

class СтатическиеНаходки(unittest.TestCase):
    """Палитра, тип видео, висячие предлоги и иконки читаются с диска — браузер им не нужен.
    Один раз собираем настоящий сайт из фикстуры «работа-образец» (собрать.собрать — тот же
    путь, что и в бою), дальше портим копию нарочно и возвращаем как было."""

    @classmethod
    def setUpClass(cls):
        cls._временная = tempfile.TemporaryDirectory()
        работа = Path(cls._временная.name) / "работа"
        shutil.copytree(ФИКСТУРЫ / "экраны-все", работа / "экраны")
        for что in ("img", "video"):
            shutil.copytree(ФИКСТУРЫ / "работа-образец" / что, работа / что)
        shutil.copytree(ФИКСТУРЫ / "профиль-образец", работа.parent / "профиль-образец")
        for ф in ("дизайн.md", "поиск.md", "прототип.md"):
            shutil.copyfile(ФИКСТУРЫ / "работа-образец" / ф, работа / ф)
        cls.работа = работа
        cls.путь, cls.найденное_при_сборке = собрать.собрать(работа)
        cls.папка = cls.путь.parent
        cls.html = cls.путь.read_text(encoding="utf-8")

    @classmethod
    def tearDownClass(cls):
        cls._временная.cleanup()

    def флаги_папки(self, папка) -> list[str]:
        return [н["что"] for н in флаги_дизайна.флаги({}, {}, папка)]

    # ── живой материал: настоящий сайт молчит на все четыре ──

    def test_настоящий_сайт_молчит_на_все_четыре_статические_находки(self):
        молчащие = {"Палитра профиля неполна", "Тип источника видео испорчен",
                    "Висячие предлоги", "Иконка подобрана приблизительно"}
        self.assertEqual(set(self.флаги_папки(self.папка)) & молчащие, set())

    def test_предлоги_защищены_собрать_py(self):
        """Задача 13: экраны фикстуры полны однобуквенных предлогов в обычной прозе — не защищённых
        руками, protection ставит собрать.py на лету. Без правки этот же html дал бы находки."""
        self.assertIn(" ", self.html)   # обычные пробелы в вёрстке остались — правка не всё стёрла
        self.assertEqual(флаги_дизайна.висячие_предлоги(self.html), [])
        # тот же текст без прогона через собрать.py — предлоги висят
        сырой = "".join(ф.read_text(encoding="utf-8-sig") for ф in sorted((self.работа / "экраны").glob("*.html")))
        self.assertGreater(len(флаги_дизайна.висячие_предлоги(сырой)), 0)

    # ── сломать нарочно: палитра ──

    def test_бедная_палитра_ловится(self):
        бедный = re.sub(r":root\s*\{[^}]*\}",
                        ":root { --цвет-фон: #FFFFFF; --цвет-текст: #111111; --цвет-акцент: #2C4A63; }",
                        self.html, count=1)
        with tempfile.TemporaryDirectory() as д:
            папка = Path(д)
            (папка / "index.html").write_text(бедный, encoding="utf-8")
            self.assertIn("Палитра профиля неполна", self.флаги_папки(папка))
        # исходный сайт остался на диске нетронутым — палитра там полная
        self.assertNotIn("Палитра профиля неполна", self.флаги_папки(self.папка))

    def test_палитра_без_root_молчит(self):
        self.assertIsNone(флаги_дизайна._палитра(None))
        with tempfile.TemporaryDirectory() as д:
            (Path(д) / "index.html").write_text("<html></html>", encoding="utf-8")
            self.assertIsNone(флаги_дизайна._палитра(Path(д)))

    # ── сломать нарочно: тип источника видео ──

    def test_источник_видео_с_чужим_типом_ловится(self):
        живая_обложка = (ФИКСТУРЫ / "экраны-все" / "01-первый-экран-живая-обложка-лендинг.html").read_text(encoding="utf-8")
        self.assertEqual(флаги_дизайна.источники_видео_с_чужим_типом(живая_обложка), [])
        # живая обложка ставит адрес ролика скриптом (data-ролик-…), <source> у неё больше нет —
        # портим старую пару <source>, которой ещё пользуются экраны работ
        испорченный = живая_обложка.replace("</video>", '<source src="video/пример.webm" type="video/mp4"></video>', 1)
        строки = флаги_дизайна.источники_видео_с_чужим_типом(испорченный)
        self.assertEqual(len(строки), 1)
        self.assertIn("video/webm", строки[0])
        with tempfile.TemporaryDirectory() as д:
            (Path(д) / "index.html").write_text(испорченный, encoding="utf-8")
            self.assertIn("Тип источника видео испорчен", self.флаги_папки(Path(д)))

    def test_картинка_source_без_type_не_считается(self):
        """`<picture><source media=… srcset=…>` — не видео, атрибута type у него нет вовсе."""
        self.assertEqual(флаги_дизайна.источники_видео_с_чужим_типом(
            '<picture><source media="(max-width: 899px)" srcset="img/пример.svg"></picture>'), [])

    # ── сломать нарочно: висячие предлоги ──

    def test_неразрывные_пробелы_защищают_и_проверка_видит_защиту(self):
        сырой = "<p>Заходите в гости и смотрите с нами</p>"
        защищённый = флаги_дизайна.неразрывные_пробелы(сырой)
        self.assertNotEqual(защищённый, сырой)
        найдено = флаги_дизайна.висячие_предлоги(сырой)
        self.assertEqual([с.split("»")[0] + "»" for с in найдено], ["«в»", "«и»", "«с»"])
        self.assertIn("в гости", защищённый)
        self.assertIn("и смотрите", защищённый)
        self.assertIn("с нами", защищённый)
        self.assertEqual(флаги_дизайна.висячие_предлоги(защищённый), [])

    def test_атрибуты_и_скрипты_не_трогаем(self):
        """Предлог внутри href/aria-label и внутри <script> — не текст на экране, не считаем."""
        html = ('<a href="/о-нас" aria-label="о нас">Ссылка</a>'
               '<script>var в = "с текстом";</script>')
        self.assertEqual(флаги_дизайна.висячие_предлоги(html), [])
        self.assertEqual(флаги_дизайна.неразрывные_пробелы(html), html)

    def test_title_не_переносится_по_строкам_не_считаем(self):
        self.assertEqual(флаги_дизайна.висячие_предлоги("<title>Ремонт в Москве</title>"), [])

    # ── сломать нарочно: иконка приблизительно ──

    def test_иконка_приблизительно_ловится(self):
        текст = ('# Дизайн\n\nпункт «Доставим за час» → иконка «карандаш»\n'
                'пункт «Сертификат по итогам курса» → иконка «диплом»\n')
        найдено = флаги_дизайна.иконки_приблизительно(текст)
