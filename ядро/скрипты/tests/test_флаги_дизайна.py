    def test_живая_кнопка_молчит(self):
        self.assertIsNone(флаги_дизайна._кнопка_не_зовёт({"зов": [self.КНОПКА]}, {"зов": [self.КНОПКА]}))

    def test_погашенная_кнопка_красная(self):
        н = флаги_дизайна._кнопка_не_зовёт({"зов": [self.КНОПКА]},
                                          {"зов": [{**self.КНОПКА, "сама": "none", "блик": "none"}]})
