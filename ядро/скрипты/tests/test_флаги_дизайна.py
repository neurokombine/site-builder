class ВБраузере(unittest.TestCase):
    """Каждая страница — во временный index.html, снимается снять_дизайн в двух размерах."""

    @classmethod
    def setUpClass(cls):
        from playwright.sync_api import sync_playwright

        cls._playwright = sync_playwright().start()
        cls.браузер = глаза.запустить_браузер(cls._playwright)
        cls._временная = tempfile.TemporaryDirectory()
        cls.папка = Path(cls._временная.name)

    @classmethod
    def tearDownClass(cls):
        cls.браузер.close()
        cls._playwright.stop()
        cls._временная.cleanup()

    def флаги_страницы(self, путь: Path) -> list[str]:
        замер = флаги_дизайна.снять_дизайн(self.браузер, f"file://{путь}")
        self.assertEqual(set(замер), set(глаза.РАЗМЕРЫ))
        return [н["что"] for н in флаги_дизайна.флаги({"дизайн": замер}, {})]

    def test_семь_страниц_по_одному_флагу(self):
        for имя, (тело, ожидаем) in СТРАНИЦЫ.items():
            with self.subTest(имя):
                путь = self.папка / имя / "index.html"
                путь.parent.mkdir()
                путь.write_text(страница(тело), encoding="utf-8")
                self.assertEqual(self.флаги_страницы(путь), ожидаем)

    def test_не_открылось_пустой_замер_без_флагов(self):
        замер = флаги_дизайна.снять_дизайн(self.браузер, f"file://{self.папка / 'нет-такой' / 'index.html'}")
        self.assertEqual(замер, {размер: {} for размер in глаза.РАЗМЕРЫ})
        self.assertEqual(флаги_дизайна.флаги({"дизайн": замер}, {}), [])

    def test_гейт_страница_из_всех_блоков_без_флагов(self):
        """Ruling 19: страница из фикстуры экраны-все, собранная как в selftest, не ловит ни одного из семи."""
        работа = self.папка / "все" / "работа"
        shutil.copytree(ФИКСТУРЫ / "экраны-все", работа / "экраны")
        shutil.copytree(ФИКСТУРЫ / "работа-образец" / "img", работа / "img")
        shutil.copytree(ФИКСТУРЫ / "профиль-образец", работа.parent / "профиль-образец")
        for имя in ("дизайн.md", "поиск.md", "прототип.md"):
            shutil.copyfile(ФИКСТУРЫ / "работа-образец" / имя, работа / имя)
        путь, _ = собрать.собрать(работа)
        self.assertEqual(self.флаги_страницы(путь), [])


