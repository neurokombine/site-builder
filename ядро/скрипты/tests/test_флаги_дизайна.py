def экран(*внутри: str) -> str:
    return f'<section class="блок" id="экран-1"><div class="блок__внутри">{"".join(внутри)}</div></section>'


def страница(тело: str) -> str:
    return ('<!DOCTYPE html><html lang="ru"><head><meta charset="utf-8">'
            '<meta name="viewport" content="width=device-width, initial-scale=1"><title>Проба</title>'
            f"<style>{СТИЛИ}\n{ТОКЕНЫ}</style></head><body>{ШАПКА}{тело}</body></html>")


