    def test_плашка_во_всю_картинку(self):
        """Фикс-раунд А: числа — с линейки по макетам и по сломанной сборке (см. ПЛАШКА_ДОЛЯ)."""
        def с_плашками(*плашки, размер="компьютер"):
            э = герой([КАРТИНКА])   # без картинки сработало бы 🔴 «Первый экран без картинки»
            э["первый_экран"]["плашки"] = [{"текст": т, "доля": д, "строк": с} for т, д, с in плашки]
            пусто = {**ЧИСТО, **герой([КАРТИНКА])}
            пусто["первый_экран"]["плашки"] = []
            свой = {**ЧИСТО, **э}
            пара = {"компьютер": свой, "телефон": пусто} if размер == "компьютер" else {"компьютер": пусто, "телефон": свой}
            return [н["что"] for н in флаги_дизайна.флаги({"дизайн": пара}, ЗАМЕРЫ)]

        # Макеты: «товар крупно» — 43 % в одну строку (иконка делает высоту двух), «разворот» — 47 % в одну.
        self.assertEqual(с_плашками(("сценарий", 43, 2), ("Первый ролик — в первый вечер", 47, 1)), [])
        # Наша вёрстка после правки: 58 % у разворота и 67 % у ярлыка в 16 знаков на мелкой палитре.
        self.assertEqual(с_плашками(("Сценарий — полный цикл", 58, 1), ("Разбор пробелов", 67, 1)), [])
        # Сборка до правки: бейджи в 78 % ширины рамки и плашка разворота в три строки.
        н = с_плашками(("Сценарий → кадр → герой → монтаж", 78, 1))
        self.assertEqual(н, ["Плашка на картинке во всю ширину"])
        self.assertEqual(с_плашками(("SYNTX — все нейросети в одном окне", 60, 3)), ["Плашка на картинке во всю ширину"])
        # Телефон не судим: там и макеты кладут плашки рядком под кадр во всю его ширину.
        self.assertEqual(с_плашками(("Сценарий → кадр → герой → монтаж", 92, 3), размер="телефон"), [])

    def test_заголовок_съедает_первый_экран(self):
        """Фикс-раунд В: пороги сняты с одиннадцати макетов (см. ЗАГОЛОВОК_СТРОК/ЗАГОЛОВОК_ДОЛЯ)."""
        def с_заголовком(строк, доля, размер="компьютер"):
            э = герой([КАРТИНКА])
            э["первый_экран"].update({"строк_h1": строк, "доля_h1": доля})
            пусто = {**ЧИСТО, **герой([КАРТИНКА])}
            свой = {**ЧИСТО, **э}
            пара = {"компьютер": свой, "телефон": пусто} if размер == "компьютер" else {"компьютер": пусто, "телефон": свой}
            return [н["что"] for н in флаги_дизайна.флаги({"дизайн": пара}, ЗАМЕРЫ)]

        # Макеты молчат все одиннадцать: орбита и центр — 2 строки/12 %, разворот — 3/20,
        # сцена и живая сцена — 4/28 (их собственный вид, а не поломка).
        for строк, доля in ((2, 12), (3, 20), (4, 28)):
            self.assertEqual(с_заголовком(строк, доля), [], f"{строк} строки, {доля} %")
        # Фикс-раунд Г: потолок нашей сборки опущен до 4 строк и 27 % (интерлиньяж хвоста стал
        # макетным), порог сужен с 33 % до 30 % — 27 % молчит, 31 % теперь говорит.
        self.assertEqual(с_заголовком(4, 27), [])
        self.assertEqual(с_заголовком(4, 31), ["Заголовок съедает первый экран"])
        # Пятая строка — вне семьи макетов; половина высоты окна — то, из-за чего цифры и лицензия
        # уезжали за нижнюю кромку.
        self.assertEqual(с_заголовком(5, 30), ["Заголовок съедает первый экран"])
        self.assertEqual(с_заголовком(4, 48), ["Заголовок съедает первый экран"])
        # Телефон не судим: там три строки дают все одиннадцать макетов.
        self.assertEqual(с_заголовком(6, 60, размер="телефон"), [])

