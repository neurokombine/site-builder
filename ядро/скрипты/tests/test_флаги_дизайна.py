def герой(картинки=None, схема="разворот", тип="фото", звук=None, окно=844):
    return {"первый_экран": {"есть": True, "схема": схема, "тип": тип, "высота_окна": окно, "картинки": картинки or [],
                             "звук": звук or {"кнопка": False, "почему": False, "субтитры": False}}}


def разметка(**правки):
    компьютер, телефон = dict(ЧИСТО), dict(ЧИСТО)
    for ключ, значение in правки.items():
        (телефон if ключ == "мелкий_текст" else компьютер)[ключ] = значение
    return {"дизайн": {"компьютер": компьютер, "телефон": телефон}}


class Правила(unittest.TestCase):
    def что(self, **правки):
        return [н["что"] for н in флаги_дизайна.флаги(разметка(**правки), ЗАМЕРЫ)]

    def test_чистая_страница_без_флагов(self):
        self.assertEqual(self.что(), [])
        self.assertEqual(флаги_дизайна.флаги({"дизайн": {}}, ЗАМЕРЫ), [])
        н = флаги_дизайна.флаги(разметка(тени=0, градиенты=0, кегли=[16, 44]), ЗАМЕРЫ)
        self.assertEqual([х["уровень"] for х in н], [находки.ПОПРАВИТЬ, находки.К_СВЕДЕНИЮ])

    def test_семь_флагов_по_одному(self):
        случаи = (
            ({"мелкий_текст": {"тело_мельче_16": 2, "любой_мельче_13": 0, "примеры": ["li: 14px «Онлайн»"]}}, "На телефоне текст мельче 16 px"),
            ({"главных_по_секциям": [1, 2]}, "Больше одной главной кнопки на экране"),
            ({"таймер": {"есть": True, "дедлайн": "2020-01-01T00:00:00+03:00", "обнулён": True}}, "Таймер без живой даты"),
            ({"таймер": {"есть": True, "дедлайн": "", "обнулён": False}}, "Таймер без живой даты"),
            ({"тени": 0, "градиенты": 0}, "Страница плоская: ни одной тени и градиента"),
            ({"секции": ["h2>ul", "h2>ul", "h2>ul"]}, "Все секции одной структуры"),
            ({"фото_без_маски": 1}, "Фото без маски или скругления"),
            ({"кегли": [16, 18, 44]}, "Меньше четырёх кеглей текста"))
        for правки, ожидаем in случаи:
            self.assertEqual(self.что(**правки), [ожидаем], правки)

    def test_просроченные_дедлайны(self):
        html = '<div data-дедлайн="2020-01-01T00:00:00+03:00"></div><div data-дедлайн="2099-01-01T00:00:00+03:00"></div>'
        self.assertEqual(флаги_дизайна.просроченные_дедлайны(html), ["2020-01-01T00:00:00+03:00"])
        self.assertEqual(флаги_дизайна.просроченные_дедлайны('<i data-дедлайн="вчера"></i>'), ["вчера"])
        self.assertEqual(флаги_дизайна.просроченные_дедлайны('<i data-дедлайн="2099-10-01"></i><i data-дедлайн="2099-10-01 23:59"></i><i data-дедлайн="2099-10-01T23:59"></i><i data-дедлайн="2099-10-01T23:59:00Z"></i>'), ["2099-10-01", "2099-10-01 23:59", "2099-10-01T23:59"])   # без T или без смещения — негодна; Z — годна

    def test_все_семь_разом_и_ни_одного_красного(self):
        """Один размер не открылся → пустой словарь размера, правила его пропускают; семь бед сразу — семь
        находок, и ни одна не 🔴: флаги дизайна код выхода не трогают."""
        self.assertEqual(флаги_дизайна.флаги({"дизайн": {"компьютер": {}, "телефон": dict(ЧИСТО)}}, ЗАМЕРЫ), [])
        н = флаги_дизайна.флаги(разметка(
            тени=0, градиенты=0, кегли=[16], фото_без_маски=2, секции=["h2>p"] * 3, главных_по_секциям=[0, 2],
            таймер={"есть": True, "дедлайн": "", "обнулён": True},
            мелкий_текст={"тело_мельче_16": 1, "любой_мельче_13": 1, "примеры": ["p: 14px «Мелко»"]}), ЗАМЕРЫ)
        self.assertEqual(len(н), 7)
        self.assertNotIn(находки.ЧИНИТЬ, {х["уровень"] for х in н})
        self.assertIn("13.5 px", н[0]["строки"][0])


class ПравилаКартинки(unittest.TestCase):
    def флаги(self, компьютер, телефон=None, папка=None):
        разметка = {"дизайн": {"компьютер": {**ЧИСТО, **компьютер}, "телефон": {**ЧИСТО, **(телефон if телефон is not None else компьютер)}}}
        return [н["что"] for н in флаги_дизайна.флаги(разметка, ЗАМЕРЫ, папка)]

    def test_восемь_находок_по_одной(self):
        self.assertEqual(self.флаги(герой([КАРТИНКА])), [])
        self.assertEqual(self.флаги({}), [])                                    # страница без [data-схема] — старые сайты, молчим
        self.assertEqual(self.флаги(герой([])), ["Первый экран без картинки"])
        self.assertEqual(self.флаги(герой([КАРТИНКА]), герой([{**КАРТИНКА, "верх": 900}])), ["На телефоне в первом экране картинки нет"])
        self.assertEqual(self.флаги(герой([КАРТИНКА]), герой([])), ["На телефоне в первом экране картинки нет"])   # скрыта стилями под 899px
        self.assertEqual(self.флаги(герой([]), герой([КАРТИНКА])), ["Первый экран без картинки"])                 # пусто на компьютере — одно правило
        self.assertEqual(флаги_дизайна.флаги({"дизайн": {"компьютер": {**ЧИСТО, **герой([КАРТИНКА])}, "телефон": {}}}, ЗАМЕРЫ), [])   # телефон не открылся
        [н] = флаги_дизайна.флаги({"дизайн": {"компьютер": {**ЧИСТО, **герой([КАРТИНКА])}, "телефон": {**ЧИСТО, **герой([])}}}, ЗАМЕРЫ)
        self.assertEqual(н["строки"], ["на компьютере картинка есть, на телефоне видимых 0"])
        self.assertEqual(self.флаги(герой([{**КАРТИНКА, "вписана": "fill", "ширина": 300, "высота": 100}])), ["Картинка сплющена"])
        self.assertEqual(self.флаги(герой([{**КАРТИНКА, "на_лице": "Заголовок"}])), ["Текст ложится на зону лица"])
        self.assertEqual(self.флаги(герой([{**КАРТИНКА, "тег": "video", "постер": False}])), ["Видео без постера или со звуком"])
        self.assertEqual(self.флаги(герой([КАРТИНКА], тип="видео-с-голосом")), ["Живая сцена без кнопки звука"])
        self.assertEqual(self.флаги(герой([КАРТИНКА], звук={"кнопка": True, "почему": True, "субтитры": True})), ["В видео субтитры"])
        уровни = {н["что"]: н["уровень"] for н in флаги_дизайна.флаги(
            {"дизайн": {"компьютер": {**ЧИСТО, **герой([])}, "телефон": {**ЧИСТО, **герой([])}}}, ЗАМЕРЫ)}
        self.assertEqual(уровни, {"Первый экран без картинки": находки.ЧИНИТЬ})   # GC 12: три 🔴 — только про картинку

    def test_вырез_у_края_только_в_центре(self):
        with tempfile.TemporaryDirectory() as д:
            (Path(д) / "img").mkdir()
            к = Image.new("RGBA", (200, 300), (0, 0, 0, 0))
            к.paste((1, 1, 1, 255), (0, 0, 150, 300))
            к.save(Path(д) / "img" / "figura.png")
            своя = [{**КАРТИНКА, "адрес": "img/figura.png"}]
            self.assertEqual(self.флаги(герой(своя, схема="центр"), папка=Path(д)), ["Вырез касается края при схеме центр"])
            self.assertEqual(self.флаги(герой(своя, схема="орбита"), папка=Path(д)), [])
            self.assertEqual(self.флаги(герой(своя, схема="центр")), [])       # без папки файл не открыть — молчим


