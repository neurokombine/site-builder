"""Сторож: засечная гарнитура не всплывает там, где система что-то ПРЕДЛАГАЕТ или собирает.

Правило владелицы (15.09.2026, дословно): «Никаких шрифтов с засечками. Никогда. На экране
читаются отвратительно» — без исключений: ни в заголовках, ни в тексте, ни как один из
вариантов на выбор. Список засечных имён — не здесь: один на всю систему в `ядро/скрипты/
гарнитуры.py`, его же использует замена донорских шрифтов в `ресёрч_ниши.py`.

Зачем отдельный обход, а не общий с `test_личное.py`. Личное ищут по всему ядру и без исключений
по смыслу — засечки нужно узнавать по смыслу места: рецепт, документ или фикстура, где гарнитуру
ПРЕДЛАГАЮТ человеку, — это находка; строка в коде, которая РАСПОЗНАЁТ засечку по имени (списки
системных шрифтов, тесты определения гарнитуры на выдуманном доноре) — не находка, и таких мест
в `.py` много. Поэтому обход берёт только то, что видит человек или нейросеть, выбирая шрифт:
документы (`.md`), фикстуры дизайна и рецепты (`.html`, `.json`), стили (`.css`) — код (`.py`,
`.js`) не трогаем вовсе, там имена живут по делу (см. докстринг `гарнитуры.py`).

Исключения — по файлу и по точной подстроке в строке, а не по всему файлу: иначе сторож
переставал бы видеть новую засечку в документе, который и так знает одно легальное имя.
"""
import sys
import unittest
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import гарнитуры  # noqa: E402

РАСШИРЕНИЯ = {".md", ".html", ".css", ".json"}
ОБХОДИМ = ("ядро",)

# (относительный путь от корня репозитория) → подстроки, которым разрешено содержать засечное
# имя в этом конкретном файле. Каждая — с объяснением, почему это не рекомендация человеку.
ИСКЛЮЧЕНИЯ_ПО_СТРОКЕ: dict[str, tuple[str, ...]] = {
    # Список распознавания системных шрифтов доноров — не рекомендация, а опознание
    # (`ресёрч_ниши.СИСТЕМНЫЕ_ШРИФТЫ`); документ его цитирует, а не предлагает взять Georgia.
    "ядро/дизайн-система.md": ("ресёрч_ниши.СИСТЕМНЫЕ_ШРИФТЫ",),
    # Пример гарнитуры с мелким очком в измерении браузером — довод «не берите такую», а не
    # предложение выбрать: следующее предложение прямо советует гарнитуру с более крупным очком.
    "ядро/дизайн/ритм-и-громкость.md": ("Cormorant Garamond",),
    # Донорский сайт для теста «свой шрифт определился браузером» (`test_глаза.py`,
    # `test_собрать.py`) — фикстура нарочно засечная, чтобы проверить измерение, а не дизайн.
    "ядро/скрипты/tests/фикстуры/референс/index.html": ("Georgia, serif",),
}


def _текстовые_файлы() -> list[Path]:
    найденные: list[Path] = []
    for папка in ОБХОДИМ:
        найденные += sorted((КОРЕНЬ / папка).rglob("*"))
    итог = []
    for файл in найденные:
        if not файл.is_file() or файл.suffix.lower() not in РАСШИРЕНИЯ:
            continue
        if "__pycache__" in файл.parts:
            continue
        итог.append(файл)
    return итог


def находки_в_файле(файл: Path) -> list[str]:
    """Строки файла, где всплыла засечная гарнитура и это не по разрешённому списку строк."""
    путь = файл.resolve().relative_to(КОРЕНЬ).as_posix()
    разрешено = ИСКЛЮЧЕНИЯ_ПО_СТРОКЕ.get(путь, ())
    текст = файл.read_text(encoding="utf-8-sig", errors="replace")
    итог = []
    for номер, строка in enumerate(текст.splitlines(), 1):
        if any(подстрока in строка for подстрока in разрешено):
            continue
        if гарнитуры.засечная_в_тексте(строка):
            итог.append(f"{путь}:{номер}: {строка.strip()[:120]}")
    return итог


class ЗасечныхНетТам_ГдеПредлагаем(unittest.TestCase):
    def test_ни_в_одном_документе_фикстуре_рецепте_или_стиле_нет_засечки(self):
        находки: list[str] = []
        for файл in _текстовые_файлы():
            находки += находки_в_файле(файл)
        self.assertEqual(находки, [], "засечная гарнитура там, где систему выбирают:\n"
                                       + "\n".join(находки))

    def test_обход_добирается_до_нужных_мест(self):
        """Сторож, который ничего не обошёл, не сторож."""
        пути = {ф.resolve().relative_to(КОРЕНЬ).as_posix() for ф in _текстовые_файлы()}
        self.assertGreater(len(пути), 30, "обход ядра опустел — сторож мерит не то")
        for обязательный in ("ядро/дизайн/палитра-и-токены.md", "ядро/дизайн-система.md",
                              "ядро/скрипты/tests/фикстуры/работа-образец/дизайн.md"):
            self.assertIn(обязательный, пути, обязательный)

    def test_сторож_ловит_подсунутое(self):
        """Проверка самого детектора: то же сравнение, которым живёт весь обход."""
        строка_с_засечкой = "  --шрифт-заголовков: Georgia, 'Times New Roman', serif;"
        строка_чистая = "  --шрифт-заголовков: Montserrat, system-ui, sans-serif;"
        self.assertTrue(гарнитуры.засечная_в_тексте(строка_с_засечкой))
        self.assertFalse(гарнитуры.засечная_в_тексте(строка_чистая))

    def test_исключение_работает_только_на_своей_строке(self):
        """Разрешённая подстрока не открывает файл целиком: другая засечка в том же файле
        обязана остаться поймана."""
        разрешено = ИСКЛЮЧЕНИЯ_ПО_СТРОКЕ["ядро/дизайн-система.md"]
        строка_разрешённая = "Системные (ресёрч_ниши.СИСТЕМНЫЕ_ШРИФТЫ: Georgia, Verdana) грузить не надо"
        строка_новая_засечка = "Возьмите Playfair Display для заголовков"
        self.assertTrue(any(п in строка_разрешённая for п in разрешено))
        self.assertFalse(any(п in строка_новая_засечка for п in разрешено))
        self.assertTrue(гарнитуры.засечная_в_тексте(строка_новая_засечка))

    def test_сторож_не_ловит_гротески(self):
        """Сторож, который ругается на чистую строку, выключат первым же утром. Антиква ищется
        по границам слова: «Explora» — не «Lora», «sans-serif» — не «serif»."""
        for строка in ("  --шрифт-заголовков: Montserrat, system-ui, sans-serif;",
                       "  --шрифт-текста: Inter, ui-sans-serif;",
                       "Explora — гротеск, его берём",
                       "Открытые гротески: Montserrat, Open Sans, Jost"):
            with self.subTest(строка=строка):
                self.assertFalse(гарнитуры.засечная_в_тексте(строка), строка)


if __name__ == "__main__":
    unittest.main()
