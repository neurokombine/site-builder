"""Контракт карты: всё, что CLAUDE.md и как-работаем.md называют без ⏳, существует на диске.

Иначе нейросеть откроет несуществующий файл и решит, что система сломана.
"""
import re
import unittest
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[3]
ЯДРО = КОРЕНЬ / "ядро"
# Имя файла в бэктиках, с необязательным путём впереди: `прототип.md` и `ядро/прототип.md` —
# одно и то же имя. Группа 1 — путь, группа 2 — само имя.
ИМЯ = re.compile(r"`((?:[^`\s]*/)?)([\w\-]+\.(?:md|py))`")
РАБОЧИЕ = {"разведка.md", "референсы.md", "прототип.md", "дизайн.md", "журнал.md",
           "отчёт.md", "замеры.md", "_сводка.md", "profile.json", "README.md",
           "ЕСЛИ-СЛОМАЛОСЬ.md", "CLAUDE.md", "AGENTS.md", "index.html"}


def имена_к_проверке(текст: str) -> set[str]:
    """Имена файлов, которые обязаны лежать в ядре.

    Рабочие файлы человека (`сайты/<имя>/прототип.md`) в ядре не лежат — их пропускаем.
    Но ровно до тех пор, пока их назвали без пути: `ядро/прототип.md` — уже обещание файла
    ядра, и его проверяем, даже если имя совпало с рабочим.
    """
    имена = set()
    for путь, имя in ИМЯ.findall(текст):
        if имя in РАБОЧИЕ and путь != "ядро/":
            continue
        имена.add(имя)
    return имена


def названные_без_ожидания(текст: str, только_строки=None) -> set[str]:
    имена = set()
    for строка in текст.splitlines():
        if "⏳" in строка:
            continue
        if только_строки and not только_строки(строка):
            continue
        имена |= имена_к_проверке(строка)
    return имена


def пункты_списка(текст: str, начало: str) -> list[str]:
    """Собирает пункты списка целиком — вместе с переносами на следующие строки.

    Пункт дороги длиннее строки: имя файла нередко уезжает на вторую строку, и проверка
    по одной первой строке его не увидит. Продолжение — строка, начатая пробелами и не с «- ».
    """
    пункты: list[list[str]] = []
    текущий: list[str] | None = None
    for строка in текст.splitlines():
        голая = строка.strip()
        продолжение = строка[:1].isspace() and голая and not голая.startswith("- ")
        if текущий is not None and продолжение:
            текущий.append(голая)
            continue
        текущий = None
        if голая.startswith(начало):
            текущий = [голая]
            пункты.append(текущий)
    return ["\n".join(п) for п in пункты]


def существует_в_ядре(имя: str) -> bool:
    return (ЯДРО / имя).exists() or (ЯДРО / "скрипты" / имя).exists()


class КартаТесты(unittest.TestCase):
    def test_таблица_маршрута_в_claude_md(self):
        текст = (КОРЕНЬ / "CLAUDE.md").read_text(encoding="utf-8")
        строки_таблицы = lambda с: с.startswith("| ") and с.count("|") >= 5
        for имя in названные_без_ожидания(текст, строки_таблицы):
            with self.subTest(имя=имя):
                self.assertTrue(существует_в_ядре(имя), f"CLAUDE.md называет {имя} без ⏳, а файла нет")

    def test_строки_открыть_в_дороге(self):
        текст = (ЯДРО / "как-работаем.md").read_text(encoding="utf-8")
        for пункт in пункты_списка(текст, "- **Открыть:**"):
            if "⏳" in пункт:  # приедет следующим пакетом — сейчас файла и не ждём
                continue
            for имя in имена_к_проверке(пункт):
                with self.subTest(имя=имя):
                    self.assertTrue(существует_в_ядре(имя),
                                    f"как-работаем.md велит открыть {имя}, а файла нет")

    def test_пункт_собирается_вместе_с_переносом(self):
        текст = ("- **Открыть:** `ядро/первый.md` и ещё\n"
                 "  `ядро/второй.md` — хвост пункта\n"
                 "- **Делаем:** что-то другое\n")
        пункты = пункты_списка(текст, "- **Открыть:**")
        self.assertEqual(len(пункты), 1)
        self.assertEqual(имена_к_проверке(пункты[0]), {"первый.md", "второй.md"})

    def test_ожидание_на_второй_строке_снимает_весь_пункт(self):
        текст = ("- **Открыть:** `ядро/первый.md` и\n"
                 "  `ядро/второй.md` ⏳ — приедет позже\n")
        пункт, = пункты_списка(текст, "- **Открыть:**")
        self.assertIn("⏳", пункт)

    def test_рабочий_файл_с_путём_ядра_всё_равно_проверяется(self):
        self.assertEqual(имена_к_проверке("`сайты/<имя>/прототип.md`"), set())
        self.assertEqual(имена_к_проверке("`ядро/прототип.md`"), {"прототип.md"})

    def test_каждый_файл_ядра_назван_в_карте(self):
        карта = (КОРЕНЬ / "CLAUDE.md").read_text(encoding="utf-8")
        for файл in ЯДРО.glob("*.md"):
            with self.subTest(файл=файл.name):
                self.assertIn(f"`{файл.name}`", карта, f"{файл.name} лежит в ядре, но CLAUDE.md о нём молчит")


if __name__ == "__main__":
    unittest.main()
