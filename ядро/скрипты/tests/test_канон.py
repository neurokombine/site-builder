"""Сторож канона: каждое правило в `ядро/канон.md` либо стоит в коде, либо честно помечено «глаза».

Зачем. Канон — единственная страница, по которой принимается собранный сайт: одна таблица,
одна строка на правило. Документ и код расходятся молча — правило переименовали в скрипте,
а в каноне осталось прежнее имя, и человек ищет находку, которой не бывает. Сторож не даёт
им разойтись: имя находки в третьей колонке обязано дословно стоять в `проверить.py` или
`флаги_дизайна.py`.

Почему колонка разбирается не регуляркой из плана. Имя находки — это её заголовок целиком
(«Кнопка не видна как кнопка»): с пробелами, прописными и запятыми. Строку таблицы режем по
разделителю и берём последнюю ячейку — так в первых двух колонках можно свободно писать
обратные кавычки (имена файлов, токены), и разбор от этого не съезжает.

Запуск из корня репозитория:
    .venv/bin/python -m unittest discover -s ядро/скрипты/tests -t .
"""
import re
import unittest
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[3]
СКРИПТЫ = КОРЕНЬ / "ядро" / "скрипты"
КАНОН = КОРЕНЬ / "ядро" / "канон.md"

# Правило, которого скрипт не ловит: смотрим по снимкам. Пишется без обратных кавычек —
# это не имя находки, а честное «здесь скрипта нет».
ГЛАЗА = "глаза"
В_КАВЫЧКАХ = re.compile(r"^`(.+)`$")
ПОТОЛОК_СТРОК = 150     # документы ядра не растут, а дробятся
ШАПКА = ["правило", "как проверяется", "находка"]
РАЗДЕЛЫ = ("Текст и шрифты", "Цвет и кнопка", "Кадр и экран", "Ритм страницы",
           "Однородность", "Контракт свободного экрана")
РИТМ = ("Соседние экраны одной светлоты", "Карточка в тон фона своей секции",
        "Две главные кнопки на одном экране")
# Девять находок Контракта В (задача гибрида): свободную вёрстку держат они, и канон обязан
# называть их теми же словами, какими их называет скрипт.
КОНТРАКТ_В = ("Первая строка экрана не по контракту", "В экране больше одного стиля",
              "Стиль экрана не сразу после секции",
              "Стиль экрана без префикса своего id", "В стиле экрана цвет не из профиля",
              "В стиле экрана кегль, скругление или тень мимо токенов",
              "В стиле экрана задан шрифт", "На экране две связи", "Картинка экрана без обёртки")
# Шесть находок однородности: их считает `однородность.py` по вычисленным стилям всей страницы.
ОДНОРОДНОСТЬ = ("Шрифтов больше двух", "Кегль заголовка или текста выбивается из шкалы",
                "Скругления карточек или кнопок разные", "Тени у карточек то есть, то нет",
                "Цвет не из палитры профиля", "Главные кнопки разной формы")
# Где живут имена находок: канон сверяется с этими файлами, и ни с какими другими.
КОД = ("проверить.py", "флаги_дизайна.py", "однородность.py")


def строки_таблицы(текст: str) -> list[list[str]]:
    """Строки канона: три ячейки каждая. Шапка и разделитель `|---|` сюда не попадают."""
    строки = []
    for строка in текст.splitlines():
        голая = строка.strip()
        if not голая.startswith("|") or not голая.endswith("|"):
            continue
        ячейки = [я.strip() for я in голая.strip("|").split("|")]
        if len(ячейки) != 3 or set("".join(ячейки)) <= set("-: "):
            continue
        строки.append(ячейки)
    return строки


class КанонТесты(unittest.TestCase):
    def setUp(self):
        self.текст = КАНОН.read_text(encoding="utf-8")
        разобранные = строки_таблицы(self.текст)
        шапки = [с for с in разобранные if [я.lower() for я in с] == ШАПКА]
        self.assertEqual(len(шапки), len(РАЗДЕЛЫ),
                         f"шапка «{' | '.join(ШАПКА)}» должна стоять у каждого из "
                         f"{len(РАЗДЕЛЫ)} разделов — нашлось {len(шапки)}")
        self.строки = [с for с in разобранные if с not in шапки]

    def test_канон_не_пустой(self):
        """Сторож, который ничего не разобрал, не сторож."""
        self.assertGreaterEqual(len(self.строки), 20,
                                "канон разобрался в две строки — значит, разбор съехал, а не канон похудел")

    def test_каждое_правило_с_кодом_есть_в_коде(self):
        код_скриптов = "".join((СКРИПТЫ / имя).read_text(encoding="utf-8") for имя in КОД)
        for правило, _как, находка in self.строки:
            with self.subTest(правило=правило):
                if находка == ГЛАЗА:
                    continue
                совпало = В_КАВЫЧКАХ.match(находка)
                self.assertTrue(совпало, f"третья колонка «{находка}» — ни имя находки в обратных "
                                         f"кавычках, ни «{ГЛАЗА}»")
                self.assertIn(f'"{совпало.group(1)}"', код_скриптов, правило)

    def test_ритм_в_каноне(self):
        for код in РИТМ:
            self.assertIn(f"`{код}`", self.текст, f"канон молчит о находке «{код}»")

    def test_контракт_свободного_экрана_в_каноне(self):
        for код in КОНТРАКТ_В:
            self.assertIn(f"`{код}`", self.текст, f"канон молчит о находке «{код}»")

    def test_однородность_в_каноне(self):
        for код in ОДНОРОДНОСТЬ:
            self.assertIn(f"`{код}`", self.текст, f"канон молчит о находке «{код}»")

    def test_есть_все_четыре_раздела(self):
        for раздел in РАЗДЕЛЫ:
            self.assertIn(раздел, self.текст, f"в каноне нет раздела «{раздел}»")

    def test_канон_не_растёт(self):
        сколько = len(self.текст.splitlines())
        self.assertLessEqual(сколько, ПОТОЛОК_СТРОК,
                             f"канон на {сколько} строк при потолке {ПОТОЛОК_СТРОК}: дробить, а не растить")

    def test_канон_назван_в_карте(self):
        карта = (КОРЕНЬ / "CLAUDE.md").read_text(encoding="utf-8")
        self.assertIn("`канон.md`", карта, "канон лежит в ядре, но CLAUDE.md о нём молчит")


if __name__ == "__main__":
    unittest.main()
