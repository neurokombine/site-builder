class ОтПапкиРаботы(unittest.TestCase):
    """От папки работы канон подставляется сам — второй команды человек держать не обязан."""

    def setUp(self):
        self._в = tempfile.TemporaryDirectory()
        корень = Path(self._в.name)
        self.addCleanup(self._в.cleanup)
        self.папка = корень / "сайт-проба"
        self.профиль = корень / "проба"
        self.папка.mkdir()
        self.профиль.mkdir()
        for имя in ("селфи-1.jpg", "селфи-2.jpg", "селфи-3.jpg"):
            снимок(self.профиль / имя)
        (self.профиль / "profile.json").write_text(
            json.dumps(ПРОФИЛЬ, ensure_ascii=False), encoding="utf-8")
        (self.папка / "прототип.md").write_text(
            "# Прототип: проба\n\n- Пресет: визитка\n- Профиль: проба\n\n"
            "## Экран 1 · Первый экран · статус: принят\n"
            "Задача экрана: показать мастера\n"
            "- Заголовок: Электрика без сюрпризов\n  - или: Проводка под ключ\n"
            "- Подзаголовок: Работаю по квартирам\n- Кнопка: Написать\n"
            "- Картинка: мастер у щитка\n"
            "- Почему этот экран: доверие\n- Не делаем: стоковых улыбок\n", encoding="utf-8")
        (self.папка / "дизайн.md").write_text(
            "# Дизайн-система: проба\n\n- Профиль: проба\n\n## Решения\n"
            "Выбран: Вариант 1 «Светлый щиток»\n"
            "- Схема первого экрана: разворот\n- Сторона: справа\n- Картинка: фото\n"
            "- Лицо смотрит: влево\n- Доминанта: светлая\n- Атмосфера: чисто\n", encoding="utf-8")

    def test_внешность_подставилась_сама(self):
        з, найденное = заказ.заказ_для_сайта(self.папка)
        self.assertIn("лицо и причёска строго с них", з["промт"])
        self.assertIn("Никогда: галстук", з["промт"])
        self.assertEqual(len(з["рефы"]), 3)
        self.assertEqual(найденное, [])

    def test_снимки_ушли_образцами_в_кисть(self):
        з, _ = заказ.заказ_для_сайта(self.папка)
        for путь in з["рефы"]:
            self.assertTrue(Path(путь).is_file(), путь)

    def test_блок_стоит_раньше_фона_и_в_настоящем_заказе(self):
        з, _ = заказ.заказ_для_сайта(self.папка)
        место = заказ.место_внешности(з)
        self.assertGreater(место, 0)
        строки = [с["строка"] for с in з["строки"]]
        фон = next(н for н, с in enumerate(строки) if с.startswith("Фон кадра"))
        крупность = next(н for н, с in enumerate(строки) if с.startswith("Крупность"))
        self.assertLess(место, фон)
        self.assertLess(место, крупность)

    def test_без_снимков_красная_находка_и_код_1(self):
        данные = json.loads((self.профиль / "profile.json").read_text(encoding="utf-8"))
        данные["внешность"]["селфи"] = []
        (self.профиль / "profile.json").write_text(json.dumps(данные, ensure_ascii=False),
                                                   encoding="utf-8")
        вывод = io.StringIO()
        with contextlib.redirect_stdout(вывод):
            код = заказ.main_с_аргументами([str(self.папка), "--без-журнала"])
        self.assertEqual(код, 1)
        self.assertIn("Нет ваших снимков", вывод.getvalue())

    def test_свои_рефы_из_команды_перебивают_профиль(self):
        з, найденное = заказ.заказ_для_сайта(self.папка, рефы=[str(self.профиль / "селфи-1.jpg")])
        self.assertEqual(len(з["рефы"]), 1)
        self.assertTrue(any("из команды" in н["что"] for н in найденное), найденное)

    def test_кадру_без_человека_канон_не_вменяют(self):
        з, найденное = заказ.заказ_для_сайта(self.папка, схема="товар-крупно")
        self.assertEqual(заказ.место_внешности(з), -1)
        self.assertFalse([н for н in найденное if "снимк" in н["что"].lower()])


class ВПрофиле(unittest.TestCase):
    """Внешность — поля профиля, и профиль сам говорит, чего в них не хватает."""

