"""Единый список засечных гарнитур — чтобы его пополняли в одном месте, а не искали по коду.

Правило владелицы (15.09.2026, дословно): «Никаких шрифтов с засечками. Никогда. На экране
читаются отвратительно» — без исключений: ни в заголовках, ни в тексте, ни как один из
вариантов на выбор.

Список неполный по построению (шрифтов на свете больше, чем можно перечислить) — он покрывает
антиквы, которые реально всплывали в образцах и на донорских сайтах. Сюда же дописывать новые,
если найдётся ещё одна.

Отдельно от этого списка — распознавание системных шрифтов доноров
(`ресёрч_ниши.СИСТЕМНЫЕ_ШРИФТЫ`): там имя нужно, чтобы ОПОЗНАТЬ шрифт, а не чтобы его
предложить, и этот файл его не трогает.
"""
from __future__ import annotations

import re

# Конкретные антиквы, в нижнем регистре без кавычек. Сравниваются с ИМЕНЕМ ЦЕЛИКОМ, а не с
# обрывком строки: «Lora» внутри «Explora» — это другой шрифт, и Explora гротеск. Поэтому строку
# объявления сначала режем по запятым на отдельные имена, а потом каждое имя сверяем целиком —
# либо оно равно засечному, либо начинается с него и дальше идёт пробел («Georgia Pro»,
# «Lora Italic» — та же антиква в другом начертании).
ИМЕНА = {
    "georgia", "times new roman", "times",
    "playfair display", "playfair",
    "merriweather", "lora", "pt serif", "garamond", "cormorant garamond", "cormorant",
    "cambria", "bodoni", "didot", "baskerville",
    "crimson text", "crimson pro", "crimson",
    "spectral", "source serif pro", "source serif",
    "noto serif", "roboto slab",
}

# Родовые CSS-имена семейства «с засечками». Проверяются НЕ вхождением подстроки, а полным
# совпадением одного элемента через запятую: `serif` как подстрока ловит и `sans-serif`,
# и `ui-sans-serif` — оба гротески, и их обязана пропустить.
РОДОВЫЕ = {"serif", "ui-serif"}

# Полный список одним куском — для внешнего перебора (тесты, отчёты о поддержанных именах).
ЗАСЕЧНЫЕ = ИМЕНА | РОДОВЫЕ

# Чем заменить конкретную антикву — гротеск с похожим характером, а не первый попавшийся.
# Строгие геометричные афиши (Didot, Bodoni, Playfair, Garamond, Baskerville) — на Montserrat,
# он тоже держит крупный заголовок с характером. Своя пара есть у Roboto Slab — родной гротеск
# той же семьи. Для остального — нейтральный гуманистический гротеск по умолчанию.
_ЗАМЕНЫ = {
    "playfair display": "Montserrat", "playfair": "Montserrat",
    "cormorant garamond": "Montserrat", "cormorant": "Montserrat",
    "garamond": "Montserrat", "bodoni": "Montserrat", "didot": "Montserrat",
    "baskerville": "Montserrat",
    "roboto slab": "Roboto",
}
ГРОТЕСК_ПО_УМОЛЧАНИЮ = "Open Sans"


def _к_сравнению(имя: str | None) -> str:
    return (имя or "").strip().strip("\"'").lower()


def _токены(сравнение: str) -> list[str]:
    """Строка объявления шрифта («X, Y, sans-serif») на отдельные имена через запятую, каждое —
    без кавычек и краевых пробелов. Так родовое имя сравнивается ЦЕЛИКОМ, а не подстрокой."""
    return [т.strip().strip("\"'") for т in сравнение.split(",")]


def _это_имя(токен: str, засечное: str) -> bool:
    """Одно имя из объявления — это та самая антиква? Целиком или та же антиква в другом
    начертании («Georgia Pro»). Обрывок слова не считается: «Explora» — не «Lora»."""
    return токен == засечное or токен.startswith(засечное + " ")


def засечная(имя: str | None) -> bool:
    """Имя гарнитуры, как оно записано в CSS или в замерах донора — засечная?

    Строку режем по запятым и каждое имя сверяем целиком: и с конкретными антиквами, и с
    родовыми CSS-именами (`serif`, `ui-serif`). Целиком — потому что подстрока врёт в обе
    стороны: «Montserrat, sans-serif» ловилась бы на «serif» внутри «sans-serif», а «Explora» —
    на «Lora», и оба гротеска попали бы под замену. Пустое имя — не засечная."""
    сравнение = _к_сравнению(имя)
    if not сравнение:
        return False
    for токен in _токены(сравнение):
        if токен in РОДОВЫЕ or any(_это_имя(токен, з) for з in ИМЕНА):
            return True
    return False


def ближайший_гротеск(имя: str | None) -> str:
    """Чем заменить засечную гарнитуру — по конкретному имени, умолчание — нейтральный гротеск."""
    токены = _токены(_к_сравнению(имя))
    for засечная_гарнитура, замена in _ЗАМЕНЫ.items():
        if any(_это_имя(т, засечная_гарнитура) for т in токены):
            return замена
    return ГРОТЕСК_ПО_УМОЛЧАНИЮ


# Две разные работы, и путать их нельзя.
# `засечная` смотрит на ОБЪЯВЛЕНИЕ шрифта — «Montserrat, sans-serif», значение из профиля, замер
# донора: там имена стоят через запятую, и каждое сверяется целиком.
# `засечная_в_тексте` смотрит на ПРОИЗВОЛЬНУЮ СТРОКУ — строку документа, комментарий, строку CSS
# вместе с именем переменной: там антикву надо найти внутри фразы, но по границам слова, иначе
# «Explora» поймается на «Lora», а «sans-serif» — на «serif».
_ГРАНИЦА = r"(?<![0-9A-Za-zА-Яа-яЁё])%s(?![0-9A-Za-zА-Яа-яЁё])"
_В_ТЕКСТЕ = [re.compile(_ГРАНИЦА % re.escape(и), re.IGNORECASE) for и in sorted(ИМЕНА)]
# Родовое `serif` в тексте: перед ним не должно быть ни буквы, ни дефиса — дефис значит
# «sans-serif» или «ui-sans-serif», а это гротески. `ui-serif` ловится отдельным правилом.
_РОДОВОЕ_В_ТЕКСТЕ = [re.compile(r"(?<![0-9A-Za-zА-Яа-яЁё\-])serif\b", re.IGNORECASE),
                     re.compile(r"(?<![0-9A-Za-zА-Яа-яЁё])ui-serif\b", re.IGNORECASE)]


def засечная_в_тексте(строка: str | None) -> bool:
    """Есть ли в произвольной строке упоминание засечной гарнитуры — по границам слова.

    Этим живёт сторож ядра: он читает документы и фикстуры построчно, и антиква в них
    встречается и внутри фразы («возьмите Playfair Display»), и внутри объявления вместе
    с именем переменной («--шрифт-заголовков: Georgia, serif;»)."""
    if not строка:
        return False
    return (any(п.search(строка) for п in _В_ТЕКСТЕ)
            or any(п.search(строка) for п in _РОДОВОЕ_В_ТЕКСТЕ))
