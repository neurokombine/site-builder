def примерка(блоки: list[dict], площадка: str, до_сайта: str = "") -> str:
    """Все блоки подряд в обёртке, похожей на площадку: корень 10 px, `text-center`, тема со
    своими `blockquote`/`ul`/`a`. Так видно, держит ли блок оборону, не заходя на площадку.
    Картинки без адреса показываем из папки сайта — примерка нужна и до заливки."""
    def картинки(html: str) -> str:
        return ПЛЕЙСХОЛДЕР_ИЩИ.sub(lambda м: f"{до_сайта}/{м.group(1)}" if до_сайта else м.group(1), html)
    тела = "\n".join(
        f'<div class="lt-block"><div class="container text-center">\n{картинки(б["html"])}\n</div></div>'
        for б in блоки)
    return ("<!DOCTYPE html>\n<html lang=\"ru\">\n<head>\n<meta charset=\"utf-8\">\n"
            "<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\n"
            f"<title>Примерка блоков — {escape(ПЛОЩАДКИ[площадка]['имя'])}</title>\n"
            "<style>\n"
            "html{font-size:10px}body{margin:0;font:14px/1.42 Georgia,serif;color:#333;background:#fff}\n"
            ".text-center{text-align:center}\n"
            "blockquote{padding:10px 20px;margin:0 0 20px;font-size:17.5px;border-left:5px solid #eee}\n"
            "ul,ol{margin-top:0;margin-bottom:10px}figure{margin:1em 40px}\n"
            "h1,h2,h3{margin-top:20px;margin-bottom:10px;font-weight:500;line-height:1.1}\n"
            "p{margin:0 0 10px}a{color:#337ab7}a:hover{color:#23527c;text-decoration:underline}\n"
            "</style>\n</head>\n<body>\n" + тела + "\n</body>\n</html>\n")


