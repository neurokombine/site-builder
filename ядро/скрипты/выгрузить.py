def построить_парсер() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(description="Собранный сайт → блоки «HTML-код» для GetCourse или Тильды: "
                                            "один экран = один блок, стили внутри блока.")
    p.add_argument("работа", help="папка работы сайты/<имя> (или её папка сайт/)")
    вид = p.add_mutually_exclusive_group(required=True)
    вид.add_argument("--getcourse", action="store_const", const="getcourse", dest="площадка")
    вид.add_argument("--tilda", action="store_const", const="tilda", dest="площадка")
    p.add_argument("--ссылки", metavar="JSON", help="адреса залитых файлов: {\"img/фото.webp\": \"https://…\"}")
