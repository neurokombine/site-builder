"""Выгрузка на площадку: собранный сайт → блоки «HTML-код» для GetCourse или Тильды.

Берёт то, что уже собрал `собрать.py` (`сайты/<имя>/сайт/index.html` и `style.css`), и режет
страницу по экранам: **один экран = один самодостаточный блок**. В каждом блоке — свои стили и
общие токены дизайн-системы, всё под классом-обёрткой работы (`.сб-<имя>`): тема площадки не
протекает в блок, блок не протекает в соседей. Картинки и ролики площадка берёт по прямым
ссылкам, поэтому в блоке сначала стоит плейсхолдер `{{КАРТИНКА:img/…}}`, а список файлов для
заливки лежит рядом (`картинки-залить.md`). Залили, собрали адреса в JSON — запуск с
`--ссылки` подставляет их. Не хватает хоть одного адреса — блок помечен `НЕ-ГОТОВ` и находка 🔴.

Рядом ложатся `ИНСТРУКЦИЯ.md` (как вставлять, по шагам — её читает нейросеть, работающая в
браузере) и `примерка.html` — все блоки подряд внутри «враждебной» обёртки, как их увидит
площадка: корневой кегль 10 px, обёртка `text-center`, тема со своими `blockquote` и `ul`.
Рецепт площадок целиком — `ядро/площадки.md`.

Запуск:
    .venv/bin/python ядро/скрипты/выгрузить.py сайты/моё-дело --getcourse
    .venv/bin/python ядро/скрипты/выгрузить.py сайты/моё-дело --getcourse --ссылки сайты/моё-дело/на-площадку/getcourse/ссылки.json
    .venv/bin/python ядро/скрипты/выгрузить.py сайты/моё-дело --tilda --ссылки <json>

⛔ Сама ничего никуда не отправляет: только файлы в `сайты/<имя>/на-площадку/<площадка>/`.
Правки по-прежнему делаются в экранах работы («витрина и цех»): поправили → `собрать.py` →
снова `выгрузить.py` → заменили изменившийся блок на площадке.
"""
