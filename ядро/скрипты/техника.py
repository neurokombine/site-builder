"""Техническая приёмка сайта: как быстро он открывается и как выглядит на разных экранах.

Зачем. Обычная проверка (`проверить.py`) смотрит страницу в двух размерах и на быстром
соединении — так, как её видит автор за своим компьютером. Живой человек открывает ссылку из
мессенджера на телефоне, в метро, с одной палочкой сигнала, и часто в Safari. Здесь — то, что
видит он:

- **скорость на медленном мобильном интернете** — телефон, 4G со слабым сигналом, процессор
  вчетверо медленнее компьютера (так мерит и сама Google). Три числа: когда показался первый
  экран (LCP), прыгала ли вёрстка при загрузке (CLS) и сколько всего скачано;
- **картинки под экран** — файл намного шире, чем показывается; ленивая загрузка не там, где
  нужно; место под картинку не держится, пока она грузится; сколько весят шрифты;
- **ещё пять экранов** — маленький телефон 360, планшет 768, ноутбук 1280, телефон лёжа и
  iPhone в Safari (движок WebKit): ездит ли страница вбок, вылезают ли картинки, не мельчит ли
  текст; снимок каждого кладётся рядом с отчётом;
- **оценка Google PageSpeed** — только по живому адресу: папку на вашем компьютере Google не
  видит. Открытый вызов без ключа; нет сети или кончился лимит — честная ℹ️, а не падение.

Запускается флагом: `проверить.py <папка или адрес> --техника`. Отдельно, а не всегда, потому что
замер на медленном интернете честно длится медленно — обычная проверка остаётся около минуты.
Руками этот файл не запускают.

Пороги — Core Web Vitals (web.dev, проверено 09.2026): первый экран до 2,5 с — хорошо, дольше
4 с — плохо; сдвиг вёрстки до 0,1 — хорошо, больше 0,25 — плохо.
"""
