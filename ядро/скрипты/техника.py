# ── Что меряем в браузере ────────────────────────────────────────────────────────────────

# Ставится в страницу ДО её загрузки: наблюдатели браузера за самым крупным элементом первого
# экрана и за сдвигами вёрстки. `buffered: true` отдаёт и то, что случилось до подписки.
НАБЛЮДАТЕЛЬ_JS = r"""
(() => {
  const т = window.__техника = {lcp: null, первым: null, cls: 0, сдвиги: []};
  const описать = у => у.tagName.toLowerCase() + (у.id ? '#' + у.id : '')
    + (у.classList && у.classList[0] ? '.' + у.classList[0] : '');
  try {
    new PerformanceObserver(список => {
      for (const з of список.getEntries()) {
        т.lcp = з.startTime;
        const эл = з.element;
        т.первым = эл ? {
          тег: эл.tagName.toLowerCase(),
          адрес: (эл.currentSrc || эл.getAttribute('src') || з.url || '').slice(0, 160),
          текст: эл.tagName === 'IMG' ? '' : (эл.innerText || '').trim().slice(0, 60),
          ленивая: эл.getAttribute('loading') === 'lazy',
        } : (з.url ? {тег: 'фон', адрес: з.url.slice(0, 160), текст: '', ленивая: false} : null);
      }
    }).observe({type: 'largest-contentful-paint', buffered: true});
  } catch (e) {}
  try {
    new PerformanceObserver(список => {
      for (const з of список.getEntries()) {
        if (з.hadRecentInput) continue;
        т.cls += з.value;
        for (const и of (з.sources || [])) {
          if (и.node && и.node.nodeType === 1) т.сдвиги.push({кто: описать(и.node), на: з.value});
        }
      }
    }).observe({type: 'layout-shift', buffered: true});
  } catch (e) {}
})();
"""

# Картинки под экран. Меряется на телефоне, когда страница уже прокручена до низа и ленивые
# картинки догрузились. Координаты — от верха страницы, а не окна.
КАРТИНКИ_JS = r"""
(значок) => {
  const dpr = window.devicePixelRatio || 1;
  const экран = document.documentElement.clientHeight || innerHeight;
  const итог = {dpr, экран, крупные: [], без_лени: [], ленивые_сверху: [], без_размеров: []};
  for (const к of Array.from(document.images)) {
    const r = к.getBoundingClientRect();
    const cs = getComputedStyle(к);
    if (cs.display === 'none' || cs.visibility === 'hidden') continue;
    if (r.width < значок || r.height < значок) continue;
    const адрес = (к.currentSrc || к.getAttribute('src') || '').slice(0, 160);
    const векторная = /^data:image\/svg|\.svg(\?|#|$)/i.test(адрес);
    const верх = r.top + scrollY;
    const ленивая = к.getAttribute('loading') === 'lazy';
    if (верх >= экран && !ленивая) итог.без_лени.push({адрес, верх: Math.round(верх)});
    if (верх < экран && ленивая) итог.ленивые_сверху.push({адрес, верх: Math.round(верх)});
    if (!векторная && к.complete && к.naturalWidth > 0 && к.naturalHeight > 0) {
      // Кадр «cover» обрезан рамкой: показывается шире рамки, и нужен ему файл шире.
      const пропорция = к.naturalWidth / к.naturalHeight;
      const показ = cs.objectFit === 'cover' ? Math.max(r.width, r.height * пропорция) : r.width;
      const нужно = показ * dpr;
      if (к.naturalWidth > нужно * __ЗАПАС__) {
        итог.крупные.push({адрес, файл: к.naturalWidth, показ: Math.round(показ),
                           нужно: Math.round(нужно)});
      }
    }
    // Держится ли место под картинку до её загрузки: ставим рядом двойника без файла и
    // смотрим его высоту. Нет ни width/height, ни пропорции, ни высоты в стиле — у двойника 0.
    if (к.parentNode) {
      const двойник = к.cloneNode(false);
      for (const имя of ['src', 'srcset', 'alt', 'id']) двойник.removeAttribute(имя);
      двойник.style.visibility = 'hidden';
      к.parentNode.insertBefore(двойник, к.nextSibling);
      const высота = двойник.getBoundingClientRect().height;
      двойник.remove();
      if (высота < 2) итог.без_размеров.push({адрес, верх: Math.round(верх)});
    }
  }
  return итог;
}
""".replace("__ЗАПАС__", str(ЗАПАС_КАРТИНКИ))


def _первая_строка(ошибка: Exception) -> str:
    return f"{type(ошибка).__name__}: {ошибка}".split("\n")[0][:200]


def замерить_скорость(браузер, адрес: str) -> dict:
    """Открыть страницу на телефоне при медленном интернете и медленном процессоре.

    Работает только в Chromium: троттлинг сети и процессора — его протокол отладки (CDP).
    Кэш выключен — меряем первый визит, а не повторный.
    """
    контекст = глаза.контекст(браузер, "телефон")
    ответы: dict[str, dict] = {}
    try:
        страница = контекст.new_page()
        страница.add_init_script(НАБЛЮДАТЕЛЬ_JS)
        cdp = контекст.new_cdp_session(страница)
        cdp.send("Network.enable")
        cdp.send("Network.setCacheDisabled", {"cacheDisabled": True})
        cdp.send("Network.emulateNetworkConditions", СЕТЬ_МЕДЛЕННАЯ)
        cdp.send("Emulation.setCPUThrottlingRate", {"rate": ПРОЦЕССОР_МЕДЛЕННЕЕ})

        def при_ответе(с):
            запись = ответы.setdefault(с["requestId"], {})
            запись.update(адрес=с["response"].get("url", ""), тип=с.get("type", ""))

        def при_конце(с):
            ответы.setdefault(с["requestId"], {})["байт"] = int(с.get("encodedDataLength") or 0)

        cdp.on("Network.responseReceived", при_ответе)
        cdp.on("Network.loadingFinished", при_конце)

        начало = time.time()
        дождались = глаза.открыть(страница, адрес, ТАЙМАУТ_МЕДЛЕННОЙ_ЗАГРУЗКИ_МС)
        загрузка_с = time.time() - начало
        try:
            страница.wait_for_load_state("networkidle", timeout=ТАЙМАУТ_ТИШИНЫ_МС)
        except Exception:
            pass  # трекеры и чаты не затихают никогда
        страница.wait_for_timeout(1500)   # поздние сдвиги вёрстки случаются уже после «загрузилась»
        т = страница.evaluate("() => window.__техника || null") or {}
    except Exception as ошибка:
        return {"не_вышло": _первая_строка(ошибка)}
    finally:
        контекст.close()

    файлы = [о for о in ответы.values() if о.get("адрес", "").startswith("http")]
    по_типам: dict[str, int] = {}
    for о in файлы:
        тип = ТИПЫ_СЛОВАМИ.get(о.get("тип", ""), "прочее")
        по_типам[тип] = по_типам.get(тип, 0) + о.get("байт", 0)
    шрифты = sorted(({"адрес": о["адрес"], "байт": о.get("байт", 0)}
                     for о in файлы if о.get("тип") == "Font"), key=lambda ш: -ш["байт"])
    сдвиги: dict[str, float] = {}
    for с in т.get("сдвиги") or []:
        сдвиги[с["кто"]] = сдвиги.get(с["кто"], 0) + с["на"]
    return {
        "lcp_с": round(т["lcp"] / 1000, 2) if т.get("lcp") is not None else None,
        "первым": т.get("первым"),
        "cls": round(т.get("cls") or 0, 3),
        "сдвигались": [к for к, _ in sorted(сдвиги.items(), key=lambda п: -п[1])[:5]],
        "загрузка_с": round(загрузка_с, 1),
        "загрузка_не_кончилась": not дождались,
        "скачано": {"всего": sum(по_типам.values()), "файлов": len(файлы),
                    "по_типам": dict(sorted(по_типам.items(), key=lambda п: -п[1]))},
        "шрифты": шрифты,
        "файлы": [{"адрес": о["адрес"][:200], "тип": о.get("тип", ""), "байт": о.get("байт", 0)}
                  for о in файлы],
    }


def замерить_картинки(браузер, адрес: str) -> dict:
    """Картинки под экран телефона: догружаем ленивые прокруткой до низа и меряем все разом."""
    контекст = глаза.контекст(браузер, "телефон")
    try:
        страница = контекст.new_page()
        глаза.открыть(страница, адрес)
        высота = страница.evaluate("() => document.documentElement.scrollHeight")
        шаг = 700
        for у in range(0, int(высота) + шаг, шаг):
            страница.evaluate(f"() => window.scrollTo(0, {у})")
            страница.wait_for_timeout(80)
        try:
            страница.wait_for_load_state("networkidle", timeout=5000)
        except Exception:
            pass
        return страница.evaluate(КАРТИНКИ_JS, КАРТИНКА_ЗНАЧОК_PX)
    except Exception as ошибка:
        return {"не_вышло": _первая_строка(ошибка)}
    finally:
        контекст.close()


def снять_safari(движок, адрес: str, куда: Path, ждать_сек: float) -> dict:
    """Тот же телефон в WebKit — движке Safari. Движка нет — так и говорим, не падаем."""
    if движок is None:
        return {"статус": "нет_движка", "почему": "движок браузеров не передан"}
    try:
        браузер = движок.webkit.launch(headless=True)
    except Exception as ошибка:
        return {"статус": "нет_движка", "почему": _первая_строка(ошибка)}
    try:
        return глаза.снять_размер(браузер, адрес, SAFARI, куда, ждать_сек)
    except Exception as ошибка:
        return {"статус": "ошибка", "не_пустило": {"вид": "ошибка", "признак": _первая_строка(ошибка)}}
    finally:
        браузер.close()


# ── Google PageSpeed Insights ────────────────────────────────────────────────────────────

def разобрать_google(данные: dict) -> dict:
    """Ответ PageSpeed — в четыре числа и, если Google знает живых посетителей, их опыт."""
    маяк = данные.get("lighthouseResult") or {}
    оценка = ((маяк.get("categories") or {}).get("performance") or {}).get("score")
    аудиты = маяк.get("audits") or {}

    def число(имя):
        return (аудиты.get(имя) or {}).get("numericValue")

    lcp = число("largest-contentful-paint")
    итог = {
        "оценка": None if оценка is None else round(оценка * 100),
        "lcp_с": None if lcp is None else round(lcp / 1000, 1),
        "cls": число("cumulative-layout-shift"),
        "вес": число("total-byte-weight"),
        "живые_люди": None,
    }
    поле = (данные.get("loadingExperience") or {}).get("metrics") or {}
    живой_lcp = (поле.get("LARGEST_CONTENTFUL_PAINT_MS") or {}).get("percentile")
    if живой_lcp:
        итог["живые_люди"] = {"lcp_с": round(живой_lcp / 1000, 1)}
    return итог


def спросить_google(адрес: str, таймаут: float = ТАЙМАУТ_GOOGLE_СЕК) -> dict:
    """PageSpeed Insights для телефона. Ключ необязателен: без него общий лимит, и он кончается."""
    параметры = {"url": адрес, "strategy": "mobile", "category": "performance", "locale": "ru"}
    ключ = os.environ.get(КЛЮЧ_PAGESPEED, "").strip()
    if ключ:
        параметры["key"] = ключ
    запрос = urllib.request.Request(f"{PAGESPEED}?{urllib.parse.urlencode(параметры)}",
                                    headers={"User-Agent": "site-builder"})
    try:
        with urllib.request.urlopen(запрос, timeout=таймаут) as ответ:
            return разобрать_google(json.loads(ответ.read().decode("utf-8")))
    except urllib.error.HTTPError as ошибка:
        if ошибка.code == 429:
            return {"не_вышло": "у Google кончился общий лимит проверок без ключа"}
        try:
            текст = json.loads(ошибка.read().decode("utf-8"))["error"]["message"][:160]
        except Exception:
            текст = str(ошибка)
        return {"не_вышло": f"Google ответил {ошибка.code}: {текст}"}
    except Exception as ошибка:
        return {"не_вышло": f"до Google не достучались — {_первая_строка(ошибка)}"}


# ── Всё вместе ───────────────────────────────────────────────────────────────────────────

def снять(браузер, адрес: str, куда: Path, *, живой: bool, движок=None,
          ждать_сек: float = 1.0, google: bool = True) -> dict:
    """Техническая приёмка целиком. `браузер` — Chromium; `движок` — объект Playwright, из
    которого поднимается WebKit для Safari. Google спрашиваем параллельно: он думает дольше всех."""
    куда = Path(куда)
    итог: dict = {"живой": живой, "google": None}
    поток = None
    if живой and google:
        ответ_google: dict = {}
        поток = threading.Thread(target=lambda: ответ_google.update(спросить_google(адрес)),
                                 daemon=True)
        поток.start()

    итог["скорость"] = замерить_скорость(браузер, адрес)
    итог["картинки"] = замерить_картинки(браузер, адрес)
    итог["экраны"] = {размер: глаза.снять_размер(браузер, адрес, размер, куда, ждать_сек)
                      for размер in ДОП_ЭКРАНЫ}
    итог["экраны"][SAFARI] = снять_safari(движок, адрес, куда, ждать_сек)

    if поток is not None:
        поток.join(timeout=ТАЙМАУТ_GOOGLE_СЕК + 5)
        итог["google"] = ответ_google or {"не_вышло": "Google не ответил вовремя"}
    return итог


# ── Находки ──────────────────────────────────────────────────────────────────────────────

def секунды(число: float) -> str:
    return f"{число:.1f}".replace(".", ",") + " с"


def доля(число: float) -> str:
    return f"{число:.2f}".replace(".", ",")


def вес(байты: int) -> str:
    if байты >= 1024 * 1024:
        return f"{байты / 1024 / 1024:.1f}".replace(".", ",") + " МБ"
    return f"{round(байты / 1024)} КБ"


def имя_файла(адрес: str) -> str:
    """Человеку — хвост адреса, а не служебный порт локального сервера."""
    if адрес.startswith("data:"):
        return "картинка внутри страницы (data)"
    путь = urllib.parse.unquote(urllib.parse.urlsplit(адрес).path)
    return путь.rsplit("/", 1)[-1] or адрес


def _что_первым(первым: dict | None) -> str:
    if not первым:
        return "что именно — браузер не назвал"
    if первым.get("тег") == "img" or первым.get("тег") == "фон":
        return f"картинка «{имя_файла(первым.get('адрес') or '')}»"
    if первым.get("тег") == "video":
        return "ролик первого экрана"
    return f"текст «{первым.get('текст') or '…'}»"


def _что_предлагаю(первым: dict, скорость: dict) -> str:
    """Совет под причину, а не дежурный: тяжёлую картинку — пережать, лёгкую — искать, что
    грузится раньше неё. Первый экран ждёт и стилей, и шрифтов: без них браузер не рисует."""
    по_типам = (скорость.get("скачано") or {}).get("по_типам") or {}
    до_неё = f"стили {вес(по_типам.get('стили', 0))}, шрифты {вес(по_типам.get('шрифты', 0))}"
    if первым.get("тег") in ("img", "фон"):
        адрес = первым.get("адрес") or ""
        байт = next((ф["байт"] for ф in скорость.get("файлы") or []
                     if адрес and имя_файла(ф["адрес"]) == имя_файла(адрес)), None)
        if байт is None or байт > КАРТИНКА_ПЕРВОГО_ЭКРАНА_ЛЁГКАЯ:
            сколько = f" ({вес(байт)})" if байт else ""
            return (f"предлагаю: пережать эту картинку{сколько} под ширину экрана телефона "
                    "(`картинка.py`) — это техническое, сделаю после вашего «да»")
        return (f"сама картинка лёгкая ({вес(байт)}): первый экран ждёт того, что грузится "
                f"раньше неё, — {до_неё}; предлагаю оставить в стилях только то, что на "
                "странице, а шрифтам — два-три начертания")
    return (f"текст ждёт шрифтов и стилей ({до_неё}); предлагаю оставить два-три начертания "
            "шрифтов и font-display: swap — текст покажется сразу, а шрифт подменится следом")


def находки_по_скорости(скорость: dict, живой: bool) -> list[dict]:
    if not скорость or скорость.get("не_вышло"):
        return [находка(К_СВЕДЕНИЮ, "Скорость не замерена",
                        [(скорость or {}).get("не_вышло") or "замер не запускался"],
                        "Остальное проверено; повторите позже — чаще всего это сеть.")]
    находки = []
    lcp, cls = скорость.get("lcp_с"), скорость.get("cls") or 0
    скачано = скорость.get("скачано") or {}
    куски = " · ".join(f"{тип} {вес(б)}" for тип, б in (скачано.get("по_типам") or {}).items() if б >= 1024)
    сводка = [
        f"условия: {УСЛОВИЯ_СЛОВАМИ}",
        f"первый экран показался через {секунды(lcp)}" if lcp is not None
        else "когда показался первый экран — браузер не сказал",
        f"вёрстка при загрузке сдвинулась на {доля(cls)} (хорошо — до {доля(CLS_ХОРОШО)})",
        f"скачано {вес(скачано.get('всего', 0))} в {скачано.get('файлов', 0)} файлах"
        + (f": {куски}" if куски else ""),
    ]
    if скорость.get("загрузка_не_кончилась"):
        сводка.append(f"страница так и не сказала «загрузилась» за {секунды(скорость.get('загрузка_с') or 0)}: "
                      "её держат чужие скрипты (счётчики, чат, проверки площадки) — на площадке это "
                      "обычное дело; первый экран измерен по тому, что успело открыться")
    if not живой:
        сводка.append("проверяли папку: сервер под боком, задержку сети изображает браузер — "
                      "точные числа даст тот же замер по живому адресу")
    находки.append(находка(К_СВЕДЕНИЮ, "Как сайт открывается на телефоне", сводка))

    if lcp is not None and lcp > LCP_ХОРОШО_С:
        уровень = ЧИНИТЬ if lcp > LCP_ПЛОХО_С else ПОПРАВИТЬ
        первым = скорость.get("первым") or {}
        строки = [f"первый экран появляется через {секунды(lcp)} на мобильном интернете "
                  f"(хорошо — до {секунды(LCP_ХОРОШО_С)}, дольше {секунды(LCP_ПЛОХО_С)} — плохо)",
                  f"дольше всего ждали: {_что_первым(первым)}"]
        if первым.get("ленивая"):
            строки.append("она помечена loading=\"lazy\" — браузер откладывает её, хотя это первый "
                          "экран: снять пометку")
        строки.append(_что_предлагаю(первым, скорость))
        находки.append(находка(
            уровень, "Первый экран появляется долго", строки,
            "половина уйдёт, не дождавшись: на телефоне дольше четырёх секунд белый экран не ждут"
            if уровень == ЧИНИТЬ else
            "часть людей не дождётся и закроет вкладку раньше, чем увидит, кто вы"))

    if cls > CLS_ХОРОШО:
        уровень = ЧИНИТЬ if cls > CLS_ПЛОХО else ПОПРАВИТЬ
        строки = [f"вёрстка при загрузке сдвинулась на {доля(cls)} (хорошо — до "
                  f"{доля(CLS_ХОРОШО)}, больше {доля(CLS_ПЛОХО)} — плохо)"]
        if скорость.get("сдвигались"):
            строки.append("сдвигались: " + ", ".join(скорость["сдвигались"]))
        строки.append("предлагаю: картинкам — width и height, всему, что появляется позже, — "
                      "место заранее")
        находки.append(находка(
            уровень, "Вёрстка прыгает при загрузке", строки,
            "человек целится в кнопку, а она уезжает из-под пальца: промахивается или бросает"))

    шрифты = скорость.get("шрифты") or []
    всего_шрифтов = sum(ш["байт"] for ш in шрифты)
    if всего_шрифтов > ШРИФТЫ_ТЯЖЁЛЫЕ:
        находки.append(находка(
            ПОПРАВИТЬ, "Шрифты весят много",
            [f"{len(шрифты)} файлов шрифтов, вместе {вес(всего_шрифтов)} (хорошо — до "
             f"{вес(ШРИФТЫ_ТЯЖЁЛЫЕ)})"]
            + [f"«{имя_файла(ш['адрес'])}» — {вес(ш['байт'])}" for ш in шрифты[:3]]
            + ["предлагаю: оставить только те начертания, что на странице, — обычно два-три"],
            "пока шрифт не скачался, текст не виден или прыгает при подмене"))
    return находки


def находки_по_картинкам(картинки: dict) -> list[dict]:
    if not картинки or картинки.get("не_вышло"):
        return []   # о сбое говорит сводка скорости; картинки без замера молчат, а не врут
    находки = []
    крупные = картинки.get("крупные") or []
    if крупные:
        находки.append(находка(
            ПОПРАВИТЬ, "Картинка крупнее, чем показывается",
            [f"«{имя_файла(к['адрес'])}» — в файле {к['файл']} px, на телефоне показывается "
             f"{к['показ']} px (с запасом на чёткий экран хватит {к['нужно']} px)" for к in крупные]
            + ["предлагаю: пережать под нужную ширину — `картинка.py`; это техническое, сделаю "
               "после вашего «да»"],
            "телефон качает лишние мегабайты, а человек видит ту же картинку"))
    без_лени = картинки.get("без_лени") or []
    сверху = картинки.get("ленивые_сверху") or []
    if без_лени or сверху:
        строки = [f"«{имя_файла(к['адрес'])}» ниже первого экрана грузится сразу — нужен "
                  "loading=\"lazy\"" for к in без_лени]
        строки += [f"«{имя_файла(к['адрес'])}» на первом экране помечена loading=\"lazy\" — "
                   "пометку снять" for к in сверху]
        находки.append(находка(
            ПОПРАВИТЬ, "Ленивая загрузка не там, где нужно", строки,
            "первый экран ждёт картинок, до которых человек ещё не долистал"))
    без_размеров = картинки.get("без_размеров") or []
    if без_размеров:
        находки.append(находка(
            ПОПРАВИТЬ, "Картинки без размеров",
            [f"«{имя_файла(к['адрес'])}» — ни width и height, ни пропорции в стиле" for к in без_размеров]
            + ["предлагаю: дописать width и height по размеру файла — это техническое"],
            "пока картинка грузится, место под неё не держится — текст ниже прыгает"))
    return находки


def находки_по_экранам(экраны: dict, телефон: dict | None = None) -> list[dict]:
    """Дополнительные экраны. Мелкий текст, о котором уже сказал главный телефон, не
    повторяем: называем только экраны, где его больше или он мельче, — иначе одна беда
    звучит шесть раз и заслоняет остальное."""
    ломается, мелко, не_снялись = [], [], []
    уже = (телефон or {}).get("мелкий_текст") or {}
    уже_мест = уже.get("элементов_мельче_порога") or 0
    уже_минимум = уже.get("минимум_px") or 0
    for размер, у in (экраны or {}).items():
        подпись = глаза.ПОДПИСИ_РАЗМЕРОВ.get(размер, размер)
        if у.get("статус") == "нет_движка":
            continue
        if у.get("статус") != "ок":
            беда = у.get("не_пустило") or {}
            if размер == SAFARI:
                ломается.append(f"{подпись}: страница не открылась — {беда.get('признак')}")
            else:
                не_снялись.append(f"{подпись}: {беда.get('признак') or у.get('статус')}")
            continue
        прокрутка = у.get("прокрутка_вбок") or {}
        if прокрутка.get("есть"):
            ломается.append(f"{подпись}: страница ездит вбок — ширина {прокрутка.get('ширина_страницы')} px "
                            f"при экране {прокрутка.get('ширина_экрана')} px")
        for к in у.get("вылезающие_картинки") or []:
            ломается.append(f"{подпись}: картинка шириной {к.get('ширина')} px вылезает за край — "
                            f"«{имя_файла(к.get('адрес') or '')}»")
        мелкий = у.get("мелкий_текст") or {}
        мест = мелкий.get("элементов_мельче_порога") or 0
        if мест and (мест > уже_мест or (мелкий.get("минимум_px") or 0) < уже_минимум):
            мелко.append(f"{подпись}: таких мест {мелкий['элементов_мельче_порога']}, самый мелкий — "
                         f"{мелкий.get('минимум_px')} px")
    находки = []
    if ломается:
        находки.append(находка(
            ЧИНИТЬ, "На других экранах вёрстка ломается", ломается + [
                "снимки каждого экрана лежат рядом с отчётом — посмотрите глазами"],
            "у кого-то из посетителей именно этот экран: текст уезжает за край, и его читают, "
            "дёргая страницу пальцем"))
    if мелко:
        находки.append(находка(
            ПОПРАВИТЬ, "На других экранах есть текст мельче 13 px", мелко,
            "мелкий текст не читают, а пролистывают"))
    if не_снялись:
        находки.append(находка(К_СВЕДЕНИЮ, "Часть экранов не снялась", не_снялись,
                               "Остальные сняты; повторите проверку — чаще всего это сеть."))
    safari = (экраны or {}).get(SAFARI) or {}
    if safari.get("статус") == "нет_движка":
        находки.append(находка(
            К_СВЕДЕНИЮ, "Safari не проверен",
            [f"движок Safari (WebKit) не поставлен: {safari.get('почему')}",
             f"поставить одной командой: {ПОСТАВИТЬ_SAFARI} — около 80 МБ, минута-две"],
            "iPhone рисует страницу своим движком; без него проверен только Chrome."))
    return находки


def находки_по_google(google: dict | None, живой: bool) -> list[dict]:
    if not живой:
        return []
    if not google:
        return []
    if google.get("не_вышло"):
        return [находка(
            К_СВЕДЕНИЮ, "PageSpeed не ответил",
            [google["не_вышло"],
             "проверить руками: pagespeed.web.dev — вставить адрес сайта; или завести бесплатный "
             f"ключ Google и положить его в переменную {КЛЮЧ_PAGESPEED}"],
            "Свой замер скорости выше сделан и без Google.")]
    строки = [f"оценка скорости на телефоне: {google.get('оценка')} из 100"]
    if google.get("lcp_с") is not None:
        строки.append(f"первый экран у Google — через {секунды(google['lcp_с'])}")
    if google.get("cls") is not None:
        строки.append(f"сдвиг вёрстки у Google — {доля(google['cls'])}")
    if google.get("вес"):
        строки.append(f"вес страницы у Google — {вес(int(google['вес']))}")
    if google.get("живые_люди"):
        строки.append(f"у живых посетителей за 28 дней первый экран — через "
                      f"{секунды(google['живые_люди']['lcp_с'])}")
    находки = [находка(К_СВЕДЕНИЮ, "Оценка Google PageSpeed", строки,
                       "Та же шкала, по которой Google ранжирует страницы в поиске.")]
    оценка = google.get("оценка")
    if оценка is not None and оценка < ГУГЛ_НИЗКО:
        находки.append(находка(
            ПОПРАВИТЬ, "Оценка скорости от Google низкая",
            [f"{оценка} из 100 на телефоне (ниже {ГУГЛ_НИЗКО} Google называет медленным)"],
            "медленную страницу поиск показывает ниже, а человек с телефона не дожидается"))
    return находки


def находки(техника: dict, телефон: dict | None = None) -> list[dict]:
    """Все находки технической приёмки — в порядке разговора: скорость, картинки, экраны, Google.
    `телефон` — замеры главного телефона обычной проверки: сказанное им здесь не повторяем."""
    if not техника:
        return []
    живой = bool(техника.get("живой"))
    return (находки_по_скорости(техника.get("скорость") or {}, живой)
            + находки_по_картинкам(техника.get("картинки") or {})
            + находки_по_экранам(техника.get("экраны") or {}, телефон)
            + находки_по_google(техника.get("google"), живой))


def строки_отчёта(техника: dict) -> list[str]:
    """Раздел отчёта: числа по каждому дополнительному экрану — коротко, по строке на экран."""
    строки = ["", "## Техника: ещё пять экранов", ""]
    for размер, у in (техника.get("экраны") or {}).items():
        подпись = глаза.ПОДПИСИ_РАЗМЕРОВ.get(размер, размер)
        if у.get("статус") == "нет_движка":
            строки.append(f"- {подпись} — не снят: нет движка Safari ({ПОСТАВИТЬ_SAFARI})")
            continue
        if у.get("статус") != "ок":
            строки.append(f"- {подпись} — {глаза.состояние_словами(у)}")
            continue
        прокрутка = у.get("прокрутка_вбок") or {}
        мелких = (у.get("мелкий_текст") or {}).get("элементов_мельче_порога") or 0
        вылезает = len(у.get("вылезающие_картинки") or [])
        снимки = " · ".join(Path(п).name for п in (у.get("скриншоты") or {}).values()
                            if str(п).endswith(".png"))
        строки.append(
            f"- {подпись} — " + " · ".join([
                "ездит вбок" if прокрутка.get("есть") else "вбок не ездит",
                f"картинок за край: {вылезает}" if вылезает else "картинки на месте",
                f"текста мельче {глаза.МЕЛКИЙ_ТЕКСТ_PX} px: {мелких}" if мелких
                else f"текста мельче {глаза.МЕЛКИЙ_ТЕКСТ_PX} px нет",
            ]) + (f" — {снимки}" if снимки else ""))
    return строки


def снимки(техника: dict) -> list[str]:
    """Пути всех снимков дополнительных экранов — для списка «Экраны» в конце отчёта."""
    return [str(п) for у in (техника.get("экраны") or {}).values()
            for п in (у.get("скриншоты") or {}).values() if str(п).endswith(".png")]
