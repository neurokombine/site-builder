#!/usr/bin/env python3
"""Версии системы: сохранить перед правкой, посмотреть список, откатиться.

Зачем. Система живёт в папке, у которой есть история версий. Пока версия не сохранена,
правка необратима: нейросеть перепишет файл — и прежнего текста нигде нет. Поэтому перед
любой правкой файлов системы сохраняем версию, а если правка не понравилась — возвращаемся.

Личные данные (профили, принесённые файлы, готовые документы) в версии НЕ попадают —
их отсекает .gitignore. Сохраняется только сама система.

    .venv/bin/python ядро/скрипты/версия.py сохрани "перед тем как менять правила вёрстки"
    .venv/bin/python ядро/скрипты/версия.py список
    .venv/bin/python ядро/скрипты/версия.py откати            # к предыдущей сохранённой версии
    .venv/bin/python ядро/скрипты/версия.py откати --на 3     # к версии №3 из списка
"""
from __future__ import annotations

import argparse
import subprocess
import sys
from datetime import datetime, timezone, timedelta
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent.parent
МСК = timezone(timedelta(hours=3))


def git(*аргументы: str, тихо: bool = False) -> tuple[int, str]:
    р = subprocess.run(["git", *аргументы], cwd=КОРЕНЬ, capture_output=True, text=True)
    вывод = (р.stdout + р.stderr).strip()
    if р.returncode != 0 and not тихо:
        print(вывод, file=sys.stderr)
    return р.returncode, вывод


def проверить_готовность() -> bool:
    """Git установлен, папка — под версиями, есть чем подписывать сохранения."""
    if subprocess.run(["git", "--version"], capture_output=True).returncode != 0:
        print("На этом компьютере нет git — того, что помнит версии. Система работать будет,\n"
              "но откатиться не получится. Скажите об этом в чате курса, вам помогут его поставить.")
        return False
    код, _ = git("rev-parse", "--git-dir", тихо=True)
    if код != 0:
        print("Эта папка не под версиями: истории у неё нет, откатываться не к чему.\n"
              "Так бывает, если систему скачали архивом, а не забрали с полки.")
        return False
    _, имя = git("config", "user.name", тихо=True)
    _, почта = git("config", "user.email", тихо=True)
    if not имя or not почта:
        git("config", "user.name", "Хозяин системы")
        git("config", "user.email", "system@local")
        print("Подписал сохранения именем «Хозяин системы» — это нужно только для истории версий,\n"
              "наружу оно никуда не уходит.")
    return True


def есть_изменения() -> bool:
    _, вывод = git("status", "--porcelain")
    return bool(вывод.strip())


def версии(сколько: int = 10) -> list[dict]:
    код, вывод = git("log", f"-{сколько}", "--pretty=%H%x1f%at%x1f%s", тихо=True)
    if код != 0 or not вывод:
        return []
    итог = []
    for строка in вывод.splitlines():
        хеш, когда, описание = строка.split("\x1f")
        итог.append({
            "хеш": хеш,
            "когда": datetime.fromtimestamp(int(когда), МСК).strftime("%d.%m.%Y %H:%M"),
            "описание": описание,
        })
    return итог


def команда_сохрани(a) -> int:
    if not проверить_готовность():
        return 1
    if not есть_изменения():
        print("Сохранять нечего — с прошлой версии в системе ничего не менялось.")
        return 0
    описание = (a.описание or "").strip() or "правки в системе"
    метка = datetime.now(МСК).strftime("%d.%m.%Y %H:%M")
    git("add", "-A")
    код, вывод = git("commit", "-m", описание)
    if код != 0:
        print("Не получилось сохранить версию:\n" + вывод)
        return 1
    print(f"Версия сохранена: «{описание}» ({метка}).\n"
          f"Если следующая правка не понравится — вернёмся сюда.")
    return 0


def команда_список(a) -> int:
    if not проверить_готовность():
        return 1
    список = версии(a.сколько)
    if not список:
        print("Сохранённых версий пока нет.")
        return 0
    if есть_изменения():
        print("⚠️ Сейчас в системе есть правки, которые ещё не сохранены как версия.\n"
              "   Скажете «откати» — вернёмся к версии №1, и эти правки пропадут "
              "(перед откатом я их всё равно сохраню отдельно).\n")
    print("Сохранённые версии (свежие сверху):\n")
    for номер, в in enumerate(список, start=1):
        пометка = "  ← последняя сохранённая" if номер == 1 else ""
        print(f"  {номер}. {в['когда']} — {в['описание']}{пометка}")
    print("\nВернуться к какой-нибудь: «откати меня к версии номер N».")
    return 0


def команда_откати(a) -> int:
    if not проверить_готовность():
        return 1
    список = версии(30)
    if len(список) < 2:
        print("Откатываться некуда: сохранённая версия всего одна (или их нет).")
        return 1

    # «Верни как было» значит разное в двух случаях:
    #   есть несохранённые правки → вернуть к последней сохранённой версии (№1);
    #   всё сохранено → вернуть на шаг назад (№2).
    грязно = есть_изменения()
    номер = a.на if a.на else (1 if грязно else 2)
    if номер < 1 or номер > len(список):
        print(f"В списке нет версии №{номер}. Посмотрите «список версий».")
        return 1
    цель = список[номер - 1]

    if грязно:
        метка = datetime.now(МСК).strftime("%d.%m.%Y %H:%M")
        git("add", "-A")
        git("commit", "-m", f"состояние перед откатом ({метка})")
        print("Сначала сохранил то, что было сейчас, — на случай если откат не понравится.")

    код, вывод = git("checkout", цель["хеш"], "--", ".")
    if код != 0:
        print("Откат не получился:\n" + вывод)
        return 1

    # файлы, появившиеся ПОСЛЕ целевой версии, вернуть нельзя «содержимым» — их надо убрать
    _, новые = git("diff", "--name-only", "--diff-filter=A", цель["хеш"], "HEAD", тихо=True)
    for файл in [ф for ф in новые.splitlines() if ф.strip()]:
        git("rm", "-f", "--quiet", файл, тихо=True)

    метка = datetime.now(МСК).strftime("%d.%m.%Y %H:%M")
    git("add", "-A")
    код, вывод = git("commit", "-m", f"откат к версии «{цель['описание']}»")
    if код != 0 and "nothing to commit" not in вывод:
        print("Файлы вернул, но новую версию записать не вышло:\n" + вывод)
        return 1

    print(f"Система вернулась к состоянию: «{цель['описание']}» ({цель['когда']}).\n"
          f"Ничего не потеряно — и прежнее, и то, что делали после, осталось в истории.")
    return 0


def main() -> int:
    p = argparse.ArgumentParser(description="Версии системы: сохранить, посмотреть, откатиться")
    под = p.add_subparsers(dest="команда", required=True)

    s = под.add_parser("сохрани", help="сохранить версию перед правкой")
    s.add_argument("описание", nargs="?", default="")
    s.set_defaults(func=команда_сохрани)

    s = под.add_parser("список", help="показать сохранённые версии")
    s.add_argument("--сколько", type=int, default=10)
    s.set_defaults(func=команда_список)

    s = под.add_parser("откати", help="вернуть систему к сохранённой версии")
    s.add_argument("--на", type=int, default=None, help="номер версии из списка")
    s.set_defaults(func=команда_откати)

    a = p.parse_args()
    return a.func(a)


if __name__ == "__main__":
    raise SystemExit(main())
