def _обёртка(классы: str) -> str:
    """Имя обёртки по классам `<figure>`: «первый экран», «фото», «мокап». Чужое — пусто."""
    набор = классы.split()
    if ПЕРВЫЙ_ЭКРАН in набор:
        return "первый экран"
    for имя in ОБЁРТКИ:
        if имя in набор:
            return имя
    return ""


def _пропорция(обёртка: str, классы: str, схема: str, тип_кадра: str) -> str:
    """Какой формат просит это место. У первого экрана его решает схема, у остальных — обёртка."""
    if обёртка == "первый экран":
        return заказ.пропорция_схемы(схема, тип_кадра)
    if обёртка == "мокап" and ОКНО_ПЛЕЕРА in классы.split():
        return ПРОПОРЦИЯ_ПЛЕЕРА
    return ОБЁРТКИ.get(обёртка, "")


def чем_закрывать(тип_экрана: str, слот: str, схема: str = "", тип_кадра: str = "") -> str:
    """Портрет · съёмка · генерация · ролик — одним словом на каждое пустое место.

    Первый экран считается машиной заказа, а не таблицей: схема уже знает, ролик ей нужен или
    кадр, и стоит ли в кадре человек. Остальные экраны — по таблице `ЧЕМ_ЗАКРЫВАТЬ`.
    """
    if тип_экрана == "первый-экран":
        не_рисуем, _ = заказ.почему_не_рисуем(тип_кадра)
        if не_рисуем:
            return СНИМАТЬ if тип_кадра == "мокап" else РОЛИК
        return ПОРТРЕТ if заказ.человек_в_кадре(схема, тип_кадра) else ГЕНЕРАЦИЯ
    for тип, начало, ответ in ЧЕМ_ЗАКРЫВАТЬ:
        if тип == тип_экрана and (not начало or слот.startswith(начало)):
            return ответ
    return ГЕНЕРАЦИЯ


def места_картинок(html: str, тип_экрана: str, схема: str = "", тип_кадра: str = "") -> list[dict]:
    """Места под картинку в одном экране работы: обёртка, пропорция, слот, занято ли.

    Смотрим сам экран, а не рецепт ядра: где картинка была украшением, вёрстка уже распущена
    (`ядро/блоки.md` § 5-bis) — и звать человека туда, где места нет, значит выдумывать работу.
    """
    места: list[dict] = []
    for классы, нутро in ФИГУРА.findall(html):
        обёртка = _обёртка(классы)
        if not обёртка:
            continue
        слот = СЛОТ_КАРТИНКИ.search(нутро)
        места.append({
            "обёртка": обёртка,
            "пропорция": _пропорция(обёртка, классы, схема, тип_кадра),
            "слот": слот.group(1) if слот else "",
            "есть": bool(ИСТОЧНИК.search(нутро)),
            "заглушка": ЗАГЛУШКА in нутро,
        })
    # Аватар живёт без `<figure>` — круглая картинка прямо в подписи отзыва или карточке случая.
    for кусок in АВАТАР.findall(html):
        слот = СЛОТ_КАРТИНКИ.search(кусок)
        места.append({"обёртка": "аватар", "пропорция": ОБЁРТКИ["аватар"],
                      "слот": слот.group(1) if слот else "",
                      "есть": bool(ИСТОЧНИК.search(кусок)), "заглушка": False})
    for место in места:
        место["чем"] = чем_закрывать(тип_экрана, место["слот"], схема, тип_кадра)
    return места


def экраны_работы(работа: Path) -> list[dict]:
    """Экраны страницы по порядку: номер, тип, схема и места под картинку в каждом."""
    итог: list[dict] = []
    for файл in sorted((Path(работа) / "экраны").glob("*.html")):
        html = файл.read_text(encoding="utf-8-sig")
        номер = ЭКРАН_СЕКЦИИ.search(html)
        тип = ТИП_СЕКЦИИ.search(html)
        схема = СХЕМА_СЕКЦИИ.search(html)
        кадр = КАРТИНКА_СЕКЦИИ.search(html)
        тип_экрана = тип.group(1) if тип else файл.stem.split("-", 1)[-1]
        итог.append({
            "номер": int(номер.group(1)) if номер else len(итог) + 1,
            "тип": тип_экрана,
            "схема": схема.group(1) if схема else "",
            "тип_кадра": кадр.group(1) if кадр else "",
            "файл": файл,
            "места": места_картинок(html, тип_экрана, схема.group(1) if схема else "",
                                    кадр.group(1) if кадр else ""),
        })
    return итог


def нехватка(экраны: list[dict]) -> list[dict]:
    """Только те экраны, где место под картинку есть, а картинки в нём нет."""
    итог = []
    for экран in экраны:
        пустые = [м for м in экран["места"] if not м["есть"]]
        if пустые:
            итог.append({**экран, "места": пустые})
    return итог


def одинаковые(места: list[dict]) -> list[tuple[dict, int]]:
    """Одинаковые места одного экрана — одной строкой со счётом.

    На экране работ таких мест три, в отзывах — два, и они ничем друг от друга не отличаются:
    та же обёртка, та же пропорция, то же «чем закрывать». Три одинаковых абзаца подряд человек
    читает как сбой системы, а не как список.
    """
    итог: list[tuple[dict, int]] = []
    for место in места:
        признак = (место["обёртка"], место["пропорция"], место["чем"], место["заглушка"])
        for номер, (прежнее, сколько) in enumerate(итог):
            if (прежнее["обёртка"], прежнее["пропорция"], прежнее["чем"],
                    прежнее["заглушка"]) == признак:
                итог[номер] = (прежнее, сколько + 1)
                break
        else:
            итог.append((место, 1))
    return итог


