def сюжеты_прототипа(работа: Path) -> dict[int, str]:
    """Строки «Картинка» экранов прототипа по номерам — то единственное, чего система не знает."""
    файл = Path(работа) / "прототип.md"
    if not файл.is_file():
        return {}
    итог: dict[int, str] = {}
    for прототип in проверить_прототип.разобрать(файл.read_text(encoding="utf-8-sig")):
        for номер, экран in enumerate(прототип["экраны"], start=1):
            строка = (экран.get("слоты", {}).get("Картинка") or [""])[0].strip()
            сюжет = заказ.сюжет_из_строки(строка)
            if сюжет:
                итог[экран.get("номер") or номер] = сюжет
    return итог


