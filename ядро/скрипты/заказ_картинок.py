ЖДЁМ_ОТВЕТА = ("Жду вашего ответа: откройте «{файл}», внизу раздел «Решения» — назовите стиль и "
               "скажите по каждому экрану, рисуем его, несёте свой файл или пропускаем. "
               "До ответа ничего не рисуется.")


def разговор(работа: Path, *, нарисуй: bool = False, без_журнала: bool = False,
             куда: str = "", печатать=print) -> int:
    """Весь разговор одной командой: первый запуск заводит файл, второй — собирает промты."""
    работа = Path(работа)
    файл = работа / ФАЙЛ_РАЗГОВОРА
    данные, папка_профиля, беда = собрать._профиль(работа)
    палитра = (данные or {}).get("палитра") if isinstance(данные, dict) else None
    роль = ((данные or {}).get("автор") or {}).get("роль", "") if isinstance(данные, dict) else ""
    поля = заказ.решения(работа)
    ключ = "светлый" if поля.get("доминанта") == "светлая" else "тёмный"
    стили = три_стиля(поля, палитра, роль)
    экраны = экраны_работы(работа)
    найденное: list[dict] = []
    if беда:
        найденное.append(находка(ПОПРАВИТЬ, "Профиль не прочитался", [беда],
                                 "без него в промтах не будет ни палитры, ни роли — кадры выйдут «вообще»"))
    if not экраны:
        найденное.append(находка(
            ЧИНИТЬ, "Экранов ещё нет", [f"в «{работа / 'экраны'}» нет файлов NN-<тип>.html"],
            "разговор о картинках идёт по собранным экранам: сперва соберите страницу, "
            "потом видно, каких кадров не хватает"))
        for строка in строки_по_уровням(найденное, заголовки_уровней("съёмки")):
            печатать(строка)
        return код_выхода(найденное)

    нехватающие = нехватка(экраны)
    нужен_портрет = any(м["чем"] == ПОРТРЕТ for э in нехватающие for м in э["места"])
    снимки, про_снимки = ([], [])
    if нужен_портрет and isinstance(данные, dict):
        снимки, про_снимки = портрет.селфи(данные, папка_профиля, лицо_обязательно=False)
    нужны_снимки = нужен_портрет and len(снимки) < портрет.НОРМА_СЕЛФИ

    решения = прочитать_решения(файл.read_text(encoding="utf-8-sig")) if файл.is_file() else {
        "стиль": "", "экраны": {}, "свои_файлы": {}, "отвечено": False}

    # Первый запуск (и повторный, пока «Решения» пустые) — разговор. Заполненный файл не трогаем:
    # в нём стоит ответ человека, и переписать его значит спросить второй раз то же самое.
    if not решения["отвечено"]:
        файл.write_text(текст_разговора(нехватающие, стили, сюжеты_прототипа(работа), нужны_снимки),
                        encoding="utf-8")
        печатать(файл.read_text(encoding="utf-8"))
        печатать("")
        печатать(ЖДЁМ_ОТВЕТА.format(файл=файл))
        найденное = без_повторов(найденное + про_снимки)
        for строка in строки_по_уровням(найденное, заголовки_уровней("съёмки")):
            печатать(строка)
        return код_выхода(найденное)

    # Второй запуск: ответ есть — собираем промты и, если попросили, зовём приёмку по очереди.
    стиль = выбранный_стиль(решения, стили)
    сюжеты = сюжеты_прототипа(работа)
    печатать(f"Стиль: {стиль['имя']} · ключ страницы {ключ}\n")
    заказы: list[dict] = []
    for экран in нехватающие:
        ответ = решения["экраны"].get(ключ_экрана(экран), "")
        если_нечего = [м for м in экран["места"] if м["чем"] not in РИСУЕМ]
        if ответ == СВОЙ_ФАЙЛ or (ответ.startswith(СВОЙ_ФАЙЛ) if ответ else False):
            имя = решения["свои_файлы"].get(ключ_экрана(экран), "<файл>")
            печатать(f"{ключ_экрана(экран)} · {экран['тип']}: ваш файл — "
                     f"`.venv/bin/python ядро/скрипты/картинка.py {имя} --куда {работа / 'img'}`\n")
            continue
        if ответ == ПРОПУСТИТЬ:
            печатать(f"{ключ_экрана(экран)} · {экран['тип']}: пропускаем\n")
            continue
        if ответ != ГЕНЕРИРОВАТЬ:
            печатать(f"{ключ_экрана(экран)} · {экран['тип']}: ответа нет, жду\n")
            continue
        if если_нечего:
            печатать(f"{ключ_экрана(экран)} · {экран['тип']}: не рисую — "
                     f"{СЛОВА_ЧЕМ[если_нечего[0]['чем']]}\n")
            continue
        собранный, свои = промт_экрана(работа, экран, стиль, данные, палитра, роль, ключ, сюжеты)
        найденное += свои
        if not собранный.get("промт"):
            печатать(f"{ключ_экрана(экран)} · {экран['тип']}: промт не собрался\n")
            continue
        печатать(f"{ключ_экрана(экран)} · {экран['тип']} · обёртка "
                 f"{собранный.get('обёртка', 'первый экран')} {собранный['пропорция']}\n")
        печатать(собранный["промт"])
        печатать("\nПочему каждая строка:")
        for с in собранный["строки"]:
            печатать(f"  • {с['строка']}\n    ← {с['откуда']}")
        if not без_журнала:
            печатать(f"\nЗаписано в «{заказ.в_журнал(работа, собранный)}»")
        печатать("")
        заказы.append({"экран": экран, "заказ": собранный})

    найденное = без_повторов(найденное)
    for строка in строки_по_уровням(найденное, заголовки_уровней("съёмки")):
        печатать(строка)

    if нарисуй and заказы and есть_красное(найденное):
        печатать("\nНе рисую: сперва закройте 🔴 выше — иначе генератор нарисует не вас.")
        return 1
    if нарисуй and заказы:
        import приёмка
        основа = Path(куда) if куда else работа / "витрина" / приёмка.ЖДЁТ
        for пара in заказы:
            экран, собранный = пара["экран"], пара["заказ"]
            try:
                итог = приёмка.нарисовать_и_принять(
                    собранный, основа, работа=работа, имя=f"kadr-{ключ_экрана(экран)}",
                    светлота_фона=приёмка._светлота_страницы(работа, собранный["ключ"]))
            except (приёмка.ЛицоБезСлова, приёмка.кисть.БедаКисти) as беда_кисти:
                # Беда ввода или канала: дальше по списку не идём — следующий кадр упрётся в неё же,
                # а человек получит пять одинаковых отказов вместо одного.
                печатать(f"\n❌ {ключ_экрана(экран)}: {беда_кисти}")
                return 3
            печатать(f"{ключ_экрана(экран)}: кадр {итог['файл']} · попыток {итог['попыток']}")
            for строка in строки_по_уровням(итог.get("промахи") or [],
                                            заголовки_уровней("показа")):
                печатать(строка)
            if итог.get("беда"):
                печатать(f"\n❌ {итог['беда']}")
                return 3
    return код_выхода(найденное)
