def текст_разговора(нехватающие: list[dict], стили: list[dict], сюжеты: dict[int, str],
                    нужны_снимки: bool = False) -> str:
    """Весь файл разговора одним текстом — по образцу `дизайн.md`: варианты сверху, ответ снизу."""
    строки = [ШАПКА, "", ПРЕДИСЛОВИЕ, "", ЗАГОЛОВОК_НЕХВАТКИ, ""]
    if not нехватающие:
        строки += ["Пустых мест на странице нет: каждая обёртка занята. Просить нечего.", ""]
    for экран in нехватающие:
        строки.append(f"### {ключ_экрана(экран)} · {экран['тип']}")
        строки.append("")
        for место, сколько in одинаковые(экран["места"]):
            где = f"обёртка `{место['обёртка']}`"
            если = f", {место['пропорция']}" if место["пропорция"] else ""
            сколько_словами = "" if сколько == 1 else f", таких мест {сколько}"
            сейчас = "сейчас там серая заглушка" if место["заглушка"] else "место пустое"
            строки.append(f"- {где}{если}{сколько_словами} — {сейчас}.")
            строки.append(f"  Что на кадре: {что_на_кадре(экран, сюжеты)}.")
            строки.append(f"  Зачем экрану: {зачем_экрану(экран)}.")
            строки.append(f"  Чем закрывать: {СЛОВА_ЧЕМ[место['чем']]}.")
        строки.append("")
    строки += [ЗАГОЛОВОК_СТИЛЕЙ, ""]
    for стиль in стили:
        строки.append(f"### Стиль {стиль['номер']} · {стиль['имя']}")
        строки += стиль["описание"]
        строки.append(f"- Цвета кадра: {стиль['цвета']}")
        строки.append(f"- Свет: {стиль['свет']}")
        строки.append(f"- Почему подходит этому сайту: {стиль['почему']}")
        строки.append("")
    if нужны_снимки:
        строки += [ЗАГОЛОВОК_СНИМКОВ, "", ВОПРОС_ПРО_СНИМКИ, ""]
    строки += [ЗАГОЛОВОК_РЕШЕНИЙ, "",
               f"- Стиль: {ОТВЕТЫ_СТИЛЯ}",
               ОБРАЗЕЦ_СВОИХ_ФАЙЛОВ, ""]
    for экран in нехватающие:
        строки.append(f"- {ключ_экрана(экран)} · {экран['тип']}: {ответы_экрана(экран)}")
    return "\n".join(строки).rstrip("\n") + "\n"


# ── ответ человека ───────────────────────────────────────────────────────────
СТРОКА_СТИЛЯ = re.compile(r"^-\s*Стиль:\s*(.*)$", re.M)
СТРОКА_СВОИХ_ФАЙЛОВ = re.compile(r"^-\s*Свои файлы:\s*(.*)$", re.M)
СТРОКА_ЭКРАНА = re.compile(r"^-\s*(экран-\d+)[^:]*:\s*(.*)$", re.M)
ПАРА_ФАЙЛА = re.compile(r"^(экран-\d+)\s*(?:→|->)\s*(.+)$")


def _ответ(значение: str) -> str:
    """Ответ человека или пусто: строка с палками — это ещё вопрос, а не ответ."""
    значение = (значение or "").strip()
    if not значение or "|" in значение or значение.startswith("<"):
        return ""
    return значение


def прочитать_решения(текст: str) -> dict:
    """Раздел «Решения» файла разговора → `{стиль, экраны, свои_файлы, отвечено}`."""
    низ = текст.split(ЗАГОЛОВОК_РЕШЕНИЙ, 1)
    хвост = низ[1] if len(низ) > 1 else ""
    стиль_строка = СТРОКА_СТИЛЯ.search(хвост)
    стиль = _ответ(стиль_строка.group(1) if стиль_строка else "")
    экраны = {ключ: _ответ(значение) for ключ, значение in СТРОКА_ЭКРАНА.findall(хвост)}
    экраны = {ключ: значение for ключ, значение in экраны.items() if значение}
    свои: dict[str, str] = {}
    for строка in СТРОКА_СВОИХ_ФАЙЛОВ.findall(хвост):
        пара = ПАРА_ФАЙЛА.match(строка.strip())
        if пара:
            свои[пара.group(1)] = пара.group(2).strip()
    return {"стиль": стиль, "экраны": экраны, "свои_файлы": свои,
            "отвечено": bool(стиль and экраны)}


def выбранный_стиль(решения: dict, стили: list[dict]) -> dict:
    """Стиль из ответа: номер из трёх — или свои слова человека, они старше предложенного."""
    ответ = (решения.get("стиль") or "").strip()
    свои = re.sub(r"^своими словами:\s*", "", ответ, flags=re.I)
    if свои != ответ and свои.strip():
        return {"номер": 0, "имя": "свои слова", "описание": [свои.strip()],
                "цвета": "", "свет": свои.strip(), "почему": ""}
    for стиль in стили:
        if ответ.startswith(str(стиль["номер"])):
            return стиль
    return стили[0]


