ОТКУДА_СТИЛЬ = "ответ человека в разделе «Решения» разговора о картинках"
ОТКУДА_ПРОПОРЦИИ = "пропорция обёртки экрана (`ядро/картинки.md` § 4): кадр другого формата обрежется по центру"
ГЕНЕРИРОВАТЬ = "генерировать"
СВОЙ_ФАЙЛ = "свой файл"
ПРОПУСТИТЬ = "пропустить"


def без_повторов(найденное: list[dict]) -> list[dict]:
    """Про одно и то же — один раз.

    Портретных мест на странице бывает два и больше, а профиль у них один: без этого человек
    получал «нет ваших снимков» столько раз, сколько на странице лиц, и читал это как сбой.
    Остаётся первая находка — она пришла с того экрана, где лицо обязательно, и уровень у неё
    строже.
    """
    итог, видели = [], set()
    for находка_ in найденное:
        if находка_["что"] in видели:
            continue
        видели.add(находка_["что"])
        итог.append(находка_)
    return итог


def _откуда(экран: dict, первый: bool = False) -> dict:
    """Подписи «откуда» для строк, чей источник на этом экране свой, а не тот же, что у первого."""
    сюжет = (f"строка «Картинка» экрана {экран['номер']} прототипа — что в кадре решает работа, "
             f"а не эта сборка")
    подписи = {"стиль": ОТКУДА_СТИЛЬ, "настроение": ОТКУДА_СТИЛЬ}
    if not первый:
        подписи.update({"сюжет": сюжет, "пропорция": ОТКУДА_ПРОПОРЦИИ})
    return подписи


def _строка_стиля(стиль: dict) -> str:
    """Стиль одной строкой промта: имя, потом его описание — фразами, а не свалкой слов."""
    части = [*стиль["описание"]]
    if стиль.get("цвета"):
        части.append(f"Цвета: {стиль['цвета']}")
    хвост = ". ".join(ч.strip().rstrip(".") for ч in части if ч and ч.strip())
    return f"{стиль['имя']} — {хвост}" if хвост else стиль["имя"]


def промт_экрана(работа: Path, экран: dict, стиль: dict, данные: dict | None, палитра,
                 роль: str, ключ: str, сюжеты: dict[int, str]) -> tuple[dict, list[dict]]:
    """Промт под один экран той же машиной, что собирает промт первого экрана.

    Первый экран уходит по своему пути (`заказ.заказ_для_сайта`): там схема решает вырез это или
    фотография, крупность головы и фон под ключ. Остальным экранам схемы нет — у них есть обёртка
    и её пропорция, поэтому схему не выдумываем, а передаём пустую: промт тогда состоит из сюжета,
    палитры, стиля, пропорции и запретов, и ни одна строка в нём не притворяется замером.
    """
    место = экран["места"][0]
    if экран["тип"] == "первый-экран":
        return заказ.заказ_для_сайта(работа, стиль=_строка_стиля(стиль), настроение=стиль["свет"],
                                     откуда=_откуда(экран, первый=True))
    найденное: list[dict] = []
    внешность = ""
    if место["чем"] == ПОРТРЕТ and isinstance(данные, dict):
        внешность, _, свои = портрет.собрать_внешность(данные, "", "фото", папка=None, роль=роль,
                                                       лицо_обязательно=False)
        найденное += свои
    собранный = заказ.собрать_промт(
        "", ключ, что_в_кадре=что_на_кадре(экран, сюжеты), палитра=палитра, роль=роль,
        внешность=внешность, настроение=стиль["свет"], стиль=_строка_стиля(стиль),
        пропорция=место["пропорция"], место_кадра="сайта", откуда=_откуда(экран))
    собранный["место"] = f"{ключ_экрана(экран)} · {экран['тип']}"
    собранный["обёртка"] = место["обёртка"]
    # Портрет и на этом экране кончается показом и словом «беру»: признак «в кадре человек» приёмка
    # читает из заказа, а не из слов промта (`портрет.нужен_показ`).
    if место["чем"] == ПОРТРЕТ:
        собранный["тип"] = "фото"
    return собранный, найденное


