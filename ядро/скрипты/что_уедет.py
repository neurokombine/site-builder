"""Что уедет на полку, если выложить эту систему — или отдельный сайт — наружу.

Перед тем как класть систему или собранный сайт в открытый доступ, надо посмотреть глазами,
что именно уезжает. Система — уезжает. Ваши данные, ключи и документы — остаются дома.
Перепутать эти две вещи можно ровно один раз: выложенное в открытый репозиторий остаётся в
его истории, даже если файл потом удалить.

Скрипт показывает список и отдельно — то, что похоже на личное.

Запуск:
    .venv/bin/python ядро/скрипты/что_уедет.py                       # для этой системы
    .venv/bin/python ядро/скрипты/что_уедет.py сайты/моё-дело/сайт   # для сайта перед публикацией
    .venv/bin/python ядро/скрипты/что_уедет.py <папка> --закрыть     # дописать находки в .gitignore
"""
import argparse
import fnmatch
import re
import subprocess
import sys
from pathlib import Path

# Имена и куски имён, за которыми обычно стоят личные данные
ОПАСНЫЕ_ИМЕНА = [
    ("выписк", "банковская выписка"),
    ("чек", "чеки"),
    ("отчёт", "готовые отчёты с вашими цифрами"),
    ("отчет", "готовые отчёты с вашими цифрами"),
    ("данные", "папка с данными"),
    ("ключ", "ключи доступа"),
    ("token", "токен доступа"),
    ("secret", "секрет"),
    ("credential", "учётные данные"),
    ("passw", "пароль"),
    ("cookie", "куки браузера"),
    (r"\bauth\b", "данные входа"),   # именно слово: «author» — не про это
    ("профил", "профиль с вашими данными"),
    ("паспорт", "персональные документы"),
    ("договор", "документы"),
    ("клиент", "данные клиентов"),
    ("фото", "фотографии (проверьте, чьи)"),
    ("сайты", "ваши сайты и материалы к ним"),
]
ОПАСНЫЕ_РАСШИРЕНИЯ = {
    ".csv": "таблица с данными",
    ".xlsx": "таблица с данными",
    ".xls": "таблица с данными",
    ".ofx": "выгрузка из банка",
    ".qif": "выгрузка из банка",
    ".db": "база данных",
    ".sqlite": "база данных",
    ".sqlite3": "база данных",
    ".pdf": "документ (проверьте, чей)",
    ".env": "файл с ключами",
    ".pem": "ключ",
    ".key": "ключ",
    ".p12": "сертификат",
    ".mp4": "запись (может быть личной)",
    ".mov": "запись (может быть личной)",
    ".m4a": "запись голоса",
    ".mp3": "запись голоса",
}
# Файлы, опасные самим именем: расширения у них нет, и по расширению их не поймать.
# Именно сюда попадает `.env` — файл, в котором ученик хранит ключи доступа.
ОПАСНЫЕ_ИМЕНА_ФАЙЛОВ = [
    (".env", "файл с ключами доступа"),
    ("id_rsa", "закрытый ключ доступа"),
    ("id_ed25519", "закрытый ключ доступа"),
    (".netrc", "сохранённые логины и пароли"),
    (".npmrc", "токен доступа"),
    ("credentials", "учётные данные"),
    ("settings.local.json", "личные настройки машины"),
]
# Похоже на ключ доступа внутри файла
ПОХОЖЕ_НА_КЛЮЧ = re.compile(
    r"(sk-[A-Za-z0-9_\-]{16,}|ghp_[A-Za-z0-9]{20,}|AIza[A-Za-z0-9_\-]{20,}|"
    r"[A-Za-z0-9_\-]{0,20}(api[_\-]?key|token|secret)[\"'\s:=]+[A-Za-z0-9_\-]{16,})",
    re.I,
)
ТЕКСТОВЫЕ = {".md", ".txt", ".json", ".toml", ".yaml", ".yml", ".py", ".sh", ".html", ".css", ".js"}

# Учебное и образцы — часть системы, они как раз ЕДУТ. Иначе ученик закроет то,
# на чём другой человек будет пробовать систему в первый раз.
УЧЕБНОЕ = ("демо", "demo", "учебн", "образец", "образцы", "пример", "sample", "шаблон", "_шаблон", "test")


def правила_исключений(папка):
    """Строки .gitignore — то, что человек уже решил оставить дома."""
    файл = папка / ".gitignore"
    if not файл.exists():
        return []
    правила = []
    for строка in файл.read_text(encoding="utf-8", errors="ignore").split("\n"):
        строка = строка.split("#")[0].strip()
        if строка and not строка.startswith("!"):
            правила.append(строка.strip("/"))
    return правила


def закрыт(относительный, правила):
    части = относительный.split("/")
    for правило in правила:
        if "/" in правило:
            if fnmatch.fnmatch(относительный, правило) or относительный.startswith(правило + "/"):
                return True
        elif any(fnmatch.fnmatch(часть, правило) for часть in части):
            return True
    return False


def файлы_под_git(папка):
    """Что реально уедет: git показывает это точнее любых догадок.

    Два места, где голому `git ls-files` доверять нельзя:
    1. По умолчанию git прячет кириллические (и вообще не-ASCII) имена файлов за
       нечитаемыми экранированными кодами вида `"\\320\\277..."` — чиним флагом
       `-c core.quotepath=false`, а система вся на кириллических именах.
    2. Если папка лежит ВНУТРИ другого репозитория и сама целиком закрыта в его
       `.gitignore` (ровно так с папкой сайта: `сайты/*` в `.gitignore` системы) —
       git не ошибается, он честно отдаёт пустой список, будто в папке пусто, хотя
       файлы там есть. Отличаем этот случай от «и правда пустая папка» и считаем
       сами — иначе `.env` с ключами внутри собранного сайта проскочит незамеченным.
    """
    try:
        готово = subprocess.run(
            ["git", "-c", "core.quotepath=false", "-C", str(папка), "ls-files"],
            capture_output=True, text=True, check=True,
        )
        файлы = [папка / с for с in готово.stdout.split("\n") if с.strip()]
        есть_на_диске = any(
            п.is_file() and ".git" not in п.parts for п in папка.rglob("*")
        )
        if файлы or not есть_на_диске:
            return файлы, True
        # git отработал без ошибок, но список пуст, а на диске файлы есть — своей
        # истории у папки нет (или она вся закрыта родительским .gitignore).
        # Считаем сами, ниже.
    except Exception:
        pass

    # Истории версий ещё нет — считаем сами, но исключения уважаем: иначе после
    # «дописать в исключения» список не изменится и человек решит, что защита не
    # сработала. Правила берём у ЭТОЙ папки, а не у родительского репозитория —
    # если своего .gitignore нет, значит пока не закрыто ничего.
    правила = правила_исключений(папка)
    файлы = [
        п for п in папка.rglob("*")
        if п.is_file() and ".git" not in п.parts and "__pycache__" not in п.parts
        and not закрыт(str(п.relative_to(папка)).replace("\\", "/"), правила)
    ]
    return файлы, False


def чем_опасен(путь, корень):
    относительный = str(путь.relative_to(корень)).lower()
    причины = []

    # Ключи и пароли ищем всегда — даже в учебных папках
    имя = путь.name.lower()
    for кусок, что_это in ОПАСНЫЕ_ИМЕНА_ФАЙЛОВ:
        if имя == кусок or имя.startswith(кусок):
            причины.append(что_это)
            break
    if путь.suffix.lower() in ТЕКСТОВЫЕ or not путь.suffix:
        try:
            if путь.stat().st_size < 2_000_000 and ПОХОЖЕ_НА_КЛЮЧ.search(
                путь.read_text(encoding="utf-8", errors="ignore")
            ):
                причины.append("⚠️ внутри похоже на ключ доступа")
        except Exception:
            pass

    # Служебные файлы папок — README.md и .gitkeep. Личных данных в них не бывает по смыслу
    # (это не подстрока, а имя файла целиком), поэтому не гоняем их через ОПАСНЫЕ_ИМЕНА: иначе
    # `профили/README.md` и `сайты/.gitkeep` — файлы самой системы — каждый раз ложно пугали бы
    # человека «профилем с вашими данными» и «вашими сайтами». Проверку на ключ внутри текста
    # (выше) это не отменяет: README с вписанным по ошибке токеном всё равно поймается.
    if имя in ("readme.md", ".gitkeep"):
        return причины

    if any(у in относительный for у in УЧЕБНОЕ):
        return причины     # учебные данные и образцы уезжают вместе с системой — так и надо
    for кусок, что_это in ОПАСНЫЕ_ИМЕНА:
        совпало = re.search(кусок, относительный) if кусок.startswith(r"\b") else (кусок in относительный)
        if совпало:
            причины.append(что_это)
            break
    подпись = ОПАСНЫЕ_РАСШИРЕНИЯ.get(путь.suffix.lower())
    if подпись:
        причины.append(подпись)
    return причины


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("папка", nargs="?", default=".", help="папка системы или сайта, которую собираетесь выложить")
    ap.add_argument("--закрыть", action="store_true", help="дописать находки в .gitignore")
    args = ap.parse_args()

    корень = Path(args.папка).expanduser().resolve()
    if not корень.exists():
        print(f"\n⛔ Нет такой папки: {корень}\n")
        sys.exit(1)

    файлы, под_git = файлы_под_git(корень)
    if not файлы:
        print("В папке нечего выкладывать — файлов не нашлось.")
        return

    подозрительные = []
    for ф in файлы:
        причины = чем_опасен(ф, корень)
        if причины:
            подозрительные.append((ф.relative_to(корень), причины))

    print(f"Папка: {корень}")
    подпись = "" if под_git else "  (истории версий ещё нет — считаю всё, кроме закрытого в исключениях)"
    print(f"Уедет файлов: {len(файлы)}{подпись}")
    print()

    if not подозрительные:
        print("✅ Ничего похожего на личное не нашлось.")
        print("   Всё равно пролистайте список глазами: машина ищет по именам и расширениям,")
        print("   а ваши данные могут лежать в файле с любым названием.")
        return

    print(f"⚠️  Похоже на личное — {len(подозрительные)} шт. Это НЕ должно уезжать на полку:\n")
    for путь, причины in подозрительные[:60]:
        print(f"   {путь}")
        print(f"      ← {', '.join(причины)}")
    if len(подозрительные) > 60:
        print(f"   … и ещё {len(подозрительные) - 60}")

    сырые = sorted({
        (str(п.parent) + "/") if str(п.parent) != "." else п.name for п, _ in подозрительные
    })
    # «данные/» уже закрывает «данные/чеки/» — вложенные не пишем, чтобы список читался
    правила = [
        п for п in сырые
        if not any(д != п and п.startswith(д) for д in сырые if д.endswith("/"))
    ]
    print("\nЧто добавить в `.gitignore`, чтобы это осталось дома:\n")
    for п in правила:
        print(f"   {п}")

    if args.закрыть:
        файл = корень / ".gitignore"
        было = файл.read_text(encoding="utf-8") if файл.exists() else ""
        новые = [п for п in правила if п not in было]
        if новые:
            шапка = (было.rstrip("\n") + "\n\n") if было.strip() else ""
            файл.write_text(
                шапка + "# Личное — на полку не уезжает (ядро/скрипты/что_уедет.py)\n"
                + "\n".join(новые) + "\n",
                encoding="utf-8",
            )
            print(f"\n✅ Дописано в .gitignore правил: {len(новые)}")
            куда = "" if корень == Path.cwd() else f' "{корень}"'
            print(f"   Проверьте ещё раз: .venv/bin/python ядро/скрипты/что_уедет.py{куда}")
        else:
            print("\n.gitignore уже всё это закрывает.")
    else:
        print("\nДописать автоматически: добавьте к команде --закрыть")
        print("⛔ Уже выложенное не лечится удалением файла: он остаётся в истории.")
        print("   Если личное уже уехало — репозиторий надо удалить и создать заново.")


if __name__ == "__main__":
    main()
