"""Каноны портрета: чьё лицо в кадре, откуда оно берётся и как этот кадр снят.

`заказ.py` умеет попросить кадр нужной формы: вырез или фотографию, на светлом фоне или на
тёмном, такой-то крупности и пропорции. Чего он не знает — **кто** на этом кадре. Портрет тем и
отличается от фона и от предмета: фон безличен и переделывается одной командой, а лицо на первом
экране видят чужие люди, и оно обязано быть лицом владельца сайта, а не «специалиста вообще».

Отсюда три правила, ради которых заведён этот модуль:

1. **Лицо и причёска — только с опорных снимков владельца, и ровно с них.** Не с фотографии
   знакомого, не с прошлого нарисованного кадра, не «похоже на описание». Снимков нужно три
   (`НОРМА_СЕЛФИ`): с одного генератор усредняет и рисует похожего человека, а не этого;
   три снимка с разных сторон закрепляют лицо. Больше трёх не помогает: остальные размывают.
2. **Фигура — словами, а не картинкой.** Ростовой снимок, приложенный образцом, тянет на себя
   внимание генератора и сбивает лицо; то же телосложение, сказанное одной строкой, лицо не
   трогает. Поэтому `телосложение` — текстовое поле профиля, а образцы — только портретные.
3. **Что в кадре обязано быть и чего в нём не бывает — решает владелец, а не система.** У одного
   это очки, которые он не снимает, у другого — рабочая форма, у третьего — «никогда без бороды».
   Наш код этих списков не знает и знать не может: он читает `всегда` и `никогда` из профиля.

⭐ **Отчуждаемость.** В модуле нет ни одного личного слова: ни имени, ни ниши, ни чьего-то списка
запретов. Всё личное живёт в `профили/<имя>/profile.json` → `внешность` (формат — `ядро/профиль.md`
§ 6), а жанр съёмки выводится из схемы обложки, которую человек уже выбрал на витрине.

**Жанр не спрашивается заново.** Свет, крупность и объектив портрета зависят от жанра — студийный,
деловой, живой кадр в своей среде. Но человек на витрине обложек уже ответил на этот вопрос,
когда выбирал схему: «орбита» и «центр» просят вырез на ровном фоне — это студия; «разворот»
кладёт под лицо плашку «имя · опора» — это деловой портрет-визитка; «сцена» показывает среду во
весь экран — это живой кадр. Спрашивать второй раз то же самое другими словами — способ получить
два разных ответа. Ниша (роль из профиля) внутри жанра решает не свет и не объектив, а во что
человек одет и в какой среде стоит: `одежда` из профиля, а нет её — выводим по роли и говорим,
что вывели.

**Портрет ставится только по «да» человека** (`нужен_показ`): решение владелицы 13.09.2026 —
«портрет — с показом и словом человека, остальное система ставит сама». Фон, предмет и мокап
безличны и переделываются одной командой; лицо — нет.

Команда — посмотреть, что система скажет генератору про внешность, до всякой генерации:

    .venv/bin/python ядро/скрипты/портрет.py <профиль> --схема орбита
    .venv/bin/python ядро/скрипты/портрет.py сайты/моё-дело --схема разворот   # профиль из работы
"""
