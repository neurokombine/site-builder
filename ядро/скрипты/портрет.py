# ── поля профиля ─────────────────────────────────────────────────────────────
def раздел(профиль: dict | None) -> dict:
    """Раздел «внешность» профиля. Нет его или он не словарь — пустой словарь, а не падение:
    профиль ученика мог быть заведён до того, как этот раздел появился."""
    свой = (профиль or {}).get(ПОЛЕ) if isinstance(профиль, dict) else None
    return свой if isinstance(свой, dict) else {}


def _строка(данные: dict, ключ: str) -> str:
    return str(данные.get(ключ) or "").strip()


def _список(данные: dict, ключ: str) -> list[str]:
    значение = данные.get(ключ)
    if isinstance(значение, str):
        значение = [значение]
    return [str(з).strip() for з in значение or [] if str(з).strip()]


def _пути_селфи(данные: dict, папка: Path | None) -> list[Path]:
    основа = Path(папка) if папка else Path(".")
    return [основа / п for п in _список(данные, "селфи")]


def проверить_снимок(файл: Path) -> str:
    """Пусто — снимок годится образцом. Иначе одной фразой, что с ним не так.

    Мерим то, что видно из файла: есть ли он вообще, картинка ли это и не мельче ли он клетки,
    по которой генератор считывает черты. Похоже ли на владельца — не наше дело: это видно
    человеку, а не скрипту, и он скажет об этом при показе кадра.
    """
    файл = Path(файл)
    if not файл.is_file():
        return "файла нет на диске"
    try:
        картинка = _открыть(файл)
    except (OSError, ValueError):
        return "это не картинка — Pillow его не открывает"
    сторона = min(картинка.size)
    if сторона < МИН_СТОРОНА:
        return (f"снимок мелкий: короткая сторона {сторона} px при нужных {МИН_СТОРОНА} — "
                f"лицо на нём меньше, чем генератор различает")
    if обложка.доля_прозрачного(файл) > обложка.ПОРОГ_ПРОЗРАЧНОГО:
        return "это вырез с прозрачным фоном, а образцом лица нужен обычный снимок"
    return ""


def селфи(профиль: dict | None, папка: Path | None = None, *,
          лицо_обязательно: bool = True) -> tuple[list[Path], list[dict]]:
    """Опорные снимки владельца и находки про них. Возвращаем только годные — и только три.

    Негодный снимок молча не пропускаем: пустое место в наборе бьёт по сходству ровно так же,
    как чужое лицо, и человек об этом узнает не из кадра, а из строки в отчёте.
    """
    данные = раздел(профиль)
    найденное: list[dict] = []
    все = _пути_селфи(данные, папка)
    годные, плохие = [], []
    for путь in все:
        беда = проверить_снимок(путь)
        (плохие if беда else годные).append((путь, беда))
    if плохие:
        найденное.append(находка(
            ПОПРАВИТЬ, "Снимок-образец не годится",
            [f"{путь} — {беда}" for путь, беда in плохие],
            "лицо берётся только с этих снимков: чем их меньше, тем сильнее генератор "
            "«додумывает» черты"))
    пути = [путь for путь, _ in годные]
    if len(пути) > НОРМА_СЕЛФИ:
        найденное.append(находка(
            К_СВЕДЕНИЮ, f"Снимков больше трёх — беру первые {НОРМА_СЕЛФИ}",
            [f"в профиле их {len(пути)}"],
            f"канон — ровно {НОРМА_СЕЛФИ}: остальные не добавляют сходства, а размывают его"))
        пути = пути[:НОРМА_СЕЛФИ]
    if not пути:
        найденное.append(находка(
            ЧИНИТЬ if лицо_обязательно else ПОПРАВИТЬ,
            "Нет ваших снимков — рисовать лицо не с чего",
            [f"в профиле пусто: {ПОЛЕ} → селфи"],
            "лицо на первом экране видят чужие люди, и оно должно быть вашим. Снимите три "
            "портрета на телефон при обычном свете: анфас, вполоборота и с обычной для вас "
            "улыбкой — и впишите их в профиль (`ядро/профиль.md` § 6)"))
    elif len(пути) < НОРМА_СЕЛФИ:
        найденное.append(находка(
            ПОПРАВИТЬ, f"Снимков меньше трёх — их {len(пути)}",
            [str(п) for п in пути],
            "с одного снимка генератор усредняет черты и рисует похожего человека, а не вас; "
            "три снимка с разных сторон держат лицо"))
    return пути, найденное


def одежда_по_умолчанию(имя_жанра: str, роль: str = "") -> str:
    """Во что одет, когда в профиле про одежду не сказано.

    Не вкус и не мода: нейтральная строка, которая ничего не выдумывает про человека. Живой кадр
    в своей среде просит рабочей одежды этого дела, портрет — обычной для дела и однотонной,
    чтобы кадр не спорил с палитрой страницы. Роль подставляется, если она есть в профиле.
    """
    дело = f" — {роль.strip().rstrip('.')}" if роль.strip() else ""
    если = "рабочая, в которой это дело и делают" if имя_жанра == "лайфстайл" else "обычная для этого дела"
    return f"{если}{дело}; однотонная, без надписей и логотипов"


def собрать_внешность(профиль: dict | None, схема: str, тип: str, *, папка: Path | None = None,
                      роль: str = "", лицо_обязательно: bool = True,
                      свои_рефы=()) -> tuple[str, list[Path], list[dict]]:
    """Профиль + схема → (блок внешности одной строкой, снимки-образцы, находки).

    Блок уходит в `заказ.собрать_промт(внешность=…)` и встаёт там сразу после «что в кадре» — до
    фона и крупности. Порядок предложений внутри блока тот же, в каком его читает генератор:
    сперва кто это, потом какой он, потом что на нём, и только потом — как снято.

    Одной строкой, без переносов: этот же текст уезжает в таблицу журнала работы, а перенос
    внутри ячейки её ломает.
    """
    данные = раздел(профиль)
    имя_жанра = жанр(схема, тип)
    найденное: list[dict] = []
    if свои_рефы:
        снимки = [Path(р) for р in свои_рефы]
        найденное.append(находка(
            К_СВЕДЕНИЮ, "Беру снимки из команды, а не из профиля",
            [str(р) for р in снимки],
            "лицо возьмётся с них; снимки разных людей в одном заказе смешивать нельзя — "
            "получится третий человек"))
    else:
        снимки, найденное = селфи(профиль, папка, лицо_обязательно=лицо_обязательно)

    части = [С_ОБРАЗЦОВ if снимки else БЕЗ_ОБРАЗЦОВ]

    телосложение = _строка(данные, "телосложение")
    if телосложение:
        части.append(f"Телосложение: {телосложение.rstrip('.')}")
    else:
        найденное.append(находка(
            ПОПРАВИТЬ, "Телосложение не описано",
            [f"пусто: {ПОЛЕ} → телосложение"],
            "снимки-образцы показывают лицо, а фигуру генератор придумает свою — и человек на "
            "кадре окажется другой комплекции. Хватит одной строки словами; ростовое фото "
            "образцом не прикладываем, оно сбивает лицо"))

    приметы = _строка(данные, "приметы")
    if приметы:
        части.append(f"Что важно не перепутать: {приметы.rstrip('.')}")

    одежда = _строка(данные, "одежда")
    if not одежда:
        одежда = одежда_по_умолчанию(имя_жанра, роль)
        найденное.append(находка(
            ПОПРАВИТЬ, "Про одежду в профиле не сказано — взял по умолчанию",
            [f"в промт ушло: «{одежда}»"],
            "одежда на первом экране говорит о деле не меньше лица; не понравится — впишите "
            f"своё в профиль ({ПОЛЕ} → одежда)"))
    части.append(f"Одежда: {одежда.rstrip('.')}")

    всегда = _список(данные, "всегда")
    if всегда:
        части.append(f"Обязательно в кадре: {'; '.join(з.rstrip('.') for з in всегда)}")
    никогда = _список(данные, "никогда")
    if никогда:
        части.append(f"Никогда: {'; '.join(з.rstrip('.') for з in никогда)}")
    if not всегда and not никогда:
        найденное.append(находка(
            К_СВЕДЕНИЮ, "Списки «всегда» и «никогда» пустые",
            [f"{ПОЛЕ} → всегда, {ПОЛЕ} → никогда"],
            "сюда пишут то, что генератор угадать не может и в чём вы себя не узнаете: очки, "
            "которые не снимаете, форму, кольцо, — и то, чего у вас не бывает никогда. "
            "Заполняется по ходу: увидели на кадре чужое — строкой в «никогда», и больше не "
            "повторится"))

    части.append(ЖАНРЫ[имя_жанра])
    части.append(ЖИВОЕ_ЛИЦО)
