def жанр(схема: str, тип: str) -> str:
    """«студия» · «деловой» · «лайфстайл» — из схемы, которую человек уже выбрал на витрине.

    Вырез (орбита, центр, живой портрет) снимается на ровном однотонном фоне и приводится к общей
    рамке — это студия по устройству, а не по вкусу. Схемы с плашкой «имя · опора» показывают
    портрет-визитку рядом с текстом — деловой. Схемы, где кадр занимает весь экран и человек стоит
    внутри своего дела, — живой кадр. Всё остальное (плитка, товар) сводим к деловому: он самый
    спокойный и ничем не рискует.
    """
    if тип in обложка.СХЕМЫ_ВЫРЕЗА:
        return "студия"
    if схема in обложка.СХЕМЫ_ПЛАШКИ:
        return "деловой"
    if схема in СХЕМЫ_СРЕДЫ:
        return "лайфстайл"
    return "деловой"


