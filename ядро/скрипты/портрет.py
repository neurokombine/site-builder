def прочитать_профиль(путь: Path) -> tuple[dict | None, Path | None, str]:
    """Профиль по пути: папка профиля, сам `profile.json` или папка работы (тогда — её профиль)."""
    путь = Path(путь)
    if путь.is_file():
        return json.loads(путь.read_text(encoding="utf-8-sig")), путь.parent, ""
    if (путь / "profile.json").is_file():
        файл = путь / "profile.json"
        return json.loads(файл.read_text(encoding="utf-8-sig")), путь, ""
    if (путь / "прототип.md").is_file():
        import собрать
        данные, папка, беда = собрать._профиль(путь)
        return данные, папка, беда
    import профиль as профили
    папка = профили.ПРОФИЛИ / путь.name
    if (папка / "profile.json").is_file():
        файл = папка / "profile.json"
        return json.loads(файл.read_text(encoding="utf-8-sig")), папка, ""
    return None, None, f"не нашёл профиля по «{путь}»"


def построить_парсер() -> argparse.ArgumentParser:
    парсер = argparse.ArgumentParser(
        description="Каноны портрета: что система скажет про внешность — до всякой генерации")
    парсер.add_argument("профиль", help="имя профиля, папка профиля или папка работы")
    парсер.add_argument("--схема", default="разворот", help="схема первого экрана")
    парсер.add_argument("--тип", default="", help="вырез или фото; по умолчанию — из рецепта схемы")
    return парсер


def main_с_аргументами(argv) -> int:
    вывод_в_utf8()
    а = построить_парсер().parse_args(argv)
    данные, папка, беда = прочитать_профиль(Path(а.профиль))
    if беда or данные is None:
        print(f"❌ {беда or 'профиль не прочитался'}")
        return 1
    import заказ
    тип = а.тип or заказ.тип_кадра(а.схема)
    if not тип:
        print(f"❌ не знаю схемы «{а.схема}» — её рецепта нет в `ядро/блоки/`")
        return 1
    роль = ((данные.get("автор") or {}).get("роль") or "") if isinstance(данные, dict) else ""
    обязательно = заказ.лицо_обязательно(а.схема, тип)
    блок, снимки, найденное = собрать_внешность(данные, а.схема, тип, папка=папка, роль=роль,
                                                лицо_обязательно=обязательно)
    print(f"Схема «{а.схема}» · кадр: {тип} · жанр съёмки: {жанр(а.схема, тип)}\n")
    print(блок)
    print("\nСнимки-образцы (лицо только с них):")
    for путь in снимки or []:
        print(f"  • {путь}")
    if not снимки:
        print("  — ни одного")
    if нужен_показ(а.схема, тип):
        print("\nПеред показом человеку рядом с кадром должно быть видно:")
        for что, зачем in ЧТО_ПОКАЗАТЬ:
            print(f"  • {что} — {зачем}")
        print(f"\nСлово человека: {СЛОВО_ЧЕЛОВЕКА}")
    for строка in строки_по_уровням(найденное, заголовки_уровней("съёмки")):
        print(строка)
    return код_выхода(найденное)


