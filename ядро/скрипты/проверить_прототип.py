"""Связность прототипа — машинная половина: форма, пресет, гейт, кнопки, цифры, слова.

Зачем. Прототип одобряют поэкранно, и в этом — слепое пятно: каждый экран по отдельности
хорош, а вместе они говорят три разные вещи. Эта половина считает то, что считается: шапку
и статусы, число экранов под пресет, гейт «черновик — а дальше уже написано», ведут ли все
кнопки к одному действию, цифры без источника, стоп-слова и то, что запрещено профилем.
Смысл — одно ли обещание, нарастает ли аргументация, тот ли тон — читает нейросеть по
чек-листу в `ядро/прототип.md` (раздел 8), это скрипт не умеет и не обещает.

Запуск:
    .venv/bin/python ядро/скрипты/проверить_прототип.py сайты/моё-дело/прототип.md
    .venv/bin/python ядро/скрипты/проверить_прототип.py сайты/моё-дело/прототип.md --профиль моё-дело
    .venv/bin/python ядро/скрипты/проверить_прототип.py сайты/моё-дело/прототип.md --без-профиля
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import профиль  # noqa: E402

ЧИНИТЬ = "🔴"       # чинить до вёрстки
ПОПРАВИТЬ = "🟡"    # стоит поправить
К_СВЕДЕНИЮ = "ℹ️"   # к сведению; четвёртого уровня в системе нет
ЗАГОЛОВКИ_УРОВНЕЙ = {
    ЧИНИТЬ: "Чинить до вёрстки",
    ПОПРАВИТЬ: "Стоит поправить",
    К_СВЕДЕНИЮ: "К сведению",
}

ПРЕСЕТЫ = {"визитка": (5, 7), "лендинг": (8, 15)}
СТАТУСЫ_ЭКРАНА = ("черновик", "принят", "переоткрыт")
СТАТУСЫ_ШАПКИ = ("собираем", "принят целиком", "проверен")
ПОЛЯ_ШАПКИ = ("Пресет", "Профиль", "Для кого", "Обещание", "Действие", "Статус")
СЛОТЫ = ("Заголовок", "Подзаголовок", "Список", "Кнопка", "Доказательство", "Картинка",
         "Почему этот экран", "Не делаем")
ОБЯЗАТЕЛЬНЫЕ_СЛОТЫ = ("Заголовок", "Почему этот экран", "Не делаем")
СТОП_СЛОВА = ("легко", "без усилий", "гарантиру", "многие", "лучший", "уникальн", "секретн",
              "только сегодня", "осталось", "успейте", "быстро и просто", "даже вы", "друзья")
СОКРАЩЕНИЯ = {"ИП", "ООО", "ИНН", "ОГРН", "НДС", "ОГЭ", "ЕГЭ", "РФ", "СМИ", "PDF", "HTML"}   # капс, который не капс
ЗАГОЛОВОК_ЭКРАНА = re.compile(r"^## Экран (\d+) · (.+?) · статус: (черновик|принят|переоткрыт)\s*$")
ШАПКА_ПРОТОТИПА = re.compile(r"^# Прототип: (.+)$")
ПОЛЕ = re.compile(r"^- ([А-ЯЁа-яё ]+?): ?(.*)$")
ЧИСЛО = re.compile(r"\d{3,}|\d+\s?(?:%|₽|руб|лет|года?|учеников|клиентов|человек)")   # в остальных слотах
ЛЮБАЯ_ЦИФРА = re.compile(r"\d")                                                       # в слоте Доказательство

ИСТОЧНИКИ = ("источник:", "[проверить]", "[пример]")

ФОРМАТ_НЕ_РАСПОЗНАН = "Это не прототип в нашем формате — формат в ядро/прототип.md"
ФИНАЛЬНАЯ_ФРАЗА = ("Это форма и цифры. Смысл — одно ли обещание, нарастает ли аргументация, "
                    "тот ли тон — читай сам по чек-листу в ядро/прототип.md.")


# ── Находки ──────────────────────────────────────────────────────────────────────────────

def находка(уровень: str, что: str, строки: list[str], чем_грозит: str = "") -> dict:
    """Одна находка: что не так → чем грозит → перечень мест. Стиль — как в `проверить.py`."""
    return {"уровень": уровень, "что": что, "чем_грозит": чем_грозит, "строки": строки}


# ── Разбор ───────────────────────────────────────────────────────────────────────────────

def _новый_экран(номер: int, название: str, статус: str) -> dict:
    return {
        "номер": номер, "название": название, "статус": статус,
        "слоты": {}, "задача": "", "_счёт_строк": 1,
    }


def _закрыть_экран(экран: dict | None) -> None:
    """Переводит служебный счётчик строк в поле «строка» — сколько строк занял экран."""
    if экран is not None and "_счёт_строк" in экран:
        экран["строка"] = экран.pop("_счёт_строк")


def разобрать(текст: str) -> list[dict]:
    """Текст прототипа → список прототипов: `{имя, шапка, экраны}`.

    Один файл почти всегда — один прототип; эталон — исключение с несколькими, каждый
    начинается со своей строки `# Прототип:` (граница: шапка и счётчик экранов сбрасываются).
    Пустые строки и `---` внутри и между прототипами молча пропускаются, как и всё до первой
    строки `# Прототип:` (преамбула файла).
    """
    прототипы: list[dict] = []
    текущий: dict | None = None
    текущий_экран: dict | None = None
    текущий_слот: str | None = None

    for сырая in текст.splitlines():
        строка = сырая.rstrip("\r\n")
        очищ = строка.strip()

        if очищ == "" or очищ == "---":
            if текущий_экран is not None:
                текущий_экран["_счёт_строк"] += 1
            continue

        совпадение = ШАПКА_ПРОТОТИПА.match(строка)
        if совпадение:
            _закрыть_экран(текущий_экран)
            текущий = {"имя": совпадение.group(1).strip(), "шапка": {}, "экраны": []}
            прототипы.append(текущий)
            текущий_экран = None
            текущий_слот = None
            continue

        if текущий is None:
            continue  # преамбула файла — до первого «# Прототип:»

        совпадение = ЗАГОЛОВОК_ЭКРАНА.match(строка)
        if совпадение:
            _закрыть_экран(текущий_экран)
            текущий_экран = _новый_экран(
                int(совпадение.group(1)), совпадение.group(2).strip(), совпадение.group(3))
            текущий["экраны"].append(текущий_экран)
            текущий_слот = None
            continue

        if текущий_экран is None:
            # строка шапки прототипа: - Ключ: значение
            совпадение = ПОЛЕ.match(строка)
            if совпадение:
                текущий["шапка"][совпадение.group(1).strip()] = совпадение.group(2).strip()
            continue

        текущий_экран["_счёт_строк"] += 1

        if строка.startswith("Задача экрана:"):
            текущий_экран["задача"] = строка.split(":", 1)[1].strip()
            continue

        if строка[:1].isspace() and очищ.startswith("- "):
            # подстрока внутри слота: только «или:» и «почему:» — подслоты,
            # всё остальное на этом отступе — пункт «Список» (даже если внутри есть двоеточие)
            содержимое = очищ[2:]
            if содержимое.startswith("или:"):
                if текущий_слот:
                    значение = содержимое.split(":", 1)[1].strip()
                    текущий_экран["слоты"].setdefault(текущий_слот, []).append(значение)
            elif содержимое.startswith("почему:"):
                pass  # слова в «почему:» не считаются нигде дальше — отбрасываем
            elif текущий_слот:
                текущий_экран["слоты"].setdefault(текущий_слот, []).append(содержимое.strip())
            continue

        совпадение = ПОЛЕ.match(строка)
        if совпадение:
            имя_слота = совпадение.group(1).strip()
            значение = совпадение.group(2).strip()
            текущий_слот = имя_слота
            слот = текущий_экран["слоты"].setdefault(имя_слота, [])
            if значение:
                слот.append(значение)
            continue
        # неопознанная строка — молча пропускаем

    _закрыть_экран(текущий_экран)
    return прототипы


# ── Проверки ─────────────────────────────────────────────────────────────────────────────

def _слов(текст: str) -> int:
    """Число слов: токен из одной пунктуации (одиночное тире) словом не считается."""
    return len([т for т in текст.split() if any(з.isalnum() for з in т)])


def _с_источником(текст: str) -> bool:
    return any(метка in текст for метка in ИСТОЧНИКИ)


def _нормализовать(текст: str) -> str:
    return " ".join(текст.lower().split())


def _заголовок_находки(экран: dict) -> list[dict]:
    результат: list[dict] = []
    N = экран["номер"]
    заголовки = экран["слоты"].get("Заголовок", [])
    if заголовки:
        варианты = len(заголовки) - 1
        if варианты < 2:
            результат.append(находка(
                ПОПРАВИТЬ,
                f"у заголовка экрана {N} одна «или» или ни одной — нужны два варианта "
                "с других углов", []))
        for текст in заголовки:
            if текст.endswith("."):
                результат.append(находка(
                    ЧИНИТЬ, f"точка в конце заголовка на экране {N}: «{текст}»", []))
            if _слов(текст) > 10:
                результат.append(находка(
                    ПОПРАВИТЬ, f"заголовок экрана {N} длиннее 10 слов: «{текст}»", []))

    for текст in экран["слоты"].get("Подзаголовок", []):
        if _слов(текст) > 20:
            результат.append(находка(
                ПОПРАВИТЬ, f"подзаголовок экрана {N} длиннее 20 слов: «{текст}»", []))

    список = экран["слоты"].get("Список", [])
    if список and not (3 <= len(список) <= 5):
        результат.append(находка(
            ПОПРАВИТЬ, f"{len(список)} пунктов в списке на экране {N} (нужно 3–5)", []))

    return результат


def _кнопка_находки(экран: dict, первый: bool, последний: bool, действие_шапки: str) -> list[dict]:
    результат: list[dict] = []
    N = экран["номер"]
    кнопка = экран["слоты"].get("Кнопка", [])
    основная = кнопка[0].strip() if кнопка else "нет"

    if _нормализовать(основная) == "нет":
        if первый:
            результат.append(находка(ЧИНИТЬ, f"на первом экране нет кнопки (экран {N})", []))
        elif последний:
            результат.append(находка(ЧИНИТЬ, f"на последнем экране нет кнопки (экран {N})", []))
        return результат

    if "→" not in основная:
        результат.append(находка(
            ЧИНИТЬ, f"у кнопки нет действия на экране {N}: «{основная}»", []))
        return результат

    действие_кнопки = основная.split("→", 1)[1].strip()
    if _нормализовать(действие_кнопки) != _нормализовать(действие_шапки):
        результат.append(находка(
            ЧИНИТЬ,
            f"кнопки ведут в разные места: экран {N} → «{действие_кнопки}», "
            f"а в шапке действие — «{действие_шапки}»", []))
    return результат


def _числовые_находки(экран: dict) -> list[dict]:
    результат: list[dict] = []
    N = экран["номер"]
    for имя_слота, значения in экран["слоты"].items():
        for текст in значения:
            совпало = ЛЮБАЯ_ЦИФРА.search(текст) if имя_слота == "Доказательство" \
                else ЧИСЛО.search(текст)
            if совпало and not _с_источником(текст):
                результат.append(находка(
                    ПОПРАВИТЬ, f"цифра без источника: «{текст}» на экране {N} (слот «{имя_слота}»)", []))
    return результат


def _текстовые_находки(экран: dict, нельзя_говорить: list[str]) -> list[dict]:
    результат: list[dict] = []
    N = экран["номер"]
    части = [экран.get("задача", "")]
    for значения in экран["слоты"].values():
        части.extend(значения)
    весь_текст = " ".join(части)
    низ = весь_текст.lower()

    for слово in СТОП_СЛОВА:
        if слово in низ:
            результат.append(находка(ПОПРАВИТЬ, f"стоп-слово «{слово}» на экране {N}", []))

    увиденные: set[str] = set()
    for токен in re.findall(r"[А-ЯЁа-яё]+", весь_текст):
        if токен.isupper() and len(токен) >= 4 and токен not in СОКРАЩЕНИЯ and токен not in увиденные:
            увиденные.add(токен)
            результат.append(находка(ПОПРАВИТЬ, f"капс: «{токен}» на экране {N}", []))

    if "!!" in весь_текст:
        результат.append(находка(ПОПРАВИТЬ, f"«!!» на экране {N}", []))

    for фраза in нельзя_говорить:
        if фраза and фраза.lower() in низ:
            результат.append(находка(
                ЧИНИТЬ, f"на экране {N} то, что нельзя говорить: «{фраза}»", []))

    return результат


def проверить_прототип(прототип: dict, нельзя_говорить: list[str] | None = None,
                       тип_из_профиля: str | None = None) -> list[dict]:
    """Форма, пресет, гейт, кнопки, цифры, стоп-слова и запреты профиля — одним списком находок."""
    нельзя_говорить = нельзя_говорить or []
    находки: list[dict] = []
    шапка = прототип.get("шапка", {})
    экраны = прототип.get("экраны", [])

    for поле in ПОЛЯ_ШАПКИ:
        if not шапка.get(поле, "").strip():
            находки.append(находка(ЧИНИТЬ, f"в шапке нет поля «{поле}»", []))

    пресет = шапка.get("Пресет", "").strip()
    if пресет and пресет not in ПРЕСЕТЫ:
        находки.append(находка(ЧИНИТЬ, f"пресет «{пресет}» не «визитка» и не «лендинг»", []))

    статус_шапки = шапка.get("Статус", "").strip()
    if статус_шапки and статус_шапки not in СТАТУСЫ_ШАПКИ:
        находки.append(находка(ЧИНИТЬ, f"статус в шапке «{статус_шапки}» не из списка", []))

    if пресет in ПРЕСЕТЫ:
        мин, макс = ПРЕСЕТЫ[пресет]
        кол_во = len(экраны)
        if кол_во < мин:
            находки.append(находка(
                ЧИНИТЬ, f"мало экранов: {кол_во} при пресете {пресет} (нужно {мин}–{макс})", []))
        elif кол_во > макс:
            находки.append(находка(
                ЧИНИТЬ, f"много экранов: {кол_во} при пресете {пресет} (нужно {мин}–{макс})", []))

    if экраны and экраны[0]["название"] != "Первый экран":
        находки.append(находка(
            ПОПРАВИТЬ,
            f"экран 1 назван «{экраны[0]['название']}», а должен называться «Первый экран»", []))

    for i, экран in enumerate(экраны):
        ожидаемый = i + 1
        if экран["номер"] != ожидаемый:
            находки.append(находка(
                ЧИНИТЬ,
                f"разрыв в нумерации экранов: экран №{экран['номер']} стоит на месте "
                f"{ожидаемый}-го по счёту", []))

    if статус_шапки in ("принят целиком", "проверен"):
        for экран in экраны:
            if экран["статус"] != "принят":
                находки.append(находка(
                    ЧИНИТЬ,
                    f"шапка говорит «{статус_шапки}», а экран {экран['номер']} — "
                    f"{экран['статус']}", []))

    увиденные_заголовки: dict[str, int] = {}

    for i, экран in enumerate(экраны):
        первый = i == 0
        последний = i == len(экраны) - 1
        N = экран["номер"]

        for слот in ОБЯЗАТЕЛЬНЫЕ_СЛОТЫ:
            if not экран["слоты"].get(слот):
                находки.append(находка(ЧИНИТЬ, f"на экране {N} нет слота «{слот}»", []))

        if первый and not экран["слоты"].get("Подзаголовок"):
            находки.append(находка(ПОПРАВИТЬ, f"на первом экране нет подзаголовка", []))

        находки += _заголовок_находки(экран)
        находки += _кнопка_находки(экран, первый, последний, шапка.get("Действие", "").strip())
        находки += _числовые_находки(экран)
        находки += _текстовые_находки(экран, нельзя_говорить)

        if экран["статус"] == "черновик" and i + 1 < len(экраны):
            следующий = экраны[i + 1]
            находки.append(находка(
                ПОПРАВИТЬ,
                f"экран {N} не принят, а экран {следующий['номер']} уже написан", []))
        elif экран["статус"] == "переоткрыт":
            находки.append(находка(
                К_СВЕДЕНИЮ, f"экран {N} переоткрыт — проверьте, что правка уже сделана", []))

        if экран.get("строка", 0) > 40:
            находки.append(находка(К_СВЕДЕНИЮ, f"экран {N} длинный", []))

        главный_заголовок = (экран["слоты"].get("Заголовок") or [None])[0]
        if главный_заголовок is not None:
            if главный_заголовок in увиденные_заголовки:
                находки.append(находка(
                    ПОПРАВИТЬ,
                    f"заголовок экрана {N} повторяет заголовок экрана "
                    f"{увиденные_заголовки[главный_заголовок]}: «{главный_заголовок}»", []))
            else:
                увиденные_заголовки[главный_заголовок] = N

    if тип_из_профиля and пресет and тип_из_профиля != пресет:
        находки.append(находка(
            ПОПРАВИТЬ, f"тип из профиля «{тип_из_профиля}», а пресет «{пресет}»", []))

    return находки


# ── Отчёт ────────────────────────────────────────────────────────────────────────────────

def отчёт_словами(прототип: dict, находки: list[dict]) -> str:
    """Один и тот же текст — и в консоль, и (если понадобится) в файл рядом с прототипом."""
    шапка = прототип.get("шапка", {})
    пресет = шапка.get("Пресет", "?")
    экранов = len(прототип.get("экраны", []))
    диапазон = ПРЕСЕТЫ.get(пресет)
    норма = f"{диапазон[0]}–{диапазон[1]}" if диапазон else "?"

    строки = [f"Прототип «{прототип.get('имя', '?')}»: пресет {пресет}, "
              f"экранов {экранов} (норма {норма})"]

    for уровень in (ЧИНИТЬ, ПОПРАВИТЬ, К_СВЕДЕНИЮ):
        свои = [н for н in находки if н["уровень"] == уровень]
        строки += ["", f"{уровень} {ЗАГОЛОВКИ_УРОВНЕЙ[уровень]} — {len(свои)}"]
        if not свои:
            строки.append("Ничего не нашлось.")
            continue
        for н in свои:
            строки.append(f"- {н['что']}")
            if н.get("чем_грозит"):
                строки.append(f"  Чем грозит: {н['чем_грозит']}.")

    строки += ["", ФИНАЛЬНАЯ_ФРАЗА, ""]
    return "\n".join(строки)


# ── Профиль ──────────────────────────────────────────────────────────────────────────────

def _прочитать_профиль(имя: str) -> tuple[list[str], str | None, dict | None]:
    """Читает `профили/<имя>/profile.json`. Нет такого — вернёт (пусто, None, None)."""
    файл = профиль.ПРОФИЛИ / имя / "profile.json"
    if not имя or not файл.exists():
        return [], None, None
    try:
        данные = профиль.прочитать_json(файл)
    except профиль.ОшибкаПрофиля:
        return [], None, None
    сайт = данные.get("сайт") if isinstance(данные, dict) else None
    сайт = сайт if isinstance(сайт, dict) else {}
    нельзя_говорить = [ф for ф in (сайт.get("нельзя_говорить") or []) if isinstance(ф, str)]
    тип = str(сайт.get("тип") or "").strip() or None
    return нельзя_говорить, тип, данные


# ── CLI ──────────────────────────────────────────────────────────────────────────────────

def построить_парсер() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(
        description="Проверить прототип: форма, пресет, гейт, кнопки, цифры, стоп-слова, "
                    "запреты из профиля.")
    p.add_argument("файл", help="путь к прототип.md")
    p.add_argument("--профиль", metavar="ИМЯ",
                   help="взять этот профиль вместо указанного в шапке «Профиль:»")
    p.add_argument("--без-профиля", action="store_true",
                   help="не читать профиль вовсе: пропустить «нельзя говорить» и сверку типа")
    return p


def main() -> int:
    аргументы = построить_парсер().parse_args()
    путь = Path(аргументы.файл)

    try:
        текст = путь.read_text(encoding="utf-8")
    except OSError as ошибка:
        print(f"\n⛔ Не получилось прочитать «{путь}»: {ошибка}\n")
        return 2

    прототипы = разобрать(текст)
    if not прототипы or all(not п["экраны"] for п in прототипы):
        print(f"\n⛔ {ФОРМАТ_НЕ_РАСПОЗНАН}\n")
        return 2

    код = 0
    for прототип in прототипы:
        нельзя_говорить: list[str] = []
        тип_из_профиля: str | None = None
        предупреждения: list[dict] = []

        if not getattr(аргументы, "без_профиля"):
            имя_профиля = (аргументы.профиль or прототип["шапка"].get("Профиль", "")).strip()
            нельзя_говорить, тип_из_профиля, данные = _прочитать_профиль(имя_профиля)
            if данные is None:
                предупреждения.append(находка(
                    К_СВЕДЕНИЮ,
                    f"профиль «{имя_профиля}» не найден, проверку „нельзя_говорить“ "
                    "и типа пропускаю", []))

        находки = предупреждения + проверить_прототип(прототип, нельзя_говорить, тип_из_профиля)
        print(отчёт_словами(прототип, находки))
        if any(н["уровень"] == ЧИНИТЬ for н in находки):
            код = 1

    return код


if __name__ == "__main__":
    sys.exit(main())
