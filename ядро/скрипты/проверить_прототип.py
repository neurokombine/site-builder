def _чипы_длиной_находки(экран: dict, схема: str) -> list[dict]:
    """Фикс-раунд В (хвост фикс-раунда А): у схем-ярлыков витрина сама сократит длинный чип, и
    вёрстка будет цела — а смысл нет. Предупреждаем на прототипе, где текст ещё можно переписать."""
    if схема not in СХЕМЫ_ЯРЛЫКА:
        return []
    слот = экран["слоты"].get("Чипы")
    if not слот or _это_нет(слот):
        return []
    результат: list[dict] = []
    for строка in слот:
        заголовок, _, пояснение = строка.partition("·")
        for часть, предел, имя in ((заголовок.strip(" —"), ПРЕДЕЛ_ЯРЛЫКА, "заголовок"),
                                   (пояснение.strip(), ПРЕДЕЛ_ПОЯСНЕНИЯ, "пояснение")):
            if len(часть) > предел:
                результат.append(находка(
                    ПОПРАВИТЬ, f"{имя} чипа длиннее предела ({len(часть)} знаков против {предел}): "
                               f"«{часть}» — схема «{схема}» обрежет, перепишите короче", []))
    return результат


def _вторая_ссылка_находки(текст: str, N: int, всего_экранов: int) -> list[dict]:
    """`- Вторая ссылка: Тарифы и цены → экран 8` — текст контурной кнопки и номер экрана."""
    цель = текст.rsplit("→", 1)[1].strip() if "→" in текст else ""
    куда = re.fullmatch(r"экран\s+(\d+)", _нормализовать(цель))
    if not куда:
        return [находка(
            ПОПРАВИТЬ,
            f"вторая ссылка на экране {N} без цели: «{текст}» — пишется "
            "«- Вторая ссылка: <текст кнопки> → экран N»", [])]
    номер = int(куда.group(1))
    if not (1 <= номер <= всего_экранов):
        return [находка(
            ПОПРАВИТЬ,
            f"вторая ссылка с экрана {N} ведёт на экран {номер}, а экранов "
            f"{всего_экранов}", [])]
    return []


def _поля_экрана_находки(экран: dict, всего_экранов: int) -> list[dict]:
    """Поля-переключатели: значение должно быть из списка, а не любое.

    «Вид цены» выбирает файл блока цен, «Подсветить» — какая карточка тарифа станет главной.
    Оба необязательны: нет поля — система берёт умолчание (вид цены по пресету, подсвечена
    средняя карточка), и это не находка. А вот значение мимо списка — 🟡: молча взятое
    умолчание человек примет за свой выбор.
    """
    результат: list[dict] = []
    N = экран["номер"]

    вид = (экран["слоты"].get("Вид цены") or [""])[0]
    if вид and not _это_нет([вид]) and _нормализовать(вид) not in ВИДЫ_ЦЕНЫ:
        результат.append(находка(
            ПОПРАВИТЬ,
            f"нет такого вида цены «{вид}» на экране {N} — бывают "
            f"«{'» и «'.join(ВИДЫ_ЦЕНЫ)}»", []))

    подсветить = (экран["слоты"].get("Подсветить") or [""])[0]
    if подсветить and not _это_нет([подсветить]):
        имена = [разделить_пункт(п)[0] for п in экран["слоты"].get("Список", [])]
        if _нормализовать(подсветить) not in [_нормализовать(и) for и in имена]:
            где = ("; на экране есть «" + "», «".join(имена) + "»") if имена else \
                  "; списка тарифов на экране нет вовсе"
            результат.append(находка(
                ПОПРАВИТЬ,
                f"подсвечивать нечего: тарифа «{подсветить}» нет на экране {N}{где}", []))

    for текст in экран["слоты"].get("Вторая ссылка", []):
        if _это_нет([текст]):
            continue
        результат += _вторая_ссылка_находки(текст, N, всего_экранов)

    return результат


def _первый_экран_находки(экран: dict, схема_снаружи: str | None) -> list[dict]:
    """Поля вёрстки первого экрана: общие — всегда, по схеме — когда схема уже выбрана."""
    результат = _кикер_находки(экран, обязателен=True) + _верхняя_строка_находки(экран)
    в_слоте = (экран["слоты"].get("Схема") or [""])[0]
    схема = нормальная_схема(схема_снаружи or в_слоте)
    if not схема or схема == СХЕМА_НЕ_ВЫБРАНА:
        результат.append(находка(
            К_СВЕДЕНИЮ, "схема первого экрана не выбрана — после выбора на витрине переоткрой "
                        "первый экран и допиши, что просит схема (как-работаем.md, 6-ter)", []))
        return результат
    if схема not in ПРОСИТ_СХЕМА:
        результат.append(находка(
            ЧИНИТЬ, f"схема «{схема}» не из одиннадцати: {', '.join(СХЕМЫ)}", []))
        return результат
    просит = ПРОСИТ_СХЕМА[схема]
    результат += _регалии_находки(экран, схема, bool(просит["Регалии"]))
    for поле in ("Чипы", "Подписи роликов"):
        результат += _счётные_находки(экран, схема, поле, int(просит[поле]))
    результат += _чипы_длиной_находки(экран, схема)
    return результат


def проверить_прототип(прототип: dict, нельзя_говорить: list[str] | None = None,
                       тип_из_профиля: str | None = None, схема: str | None = None) -> list[dict]:
    """Форма, пресет, гейт, кнопки, цифры, стоп-слова и запреты профиля — одним списком находок.

    `схема` — имя схемы первого экрана поверх слота `- Схема:` (флаг `--схема`); None — из слота.
    """
    нельзя_говорить = нельзя_говорить or []
    находки: list[dict] = []
    шапка = прототип.get("шапка", {})
    экраны = прототип.get("экраны", [])

    for поле in ПОЛЯ_ШАПКИ:
        if not шапка.get(поле, "").strip():
            находки.append(находка(ЧИНИТЬ, f"в шапке нет поля «{поле}»", []))

    пресет = шапка.get("Пресет", "").strip()
    if пресет and пресет not in ПРЕСЕТЫ:
        находки.append(находка(ЧИНИТЬ, f"пресет «{пресет}» не «визитка» и не «лендинг»", []))

    статус_шапки = шапка.get("Статус", "").strip()
    if статус_шапки and статус_шапки not in СТАТУСЫ_ШАПКИ:
        находки.append(находка(ЧИНИТЬ, f"статус в шапке «{статус_шапки}» не из списка", []))

    if пресет in ПРЕСЕТЫ:
        мин, макс = ПРЕСЕТЫ[пресет]
        кол_во = len(экраны)
        if кол_во < мин:
            находки.append(находка(
                ЧИНИТЬ, f"мало экранов: {кол_во} при пресете {пресет} (нужно {мин}–{макс})", []))
        elif кол_во > макс:
            находки.append(находка(
                ЧИНИТЬ, f"много экранов: {кол_во} при пресете {пресет} (нужно {мин}–{макс})", []))

    if экраны and экраны[0]["название"] != "Первый экран":
        находки.append(находка(
            ПОПРАВИТЬ,
            f"экран 1 назван «{экраны[0]['название']}», а должен называться «Первый экран»", []))

    for i, экран in enumerate(экраны):
        ожидаемый = i + 1
        if экран["номер"] != ожидаемый:
            находки.append(находка(
                ЧИНИТЬ,
                f"разрыв в нумерации экранов: экран №{экран['номер']} стоит на месте "
                f"{ожидаемый}-го по счёту", []))

    if статус_шапки in ("принят целиком", "проверен"):
        for экран in экраны:
            if not экран["статус"]:
                continue    # про такой экран уже сказано отдельной находкой «без статуса»
            if экран["статус"] != "принят":
                находки.append(находка(
                    ЧИНИТЬ,
                    f"шапка говорит «{статус_шапки}», а экран {экран['номер']} — "
                    f"{экран['статус']}", []))

    увиденные_заголовки: dict[str, int] = {}

    for i, экран in enumerate(экраны):
        первый = i == 0
        последний = i == len(экраны) - 1
        N = экран["номер"]

        if not экран["статус"]:
            находки.append(находка(
                ЧИНИТЬ,
                f"экран без статуса: «{экран['заголовок_экрана']}» — строка-заголовок пишется "
                f"так: {ФОРМАТ_ЗАГОЛОВКА}", []))

        for слот in ОБЯЗАТЕЛЬНЫЕ_СЛОТЫ:
            if not экран["слоты"].get(слот):
                находки.append(находка(ЧИНИТЬ, f"на экране {N} нет слота «{слот}»", []))

        if not экран.get("задача", "").strip():
            находки.append(находка(ПОПРАВИТЬ, f"на экране {N} нет задачи экрана", []))

        if первый and not экран["слоты"].get("Подзаголовок"):
            находки.append(находка(ПОПРАВИТЬ, f"на первом экране нет подзаголовка", []))

        находки += _заголовок_находки(экран)
        if первый:
            находки += _первый_экран_находки(экран, схема)
        else:
            находки += _кикер_находки(экран, обязателен=False)
        находки += _поля_экрана_находки(экран, len(экраны))
        находки += _кнопка_находки(экран, первый, последний, шапка.get("Действие", "").strip())
        находки += _числовые_находки(экран)
        находки += _текстовые_находки(экран, нельзя_говорить)

        if экран["статус"] == "черновик" and i + 1 < len(экраны):
            следующий = экраны[i + 1]
            находки.append(находка(
                ПОПРАВИТЬ,
                f"экран {N} не принят, а экран {следующий['номер']} уже написан", []))
        elif экран["статус"] == "переоткрыт":
            находки.append(находка(
                К_СВЕДЕНИЮ, f"экран {N} переоткрыт — проверьте, что правка уже сделана", []))

        if экран.get("строка", 0) > 40:
            находки.append(находка(К_СВЕДЕНИЮ, f"экран {N} длинный", []))

        главный_заголовок = (экран["слоты"].get("Заголовок") or [None])[0]
        if главный_заголовок is not None:
            if главный_заголовок in увиденные_заголовки:
                находки.append(находка(
                    ПОПРАВИТЬ,
                    f"заголовок экрана {N} повторяет заголовок экрана "
                    f"{увиденные_заголовки[главный_заголовок]}: «{главный_заголовок}»", []))
            else:
                увиденные_заголовки[главный_заголовок] = N

    if тип_из_профиля and пресет and тип_из_профиля != пресет:
        находки.append(находка(
            ПОПРАВИТЬ, f"тип из профиля «{тип_из_профиля}», а пресет «{пресет}»", []))

    return находки


# ── Отчёт ────────────────────────────────────────────────────────────────────────────────

def отчёт_словами(прототип: dict, находки: list[dict]) -> str:
    """Один и тот же текст — и в консоль, и (если понадобится) в файл рядом с прототипом."""
    шапка = прототип.get("шапка", {})
    пресет = шапка.get("Пресет", "?")
    экранов = len(прототип.get("экраны", []))
    диапазон = ПРЕСЕТЫ.get(пресет)
    норма = f"{диапазон[0]}–{диапазон[1]}" if диапазон else "?"

    строки = [f"Прототип «{прототип.get('имя', '?')}»: пресет {пресет}, "
              f"экранов {экранов} (норма {норма})"]

    for уровень in (ЧИНИТЬ, ПОПРАВИТЬ, К_СВЕДЕНИЮ):
        свои = [н for н in находки if н["уровень"] == уровень]
        строки += ["", f"{уровень} {ЗАГОЛОВКИ_УРОВНЕЙ[уровень]} — {len(свои)}"]
        if not свои:
            строки.append("Ничего не нашлось.")
            continue
        for н in свои:
            строки.append(f"- {н['что']}")
            if н.get("чем_грозит"):
                строки.append(f"  Чем грозит: {н['чем_грозит']}.")

    строки += ["", ФИНАЛЬНАЯ_ФРАЗА, ""]
    return "\n".join(строки)


# ── Профиль ──────────────────────────────────────────────────────────────────────────────

def _прочитать_профиль(имя: str) -> tuple[list[str], str | None, str | None, dict | None]:
    """Читает `профили/<имя>/profile.json`.

    Возвращает `(нельзя_говорить, тип, беда, данные)` — «беда» пусто, когда профиль прочитан;
    иначе это готовая для человека причина («папки нет» / «битый JSON»), чтобы CLI не путал два
    разных случая в одном и том же сообщении. `данные` — весь прочитанный профиль: по нему
    задача 4 отчуждаемости спрашивает про неукомплектованную палитру (тем же вердиктом, что и
    `проверить.py`), и читать файл второй раз ради этого незачем.
    """
    файл = профиль.ПРОФИЛИ / имя / "profile.json"
    if not имя or not файл.exists():
        return [], None, f"профиль «{имя}» не найден, проверку „нельзя_говорить“ и типа пропускаю", None
    try:
        данные = профиль.прочитать_json(файл)
    except профиль.ОшибкаПрофиля:
        return [], None, (
            f"профиль «{имя}» не читается (ошибка в profile.json) — проверку "
            "„нельзя_говорить“ и типа пропускаю"), None
    сайт = данные.get("сайт") if isinstance(данные, dict) else None
    сайт = сайт if isinstance(сайт, dict) else {}
    нельзя_говорить = [ф for ф in (сайт.get("нельзя_говорить") or []) if isinstance(ф, str)]
    тип = str(сайт.get("тип") or "").strip() or None
    return нельзя_говорить, тип, None, данные


# ── CLI ──────────────────────────────────────────────────────────────────────────────────

def построить_парсер() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(
        description="Проверить прототип: форма, пресет, гейт, кнопки, цифры, стоп-слова, "
                    "запреты из профиля, поля первого экрана по схеме.")
    p.add_argument("файл", help="путь к прототип.md")
    p.add_argument("--профиль", metavar="ИМЯ",
                   help="взять этот профиль вместо указанного в шапке «Профиль:»")
    p.add_argument("--без-профиля", action="store_true",
                   help="не читать профиль вовсе: пропустить «нельзя говорить» и сверку типа")
    p.add_argument("--схема", metavar="ИМЯ",
                   help="схема первого экрана поверх слота «Схема:» (например, орбита)")
    return p


def main() -> int:
    вывод_в_utf8()
    аргументы = построить_парсер().parse_args()
    путь = Path(аргументы.файл)

    try:
        # utf-8-sig: снимает BOM «UTF-8 с BOM» (частый режим Windows-редакторов), если он есть,
        # и ничего не меняет, если его нет.
        текст = путь.read_text(encoding="utf-8-sig")
    except (OSError, UnicodeDecodeError) as ошибка:
        if isinstance(ошибка, UnicodeDecodeError):
            print(f"\n⛔ Файл «{путь}» не в кодировке UTF-8 — сохраните его как UTF-8 "
                  "и запустите снова.\n")
        else:
            print(f"\n⛔ Не получилось прочитать «{путь}»: {ошибка}\n")
        return 2

    прототипы = разобрать(текст)
    if not прототипы or all(not п["экраны"] for п in прототипы):
        print(f"\n⛔ {ФОРМАТ_НЕ_РАСПОЗНАН}\n")
        return 2

    код = 0
    for прототип in прототипы:
        нельзя_говорить: list[str] = []
        тип_из_профиля: str | None = None
        предупреждения: list[dict] = []

        if not getattr(аргументы, "без_профиля"):
            имя_профиля = (аргументы.профиль or прототип["шапка"].get("Профиль", "")).strip()
            нельзя_говорить, тип_из_профиля, беда, данные = _прочитать_профиль(имя_профиля)
            if беда:
                предупреждения.append(находка(К_СВЕДЕНИЮ, беда, []))
            # Задача 4: неполный профиль — 🔴 уже здесь, на шаге прототипа, а не на последнем
            # шаге проверки собранного сайта. Текст один на всю систему (профиль.py).
            предупреждения += профиль.находки_по_комплекту(данные, имя_профиля)

        находки = предупреждения + проверить_прототип(
            прототип, нельзя_говорить, тип_из_профиля, схема=аргументы.схема)
        print(отчёт_словами(прототип, находки))
        if код_выхода(находки):
            код = 1

    return код


if __name__ == "__main__":
    sys.exit(main())
