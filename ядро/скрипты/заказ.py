def тип_кадра(схема: str, пресет: str = "лендинг") -> str:
    """`data-картинка` из рецепта схемы: «фото», «вырез», «видео», «мокап», «товар», «мозаика»…

    Читаем рецепт, а не таблицу в голове: тип кадра — свойство схемы, и живёт оно там же, где
    сама схема. Нет рецепта в этом пресете — смотрим второй (у визитки схем меньше).
    """
    имя = "разворот" if схема == "разворот-слева" else схема
    for набор in (пресет, *(п for п in ПРЕСЕТЫ if п != пресет)):
        файл = собрать.БЛОКИ / набор / f"01-первый-экран-{имя}.html"
        if файл.is_file():
            м = собрать.КАРТИНКА_СЕКЦИИ.search(файл.read_text(encoding="utf-8"))
            if м:
                return м.group(1)
    return ""


def текст_на_кадре(схема: str, пресет: str = "лендинг") -> bool:
    """Лежит ли заголовок прямо на кадре — видно по слоту `{{ДОБОР_ЗАТЕМНЕНИЯ}}` в рецепте.

    Признак не выдуман: этот слот стоит ровно у тех схем, которые притемняют кадр со стороны
    текста (`ядро/дизайн/схемы-обложек.md` § 8), и по нему же сборка решает, мерить светлоту
    полосы или нет.
    """
    имя = "разворот" if схема == "разворот-слева" else схема
    for набор in (пресет, *(п for п in ПРЕСЕТЫ if п != пресет)):
        файл = собрать.БЛОКИ / набор / f"01-первый-экран-{имя}.html"
        if файл.is_file():
            return "{{ДОБОР_ЗАТЕМНЕНИЯ}}" in файл.read_text(encoding="utf-8")
    return False


def пропорция_схемы(схема: str, тип: str) -> str:
    """Какой формат кадра просит схема — «2:3», «3:4», «16:9»…

    Три источника, и все три уже есть в системе, ни одного нового числа:
    • вырез — `обложка.РАМКА_ВЫРЕЗА`: к этой рамке скрипт всё равно приведёт кадр, и просить
      другую пропорцию значит заранее отдать часть кадра под обрезку;
    • фотография — контракт имён файлов (`обложки.ПОДБОР`, `ПОДБОР_СХЕМ`): `-3x4` у разворота,
      `-16x9` у сцены, `-9x16` у товара — там пропорция и записана;
    • мокап — `ПРОПОРЦИЯ_МОКАПА`, единственная названная словами.
    """
    if тип in ("вырез", "живой-портрет"):
        ш, в = обложка.РАМКА_ВЫРЕЗА
        return f"{ш}:{в}"
    if тип == "мокап":
        return ПРОПОРЦИЯ_МОКАПА
    имя = "разворот" if схема == "разворот-слева" else схема
    for подстрока in обложки.ПОДБОР_СХЕМ.get(имя, ()) + обложки.ПОДБОР.get(тип, ()):
        м = РАЗМЕР_В_ИМЕНИ.search(подстрока)
        if м:
            return f"{м.group(1)}:{м.group(2)}"
    return ""


def вилка_головы(схема: str, тип: str) -> tuple[float, float] | None:
    """Какую долю высоты кадра вправе занять голова. Не про вырез: его крупность правит рамка.

    Нижняя и верхняя кромки — `обложка.НОРМА_ГОЛОВЫ_НА_ТЕЛЕФОНЕ`, снятая с утверждённых макетов
    (§ 7-bis). Телефонный кадр режется из исходника по ширине (`обложка.КАДР_ТЕЛЕФОНА` уже
    в этой пропорции), высота не трогается — значит доля головы в исходнике и в телефонном кадре
    одна и та же, и вилку можно просить прямо у генератора.

    У схем с плашкой «имя · опора» верхняя кромка ниже: плашка садится под лицо, и подбородок
    обязан остаться выше `обложка.ПОРОГ_ПОДБОРОДКА`. Считаем честно: подбородок = воздух над
    макушкой + сама голова.
    """
    if тип == "вырез" or not человек_в_кадре(схема, тип):
        return None
    низ, верх = обложка.НОРМА_ГОЛОВЫ_НА_ТЕЛЕФОНЕ
    if схема in обложка.СХЕМЫ_ПЛАШКИ:
        верх = min(верх, обложка.ПОРОГ_ПОДБОРОДКА - ВОЗДУХ_НАД_ГОЛОВОЙ)
    return (низ, верх)


