def _из_шкалы(шкала, значение: float) -> str:
    for предел, слово in шкала:
        if значение < предел:
            return слово
    return шкала[-1][1]


def цвет_словами(hex_цвет: str) -> str:
    """«#2C4A63» → «тёмный приглушённый синий», «#FAF8F5» → «почти белый», «#C8A97E» → «бежевый».

    Считается из цвета, а не подбирается по таблице готовых: палитра у каждого своя, и «глубокий
    синий» в чужой может не встретиться ни разу. Пустая строка — если это не «#RRGGBB».
    """
    цвет = (hex_цвет or "").strip()
    if not re.fullmatch(r"#[0-9a-fA-F]{6}", цвет):
        return ""
    r, g, b = (int(цвет[i:i + 2], 16) / 255 for i in (1, 3, 5))
    тон, светлота, _ = colorsys.rgb_to_hls(r, g, b)
    размах = max(r, g, b) - min(r, g, b)
    if размах < ПОРОГ_СЕРОГО:
        return _из_шкалы(СЕРЫЕ, светлота)
    градусы = тон * 360
    имя = _из_шкалы(ТОНА, градусы)
    тёплый = ТЕПЛЫЕ_ТОНА[0] <= градусы < ТЕПЛЫЕ_ТОНА[1]
    if тёплый and размах < ПРИГЛУШЁН:
        имя = "бежевый" if светлота >= .5 else "коричневый"
    elif размах < ПРИГЛУШЁН:
        имя = f"приглушённый {имя}"
    elif размах > НАСЫЩЕН:
        имя = f"насыщенный {имя}"
    return f"{_из_шкалы(СВЕТЛОТЫ, светлота)} {имя}".strip()


