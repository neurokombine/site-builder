# ── чистая логика (её и проверяют тесты, без единого браузера) ───────────────
def картинка_ленты_годится(снимок: dict | None) -> bool:
    """Годится ли картинка в счёт ленты.

    Грабля 08.09: «любая большая картинка на странице» ловила не то. Иконки в сайдбаре ровно
    512×512, а превью вложения после загрузки отдаётся обычным адресом — порог выполнялся без
    единой генерации, и на диск уезжало исходное фото человека вместо нарисованного кадра.

    ⭐ Наша добавка к переносимому коду: картинки из реплики ЧЕЛОВЕКА (`inUser`) не считаем
    вовсе. У «цеха» вместо этого к порогу прибавляли число вложений — но там реф всегда
    крупный, а нам ученик приложит хоть селфи 400 px, и порог разъедется. Отметке можно
    доверять: отправку мы подтверждаем по этой же разметке (`JS_РЕПЛИКИ`) — не работала бы
    она, до ожидания картинки дело бы не дошло.
    """
    if not снимок or not isinstance(снимок.get("src"), str) or not снимок["src"]:
        return False
    if not ((снимок.get("naturalWidth") or 0) > 500) or not ((снимок.get("naturalHeight") or 0) > 500):
        return False
    if re.search(r"avatar|profile|favicon", снимок["src"]):
        return False
    if снимок["src"].startswith("blob:"):      # blob: — превью вложения, не ответ
        return False
    if снимок.get("inForm"):                   # всё, что внутри формы, — композер
        return False
    if снимок.get("inUser"):                   # это мы сами приложили, а не нам нарисовали
        return False
    return True


def адреса_ленты(снимки) -> list[str]:
    """Адреса картинок ленты по порядку разметки, без повторов: у одной картинки в разметке
    живёт несколько копий — превью и просмотрщик."""
    найдено: dict[str, None] = {}
    for снимок in снимки or []:
        if картинка_ленты_годится(снимок):
            найдено.setdefault(снимок["src"], None)
    return list(найдено)          # словарь помнит порядок вставки, то есть порядок разметки


def шаг_готовности(состояние: dict | None, снимок: dict,
                   мин_ожидание_мс: int = МИН_ОЖИДАНИЕ_МС,
                   стабильно_мс: int = СТАБИЛЬНО_МС) -> dict:
    """Один шаг ожидания картинки — чистое ядро цикла.

    Грабля 08.09: адреса подписанные, при перерисовке к ним дописывается новая метка времени,
    и старая картинка выглядит новой — партия уехала на диск со сдвигом на один ход. Поэтому
    признак готовности — ЧИСЛО картинок ленты, а не «адрес поменялся»; и сверх того последний
    адрес должен постоять неизменным, пока модель дорисовывает.
    """
    прежнее = состояние or {"кандидат": None, "кандидат_с": 0}
    адреса = снимок.get("адреса") or []
    цель, прошло, сейчас = снимок["цель"], снимок["прошло_мс"], снимок["сейчас"]
    if len(адреса) < цель or not прошло > мин_ожидание_мс:
        return {"готово": False, "адрес": None, "состояние": прежнее}
    последний = адреса[-1]
    if последний != прежнее["кандидат"]:
        return {"готово": False, "адрес": None,
                "состояние": {"кандидат": последний, "кандидат_с": сейчас}}
    if сейчас - прежнее["кандидат_с"] > стабильно_мс:
        return {"готово": True, "адрес": последний, "состояние": прежнее}
    return {"готово": False, "адрес": None, "состояние": прежнее}


def композер_свободен(снимок: dict | None) -> bool:
    """Свободен ли композер. Занят, пока висит кнопка «Стоп» или маркер незакрытого ответа.
    Пустой композер с погашенной кнопкой отправки — это как раз свободно, нам подходит."""
    if not isinstance(снимок, dict):
        return False                       # снимок не прочитался — не считаем, что свободно
    if not снимок.get("composer"):
        return False                       # страница ещё не готова
    if (снимок.get("stop") or 0) > 0:
        return False                       # ответ пишется
    if (снимок.get("streaming") or 0) > 0:
        return False
    return True


def разобрать_состояние(признаки: dict) -> dict:
    """Вошли, не вошли или непонятно — по ДВУМ признакам, а не по одному.

    Кнопка входа есть — не вошли. Кнопки нет, а поле для вопроса есть — вошли. Молчат оба
    признака — честно говорим «непонятно» вместо того, чтобы угадать и разбудить человека
    зря: так выглядит проверка на роботов и недогруженная страница.

    ⚠️ Почему кнопка входа старше поля для вопроса, хотя у пилота «цеха» было наоборот:
    chatgpt.com показывает поле для вопроса и НЕ вошедшему — спросить можно без входа.
    Поле само по себе больше ничего не доказывает, а вот «Войти»/«Sign up» на странице
    залогиненного человека не висит.
    """
    заголовок = (признаки.get("заголовок") or "")[:80]
    if признаки.get("кнопки_входа"):
        return {"вход": "нет", "заголовок": заголовок}
    if признаки.get("композер"):
        return {"вход": "есть", "заголовок": заголовок}
    return {"вход": "непонятно", "заголовок": заголовок,
            "подсказка": "ни поля для вопроса, ни кнопки входа — похоже на проверку "
                         "на роботов или недогруженную страницу; повторить позже"}


def режим_картинки_включён(текст_формы: str | None) -> bool:
    """Стоит ли в композере метка «Создать изображение».

    Единственный надёжный признак: пункт меню не помечен ни ролью, ни `data-testid`, зато
    включённый режим подписывает сам композер.
    """
    текст = текст_формы or ""
    return any(метка.lower() in текст.lower() for метка in ПУНКТЫ_РЕЖИМА_КАРТИНКИ)


def разобрать_пропорцию(запись: str | None) -> float | None:
    """«16:10» → 1.6, «4:5» → 0.8, «1.6» → 1.6. Непонятное — None, а не догадка."""
    if not запись:
        return None
    текст = str(запись).strip().replace(",", ".").replace("×", ":").replace("x", ":")
    try:
        if ":" in текст:
            ширина, высота = текст.split(":", 1)
            ш, в = float(ширина), float(высота)
            return ш / в if в else None
        значение = float(текст)
        return значение if значение > 0 else None
    except ValueError:
        return None


def пропорция_совпала(фактическая: float, заказанная: float | None,
                      допуск: float = ДОПУСК_ПРОПОРЦИИ) -> bool:
    """Тот ли это формат. Сравниваем ОТНОСИТЕЛЬНО: у широких и узких кадров разная цена
    одной сотой, а разойтись на 2 % соседние форматы не умеют."""
    if not заказанная or заказанная <= 0 or фактическая <= 0:
        return True                       # не просили формат — нечему и не совпасть
    return abs(фактическая - заказанная) / заказанная <= допуск


def промт_с_пропорцией(промт: str, пропорция: str | None) -> str:
    """Пропорцию просим словами в самом промте: режим «Создать изображение» её понимает.

    Полную сборку промта из замеров делает задача 2 плана — здесь ровно одна строка, чтобы
    канал можно было проверить и чтобы сторож пропорции было с чем сравнивать.
    """
    if not пропорция or пропорция in промт:
        return промт
    return f"{промт}\n\nСоотношение сторон кадра: {пропорция}."


def строка_журнала(чем: dict, когда: datetime | None = None) -> str:
    """Строка журнала «чем рисовали». Время московское — как всё в системе.

    Пишем наблюдаемое, а не желаемое: имени модели интерфейс не даёт, поэтому в журнал идут
    режим ответа, состояние режима картинки и пропорция готового кадра.
    """
    когда = когда or datetime.now(МСК)
    части = " · ".join(f"{ключ}: {значение}" for ключ, значение in чем.items()
                       if значение not in (None, ""))
    return f"{когда.astimezone(МСК):%Y-%m-%d %H:%M} МСК — {части or 'нечего записать'}\n"


def записать_журнал(чем: dict, журнал: Path = ЖУРНАЛ_МОДЕЛИ,
                    когда: datetime | None = None) -> Path:
    журнал.parent.mkdir(parents=True, exist_ok=True)
    with журнал.open("a", encoding="utf-8") as файл:
        файл.write(строка_журнала(чем, когда))
    return журнал


