# ── где Chrome ───────────────────────────────────────────────────────────────
# Единственное место, где живёт это знание. Путь ищется, а не зашивается: у ученика
# Chrome стоит там, где стоит, а на Windows — вообще в другом месте.
КАНДИДАТЫ_CHROME = {
    "darwin": [
        "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
        "~/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
    ],
    "win32": [
        r"C:\Program Files\Google\Chrome\Application\chrome.exe",
        r"C:\Program Files (x86)\Google\Chrome\Application\chrome.exe",
        r"%LOCALAPPDATA%\Google\Chrome\Application\chrome.exe",
    ],
    "linux": [
        "/usr/bin/google-chrome",
        "/usr/bin/google-chrome-stable",
        "/usr/bin/chromium",
        "/usr/bin/chromium-browser",
    ],
}


def найти_chrome(платформа: str | None = None, окружение: dict | None = None,
                 есть=None) -> str:
    """Путь к Chrome на этой машине. `CHROME_BIN` перебивает поиск — это ручка для человека,
    у которого браузер лежит не там, где принято."""
    окружение = os.environ if окружение is None else окружение
    платформа = sys.platform if платформа is None else платформа
    есть = (lambda п: Path(п).exists()) if есть is None else есть
    свой = окружение.get("CHROME_BIN")
    if свой:
        return свой
    список = КАНДИДАТЫ_CHROME.get(платформа, [])
    for путь in список:
        развёрнутый = os.path.expandvars(os.path.expanduser(путь)) if "~" in путь or "%" in путь else путь
        # `%LOCALAPPDATA%` на не-Windows не разворачивается — такой путь просто не найдётся
        if "%" in развёрнутый:
            continue
        if есть(развёрнутый):
            return развёрнутый
    raise БедаКисти(
        "Не нашёл Google Chrome на этом компьютере. Поставьте его с google.com/chrome — "
        "или, если он уже стоит в необычном месте, скажите системе где: "
        "CHROME_BIN=<путь к браузеру>."
    )


# ── какие Chrome уже живы и чьи они ──────────────────────────────────────────
def команды_chrome() -> list[str]:
    """Строки запуска живых процессов Chrome. Нужны, чтобы отличить СВОЙ браузер от чужого:
    подключаться к чужой сессии нельзя ни при каких условиях."""
    try:
        if sys.platform == "win32":
            запрос = ("Get-CimInstance Win32_Process -Filter \"Name='chrome.exe'\" "
                      "| ForEach-Object { $_.CommandLine }")
            вывод = subprocess.run(
                ["powershell.exe", "-NoProfile", "-NonInteractive", "-Command", запрос],
                capture_output=True, text=True, timeout=20, check=False).stdout
        else:
            вывод = subprocess.run(["ps", "-axo", "command"], capture_output=True,
                                   text=True, timeout=20, check=False).stdout
        return вывод.splitlines()
    except Exception:
        return []


ПОРТ_В_СТРОКЕ = re.compile(r"remote-debugging-port=(\d+)")
ПРОФИЛЬ_В_СТРОКЕ = re.compile(r'user-data-dir="?(.+?)"?(?:\s--|\s*$)')


def разобрать_порты(строки) -> dict[int, str]:
    """{порт: имя папки профиля} по строкам запуска. `--type=` отсекаем: это дочерние
    процессы вкладок, они наследуют флаги родителя и задвоили бы порт."""
    найдено: dict[int, str] = {}
    for строка in строки or []:
        if "remote-debugging-port=" not in строка or "--type=" in строка:
            continue
        порт = ПОРТ_В_СТРОКЕ.search(строка)
        папка = ПРОФИЛЬ_В_СТРОКЕ.search(строка)
        if порт and папка:
            найдено[int(порт.group(1))] = Path(папка.group(1).strip().replace("\\", "/")).name
    return найдено


def жив_порт(порт: int, таймаут: float = 3.0) -> bool:
    """Откликается ли отладочный порт. Без этого «свободный порт» — гадание."""
    try:
        with urllib.request.urlopen(f"http://127.0.0.1:{порт}/json/version",
                                    timeout=таймаут) as ответ:
            return ответ.status == 200
    except (urllib.error.URLError, OSError, ValueError):
        return False


def свободный_порт(порты=ПОРТЫ, живой=жив_порт) -> int:
    """Первый порт диапазона, на котором никто не сидит."""
    for порт in порты:
        if not живой(порт):
            return порт
    raise БедаКисти(
        f"Все порты {порты[0]}–{порты[-1]} заняты. Похоже, открыто несколько окон системы: "
        "закройте лишние окна Chrome и попробуйте снова."
    )


def наш_живой_порт(порты=ПОРТЫ, живой=жив_порт, команды=команды_chrome,
                   имя_профиля: str = ИМЯ_ПРОФИЛЯ, запомненный: int | None = None) -> int | None:
    """Порт УЖЕ поднятого нашего Chrome — или None.

    ⚠️ Чужой браузер не трогаем: порт считается нашим только если процесс на нём запущен
    с нашей папкой профиля. Иначе однажды подключимся к чужой рабочей сессии и закроем
    человеку вкладки.
    """
    свои = {порт for порт, папка in разобрать_порты(команды()).items() if папка == имя_профиля}
    порядок = ([запомненный] if запомненный else []) + [п for п in порты if п != запомненный]
    for порт in порядок:
        if порт in свои and живой(порт):
            return порт
    return None


def запомненный_порт(файл: Path = ФАЙЛ_ПОРТА) -> int | None:
    try:
        return int(файл.read_text(encoding="utf-8").strip())
    except (OSError, ValueError):
        return None


# ── один браузер на профиль ──────────────────────────────────────────────────
def занять_замок(файл: Path = ЗАМОК) -> bool:
    """Два процесса на одном профиле рвут сессию. Замок — файл с номером процесса.

    Мёртвый замок от упавшего прогона не должен запирать систему навсегда: если процесса
    с таким номером уже нет, замок снимаем и берём заново.
    """
    файл.parent.mkdir(parents=True, exist_ok=True)
    for _ in range(2):
        try:
            ручка = os.open(файл, os.O_CREAT | os.O_EXCL | os.O_WRONLY)
        except FileExistsError:
            if _процесс_жив(_номер_из_замка(файл)):
                return False
            файл.unlink(missing_ok=True)
            continue
        os.write(ручка, str(os.getpid()).encode())
        os.close(ручка)
        return True
    return False


def отпустить_замок(файл: Path = ЗАМОК) -> None:
    файл.unlink(missing_ok=True)


def _номер_из_замка(файл: Path) -> int:
    try:
        return int(файл.read_text(encoding="utf-8").strip() or 0)
    except (OSError, ValueError):
        return 0


def _процесс_жив(номер: int) -> bool:
    if not номер:
        return False
    try:
        os.kill(номер, 0)
    except (ProcessLookupError, ValueError):
        return False
    except PermissionError:
        return True          # чужой процесс, но живой — замок настоящий
    except OSError:
        return False
    return True


# ── поднять окно ─────────────────────────────────────────────────────────────
def поднять_chrome(порт: int, профиль: Path = ПРОФИЛЬ, путь_chrome: str | None = None,
                   ждать_с: int = ПОДЪЁМ_С) -> int:
    """Открыть настоящее окно Chrome с нашим профилем и отладочным портом."""
    профиль.mkdir(parents=True, exist_ok=True)
    флаги = [
        путь_chrome or найти_chrome(),
        f"--remote-debugging-port={порт}",
        f"--user-data-dir={профиль}",
        "--no-first-run", "--no-default-browser-check",
        "--disable-extensions", "--hide-crash-restore-bubble",
        # Без этого флага Chrome сам объявляет себя автоматизированным, и проверка на
        # роботов встречает страницей-заглушкой даже с живой сессией.
        "--disable-blink-features=AutomationControlled",
        "about:blank",
    ]
    # Окно должно пережить наш процесс: иначе оно умрёт вместе со скриптом, а вместе с ним
    # и разговор с ChatGPT посреди генерации.
    отдельно: dict = {"start_new_session": True}
    if sys.platform == "win32":
        отдельно = {"creationflags": subprocess.DETACHED_PROCESS | subprocess.CREATE_NEW_PROCESS_GROUP}
    subprocess.Popen(флаги, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, **отдельно)
    for _ in range(ждать_с):
        if жив_порт(порт):
            # Отвечающий порт — ещё НЕ готовый браузер, см. `ждать_вкладку`.
            ждать_вкладку(порт)
            ФАЙЛ_ПОРТА.parent.mkdir(parents=True, exist_ok=True)
            ФАЙЛ_ПОРТА.write_text(str(порт), encoding="utf-8")
            return порт
        time.sleep(1)
    raise НеГотово(f"Chrome не поднялся на порту {порт} за {ждать_с} с — попробуйте ещё раз.")


def ждать_вкладку(порт: int, ждать_с: int = 20) -> bool:
    """Дождаться, пока у Chrome появится настоящая вкладка.

    ⚠️ Грабля первого запуска (13.09.2026, Chrome 152.0.7977.84, Playwright 1.62): порт
    начинает отвечать раньше, чем браузер поднял свой контекст, и подключение в эту щель
    падает «Protocol error (Browser.setDownloadBehavior): Browser context management is not
    supported». Повтор проходит — то есть это гонка, а не поломка. Но первый запуск у ученика
    и будет первым, второй попытки он делать не должен. Поэтому готовность меряем по существу:
    не «порт ответил», а «в браузере есть вкладка».
    """
    for _ in range(ждать_с):
        try:
            with urllib.request.urlopen(f"http://127.0.0.1:{порт}/json/list", timeout=3) as ответ:
                цели = json.loads(ответ.read().decode("utf-8"))
            if any(цель.get("type") == "page" for цель in цели):
                return True
        except (urllib.error.URLError, OSError, ValueError):
            pass
        time.sleep(1)
    return False


def порт_браузера(порт: int | None = None) -> int:
    """Живой порт нашего Chrome: найти уже открытое окно или поднять новое.

    Окно не перезапускаем. Нашли своё — работаем в нём.
    """
    if порт and жив_порт(порт):
        return порт
    свой = наш_живой_порт(запомненный=порт or запомненный_порт())
    if свой:
        return свой
    return поднять_chrome(порт or свободный_порт())


@contextmanager
def подключение(порт: int, попыток: int = 3):
    """Разговор с живым окном по отладочному порту.

    ⚠️ `browser.close()` здесь ЗАПРЕЩЁН: по отладочному порту он гасит сам Chrome вместе со
    всеми вкладками — в том числе чужими. Соединение просто отпускаем.

    ⚠️ Почему подключение вообще безопасно: оно цепляется ко ВСЕМ вкладкам браузера и виснет
    на «retrieving websocket url», если в окне открыта тяжёлая страница с десятком врезок
    (плееры, проверки на роботов, виджеты) — в «Визуальном цехе» из-за этого завели отдельный
    путь на сыром CDP. У нас этого не случается по устройству: в нашем профиле живут только
    `about:blank` и chatgpt.com, а к чужому профилю мы не подключаемся никогда (`наш_живой_порт`).
    """
    from playwright.sync_api import sync_playwright

    ждать_вкладку(порт)          # порт ответил — это ещё не значит, что браузер готов
    движок = sync_playwright().start()
    try:
        последняя = None
        контекст = None
        for заход in range(попыток):
            try:
                браузер = движок.chromium.connect_over_cdp(f"http://127.0.0.1:{порт}",
                                                           timeout=ПОДКЛЮЧЕНИЕ_МС)
                контекст = браузер.contexts[0] if браузер.contexts else браузер.new_context()
                break
            except Exception as беда:
                # Гонка первого запуска бывает и после ожидания вкладки — тогда просто ждём
                # и пробуем ещё раз, вместо того чтобы вываливать человеку протокольную ошибку.
                последняя = беда
                if заход < попыток - 1:
                    time.sleep(3)
        if контекст is None:
            raise НеГотово(
                f"не получилось подключиться к браузеру на порту {порт} за {попыток} захода: "
                f"{type(последняя).__name__}. Закройте окно системы и повторите команду."
            ) from последняя
        yield контекст
    finally:
        движок.stop()


