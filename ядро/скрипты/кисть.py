def закрыть_окошко(страница) -> None:
    """Плашку про лимиты убираем: она перехватывает клики и роняет отправку."""
    try:
        плашка = страница.locator('[data-testid*="rate-limit"], [id*="rate-limit"]')
        for _ in range(3):
            if not плашка.count():
                return
            страница.keyboard.press("Escape")
            страница.mouse.click(20, 20)
            страница.wait_for_timeout(1500)
    except Exception:
        pass


def открыть_chatgpt(контекст, ждать_мс: int = ЗАГРУЗКА_МС):
    """Новая вкладка на chatgpt.com. Существующие вкладки человека не трогаем."""
    страница = контекст.new_page()
    try:
        ответ = страница.goto(АДРЕС, timeout=ждать_мс, wait_until="domcontentloaded")
    except Exception as беда:
        raise НеГотово(f"страница не открылась: {type(беда).__name__}") from беда
    if ответ is not None and ответ.status >= 400:
        # 403 в настоящем окне — это признак того, что нас приняли за робота, а не разлогин.
        raise НеГотово(f"chatgpt.com ответил HTTP {ответ.status} — это защита от роботов "
                       "или сеть, а не потерянный вход")
    страница.wait_for_timeout(3000)
    закрыть_окошко(страница)
    return страница


