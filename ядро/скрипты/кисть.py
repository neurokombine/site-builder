def команда_нарисуй(промт: str, куда: str, имя: str, рефы: list[str],
                    пропорция: str | None, подрезать: bool, порт: int | None) -> int:
    итог = нарисовать(промт, Path(куда), имя=имя, рефы=рефы, пропорция=пропорция,
                      подрезать=подрезать, порт=порт)
    ширина, высота = итог["размер"]
    # Галочку ставим только когда формат тот: «✅», а следом «🔴 формат не тот» читается
    # как «всё хорошо», и человек закроет глаза на вторую строку.
    print(f"\n{'✅' if итог['совпала'] else '⚠️'} {итог['файл']}")
    print(f"   кадр: {ширина}×{высота}, пропорция {итог['пропорция']:.3f}"
          + (f", просили {пропорция}" if пропорция else ""))
    if not итог["совпала"]:
        # Сторож модели. Молчать здесь нельзя: кадр не того формата в первом экране заметят
        # не сейчас, а на телефоне у чужого человека.
        print(f"🔴 формат не тот: просили {пропорция} "
              f"({итог['заказана']:.3f}), пришло {итог['пропорция']:.3f}.")
        print("   Так бывает по двум причинам: режим «Создать изображение» не включился или "
              "ChatGPT нарисовал старой моделью — она умеет только 3:2, 2:3 и 1:1.")
        print("   Что делать: повторите команду (режим включится заново). Нужен именно этот "
              "кадр — можно обрезать по центру флагом --подрежь, но это последнее средство: "
              "композиция снималась под другой формат.")
    print("   Дальше: ужать и переименовать латиницей — "
          f"ядро/скрипты/картинка.py «{итог['файл']}» --куда {куда}")
    return 0 if итог["совпала"] else 4


