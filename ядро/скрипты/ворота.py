"""Ворота в `img/`: одна проверка на две двери.

Правило владелицы 13.09.2026 — «пока человек не сказал „беру“, лицо на страницу не идёт» —
держится не памятью, а отказом писать кадр прямо в `img/` работы. Дверей туда две:
`приёмка.добиться_кадра` (штатный путь) и `кисть.py --нарисуй --куда …` (прямая команда,
документированная в `CLAUDE.md` § 6). Проверка была только на первой, и документ обещал
больше, чем охранял код, — отсюда этот модуль: **проверка одна, зовут её обе двери.**

⚠️ Имя последней папки в пути ворота не охраняет — обходится тремя способами сразу:
`img/кадры` (подпапка; `собрать.py` копирует `img/` целиком, вместе с подпапками),
`витрина/кадр-ждёт` → симлинк на `../img`, `IMG` (на macOS и Windows это та же папка).
Поэтому смотрим не имя последней папки, а **разрешённый путь**: `resolve()` разворачивает
симлинки и `..`, а дальше на имя `img` проверяется сам путь и его предки, без учёта регистра.
⚠️ Предки — не до корня диска, а **до папки работы**: система, лежащая под чужой папкой `img`
(фотоархив, `~/img/`, том `/Volumes/IMG/`), иначе получала отказ на всех путях сразу, включая
законный `витрина/кадр-ждёт`. Рамка поиска — ниже, в `ПРИМЕТЫ_РАБОТЫ`.

Модуль нарочно пустой по зависимостям: его зовёт и `кисть.py` (которая про портреты не знает
и знать не должна), и `приёмка.py` (которая знает). Встречный импорт сцепил бы их в кольцо.
"""
from __future__ import annotations

from pathlib import Path

ИМЯ_IMG = "img"
# Имя папки ожидания: кадр живёт в ней, пока человек не сказал «беру». Лежит здесь, а не в
# `приёмка.py`, потому что его называют в отказе обе двери, а кисть про приёмку не знает.
ЖДЁТ = "кадр-ждёт"

# ⚠️ Рамка поиска: `img` ищется ВНУТРИ работы, а не до корня диска.
# `resolve()` делает путь абсолютным, а `.parents` идут до `/` — и система, сама лежащая под
# папкой с именем `img` (фотоархив, синхронизируемый диск, `~/img/`, том `/Volumes/IMG/`),
# получала отказ на любом пути, включая законный `витрина/кадр-ждёт`: линия картинок у такого
# человека не работала вовсе, а подсказка «рисуйте вот сюда» указывала наружу его работы.
# Поэтому поднимаемся только до папки работы — ближайшего предка, в котором лежит `прототип.md`
# или папка `экраны` (по ним работа и опознаётся во всей системе). Выше неё имя `img` уже не
# наше дело: что там у человека на диске, системы не касается.
ПРИМЕТЫ_РАБОТЫ = ("прототип.md", "экраны")
# Работы не нашли (временная папка в тестах, кадр в стороне от сайта) — смотрим `куда` и трёх
# его предков: столько же, сколько их набирается внутри живой работы (`работа/img/кадры` — два,
# `работа/витрина/кадр-ждёт` — два). Так ворота остаются воротами и без примет работы, но
# по-прежнему не лезут через весь диск.
ПРЕДКОВ_БЕЗ_РАБОТЫ = 3


def папка_работы(куда) -> Path | None:
    """Ближайший предок `куда` (или он сам), похожий на папку работы, — или None."""
    путь = Path(куда).expanduser().resolve(strict=False)
    for кандидат in (путь, *путь.parents):
        if (кандидат / "прототип.md").is_file() or (кандидат / "экраны").is_dir():
            return кандидат
    return None


def _кандидаты(путь: Path, работа: Path | None) -> list[Path]:
    """Отрезок пути, который ворота вообще смотрят: от `куда` вверх и не выше работы."""
    цепочка = [путь, *путь.parents]
    if работа is None:
        return цепочка[:1 + ПРЕДКОВ_БЕЗ_РАБОТЫ]
    отрезок: list[Path] = []
    for кандидат in цепочка:
        if кандидат == работа:
            break
        отрезок.append(кандидат)
    return отрезок


def папка_img(куда) -> Path | None:
    """Та самая папка `img/` работы, внутри которой лежит `куда`, — или None, если её в пути нет.

    Путь сперва разрешается (`strict=False`: папки может ещё не быть — её создадут следом),
    и только потом сверяется имя. Сравниваем через `casefold()`, а не побуквенно: на macOS
    (APFS) и на Windows `IMG` и `img` — одна и та же папка, и ворота, которые этого не знают,
    обходятся одной нажатой клавишей Shift. Выше папки работы не поднимаемся — см. рамку поиска.
    """
    путь = Path(куда).expanduser().resolve(strict=False)
    for кандидат in _кандидаты(путь, папка_работы(путь)):
        if кандидат.name.casefold() == ИМЯ_IMG:
            return кандидат
    return None


def внутри_img(куда) -> bool:
    """Ведёт ли этот путь в `img/` — хоть сам, хоть подпапкой, хоть симлинком, хоть регистром."""
    return папка_img(куда) is not None


def куда_вместо_img(куда) -> Path:
    """Куда система предлагает рисовать вместо `img/`: папка ожидания внутри работы.

    Слова в отказе должны не только запрещать, но и говорить, что делать: человек попросил
    картинку и остался без неё — без подсказки он повторит ту же команду. Первой опорой берём
    саму работу: у системы, лежащей под чужой папкой `img`, подсказка «родитель первой найденной
    img» указывала наружу работы — совет, по которому нельзя было сделать ничего.
    """
    путь = Path(куда).expanduser().resolve(strict=False)
    работа = папка_работы(путь)
    if работа is not None:
        return работа / "витрина" / ЖДЁТ
    папка = папка_img(путь)
    корень = папка.parent if папка is not None else путь.parent
    return корень / "витрина" / ЖДЁТ
