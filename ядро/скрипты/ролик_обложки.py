from pathlib import Path

from картинка import имя_латиницей

БЮДЖЕТ_МБ = {"телефон": 1.5, "компьютер": 2.5}
# Вес самого ролика (не анимации) — рядом с бюджетами анимации, на клип 5–10 секунд: обложка грузится первой,
# а ролик 1080p в 3–5 Мбит/с — это 3–6 МБ на мобильном интернете до первого кадра.
БЮДЖЕТ_РОЛИКА_МБ = {"телефон": 1.5, "компьютер": 2.5}
# Порог битрейта видеопотока, кбит/с. На петле обложки (мало движения, крупные плоскости) crf 21 даёт у 1080p
# 2,0–2,5 Мбит/с, у 720p и ниже — 1,0–1,5: выше порога поток почти наверняка раздут экспортом из редактора.
ПОРОГ_ПОТОКА_КБИТ = {"1080p": 2500, "720p": 1500}
ПОРОГ_ВЫСОКОГО = 1080     # короткая сторона от этого — «1080p и выше»; меньше — порог 720p
# Пережатие «без видимой потери» (школьная настройка): crf 21, preset slow; если после него всё ещё выше
# бюджета — один шаг crf 23 и стоп: дальше не ухудшаем, а говорим вслух.
CRF_ПЕРЕЖАТИЯ, CRF_ПОСЛЕДНИЙ_ШАГ = 21, 23
# Потолок размера картинки: у телефона — по короткой стороне (кадр 3 : 4 или 9 : 16 шириной 720 —
# чётко на экране в 390 точек при плотности 2), у компьютера — по длинной (1920, полный HD).
ПОТОЛОК = {"телефон": ("короткая", 720), "компьютер": ("длинная", 1920)}
# Лестница: сначала кадры в секунду (12–15 глазом не отличить на петле обложки), потом размер.
ЛЕСТНИЦА = ((15, 1.0), (12, 1.0), (12, .85), (12, .75), (10, .75), (10, .6), (8, .5))
КАЧЕСТВО_AVIF = 62       # Pillow, 0–100: на петле обложки разницы с роликом глазом не видно
СКОРОСТЬ_AVIF = 6        # 0 — медленно и плотно, 10 — быстро и рыхло
КАЧЕСТВО_WEBP = 75
ДЛИННЫЙ_КЛИП_С = 10      # дольше — анимация тяжелеет, а петля обложки 6–10 секунд
# Уровень H.264 4.0 (таблица A-1 стандарта): кадр до 8192 макроблоков (1920 × 1080 — 8160), до 245 760
# макроблоков в секунду (1080p при 30 к/с), буфер опорных кадров 32 768 макроблоков (у 1080p — 4 кадра).
# Поток High 4.0 — до 25 Мбит/с; берём 20 с запасом: телефону важна не метка, а то, что он потянет.
УРОВЕНЬ = 40
МАКС_КАДР_МБ, МАКС_МБ_В_С, МАКС_БУФЕР_МБ, МАКС_ПОТОК_КБИТ = 8192, 245_760, 32_768, 20_000
ПРОФИЛИ = ("High", "Main", "Constrained Baseline", "Baseline")

