"""Ролик обложки под живые телефоны: ролик под iOS, постер первого кадра и анимированная картинка того же клипа.

Зачем. Ролик на обложке играет не везде. iOS в режиме энергосбережения и встроенные браузеры мессенджеров
(Telegram, VK, Max) запрещают автозапуск любого видео — и разметкой это не обходится: `autoplay muted
playsinline` они просто не слушают. Анимированная картинка в них движется. Поэтому у каждого ролика обложки
есть запасной ход того же клипа: AVIF (основной, лёгкий) и WebP (запасной — для браузеров без AVIF), первый
кадр = постер, чтобы подмена прошла без скачка. Страница грузит картинку только тогда, когда ролик отказал
(`ядро/блоки/обложка.js`, `ядро/картинки.md` § 7).

Что делает `приготовить(ролик, куда, вид)`:
- **ролик под iOS**: H.264 High не выше уровня 4.0, yuv420p, `faststart` (начало файла — сразу метаданные:
  телефон начинает играть, не скачав файл целиком), без звуковой дорожки. Уровень выше 4.0 при потоке,
  который в рамки 4.0 и так влезает (размер кадра, кадры в секунду, опорные кадры, поток), — переписываем
  только метку уровня, без перекодирования: картинка байт в байт та же. Не влезает — перекодируем;
- **вес ролика**: поток выше порога (2,5 Мбит/с от 1080p, 1,5 — ниже) или файл больше бюджета (телефон 1,5 МБ,
  компьютер 2,5 МБ) — перекодируем даже совместимый: crf 21 slow; всё ещё тяжело — один шаг crf 23 и
  слова вслух. Печатаем «было → стало» и, если у ffmpeg есть libvmaf, VMAF. Лёгкий и совместимый — не трогаем;
- **постер** — первый кадр готового ролика (`<имя>-poster.jpg`, у ролика с прозрачностью — `.png`);
- **анимированная картинка** `<имя>-anim.avif` и `<имя>-anim.webp`: 15, а если тяжело — 12 кадров в секунду,
  бюджет на файл — телефон 1,5 МБ, компьютер 2,5 МБ. Не влезла — понижаем кадры в секунду и размер
  картинки по лестнице; ролик при этом не трогаем.

Кодирует Pillow (AVIF и WebP в нём есть с версии 11.3); нет — ffmpeg с libsvtav1/libaom-av1 и libwebp; нет
и их — скрипт говорит, что поставить, и делает то, что может. Импортирует только картинка и находки.
Запуск — через `обложка.py <ролик> --куда сайты/<имя>/video --анимация [--вид телефон|компьютер]`.
"""
from __future__ import annotations

import json
import re
import shutil
import subprocess
import tempfile
