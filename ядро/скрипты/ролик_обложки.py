# ── ffmpeg и разбор ролика ────────────────────────────────────────────────────────────────

def ffmpeg_есть() -> str | None:
    return shutil.which("ffmpeg")


def _ffprobe() -> str | None:
    return shutil.which("ffprobe")


def _ffmpeg(*аргументы: str) -> None:
    subprocess.run([ffmpeg_есть(), "-hide_banner", "-nostdin", "-loglevel", "error", "-y", *аргументы],
                   check=True, capture_output=True)


def кодеры_ffmpeg() -> set[str]:
    if not ffmpeg_есть():
        return set()
    вывод = subprocess.run([ffmpeg_есть(), "-hide_banner", "-encoders"], capture_output=True, text=True).stdout
    return {строка.split()[1] for строка in вывод.splitlines() if len(строка.split()) > 1 and строка.startswith(" V")}


def разобрать(ролик: Path) -> dict:
    """Что за ролик: кодек, профиль, уровень, пиксели, размер, кадры в секунду, поток, звук, прозрачность."""
    вывод = subprocess.run([_ffprobe(), "-v", "error", "-print_format", "json", "-show_streams", "-show_format",
                            str(ролик)], capture_output=True, text=True, check=True).stdout
    данные = json.loads(вывод)
    видео = next((п for п in данные.get("streams", []) if п.get("codec_type") == "video"), {})
    частота = видео.get("avg_frame_rate") or видео.get("r_frame_rate") or "0/1"
    try:
        кадров_в_с = float(Fraction(частота)) if частота != "0/0" else 0.0
    except (ValueError, ZeroDivisionError):
        кадров_в_с = 0.0
    поток = видео.get("bit_rate") or данные.get("format", {}).get("bit_rate") or 0
    теги = {к.lower(): str(з) for к, з in (видео.get("tags") or {}).items()}
    return {"кодек": видео.get("codec_name", ""), "профиль": видео.get("profile", ""),
            "уровень": int(видео.get("level") or 0), "пиксели": видео.get("pix_fmt", ""),
            "ширина": int(видео.get("width") or 0), "высота": int(видео.get("height") or 0),
            "кадров_в_с": кадров_в_с, "поток_кбит": int(поток) // 1000 if str(поток).isdigit() else 0,
            "звук": any(п.get("codec_type") == "audio" for п in данные.get("streams", [])),
            "альфа": теги.get("alpha_mode") == "1" or видео.get("pix_fmt", "").startswith(("yuva", "rgba", "argb")),
            "длительность": float(данные.get("format", {}).get("duration") or 0)}


ПОЛЯ_SPS = ("level_idc", "max_num_ref_frames", "max_dec_frame_buffering", "pic_width_in_mbs_minus1",
            "pic_height_in_map_units_minus1", "frame_mbs_only_flag")


def sps(ролик: Path) -> dict:
    """Заголовок потока H.264 (SPS) как он записан в файле: метка уровня, опорные кадры, размер в макроблоках.
    ffprobe показывает не всё — опорных кадров он не знает, — поэтому читаем через trace_headers."""
    вывод = subprocess.run([ffmpeg_есть(), "-hide_banner", "-nostdin", "-i", str(ролик), "-map", "0:v:0", "-c", "copy",
                            "-bsf:v", "trace_headers", "-frames:v", "1", "-f", "null", "-"],
                           capture_output=True, text=True).stderr
    итог: dict[str, int] = {}
    for поле in ПОЛЯ_SPS:
        м = re.search(rf"\b{поле}\s+[01]+\s*=\s*(\d+)", вывод)
        if м:
            итог[поле] = int(м.group(1))
    return итог


def faststart(ролик: Path) -> bool:
    """Метаданные (moov) стоят до самих кадров (mdat) — телефон начинает играть, не скачав файл целиком."""
    with open(ролик, "rb") as ф:
        while True:
            шапка = ф.read(8)
            if len(шапка) < 8:
                return False
            размер, тип = int.from_bytes(шапка[:4], "big"), шапка[4:8]
            сдвиг = 8
            if размер == 1:
                размер, сдвиг = int.from_bytes(ф.read(8), "big"), 16
            if тип == b"moov":
                return True
            if тип == b"mdat" or размер == 0:
                return False
            ф.seek(размер - сдвиг, 1)


def влезает_в_уровень(р: dict, с: dict) -> tuple[bool, str]:
    """Влезает ли поток в рамки уровня 4.0 сам по себе — тогда метку можно переписать без перекодирования."""
    if not с or "pic_width_in_mbs_minus1" not in с:
        return False, "заголовок потока не прочитался"
    кадр_мб = (с["pic_width_in_mbs_minus1"] + 1) * (с["pic_height_in_map_units_minus1"] + 1) * \
        (2 - с.get("frame_mbs_only_flag", 1))
    буфер = max(с.get("max_dec_frame_buffering", 0), с.get("max_num_ref_frames", 0))
    if кадр_мб > МАКС_КАДР_МБ:
        return False, f"кадр {р['ширина']}×{р['высота']} больше, чем позволяет уровень 4.0"
    if кадр_мб * (р["кадров_в_с"] or 30) > МАКС_МБ_В_С:
        return False, f"{round(р['кадров_в_с'])} кадров в секунду при таком размере — больше уровня 4.0"
    if буфер * кадр_мб > МАКС_БУФЕР_МБ:
        return False, f"опорных кадров {буфер} — уровень 4.0 при таком размере держит {МАКС_БУФЕР_МБ // кадр_мб}"
    if р["поток_кбит"] > МАКС_ПОТОК_КБИТ:
        return False, f"поток {р['поток_кбит']} кбит/с — больше {МАКС_ПОТОК_КБИТ}"
    return True, ""


# ── Ролик под iOS ─────────────────────────────────────────────────────────────────────────

def порог_потока(р: dict) -> int:
    """Порог битрейта по размеру кадра: от 1080p по короткой стороне — один, ниже — другой (не апскейлим)."""
    return ПОРОГ_ПОТОКА_КБИТ["1080p" if min(р["ширина"], р["высота"]) >= ПОРОГ_ВЫСОКОГО else "720p"]


def тяжесть(р: dict, размер_байт: int | None, вид: str | None) -> str:
    """Почему ролик тяжёл для обложки (пустая строка — не тяжёл): поток выше порога или файл больше бюджета."""
    if р["поток_кбит"] and р["поток_кбит"] > порог_потока(р):
        return f"поток {р['поток_кбит']} кбит/с — для обложки тяжело (порог {порог_потока(р)} кбит/с), пережимаю"
    if размер_байт and вид in БЮДЖЕТ_РОЛИКА_МБ and размер_байт > БЮДЖЕТ_РОЛИКА_МБ[вид] * 1_048_576:
        return (f"файл {размер_байт / 1_048_576:.1f} МБ — больше бюджета ролика "
                f"{БЮДЖЕТ_РОЛИКА_МБ[вид]} МБ ({вид}), пережимаю")
    return ""


def план_под_ios(р: dict, с: dict, быстрый_старт: bool, размер_байт: int | None = None,
                 вид: str | None = None) -> dict:
    """Что делать с роликом: ничего, переупаковать (звук, faststart), переписать метку уровня или перекодировать."""
    причины, перекодировать = [], False
    тяжёлый = тяжесть(р, размер_байт, вид)
    if тяжёлый:
        перекодировать = True
        причины.append(тяжёлый)
    if р["кодек"] != "h264":
        перекодировать = True
        причины.append(f"кодек {р['кодек'] or 'неизвестен'}, а iPhone надёжно играет H.264")
    elif р["профиль"] not in ПРОФИЛИ:
        перекодировать = True
        причины.append(f"профиль {р['профиль']} — iPhone ждёт High, Main или Baseline")
    if р["пиксели"] != "yuv420p":
        перекодировать = True
        причины.append(f"пиксели {р['пиксели']} — нужен yuv420p, иначе часть телефонов покажет чёрный кадр")
    уровень = с.get("level_idc", р["уровень"])
    метка = False
    if not перекодировать and (уровень > УРОВЕНЬ or уровень < 10):
        влезает, почему = влезает_в_уровень(р, с)
        if влезает:
            метка = True
            причины.append(f"метка уровня {уровень / 10:.1f} — переписываю на 4.0 без перекодирования: поток в рамки 4.0 влезает")
        else:
            перекодировать = True
            причины.append(f"уровень {уровень / 10:.1f}, а метку переписать нельзя: {почему}")
    if р["звук"]:
        причины.append("звуковая дорожка — на обложке звука нет, а лишний вес и запрет автозапуска со звуком есть")
    if not быстрый_старт:
        причины.append("метаданные в конце файла — переношу в начало (faststart)")
    if перекодировать:
        действие = "перекодировать"
    elif метка:
        действие = "метка"
    elif р["звук"] or not быстрый_старт:
        действие = "переупаковать"
    else:
        действие = "ничего"
    return {"действие": действие, "причины": причины, "тяжёлый": bool(тяжёлый)}


def _vmaf(исходник: Path, готовый: Path) -> float | None:
    """VMAF готового против исходника — только если ffmpeg собран с libvmaf; информативно, не блокирует."""
    if "libvmaf" not in subprocess.run([ffmpeg_есть(), "-hide_banner", "-filters"], capture_output=True,
                                       text=True).stdout:
        return None
    try:
        вывод = subprocess.run(
            [ffmpeg_есть(), "-hide_banner", "-nostdin", "-i", str(готовый), "-i", str(исходник), "-lavfi",
             "[0:v][1:v]scale2ref=flags=bicubic[a][b];[a][b]libvmaf", "-f", "null", "-"],
            capture_output=True, text=True, timeout=300).stderr
    except subprocess.TimeoutExpired:
        return None
    м = re.search(r"VMAF score:\s*([\d.]+)", вывод)
    return round(float(м.group(1)), 1) if м else None


def под_ios(ролик: Path, куда: Path, вид: str | None = None) -> dict:
    """Готовый к iPhone ролик в `куда`. Исходник не трогаем никогда: если он уже лежит в `куда` под тем же
    именем и его надо менять — пишем рядом `<имя>-ios.mp4`. Тяжёлый ролик (поток выше порога или файл больше
    бюджета) пережимаем даже если он iOS-совместим."""
    р = разобрать(ролик)
    с = sps(ролик) if р["кодек"] == "h264" else {}
    быстрый = faststart(ролик) if ролик.suffix.lower() in (".mp4", ".m4v", ".mov") else False
    вид = вид or ("телефон" if р["высота"] > р["ширина"] else "компьютер")
    было = ролик.stat().st_size
    план = план_под_ios(р, с, быстрый, было, вид)
    цель = куда / (имя_латиницей(ролик.stem) + ".mp4")
    if план["действие"] != "ничего" and цель.resolve() == ролик.resolve():
        цель = куда / (имя_латиницей(ролик.stem) + "-ios.mp4")
    общие = ("-i", str(ролик), "-map", "0:v:0", "-an", "-movflags", "+faststart")
    итог_вес: dict = {}
    if план["действие"] == "перекодировать":
        фильтр = ("scale=w='min(1920,iw)':h='min(1080,ih)':force_original_aspect_ratio=decrease,"
                  "scale=trunc(iw/2)*2:trunc(ih/2)*2")
        if р["ширина"] < р["высота"]:   # вертикальный: ограничение 1080 × 1920
            фильтр = фильтр.replace("min(1920,iw)", "min(1080,iw)").replace("min(1080,ih)", "min(1920,ih)")
        частота = ("-r", "30") if р["кадров_в_с"] > 30 else ()
        бюджет = БЮДЖЕТ_РОЛИКА_МБ[вид] * 1_048_576
        crf = CRF_ПЕРЕЖАТИЯ
        while True:
            _ffmpeg(*общие, "-vf", фильтр, *частота, "-c:v", "libx264", "-profile:v", "high", "-level:v", "4.0",
                    "-refs", "4", "-pix_fmt", "yuv420p", "-crf", str(crf), "-preset", "slow", str(цель))
            if цель.stat().st_size <= бюджет or crf >= CRF_ПОСЛЕДНИЙ_ШАГ:
                break
            crf = CRF_ПОСЛЕДНИЙ_ШАГ
        стало = цель.stat().st_size
        итог_вес = {"было_мб": round(было / 1_048_576, 2), "стало_мб": round(стало / 1_048_576, 2), "crf": crf}
        if стало > бюджет:
            итог_вес["предупреждение"] = (
                f"после crf {crf} ролик всё ещё {итог_вес['стало_мб']} МБ при бюджете {БЮДЖЕТ_РОЛИКА_МБ[вид]} МБ "
                f"({вид}) — качество дальше не ухудшаю. Укоротите клип, упростите кадр или уменьшите размер.")
        итог_вес["vmaf"] = _vmaf(ролик, цель)
    elif план["действие"] == "метка":
        # 40, а не «4.0»: фильтр понимает «4.0» как level_idc = 4 — метку несуществующего уровня.
        _ffmpeg(*общие, "-c:v", "copy", "-bsf:v", f"h264_metadata=level={УРОВЕНЬ}", str(цель))
    elif план["действие"] == "переупаковать":
        _ffmpeg(*общие, "-c:v", "copy", str(цель))
    elif цель.resolve() != ролик.resolve():
        shutil.copyfile(ролик, цель)
    return {"путь": цель, **план, **итог_вес}


# ── Анимированная картинка ────────────────────────────────────────────────────────────────

def _размер(р: dict, вид: str, доля: float) -> tuple[int, int]:
    сторона, предел = ПОТОЛОК[вид]
    ш, в = р["ширина"], р["высота"]
    мерка = min(ш, в) if сторона == "короткая" else max(ш, в)
    масштаб = min(1.0, предел / мерка) * доля if мерка else доля
    return max(2, round(ш * масштаб / 2) * 2), max(2, round(в * масштаб / 2) * 2)


def _кадры(ролик: Path, куда: Path, кадров_в_с: int, размер: tuple[int, int], альфа: bool) -> Path:
    """Кадры клипа одним файлом APNG без сжатия: Pillow читает его по кадру, а не все сразу в память."""
    файл = куда / f"кадры-{кадров_в_с}-{размер[0]}.apng"
    декодер = ("-c:v", "libvpx-vp9") if альфа else ()   # прозрачность VP9 видит только libvpx
    _ffmpeg(*декодер, "-i", str(ролик), "-map", "0:v:0", "-an",
            "-vf", f"fps={кадров_в_с},scale={размер[0]}:{размер[1]}:flags=lanczos",
            "-pix_fmt", "rgba" if альфа else "rgb24", "-compression_level", "1", "-pred", "none",
            "-plays", "0", "-f", "apng", str(файл))
    return файл


def чем_кодировать() -> dict:
    """Чем собрать каждый формат: Pillow, ffmpeg или ничем (тогда — слова, что поставить)."""
    from PIL import features

    кодеры = кодеры_ffmpeg()
    avif = "pillow" if features.check("avif") else next((к for к in ("libsvtav1", "libaom-av1") if к in кодеры), "")
    webp = "pillow" if features.check("webp") else ("libwebp_anim" if "libwebp_anim" in кодеры else
                                                   "libwebp" if "libwebp" in кодеры else "")
    return {"avif": avif, "webp": webp}


def _закодировать(кадры: Path, цель: Path, формат: str, чем: str, кадров_в_с: int, альфа: bool) -> None:
    длительность = round(1000 / кадров_в_с)
    if чем == "pillow":
        from PIL import Image

        with Image.open(кадры) as клип:
            if формат == "avif":
                клип.save(цель, save_all=True, duration=длительность, loop=0, quality=КАЧЕСТВО_AVIF, speed=СКОРОСТЬ_AVIF)
            else:
                клип.save(цель, save_all=True, duration=длительность, loop=0, quality=КАЧЕСТВО_WEBP, method=4)
        return
    if формат == "avif":
        _ffmpeg("-i", str(кадры), "-c:v", чем, "-crf", "34", "-pix_fmt", "yuva420p" if альфа else "yuv420p",
                "-loop", "0", "-f", "avif", str(цель))
    else:
        _ffmpeg("-i", str(кадры), "-c:v", чем, "-quality", str(КАЧЕСТВО_WEBP), "-loop", "0", str(цель))


def анимация(ролик: Path, куда: Path, вид: str, имя: str | None = None) -> dict:
    """`<имя>-anim.avif` и `<имя>-anim.webp` по лестнице, пока каждый не влезет в бюджет вида."""
    р = разобрать(ролик)
    имя = имя or имя_латиницей(ролик.stem)
    бюджет = int(БЮДЖЕТ_МБ[вид] * 1_048_576)
    чем = чем_кодировать()
    итог: dict = {"слова": [], "файлы": {}}
    if р["длительность"] > ДЛИННЫЙ_КЛИП_С:
        итог["слова"].append(f"Клип {р['длительность']:.0f} с — петле обложки хватает 6–10 с; анимация от длины тяжелеет.")
    with tempfile.TemporaryDirectory() as временная:
        временная = Path(временная)
        кэш: dict = {}
        for формат, нет in (("avif", НЕТ_AVIF), ("webp", НЕТ_WEBP)):
            if not чем[формат]:
                итог["слова"].append(нет)
                continue
            цель = куда / f"{имя}-anim.{формат}"
            for кадров_в_с, доля in ЛЕСТНИЦА:
                размер = _размер(р, вид, доля)
                ключ = (кадров_в_с, размер)
                if ключ not in кэш:
                    кэш[ключ] = _кадры(ролик, временная, кадров_в_с, размер, р["альфа"])
                _закодировать(кэш[ключ], цель, формат, чем[формат], кадров_в_с, р["альфа"])
                вес = цель.stat().st_size
                итог["файлы"][формат] = {"путь": цель, "мб": round(вес / 1_048_576, 2), "кадров_в_с": кадров_в_с,
                                         "размер": размер, "чем": чем[формат]}
                if вес <= бюджет:
                    break
            else:
                итог["слова"].append(f"{цель.name}: {итог['файлы'][формат]['мб']} МБ и на нижней ступени лестницы — "
                                     f"больше бюджета {БЮДЖЕТ_МБ[вид]} МБ. Укоротите клип (6–8 с) или упростите кадр.")
    return итог


def постер(ролик: Path, куда: Path, имя: str, альфа: bool) -> Path:
    """Первый кадр — тот же, с которого начинается анимация: подмена ролика картинкой идёт без скачка."""
    цель = куда / f"{имя}-poster.{'png' if альфа else 'jpg'}"
    декодер = ("-c:v", "libvpx-vp9") if альфа else ()
    _ffmpeg(*декодер, "-i", str(ролик), "-map", "0:v:0", "-frames:v", "1",
            *(("-pix_fmt", "rgba") if альфа else ("-q:v", "3")), str(цель))
    return цель


def угадать_вид(ролик: Path) -> str:
    р = разобрать(ролик)
    return "телефон" if р["высота"] > р["ширина"] else "компьютер"


def приготовить(ролик: Path, куда: Path, вид: str | None = None) -> dict | None:
    """Ролик под iOS + постер + анимация. Без ffmpeg — None (CLI печатает НЕТ_FFMPEG)."""
    if not ffmpeg_есть() or not _ffprobe():
        return None
    ролик, куда = Path(ролик), Path(куда)
    куда.mkdir(parents=True, exist_ok=True)
    вид = вид or угадать_вид(ролик)
    р = разобрать(ролик)
    if р["альфа"]:
        # Ролик с прозрачностью (живой портрет) — WebM VP9 для Chrome; Safari прозрачность не играет, там
        # движется анимированная картинка с прозрачностью. Под iOS такой ролик не приводим: незачем.
        готовый = {"путь": ролик, "действие": "ничего",
                   "причины": ["ролик с прозрачностью — Safari его не играет, там движется картинка; под iOS не привожу"]}
    else:
        готовый = под_ios(ролик, куда, вид)
    имя = готовый["путь"].stem
    итог = анимация(готовый["путь"], куда, вид, имя)
    итог.update({"вид": вид, "ролик": готовый, "постер": постер(готовый["путь"], куда, имя, р["альфа"]), "имя": имя})
    return итог


def разметка(итог: dict) -> str:
    """Какие атрибуты получит картинка-постер: имена файлов выводятся из имени ролика (`{{ВИДЕО}}`)."""
    имя, вид = итог["имя"], итог["вид"]
    слот = ("у живой обложки — {{ВИДЕО_ТЕЛЕФОН}}, у остальных схем — {{ВИДЕО}}" if вид == "телефон" else "{{ВИДЕО}}")
    return (f'слот {слот} = {имя}: рецепт сам возьмёт '
            f'video/{имя}-anim.avif и video/{имя}-anim.webp (data-анимация-avif… / data-анимация-webp…), '
            f'постер — video/{итог["постер"].name}')


def слова(итог: dict) -> list[str]:
    """Отчёт человеку: что сделано с роликом, что получилось и сколько весит."""
    ролик = итог["ролик"]
    строки = [f"Ролик: {ролик['путь'].name} — " + {"ничего": "уже годится для iPhone",
                                                     "переупаковать": "переупакован без перекодирования",
                                                     "метка": "переписана метка уровня, картинка та же",
                                                     "перекодировать": "перекодирован под iPhone"}[ролик["действие"]]]
    строки += [f"  · {п}" for п in ролик["причины"]]
    if "было_мб" in ролик:
        строка = f"  · было {ролик['было_мб']} МБ → стало {ролик['стало_мб']} МБ (crf {ролик['crf']})"
        if ролик.get("vmaf") is not None:
            строка += f" · VMAF {ролик['vmaf']} против исходника"
        строки.append(строка)
        if ролик.get("предупреждение"):
            строки.append("  ! " + ролик["предупреждение"])
    строки.append(f"Постер: {итог['постер'].name} — первый кадр, им же начинается анимация")
    for формат, ф in итог["файлы"].items():
        строки.append(f"Анимация {формат.upper()}: {ф['путь'].name} · {ф['размер'][0]}×{ф['размер'][1]} · "
                      f"{ф['кадров_в_с']} к/с · {ф['мб']} МБ (бюджет {БЮДЖЕТ_МБ[итог['вид']]} МБ, {итог['вид']}) · {ф['чем']}")
    строки += итог["слова"]
    строки.append("Разметка: " + разметка(итог))
    return строки
