"""Свежесть экранов: не отстал ли экран работы от рецепта ядра, по которому его когда-то собрали.

⭐ Зачем это есть. Слой «Работа» (`сайты/<имя>/экраны/NN-<тип>.html`) — это собственные копии,
снятые когда-то с рецептов ядра. Ядро потом обновляется пакетами, а копии остаются прежними:
`собрать.py` честно собирает то, что лежит в работе, и пересборка их не трогает. Значит человек,
собравший сайт полгода назад, навсегда остаётся на старом дизайне и никто ему об этом не скажет.
Ровно это и случилось с обоими демо 12.09.2026: семь фикс-раундов переделали первый экран, а в
демо не было ни шапки с лицензией, ни двухступенчатого заголовка.

🔴 Правило слоёв не нарушается: здесь только СВЕРКА и слова человеку. Ядро в работу молча не
лезет — переложить экран по свежему рецепту предлагает отдельная команда `обновить_экран.py`,
и делает это лишь тогда, когда человек её позвал.

Как меряем — по-разному у первого экрана и у остальных, и это не прихоть:

* **Первый экран** система заполняет сама (`витрина.заполнить_первый_экран`) из прототипа и
  профиля. Значит «свежий вид» этого экрана можно просто СОБРАТЬ заново и сравнить с тем, что
  лежит в работе. Пустые поля прототипа при этом снимают свои элементы в обоих текстах одинаково —
  ложных тревог вроде «у вас нет карточки автора» не будет: её нет и в свежем.
* **Остальные экраны** заполняет роль `screen-builder` руками, «свежий вид» для них никто
  вычислить не может. Там сверяем с самим рецептом и говорим осторожно (ℹ️, не 🟡): пропавший
  элемент бывает и решением автора — у него, скажем, три вопроса в списке вместо пяти.
"""
from __future__ import annotations

import re
from pathlib import Path

from находки import ПОПРАВИТЬ, К_СВЕДЕНИЮ, находка

БЛОКИ = Path(__file__).resolve().parent.parent / "блоки"
КЛАСС = re.compile(r'class="([^"]*)"')
СХЕМА = re.compile(r'data-схема="([^"]+)"')
# Ключ макета — единственный признак экрана, который живёт не в классах, а в атрибуте: по нему
# стили узнают, светлый ключ у схемы родной (макет и задуман плоским) или перекрашен из тёмного и
# обязан взять ту же глубину. Фикс-раунд Л завёл его в рецептах — и без этой строки сверка молчала
# бы: экран, собранный вчера, остался бы навсегда с плоским светлым ключом и никто бы не сказал.
КЛЮЧ_МАКЕТА = re.compile(r'data-ключ-макета="[^"]+"')
ХВОСТ_ИМЕНИ = re.compile(r"^\d+-(.+)$")
ОТКРЫВАЮЩИЙ_SECTION = re.compile(r"<section\b[^>]*>")
ПЕРВЫЙ_КОММЕНТАРИЙ = re.compile(r"\s*<!--.*?-->", re.S)
# Классы, по которым не судим: их ставит не рецепт, а поля дизайн.md (`собрать.применить_вариант`)
# — светлота, атмосфера и сторона. Экран работы уже несёт их проставленными, свежий рецепт ещё нет,
# и без этого списка каждая сверка кричала бы о «пропавшем» классе «тёмный».
# Роли светлоты (`ключ--основной` и родня) сюда же: рецепт несёт роль, а собранная страница —
# уже настоящий класс, который роль развернула по ключу страницы. Сверять их между собой значит
# каждый раз находить «пропажу» там, где всё на месте.
НЕ_ОТ_РЕЦЕПТА = {"светлый", "тёмный", "второй", "сторона--слева",
                 "фон--пятна", "фон--сетка", "фон--зерно",
                 "ключ--основной", "ключ--глубже", "ключ--наоборот"}
ПЕРВЫЙ_ЭКРАН = "первый-экран"
# Слот связи в экране работы ОСТАЁТСЯ слотом: кнопку из него ставит `собрать.py` по профилю той
# работы, которую собирают. Развернуть его здесь значило бы вписать в файл экрана чужой адрес —
# тот же замок и по той же причине стоит в tests/пересобрать_фикстуру.py.
ЗАМОК_СВЯЗИ = "@@СВЯЗЬ@@"
СЛОТ_СВЯЗИ = re.compile(r"\{\{СВЯЗЬ:[^}]*\}\}")


КОММЕНТАРИЙ = re.compile(r"<!--.*?-->", re.S)


def признаки(html: str) -> set[str]:
    """Все имена классов разметки — это и есть скелет экрана: какие детали в нём есть.

    Комментарии выбрасываем до разбора: в них не разметка, а инструкция тому, кто собирает экран,
    и примеры разметки в ней тоже есть («картинки нет — поставь заглушку: <div class="…">»).
    Считать их деталями экрана значит находить «пропажу» там, где её не было.
    """
    голый = КОММЕНТАРИЙ.sub("", html)
    имена = {к for м in КЛАСС.finditer(голый) for к in м.group(1).split()} - НЕ_ОТ_РЕЦЕПТА
    return имена | set(КЛЮЧ_МАКЕТА.findall(голый))


def хвост_имени(файл: Path) -> str:
    """`03-программа.html` → `программа`: номера экранов в работе свои, имена типов общие."""
    м = ХВОСТ_ИМЕНИ.match(Path(файл).stem)
    return м.group(1) if м else Path(файл).stem


def рецепт_для(экран: Path, пресет: str) -> Path | None:
    """Рецепт ядра, с которого снят этот экран; свой блок автора рецепта не имеет — None.
    У первого экрана имя рецепта договаривает схема из самой разметки (`data-схема`)."""
    хвост = хвост_имени(экран)
    if хвост == ПЕРВЫЙ_ЭКРАН:
        схема = СХЕМА.search(Path(экран).read_text(encoding="utf-8-sig"))
        файл = БЛОКИ / пресет / f"01-первый-экран-{схема.group(1)}.html" if схема else None
        return файл if файл and файл.is_file() else None
    найдено = sorted((БЛОКИ / пресет).glob(f"*-{хвост}.html")) if (БЛОКИ / пресет).is_dir() else []
    return найдено[0] if найдено else None


def свежий_первый_экран(работа: Path) -> str | None:
    """Первый экран, собранный заново по нынешнему рецепту ядра с текстами прототипа и профиля.

    Ленивый импорт не от лени: `витрина` на уровне модуля берёт `собрать.БЛОКИ`, а `собрать`
    зовёт эту сверку — импортируй мы их сверху, кольцо замкнулось бы на полузагруженном модуле.
    К моменту вызова оба модуля загружены целиком, и импорт здесь стоит ровно один поиск в кэше.
    """
    import витрина   # noqa: PLC0415 — см. объяснение выше
    import собрать   # noqa: PLC0415

    работа = Path(работа)
    тексты = витрина.тексты_первого_экрана(работа)
    if not тексты:
        return None
    пресет = витрина.набор(тексты["пресет"])
    дизайн = собрать.прочитать_дизайн(работа / "дизайн.md")
    поля = дизайн["решения_поля"] if дизайн["решения"] else (дизайн["варианты"] or [{}])[0]
    # Схему спрашиваем сперва у «Решений» дизайн.md — это выбор человека на витрине обложек; чужая
    # строка или пусто — берём ту, что уже стоит в самом экране работы, чтобы не подменить схему
    # молча (о расхождении этих двух мест и без нас скажет «Первый экран не той схемы» из собрать.py).
    файл = БЛОКИ / пресет / f"01-первый-экран-{поля.get('схема')}.html"
    if поля.get("схема") not in собрать.СХЕМЫ or not файл.is_file():
        экран = работа / "экраны" / "01-первый-экран.html"
        файл = рецепт_для(экран, пресет) if экран.is_file() else None
    if not файл or not файл.is_file():
        return None
    данные, папка_профиля, _ = собрать._профиль(работа)
    шаблон = файл.read_text(encoding="utf-8").replace("{{СВЯЗЬ:", ЗАМОК_СВЯЗИ)
    готово = витрина.заполнить_первый_экран(шаблон, тексты, данные, папка_профиля)
    # Подпись кнопки — из прототипа («Кнопка»), а не та, что стоит в рецепте умолчанием: рецепт
    # не знает, каким словом человек зовёт своё действие.
    return СЛОТ_СВЯЗИ.sub("{{СВЯЗЬ:" + тексты["кнопка"] + "}}",
                          готово.replace(ЗАМОК_СВЯЗИ, "{{СВЯЗЬ:"))


def как_соберётся(html: str, работа: Path) -> str:
    """Экран работы в том виде, в каком его увидит страница: со слотом связи, развёрнутым по профилю.

    Без этого сверка врала бы в одну сторону всегда: в файле работы стоит `{{СВЯЗЬ:…}}`, а в свежем
    рецепте она уже развёрнута в `<a class="кнопка кнопка--главная">` — и «главная кнопка» каждый
    раз числилась бы пропавшей деталью.
    """
    import собрать   # noqa: PLC0415 — кольцо импортов, см. свежий_первый_экран

    данные, папка_профиля, _ = собрать._профиль(Path(работа))
    return собрать._подставить_связь(html, данные, папка_профиля)[0]


КАДР = re.compile(r'<figure class="[^"]*первый-экран__картинка[^"]*".*?</figure>', re.S)
ТЕГ_КАДРА = re.compile(r"<(img|source|video)\b([^>]*)>")
# Что в кадре — решение владельца сайта, а не рецепта: какой файл, какой кроп под телефон, где на
# нём лицо и как кадр подписан для незрячего. Рецепт про это ничего не знает — у него слоты.
АТРИБУТЫ_КАДРА = ("src", "srcset", "poster", "alt", "data-лицо")
ЗНАЧЕНИЕ_АТРИБУТА = '{}="([^"]*)"'


def _атрибуты(тег: str) -> dict:
    return {имя: м.group(1) for имя in АТРИБУТЫ_КАДРА
            if (м := re.search(ЗНАЧЕНИЕ_АТРИБУТА.format(re.escape(имя)), тег))}


def перенести_кадр(свежий: str, старый: str) -> str:
    """Картинку первого экрана переносим из старого экрана в новый как есть.

    Заполнение рецепта ищет файл кадра по папке `img/` — берёт первый по алфавиту, и для витрины
    (где картинки человека ещё нет) этого хватает. Для перекладки уже собранного экрана — нет:
    у студии рядом с героем лежит `card.jpg`, картинка для мессенджера, и она по алфавиту первая.
    Поэтому не угадываем, а переносим: файл, телефонный кроп, точку лица и подпись для незрячего
    человек когда-то выбрал сам, и рецепт не повод это решение пересматривать.
    """
    новый_кадр, старый_кадр = КАДР.search(свежий), КАДР.search(старый)
    if not (новый_кадр and старый_кадр):
        return свежий
    было_по_тегам: dict[str, list[dict]] = {}
    for м in ТЕГ_КАДРА.finditer(старый_кадр.group(0)):
        было_по_тегам.setdefault(м.group(1), []).append(_атрибуты(м.group(0)))
    счётчик: dict[str, int] = {}

    def заменить(м: re.Match) -> str:
        тег, номер = м.group(1), счётчик.get(м.group(1), 0)
        счётчик[тег] = номер + 1
        было = (было_по_тегам.get(тег) or [{}] * (номер + 1))[номер] if номер < len(было_по_тегам.get(тег, [])) else {}
        текст = м.group(0)
        for имя, значение in было.items():
            образец = ЗНАЧЕНИЕ_АТРИБУТА.format(re.escape(имя))
            текст = (re.sub(образец, f'{имя}="{значение}"', текст, count=1) if re.search(образец, текст)
                     else текст[:-1].rstrip() + f' {имя}="{значение}">')
        return текст

    кадр = ТЕГ_КАДРА.sub(заменить, новый_кадр.group(0))
    return свежий[:новый_кадр.start()] + кадр + свежий[новый_кадр.end():]


def отстал(экран_html: str, свежий_html: str) -> list[str]:
    """Чего в экране работы нет, а в свежем рецепте есть. Имена классов — словами не переводим:
    по ним человек (и нейросеть рядом с ним) находит место в `ядро/дизайн/детали.md`."""
    return sorted(признаки(свежий_html) - признаки(экран_html))


def сверить(работа: Path) -> list[dict]:
    """Все экраны работы против нынешних рецептов ядра. Ничего не отстало — пустой список."""
    работа = Path(работа)
    папка = работа / "экраны"
    if not папка.is_dir():
        return []
    пресет = "визитка"
    try:
        import витрина   # noqa: PLC0415

        тексты = витрина.тексты_первого_экрана(работа)
        пресет = витрина.набор((тексты or {}).get("пресет", ""))
    except Exception:                                    # noqa: BLE001 — сверка не имеет права ронять сборку
        return []
    найденное: list[dict] = []
    строки_прочих: list[str] = []
    for файл in sorted(папка.glob("*.html")):
        экран = как_соберётся(файл.read_text(encoding="utf-8-sig"), работа)
        if хвост_имени(файл) == ПЕРВЫЙ_ЭКРАН:
            try:
                свежий = свежий_первый_экран(работа)
            except Exception:                            # noqa: BLE001
                свежий = None
            пропало = отстал(экран, свежий) if свежий else []
            if пропало:
                найденное.append(находка(
                    ПОПРАВИТЬ, "Первый экран отстал от рецепта ядра",
                    [f"{файл.name}: в рецепте ядра есть, а в вашем экране нет — " + ", ".join(пропало)],
                    "экраны работы — ваши собственные копии, снятые когда-то с рецептов; ядро с тех пор "
                    "обновилось, и пересборка копию не меняет. Переложить экран по свежему рецепту, "
                    "сохранив ваши тексты и решения: "
                    f".venv/bin/python ядро/скрипты/обновить_экран.py {работа} — сначала покажет, "
                    "что изменится, и только с флагом --перезаложим перепишет файл"))
            continue
        рецепт = рецепт_для(файл, пресет)
        if not рецепт:
            continue
        пропало = отстал(экран, как_соберётся(рецепт.read_text(encoding="utf-8"), работа))
        if пропало:
            строки_прочих.append(f"{файл.name} (рецепт {рецепт.name}): " + ", ".join(пропало))
    if строки_прочих:
        найденное.append(находка(
            К_СВЕДЕНИЮ, "Экраны ниже первого расходятся с рецептами ядра", строки_прочих,
            "Может быть, так и задумано: эти экраны заполняются руками, и лишний пункт или карточку "
            "автор вправе убрать. А может быть, рецепт в ядре с тех пор обновился — тогда сверьтесь "
            "с ним глазами: ядро/блоки/<пресет>/. Сама сборка здесь ничего не меняет."))
    return найденное


def перезаложить(работа: Path) -> tuple[Path, str, list[str]] | None:
    """Новый текст первого экрана по нынешнему рецепту ядра. Файл не пишет — это дело вызвавшего.

    Тексты и картинки берутся из прототипа и профиля, решения (схема, светлота, атмосфера,
    сторона) — из `дизайн.md`; собственный комментарий-пояснение из старого файла переносится
    в новый как есть: там записано, ПОЧЕМУ экран такой, и это работа человека, а не ядра.
    """
    import собрать   # noqa: PLC0415

    работа = Path(работа)
    файл = работа / "экраны" / "01-первый-экран.html"
    if not файл.is_file():
        return None
    свежий = свежий_первый_экран(работа)
    if not свежий:
        return None
    старый = файл.read_text(encoding="utf-8-sig")
    дизайн = собрать.прочитать_дизайн(работа / "дизайн.md")
    поля = дизайн["решения_поля"] if дизайн["решения"] else (дизайн["варианты"] or [{}])[0]
    свежий = перенести_кадр(собрать.применить_вариант(свежий, поля), старый)
    открывающий = ОТКРЫВАЮЩИЙ_SECTION.search(старый)
    пояснение = ПЕРВЫЙ_КОММЕНТАРИЙ.match(старый, открывающий.end()) if открывающий else None
    if пояснение:
        место = ОТКРЫВАЮЩИЙ_SECTION.search(свежий)
        if место:
            свежий = свежий[:место.end()] + пояснение.group(0) + свежий[место.end():]
    return файл, свежий.rstrip() + "\n", отстал(как_соберётся(старый, работа), свежий)
