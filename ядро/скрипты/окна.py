"""Обложка в первом экране: открыть страницу на наборе живых окон и померить, влезла ли обложка.

Зачем. Обычная проверка смотрит страницу в двух удобных окнах — 1440 × 900 и 390 × 844. У живых
людей окна ниже: ноутбук с панелью задач и строкой закладок даёт 1366 × 625, телефон в Safari с
панелями сверху и снизу — 390 × 664. Обложка, которая влезла в удобное окно, в живом уходит под
кромку: цифры, строка доверия, ступни фигуры — а на телефоне и главная кнопка. Здесь — те окна.

Правило (`ядро/канон.md`, «Кадр и экран»; устройство — `ядро/блоки.md` § 2-bis):
- **компьютер** (ширина от `БРЕЙКПОИНТ`): низ последнего значимого элемента обложки и низ её
  кадра — не ниже окна. Окна ниже `ВЫСОТА_МИН` в набор не входят: там обложка растёт и
  листается, и это честно;
- **телефон**: низ главной кнопки — не ниже видимой высоты окна;
- **ни на одном окне** страница не ездит вбок.

Руками этот файл не запускают: его зовёт `проверить.py`.
"""
from __future__ import annotations

from pathlib import Path

import глаза
from находки import ЧИНИТЬ, находка

БРЕЙКПОИНТ = 900     # px: с этой ширины у обложки раскладка компьютера (`@media (min-width: 900px)`)
ВЫСОТА_МИН = 600     # px: ниже обложка уже не обязана влезать — растёт и листается
ДОПУСК_PX = 2        # браузер округляет коробки до пикселя; меньше двух — не «вылезло»
ДОПУСК_СРЕЗА_PX = 4  # парящий чип ходит на пару пикселей у кромки своей рамки — это не срез

# Видимая высота окна — то, что остаётся под страницу, а не размер экрана. Компьютер: самые частые
# ширины ноутбуков и мониторов (1366, 1440, 1536, 1920, 1280) за вычетом панели задач, вкладок,
# адресной строки и строки закладок; 1440 × 753 — снимок живого окна MacBook Air с Chrome;
# 1024 × 700 — узкий компьютер у самой кромки раскладки. Телефон: видимая высота Safari, когда
# открыты обе панели — так страницу видят сразу после перехода по ссылке из мессенджера:
# iPhone SE 667 − 20 (статус) − 50 (адрес) − 49 (панель) ≈ 548; iPhone 14 844 − 47 − 50 − 83 ≈ 664
# (с нижней строкой адреса iOS 15+ панели вместе ≈ 133–180); iPhone Pro Max 932 − 59 − 50 − 73 ≈ 750.
ОКНА_КОМПЬЮТЕРА = (("1280 × 600", 1280, 600), ("1366 × 625", 1366, 625), ("1440 × 753", 1440, 753),
                   ("1536 × 730", 1536, 730), ("1920 × 1080", 1920, 1080), ("1024 × 700", 1024, 700))
ОКНА_ТЕЛЕФОНА = (("iPhone SE 375 × 548", 375, 548), ("iPhone 14 390 × 664", 390, 664),
                 ("iPhone Pro Max 430 × 750", 430, 750))

# Что на обложке считается значимым: всё, ради чего человек на неё смотрит. Пятна, кольца, опоры,
# дубли ленты (aria-hidden) — украшение: срезанное кромкой окна, оно ничего не теряет.
ЗНАЧИМОЕ = (".шапка", ".кикер", "h1", ".лид", ".первый-экран__действие", ".список-иконок", ".цифры",
            ".первый-экран__когда", ".первый-экран__доверие", ".первый-экран__регалии", ".чип", ".бейдж",
            ".спутник", ".центр__бок", ".бенто__ячейка", ".звук-блок")
ИМЕНА = {".шапка": "шапка", ".кикер": "надзаголовок", "h1": "заголовок", ".лид": "лид",
         ".первый-экран__действие": "кнопки", ".список-иконок": "пункты", ".цифры": "цифры",
         ".первый-экран__когда": "строка «когда»", ".первый-экран__доверие": "строка доверия",
         ".первый-экран__регалии": "карточка регалий", ".чип": "чип", ".бейдж": "бейдж",
         ".спутник": "спутник", ".центр__бок": "карточка сбоку", ".бенто__ячейка": "ячейка бенто",
         ".звук-блок": "кнопка звука"}

ЗАМЕР_JS = "([значимое]) => {" + глаза.ОБЩИЙ_JS + r"""
  const корень = document.documentElement, окно = корень.clientHeight || innerHeight;
  const итог = {высота_окна: окно, ширина_окна: корень.clientWidth, ширина_страницы: корень.scrollWidth,
                есть: false, низ_значимого: 0, что_ниже: '', срезано_px: 0, что_срезано: '', низ_кадра: 0, низ_кнопки: null, кнопка: ''};
  const герой = document.querySelector('section.блок--первый-экран');
  if (!герой) return итог;
  итог.есть = true;
  // Видимая коробка: срезана каждым предком с overflow, вплоть до самой секции. Ниже кромки
  // секции ничего не видно — значит, и не вылезло.
  const видимая = э => {
    let р = э.getBoundingClientRect(), верх = р.top, низ = р.bottom;
    for (let п = э.parentElement; п; п = п.parentElement) {
      const с = getComputedStyle(п);
      if (с.overflowY !== 'visible' || с.overflowX !== 'visible' || с.clipPath !== 'none') {
        const пр = п.getBoundingClientRect(); верх = Math.max(верх, пр.top); низ = Math.min(низ, пр.bottom);
      }
      if (п === герой) break;
    }
    return низ > верх ? {верх, низ} : null;
  };
  const снаружи = э => { for (let п = э; п && п !== герой; п = п.parentElement) {
    if (п.getAttribute('aria-hidden') === 'true' || getComputedStyle(п).position === 'fixed') return true; } return false; };
  for (const селектор of значимое) {
    for (const э of герой.querySelectorAll(селектор)) {
      if (!isVisible(э) || снаружи(э)) continue;
      // Значимое меряем целиком, а не по видимой части: срезанная кромкой секции кнопка — та же
      // беда, что кнопка под кромкой окна. Совсем невидимое (спрятано за overflow) — не в счёт.
      const р = э.getBoundingClientRect(), низ = р.bottom, в = видимая(э) || {верх: р.top, низ: р.top};
      if (низ > итог.низ_значимого) { итог.низ_значимого = Math.round(низ); итог.что_ниже = селектор; }
      // Срезано своей рамкой (ячейкой, секцией с overflow) — видно меньше, чем есть.
      if (низ - в.низ > итог.срезано_px) { итог.срезано_px = Math.round(низ - в.низ); итог.что_срезано = селектор; }
    }
  }
  // Кадр: картинка и ролик обложки. При object-fit: contain коробка шире нарисованного — считаем
  // низ того, что нарисовано (натуральные размеры и object-position по вертикали).
  for (const м of герой.querySelectorAll('.первый-экран__картинка img, .первый-экран__картинка video')) {
    if (!isVisible(м) || снаружи(м)) continue;
    const р = м.getBoundingClientRect(), с = getComputedStyle(м);
    const нш = м.videoWidth || м.naturalWidth, нв = м.videoHeight || м.naturalHeight;
    let низ = р.bottom;
    if (с.objectFit === 'contain' && нш && нв) {
      const масштаб = Math.min(р.width / нш, р.height / нв), высота = нв * масштаб;
      const поз = (с.objectPosition || '50% 50%').split(' ')[1] || '50%';
      const доля = поз.endsWith('%') ? parseFloat(поз) / 100 : 0;
      низ = р.top + (р.height - высота) * доля + высота;
    }
    const в = видимая(м);
    if (в) итог.низ_кадра = Math.max(итог.низ_кадра, Math.round(Math.min(низ, в.низ)));
  }
  // Главная кнопка: её ставит сборка (`кнопка--главная`); виджет без класса — первая ссылка или
  // кнопка в строке действия.
  const кнопка = [...герой.querySelectorAll('.кнопка--главная')].find(isVisible)
    || [...герой.querySelectorAll('.первый-экран__действие a, .первый-экран__действие button')].find(isVisible);
  if (кнопка) { итог.низ_кнопки = Math.round(кнопка.getBoundingClientRect().bottom);
    итог.кнопка = (кнопка.textContent || '').trim().replace(/\s+/g, ' ').slice(0, 40); }
  return итог;
}"""


def _замерить_окно(страница, адрес: str, ширина: int, высота: int, снимок: Path | None) -> dict:
    import флаги_дизайна   # здесь, а не наверху: флаги_дизайна сам тянет обложку и глаза

    страница.set_viewport_size({"width": ширина, "height": высота})
    глаза.открыть(страница, адрес)
    флаги_дизайна.дождаться_страницы(страница)
    замер = страница.evaluate(ЗАМЕР_JS, [list(ЗНАЧИМОЕ)])
    if снимок is not None:
        try:
            страница.screenshot(path=str(снимок), full_page=False)
            замер["снимок"] = str(снимок)
        except Exception:   # noqa: BLE001 — без снимка замер всё равно годен
            pass
    return замер


def снять(браузер, адрес: str, куда: Path | None = None) -> dict:
    """Замер на всех окнах набора: {"компьютер": {имя: замер}, "телефон": {имя: замер}}.

    Два контекста, а не девять: окно меняется размером, страница открывается заново — так скрипты
    обложки, которые смотрят на ширину при загрузке (ролик по размеру), выбирают своё."""
    папка = None
    if куда is not None:
        папка = Path(куда) / "окна"
        папка.mkdir(parents=True, exist_ok=True)
    итог: dict = {"компьютер": {}, "телефон": {}}
    for вид, окна, настройки in (
            ("компьютер", ОКНА_КОМПЬЮТЕРА, dict(user_agent=глаза.DESKTOP_UA, device_scale_factor=1)),
            ("телефон", ОКНА_ТЕЛЕФОНА, dict(user_agent=глаза.MOBILE_UA, device_scale_factor=2,
                                            is_mobile=True, has_touch=True))):
        контекст = None
        try:
            ширина, высота = окна[0][1], окна[0][2]
            контекст = браузер.new_context(locale="ru-RU", viewport={"width": ширина, "height": высота},
                                           **настройки)
            страница = контекст.new_page()
            for имя, ширина, высота in окна:
                снимок = папка / f"{глаза.слаг(имя)}.png" if папка is not None else None
                try:
                    итог[вид][имя] = _замерить_окно(страница, адрес, ширина, высота, снимок)
                except Exception as ошибка:   # noqa: BLE001 — одно окно не валит остальные
                    итог[вид][имя] = {"не_снялось": f"{type(ошибка).__name__}: {ошибка}".split("\n")[0]}
        except Exception as ошибка:   # noqa: BLE001
            итог[вид]["_ошибка"] = {"не_снялось": f"{type(ошибка).__name__}: {ошибка}".split("\n")[0]}
        finally:
            if контекст is not None:
                контекст.close()
    return итог


def находки(окна: dict) -> list[dict]:
    """Правила над замером. Окно, которое не снялось, молчит: про «не открылось» говорит проверка."""
    комп, телефон, вбок = [], [], []
    for вид in ("компьютер", "телефон"):
        for имя, з in (окна.get(вид) or {}).items():
            if not з or з.get("не_снялось") or not з.get("есть"):
                continue
            окно = з.get("высота_окна") or 0
            if (з.get("ширина_страницы") or 0) > (з.get("ширина_окна") or 0) + ДОПУСК_PX:
                вбок.append(f"{имя}: страница {з['ширина_страницы']} px при окне {з['ширина_окна']} px")
            if вид == "компьютер":
                if (з.get("ширина_окна") or 0) < БРЕЙКПОИНТ or окно < ВЫСОТА_МИН:
                    continue
                беды = []
                if з.get("низ_значимого", 0) > окно + ДОПУСК_PX:
                    что = ИМЕНА.get(з.get("что_ниже", ""), з.get("что_ниже", ""))
                    беды.append(f"{что} ниже окна на {з['низ_значимого'] - окно} px")
                if з.get("срезано_px", 0) > ДОПУСК_СРЕЗА_PX:
                    что = ИМЕНА.get(з.get("что_срезано", ""), з.get("что_срезано", ""))
                    беды.append(f"{что} срезано своей рамкой на {з['срезано_px']} px")
                if з.get("низ_кадра", 0) > окно + ДОПУСК_PX:
                    беды.append(f"кадр ниже окна на {з['низ_кадра'] - окно} px")
                if беды:
                    комп.append(f"{имя}: {', '.join(беды)}")
            elif з.get("низ_кнопки") is not None and з["низ_кнопки"] > окно + ДОПУСК_PX:
                телефон.append(f"{имя}: «{з.get('кнопка', '')}» ниже окна на {з['низ_кнопки'] - окно} px")
    итог = []
    if комп:
        итог.append(находка(
            ЧИНИТЬ, "Обложка не помещается в окно компьютера", комп,
            "в живом окне ноутбука — с панелью задач, вкладками и закладками — низ обложки уходит под "
            "кромку: цифры, строка доверия, ступни фигуры видны только после прокрутки. Экономьте на "
            "кадре, кеглях и отступах (ядро/блоки.md § 2-bis), юридические строки не сокращайте"))
    if телефон:
        итог.append(находка(
            ЧИНИТЬ, "Главная кнопка на телефоне ниже первого экрана", телефон,
            "ссылку открывают из мессенджера, Safari показывает страницу с обеими панелями — и шаг, ради "
            "которого собран сайт, оказывается под пальцем только после прокрутки. Ужмите кадр (около 40 % "
            "высоты), дайте тексту зайти на его нижний градиент, мельче отступы"))
    if вбок:
        итог.append(находка(
            ЧИНИТЬ, "На окнах набора страница ездит вбок", вбок,
            "на этом окне что-то шире экрана: страница дёргается в сторону под пальцем и мышью"))
    return итог


def строки_отчёта(окна: dict) -> list[str]:
    """Числа по окнам — рядом с находками, чтобы видно было и где влезло, и с каким запасом."""
    строки = ["", "## Обложка в первом экране", ""]
    for вид in ("компьютер", "телефон"):
        for имя, з in (окна.get(вид) or {}).items():
            if not з or з.get("не_снялось") or not з.get("есть"):
                continue
            if вид == "компьютер":
                строки.append(f"- {имя}: низ текста {з.get('низ_значимого')} · низ кадра {з.get('низ_кадра')} "
                              f"из {з.get('высота_окна')} px")
            else:
                строки.append(f"- {имя}: низ кнопки {з.get('низ_кнопки')} из {з.get('высота_окна')} px")
    return строки if len(строки) > 3 else []


def снимки(окна: dict) -> list[str]:
    return [з["снимок"] for вид in ("компьютер", "телефон") for з in (окна.get(вид) or {}).values()
            if isinstance(з, dict) and з.get("снимок")]
