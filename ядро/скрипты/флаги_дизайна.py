"""Семь предупреждений о дизайне страницы (контракт Г). Только 🟡 и ℹ️ — код выхода не трогают.
Замер — свой JS поверх глаза.ОБЩИЙ_JS по обоим размерам глаза.РАЗМЕРЫ; правила — чистые функции."""
from __future__ import annotations

import re
from datetime import datetime

import глаза
from находки import К_СВЕДЕНИЮ, ПОПРАВИТЬ, находка

ДЕДЛАЙН = re.compile(r'data-дедлайн="([^"]*)"')
ТЕЛО_МИН, МЕЛКОЕ_МИН = 16, 13

ЗАМЕР_ДИЗАЙНА_JS = глаза.ОБЩИЙ_JS + r"""
(() => {
  const все = [...document.querySelectorAll('body *')].filter(isVisible);
  const ст = э => getComputedStyle(э), кегль = э => parseFloat(ст(э).fontSize);
  const тени = все.filter(э => ст(э).boxShadow !== 'none').length, градиенты = все.filter(э => ст(э).backgroundImage.includes('gradient')).length;
  const кегли = [...new Set(все.filter(isLeafText).map(э => Math.round(кегль(э) * 2) / 2))].sort((a, b) => a - b);
  const секции = [...document.querySelectorAll('section.блок:not(.блок--подвал) .блок__внутри')]
    .map(в => [...в.children].map(д => д.tagName.toLowerCase()).join('>'));
  const главных = [...document.querySelectorAll('section.блок')].map(с => с.querySelectorAll('.кнопка--главная').length);
  const маска = э => (ст(э).maskImage || ст(э).webkitMaskImage || 'none') !== 'none';
  const фото = [...document.querySelectorAll('img')].filter(isVisible).filter(и => {
    const р = и.parentElement;
    return !(маска(и) || маска(р) || parseFloat(ст(и).borderRadius) > 0 || parseFloat(ст(р).borderRadius) > 0
             || и.classList.contains('аватар') || и.closest('.мокап'));
  }).length;
  const т = document.querySelector('[data-дедлайн]');
  const таймер = {есть: !!т, дедлайн: т ? (т.getAttribute('data-дедлайн') || '') : '',
    обнулён: !!т && [...т.querySelectorAll('.таймер__ячейка b')].every(б => /^0*$/.test(б.textContent.trim()))};
  const текст = все.filter(э => isLeafText(э) && э.textContent.trim().length >= 15);
  const тело = текст.filter(э => э.matches('p, li') && !э.closest('.мелкий, figcaption, .кикер, .бейдж, .цифра__подпись, .блок--подвал'));
  const мелкое = тело.filter(э => кегль(э) < 16);
  const мелкий_текст = {тело_мельче_16: мелкое.length, любой_мельче_13: текст.filter(э => кегль(э) < 13).length,
    примеры: мелкое.slice(0, 3).map(э => `${э.tagName.toLowerCase()}: ${Math.round(кегль(э))}px «${э.textContent.trim().slice(0, 40)}»`)};
  return {тени, градиенты, кегли, секции, главных_по_секциям: главных, фото_без_маски: фото, таймер, мелкий_текст};
})()
"""


def снять_дизайн(браузер, адрес: str) -> dict:
    """Замер по обоим размерам; не открылось — пустой словарь размера (правила его пропустят)."""
    итог = {}
    for размер in глаза.РАЗМЕРЫ:
        контекст = глаза.контекст(браузер, размер)
        try:
            страница = контекст.new_page()
            страница.goto(адрес, wait_until="load", timeout=30000)
            страница.wait_for_timeout(600)
            итог[размер] = страница.evaluate(ЗАМЕР_ДИЗАЙНА_JS)
        except Exception:   # noqa: BLE001 — флаги дизайна не должны валить проверку
            итог[размер] = {}
        finally:
            контекст.close()
    return итог


def _дата_в_прошлом(строка: str) -> bool:
    try:
        когда = datetime.fromisoformat(строка.strip())
    except ValueError:
        return True
    когда = когда if когда.tzinfo else когда.replace(tzinfo=глаза.МСК)
    return когда <= datetime.now(глаза.МСК)


def просроченные_дедлайны(html: str) -> list[str]:
    """Статически, до браузера: все data-дедлайн, что пусты, кривые или уже прошли (по МСК)."""
    return [д for д in ДЕДЛАЙН.findall(html) if not д.strip() or _дата_в_прошлом(д)]


def _мелкий_текст(телефон: dict, замеры: dict) -> dict | None:
    м = телефон.get("мелкий_текст") or {}
    if not (м.get("тело_мельче_16") or м.get("любой_мельче_13")):
        return None
    минимум = (((замеры.get("устройства") or {}).get("телефон") or {}).get("мелкий_текст") or {}).get("минимум_px")
    return находка(ПОПРАВИТЬ, "На телефоне текст мельче 16 px",
                   [f"тела мельче {ТЕЛО_МИН} px — {м.get('тело_мельче_16', 0)} шт., любого мельче {МЕЛКОЕ_МИН} px — "
                    f"{м.get('любой_мельче_13', 0)} шт." + (f", самый мелкий — {минимум} px" if минимум else "")]
                   + list(м.get("примеры") or []),
                   "на телефоне такое читают с прищуром и уходят — подними --кегль-текст до 16px, мелкое — до 13px")


def _главные_кнопки(компьютер: dict) -> dict | None:
    лишние = [f"экран {н + 1}: главных кнопок {к}" for н, к in enumerate(компьютер.get("главных_по_секциям") or []) if к >= 2]
    return находка(ПОПРАВИТЬ, "Больше одной главной кнопки на экране", лишние,
                   "две главные — значит ни одной: вторую сделай `кнопка кнопка--контур`") if лишние else None


def _таймер(компьютер: dict) -> dict | None:
    т = компьютер.get("таймер") or {}
    if not т.get("есть") or (т.get("дедлайн") and not _дата_в_прошлом(т["дедлайн"]) and not т.get("обнулён")):
        return None
    return находка(ПОПРАВИТЬ, "Таймер без живой даты", [f"data-дедлайн=«{т.get('дедлайн', '')}», ячейки "
                   f"{'обнулены' if т.get('обнулён') else 'идут'}"], "нули или прошедшая дата читаются как обман — "
                   "поставь дату в будущем с +03:00 или убери .таймер")


def _плоско(компьютер: dict) -> dict | None:
    """Ключа «тени» нет — размер не открылся, это не плоскость: молчим."""
    if "тени" not in компьютер or компьютер.get("тени") or компьютер.get("градиенты"):
        return None
    return находка(ПОПРАВИТЬ, "Страница плоская: ни одной тени и градиента",
                   [f"теней {компьютер.get('тени', 0)}, градиентов {компьютер.get('градиенты', 0)}"],
                   "плоская страница читается как черновик — карточкам `var(--тень)`, первому экрану `фон--пятна`")


def _секции(компьютер: dict) -> dict | None:
    секции = компьютер.get("секции") or []
    if len(секции) < 3 or len(set(секции)) != 1:
        return None
    return находка(К_СВЕДЕНИЮ, "Все секции одной структуры", [f"экранов {len(секции)}, у каждого «{секции[0]}»"],
                   "глаз перестаёт отличать экраны — смени раскладку через один: карточки, пара, цифры")


def _фото(компьютер: dict) -> dict | None:
    сколько = компьютер.get("фото_без_маски") or 0
    return находка(ПОПРАВИТЬ, "Фото без маски или скругления", [f"картинок без обёртки: {сколько}"],
                   "прямоугольное фото на скруглённой странице — как чужое: `figure.фото` или `.фото--маска`") if сколько else None


def _кегли(компьютер: dict) -> dict | None:
    кегли = компьютер.get("кегли") or []
    if not 0 < len(кегли) < 4:
        return None
    return находка(К_СВЕДЕНИЮ, "Меньше четырёх кеглей текста", ["кеглей: " + ", ".join(f"{к:g} px" for к in кегли)],
                   "четыре-пять кеглей задают иерархию: кикер, лид, текст, мелкий, цифра")


def флаги(разметка: dict, замеры: dict) -> list[dict]:
    """Контракт Г: семь правил над разметка["дизайн"]; нет замера — нет и находок."""
    дизайн = разметка.get("дизайн") or {}
    компьютер, телефон = дизайн.get("компьютер") or {}, дизайн.get("телефон") or {}
    if not компьютер and not телефон:
        return []
    кандидаты = [_мелкий_текст(телефон, замеры), _главные_кнопки(компьютер), _таймер(компьютер),
                 _плоско(компьютер), _секции(компьютер), _фото(компьютер), _кегли(компьютер)]
    return [н for н in кандидаты if н]
