"""Чужой сайт по ссылке: открыть в двух размерах, снять экраны и померить, что меряется.

Зачем. «Хочу как у них» — самая частая просьба. Чтобы разговор шёл о деле, а не о впечатлениях,
нужны две вещи рядом: снятые экраны (компьютер и телефон) и числа — шрифты, палитра, кегли,
воздух, адаптивность. Числа считает скрипт, вкус оценивает нейросеть по скриншоту.

Что кладём в папку: `компьютер.png` и `телефон.png` (первый экран), `компьютер-вся-страница.png`
и `телефон-вся-страница.png`, `замеры.json` (все числа) и `замеры.md` (то же словами).

Запуск:
    .venv/bin/python ядро/скрипты/посмотреть_сайт.py https://пример.ру
    .venv/bin/python ядро/скрипты/посмотреть_сайт.py https://пример.ру --куда сайты/моё-дело/референсы/
    .venv/bin/python ядро/скрипты/посмотреть_сайт.py сайты/моё-дело/сайт --только телефон
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(Path(__file__).resolve().parent))

import глаза  # noqa: E402

ПО_УМОЛЧАНИЮ = КОРЕНЬ / "сайты" / "_референсы"
НАПОМИНАНИЕ = (
    "У чужого сайта учимся, а не переодеваемся: берём приёмы и структуру, не тексты, фото "
    "и макет один в один."
)


def main() -> int:
    разбор = argparse.ArgumentParser(
        description="Открыть сайт на компьютере и на телефоне, снять экраны и померить.")
    разбор.add_argument("ссылка", help="ссылка на сайт, папка с index.html или просто домен")
    разбор.add_argument("--имя", help="короткое имя папки; по умолчанию — из домена")
    разбор.add_argument("--куда", help="папка для экранов и замеров")
    разбор.add_argument("--только", choices=["компьютер", "телефон"],
                        help="снять один размер вместо двух")
    аргументы = разбор.parse_args()

    try:
        адрес = глаза.адрес_из(аргументы.ссылка)
    except ValueError as ошибка:
        print(f"\n⛔ {ошибка}\n")
        return 1

    имя = аргументы.имя or глаза.слаг_из(адрес)
    папка = Path(аргументы.куда) if аргументы.куда else ПО_УМОЛЧАНИЮ / имя
    размеры = (аргументы.только,) if аргументы.только else ("компьютер", "телефон")

    print(f"Смотрю: {адрес}")
    print(f"Размеры: {' и '.join(размеры)}. Это займёт около минуты.\n")
    try:
        замеры = глаза.посмотреть(адрес, папка, размеры=размеры)
    except Exception as ошибка:
        print(f"\n⛔ Не удалось запустить браузер: {type(ошибка).__name__}: {ошибка}")
        print("   Проверьте установку: .venv/bin/python ядро/скрипты/selftest.py")
        print("   Что делать дальше — в ЕСЛИ-СЛОМАЛОСЬ.md.\n")
        return 1

    print(глаза.сводка(замеры))

    файлы = [str(п) for у in замеры["устройства"].values()
             for п in (у.get("скриншоты") or {}).values() if str(п).endswith(".png")]
    print("Файлы:")
    for путь in файлы + [str(папка / "замеры.md"), str(папка / "замеры.json")]:
        print(f"   {путь}")
    print(f"\n{НАПОМИНАНИЕ}\n")

    if any(у.get("статус") == "ок" for у in замеры["устройства"].values()):
        return 0
    return 2 if замеры["итог"].get("не_пустило") else 1


if __name__ == "__main__":
    sys.exit(main())
