"""Переложить обложку работы по нынешнему рецепту ядра, сохранив тексты и решения человека.

Зачем: экраны в `сайты/<имя>/экраны/` — собственные копии, снятые когда-то с рецептов ядра.
Ядро обновляется пакетами, копии — нет, и пересборка их не трогает (`свежесть.py`, шапка файла).
Эта команда — то самое «ядро не лезет в работу молча, а предлагает»: сборка говорит, что экран
отстал, а перекладывает его человек, отдельной командой и с явным флагом.

🔴 Перекладывается ТОЛЬКО обложка (первый экран). Экраны ниже неё нейросеть верстает свободно, у
них нет рецепта, с которого их можно переложить, — команда об этом говорит вслух и выходит спокойно.

Что переносится в новый экран: тексты — из `прототип.md`, картинки и связь — из `профиля`,
схема, светлота, атмосфера и сторона — из `дизайн.md` → «Решения», собственный комментарий-пояснение
из старого файла — как есть. Ничего из этого скрипт не сочиняет: нет в прототипе — нет и на экране.

Запуск: .venv/bin/python ядро/скрипты/обновить_экран.py сайты/моё-дело [--перезаложим]
Без `--перезаложим` — сухой прогон: показывает, что появится, и файла не трогает.
После — пересобрать сайт (`собрать.py`) и посмотреть оба вида глазами.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import свежесть  # noqa: E402
from находки import вывод_в_utf8  # noqa: E402


def построить_парсер() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(description="Переложить обложку по свежему рецепту ядра.")
    p.add_argument("работа", help="папка работы: сайты/<имя>")
    p.add_argument("--перезаложим", action="store_true",
                   help="переписать файл экрана (без флага — только показать, что изменится)")
    return p


def main_с_аргументами(argv) -> int:
    аргументы = построить_парсер().parse_args(argv)
    работа = Path(аргументы.работа).expanduser().resolve()
    if not работа.is_dir():
        print(f"Не нашёл папку работы «{аргументы.работа}». Нужна папка сайта целиком "
              "(сайты/<имя>), а не файл внутри неё.")
        return 2
    готовое = свежесть.перезаложить(работа)
    if готовое is None:
        # Экраны в работе есть, а обложки среди них нет — не поломка: человек мог позвать команду
        # ради экрана ниже обложки. Говорим, почему его не трогаем, и выходим спокойно.
        свободные = [ф.name for ф in sorted((работа / "экраны").glob("*.html"))
                     if свежесть.почему_не_сверяется(ф)] if (работа / "экраны").is_dir() else []
        if свободные and not (работа / "экраны" / "01-первый-экран.html").is_file():
            print(f"Обложки в работе нет, а {свежесть.НИЖЕ_ОБЛОЖКИ}. Перекладывать нечего: "
                  + ", ".join(свободные))
            return 0
        print("Переложить нечего: в работе нет «экраны/01-первый-экран.html» либо не читаются "
              "прототип и дизайн.md — по ним и собирается свежий экран.")
        return 2
    файл, новый, пропало = готовое
    старый = файл.read_text(encoding="utf-8-sig")
    print(f"# Обложка по свежему рецепту: {работа.name}\n")
    print(f"Трогаю только обложку: {свежесть.НИЖЕ_ОБЛОЖКИ}.\n")
    if not пропало and старый.strip() == новый.strip():
        print("Экран уже собран по нынешнему рецепту ядра — менять нечего.")
        return 0
    if пропало:
        print("Появится то, чего в вашем экране нет:\n" + "\n".join(f"  · {к}" for к in пропало))
    ушло = свежесть.отстал(новый, старый)
    if ушло:
        print("\nИсчезнет (этого нет в нынешнем рецепте):\n" + "\n".join(f"  · {к}" for к in ушло))
    if not аргументы.перезаложим:
        print(f"\nСухой прогон: файл «{файл}» не тронут. Переложить — та же команда с флагом "
              "--перезаложим. Тексты берутся из прототипа, решения из дизайн.md: чего там нет, "
              "того не будет и на экране — загляните в прототип до того, как перекладывать.")
        return 0
    файл.write_text(новый, encoding="utf-8")
    print(f"\nПереложил: {файл}\nТеперь пересоберите сайт и посмотрите оба вида: "
          f".venv/bin/python ядро/скрипты/собрать.py {аргументы.работа}")
    return 0


def main() -> int:
    вывод_в_utf8()
    return main_с_аргументами(sys.argv[1:])


if __name__ == "__main__":
    sys.exit(main())
