"""Картинка: вставить и сжать — файл человека → webp нужной ширины с именем латиницей.

Человек приносит файл (свой снимок, кадр со стока, картинку из генератора), скрипт кладёт его в
`сайты/<имя>/img/`: ужимает до 1600 px по ширине (меньшую не растягивает), сохраняет в webp и
переводит имя в латиницу — файлы внутри сайта становятся частью адреса, кириллица там ломается
в мессенджерах. `собрать.py` копирует `img/` работы в `сайт/img/` при каждой сборке. Метаданные
телефона (модель, где снято) в webp не переезжают: наружу уходит только картинка.

Запуск: .venv/bin/python ядро/скрипты/картинка.py <файл> --куда сайты/<имя>/img [--ширина 1600] [--имя имя-латиницей] [--карточка]
`--карточка` — картинка для мессенджера: `img/card.jpg`, 1200×630, обрезка по центру
(`ядро/картинки.md`, раздел 3). Печатает «было N КБ → стало M КБ».
"""
from __future__ import annotations

import argparse
import sys
import unicodedata
from pathlib import Path

from PIL import Image, ImageOps, UnidentifiedImageError

sys.path.insert(0, str(Path(__file__).resolve().parent))

import глаза  # noqa: E402
from находки import вывод_в_utf8  # noqa: E402

ШИРИНА = 1600
КАЧЕСТВО = 82                # webp: на глаз не отличить от исходника, вес — в разы меньше
КАРТОЧКА = (1200, 630)       # превью ссылки в мессенджерах и соцсетях
ИМЯ_КАРТОЧКИ = "card.jpg"    # jpg показывают все, webp в превью — не все
ЗАПАСНОЕ_ИМЯ = "kartinka"    # когда от имени после транслита ничего не осталось
# Буква → латиница без диакритики, чтобы имя читалось в адресе и печаталось с любой клавиатуры.
ТРАНСЛИТ = {"а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e", "ё": "yo", "ж": "zh", "з": "z",
            "и": "i", "й": "y", "к": "k", "л": "l", "м": "m", "н": "n", "о": "o", "п": "p", "р": "r",
            "с": "s", "т": "t", "у": "u", "ф": "f", "х": "kh", "ц": "ts", "ч": "ch", "ш": "sh",
            "щ": "shch", "ъ": "", "ы": "y", "ь": "", "э": "e", "ю": "yu", "я": "ya"}


def имя_латиницей(имя: str) -> str:
    """«Моё фото» → «moyo-foto»: транслит, строчными, всё, что не буква и не цифра, — дефис.
    Имя даётся без расширения: точка тоже стала бы дефисом."""
    латиница = unicodedata.normalize("NFKD", "".join(ТРАНСЛИТ.get(с, с) for с in имя.lower()))
    латиница = "".join(с if (с.isascii() and с.isalnum()) else "-" for с in латиница)  # «é» → «e», значок отпал
    return глаза.слаг(латиница) if латиница.strip("-") else ЗАПАСНОЕ_ИМЯ


def _открыть(исходник: Path) -> Image.Image:
    """Картинка как её видит человек: развёрнута по метке ориентации телефона, в режиме, который
    понимают webp и jpg. Прозрачность остаётся, палитра и чёрно-белое — в обычные цвета."""
    with Image.open(исходник) as файл:
        картинка = ImageOps.exif_transpose(файл)   # копия без ориентации и прочих меток телефона
        картинка.load()
    прозрачная = картинка.mode in ("RGBA", "LA", "PA") or "transparency" in картинка.info
    return картинка.convert("RGBA" if прозрачная else "RGB")


def сжать(исходник: Path, куда: Path, ширина: int = ШИРИНА,
          имя: str | None = None) -> tuple[Path, int, int]:
    """Файл → `куда/<имя>.webp` не шире `ширина`; вернуть путь, байт было, байт стало."""
    исходник, куда = Path(исходник), Path(куда)
    картинка = _открыть(исходник)
    картинка.thumbnail((ширина, картинка.height))   # уже заданной — не трогаем: растянутая мылит
    куда.mkdir(parents=True, exist_ok=True)
    путь = куда / f"{имя_латиницей(имя or исходник.stem)}.webp"
    картинка.save(путь, "WEBP", quality=КАЧЕСТВО, method=6)
    return путь, исходник.stat().st_size, путь.stat().st_size


def карточка(исходник: Path, куда: Path) -> Path:
    """Картинка для мессенджера: 1200×630, обрезка по центру, `card.jpg`."""
    исходник, куда = Path(исходник), Path(куда)
    картинка = _открыть(исходник)
    if картинка.mode == "RGBA":   # у jpg прозрачности нет: подложим белое, а не чёрное
        картинка = Image.alpha_composite(Image.new("RGBA", картинка.size, (255, 255, 255, 255)), картинка)
    картинка = ImageOps.fit(картинка.convert("RGB"), КАРТОЧКА, Image.Resampling.LANCZOS)
    куда.mkdir(parents=True, exist_ok=True)
    путь = куда / ИМЯ_КАРТОЧКИ
    картинка.save(путь, "JPEG", quality=85, optimize=True)
    return путь


def построить_парсер() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(description="Вставить картинку в сайт: сжать в webp нужной ширины, "
                                            "назвать латиницей, положить в img/ работы.")
    p.add_argument("файл", help="картинка от человека: jpg, png, webp")
    p.add_argument("--куда", metavar="ПАПКА", help="папка картинок работы: сайты/<имя>/img")
    p.add_argument("--ширина", type=int, default=ШИРИНА, metavar="PX", help=f"не шире стольких px (по умолчанию {ШИРИНА})")
    p.add_argument("--имя", metavar="ИМЯ", help="имя файла без расширения; кириллица переведётся в латиницу")
    p.add_argument("--карточка", action="store_true",
                   help=f"картинка для мессенджера: {ИМЯ_КАРТОЧКИ}, {КАРТОЧКА[0]}×{КАРТОЧКА[1]}")
    return p


def main_с_аргументами(argv) -> int:
    from проверить import вес_словами   # ленивый импорт: обложка → картинка → проверить → флаги_дизайна → обложка — цикл (GC 17)
    аргументы = построить_парсер().parse_args(argv)
    исходник = Path(аргументы.файл).expanduser()
    if not исходник.is_file():
        print(f"Не нашёл файл «{аргументы.файл}». Нужен путь к самой картинке — спроси человека, где она лежит.")
        return 2
    if not аргументы.куда:
        print("Не сказано, куда класть: добавь --куда сайты/<имя>/img — папку картинок этой работы.")
        return 2
    куда = Path(аргументы.куда).expanduser()
    try:
        if аргументы.карточка:
            путь = карточка(исходник, куда)
            было, стало = исходник.stat().st_size, путь.stat().st_size
            что = f"Карточка для мессенджера: {путь} — {КАРТОЧКА[0]}×{КАРТОЧКА[1]}"
            дальше = f"В поиск.md — строка «- Картинка карточки: img/{путь.name}»; адрес сайта к ней допишет собрать.py из профиля"
        else:
            путь, было, стало = сжать(исходник, куда, аргументы.ширина, аргументы.имя)
            with Image.open(путь) as готовая:
                что = f"Картинка: {путь} — {готовая.width}×{готовая.height}"
            дальше = f"В блок — src=\"img/{путь.name}\", в alt — словами, что на картинке"
    except UnidentifiedImageError:
        print(f"Файл «{исходник.name}» не открывается как картинка: формат с телефона (heic) или "
              "документ. Попроси человека пересохранить его в jpg или png.")
        return 2
    print(f"{что}, было {вес_словами(было)} → стало {вес_словами(стало)}\n{дальше}")
    return 0


def main() -> int:
    вывод_в_utf8()
    return main_с_аргументами(sys.argv[1:])


if __name__ == "__main__":
    sys.exit(main())
