"""Обложка движется: ролик идёт сам, а где автозапуск запрещён — движется анимированная картинка того же клипа.

Зачем. Ролик на обложке в удобном браузере играет всегда, и проверка «в Chrome всё движется» ничего не
доказывает. Живые люди открывают ссылку из мессенджера: встроенный браузер Telegram, VK, Max и iPhone в
режиме энергосбережения запрещают автозапуск любого видео — разметкой это не обходится. Если запасного
хода нет, человек видит застывший кадр, а то и системную кнопку «плей» поверх лица. Здесь — те условия.

Правило (`ядро/канон.md`, «Кадр и экран»; устройство — `ядро/картинки.md` § 7). Если на обложке есть
ролик, на каждом размере три прогона:
- **обычный** — к 3-й секунде кадр меняется: два снимка обложки на 2-й и 3-й секунде различаются;
- **`play()` отклонён** (так отвечает энергосбережение iOS и встроенный браузер) и
- **`play()` завис навсегда** (так ведут себя часть WebView) — встроенный автозапуск по `autoplay` тоже
  погашен; к 2-й секунде на месте ролика анимированная картинка, и два снимка через 1 с различаются.
Безмолвно стоящая обложка в двух последних — 🔴 «Обложка стоит, когда автозапуск запрещён»; в первом —
🔴 «Обложка стоит даже без запрета автозапуска». Снимаем только кадр обложки: всё остальное на странице
прячем, CSS-анимации (лента мозаики, зум сцены, пульс) ставим на паузу — двигаться должен сам клип.
Движок Safari (WebKit) поставлен — те же три прогона на телефоне в нём; нет — ℹ️ и команда установки.

Числа замера — по пикселям снимков, а не по свойствам ролика: часть WebView шлёт «playing» и стоит.
⚠️ Что встроенный браузер мессенджера покажет на самом деле, проверяется только на живом телефоне:
здесь — его поведение, воспроизведённое подменой `play()`, а не он сам.

Руками этот файл не запускают: его зовёт `проверить.py`.
"""
from __future__ import annotations

import io
import time
from pathlib import Path

import глаза
from находки import ЧИНИТЬ, К_СВЕДЕНИЮ, находка

СНИМОК_А_С, СНИМОК_Б_С = 2.0, 3.0   # от загрузки страницы: запасной ход обязан успеть к 2-й секунде
ПОРОГ_ЯРКОСТИ = 12                  # пиксель «изменился», если разница яркости больше — шум сжатия ниже
ПОРОГ_ДОЛИ = .001                   # кадр «движется», если изменилась хоть тысячная доля его пикселей
ЖДАТЬ_ЗАГРУЗКИ_МС = 20_000

# Встроенный автозапуск (атрибут autoplay) идёт мимо play() — его гасим на событии play: ролик стоит, как
# стоял бы в энергосбережении iOS.
_ГАСИТЬ = """document.addEventListener('play', e => { const в = e.target;
  if (в && в.tagName === 'VIDEO') { HTMLMediaElement.prototype.pause.call(в); } }, true);"""
ОТКАЗ_JS = _ГАСИТЬ + """
HTMLMediaElement.prototype.play = function () {
  return Promise.reject(new DOMException('автозапуск запрещён', 'NotAllowedError')); };"""
ВЕЧНО_JS = _ГАСИТЬ + """
HTMLMediaElement.prototype.play = function () { return new Promise(function () {}); };"""
РЕЖИМЫ = (("обычный", "", ""), ("отказ", ОТКАЗ_JS, "play() отклонён"), ("вечно", ВЕЧНО_JS, "play() завис"))
ЗАПРЕТ = ("отказ", "вечно")
РАЗМЕРЫ = {
    "компьютер": dict(viewport={"width": 1440, "height": 900}, user_agent=глаза.DESKTOP_UA, device_scale_factor=1),
    "телефон": dict(viewport={"width": 390, "height": 664}, user_agent=глаза.MOBILE_UA, device_scale_factor=2,
                    is_mobile=True, has_touch=True),
}
# WebKit не знает is_mobile — телефон в нём узнаётся по ширине и касанию, этого обложке хватает.
РАЗМЕРЫ_SAFARI = {"телефон": dict(viewport={"width": 390, "height": 664}, device_scale_factor=2, has_touch=True)}

ПОДГОТОВКА_JS = r"""() => {
  const герой = document.querySelector('section.блок--первый-экран');
  const фигура = герой && герой.querySelector('.первый-экран__картинка');
  if (!фигура || !фигура.querySelector('video')) return null;
  const стиль = document.createElement('style');
  стиль.textContent = '*, *::before, *::after { animation-play-state: paused !important; transition: none !important; }';
  document.head.appendChild(стиль);
  // Всё, что не кадр обложки и не его предок, — невидимо: таймер, бегущая строка, липкая кнопка не в счёт.
  for (const э of document.body.querySelectorAll('*')) {
    if (!э.contains(фигура) && !фигура.contains(э)) э.style.setProperty('visibility', 'hidden', 'important');
  }
  const р = фигура.getBoundingClientRect(), ш = document.documentElement.clientWidth, в = innerHeight;
  const x = Math.max(0, р.left), y = Math.max(0, р.top);
  const анимация = [...фигура.querySelectorAll('img')].flatMap(и => [...и.attributes]
    .filter(а => а.name.startsWith('data-анимация') || а.name.startsWith('data-аним-')).map(а => а.value));
  return {x, y, width: Math.max(1, Math.min(р.right, ш) - x), height: Math.max(1, Math.min(р.bottom, в) - y),
          ролики: фигура.querySelectorAll('video').length, анимация};
}"""

СОСТОЯНИЕ_JS = r"""() => {
  const фигура = document.querySelector('section.блок--первый-экран .первый-экран__картинка');
  if (!фигура) return null;
  const видно = э => { const с = getComputedStyle(э), р = э.getBoundingClientRect();
    return с.display !== 'none' && с.visibility !== 'hidden' && +с.opacity > 0 && р.width > 1 && р.height > 1; };
  return {ролики: [...фигура.querySelectorAll('video')].filter(в => !в.closest('[aria-hidden="true"]'))
            .map(в => ({время: в.currentTime, стоит: в.paused, видно: видно(в)})),
          картинки: [...фигура.querySelectorAll('img')].filter(и => видно(и) && и.naturalWidth > 0)
            .map(и => (и.currentSrc || и.src || '').split('/').pop().split('?')[0])};
}"""


def доля_изменений(а: bytes, б: bytes) -> float:
    """Какая доля пикселей двух снимков изменилась заметнее шума."""
    from PIL import Image, ImageChops

    первый = Image.open(io.BytesIO(а)).convert("L")
    второй = Image.open(io.BytesIO(б)).convert("L")
    if первый.size != второй.size:
        return 1.0
    маска = ImageChops.difference(первый, второй).point(lambda v: 255 if v > ПОРОГ_ЯРКОСТИ else 0)
    return маска.histogram()[255] / max(1, маска.width * маска.height)


def _открыть(браузер, адрес: str, размер: str, режим: str, js: str, настройки: dict) -> dict:
    контекст = браузер.new_context(locale="ru-RU", **настройки[размер])
    if js:
        контекст.add_init_script(js)
    страница = контекст.new_page()
    страница.goto(адрес, wait_until="load", timeout=ЖДАТЬ_ЗАГРУЗКИ_МС)
    старт = time.monotonic()
    return {"контекст": контекст, "страница": страница, "старт": старт, "размер": размер, "режим": режим,
            "рамка": страница.evaluate(ПОДГОТОВКА_JS)}


def _прогоны(браузер, адрес: str, имя_движка: str, настройки: dict, куда: Path | None) -> list[dict]:
    """Все прогоны движка сразу: страницы открываются подряд, снимки снимаются по часам каждой. Так девять
    прогонов идут секунд пять, а не по три секунды каждый."""
    открытые, итог = [], []
    try:
        for размер in настройки:
            for режим, js, _ in РЕЖИМЫ:
                try:
                    открытые.append(_открыть(браузер, адрес, размер, режим, js, настройки))
                except Exception as ошибка:   # noqa: BLE001 — один прогон не валит остальные
                    итог.append({"движок": имя_движка, "размер": размер, "режим": режим,
                                 "не_снялось": f"{type(ошибка).__name__}: {ошибка}".split("\n")[0]})
        живые = [о for о in открытые if о["рамка"]]
        if открытые and not живые:
            return [{"движок": имя_движка, "ролика_нет": True}]
        события = sorted([(о["старт"] + СНИМОК_А_С, н, "а") for н, о in enumerate(живые)]
                         + [(о["старт"] + СНИМОК_Б_С, н, "б") for н, о in enumerate(живые)])
        for когда, н, что in события:
            о = живые[н]
            пауза = когда - time.monotonic()
            if пауза > 0:
                о["страница"].wait_for_timeout(пауза * 1000)
            рамка = {к: о["рамка"][к] for к in ("x", "y", "width", "height")}
            try:
                о[что] = о["страница"].screenshot(clip=рамка)
                о["состояние_" + что] = о["страница"].evaluate(СОСТОЯНИЕ_JS)
            except Exception as ошибка:   # noqa: BLE001
                о["не_снялось"] = f"{type(ошибка).__name__}: {ошибка}".split("\n")[0]
        for о in живые:
            запись = {"движок": имя_движка, "размер": о["размер"], "режим": о["режим"],
                      "анимация": о["рамка"].get("анимация") or []}
            if о.get("не_снялось") or "а" not in о or "б" not in о:
                запись["не_снялось"] = о.get("не_снялось") or "снимок не снялся"
                итог.append(запись)
                continue
            до, после = о.get("состояние_а") or {}, о.get("состояние_б") or {}
            # петля: время могло перескочить на начало — считаем любое заметное изменение
            ролик_шёл = any(п["видно"] and not п["стоит"] and abs(п["время"] - р["время"]) > .05
                            for р, п in zip(до.get("ролики", []), после.get("ролики", [])))
            запись.update({"доля": round(доля_изменений(о["а"], о["б"]), 4), "ролик_шёл": ролик_шёл,
                           "картинки": после.get("картинки", []),
                           "время_роликов": [[round(р["время"], 2), round(п["время"], 2)] for р, п in
                                             zip(до.get("ролики", []), после.get("ролики", []))]})
            if куда is not None:
                снимок = куда / f"{глаза.слаг(f'{имя_движка}-{о['размер']}-{о['режим']}')}.png"
                снимок.write_bytes(о["б"])
                запись["снимок"] = str(снимок)
            итог.append(запись)
    finally:
        for о in открытые:
            try:
                о["контекст"].close()
            except Exception:   # noqa: BLE001
                pass
    return итог


def снять(браузер, адрес: str, куда: Path | None = None, движок=None) -> dict:
    """Замер «обложка движется»: Chromium на компьютере и телефоне, WebKit на телефоне. Ролика на обложке
    нет — один короткий заход и `{"есть": False}`."""
    папка = None
    if куда is not None:
        папка = Path(куда) / "движение"
        папка.mkdir(parents=True, exist_ok=True)
    try:
        пробный = _открыть(браузер, адрес, "компьютер", "обычный", "", РАЗМЕРЫ)
        есть = bool(пробный["рамка"])
        пробный["контекст"].close()
    except Exception as ошибка:   # noqa: BLE001 — про «не открылось» говорит сама проверка
        return {"есть": False, "не_снялось": f"{type(ошибка).__name__}: {ошибка}".split("\n")[0]}
    if not есть:
        return {"есть": False}
    итог: dict = {"есть": True, "прогоны": _прогоны(браузер, адрес, "Chromium", РАЗМЕРЫ, папка)}
    if движок is None:
        итог["safari"] = "движок браузеров не передан"
        return итог
    webkit = None
    try:
        webkit = движок.webkit.launch(headless=True)
    except Exception as ошибка:   # noqa: BLE001 — нет движка Safari: сказать и идти дальше
        итог["safari"] = f"{type(ошибка).__name__}: {ошибка}".split("\n")[0][:160]
        return итог
    try:
        итог["прогоны"] += _прогоны(webkit, адрес, "Safari", РАЗМЕРЫ_SAFARI, папка)
        итог["safari"] = "проверен"
    finally:
        webkit.close()
    return итог


def _нет_файлов(анимация: list[str], папка: Path | None) -> list[str]:
    if папка is None:
        return []
    return sorted({а for а in анимация if а and not а.startswith(("http:", "https:", "//", "data:"))
                   and not (Path(папка) / а.split("?")[0]).is_file()})


def находки(движение: dict, папка: Path | None = None) -> list[dict]:
    if not движение or not движение.get("есть"):
        return []
    стоит, стоит_всегда, причины = [], [], []
    анимация: list[str] = []
    for п in движение.get("прогоны") or []:
        if п.get("не_снялось") or п.get("ролика_нет") or "доля" not in п:
            continue
        анимация += п.get("анимация") or []
        if п["доля"] >= ПОРОГ_ДОЛИ:
            continue
        подпись = dict((р, т) for р, _, т in РЕЖИМЫ).get(п["режим"], "")
        видно = ", ".join(п.get("картинки") or []) or "ничего"
        строка = f"{п['размер']}, {п['движок']}" + (f", {подпись}" if подпись else "") + \
            f": два снимка через 1 с одинаковые, на месте — {видно}"
        (стоит if п["режим"] in ЗАПРЕТ else стоит_всегда).append(строка)
    итог = []
    if стоит:
        if not анимация:
            причины.append("у картинки обложки нет data-анимация-… — анимированной картинки нет вовсе: "
                           "возьмите рецепт схемы из ядра и сделайте её командой `обложка.py <ролик> --анимация`")
        причины += [f"{ф} — файла нет в папке сайта" for ф in _нет_файлов(анимация, папка)]
        итог.append(находка(
            ЧИНИТЬ, "Обложка стоит, когда автозапуск запрещён", стоит + причины,
            "встроенный браузер Telegram, VK, Max и iPhone в энергосбережении не запускают видео ни при какой "
            "разметке — а именно так ссылку открывают первой. Запасной ход — анимированная картинка того же "
            "клипа (AVIF + WebP, первый кадр = постер): `обложка.py <ролик> --куда сайты/<имя>/video --анимация`, "
            "разметка и скрипт — в рецепте схемы (ядро/картинки.md § 7)"))
    if стоит_всегда:
        итог.append(находка(
            ЧИНИТЬ, "Обложка стоит даже без запрета автозапуска", стоит_всегда,
            "ролик есть, но за три секунды кадр не сдвинулся: файл не открылся, у <video> нет autoplay muted "
            "playsinline в разметке или скрипт обложки не тот. Откройте страницу и посмотрите консоль браузера"))
    safari = движение.get("safari")
    if safari and safari != "проверен":
        from техника import ПОСТАВИТЬ_SAFARI

        итог.append(находка(
            К_СВЕДЕНИЮ, "Движение обложки в Safari не проверено",
            [f"движок Safari (WebKit) не поднялся: {safari}"],
            f"поставить один раз (около 80 МБ): `{ПОСТАВИТЬ_SAFARI}`. Что покажет встроенный браузер мессенджера, "
            "видно только на живом телефоне"))
    return итог


_ЧТО = {"обычный": "обычный прогон", "отказ": "play() отклонён", "вечно": "play() завис"}


def строки_отчёта(движение: dict) -> list[str]:
    if not движение or not движение.get("есть"):
        return []
    строки = ["", "## Обложка движется", ""]
    for п in движение.get("прогоны") or []:
        if п.get("ролика_нет"):
            continue
        начало = f"- {п.get('размер')} · {п.get('движок')} · {_ЧТО.get(п.get('режим'), п.get('режим'))}: "
        if п.get("не_снялось"):
            строки.append(начало + f"не снялось ({п['не_снялось']})")
            continue
        что = ("движется ролик" if п.get("ролик_шёл") else "движется картинка " + ", ".join(п.get("картинки") or [])) \
            if п["доля"] >= ПОРОГ_ДОЛИ else "стоит"
        строки.append(начало + f"{что} (изменилось {п['доля'] * 100:.1f} % кадра за 1 с)")
    if движение.get("safari") and движение["safari"] != "проверен":
        строки.append(f"- Safari: не проверен — {движение['safari']}")
    return строки


def снимки(движение: dict) -> list[str]:
    return [п["снимок"] for п in (движение or {}).get("прогоны") or [] if п.get("снимок")]
