"""Самопроверка системы: всё ли на месте и открывается ли браузер.

Проверяет по шагам: своё ли окружение запущено, стоят ли playwright и pillow, открываются ли
скрипты системы, проходит ли образцовый прототип свою же проверку, установлен ли сам браузер,
умеет ли он открыть страницу и сфотографировать её в двух размерах — на компьютере и на телефоне,
собирается ли страница из всех блоков образца и проходит ли она проверку без 🔴.
Если профиль уже настроен — заодно сверяет и его, а в конце говорит, что с каналом до
генератора картинок (есть ли Chrome и был ли вход) — но окна не открывает и на этом не падает.

Запуск:  .venv/bin/python ядро/скрипты/selftest.py
"""
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
PY = sys.executable
ПАПКА = ROOT / "сайты" / "_самопроверка"

sys.path.insert(0, str(Path(__file__).resolve().parent))
import глаза  # noqa: E402
from находки import вывод_в_utf8  # noqa: E402

СТРАНИЦА = """<!DOCTYPE html>
<html lang="ru"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="description" content="Страница самопроверки: на ней система проверяет саму себя.">
<meta name="robots" content="noindex">
<title>Самопроверка системы</title></head>
<body style="font-family:sans-serif;max-width:640px;margin:60px auto;padding:0 24px;color:black;background:white;">
<h1>Система работает</h1>
<p>Это тестовая страница для самопроверки: если браузер её открыл и сфотографировал —
значит окружение и браузер на месте.</p>
<p><a href="mailto:проверка@пример.рф" style="color:navy;">Кнопка для проверки</a></p>
</body></html>
"""


def шаг(описание, функция):
    print(f"→ {описание}")
    try:
        return функция()
    except Exception as ошибка:
        print(f"\n⛔ Не прошло: {описание}")
        for строка in str(ошибка).splitlines():
            print(f"   {строка}")
        print("   Что делать — в ЕСЛИ-СЛОМАЛОСЬ.md.\n")
        sys.exit(1)


def проверить_окружение():
    """sys.executable должен быть внутри .venv — иначе это чужой, системный python.

    ⚠️ Сравнивать нужно по sys.prefix, а не по резолву sys.executable: внутри .venv python —
    это цепочка символических ссылок (python → python3.12 → .../miniconda3/...), и полный
    resolve() уводит проверку на системный интерпретатор, даже когда запуск честно был через
    `.venv/bin/python`.
    """
    venv = (ROOT / ".venv").resolve()
    if Path(sys.prefix).resolve() != venv:
        raise RuntimeError(
            f"Запущено не своим окружением: {PY}.\nНужно: bash ядро/скрипты/setup.sh, "
            "затем .venv/bin/python ядро/скрипты/selftest.py"
        )


def проверить_библиотеки():
    import importlib
    for имя, подсказка in (("playwright", "playwright"), ("PIL", "pillow")):
        try:
            importlib.import_module(имя)
        except ImportError:
            raise RuntimeError(
                f"Библиотека «{подсказка}» не установлена.\nЗапустите: bash ядро/скрипты/setup.sh"
            )


def проверить_модули():
    """Скрипты системы должны хотя бы импортироваться: опечатка или обрыв в коде вылезет здесь,
    а не посреди работы с человеком. Чего ещё нет на диске — пропускаем, это нормально."""
    import importlib
    папка = Path(__file__).resolve().parent
    for имя in ("посмотреть_сайт", "ресёрч_ниши", "проверить_прототип",
                "находки", "собрать", "витрина", "картинка", "опубликовать"):
        if not (папка / f"{имя}.py").exists():
            print(f"   {имя}.py ещё не сделан — пропускаю, это нормально")
            continue
        try:
            importlib.import_module(имя)
        except Exception as ошибка:
            raise RuntimeError(
                f"Модуль «{имя}.py» не открывается: {type(ошибка).__name__}: {ошибка}"
            )


def проверить_эталон_прототипа():
    """Прогон проверки прототипа на своём же образце: `эталон-прототипа.md` обязан проходить её
    без 🔴. Разошлись формат и проверка — узнаём здесь, а не на прототипе живого человека.
    Профиль не читаем (`--без-профиля`): образец собран на выдуманной нише и ничьих запретов
    знать не должен."""
    скрипт = ROOT / "ядро" / "скрипты" / "проверить_прототип.py"
    эталон = ROOT / "ядро" / "эталон-прототипа.md"
    if not скрипт.exists() or not эталон.exists():
        print("→ проверка прототипа: проверить_прототип.py или эталон ещё не сделаны — пропускаю")
        return
    шаг("проверяю эталон прототипа скриптом",
        lambda: _прогнать_эталон(скрипт, эталон))


def _прогнать_эталон(скрипт: Path, эталон: Path):
    """Ждёт кода 0: на образце не должно быть ни одной находки уровня «чинить до вёрстки»."""
    готово = subprocess.run(
        [PY, str(скрипт), str(эталон), "--без-профиля"],
        cwd=ROOT, capture_output=True, text=True, encoding="utf-8",
    )
    if готово.returncode != 0:
        вывод = (готово.stdout + готово.stderr).strip()
        хвост = _красные_находки(вывод) or вывод.splitlines()[-12:]
        raise RuntimeError("Образцовый прототип не прошёл свою же проверку "
                           f"(код {готово.returncode}):\n" + "\n".join(хвост))


def _красные_находки(вывод: str) -> list[str]:
    """Оставляет от отчётов только то, из-за чего шаг упал: чей прототип и что в нём 🔴.

    В эталоне два прототипа, их отчёты идут подряд, поэтому «последние строки вывода» показали бы
    конец последнего — а сломан обычно первый, и человек читал бы «Ничего не нашлось».
    """
    находки: list[str] = []
    прототип = ""
    собираем = False
    for строка in вывод.splitlines():
        if строка.startswith("Прототип «"):
            прототип, собираем = строка, False
        elif строка.startswith("🔴"):
            собираем = not строка.rstrip().endswith("— 0")
            if собираем:
                находки += [прототип, строка]
        elif строка.startswith(("🟡", "ℹ️")):
            собираем = False
        elif собираем and строка.strip():
            находки.append(строка)
    return находки[:12]


def проверить_браузер(playwright):
    путь = Path(playwright.chromium.executable_path)
    if not путь.exists():
        raise RuntimeError(
            "Браузер не установлен.\n"
            "Поставьте командой: .venv/bin/python -m playwright install chromium"
        )


def снять_скриншоты(браузер, страница_путь):
    ПАПКА.mkdir(parents=True, exist_ok=True)
    for размер, имя_файла in (("компьютер", "компьютер.png"), ("телефон", "телефон.png")):
        контекст = глаза.контекст(браузер, размер)
        страница = контекст.new_page()
        страница.goto(страница_путь.as_uri())
        страница.screenshot(path=str(ПАПКА / имя_файла))
        контекст.close()


def проверить_проверяющего():
    """Прогон проверяющего на крошечном сайте: собирается ли отчёт и не находит ли он дыр там,
    где их нет. Сайт живёт во временной папке, итог ложится рядом с остальной самопроверкой."""
    скрипт = ROOT / "ядро" / "скрипты" / "проверить.py"
    if not скрипт.exists():
        print("→ проверка сайта: проверить.py ещё не сделан — пропускаю, это нормально")
        return
    with tempfile.TemporaryDirectory() as временная_папка:
        (Path(временная_папка) / "index.html").write_text(СТРАНИЦА, encoding="utf-8")
        шаг("проверяю крошечный сайт целиком — как проверяют настоящий",
            lambda: _прогнать_проверку(скрипт, временная_папка))


def _прогнать_проверку(скрипт: Path, папка_сайта: str):
    """Запускает проверить.py и ждёт от него двух вещей: кода 0 и отчёта рядом с экранами."""
    готово = subprocess.run(
        [PY, str(скрипт), папка_сайта, "--куда", str(ПАПКА)],
        cwd=ROOT, capture_output=True, text=True,
    )
    if готово.returncode != 0:
        хвост = (готово.stdout + готово.stderr).strip().splitlines()[-12:]
        raise RuntimeError("На чистой странице проверка нашла то, чего быть не должно "
                           f"(код {готово.returncode}):\n" + "\n".join(хвост))
    if not (ПАПКА / "отчёт.md").exists():
        raise RuntimeError("Проверка прошла, но отчёта нет — ждали отчёт.md рядом с экранами.")


def проверить_сборку():
    """Прогон сборщика на образце из всех блоков ядра: страница из всех 42 блоков обязана
    собраться без 🔴, нести иконку и липкую кнопку и пройти проверить.py кодом 0. Разошлись блок,
    стили и проверка — узнаём здесь, а не на первом экране живого человека. Работа, сайт и отчёт
    живут во временной папке: в `сайты/` после шага не остаётся ничего."""
    скрипты = Path(__file__).resolve().parent
    фикстуры = скрипты / "tests" / "фикстуры"
    экраны, образец = фикстуры / "экраны-все", фикстуры / "работа-образец"
    if not (скрипты / "собрать.py").exists() or not экраны.is_dir() or not образец.is_dir():
        print("→ сборка страницы: собрать.py или образцы ещё не сделаны — пропускаю, это нормально")
        return
    with tempfile.TemporaryDirectory() as временная_папка:
        шаг("собираю страницу из всех 42 блоков образца и проверяю её — как настоящую",
            lambda: _прогнать_сборку(Path(временная_папка), экраны, образец))


def _прогнать_сборку(папка: Path, экраны: Path, образец: Path):
    """Ждёт двух вещей: ни одной находки «чинить до показа» от собрать.py и кода 0 от проверить.py.
    Образцовый профиль кладётся рядом с работой — так слот связи получает настоящую кнопку, а не 🟡."""
    import shutil
    import собрать
    from находки import ЧИНИТЬ
    работа = папка / "работа"
    shutil.copytree(экраны, работа / "экраны")
    shutil.copytree(образец / "img", работа / "img")   # блоки ссылаются на img/пример.svg
    shutil.copytree(образец / "video", работа / "video")   # живая обложка и живая сцена берут video/пример.*
    shutil.copytree(образец.parent / "профиль-образец", папка / "профиль-образец")
    for имя in ("дизайн.md", "поиск.md", "прототип.md"):
        shutil.copyfile(образец / имя, работа / имя)
    путь, найденное = собрать.собрать(работа)
    красное = [н for н in найденное if н["уровень"] == ЧИНИТЬ]
    if красное:
        raise RuntimeError("Страница из всех блоков собралась с находками «чинить до показа»:\n"
                           + "\n".join(f"{н['что']}: {'; '.join(н['строки'])}" for н in красное))
    html = путь.read_text(encoding="utf-8")
    if '<svg class="иконка"' not in html:
        raise RuntimeError("В собранной странице нет ни одной иконки (svg class=\"иконка\") — "
                           "разошлись блоки и подстановка {{ИКОНКА:имя}} в собрать.py")
    if 'class="липкая-кнопка"' not in html:
        raise RuntimeError('В собранной странице нет липкой кнопки (class="липкая-кнопка") — '
                           "разошлись первый экран и собрать.py")
    готово = subprocess.run(
        [PY, str(ROOT / "ядро" / "скрипты" / "проверить.py"), str(работа / "сайт"),
         "--куда", str(папка / "проверка")],
        cwd=ROOT, capture_output=True, text=True, encoding="utf-8",
    )
    if готово.returncode != 0:
        хвост = (готово.stdout + готово.stderr).strip().splitlines()[-12:]
        raise RuntimeError("Страница из всех блоков не прошла проверку "
                           f"(код {готово.returncode}):\n" + "\n".join(хвост))


def проверить_профиль():
    """Если профиль уже настроен — сверяет его профиль.py --проверить. Нет ни одного — пропускаем,
    это нормальное рабочее состояние, а не поломка."""
    скрипт = ROOT / "ядро" / "скрипты" / "профиль.py"
    if not скрипт.exists():
        print("→ проверка профиля: профиль.py ещё не сделан — пропускаю, это нормально")
        return
    папка_профили = ROOT / "профили"
    профили = [
        д for д in папка_профили.iterdir()
        if д.is_dir() and not д.name.startswith("_") and (д / "profile.json").exists()
    ] if папка_профили.exists() else []
    if not профили:
        print("→ проверка профиля: профиля ещё нет — пропускаю")
        return
    шаг("проверяю профиль", lambda: subprocess.run(
        [PY, str(скрипт), "--проверить"], cwd=ROOT, check=True,
    ))


def проверить_канал():
    """Канал до генератора картинок: есть ли чем рисовать.

    Смотрим НАЛИЧИЕ, а не живой вход: нашёлся ли Chrome, входили ли в этом окне хоть раз, не
    занято ли окно другим прогоном. Живой вход здесь не проверяется намеренно — он поднимает
    окно и ждёт человека до двадцати минут; для этого есть отдельная команда `кисть.py --проверь`.

    Шаг не роняет самопроверку ни при каком ответе: картинки — возможность, а не шаг маршрута,
    и сайт собирается без них. Поэтому здесь не `шаг()`, а печать словами — как в соседних
    шагах с тем, чего ещё нет.
    """
    if not (Path(__file__).resolve().parent / "кисть.py").exists():
        print("→ канал до генератора: кисть.py ещё не сделан — пропускаю, это нормально")
        return
    print("→ смотрю канал до генератора картинок (окно не открываю)")
    try:
        import кисть
        for строка in кисть.слова_канала(кисть.состояние_канала()):
            print(f"   {строка}")
    except Exception as ошибка:
        print(f"   не смог посмотреть канал: {type(ошибка).__name__}: {ошибка}")
        print("   Это не поломка: картинки необязательны, сайт собирается и без них.")


def main():
    вывод_в_utf8()
    шаг("проверяю, что запускаюсь из своего окружения (.venv)", проверить_окружение)
    шаг("проверяю, что playwright и pillow на месте", проверить_библиотеки)
    шаг("проверяю, что модули системы импортируются", проверить_модули)
    проверить_эталон_прототипа()

    from playwright.sync_api import sync_playwright

    временный_файл = Path(tempfile.gettempdir()) / "site-builder-самопроверка.html"
    шаг("готовлю тестовую страницу",
        lambda: временный_файл.write_text(СТРАНИЦА, encoding="utf-8"))

    try:
        with sync_playwright() as p:
            шаг("проверяю, что браузер (Chromium) установлен", lambda: проверить_браузер(p))
            браузер = шаг("запускаю браузер", lambda: глаза.запустить_браузер(p))
            try:
                шаг(
                    "открываю тестовую страницу — на компьютере и на телефоне",
                    lambda: снять_скриншоты(браузер, временный_файл),
                )
            finally:
                браузер.close()
    finally:
        временный_файл.unlink(missing_ok=True)

    проверить_проверяющего()
    проверить_сборку()
    проверить_профиль()
    проверить_канал()

    полка = ПАПКА.relative_to(ROOT).as_posix()
    print("\n✅ Всё работает.")
    print(f"   Скриншоты: {полка}/компьютер.png, {полка}/телефон.png")
    print(f"   Отчёт проверки: {полка}/отчёт.md")
    print("   Дальше: скажите, чей сайт собираем, — или /setup.")


if __name__ == "__main__":
    main()
