"""Что открыть перед экраном этого типа: инструкция, примеры галереи, отмеченное «беру».

Ничего не собирает и не пишет — только печатает четыре адреса, чтобы не искать их по памяти.
Шаг необязательный: знаешь, где что лежит, — верстай сразу по `ядро/вёрстка.md`.

Запуск:
    .venv/bin/python ядро/скрипты/экран.py <тип> [--работа сайты/<имя>]
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from находки import вывод_в_utf8  # noqa: E402

ЯДРО = Path(__file__).resolve().parent.parent
ИНСТРУКЦИИ = ЯДРО / "экраны"
ПРИМЕРЫ = ЯДРО / "галерея" / "примеры"
ЦЕЛИКОМ = ПРИМЕРЫ / "страница-целиком"
РАЗДЕЛ_БЕРУ = re.compile(r"^##[ \t]+Беру[ \t]*$", re.M | re.I)
ОТМЕЧЕНО = re.compile(r"^[ \t]*-[ \t]*\[[xXхХ]\][ \t]*(.+?)[ \t]*$", re.M)
НАПОМИНАНИЕ = (
    "Перед первой строкой вёрстки перечитай `сайты/<имя>/дизайн.md` → «Решения»: цвета, кегли и "
    "скругления берутся только оттуда, переменными.",
    "Как устроен свободный экран — `ядро/вёрстка.md`; по чему его примут — `ядро/канон.md`. "
    "Контракт В: один `<style>` сразу за `<section>`, каждое правило с `#экран-NN`.",
)


def типы() -> list[str]:
    return sorted(ф.stem for ф in ИНСТРУКЦИИ.glob("*.md"))


def примеры(тип: str) -> list[str]:
    """Примеры этого типа в галерее: по набору на строку, плюс страницы целиком, где он встречается."""
    строки = [f"ядро/галерея/примеры/{тип}/{папка.name}/ — экран.html, компьютер.png, телефон.png, о-примере.md"
              for папка in sorted((ПРИМЕРЫ / тип).iterdir()) if папка.is_dir()] \
        if (ПРИМЕРЫ / тип).is_dir() else []
    for страница in sorted(ЦЕЛИКОМ.glob("*/страница.html")):
        текст = страница.read_text(encoding="utf-8", errors="ignore")
        if f'data-тип="{тип}"' in текст or f'id="{тип}"' in текст:
            строки.append(f"ядро/галерея/примеры/страница-целиком/{страница.parent.name}/"
                          f"страница.html#{тип} — тот же экран в цветовой партитуре целой страницы")
    return строки


def беру(работа: Path | None) -> list[str]:
    """Отмеченные строки раздела «Беру» из `референсы.md` работы. Пусто — список пуст."""
    if работа is None:
        return []
    файл = Path(работа) / "референсы.md"
    if not файл.is_file():
        return []
    текст = файл.read_text(encoding="utf-8-sig")
    начало = РАЗДЕЛ_БЕРУ.search(текст)
    if not начало:
        return []
    хвост = текст[начало.end():]
    следующий = re.search(r"^##[ \t]+", хвост, re.M)
    return ОТМЕЧЕНО.findall(хвост[:следующий.start()] if следующий else хвост)


def строки(тип: str, работа: Path | None) -> list[str]:
    """Всё, что стоит открыть перед экраном, — одним списком в порядке чтения."""
    итог = [f"# Экран «{тип}»", "",
            f"1 · Инструкция типа: ядро/экраны/{тип}.md — читать целиком до первой строки вёрстки.",
            "", "2 · Примеры галереи (смотреть глазами, не копировать HTML):"]
    список = примеры(тип)
    итог += [f"   {строка}" for строка in список] or \
            ["   примеров этого типа в галерее пока нет — ориентируйся на инструкцию и канон"]
    итог += ["", "3 · Раздел «Беру» из референсов работы:"]
    отмеченное = беру(работа)
    if отмеченное:
        итог += [f"   — {строка}" for строка in отмеченное]
    elif работа is None:
        итог.append("   работа не названа (--работа сайты/<имя>) — приёмы референсов не показываю")
    else:
        итог.append(f"   в «{Path(работа) / 'референсы.md'}» нет раздела «Беру» с отметками "
                    "`- [x]` — значит, приёмов от чужих сайтов на этот экран не записано")
    итог += ["", "4 · Перед вёрсткой:"] + [f"   {строка}" for строка in НАПОМИНАНИЕ]
    return итог


def построить_парсер() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(description="Что открыть перед экраном этого типа.")
    p.add_argument("тип", help="тип экрана из каталога ядро/экраны.md, например «отзывы»")
    p.add_argument("--работа", help="папка работы: сайты/<имя> — откуда взять отмеченное «беру»")
    return p


def main_с_аргументами(argv) -> int:
    аргументы = построить_парсер().parse_args(argv)
    все = типы()
    if аргументы.тип not in все:
        print(f"Типа «{аргументы.тип}» в каталоге нет. Есть эти: " + ", ".join(все) + ".")
        print("Какой экран прототипа каким типом верстается — ядро/экраны.md.")
        return 2
    работа = Path(аргументы.работа).expanduser() if аргументы.работа else None
    if работа is not None and not работа.is_dir():
        print(f"Не нашёл папку работы «{аргументы.работа}» — печатаю без раздела «Беру».")
        работа = None
    print("\n".join(строки(аргументы.тип, работа)))
    return 0


def main() -> int:
    вывод_в_utf8()
    return main_с_аргументами(sys.argv[1:])


if __name__ == "__main__":
    sys.exit(main())
