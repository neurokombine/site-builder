"""Сборка страницы: экраны работы + дизайн-система + служебная голова → сайт в папке, и показ
его в двух размерах — на компьютере и на телефоне (🔴 одобрение = одобрение обоих, CLAUDE.md § 4).

Берёт `сайты/<имя>/экраны/NN-<тип>.html` (по файлу на экран прототипа), подставляет в слот
связи начинку по профилю, сшивает всё в каркас, вписывает палитру из `дизайн.md` и голову из
`поиск.md` — и кладёт готовое в `сайты/<имя>/сайт/`. Потом отдаёт папку локальным сервером,
снимает два экрана и собирает `показ.html`, где они лежат рядом.

Запуск: .venv/bin/python ядро/скрипты/собрать.py сайты/моё-дело [--экран 3] [--без-показа] [--куда ПАПКА]
⛔ Тексты скрипт не сочиняет: чего нет в экранах, того нет и на странице; оставшаяся заглушка
`{{…}}` — красная находка, такую страницу человеку не показывают.
"""
