def _склейка_стилей() -> str:
    """Все файлы стилей ядра одной строкой, в порядке СТИЛИ — так же, как их увидит сайт."""
    return "\n".join(файл.read_text(encoding="utf-8") for файл in СТИЛИ)


# Отчуждаемость: файлы ядра живут с комментариями — в них ход разработки, чужие имена и решения,
# которых в сайте ученика быть не должно (посетитель откроет исходник и прочтёт всё). Сами файлы
# ядра не трогаем: комментарии там на месте и нужны тому, кто ядро правит. Чистится ТОЛЬКО то, что
# уезжает в папку сайта, — на последнем шаге, когда страница и стили уже собраны.
КОММЕНТАРИЙ_БЛОКОМ = re.compile(r"/\*.*?\*/", re.S)          # и CSS, и JS пишут блочный одинаково
СТРОКОВЫЙ_ЛИТЕРАЛ = re.compile(r'"[^"\n]*"|\'[^\'\n]*\'|`[^`]*`', re.S)
КОММЕНТАРИЙ_HTML = re.compile(r"<!--(?!\[if).*?-->", re.S)   # условный комментарий IE — не наш, оставляем
СТРОКА_ЦЕЛИКОМ_КОММЕНТАРИЙ = re.compile(r"^[ \t]*//.*$", re.M)
ХВОСТ_СТРОКИ = re.compile(r"[ \t]+$", re.M)
ПУСТЫЕ_ПОДРЯД = re.compile(r"\n(?:[ \t]*\n)+")   # без отступа следующей строки: её лесенку не трогаем


def _подчистить(текст: str) -> str:
    """После вырезания остаются хвосты пробелов и дыры из пустых строк — пустые схлопываем в одну."""
    return ПУСТЫЕ_ПОДРЯД.sub("\n\n", ХВОСТ_СТРОКИ.sub("", текст))


def _без_блочных(текст: str) -> str:
    """`/* … */` вон — но не тот, что лежит внутри кавычек (`content: "/*"`, адрес в строке кода).
    В файлах ядра таких нет (проверено тестом), а вот в чужом файле стилей случиться может."""
    неприкосновенно = [(м.start(), м.end()) for м in СТРОКОВЫЙ_ЛИТЕРАЛ.finditer(текст)
                       if "/*" in м.group(0) or "*/" in м.group(0)]
    return КОММЕНТАРИЙ_БЛОКОМ.sub(
        lambda м: м.group(0) if any(н <= м.start() < к for н, к in неприкосновенно) else "", текст)


def без_комментариев_css(css: str) -> str:
    """Склейка стилей для сайта: правила остаются все до одного, комментарии не уезжают никуда."""
    return _подчистить(_без_блочных(css))


def без_комментариев_html(html: str) -> str:
    """Собранная страница без `<!-- … -->`: подсказки шаблонов блоков написаны тому, кто собирает
    сайт, а читал бы их тот, кто нажал «исходный код страницы»."""
    return _подчистить(КОММЕНТАРИЙ_HTML.sub("", html))


def без_комментариев_js(код: str) -> str:
    """Скрипт, который встраивается в страницу: вон блочные `/* … */` и строки, целиком занятые
    `// …`. Хвостовой `//` в строке кода не трогаем — там он бывает частью адреса (`https://…`)
    или живёт внутри кавычек, и вырезать его вслепую значит сломать сайт ради опрятности."""
    return _подчистить(СТРОКА_ЦЕЛИКОМ_КОММЕНТАРИЙ.sub("", _без_блочных(код))).strip()


def _скрипт_ядра(файл: Path) -> str:
    """Файл скрипта ядра → тело для <script> на странице: без комментариев и без пустых краёв."""
    return без_комментариев_js(файл.read_text(encoding="utf-8"))


