БЛОКИ = Path(__file__).resolve().parent.parent / "блоки"
КАРКАС = БЛОКИ / "каркас.html"
СТИЛИ = БЛОКИ / "стили.css"
# Имена, которые ждёт стили.css (их 21, дизайн-система.md § 2); свои — только `--свой-…`.
ПЕРЕМЕННЫЕ = sorted(set(re.findall(r"var\((--[\w-]+)\)", СТИЛИ.read_text(encoding="utf-8"))))
ИМЯ_ПЕРЕМЕННОЙ = re.compile(r"(--[\w-]+)\s*:")

# Слот блока: `{{ИМЯ}}`, `{{ПУНКТ_2}}` (номер через `_`) или `{{СВЯЗЬ:Текст на кнопке}}` (контракт Б).
ПЛЕЙСХОЛДЕР = re.compile(r"\{\{([А-ЯЁ_0-9]+)(?::([^}]*))?\}\}")
СПОСОБЫ = ("телеграм", "max", "вк", "whatsapp", "форма", "виджет")

ПОЛЕ = re.compile(r"^-[ \t]+([^:\n]+?)[ \t]*:[ \t]*(.*)$", re.M)   # «- Ключ: значение» в шапке
РАЗДЕЛ = re.compile(r"^##[ \t]+(.+?)[ \t]*$", re.M)                  # «## Вариант 1 · имя», «## Решения»
ВАРИАНТ = re.compile(r"^Вариант\s+(\d+)\s*[·:—-]?\s*(.*)$")
ЧЕМ_ОТЛИЧАЕТСЯ = re.compile(r"^Чем отличается:[ \t]*(.*)$", re.M)   # строка варианта, её показывает витрина
КОД = re.compile(r"```[^\n]*\n(.*?)```", re.S)                       # блок кода внутри раздела
ЗАГОЛОВОК_ПО_УМОЛЧАНИЮ = "Сайт собирается"
ПОЛЯ_ПОИСКА = {"заголовок вкладки": "заголовок", "описание для поиска": "описание",
               "слова для поиска": "слова", "карточка в мессенджере": "карточка_текст",
               "картинка карточки": "карточка_картинка", "статус": "статус"}
ПУСТО = {"", "нет", "-", "—", "–"}
# Начертания, которые заказываем у Google Fonts: заголовкам нужен жирный, тексту хватает двух.
НАЧЕРТАНИЯ = {"--шрифт-заголовков": "400;600;700", "--шрифт-текста": "400;600"}
ЯКОРЬ_КОНТАКТОВ = '<a id="экран-контакты" aria-hidden="true"></a>'
ОДОБРЕНИЕ = "Одобрение = одобрение обоих: смотрим оба и только потом «ок»"


def прочитать_дизайн(путь: Path) -> dict:
    """`дизайн.md` (контракт А) → шапка, варианты с их css и раздел «Решения». Витрина берёт
    варианты, сборка — решения; из раздела берём ПЕРВЫЙ блок кода, ниже бывают куски на выброс."""
    итог: dict = {"профиль": "", "референс": "", "статус": "", "варианты": [], "решения": None}
    путь = Path(путь)
    if not путь.is_file():
        return итог
    текст = путь.read_text(encoding="utf-8-sig")
    разделы = list(РАЗДЕЛ.finditer(текст))
    for поле in ПОЛЕ.finditer(текст[:разделы[0].start()] if разделы else текст):
        ключ = поле.group(1).strip().lower()
        if ключ in итог:
            итог[ключ] = поле.group(2).strip()
    for номер, раздел in enumerate(разделы):
        конец = разделы[номер + 1].start() if номер + 1 < len(разделы) else len(текст)
        код = КОД.search(текст, раздел.end(), конец)
        css = код.group(1).strip() if код else ""
        вариант = ВАРИАНТ.match(раздел.group(1))
        if вариант:
            чем = ЧЕМ_ОТЛИЧАЕТСЯ.search(текст, раздел.end(), конец)
            итог["варианты"].append({"номер": int(вариант.group(1)), "имя": вариант.group(2).strip(),
                                     "css": css, "чем_отличается": чем.group(1).strip() if чем else ""})
        elif раздел.group(1).lower().startswith("решения"):
            итог["решения"] = css or None
    return итог


def прочитать_поиск(путь: Path | None) -> dict:
    """`поиск.md` (контракт Б) → служебная голова; нет файла — умолчания и `есть_файл: False`."""
    итог = {"заголовок": "", "описание": "", "слова": "", "карточка_текст": "",
            "карточка_картинка": "", "статус": "", "есть_файл": False}
    if путь is not None and Path(путь).is_file():
        итог["есть_файл"] = True
        for поле in ПОЛЕ.finditer(Path(путь).read_text(encoding="utf-8-sig")):
            ключ = ПОЛЯ_ПОИСКА.get(поле.group(1).strip().lower())
            if ключ:
                итог[ключ] = поле.group(2).strip()
    итог["статус"] = "открыт" if итог["статус"].lower() == "открыт" else "закрыт"
    if итог["карточка_картинка"].lower() in ПУСТО:
        итог["карточка_картинка"] = ""
    # какие смысловые поля пусты — про них спрашивают человека, а не заполняют за него
    итог["пусто"] = [имя for имя, ключ in (("Заголовок вкладки", "заголовок"),
                                            ("Описание для поиска", "описание")) if not итог[ключ]]
    итог["заголовок"] = итог["заголовок"] or ЗАГОЛОВОК_ПО_УМОЛЧАНИЮ
    return итог


def ссылка_на_шрифты(css: str) -> str:
    """Один <link> на несистемные шрифты дизайн-системы; оба системные — пустая строка:
    лишний поход в интернет на первом экране стоит человеку секунды загрузки."""
    семьи: list[tuple[str, str]] = []
    for переменная, начертания in НАЧЕРТАНИЯ.items():
        найдено = re.search(re.escape(переменная) + r"\s*:\s*([^;}\n]+)", css)
        имя = найдено.group(1).split(",")[0].strip().strip("'\"") if найдено else ""
        if имя and имя.lower() not in ресёрч_ниши.СИСТЕМНЫЕ_ШРИФТЫ and имя not in dict(семьи):
            семьи.append((имя, начертания))
    if not семьи:
        return ""
    семейства = "&".join(f"family={имя.replace(' ', '+')}:wght@{вес}" for имя, вес in семьи)
    return ('<link rel="preconnect" href="https://fonts.googleapis.com">\n'
            '<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>\n'
            f'<link rel="stylesheet" href="https://fonts.googleapis.com/css2?{семейства}&display=swap">')


def ссылка_связи(способ: str, адрес: str) -> str:
    """Способ связи из профиля + адрес → ссылка, по которой человек напишет."""
    способ, адрес = (способ or "").strip().lower(), (адрес or "").strip()
    if not адрес:
        return ""
    if способ == "телеграм" and "://" not in адрес and not адрес.lower().startswith("t.me/"):
        return "https://t.me/" + адрес.lstrip("@")
    if способ == "whatsapp" and any(з.isdigit() for з in адрес):
        # в ссылке whatsapp живут только цифры: скобки и дефисы номера её ломают
        return "https://wa.me/" + "".join(з for з in адрес if з.isdigit())
    if способ in ("почта", "телефон"):
        схема = "mailto:" if способ == "почта" else "tel:"
        return адрес if адрес.lower().startswith(схема) else схема + адрес
    if "://" in адрес or адрес.lower().startswith(("mailto:", "tel:")):
        return адрес
    return "https://" + адрес.lstrip("/")   # без схемы браузер прочтёт адрес как путь внутри сайта


def начинка_связи(текст: str, профиль: dict | None,
                  папка_профиля: Path | None) -> tuple[str, dict | None]:
    """Слот `{{СВЯЗЬ:Текст}}` → кнопка со ссылкой или код виджета из профиля. ⭐ Блок не знает,
    кнопка там или виджет: сменился способ — страница пересобирается, блоки не трогаем (ТЗ
    § 7.10-bis). Связи нет — кнопка ведёт на экран контактов, чтобы не быть мёртвой, и 🟡."""
    текст = (текст or "").strip() or "Написать"

    def запас(причина: str) -> tuple[str, dict]:
        return (f'<a class="кнопка" href="#экран-контакты">{escape(текст)}</a>',
                находка(ПОПРАВИТЬ, "Связь не задана", [причина],
                        "человек дочитает страницу и не поймёт, куда писать — "
                        "заполни «сайт.связь» в профиле"))

    if not isinstance(профиль, dict):
        return запас("профиль не прочитан: в шапке прототипа нет имени или папки профиля нет на месте")
    сайт = профиль.get("сайт")
    связь = сайт.get("связь") if isinstance(сайт, dict) else None
    связь = связь if isinstance(связь, dict) else {}
    способ = str(связь.get("способ") or "").strip().lower()
    адрес = str(связь.get("адрес") or "").strip()
    if способ == "виджет":
        файл = папка_профиля / "виджет.html" if папка_профиля else None
        код = файл.read_text(encoding="utf-8").strip() if файл and файл.is_file() else ""
        return (код, None) if код else запас(
            "способ связи «виджет», а файла «виджет.html» рядом с профилем нет")
    if not способ:
        return запас("в профиле пусто поле «сайт.связь.способ»")
    ссылка = ссылка_связи(способ, адрес)
    if not ссылка:
        return запас(f"способ связи «{способ}» есть, а адрес пуст или без единой цифры")
    return f'<a class="кнопка" href="{escape(ссылка)}">{escape(текст)}</a>', None


def найти_заглушки(html: str) -> list[str]:
    """Слоты, оставшиеся в готовой странице, — по разу каждый, в порядке появления."""
    return list(dict.fromkeys(с.group(0) for с in ПЛЕЙСХОЛДЕР.finditer(html) if с.group(1) != "ИКОНКА"))


def _подставить_связь(кусок: str, данные: dict | None,
                      папка_профиля: Path | None) -> tuple[str, dict | None]:
    беды: list[dict] = []   # только {{СВЯЗЬ:…}}; остальные слоты не трогаем, их ловит найти_заглушки

    def замена(с: re.Match) -> str:
        if с.group(1) != "СВЯЗЬ":
            return с.group(0)
        начинка, беда = начинка_связи(с.group(2) or "", данные, папка_профиля)
        if беда:
            беды.append(беда)
        return начинка

    return ПЛЕЙСХОЛДЕР.sub(замена, кусок), беды[0] if беды else None


def _якорь_контактов(тело: str) -> str:
    """Запасная кнопка ведёт на `#экран-контакты` — без такого места `проверить.py` скажет «ссылка
    в никуда». Невидимая метка встаёт перед экраном контактов, а нет его — перед последним."""
    if "#экран-контакты" not in тело or 'id="экран-контакты"' in тело:
        return тело
    места = [м.start() for м in re.finditer(r'<section[^>]*data-тип="контакты"', тело)]
    место = места[0] if места else max((м.start() for м in re.finditer("<section", тело)), default=0)
    return тело[:место] + ЯКОРЬ_КОНТАКТОВ + "\n" + тело[место:]


def собрать_страницу(каркас: str, токены_css: str, экраны: list[str],
                     поиск: dict, шрифты: str) -> str:
    """Каркас + палитра + служебная голова + экраны подряд → одна страница."""
    картинка = (поиск.get("карточка_картинка") or "").strip()
    описание = поиск.get("описание") or ""
    # без картинки карточки тег og:image убираем целиком: пустой заставил бы проверку искать файл
    страница = каркас if картинка else re.sub(
        r'^[ \t]*<meta property="og:image".*\n?', "", каркас, flags=re.M)
    if not шрифты:
        страница = страница.replace("{{ШРИФТЫ}}\n", "")
    for что, чем in (
        ("{{ЗАГОЛОВОК_ВКЛАДКИ}}", escape(поиск.get("заголовок") or ЗАГОЛОВОК_ПО_УМОЛЧАНИЮ)),
        ("{{ОПИСАНИЕ}}", escape(описание)),
        ("{{РОБОТЫ}}", "index, follow" if поиск.get("статус") == "открыт" else "noindex, nofollow"),
        ("{{КАРТОЧКА_ТЕКСТ}}", escape(поиск.get("карточка_текст") or описание)),
        ("{{КАРТОЧКА_КАРТИНКА}}", escape(картинка)), ("{{ШРИФТЫ}}", шрифты), ("{{ТОКЕНЫ}}", токены_css),
        ("{{ЭКРАНЫ}}", _якорь_контактов("\n".join(экраны))),  # последними: их слоты не под замены головы
    ):
        страница = страница.replace(что, чем)
    return страница


def _токены(дизайн: dict) -> tuple[str, list[dict]]:
    """Что подставить в <style>: решения; нет их — единственный вариант и ℹ️; иначе 🔴.
    К взятому css — сверка имён с переменными стили.css: расхождение — 🟡."""
    варианты = [в for в in дизайн.get("варианты") or [] if (в.get("css") or "").strip()]
    if (дизайн.get("решения") or "").strip():
        css, беды = дизайн["решения"].strip(), []
    elif len(варианты) == 1:
        css, беды = варианты[0]["css"].strip(), [находка(
            К_СВЕДЕНИЮ, "Взят единственный вариант",
            [f"вариант {варианты[0]['номер']} · {варианты[0]['имя'] or 'без имени'}"],
            "Раздела «Решения» в дизайн.md нет, но выбирать было не из чего.")]
    else:
        совет = ("дизайн.md нет или в нём нет css — сначала дизайн-система" if not варианты
                 else "покажи их витриной и запиши выбор в раздел «## Решения»")
        return "", [находка(ЧИНИТЬ, "В дизайн.md нет раздела Решения и вариантов больше одного",
                            [f"вариантов с палитрой: {len(варианты)} — {совет}"],
                            "страница соберётся без палитры и шрифтов — голой разметкой")]
    есть = set(ИМЯ_ПЕРЕМЕННОЙ.findall(css))
    нет = [и for и in ПЕРЕМЕННЫЕ if и not in есть]
    лишние = sorted(и for и in есть - set(ПЕРЕМЕННЫЕ) if not и.startswith("--свой-"))
    if нет or лишние:   # имена дословно (дизайн-система.md § 2): опечатка оставила бы блок без цвета молча
        беды.append(находка(
            ПОПРАВИТЬ, "Имена переменных расходятся со стили.css",
            [f"не хватает: {', '.join(нет)}"] * bool(нет) + [f"лишние: {', '.join(лишние)}"] * bool(лишние),
            "пропущенная оставит блок без цвета или кегля, лишняя не сработает нигде — "
            "сверь имена с ядро/дизайн-система.md, раздел 2"))
    return css, беды


def _профиль(работа: Path) -> tuple[dict | None, Path | None, str]:
    """Профиль по имени из шапки прототипа (контракт Д): `профили/<имя>/profile.json`; вторая
    полка — папка с тем же именем рядом с работой (переносимые заготовки, фикстуры тестов).
    Третье значение — почему профиля нет, словами для 🟡; пусто, когда он прочитан."""
    файл, имя = работа / "прототип.md", ""
    if файл.is_file():
        for прототип in проверить_прототип.разобрать(файл.read_text(encoding="utf-8-sig")):
            имя = (прототип.get("шапка") or {}).get("Профиль", "").strip()
            if имя:
                break
    if not имя:
        return None, None, "в папке работы нет прототипа с полем «Профиль» в шапке"
    if any(з in имя for з in ("/", "\\", "..")):
        return None, None, f"имя профиля «{имя}» похоже на путь — в шапке нужно имя папки"
    for папка in (профиль.ПРОФИЛИ / имя, работа.parent / имя):
        if (папка / "profile.json").is_file():
            try:
                return профиль.прочитать_json(папка / "profile.json"), папка, ""
            except профиль.ОшибкаПрофиля as ошибка:
                return None, None, f"профиль «{имя}» не читается ({папка / 'profile.json'}): {ошибка}"
    return None, None, f"папки профиля «{имя}» нет ни в «{профиль.ПРОФИЛИ}», ни рядом с работой"


def собрать(работа: Path, *, куда: Path | None = None) -> tuple[Path, list[dict]]:
    """Папка работы → собранный сайт (index.html, style.css, .nojekyll, robots.txt, img/) и находки."""
    работа = Path(работа)
    папка_сайта = Path(куда) if куда else работа / "сайт"
    токены, найденное = _токены(прочитать_дизайн(работа / "дизайн.md"))
    поиск = прочитать_поиск(работа / "поиск.md")
    if not поиск["есть_файл"] or поиск["пусто"]:
        найденное.append(находка(
            ПОПРАВИТЬ, "Служебная голова не заполнена",
            [f"нет файла «{работа / 'поиск.md'}» — взяты умолчания: заголовок "
             f"«{ЗАГОЛОВОК_ПО_УМОЛЧАНИЮ}», описания нет, сайт закрыт от поиска"] if not поиск["есть_файл"]
            else [f"в «{работа / 'поиск.md'}» пусто поле «{поле}»" for поле in поиск["пусто"]],
            "вкладка покажет «Сайт собирается», а поиск — ничего, вместо имени дела: спроси человека, "
            "каким словом его должны узнавать и что прочтут до перехода"))
    данные, папка_профиля, беда_профиля = _профиль(работа)
    сайт = (данные or {}).get("сайт")
    адрес_сайта = str(сайт.get("адрес") or "").strip() if isinstance(сайт, dict) else ""
    картинка = поиск["карточка_картинка"]
    if картинка and "://" not in картинка and адрес_сайта:   # og:image — полный адрес: относительный мессенджеры не разрешают
        поиск["карточка_картинка"] = адрес_сайта.rstrip("/") + "/" + картинка.lstrip("/")
    elif картинка and "://" not in картинка:
        найденное.append(находка(
            ПОПРАВИТЬ, "Карточка в мессенджере без адреса сайта", [f"«{картинка}» уедет относительной"],
            "мессенджер картинку по ссылке не покажет — впиши `сайт.адрес` в профиль после публикации"))
    файлы = sorted((работа / "экраны").glob("*.html"))
    if not файлы:
        найденное.append(находка(
            ЧИНИТЬ, "Нет ни одного экрана", [f"в «{работа / 'экраны'}» нет файлов NN-<тип>.html"],
            "собирать нечего — экраны делаются по одному из шаблонов ядро/блоки/"))
    экраны, про_связь = [], []
    for файл in файлы:
        кусок, беда = _подставить_связь(файл.read_text(encoding="utf-8-sig").strip(),
                                        данные, папка_профиля)
        экраны.append(кусок)
        про_связь += [беда] if беда else []
    if про_связь and беда_профиля:
        про_связь[0]["строки"] = [беда_профиля]   # точная причина вместо общей из начинка_связи
    найденное += про_связь[:1]   # одна находка на страницу: причина у всех слотов одна
    страница = собрать_страницу(КАРКАС.read_text(encoding="utf-8"), токены, экраны, поиск,
                                ссылка_на_шрифты(токены))
    остатки = найти_заглушки(страница)
    if остатки:
        найденное.append(находка(
            ЧИНИТЬ, "В странице остались заглушки", остатки,
            "чужие люди прочтут их раньше, чем ты покажешь страницу человеку, "
            "и решат, что сайт брошен"))

    папка_сайта.mkdir(parents=True, exist_ok=True)
    (папка_сайта / "index.html").write_text(страница, encoding="utf-8")
    shutil.copyfile(СТИЛИ, папка_сайта / "style.css")
    (папка_сайта / ".nojekyll").write_text("", encoding="utf-8")
    правило = "Allow: /" if поиск["статус"] == "открыт" else "Disallow: /"
    (папка_сайта / "robots.txt").write_text(f"User-agent: *\n{правило}\n", encoding="utf-8")
    if (работа / "img").is_dir():   # картинки человека — копией: на хостинг уедет только папка сайта
        shutil.copytree(работа / "img", папка_сайта / "img", dirs_exist_ok=True)
    return папка_сайта / "index.html", найденное


def _страница_показа(размеры: list[str], экран: int | None) -> str:
    """Самодостаточная страница показа: два снимка рядом, на телефоне — друг под другом."""
    что = f"экран {экран}" if экран else "страница сверху"
    когда = datetime.now(глаза.МСК).strftime("%d.%m.%Y, %H:%M")
    картинки = "\n".join(
        f'<figure class="{размер}"><figcaption>{размер.capitalize()} '
        f'{глаза.РАЗМЕРЫ[размер]["viewport"]["width"]}</figcaption>'
        f'<img src="{размер}.png" alt="{размер.capitalize()}"></figure>' for размер in размеры)
    return f"""<!DOCTYPE html>
<html lang="ru">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Как это выглядит: {escape(что)}</title>
<style>
body {{ margin: 0; padding: 24px; font-family: system-ui, sans-serif; line-height: 1.5; }}
h1 {{ font-size: 22px; margin: 0 0 4px; }}  .когда {{ color: rgb(90, 95, 102); margin: 0 0 4px; }}
.правило {{ font-weight: 600; margin: 0 0 24px; }}  .рядом {{ display: flex; flex-wrap: wrap; gap: 24px; align-items: flex-start; }}
figure {{ margin: 0; flex: 1 1 320px; }}  figure.телефон {{ flex: 0 1 390px; }}
figcaption {{ font-weight: 600; margin-bottom: 8px; }}  img {{ width: 100%; height: auto; border: 1px solid rgb(200, 200, 200); }}
</style>
</head>
<body>
<h1>Как это выглядит: {escape(что)}</h1>
<p class="когда">Снято {когда} МСК</p>
<p class="правило">{ОДОБРЕНИЕ}</p>
<div class="рядом">
{картинки}
</div>
</body>
</html>
"""


def показать(папка_сайта: Path, куда: Path, экран: int | None = None, браузер=None) -> Path:
    """Снять сайт в двух размерах — видимую область, как увидит человек, — и собрать `показ.html`.
    Свой браузер поднимаем, только если не дали чужой."""
    папка_сайта, куда = Path(папка_сайта), Path(куда)
    куда.mkdir(parents=True, exist_ok=True)
    хвост = f"#экран-{экран}" if экран else ""

    def снять(рабочий_браузер) -> None:
        with проверить.локальный_сервер(папка_сайта) as адрес:
            for размер in глаза.РАЗМЕРЫ:
                with глаза.контекст(рабочий_браузер, размер) as контекст:
                    страница = контекст.new_page()
                    страница.goto(адрес + "index.html" + хвост, wait_until="load",
                                  timeout=глаза.ТАЙМАУТ_ЗАГРУЗКИ_МС)
                    страница.wait_for_timeout(600)   # шрифтам и картинкам — встать на место
                    страница.screenshot(path=str(куда / f"{размер}.png"))

    if браузер is not None:
        снять(браузер)
    else:
        from playwright.sync_api import sync_playwright
        with sync_playwright() as playwright, глаза.запустить_браузер(playwright) as свой:
            снять(свой)
    показ = куда / "показ.html"
    показ.write_text(_страница_показа(list(глаза.РАЗМЕРЫ), экран), encoding="utf-8")
    return показ


def построить_парсер() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(description="Собрать страницу из экранов работы и показать её "
                                            "на компьютере и телефоне.")
    p.add_argument("работа", help="папка работы: сайты/<имя>")
    p.add_argument("--экран", type=int, metavar="N", help="показать сразу экран N")
    p.add_argument("--без-показа", action="store_true", help="только собрать, экраны не снимать")
    p.add_argument("--куда", metavar="ПАПКА", help="куда класть сайт (по умолчанию <работа>/сайт)")
    return p


def main_с_аргументами(argv) -> int:
    аргументы = построить_парсер().parse_args(argv)
    работа = Path(аргументы.работа).expanduser().resolve()   # относительный путь ронял as_uri()
    if not работа.is_dir():
        print(f"Не нашёл папку работы «{аргументы.работа}». Нужна папка сайта целиком "
              "(сайты/<имя>), а не файл внутри неё.")
        return 2
    индекс, найденное = собрать(работа, куда=Path(аргументы.куда) if аргументы.куда else None)
    print(f"# Сборка: {работа.name}\n\nСтраница: {индекс}")
    print("\n".join(строки_по_уровням(найденное, заголовки_уровней("показа"))))
    if аргументы.без_показа:
        return код_выхода(найденное)
    if есть_красное(найденное):
        print("\nПоказывать пока рано: сначала красное выше.")
        return код_выхода(найденное)
    показ = показать(индекс.parent, работа / "показ", экран=аргументы.экран)
    print(f"\nПоказал оба вида: {показ}, {показ.parent / 'компьютер.png'}, "
          f"{показ.parent / 'телефон.png'}. Спроси человека: «Так? Правим или дальше?»")
    webbrowser.open(показ.as_uri())
    return 0


def main() -> int:
    вывод_в_utf8()
    return main_с_аргументами(sys.argv[1:])


if __name__ == "__main__":
    sys.exit(main())
