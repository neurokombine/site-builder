"""Общий дом находок: уровней ровно три, четвёртого не заводим — 🔴 чинить, 🟡 поправить,
ℹ️ к сведению. Здесь же форма находки, отчёт по уровням, код выхода и кодировка вывода.

Зачем. `проверить.py`, `проверить_прототип.py`, `selftest.py` и `ресёрч_ниши.py` заводили
эти константы и функции каждый у себя — четыре места вместо одного, и правка рисковала
забыть одно из них. Отсюда и имя: не «находка про сайт» и не «находка про прототип» —
находка вообще, форма одна на всю систему, а зовущий скрипт добавляет своё («до показа»
или «до вёрстки») только в заголовок уровня.
"""
from __future__ import annotations

import sys

ЧИНИТЬ = "🔴"       # чинить, прежде чем показывать
ПОПРАВИТЬ = "🟡"    # стоит поправить
К_СВЕДЕНИЮ = "ℹ️"   # к сведению; четвёртого уровня в системе нет
УРОВНИ = (ЧИНИТЬ, ПОПРАВИТЬ, К_СВЕДЕНИЮ)


def заголовки_уровней(чинить_до: str = "показа") -> dict[str, str]:
    """Подписи трёх уровней. «Чинить до …» — своё для каждого скрипта: сайт чинят до показа,
    прототип — до вёрстки."""
    return {
        ЧИНИТЬ: f"Чинить до {чинить_до}",
        ПОПРАВИТЬ: "Стоит поправить",
        К_СВЕДЕНИЮ: "К сведению",
    }


def находка(уровень: str, что: str, строки: list[str], чем_грозит: str = "") -> dict:
    """Одна находка: что не так → чем грозит → перечень мест."""
    return {"уровень": уровень, "что": что, "чем_грозит": чем_грозит, "строки": строки}


def есть_красное(находки: list[dict]) -> bool:
    """Хотя бы одна находка уровня 🔴 — значит, показывать ещё рано."""
    return any(н["уровень"] == ЧИНИТЬ for н in находки)


def код_выхода(находки: list[dict]) -> int:
    """1 при 🔴 — чтобы провал был виден по коду возврата, а не только текстом. Иначе 0."""
    return 1 if есть_красное(находки) else 0


def строки_по_уровням(находки: list[dict], заголовки: dict[str, str]) -> list[str]:
    """Отчёт по трём уровням подряд — раньше жило в `проверить.собрать_отчёт`, текст строк
    не менялся ни на символ."""
    строки: list[str] = []
    for уровень in УРОВНИ:
        свои = [н for н in находки if н["уровень"] == уровень]
        строки += ["", f"## {уровень} {заголовки[уровень]} — {len(свои)}"]
        if not свои:
            строки += ["", "Ничего не нашлось."]
            continue
        for н in свои:
            строки += ["", f"### {н['что']}"]
            if н.get("чем_грозит"):
                # «чем грозит» — про 🔴 и 🟡; к сведению ничем не грозит, там просто пояснение
                строки.append(н["чем_грозит"] if уровень == К_СВЕДЕНИЮ
                              else f"Чем грозит: {н['чем_грозит']}.")
            строки += [f"- {с}" for с in н["строки"]]
    return строки


def вывод_в_utf8() -> None:
    """Эмодзи 🔴🟡ℹ️ в перенаправленном выводе не должны ронять запуск на Windows.

    Там `sys.stdout` в трубе берёт кодировку системы (cp1251), а не UTF-8, и `print("🔴")`
    падает с `UnicodeEncodeError` раньше, чем человек увидит хоть строку. Все скрипты курса
    запускают команды именно с перехваченным выводом.
    """
    for поток in (sys.stdout, sys.stderr):
        if hasattr(поток, "reconfigure"):
            поток.reconfigure(encoding="utf-8", errors="replace")


# ── Что считаем карточкой ─────────────────────────────────────────────────────────────────
#
# Один словарь на систему: его читают и `проверить.py` (фон карточек в ритме страницы), и
# `однородность.py` (скругления и тени карточек по всей странице). Раньше список жил у каждого
# свой, и они разошлись: одна проверка не видела отзыв, другая — работу. Здесь он один.
#
# Первый класс ищется корнем-подстрокой (в разметке он пишется по-разному: `карточка`,
# `карточки`, `карточка--светлая`), остальные — точным классом. Прозрачные попутчики вроде
# `.карточки` (обёртка сетки) и `.карточка__имя` (строка текста) отсеиваются уже в браузере:
# у карточки есть заливка, кромка или тень, у обёртки нет ничего.
КАРТОЧКИ = ("карточка", "тариф", "плитка", "врезка", "модуль", "работа", "отзыв", "отзыв-заглушка")
КАРТОЧКИ_СЕЛЕКТОР = ", ".join([f'[class*="{КАРТОЧКИ[0][:-1]}"]'] + [f".{класс}" for класс in КАРТОЧКИ[1:]])

# Виды карточек — семьи, а не классы: `отзыв-заглушка` это тот же отзыв, только без живого текста.
# Система нарочно раздаёт видам разные скругления (`--радиус-карточки`, `--радиус-плитки`,
# `--радиус-модуля`), поэтому сравнивать их между собой нельзя — только внутри вида.
ВИДЫ_КАРТОЧЕК = tuple(к for к in КАРТОЧКИ if not any(к.startswith(д + "-") for д in КАРТОЧКИ))
