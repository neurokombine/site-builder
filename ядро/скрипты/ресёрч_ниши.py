def название_вида(вид) -> str:
    """Как назвать вид «не пустило» человеку — с нашими двумя видами поверх видов `глаза.py`."""
    return НАЗВАНИЯ_ВИДОВ.get(вид, вид or "неизвестная беда")


def подсказка_по_виду(вид: str) -> str:
    """Что делать человеку — ход везде один (CLAUDE.md § 7): снять экран самому."""
    return ПОДСКАЗКИ.get(вид, глаза.подсказка_по_виду(вид))


def видимый_текст(замеры: dict) -> str:
    """Весь текст страницы, который доехал до `замеры.json`, одной строкой в нижнем регистре.

    Это заголовок вкладки и самый крупный видимый текст — по каждому снятому размеру.
    """
    куски: list[str] = []
    for устройство in (замеры.get("устройства") or {}).values():
        if not isinstance(устройство, dict):
            continue
        куски.append(str(устройство.get("заголовок_вкладки") or ""))
        крупный = устройство.get("самый_крупный_текст") or {}
        if isinstance(крупный, dict):
            куски.append(str(крупный.get("текст") or ""))
    return " ".join(куски).lower()


def маркер_проверки_на_роботов(замеры: dict) -> str | None:
    """Первое слово стены, найденное в тексте снятой страницы, — или None."""
    текст = видимый_текст(замеры)
    for маркер in МАРКЕРЫ_ПРОВЕРКИ_НА_РОБОТОВ:
        if маркер in текст:
            return маркер
    return None


def _признак_не_пустило(значение) -> str:
    """Чем именно `глаза.py` объяснил «не пустило» — словом маркера или текстом ошибки."""
    return str(значение.get("признак") or "") if isinstance(значение, dict) else ""


def разметить_не_пустило(замеры: dict) -> tuple[str | None, str | None]:
    """(статус, вид) снятого сайта — с поправкой на проверку на роботов и на 403.

    Две поправки к вердикту `глаза.py`, обе — про «не мешать вранью попасть в сводку»:
    стена, которой тот не знал, делает сайт неснятым; 403, который он назвал стеной,
    получает своё имя и свой совет.
    """
    итог = замеры.get("итог") or {}
    статус = итог.get("статус")
    вид = _вид_не_пустило(итог.get("не_пустило"))
    if маркер_проверки_на_роботов(замеры):
        return "не_пустило", ВИД_СТЕНЫ
    if вид == ВИД_СТЕНЫ:
        признак = _признак_не_пустило(итог.get("не_пустило")).lower()
        if any(м in признак for м in МАРКЕРЫ_ДОСТУПА):
            return статус, ВИД_ДОСТУПА
    return статус, вид


