# Отбор секций — обход сверху вниз от `<body>`.
#
# Почему не по тегам. Живой прогон по пяти сайтам ниши дал 1, 1, 1, 2 секции на страницу:
# конструкторы (и половина самописных страниц) не размечают экраны ни `section`, ни `main` —
# у них `body > div#allrecords > div#recNNN`, и поиск по тегам находит одну обёртку всей
# страницы. Поэтому ищем не тег, а РОВНЮ: уровень вложенности, на котором лежат подряд
# несколько крупных полос во всю ширину, — это и есть экраны, чем бы они ни были размечены.
#
# Шаг обхода: берём детей уровня (без служебных тегов), крупными считаем тех, кто выше
# 240 px и шире 80 % окна. Крупных трое и больше — похоже на уровень экранов. Меньше —
# значит мы всё ещё в обёртке: спускаемся в самого высокого ребёнка. Глубже десяти уровней
# не лезем: там уже не экраны, а внутренности карточек. Десять, а не шесть, — у конструктора
# до экранов бывает пять вложенных обёрток подряд, и запас нужен.
#
# ⚠️ «Трое крупных» — ещё не ровня. У семантической страницы на уровне `body` их ровно трое:
# высокий `header`, `main` со всеми экранами внутри и `footer`, — и остановка тут делает весь
# `main` одной секцией. Поэтому перед остановкой смотрим на самого высокого: НАБИТ ЛИ ОН САМ
# крупными полосами. Крупных детей у него больше, чем крупных на уровне, — это обёртка (у
# `main` их пять против трёх на `body`), спускаемся в неё. Не больше — остаёмся: значит это
# просто длинный экран.
#
# ⚠️ Длинный экран — обычное дело, и меряться высотой тут нельзя. Первая версия правила
# спускалась в того, кто забрал больше 60 % высоты, и на живом сайте провалилась внутрь
# программы курса: она занимала 68 % страницы, а экранов рядом было шесть. Считаем детей, а
# не пиксели: у длинной секции внутри одна обёртка `div.wrap` — один крупный против шести.
