def яркость(hex_цвет: str) -> float:
    """0..255 по формуле 0,299R + 0,587G + 0,114B; тёмный фон — меньше 96."""
    строка = (hex_цвет or "").lstrip("#")
    if len(строка) != 6:
        return 255.0  # цвет неизвестен — не называем сайт тёмным на пустом месте
    r, g, b = (int(строка[i:i + 2], 16) for i in (0, 2, 4))
    return 0.299 * r + 0.587 * g + 0.114 * b


def воздух_словами(доля: float) -> str:
    """Доля воздуха на первом экране — плотно, средне или просторно."""
    if доля < ГРАНИЦА_ПЛОТНО:
        return "плотно"
    if доля > ГРАНИЦА_ПРОСТОРНО:
        return "просторно"
    return "средне"


def _вид_не_пустило(значение):
    """«Не пустило» приходит по-разному: словарём с ключом «вид» из глаза.py или готовым
    словом. Приводим к одному виду — просто строке с названием вида (или None)."""
    if not значение:
        return None
    if isinstance(значение, dict):
        return значение.get("вид")
    return значение


def _кегль(устройство: dict):
    return ((устройство.get("кегли") or {}).get("текст") or {}).get("px")


def _имя_шрифта(имя) -> str:
    """Имя шрифта к сравнимому виду: без кавычек и лишних пробелов, в нижнем регистре."""
    return (имя or "").strip().strip("\"'").strip().lower()


def _свой_шрифт(устройство: dict) -> bool:
    """Загрузился ли на сайте свой шрифт — то есть не системный.

    Сначала имя: Arial, Georgia, Roboto, system-ui есть на устройстве и так, и «своими» они
    не становятся, даже когда браузер честно доложил «шрифт применился, не запасной».
    `запасной_ли` в списке `шрифты` говорит про запись в CSS (общее семейство вроде
    `sans-serif` или конкретное название), а не про то, скачал сайт шрифт или взял готовый.

    Имя несистемное — тогда смотрим список `шрифты`: подставился запасной — значит свой
    шрифт не доехал. Списка нет — верим имени.
    """
    имя = _имя_шрифта(устройство.get("шрифт_текста"))
    if not имя or имя in СИСТЕМНЫЕ_ШРИФТЫ:
        return False
    for запись in устройство.get("шрифты") or []:
        if _имя_шрифта(запись.get("применён")) == имя:
            return not запись.get("запасной_ли", False)
    return True


def _без_засечек(имя: str | None) -> tuple[str | None, str | None]:
    """Засечная гарнитура донора → ближайший гротеск + строка находки; не засечная — как была.

    Правило владелицы без исключений: засечных не берём никогда, даже одним из донорских
    сайтов ниши — иначе антиква доедет до сводки, а из сводки — в профиль человека."""
    if имя and гарнитуры.засечная(имя):
        замена = гарнитуры.ближайший_гротеск(имя)
        return замена, f"«{имя}» — с засечками, у себя не берём: показываем «{замена}»"
    return имя, None


def собрать_черты(замеры: dict) -> dict:
    """Один сайт — сырые замеры в компактный набор черт для сравнения по нише.

    Телефон — главное устройство (правило «телефон — первая версия»): по нему берём воздух,
    тёмный первый экран, заголовок и всю адаптивность. Шрифт и кегль текста — с компьютера:
    там типографика видна как задумана, без сжатия под маленький экран; кегль телефона
    сохраняем отдельно — он нужен для сравнения в таблице.
    """
    устройства = замеры.get("устройства") or {}
    телефон = устройства.get("телефон") or {}
    компьютер = устройства.get("компьютер") or {}
    итог = замеры.get("итог") or {}

    цвета = телефон.get("цвета_текста") or компьютер.get("цвета_текста") or []
    крупный = телефон.get("самый_крупный_текст") or компьютер.get("самый_крупный_текст") or {}
    заголовок_текст = (крупный.get("текст") or "").strip()
    слов = len(заголовок_текст.split()) if заголовок_текст else None

    воздух_данные = телефон.get("воздух") or компьютер.get("воздух") or {}
    доля_воздуха = воздух_данные.get("доля")

    главный_шрифт = компьютер if компьютер.get("шрифт_текста") else телефон

    # Телефон мог не открыться сам по себе, пока компьютер снялся нормально (кейс
    # «только_компьютер» — глаза.py считает такой сайт снятым в целом). Тогда адаптивность
    # телефона — не «нет проблем», а «не измерено»: None, а не тихий False.
    телефон_ок = телефон.get("статус") == "ок"

    # Задача 5: вердикт «пустило или нет» — не тот, что записан в замерах, а с поправкой на
    # проверку на роботов и на 403 (см. `разметить_не_пустило`). Иначе белая заглушка антибота
    # доезжает до сводки полноправным сайтом и перекашивает «у всех / ни у кого».
    статус_сайта, вид_беды = разметить_не_пустило(замеры)

    # Правило владелицы: засечных гарнитур не берём никогда, даже когда донор набран одной из
    # них. Показываем в сводке гротеск, а не тащим антикву к человеку молча — «свой_шрифт_загружен»
    # ниже мерит донора настоящим, до подмены: это про то, доехал ли ЕГО шрифт, а не про наш выбор.
    сырой_заголовков = компьютер.get("шрифт_заголовков") or телефон.get("шрифт_заголовков")
    сырой_текста = компьютер.get("шрифт_текста") or телефон.get("шрифт_текста")
    шрифт_заголовков, замена_заголовков = _без_засечек(сырой_заголовков)
    шрифт_текста, замена_текста = _без_засечек(сырой_текста)

    return {
        "адрес": замеры.get("адрес"),
        "статус": статус_сайта,
        "не_пустило": вид_беды,
        "шрифт_заголовков": шрифт_заголовков,
        "шрифт_текста": шрифт_текста,
        "замены_шрифтов": [з for з in (замена_заголовков, замена_текста) if з],
        "свой_шрифт_загружен": _свой_шрифт(главный_шрифт),
        "кегль_текста_компьютер": _кегль(компьютер),
        "кегль_текста_телефон": _кегль(телефон),
        "воздух": доля_воздуха,
        "воздух_словами": воздух_словами(доля_воздуха) if доля_воздуха is not None else None,
        "тёмный_первый_экран": (
            яркость(воздух_данные.get("фон_скриншота_hex")) < ТЁМНЫЙ_ПОРОГ
            if воздух_данные.get("фон_скриншота_hex") else False
        ),
        "цвет_текста": цвета[0]["hex"] if цвета else None,
        "телефон_ок": телефон_ок,
        "мелкий_текст_на_телефоне": (
            bool((телефон.get("мелкий_текст") or {}).get("элементов_мельче_14")) if телефон_ок else None
        ),
        "прокрутка_вбок_на_телефоне": (
            bool((телефон.get("прокрутка_вбок") or {}).get("есть")) if телефон_ок else None
        ),
        "картинки_вылезают_на_телефоне": (
            bool(телефон.get("вылезающие_картинки")) if телефон_ок else None
        ),
        "заголовок_первого_экрана": заголовок_текст or None,
        "короткий_заголовок": слов is not None and слов <= 6,
        "заголовок_вкладки": компьютер.get("заголовок_вкладки") or телефон.get("заголовок_вкладки"),
    }


def сводка_ниши(черты: list[dict], не_открылись: list[dict] | None = None) -> dict:
    """Что есть у всех сайтов, чего нет ни у кого, где по-разному — по чертам из собрать_черты.

    Признаки (булевы) и шрифты/воздух (по совпадению значений) считаются только когда снятых
    сайтов минимум два — на одном сайте нет с чем сравнивать. Кегль текста — диапазоном
    («16–18 px»), если у сайтов он разный, и одним числом, если у всех совпал.

    `не_открылись` — сайты, на которых браузер упал раньше, чем успел записать замеры.json
    (сеть, таймаут открытия и т. п.): `[{"адрес": ..., "причина": ...}]`. Это отдельная беда от
    «не пустило» (там браузер сайт открыл, просто не увидел контента) — сюда их не мешаем.
    """
    снятые = [ч for ч in черты if ч.get("статус") == "ок"]
    не_снятые = [ч for ч in черты if ч.get("статус") != "ок"]
    не_пустило = [{"адрес": ч.get("адрес"), "вид": ч.get("не_пустило")} for ч in не_снятые]

    # Засечка донора называется вслух независимо от того, набралось ли двух сайтов для «у всех/
    # по-разному»: на одном-единственном сайте подмену тоже молчать нельзя.
    замены_шрифтов = [
        f"{ч.get('адрес')} — {сообщение}"
        for ч in снятые for сообщение in (ч.get("замены_шрифтов") or [])
    ]

    у_всех: list[str] = []
    ни_у_кого: list[str] = []
    у_большинства: list[str] = []
    по_разному: list[str] = []

    if len(снятые) >= 2:
        всего = len(снятые)

        def булево(метка, значения):
            # Признак телефона может быть None у сайта, где сам телефон не открылся (кейс
            # «только_компьютер») — такой сайт не участвует ни в счёте, ни в знаменателе:
            # без него так же нечестно писать «ни у кого», как и «у всех».
            измеренные = [в for в in значения if в is not None]
            if len(измеренные) < 2:
                return
            всего_измеренных = len(измеренные)
            истинно = sum(1 for в in измеренные if в)
            if истинно == всего_измеренных:
                у_всех.append(метка)
            elif истинно == 0:
                ни_у_кого.append(метка)
            elif истинно / всего_измеренных >= ДОЛЯ_БОЛЬШИНСТВА:
                у_большинства.append(метка)
            else:
                по_разному.append(метка)

        def по_значению(метка, значения):
            непустые = [в for в in значения if в]
            if not непустые:
                return
            самое, сколько = Counter(непустые).most_common(1)[0]
            строка = f"{метка}: {самое}"
            if сколько == всего:
                у_всех.append(строка)
            elif сколько / всего >= ДОЛЯ_БОЛЬШИНСТВА:
                у_большинства.append(строка)
            else:
                по_разному.append(строка)

        for ключ, метка in ПРИЗНАКИ:
            булево(метка, [ч.get(ключ) for ч in снятые])

        по_значению("шрифт заголовков", [ч.get("шрифт_заголовков") for ч in снятые])
        по_значению("шрифт текста", [ч.get("шрифт_текста") for ч in снятые])
        по_значению("воздух", [ч.get("воздух_словами") for ч in снятые])

        кегли = [ч.get("кегль_текста_телефон") for ч in снятые if ч.get("кегль_текста_телефон") is not None]
        if кегли:
            низ, верх = min(кегли), max(кегли)
            if низ == верх:
                у_всех.append(f"кегль текста: {низ} px")
            else:
                по_разному.append(f"кегль текста: {низ}–{верх} px")

    return {
        "сайтов": len(снятые),
        "не_пустило": не_пустило,
        "не_открылись": list(не_открылись or []),
        "у_всех": у_всех,
        "ни_у_кого": ни_у_кого,
        "у_большинства": у_большинства,
        "по_разному": по_разному,
        "снятые": снятые,
        "замены_шрифтов": замены_шрифтов,
    }


def _таблица(снятые: list[dict]) -> list[str]:
    строки = [
        "| Адрес | Шрифты (заголовки / текст) | Кегль текста (к / т) | Воздух | Тёмный | Телефон |",
        "|---|---|---|---|---|---|",
    ]
    for ч in снятые:
        шрифты = f"{ч.get('шрифт_заголовков') or '—'} / {ч.get('шрифт_текста') or '—'}"
        кк = ч.get("кегль_текста_компьютер")
        кт = ч.get("кегль_текста_телефон")
        кегль = f"{кк if кк is not None else '—'} / {кт if кт is not None else '—'}"
        воздух = ч.get("воздух_словами") or "—"
        тёмный = "да" if ч.get("тёмный_первый_экран") else "нет"
        if ч.get("телефон_ок") is False:
            телефон = "не измерено"
        else:
            флаги = []
            if ч.get("мелкий_текст_на_телефоне"):
                флаги.append("мелкий текст")
            if ч.get("прокрутка_вбок_на_телефоне"):
                флаги.append("прокрутка вбок")
            if ч.get("картинки_вылезают_на_телефоне"):
                флаги.append("картинки вылезают")
            телефон = ", ".join(флаги) or "без замечаний"
        строки.append(f"| {ч.get('адрес')} | {шрифты} | {кегль} | {воздух} | {тёмный} | {телефон} |")
    return строки


def сводка_словами(сводка: dict) -> str:
    """Сводку по нише — простыми словами: таблица по сайтам и четыре списка совпадений."""
    сайтов = сводка.get("сайтов", 0)
    снятые = сводка.get("снятые") or []
    не_пустило = сводка.get("не_пустило") or []
    не_открылись = сводка.get("не_открылись") or []
    передано = сайтов + len(не_пустило) + len(не_открылись)
    строки = [
        "# Сводка по нише", "",
        f"Сайтов передано: {передано} · открылось: {сайтов} · "
        f"не пустило: {len(не_пустило)} · не открылись: {len(не_открылись)}",
        "",
    ]

    if снятые:
        строки.append("## Сайты")
        строки.append("")
        строки += _таблица(снятые)
        строки.append("")

    def раздел(заголовок, пункты):
        if not пункты:
            return
        строки.append(f"## {заголовок}")
        строки.append("")
        строки.extend(f"- {п}" for п in пункты)
        строки.append("")

    раздел("Есть у всех", сводка.get("у_всех"))
    раздел("Нет ни у кого", сводка.get("ни_у_кого"))
    раздел("У большинства", сводка.get("у_большинства"))
    раздел("По-разному", сводка.get("по_разному"))

    замены_шрифтов = сводка.get("замены_шрифтов") or []
    if замены_шрифтов:
        строки.append("## ℹ️ Гарнитуры доноров без засечек")
        строки.append("")
        строки.append("Засечных гарнитур в системе не берём никогда — даже когда так набран донор.")
        строки.extend(f"- {з}" for з in замены_шрифтов)
        строки.append("")

    if не_пустило:
        строки.append("## Не пустило")
        строки.append("")
        for з in не_пустило:
            вид = з.get("вид")
            строки.append(f"- {з.get('адрес')} — {название_вида(вид)}.")
            if вид:
                строки.append(f"  {подсказка_по_виду(вид)}")
        строки.append("")

    if не_открылись:
        строки.append("## Не открылись")
        строки.append("")
        for з in не_открылись:
            строки.append(
                f"- {з.get('адрес')} — {з.get('причина') or 'причина неизвестна'}. "
                "Попросите человека сделать снимок экрана самому и показать его системе."
            )
        строки.append("")

    if сайтов < 2:
        строки.append(
            "Открылось меньше двух сайтов — мало сайтов, чтобы говорить «у всех» или "
            "«ни у кого». Добавьте ещё ссылок и повторите."
        )
        строки.append("")

    строки.append(ПАТТЕРН_НЕ_ПРИГОВОР)
    return "\n".join(строки)


def прочитать_замеры(папка_референсов: Path) -> list[dict]:
    """Все уже снятые сайты в папке референсов — по файлам `<слаг>/замеры.json`."""
    папка_референсов = Path(папка_референсов)
    результат = []
    for файл in sorted(папка_референсов.glob("*/замеры.json")):
        try:
            результат.append(json.loads(файл.read_text(encoding="utf-8")))
        except (OSError, json.JSONDecodeError) as ошибка:
            print(f"⚠️ Не прочитал {файл}: {ошибка}", file=sys.stderr)
    return результат


def записать_сводку(папка_референсов: Path, сводка: dict) -> tuple[Path, Path]:
    """Кладёт `_сводка.md` и `_сводка.json` рядом с папками сайтов; дата — московская."""
    папка_референсов = Path(папка_референсов)
    папка_референсов.mkdir(parents=True, exist_ok=True)
    дата = datetime.now(глаза.МСК).strftime("%d.%m.%Y %H:%M МСК")
    путь_md = папка_референсов / "_сводка.md"
    путь_json = папка_референсов / "_сводка.json"
    путь_md.write_text(f"Собрано: {дата}\n\n{сводка_словами(сводка)}", encoding="utf-8")
    путь_json.write_text(json.dumps(сводка, ensure_ascii=False, indent=2), encoding="utf-8")
    return путь_md, путь_json


def _уникальный_слаг(адрес: str, занятые: dict) -> str:
    """Слаг из адреса — и разводим повтор, если у двух ссылок он совпал.

    `глаза.слаг_из` берёт имя папки, в которой лежит файл: для сайта из папки с index.html
    это имя самого сайта, а для двух учебных страниц-соседей вроде `лендинг.html` и
    `стена.html` (лежат прямо в одной папке фикстур) слаг выходит одинаковым — «фикстуры».
    В `посмотреть_сайт.py` это не беда: там всегда один сайт за запуск. Здесь сайтов
    несколько за один проход, и без разводки второй затирал бы папку первого.
    """
    слаг = глаза.слаг_из(адрес)
    занятые[слаг] = занятые.get(слаг, 0) + 1
    if занятые[слаг] == 1:
        return слаг
    return f"{слаг}-{занятые[слаг]}"


def main_с_аргументами(argv) -> int:
    разбор = argparse.ArgumentParser(
        description="Несколько чужих сайтов одной ниши за один проход браузера: "
                     "экраны и замеры по каждому плюс сводка — что есть у всех, чего нет "
                     "ни у кого, где по-разному.")
    разбор.add_argument("ссылки", nargs="*", help="ссылки на чужие сайты одной ниши")
    разбор.add_argument("--работа", required=True, help="папка работы, например сайты/моё-дело")
    разбор.add_argument("--только-сводка", action="store_true",
                        help="пересобрать сводку из уже снятых папок — без браузера")
    аргументы = разбор.parse_args(argv)

    if аргументы.только_сводка and аргументы.ссылки:
        print("⚠️ С флагом --только-сводка ссылки не открываются: пересобираю сводку "
              "из уже снятых папок.")

    папка_референсов = Path(аргументы.работа) / "референсы"
    не_открылись: list[dict] = []  # сайты, где браузер упал раньше, чем записал замеры.json

    if not аргументы.только_сводка:
        if not аргументы.ссылки:
            print("\n⛔ Нужна хотя бы одна ссылка на сайт — или флаг --только-сводка.\n")
            return 1
        try:
            from playwright.sync_api import sync_playwright
        except Exception as ошибка:
            print(f"\n⛔ Не удалось запустить браузер: {type(ошибка).__name__}: {ошибка}")
            print("   Проверьте установку: .venv/bin/python ядро/скрипты/selftest.py")
            print("   Что делать дальше — в ЕСЛИ-СЛОМАЛОСЬ.md.\n")
            return 1

        всего = len(аргументы.ссылки)
        занятые_слаги: dict = {}
        try:
            with sync_playwright() as движок:
                браузер = глаза.запустить_браузер(движок)
                try:
                    for номер, ссылка in enumerate(аргументы.ссылки, start=1):
                        try:
                            адрес = глаза.адрес_из(ссылка)
                        except ValueError as ошибка:
                            print(f"⛔ {ссылка}: {ошибка}")
                            continue
                        слаг = _уникальный_слаг(адрес, занятые_слаги)
                        print(f"Смотрю {номер} из {всего}: {адрес}")
                        try:
                            замеры = глаза.посмотреть(
                                адрес, папка_референсов / слаг, браузер=браузер)
                        except Exception as ошибка:
                            причина = f"{type(ошибка).__name__}: {ошибка}"
                            print(f"   ⛔ Сайт не открылся: {причина}")
                            не_открылись.append({"адрес": адрес, "причина": причина})
                            continue
                        # Задача 5: вид беды — по нашей разметке, а не по вердикту замеров:
                        # стену, которой `глаза.py` не знает, человек должен услышать сразу,
                        # а не увидеть в сводке лишним сайтом «без замечаний».
                        _, не_пустило = разметить_не_пустило(замеры)
                        if не_пустило:
                            print(f"   Не пустило: {название_вида(не_пустило)}")
                            print(f"   {подсказка_по_виду(не_пустило)}")
                finally:
                    браузер.close()
        except Exception as ошибка:
            print(f"\n⛔ Не удалось запустить браузер: {type(ошибка).__name__}: {ошибка}")
            print("   Проверьте установку: .venv/bin/python ядро/скрипты/selftest.py")
            print("   Что делать дальше — в ЕСЛИ-СЛОМАЛОСЬ.md.\n")
            return 1

    все_замеры = прочитать_замеры(папка_референсов)
    if not все_замеры:
        print(f"\n⛔ В папке «{папка_референсов}» пока ничего не снято — нечего сводить.\n")
        return 1

    черты = [собрать_черты(з) for з in все_замеры]
    сводка = сводка_ниши(черты, не_открылись=не_открылись)
    путь_md, путь_json = записать_сводку(папка_референсов, сводка)

    print()
    print(сводка_словами(сводка))
    print()
    print("Файлы:")
    print(f"   {путь_md}")
    print(f"   {путь_json}")
    print(f"\n{посмотреть_сайт.НАПОМИНАНИЕ}\n")

    return 0 if сводка["сайтов"] > 0 else 2


def main() -> int:
    вывод_в_utf8()
    return main_с_аргументами(sys.argv[1:])


if __name__ == "__main__":
    sys.exit(main())
