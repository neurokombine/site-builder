def направления(работа: Path, экраны: str | None = None, браузер=None) -> tuple[Path, list[dict]]:
    """Папка работы → `показ/направления.html` и по собранной странице на каждое направление."""
    работа = Path(работа)
    корень = работа / "показ" / "направления"
    итог = работа / "показ" / "направления.html"
    номера = номера_экранов(экраны)
    найденное: list[dict] = []
    папки = папки_направлений(работа)
    if not папки:
        найденное.append(находка(
            ЧИНИТЬ, "Нет направлений", [f"в «{работа / 'направления'}» нет папок 1, 2, 3"],
            "сравнивать нечего: положи в каждую `направление.md` (имя, идея, откуда, детали) и "
            "два экрана по Контракту В — как это делается, написано в `ядро/вёрстка.md`"))
    elif len(папки) < 2:
        найденное.append(находка(
            ЧИНИТЬ, "Направление всего одно", [f"папок в «{работа / 'направления'}»: {len(папки)}"],
            "из одного не выбирают — его принимают молча. Нужно два-три: два от галереи и "
            "референсов работы, одно от разведки ниши"))
    elif len(папки) > СКОЛЬКО_ЖДЁМ:
        найденное.append(находка(
            К_СВЕДЕНИЮ, "Направлений больше трёх", [f"их {len(папки)}"],
            "Из трёх человек выбирает уверенно; из пяти — устаёт и берёт первое попавшееся."))
    if есть_красное(найденное):
        return итог, найденное

    # Профиль кладём рядом с временными работами: собранная страница ищет его по соседству с
    # папкой работы, а временная лежит глубоко внутри показа.
    _, папка_профиля, _ = собрать._профиль(работа)
    корень.mkdir(parents=True, exist_ok=True)
    if папка_профиля and папка_профиля.is_dir() and not (корень / папка_профиля.name).exists():
        shutil.copytree(папка_профиля, корень / папка_профиля.name)

    собранные, снимать = [], []
    for папка in папки:
        куда = корень / папка.name
        взятые = _разложить(работа, папка, куда, номера)
        сведения = прочитать_направление(папка / "направление.md")
        if not взятые:
            найденное.append(находка(
                ЧИНИТЬ, "У направления нет экранов", [f"в «{папка / 'экраны'}» пусто"],
                "направление — это два свёрстанных экрана на текстах работы, а не одно описание"))
            continue
        if not сведения["имя"]:
            найденное.append(находка(
                ПОПРАВИТЬ, "У направления нет имени", [f"в «{папка / 'направление.md'}» нет «- Имя:»"],
                "по имени человек его и назовёт, когда будет выбирать"))
        _, про_сборку = собрать.собрать(куда)
        for н in про_сборку:
            if н["уровень"] != ЧИНИТЬ:
                continue
            # Профиль у трёх направлений один, значит и вердикт о его комплекте один: сборка
            # зовётся трижды и каждый раз возвращает его заново, а трижды повторённая строка
            # читается как три разные беды — человек пойдёт искать несуществующие две.
            if н["что"] == профиль.СЛОВА_НЕУКОМПЛЕКТОВАН and any(
                    с["что"] == профиль.СЛОВА_НЕУКОМПЛЕКТОВАН for с in найденное):
                continue
            найденное.append(н)
        собранные.append({**сведения, "номер": папка.name})
        снимать.append(куда)
    # Гейт смотрит на красное, которое мешает СНЯТЬ пробу: сломанный экран, нечитаемый рецепт.
    # Неукомплектованная палитра профиля — красное про другое: страница собралась, тёмные тона
    # взяты из «Решений» работы, и снимок покажет ровно то, что человек увидит. Раньше этот вердикт
    # гасил съёмку целиком, и бедный профиль оставлял человека без единой пробы — то есть система
    # закрывала ровно тот случай, ради которого бедный профиль и заводят. Теперь он печатается
    # рядом с пробами, а не вместо них.
    мешает_снимать = [н for н in найденное
                      if н["уровень"] == ЧИНИТЬ and н["что"] != профиль.СЛОВА_НЕУКОМПЛЕКТОВАН]
    if мешает_снимать:
        return итог, найденное

    if браузер is not None:
        _снять(снимать, браузер)
    else:
        from playwright.sync_api import sync_playwright
        with sync_playwright() as playwright, глаза.запустить_браузер(playwright) as свой:
            _снять(снимать, свой)
    итог.write_text(_страница_направлений(работа.name, собранные), encoding="utf-8")
    return итог, найденное


def записать_решение(файл: Path, строка: str) -> None:
    """Строка решения — внутрь `## Решения`, до палитры: там её ищет человек и читает сборка."""
    if not файл.is_file():
        файл.write_text(f"## Решения\n{строка}\n", encoding="utf-8")
        return
    текст = файл.read_text(encoding="utf-8")
    место = текст.find("## Решения")
    if место < 0:
        файл.write_text(текст.rstrip("\n") + f"\n\n## Решения\n{строка}\n", encoding="utf-8")
        return
    начало = текст.find("\n", место) + 1
    ограда = текст.find("```", начало)
    конец = ограда if ограда >= 0 else len(текст)
    файл.write_text(текст[:начало] + текст[начало:конец].rstrip("\n") + f"\n{строка}\n\n"
                    + текст[конец:], encoding="utf-8")


def взять(работа: Path, номер: str, экраны: str | None = None) -> tuple[list[Path], list[str]]:
    """Экраны выбранного направления — в `экраны/` работы; решение — в `дизайн.md`.

    Экран с тем же номером уступает место и об этом говорится вслух — и когда имя файла другое,
    и когда то же самое: молча переписанная работа возвращается вопросом «а где мой экран» через
    неделю, а одноимённый файл как раз самый частый случай."""
    работа = Path(работа)
    папка = работа / "направления" / str(номер)
    исходные = экраны_направления(папка, номера_экранов(экраны))
    if not папка.is_dir() or not исходные:
        raise НетНаправления(f"в «{работа / 'направления'}» нет направления «{номер}» с экранами")
    куда = работа / "экраны"
    куда.mkdir(parents=True, exist_ok=True)
    взятые, предупреждения = [], []
    for файл in исходные:
        совпало = НОМЕР_ФАЙЛА.match(файл.name)
        for прежний in sorted(куда.glob(f"{совпало.group(1)}-*.html")) if совпало else []:
            if прежний.name == файл.name:
                предупреждения.append(f"экран «{файл.name}» перезаписан экраном направления")
                continue                       # перезапишет `copyfile` ниже, удалять не нужно
            предупреждения.append(f"экран «{прежний.name}» уступил место «{файл.name}»")
            прежний.unlink()
        shutil.copyfile(файл, куда / файл.name)
        взятые.append(куда / файл.name)
    имя = прочитать_направление(папка / "направление.md")["имя"] or "без имени"
    когда = datetime.now(глаза.МСК).strftime("%d.%m.%Y %H:%M")
    записать_решение(работа / "дизайн.md", f"- Направление: {номер} — {имя} ({когда} МСК)")
    return взятые, предупреждения


def построить_парсер() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(
        description="Три направления вёрстки на текстах работы — рядом, на компьютере и телефоне.")
    p.add_argument("--работа", required=True, help="папка работы: сайты/<имя>")
    p.add_argument("--экраны", help="какие экраны собирать, например 02,04 (по умолчанию все, что лежат)")
    p.add_argument("--взять", metavar="N", help="перенести экраны направления N в экраны/ работы")
    p.add_argument("--без-показа", action="store_true", help="собрать, браузер с показом не открывать")
    return p


def main_с_аргументами(argv) -> int:
    аргументы = построить_парсер().parse_args(argv)
    работа = Path(аргументы.работа).expanduser().resolve()   # относительный путь ронял as_uri()
    if not работа.is_dir():
        print(f"Не нашёл папку работы «{аргументы.работа}». Нужна папка сайта целиком "
              "(сайты/<имя>), а не файл внутри неё.")
        return 2
    if аргументы.взять:
        try:
            взятые, предупреждения = взять(работа, аргументы.взять, аргументы.экраны)
        except НетНаправления as беда:
            print(беда)
            return 1
        for строка in предупреждения:
            print(f"⚠️  {строка}")
        print("Взято направление " + аргументы.взять + ": "
              + ", ".join(п.name for п in взятые))
        print(f"Решение записано в «{работа / 'дизайн.md'}» → «## Решения». Дальше — по экрану за раз: "
              "`ядро/вёрстка.md`, раздел «Один экран за раз».")
        return 0
    путь, найденное = направления(работа, аргументы.экраны)
    print(f"# Направления: {работа.name}")
    print("\n".join(строки_по_уровням(найденное, заголовки_уровней("показа"))))
    # Тот же гейт, что у сборки (`собрать.py`, «Показывать пока рано»): красное про палитру
    # профиля пробы не ломает — они собрались, тёмные тона взяты из «Решений» работы, и снимки
    # покажут ровно то, что увидит человек. `направления()` этот вердикт уже пропустило мимо
    # своего гейта и сняло пробы; спрашивать здесь нефильтрованное «есть_красное» значило
    # прятать готовый файл и выходить кодом 1 ровно в том случае, ради которого бедный профиль
    # и заводят — вердикт напечатан выше и никуда не денется.
    мешает_показу = [н for н in найденное
                     if н["уровень"] == ЧИНИТЬ and н["что"] != профиль.СЛОВА_НЕУКОМПЛЕКТОВАН]
    if мешает_показу:
        print("\nПоказ пока не собираю: сначала красное выше.")
        return код_выхода(найденное)
    print(f"\nТри направления {'собраны' if аргументы.без_показа else 'открыты'}: {путь}. {ПРАВИЛО}.")
    print(ЧТО_ДАЛЬШЕ)
    if not аргументы.без_показа:
        webbrowser.open(путь.as_uri())
    return 0


