def номер_экрана(html: str) -> str:
    """Номер экрана двумя цифрами: сперва по контракту, потом по `id` — чтобы даже сбитый заголовок
    секции не оставил находку без адреса."""
    по_контракту = СЕКЦИЯ_В.match(html.lstrip())
    if по_контракту:
        return по_контракту.group(4)
    по_идентификатору = НОМЕР_ЭКРАНА.search(html)
    return по_идентификатору.group(1) if по_идентификатору else "?"


def _класс_типа(класс: str) -> bool:
    """`блок--<тип>` — класс типа экрана; сам `блок` им не считается."""
    return класс.startswith("блок--") and len(класс) > len("блок--")


def почему_не_по_контракту(тег: str) -> list[str]:
    """Чем открывающий тег секции разошёлся с образцом Контракта В — словами, а не «не сходится»."""
    беды: list[str] = []
    найден = КЛАСС_СЕКЦИИ.search(тег)
    классы = (найден.group(1) if найден else "").split()
    типовые = [к for к in классы if _класс_типа(к)]
    тип_класса = типовые[0][len("блок--"):] if типовые else ""
    if "блок" not in классы or not тип_класса:
        беды.append("в классах нет пары «блок блок--<тип>»")
    elif len(типовые) > 1:
        беды.append("классов «блок--…» больше одного: " + ", ".join(f"`{к}`" for к in типовые)
                    + " — громкость и отделку экран задаёт своим стилем, а не вторым классом")
    if not any(к in РОЛИ_КЛЮЧА for к in классы):
        беды.append("нет роли ключа: " + " · ".join(f"`{р}`" for р in РОЛИ_КЛЮЧА))
    лишние = [к for к in классы
              if к != "блок" and not _класс_типа(к) and к not in РОЛИ_КЛЮЧА and к not in ФАКТУРЫ]
    if лишние:
        беды.append("лишние классы: " + ", ".join(f"`{к}`" for к in лишние)
                    + " — раскладка живёт в стиле экрана, а не в классах секции")
    ид = ИД_СЕКЦИИ.search(тег)
    if not ид or not ИД_ЭКРАНА_ДВЕ_ЦИФРЫ.match(ид.group(1)):
        беды.append("`id` должен быть `экран-NN` двумя цифрами, а стоит "
                    + (f"«{ид.group(1)}»" if ид else "ничего"))
    тип = ТИП_СЕКЦИИ.search(тег)
    if not тип:
        беды.append("нет `data-тип`")
    elif тип_класса and тип.group(1) != тип_класса:
        беды.append(f"тип в классе «{тип_класса}» и в `data-тип` «{тип.group(1)}» разные")
    if not беды:
        беды.append("порядок или написание атрибутов не как в образце "
                    "(`ядро/вёрстка.md`, раздел «Контракт В»)")
    return беды


def правила_стиля(css: str) -> list[tuple[str, str]]:
    """Стиль экрана → пары «селектор, тело правила», с заходом внутрь `@media` и его родни.

    Внутрь `@keyframes` и `@font-face` не заходим: там слева от `{` стоят не селекторы, и
    требовать от них префикса экрана было бы выдуманной находкой."""
    итог: list[tuple[str, str]] = []
    заголовок: list[str] = []
    место = 0
    while место < len(css):
        знак = css[место]
        if знак != "{":
            заголовок.append(знак)
            место += 1
            continue
        имя = "".join(заголовок).strip()
        заголовок = []
        конец = _закрывающая(css, место)
        нутро = css[место + 1:конец]
        if имя.startswith("@"):
            if имя.split()[0] in ВЛОЖЕННЫЕ_ПРАВИЛА:
                итог += правила_стиля(нутро)
        elif имя:
            итог.append((имя, нутро))
        место = конец + 1
    return итог


def _закрывающая(css: str, начало: int) -> int:
    глубина = 0
    for место in range(начало, len(css)):
        if css[место] == "{":
            глубина += 1
        elif css[место] == "}":
            глубина -= 1
            if глубина == 0:
                return место
    return len(css)


def имена_токенов(значение: str) -> tuple[list[str], str]:
    """Имена из всех `var(…)` значения и то, что осталось вне них.

    Остаток — это и есть «вписано своё»: у `0 10px 30px var(--тень)` он не пуст. Запасное
    значение внутри `var(--имя, …)` разрешено и в остаток не идёт."""
    имена: list[str] = []
    остаток: list[str] = []
    место = 0
    while место < len(значение):
        начало = значение.find("var(", место)
        if начало < 0:
            остаток.append(значение[место:])
            break
        остаток.append(значение[место:начало])
        глубина, конец = 0, len(значение) - 1
        for шаг in range(начало + 3, len(значение)):
            if значение[шаг] == "(":
                глубина += 1
            elif значение[шаг] == ")":
                глубина -= 1
                if глубина == 0:
                    конец = шаг
                    break
        внутри = значение[начало + 4:конец]
        имена.append(внутри.split(",")[0].strip())
        запас = внутри.split(",", 1)[1] if "," in внутри else ""
        if "var(" in запас:
            вложенные, _ = имена_токенов(запас)
            имена += вложенные
        место = конец + 1
    return имена, "".join(остаток)


def _проверить_токен(свойство: str, значение: str, где: str, места: dict[str, list[str]]) -> None:
    """Кегль, скругление и тень — только объявленным токеном профиля, и токеном своего рода."""
    слово = КЛЮЧИ_ТОКЕНА[свойство]
    голое = значение.strip()
    if голое.lower() in ЗНАЧЕНИЕ_БЕЗ_ТОКЕНА:
        return
    имена, остаток = имена_токенов(голое)
    каталог = токены_профиля()
    беда = ""
    if not имена or остаток.strip(" \t\n,"):
        беда = "своё значение вместо токена"
    else:
        for имя in имена:
            if каталог and имя not in каталог:
                беда = f"токена `{имя}` в профиле нет"
                break
            if слово not in имя:
                беда = f"`{имя}` — это не {слово}"
                break
    if беда:
        места.setdefault("токены", []).append(f"{где}: «{свойство}: {голое}» — {беда}")


def места_контракта(экран: str, номер: str, места: dict[str, list[str]]) -> None:
    """Один экран по Контракту В → места нарушений, сложенные по ключу находки.

    Копит в общий словарь: находка на странице одна, а мест в ней столько, сколько нашлось.
    На вход идёт файл экрана целиком, со всеми `<style>`: «стилей больше одного» и «стиль не
    сразу после секции» видно только по исходному тексту."""
    где = f"экран {номер}"
    голый = экран.lstrip()
    тег = ОТКРЫВАЮЩИЙ_ТЕГ.match(голый)
    по_контракту = СЕКЦИЯ_В.match(голый)
    if not по_контракту:
        места.setdefault("первая_строка", []).extend(
            f"{где}: {беда}" for беда in почему_не_по_контракту(тег.group(0) if тег else голый))

    блоки = СТИЛЬ_ЭКРАНА.findall(экран)
    if len(блоки) > 1:
        места.setdefault("лишний_стиль", []).append(
            f"{где}: блоков <style> {len(блоки)}, а должен быть один — сразу за `<section>`")
    первый = голый.find("<style>")
    if первый >= 0 and тег and голый[тег.end():первый].strip():
        места.setdefault("стиль_не_сразу", []).append(
            f"{где}: между первой строкой и `<style>` есть разметка")

    стиль_экрана = СТИЛЬ_ЭКРАНА.search(экран)
    стиль = КОММЕНТАРИЙ_CSS.sub("", стиль_экрана.group(1)) if стиль_экрана else ""
    тело = (экран[:стиль_экрана.start()] + экран[стиль_экрана.end():]) if стиль_экрана else экран

    for селектор, нутро in правила_стиля(стиль):
        # Номер надёжен только когда первая строка сошлась с контрактом: иначе мы сами не знаем,
        # каким `#экран-NN` правило обязано начинаться, и промолчать честнее.
        if по_контракту:
            for один in селектор.split(","):
                один = один.strip()
                if один and not один.startswith(f"#экран-{номер}"):
                    места.setdefault("префикс", []).append(f"{где}: правило «{один}»")
        for свойство, значение in ОБЪЯВЛЕНИЕ.findall(нутро):
            значение = значение.strip()
            if свойство == "font-family":
                места.setdefault("шрифт", []).append(f"{где}: «{свойство}: {значение}»")
            if свойство in КЛЮЧИ_ТОКЕНА:
                _проверить_токен(свойство, значение, где, места)
    for цвет in dict.fromkeys(м.group(0) for м in ЦВЕТ_ЧИСЛОМ.finditer(стиль)):
        места.setdefault("цвет", []).append(f"{где}: «{цвет}»")

    связи = СЛОТ_СВЯЗИ.findall(тело)
    if len(связи) > 1:
        места.setdefault("связи", []).append(f"{где}: связей {len(связи)} — " + ", ".join(связи))
    голое = ОБЁРТКА_КАРТИНКИ.sub("", ЗАГЛУШКА_КАРТИНКИ.sub("", тело))
    for тег_картинки in dict.fromkeys(м.group(1) for м in КАРТИНКА_ЭКРАНА.finditer(голое)):
        места.setdefault("картинка", []).append(
            f"{где}: <{тег_картинки}> вне figure.фото | мокап | аватар")


def находки_контракта_в(места: dict[str, list[str]]) -> list[dict]:
    """Собранные места → находки в одном и том же порядке, какой бы экран их ни принёс."""
    return [находка(уровень, что, места[ключ], чем_грозит)
            for ключ, уровень, что, чем_грозит in КОНТРАКТ_В if места.get(ключ)]


def находки_по_контракту_в(папка_сайта: Path | None) -> list[dict]:
    """Экраны работы рядом с собранной папкой — по Контракту В. Обложка сюда не попадает:
    у неё нет `data-вёрстка="своя"`, она собрана по рецепту и проверяется своими мерками."""
    if not папка_сайта:
        return []
    папка = Path(папка_сайта).parent / "экраны"
    if not папка.is_dir():
        return []
    места: dict[str, list[str]] = {}
    for файл in sorted(папка.glob("*.html")):
        текст = файл.read_text(encoding="utf-8-sig")
        if СВОЯ_ВЁРСТКА not in текст:
            continue
        места_контракта(текст, номер_экрана(текст), места)
    return находки_контракта_в(места)


# ── Профиль сайта не укомплектован (задача 11) ────────────────────────────────────────────
#
# `флаги_дизайна.находки_по_палитре` (задача 13) ловит РЕЗУЛЬТАТ: мало разных цветов доехало
# до `:root` уже собранной страницы — симптом. Эта проверка смотрит в ПРИЧИНУ: в сам профиль,
# из которого сайт собирали, — не задали ли человеку вопрос про цвет, который нельзя вывести
# самим (`профиль.добрать_палитру`). Находки не дублируются: эта молчит, если профиль найти
# не вышло (не у каждого сайта в проверке есть прототип рядом), и молчит, если палитра
# укомплектована, даже если результат ловит что-то ещё (тень, кнопки — не про цвета).

def _профиль_сайта(папка_сайта: Path | None) -> tuple[dict | None, str]:
    """profile.json, из которого собран этот сайт, — по шапке `- Профиль:` прототипа рядом с
    папкой «сайт» (контракт Д, тот же приём, что `собрать._профиль`, без кросс-импорта — он сам
    импортирует этот модуль). Профиля не нашли — молча (None, ""): не у каждой проверяемой папки
    есть прототип по соседству (пример — фикстуры проверить.py, эталон-прототипа и т. п.)."""
    if not папка_сайта:
        return None, ""
    работа = Path(папка_сайта).parent
    файл_прототипа = работа / "прототип.md"
    if not файл_прототипа.is_file():
        return None, ""
    try:
        прототипы = проверить_прототип.разобрать(файл_прототипа.read_text(encoding="utf-8-sig"))
    except Exception:
        return None, ""
    имя = ""
    for п in прототипы:
        имя = (п.get("шапка") or {}).get("Профиль", "").strip()
        if имя:
            break
    if not имя or any(з in имя for з in ("/", "\\", "..")):
        return None, имя
    for папка_профиля in (профиль.ПРОФИЛИ / имя, работа.parent / имя):
        файл = папка_профиля / "profile.json"
        if файл.is_file():
            try:
                return профиль.прочитать_json(файл), имя
            except профиль.ОшибкаПрофиля:
                return None, имя
    return None, имя


def находки_по_комплекту_профиля(папка: Path | None) -> list[dict]:
    """Задача 11: до показа спрашиваем то, что нельзя вывести самим, — не собираем молча.

    Слова вердикта живут в `профиль.находки_по_комплекту` (задача 4 отчуждаемости): тот же
    текст говорят теперь и `проверить_прототип.py`, `витрина.py`, `обложки.py`, `собрать.py` —
    на шаге, где цвет ещё дёшево вписать, а не на последнем.
    """
    данные, имя = _профиль_сайта(папка)
    return профиль.находки_по_комплекту(данные, имя)


def собрать_находки(замеры: dict, разметка: dict, папка: Path | None) -> list[dict]:
    """Всё, что мы умеем находить, — одним списком в порядке разговора с человеком."""
    находки: list[dict] = []
    устройства = замеры.get("устройства", {})
    компьютер = устройства.get("компьютер", {})
    телефон = устройства.get("телефон", {})

    for имя, устройство in устройства.items():
        if устройство.get("статус") != "ок":
            беда = устройство.get("не_пустило") or {}
            находки.append(находка(
                ЧИНИТЬ, f"Страница не открылась ({имя})",
                [f"{глаза.НАЗВАНИЯ_ВИДОВ.get(беда.get('вид'), беда.get('вид', 'ошибка'))}: "
                 f"{беда.get('признак')}"],
                "мерить нечего, пока страница не открывается"))

    if разметка.get("не_разобралось"):
        находки.append(находка(ЧИНИТЬ, "Разметку прочитать не вышло",
                               [разметка["не_разобралось"]],
                               "ссылки, заглушки и контраст остались непроверенными"))
        return находки

    заглушки = найти_заглушки(разметка.get("текст", ""), разметка.get("заголовок", ""))
    if заглушки:
        находки.append(находка(ЧИНИТЬ, "Забытые заглушки", заглушки,
                               "человек прочтёт их раньше вас и решит, что сайт брошен"))

    метки = найти_метки(f"{разметка.get('заголовок', '')}\n{разметка.get('текст', '')}")
    if метки:
        находки.append(находка(
            ЧИНИТЬ, "В тексте остались метки прототипа", метки,
            "«[проверить]» и «[пример]» — ваши пометки себе, а не текст сайта: человек прочтёт их "
            "как недоделанную страницу. Сверьте помеченное с жизнью, уберите скобки в прототипе и "
            "пересоберите сайт"))

    прокрутка = телефон.get("прокрутка_вбок") or {}
    if прокрутка.get("есть"):
        находки.append(находка(
            ЧИНИТЬ, "На телефоне страница ездит вбок",
            [f"ширина страницы {прокрутка.get('ширина_страницы')} px при экране "
             f"{прокрутка.get('ширина_экрана')} px"],
            "текст уезжает за край, и его читают, дёргая страницу пальцем"))

    вылезают = телефон.get("вылезающие_картинки") or []
    if вылезают:
        находки.append(находка(
            ЧИНИТЬ, "На телефоне картинки вылезают за экран",
            [f"{к.get('тег')} шириной {к.get('ширина')} px — «{(к.get('адрес') or '')[:60]}»"
             for к in вылезают],
            "картинка обрезана краем экрана: видно половину"))

    ссылки = разметка.get("ссылки") or []
    вес_html = 0
    if папка is not None and (папка / "index.html").is_file():
        вес_html = (папка / "index.html").stat().st_size
    находки += находки_по_весу(ссылки, папка, вес_html)
    находки += находки_по_ссылкам(ссылки, разметка.get("якоря") or [], папка)

    мелкий = телефон.get("мелкий_текст") or {}
    сколько_мелкого = мелкий.get("элементов_мельче_14") or 0
    if сколько_мелкого:
        находки.append(находка(
            ПОПРАВИТЬ, "На телефоне есть текст мельче 14 px",
            [f"таких мест: {сколько_мелкого}, самый мелкий — {мелкий.get('минимум_px')} px"],
            "мелкий текст на телефоне не читают, а пролистывают"))

    # Снимок всей страницы — последнее слово по контрасту: разметку он перебивает, а не дополняет.
    экран = экран_страницы(замеры, разметка)
    находки += находки_по_контрасту(разметка.get("контраст") or [], экран)
    находки += находки_по_кнопкам(разметка.get("кнопки") or [], экран)
    находки += находки_по_тёплому(разметка.get("тёплый") or [], экран)
    находки += находки_по_ритму(разметка.get("секции") or [])

    заголовок = (разметка.get("заголовок") or "").strip()
    if not заголовок or заголовок.lower() in ПУСТЫЕ_ЗАГОЛОВКИ:
        находки.append(находка(
            ПОПРАВИТЬ, "Заголовок вкладки пустой или дежурный",
            [f"сейчас: «{заголовок}»" if заголовок else "заголовка нет вовсе"],
            "это имя сайта в закладке, в поиске и в пересланной ссылке — "
            "спросите человека, каким словом его должны узнавать"))

    if not (разметка.get("язык") or "").strip():
        находки.append(находка(
            ПОПРАВИТЬ, "У страницы не указан язык",
            ["в теге <html> нет атрибута lang"],
            "браузер предложит перевести русскую страницу, а голосовой чтец прочтёт её "
            "с чужим акцентом"))

    if not (разметка.get("описание") or "").strip():
        находки.append(находка(
            К_СВЕДЕНИЮ, "Нет описания для поиска",
            ["meta description пустой"],
            "Описание для поиска — напишем перед запуском, вместе с человеком."))

    закрыт = "noindex" in (разметка.get("роботы") or "").lower()
    находки.append(находка(
        К_СВЕДЕНИЮ, "Сайт закрыт от поиска" if закрыт else "Сайт открыт поиску",
        ["так и задумано, пока собираем" if закрыт
         else "поисковики могут его найти — если сайт ещё собирается, закройте его до запуска"]))

    if компьютер.get("предупреждение"):
        находки.append(находка(К_СВЕДЕНИЮ, "Пометка при замере", [компьютер["предупреждение"]]))
    находки += флаги_дизайна.флаги(разметка, замеры, папка)
    находки += находки_по_контракту_в(папка)
    находки += находки_по_комплекту_профиля(папка)
    return находки


# ── Сравнение с референсом ───────────────────────────────────────────────────────────────

def _кегль(устройство: dict, тег: str) -> str:
    значение = (устройство.get("кегли") or {}).get(тег)
    return f"{значение['px']} px" if значение else "—"


def _воздух(устройство: dict) -> str:
    доля = (устройство.get("воздух") or {}).get("доля")
    return f"{глаза.процент(доля)} %" if доля is not None else "—"


def _заметных_цветов(устройство: dict) -> str:
    цвета = устройство.get("цвета_текста") or []
    заметные = [ц for ц in цвета if ц.get("доля", 0) > 5]
    return str(len(заметные)) if цвета else "—"


def _минимальный_кегль(устройство: dict) -> str:
    минимум = (устройство.get("мелкий_текст") or {}).get("минимум_px")
    return f"{round(минимум)} px" if минимум else "—"


def _пара(замеры: dict, как: str) -> str:
    """Одно число в двух размерах: «48 px / 32 px»."""
    устройства = замеры.get("устройства", {})
    компьютер = устройства.get("компьютер", {})
    телефон = устройства.get("телефон", {})
    if как == "h1":
        return f"{_кегль(компьютер, 'h1')} / {_кегль(телефон, 'h1')}"
    if как == "текст":
        return f"{_кегль(компьютер, 'текст')} / {_кегль(телефон, 'текст')}"
    return f"{_воздух(компьютер)} / {_воздух(телефон)}"


def строки_сравнения(наши: dict, референс: dict) -> list[str]:
    """Таблица «ваш сайт | референс»: не чтобы сделать одинаково, а чтобы увидеть разницу."""
    def устройство(замеры, имя):
        return (замеры.get("устройства") or {}).get(имя, {})

    ряды = [
        ("Шрифт заголовков",
         устройство(наши, "компьютер").get("шрифт_заголовков") or "—",
         устройство(референс, "компьютер").get("шрифт_заголовков") or "—"),
        ("Шрифт текста",
         устройство(наши, "компьютер").get("шрифт_текста") or "—",
         устройство(референс, "компьютер").get("шрифт_текста") or "—"),
        ("Кегль h1 (компьютер / телефон)", _пара(наши, "h1"), _пара(референс, "h1")),
        ("Кегль текста (компьютер / телефон)", _пара(наши, "текст"), _пара(референс, "текст")),
        ("Воздух (компьютер / телефон)", _пара(наши, "воздух"), _пара(референс, "воздух")),
        ("Заметных цветов текста",
         _заметных_цветов(устройство(наши, "компьютер")),
         _заметных_цветов(устройство(референс, "компьютер"))),
        ("Самый мелкий текст на телефоне",
         _минимальный_кегль(устройство(наши, "телефон")),
         _минимальный_кегль(устройство(референс, "телефон"))),
    ]
    строки = ["| Что | Ваш сайт | Референс |", "|---|---|---|"]
    строки += [f"| {что} | {наше} | {чужое} |" for что, наше, чужое in ряды]
    строки += ["", ПОДПИСЬ_РЕФЕРЕНСА]
    return строки


def прочитать_референс(путь: Path) -> dict:
    """`замеры.json` чужого сайта — рядом с нашими числами. Можно указать и папку с ним."""
    файл = путь / "замеры.json" if путь.is_dir() else путь
    return json.loads(файл.read_text(encoding="utf-8"))


# ── Отчёт ────────────────────────────────────────────────────────────────────────────────

def собрать_отчёт(что_проверяли: str, замеры: dict, находки: list[dict],
                  сравнение: list[str] | None, экраны: list[str], заметки: list[str]) -> str:
    """Один и тот же текст — и в консоль, и в `отчёт.md`."""
    строки = ["# Проверка сайта", "", f"Сайт: {что_проверяли}"]
    if замеры.get("снято"):
        строки.append(f"Снято: {замеры['снято']}")
    строки.append("Отдавали локальным сервером — так пути и шрифты ведут себя как на хостинге."
                  if что_проверяли and not что_проверяли.startswith("http")
                  else "Смотрели по живому адресу.")
    for заметка in заметки:
        строки.append(заметка)

    строки += строки_по_уровням(находки, ЗАГОЛОВКИ_УРОВНЕЙ)

    строки += ["", "## Числа по двум размерам"]
    for размер, устройство in (замеры.get("устройства") or {}).items():
        строки += ["", f"### {размер.capitalize()} — {глаза.состояние_словами(устройство)}", ""]
        строки += глаза.описать_размер(устройство)

    if сравнение:
        строки += ["", "## Ваш сайт и референс", ""] + сравнение

    строки += ["", "## Экраны", ""]
    строки += [f"- {путь}" for путь in экраны] or ["- экраны снять не удалось"]
    строки += ["", ПОСЛЕДНЕЕ_СЛОВО,
               "Числа считает скрипт, вкус оценивает нейросеть по скриншоту, "
               "последнее слово — за человеком.", ""]
    return "\n".join(строки)


# ── Работа целиком ───────────────────────────────────────────────────────────────────────

def снять(адрес: str, куда: Path, браузер, ждать_сек: float) -> tuple[dict, dict]:
    """Замеры двух размеров плюс разбор разметки. Браузер можно передать свой."""
    if браузер is None:
        from playwright.sync_api import sync_playwright

        with sync_playwright() as движок:
            свой = глаза.запустить_браузер(движок)
            try:
                return снять(адрес, куда, свой, ждать_сек)
            finally:
                свой.close()
    замеры = глаза.посмотреть(адрес, куда, ждать_сек=ждать_сек, браузер=браузер)
    разметка = снять_разметку(браузер, адрес)
    разметка["дизайн"] = флаги_дизайна.снять_дизайн(браузер, адрес)
    return замеры, разметка


def проверить(папка: Path | None, куда: Path, *, адрес: str | None = None, браузер=None,
              ждать_сек: float = 3.5, референс: Path | None = None) -> dict:
    """Проверить сайт целиком: замерить, найти, сравнить, написать отчёт. Возвращает находки."""
    куда = Path(куда)
    куда.mkdir(parents=True, exist_ok=True)
    что_проверяли = str(папка) if папка is not None else (адрес or "")
    заметки: list[str] = []

    if папка is not None:
        with локальный_сервер(папка) as служебный_адрес:
            замеры, разметка = снять(служебный_адрес, куда, браузер, ждать_сек)
        замеры["адрес"] = что_проверяли  # в файлах пусть будет путь, а не служебный порт
    else:
        замеры, разметка = снять(адрес or "", куда, браузер, ждать_сек)
        заметки.append("Сайт по живому адресу: вес файлов не считаем — их нет под рукой.")

    находки = собрать_находки(замеры, разметка, папка)

    сравнение = None
    if референс is not None:
        try:
            сравнение = строки_сравнения(замеры, прочитать_референс(Path(референс)))
        except Exception as ошибка:
            заметки.append(f"Референс не прочитался ({type(ошибка).__name__}) — "
                           "сравнение пропускаю, остальное проверил.")

    экраны = [str(п) for у in (замеры.get("устройства") or {}).values()
              for п in (у.get("скриншоты") or {}).values() if str(п).endswith(".png")]
    отчёт = собрать_отчёт(что_проверяли, замеры, находки, сравнение, экраны, заметки)

    (куда / "замеры.json").write_text(
        json.dumps(замеры, ensure_ascii=False, indent=2), encoding="utf-8")
    (куда / "замеры.md").write_text(глаза.сводка(замеры), encoding="utf-8")
    (куда / "отчёт.md").write_text(отчёт, encoding="utf-8")
    return {"находки": находки, "замеры": замеры, "разметка": разметка,
            "отчёт": отчёт, "куда": куда}


def найти_сайты() -> list[Path]:
    """Собранные сайты в системе: `сайты/<имя>/сайт/index.html`."""
    полка = КОРЕНЬ / "сайты"
    if not полка.exists():
        return []
    return sorted(и.parent for и in полка.glob("*/сайт/index.html"))


def куда_класть(папка: Path) -> Path:
    """Куда сложить экраны, замеры и отчёт — и это никогда не внутрь проверяемой папки.

    ⛔ Раньше папку с чужим именем проверка обживала изнутри: `<папка>/проверка/`. Но эту
    папку целиком выкладывают на живой адрес — вместе со скриншотами и `отчёт.md`, где
    списком перечислено всё красное. Показывать людям список собственных недоделок незачем.

    Своя папка сайта называется `сайт` — тогда кладём по-соседски, `<родитель>/проверка/`.
    Любое другое имя (человек назвал папку как захотел или дал путь со стороны) — на общую
    полку `сайты/_проверка/<имя>/`, ту же, куда ложится проверка сайта по ссылке.
    """
    папка = Path(папка)
    if папка.name == "сайт":
        return папка.parent / "проверка"
    return КОРЕНЬ / "сайты" / "_проверка" / слаг_папки(папка)


def слаг_папки(папка: Path) -> str:
    """Имя на полке по пути к папке: `сайты/моё-дело/лендинг` → `моё-дело-лендинг`.

    Берём две последние части пути, а не одну: папок «лендинг» в разных работах бывает две,
    и отчёт по второй не должен молча затирать отчёт по первой.
    """
    путь = Path(папка).resolve()
    части = [путь.name]
    if путь.parent != путь.parent.parent:   # не сам корень диска
        части.insert(0, путь.parent.name)
    return глаза.слаг("-".join(ч for ч in части if ч))


def похоже_на_адрес(строка: str) -> bool:
    """Того, что назвали, нет на диске. Это адрес в интернете — или опечатка в пути к папке?

    Адресом считаем только явное: со схемой (`https://…`) или голый домен без косых черт
    (`пример.рф`). Всё остальное — путь, в котором человек ошибся буквой. Уйти по нему в
    интернет значит написать «страница не открылась» там, где надо сказать «нет такой папки»:
    человек пойдёт чинить сайт, а чинить надо было имя папки.
    """
    строка = строка.strip()
    if строка.startswith(("http://", "https://")):
        return True
    if "/" in строка or "\\" in строка:
        return False
    if строка.lower().endswith((".html", ".htm")):
        return False   # страница, которую не нашли на диске, — не домен
    имя, точка, зона = строка.rpartition(".")
    return bool(имя and зона.isalpha() and len(зона) >= 2)


def сказать_что_нет_папки(что_набрали: str) -> int:
    """Нет такой папки — покажем, какие есть, и в интернет не пойдём."""
    print(f"\n⛔ Нет такой папки: {что_набрали}")
    сайты = найти_сайты()
    if сайты:
        print("   Вот что есть:\n")
        for с in сайты:
            print(f"   {с.relative_to(КОРЕНЬ).as_posix()}")
    else:
        print("   Собранных сайтов пока нет — их папки появятся в сайты/<имя>/сайт/.")
    print("\n   Если это был адрес в интернете, напишите его целиком, с https://.\n")
    return 2


def сказать_не_папка_сайта(что_набрали: str) -> int:
    """На диске есть — но это не собранный сайт: файл или папка без index.html. В сеть не идём."""
    print("\n⛔ Это не папка сайта: жду папку, в которой лежит index.html.")
    print(f"   Дали: {что_набрали}\n")
    return 2


