# ── Отчёт ────────────────────────────────────────────────────────────────────────────────

def собрать_отчёт(что_проверяли: str, замеры: dict, находки: list[dict],
                  сравнение: list[str] | None, экраны: list[str], заметки: list[str]) -> str:
    """Один и тот же текст — и в консоль, и в `отчёт.md`."""
    строки = ["# Проверка сайта", "", f"Сайт: {что_проверяли}"]
    if замеры.get("снято"):
        строки.append(f"Снято: {замеры['снято']}")
    строки.append("Отдавали локальным сервером — так пути и шрифты ведут себя как на хостинге."
                  if что_проверяли and not что_проверяли.startswith("http")
                  else "Смотрели по живому адресу.")
    for заметка in заметки:
        строки.append(заметка)

    for уровень in (ЧИНИТЬ, ПОПРАВИТЬ, К_СВЕДЕНИЮ):
        свои = [н for н in находки if н["уровень"] == уровень]
        строки += ["", f"## {уровень} {ЗАГОЛОВКИ_УРОВНЕЙ[уровень]} — {len(свои)}"]
        if not свои:
            строки += ["", "Ничего не нашлось."]
            continue
        for н in свои:
            строки += ["", f"### {н['что']}"]
            if н.get("чем_грозит"):
                # «чем грозит» — про 🔴 и 🟡; к сведению ничем не грозит, там просто пояснение
                строки.append(н["чем_грозит"] if уровень == К_СВЕДЕНИЮ
                              else f"Чем грозит: {н['чем_грозит']}.")
            строки += [f"- {с}" for с in н["строки"]]

    строки += ["", "## Числа по двум размерам"]
    for размер, устройство in (замеры.get("устройства") or {}).items():
        строки += ["", f"### {размер.capitalize()} — {глаза.состояние_словами(устройство)}", ""]
        строки += глаза.описать_размер(устройство)

    if сравнение:
        строки += ["", "## Ваш сайт и референс", ""] + сравнение

    строки += ["", "## Экраны", ""]
    строки += [f"- {путь}" for путь in экраны] or ["- экраны снять не удалось"]
    строки += ["", ПОСЛЕДНЕЕ_СЛОВО,
               "Числа считает скрипт, вкус оценивает нейросеть по скриншоту, "
               "последнее слово — за человеком.", ""]
    return "\n".join(строки)


# ── Работа целиком ───────────────────────────────────────────────────────────────────────

def снять(адрес: str, куда: Path, браузер, ждать_сек: float) -> tuple[dict, dict]:
    """Замеры двух размеров плюс разбор разметки. Браузер можно передать свой."""
    if браузер is None:
        from playwright.sync_api import sync_playwright

        with sync_playwright() as движок:
            свой = глаза.запустить_браузер(движок)
            try:
                return снять(адрес, куда, свой, ждать_сек)
            finally:
                свой.close()
    замеры = глаза.посмотреть(адрес, куда, ждать_сек=ждать_сек, браузер=браузер)
    return замеры, снять_разметку(браузер, адрес)


def проверить(папка: Path | None, куда: Path, *, адрес: str | None = None, браузер=None,
              ждать_сек: float = 3.5, референс: Path | None = None) -> dict:
    """Проверить сайт целиком: замерить, найти, сравнить, написать отчёт. Возвращает находки."""
    куда = Path(куда)
    куда.mkdir(parents=True, exist_ok=True)
    что_проверяли = str(папка) if папка is not None else (адрес or "")
    заметки: list[str] = []

    if папка is not None:
        with локальный_сервер(папка) as служебный_адрес:
            замеры, разметка = снять(служебный_адрес, куда, браузер, ждать_сек)
        замеры["адрес"] = что_проверяли  # в файлах пусть будет путь, а не служебный порт
    else:
        замеры, разметка = снять(адрес or "", куда, браузер, ждать_сек)
        заметки.append("Сайт по живому адресу: вес файлов не считаем — их нет под рукой.")

    находки = собрать_находки(замеры, разметка, папка)

    сравнение = None
    if референс is not None:
        try:
            сравнение = строки_сравнения(замеры, прочитать_референс(Path(референс)))
        except Exception as ошибка:
            заметки.append(f"Референс не прочитался ({type(ошибка).__name__}) — "
                           "сравнение пропускаю, остальное проверил.")

    экраны = [str(п) for у in (замеры.get("устройства") or {}).values()
              for п in (у.get("скриншоты") or {}).values() if str(п).endswith(".png")]
    отчёт = собрать_отчёт(что_проверяли, замеры, находки, сравнение, экраны, заметки)

    (куда / "замеры.json").write_text(
        json.dumps(замеры, ensure_ascii=False, indent=2), encoding="utf-8")
    (куда / "замеры.md").write_text(глаза.сводка(замеры), encoding="utf-8")
    (куда / "отчёт.md").write_text(отчёт, encoding="utf-8")
    return {"находки": находки, "замеры": замеры, "разметка": разметка,
            "отчёт": отчёт, "куда": куда}


def найти_сайты() -> list[Path]:
    """Собранные сайты в системе: `сайты/<имя>/сайт/index.html`."""
    полка = КОРЕНЬ / "сайты"
    if not полка.exists():
        return []
    return sorted(и.parent for и in полка.glob("*/сайт/index.html"))


def куда_класть(папка: Path) -> Path:
    """Куда сложить экраны, замеры и отчёт — и это никогда не внутрь проверяемой папки.

    ⛔ Раньше папку с чужим именем проверка обживала изнутри: `<папка>/проверка/`. Но эту
    папку целиком выкладывают на живой адрес — вместе со скриншотами и `отчёт.md`, где
    списком перечислено всё красное. Показывать людям список собственных недоделок незачем.

    Своя папка сайта называется `сайт` — тогда кладём по-соседски, `<родитель>/проверка/`.
    Любое другое имя (человек назвал папку как захотел или дал путь со стороны) — на общую
    полку `сайты/_проверка/<имя>/`, ту же, куда ложится проверка сайта по ссылке.
    """
    папка = Path(папка)
    if папка.name == "сайт":
        return папка.parent / "проверка"
    return КОРЕНЬ / "сайты" / "_проверка" / слаг_папки(папка)


def слаг_папки(папка: Path) -> str:
    """Имя на полке по пути к папке: `сайты/моё-дело/лендинг` → `моё-дело-лендинг`.

    Берём две последние части пути, а не одну: папок «лендинг» в разных работах бывает две,
    и отчёт по второй не должен молча затирать отчёт по первой.
    """
    путь = Path(папка).resolve()
    части = [путь.name]
    if путь.parent != путь.parent.parent:   # не сам корень диска
        части.insert(0, путь.parent.name)
    return глаза.слаг("-".join(ч for ч in части if ч))


def похоже_на_адрес(строка: str) -> bool:
    """Того, что назвали, нет на диске. Это адрес в интернете — или опечатка в пути к папке?

    Адресом считаем только явное: со схемой (`https://…`) или голый домен без косых черт
    (`пример.рф`). Всё остальное — путь, в котором человек ошибся буквой. Уйти по нему в
    интернет значит написать «страница не открылась» там, где надо сказать «нет такой папки»:
    человек пойдёт чинить сайт, а чинить надо было имя папки.
    """
    строка = строка.strip()
    if строка.startswith(("http://", "https://")):
        return True
    if "/" in строка or "\\" in строка:
        return False
    if строка.lower().endswith((".html", ".htm")):
        return False   # страница, которую не нашли на диске, — не домен
    имя, точка, зона = строка.rpartition(".")
    return bool(имя and зона.isalpha() and len(зона) >= 2)


def сказать_что_нет_папки(что_набрали: str) -> int:
    """Нет такой папки — покажем, какие есть, и в интернет не пойдём."""
    print(f"\n⛔ Нет такой папки: {что_набрали}")
    сайты = найти_сайты()
    if сайты:
        print("   Вот что есть:\n")
        for с in сайты:
            print(f"   {с.relative_to(КОРЕНЬ).as_posix()}")
    else:
        print("   Собранных сайтов пока нет — их папки появятся в сайты/<имя>/сайт/.")
    print("\n   Если это был адрес в интернете, напишите его целиком, с https://.\n")
    return 2


