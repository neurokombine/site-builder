# ── Локальный сервер: папка сайта ведёт себя как хостинг ─────────────────────────────────

@contextmanager
def локальный_сервер(папка: Path):
    """Отдаёт папку по http на 127.0.0.1 со свободного порта — и глушит свои логи."""

    class Тихий(http.server.SimpleHTTPRequestHandler):
        def log_message(self, формат, *аргументы):
            pass  # обращения браузера в консоли человеку не нужны

    сервер = http.server.ThreadingHTTPServer(
        ("127.0.0.1", 0), partial(Тихий, directory=str(папка)))
    поток = threading.Thread(target=сервер.serve_forever, daemon=True)
    поток.start()
    try:
        yield f"http://127.0.0.1:{сервер.server_port}/"
    finally:
        сервер.shutdown()
        сервер.server_close()
        поток.join(timeout=5)


def снять_разметку(браузер, адрес: str) -> dict:
    """Ссылки, якоря, служебные теги и контраст — одним заходом в страницу."""
    контекст = глаза.контекст(браузер, "компьютер")
    страница = контекст.new_page()
    try:
        страница.goto(адрес, wait_until="load", timeout=глаза.ТАЙМАУТ_ЗАГРУЗКИ_МС)
        try:
            страница.wait_for_load_state("networkidle", timeout=3000)
        except Exception:
            pass  # сайт с висящим чатом или трекером не затихает никогда
        return страница.evaluate(РАЗБОР_JS)
    except Exception as ошибка:
        return {"не_разобралось": f"{type(ошибка).__name__}: {ошибка}".split("\n")[0]}
    finally:
        контекст.close()


# ── Ссылки и файлы ───────────────────────────────────────────────────────────────────────

def локальный_путь(сырой: str, папка: Path | None) -> Path | None:
    """Куда на диске ведёт относительная ссылка. Внешние адреса и `data:` сюда не попадают."""
    if папка is None:
        return None
    без_хвоста = сырой.split("#")[0].split("?")[0].strip()
    if not без_хвоста or без_хвоста.startswith(("//", "data:", "mailto:", "tel:", "javascript:")):
        return None
    if "://" in без_хвоста:
        return None
    цель = папка / urllib.parse.unquote(без_хвоста).lstrip("/")
    if цель.is_dir():
        цель = цель / "index.html"
    return цель


def вес_ресурса(ссылка: dict, папка: Path | None) -> int | None:
    """Сколько весит картинка или файл: `data:` считаем по длине строки, остальное — по диску."""
    сырой = ссылка.get("сырой", "")
    if сырой.startswith("data:"):
        полезное = сырой.split(",", 1)[1] if "," in сырой else ""
        return len(полезное) * 3 // 4 if ";base64" in сырой.split(",", 1)[0] else len(полезное)
    путь = локальный_путь(сырой, папка)
    if путь is None or not путь.is_file():
        return None
    return путь.stat().st_size


def вес_словами(байты: int) -> str:
    """Байты человеку: «420 КБ», «1,4 МБ»."""
    if байты >= 1024 * 1024:
        return f"{байты / 1024 / 1024:.1f}".replace(".", ",") + " МБ"
    return f"{round(байты / 1024)} КБ"


def адрес_для_похода(ссылка: str) -> str:
    """Кириллический адрес — в тот вид, который понимает библиотека: домен в punycode, путь в %-кодах.

    Без этого «пример.рф/цены» падает с UnicodeEncodeError ещё до похода, и живая ссылка
    объявляется битой. Русские сайты — обычное дело, а не исключение.
    """
    разбор = urllib.parse.urlsplit(ссылка)
    домен = разбор.netloc
    try:
        домен = домен.encode("idna").decode("ascii")
    except Exception:
        домен = urllib.parse.quote(домен, safe=":@%")
    путь = urllib.parse.quote(разбор.path, safe="/%:@&=+$,~()!*'")
    запрос = urllib.parse.quote(разбор.query, safe="/%:@&=+$,~?()!*'")
    return urllib.parse.urlunsplit((разбор.scheme, домен, путь, запрос, ""))


def открывается_ли(ссылка: str) -> tuple[bool, str]:
    """Открывается ли внешняя ссылка. Сначала HEAD, потом GET.

    HEAD дешевле, но верить его отказу нельзя: сайты отвечают на него 403, 405, 404 и 501,
    а ту же страницу по GET отдают. Поэтому любой неудачный HEAD — повод переспросить GET-ом,
    и только его ответ идёт в находку.
    """
    заголовки = {"User-Agent": глаза.DESKTOP_UA, "Accept": "*/*"}
    последнее = "не ответила"
    адрес = адрес_для_похода(ссылка)
    for способ in ("HEAD", "GET"):
        запрос = urllib.request.Request(адрес, method=способ, headers=заголовки)
        try:
            with urllib.request.urlopen(запрос, timeout=ТАЙМАУТ_ССЫЛКИ_СЕК) as ответ:
                код = getattr(ответ, "status", 200) or 200
                if 200 <= код < 400:
                    return True, f"код {код}"
                последнее = f"код {код}"
        except urllib.error.HTTPError as ошибка:
            if 200 <= ошибка.code < 400:
                return True, f"код {ошибка.code}"
            последнее = f"код {ошибка.code}"
        except Exception as ошибка:
            последнее = f"{type(ошибка).__name__}"
        if способ == "GET":
            return False, последнее
    return False, последнее


def хост_из(сырой: str) -> str:
    """Домен из ссылки, без `www.`. Отдельной функцией, чтобы не откусить лишнего от «wa.me»."""
    разбор = urllib.parse.urlparse(сырой if "://" in сырой else "https://" + сырой)
    хост = (разбор.netloc or "").lower()
    return хост[4:] if хост.startswith("www.") else хост


def проверить_адрес_связи(сырой: str) -> str | None:
    """Почта, телефон и мессенджеры: проверяем форму записи, ходить по ним некуда."""
    низ = сырой.lower()
    if низ.startswith("mailto:"):
        почта = сырой[7:].split("?")[0].strip()
        if "@" not in почта or " " in почта or почта.startswith("@") or почта.endswith("@"):
            return "адрес почты записан не адресом — письмо уйдёт в никуда"
        имя, домен = почта.rsplit("@", 1)
        if not имя or "." not in домен or домен.endswith("."):
            return "адрес почты записан не адресом — письмо уйдёт в никуда"
        return None
    if низ.startswith("tel:"):
        # пробелы, скобки, дефисы и точки в номере разрешены и набираются везде — их снимаем;
        # красным остаётся то, что телефон не наберёт: буквы и пустота
        номер = сырой[4:].strip()
        for разделитель in РАЗДЕЛИТЕЛИ_НОМЕРА:
            номер = номер.replace(разделитель, "")
        лишнее = [з for з in номер if not (з.isdigit() or з == "+")]
        if not номер or лишнее:
            return "телефон так не набрать — в номере должны быть только цифры и «+»"
        return None
    разбор = urllib.parse.urlparse(сырой if "://" in сырой else "https://" + сырой)
    if хост_из(сырой) in МЕССЕНДЖЕРЫ and len(разбор.path.strip("/")) == 0:
        return "ссылка на мессенджер без имени или номера — по ней никто не напишет"
    return None


def находки_по_ссылкам(ссылки: list[dict], якоря: list[str], папка: Path | None) -> list[dict]:
    """Битые файлы, якоря в никуда, кривые адреса связи и внешние ссылки, которые не открылись."""
    нет_файла, нет_якоря, кривой_адрес, не_открылось = [], [], [], []
    свои_якоря = {я for я in якоря if я}
    внешние: list[str] = []   # уникальные, в порядке появления на странице

    for ссылка in ссылки:
        сырой = ссылка.get("сырой", "")
        тег = ссылка.get("тег", "a")
        низ = сырой.lower()
        if низ.startswith(("javascript:", "about:", "data:")):
            continue
        if низ.startswith("#"):
            якорь = сырой[1:]
            if якорь and якорь not in ("top",) and якорь not in свои_якоря:
                нет_якоря.append(f"«{сырой}» — на странице нет места с таким якорем: "
                                 "кнопка не прокрутит никуда")
            continue
        if низ.startswith(("mailto:", "tel:")):
            беда = проверить_адрес_связи(сырой)
            if беда:
                кривой_адрес.append(f"«{сырой}» — {беда}")
            continue
        if низ.startswith(("http://", "https://")):
            беда = проверить_адрес_связи(сырой)
            if беда:
                кривой_адрес.append(f"«{сырой}» — {беда}")
                continue
            if хост_из(сырой) in МЕССЕНДЖЕРЫ:
                continue
            if сырой not in внешние:
                внешние.append(сырой)
            continue
        путь = локальный_путь(сырой, папка)
        if путь is None:
            continue
        # Сравниваем путями, а не строками: у папки «сайт» строка «…/сайт-старый/фото.jpg»
        # тоже начинается с «…/сайт», и ссылка на соседнюю папку считалась «своей». Файл на
        # диске есть, находки нет — а на хостинге соседней папки не будет и картинка пропадёт.
        внутри = путь.resolve().is_relative_to(папка.resolve())  # type: ignore[union-attr]
        if not внутри:
            нет_файла.append(f"«{сырой}» ({тег}) — ведёт за пределы папки сайта: "
                             "на хостинге такого файла не будет")
        elif not путь.is_file():
            что = "картинки" if тег == "img" else "файла"
            нет_файла.append(f"«{сырой}» ({тег}) — {что} нет в папке сайта")

    # Внешние ссылки — единственное место, где проверка выходит в интернет, и каждая стоит
    # до двух походов по восемь секунд. Без потолка страница с сотней ссылок в подвале
    # проверялась бы четверть часа — при обещанных «около минуты». Поэтому сорок первых,
    # а про остальные говорим вслух: непроверенное не должно выглядеть проверенным.
    проверяем = внешние[:ЛИМИТ_ВНЕШНИХ_ССЫЛОК]
    остальные = len(внешние) - len(проверяем)
    for номер, адрес_ссылки in enumerate(проверяем, start=1):
        if номер % 10 == 0:
            # человеку у экрана: работа идёт, а не зависла
            print(f"Проверяю ссылки: {номер} из {len(проверяем)}…", file=sys.stderr)
        открылась, почему = открывается_ли(адрес_ссылки)
        if not открылась:
            не_открылось.append(
                f"«{адрес_ссылки}» — не открылась ({почему}): может быть защита от роботов — "
                "проверьте глазами")

    находки = []
    if нет_файла:
        находки.append(находка(ЧИНИТЬ, "Файлы, которых нет", нет_файла,
                               "на месте картинки будет пустой прямоугольник, "
                               "на месте страницы — ошибка"))
    if нет_якоря:
        находки.append(находка(ЧИНИТЬ, "Ссылки в никуда", нет_якоря,
                               "человек нажал — и ничего не произошло"))
    if кривой_адрес:
        находки.append(находка(ЧИНИТЬ, "Адрес связи записан с ошибкой", кривой_адрес,
                               "заявка не дойдёт, а человек решит, что вы недоступны"))
    if не_открылось:
        находки.append(находка(ПОПРАВИТЬ, "Внешние ссылки не открылись", не_открылось,
                               "проверьте их в браузере: битую ссылку на сайте читают "
                               "как заброшенный сайт"))
    if остальные:
        находки.append(находка(
            К_СВЕДЕНИЮ, "Внешних ссылок больше сорока",
            [f"проверены первые {ЛИМИТ_ВНЕШНИХ_ССЫЛОК}, остальные {остальные} — глазами"],
            "Дольше этого проверка перестаёт укладываться в обещанную минуту."))
    return находки


# ── Находки ──────────────────────────────────────────────────────────────────────────────

def находка(уровень: str, что: str, строки: list[str], чем_грозит: str = "") -> dict:
    """Одна находка: что не так → чем грозит → перечень мест."""
    return {"уровень": уровень, "что": что, "чем_грозит": чем_грозит, "строки": строки}


def найти_заглушки(текст: str, заголовок: str) -> list[str]:
    """Слова из шаблона, оставшиеся в живом тексте, — с куском фразы вокруг."""
    где = f"{заголовок}\n{текст}"
    низ = где.lower()
    найденные = []
    for метка in ЗАГЛУШКИ:
        место = низ.find(метка.lower())
        if место < 0:
            continue
        кусок = " ".join(где[max(0, место - 30):место + len(метка) + 30].split())
        найденные.append(f"«{метка}» — …{кусок}…")
    return найденные


def находки_по_весу(ссылки: list[dict], папка: Path | None, вес_html: int) -> list[dict]:
    """Тяжёлые картинки и общий вес страницы — по файлам папки."""
    if папка is None:
        return []
    тяжёлые, тяжеловатые = [], []
    всего = вес_html
    посчитанные = set()
    for ссылка in ссылки:
        if ссылка.get("тег") not in ГРУЗИТСЯ_СО_СТРАНИЦЕЙ:
            continue
        сырой = ссылка.get("сырой", "")
        вес = вес_ресурса(ссылка, папка)
        if вес is None:
            continue
        путь = локальный_путь(сырой, папка)
        # считаем по файлу, а не по ссылке: одна и та же картинка в <link> и в <img> — один вес
        ключ = str(путь.resolve()) if путь is not None else сырой
        if ключ in посчитанные:
            continue
        посчитанные.add(ключ)
        всего += вес
        if ссылка.get("тег") != "img":
            continue
        имя = "картинка в самой странице (data)" if сырой.startswith("data:") else f"«{сырой}»"
        if вес > КАРТИНКА_ТЯЖЁЛАЯ:
            тяжёлые.append(f"{имя} — {вес_словами(вес)}")
        elif вес > КАРТИНКА_ТЯЖЕЛОВАТА:
            тяжеловатые.append(f"{имя} — {вес_словами(вес)}")

    находки = []
    if тяжёлые:
        находки.append(находка(ЧИНИТЬ, "Тяжёлые картинки", тяжёлые,
                               "по мобильному интернету такая картинка грузится секундами — "
                               "человек уходит раньше, чем увидит её"))
    if тяжеловатые:
        находки.append(находка(ПОПРАВИТЬ, "Картинки, которые стоит сжать", тяжеловатые,
                               "страница грузится дольше, чем могла бы: на телефоне это заметно"))
    if всего > СТРАНИЦА_ТЯЖЁЛАЯ:
        находки.append(находка(
            ПОПРАВИТЬ, "Страница весит много",
            [f"вместе — {вес_словами(всего)} (считаем HTML, картинки, стили и скрипты "
             "из папки сайта)"],
            "на телефоне вдали от города страница откроется не сразу"))
    return находки


def находки_по_контрасту(контраст: list[dict]) -> list[dict]:
    """Текст, который сливается с фоном. Считаем по разметке — на фотографии число врёт."""
    if not контраст:
        return []
    строки = []
    for место in контраст:
        коэф = f"{место['коэффициент']:.1f}".replace(".", ",")
        порог = str(место["порог"]).replace(".", ",")
        хвост = " · здесь фон — картинка, смотрите глазами" if место.get("фон_картинка") else ""
        строки.append(f"«{место['текст']}» — {место['цвет']} на {место['фон']}: "
                      f"контраст {коэф} при норме {порог} (кегль {место['кегль']} px){хвост}")
    return [находка(ПОПРАВИТЬ, "Текст сливается с фоном", строки,
                    f"на телефоне на солнце такой текст не читается ({ПОДПИСЬ_КОНТРАСТА})")]


def собрать_находки(замеры: dict, разметка: dict, папка: Path | None) -> list[dict]:
    """Всё, что мы умеем находить, — одним списком в порядке разговора с человеком."""
    находки: list[dict] = []
    устройства = замеры.get("устройства", {})
    компьютер = устройства.get("компьютер", {})
    телефон = устройства.get("телефон", {})

    for имя, устройство in устройства.items():
        if устройство.get("статус") != "ок":
            беда = устройство.get("не_пустило") or {}
            находки.append(находка(
                ЧИНИТЬ, f"Страница не открылась ({имя})",
                [f"{глаза.НАЗВАНИЯ_ВИДОВ.get(беда.get('вид'), беда.get('вид', 'ошибка'))}: "
                 f"{беда.get('признак')}"],
                "мерить нечего, пока страница не открывается"))

    if разметка.get("не_разобралось"):
        находки.append(находка(ЧИНИТЬ, "Разметку прочитать не вышло",
                               [разметка["не_разобралось"]],
                               "ссылки, заглушки и контраст остались непроверенными"))
        return находки

    заглушки = найти_заглушки(разметка.get("текст", ""), разметка.get("заголовок", ""))
    if заглушки:
        находки.append(находка(ЧИНИТЬ, "Забытые заглушки", заглушки,
                               "человек прочтёт их раньше вас и решит, что сайт брошен"))

    прокрутка = телефон.get("прокрутка_вбок") or {}
    if прокрутка.get("есть"):
        находки.append(находка(
            ЧИНИТЬ, "На телефоне страница ездит вбок",
            [f"ширина страницы {прокрутка.get('ширина_страницы')} px при экране "
             f"{прокрутка.get('ширина_экрана')} px"],
            "текст уезжает за край, и его читают, дёргая страницу пальцем"))

    вылезают = телефон.get("вылезающие_картинки") or []
    if вылезают:
        находки.append(находка(
            ЧИНИТЬ, "На телефоне картинки вылезают за экран",
            [f"{к.get('тег')} шириной {к.get('ширина')} px — «{(к.get('адрес') or '')[:60]}»"
             for к in вылезают],
            "картинка обрезана краем экрана: видно половину"))

    ссылки = разметка.get("ссылки") or []
    вес_html = 0
    if папка is not None and (папка / "index.html").is_file():
        вес_html = (папка / "index.html").stat().st_size
    находки += находки_по_весу(ссылки, папка, вес_html)
    находки += находки_по_ссылкам(ссылки, разметка.get("якоря") or [], папка)

    мелкий = телефон.get("мелкий_текст") or {}
    сколько_мелкого = мелкий.get("элементов_мельче_14") or 0
    if сколько_мелкого:
        находки.append(находка(
            ПОПРАВИТЬ, "На телефоне есть текст мельче 14 px",
            [f"таких мест: {сколько_мелкого}, самый мелкий — {мелкий.get('минимум_px')} px"],
            "мелкий текст на телефоне не читают, а пролистывают"))

    находки += находки_по_контрасту(разметка.get("контраст") or [])

    заголовок = (разметка.get("заголовок") or "").strip()
    if not заголовок or заголовок.lower() in ПУСТЫЕ_ЗАГОЛОВКИ:
        находки.append(находка(
            ПОПРАВИТЬ, "Заголовок вкладки пустой или дежурный",
            [f"сейчас: «{заголовок}»" if заголовок else "заголовка нет вовсе"],
            "это имя сайта в закладке, в поиске и в пересланной ссылке — "
            "спросите человека, каким словом его должны узнавать"))

    if not (разметка.get("язык") or "").strip():
        находки.append(находка(
            ПОПРАВИТЬ, "У страницы не указан язык",
            ["в теге <html> нет атрибута lang"],
            "браузер предложит перевести русскую страницу, а голосовой чтец прочтёт её "
            "с чужим акцентом"))

    if not (разметка.get("описание") or "").strip():
        находки.append(находка(
            К_СВЕДЕНИЮ, "Нет описания для поиска",
            ["meta description пустой"],
            "Описание для поиска — напишем перед запуском, вместе с человеком."))

    закрыт = "noindex" in (разметка.get("роботы") or "").lower()
    находки.append(находка(
        К_СВЕДЕНИЮ, "Сайт закрыт от поиска" if закрыт else "Сайт открыт поиску",
        ["так и задумано, пока собираем" if закрыт
         else "поисковики могут его найти — если сайт ещё собирается, закройте его до запуска"]))

    if компьютер.get("предупреждение"):
        находки.append(находка(К_СВЕДЕНИЮ, "Пометка при замере", [компьютер["предупреждение"]]))
    return находки


# ── Сравнение с референсом ───────────────────────────────────────────────────────────────

def _кегль(устройство: dict, тег: str) -> str:
    значение = (устройство.get("кегли") or {}).get(тег)
    return f"{значение['px']} px" if значение else "—"


def _воздух(устройство: dict) -> str:
    доля = (устройство.get("воздух") or {}).get("доля")
    return f"{глаза.процент(доля)} %" if доля is not None else "—"


def _заметных_цветов(устройство: dict) -> str:
    цвета = устройство.get("цвета_текста") or []
    заметные = [ц for ц in цвета if ц.get("доля", 0) > 5]
    return str(len(заметные)) if цвета else "—"


def _минимальный_кегль(устройство: dict) -> str:
    минимум = (устройство.get("мелкий_текст") or {}).get("минимум_px")
    return f"{round(минимум)} px" if минимум else "—"


def _пара(замеры: dict, как: str) -> str:
    """Одно число в двух размерах: «48 px / 32 px»."""
    устройства = замеры.get("устройства", {})
    компьютер = устройства.get("компьютер", {})
    телефон = устройства.get("телефон", {})
    if как == "h1":
        return f"{_кегль(компьютер, 'h1')} / {_кегль(телефон, 'h1')}"
    if как == "текст":
        return f"{_кегль(компьютер, 'текст')} / {_кегль(телефон, 'текст')}"
    return f"{_воздух(компьютер)} / {_воздух(телефон)}"


def строки_сравнения(наши: dict, референс: dict) -> list[str]:
    """Таблица «ваш сайт | референс»: не чтобы сделать одинаково, а чтобы увидеть разницу."""
    def устройство(замеры, имя):
        return (замеры.get("устройства") or {}).get(имя, {})

    ряды = [
        ("Шрифт заголовков",
         устройство(наши, "компьютер").get("шрифт_заголовков") or "—",
         устройство(референс, "компьютер").get("шрифт_заголовков") or "—"),
        ("Шрифт текста",
         устройство(наши, "компьютер").get("шрифт_текста") or "—",
         устройство(референс, "компьютер").get("шрифт_текста") or "—"),
        ("Кегль h1 (компьютер / телефон)", _пара(наши, "h1"), _пара(референс, "h1")),
        ("Кегль текста (компьютер / телефон)", _пара(наши, "текст"), _пара(референс, "текст")),
        ("Воздух (компьютер / телефон)", _пара(наши, "воздух"), _пара(референс, "воздух")),
        ("Заметных цветов текста",
         _заметных_цветов(устройство(наши, "компьютер")),
         _заметных_цветов(устройство(референс, "компьютер"))),
        ("Самый мелкий текст на телефоне",
         _минимальный_кегль(устройство(наши, "телефон")),
         _минимальный_кегль(устройство(референс, "телефон"))),
    ]
    строки = ["| Что | Ваш сайт | Референс |", "|---|---|---|"]
    строки += [f"| {что} | {наше} | {чужое} |" for что, наше, чужое in ряды]
    строки += ["", ПОДПИСЬ_РЕФЕРЕНСА]
    return строки


