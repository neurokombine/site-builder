def найти_заглушки(текст: str, заголовок: str) -> list[str]:
    """Слова из шаблона, оставшиеся в живом тексте, — с куском фразы вокруг."""
    где = f"{заголовок}\n{текст}"
    низ = где.lower()
    найденные = []
    for метка in ЗАГЛУШКИ:
        место = низ.find(метка.lower())
        if место < 0:
            continue
        кусок = " ".join(где[max(0, место - 30):место + len(метка) + 30].split())
        найденные.append(f"«{метка}» — …{кусок}…")
    return найденные


def видимый_текст(html: str) -> str:
    """Что человек прочтёт на странице: без комментариев, без script/style/title, без тегов и без
    значений атрибутов. Браузеру этот разбор не нужен (там есть innerText) — он нужен `собрать.py`,
    у которого на руках только текст страницы. Теги и служебные блоки режет тем же выражением,
    что и расстановка неразрывных пробелов, — `флаги_дизайна.ТЕГ_ИЛИ_СЛУЖЕБНОЕ`."""
    части = флаги_дизайна.ТЕГ_ИЛИ_СЛУЖЕБНОЕ.split(КОММЕНТАРИЙ_HTML.sub(" ", html))
    return unescape(" ".join(части[0::2]))


def найти_метки(текст: str) -> list[str]:
    """Каждое вхождение метки прототипа в видимом тексте — с цитатой места (до ЦИТАТА_МЕТКИ знаков),
    в порядке появления."""
    низ = текст.lower()
    найденные = []
    for метка in МЕТКИ_ПРОТОТИПА:
        низ_метки, место = метка.lower(), 0
        while (место := низ.find(низ_метки, место)) >= 0:
            вокруг = " ".join(текст[max(0, место - 20):место + len(метка) + 40].split())
            найденные.append((место, f"«{метка}» — …{вокруг[:ЦИТАТА_МЕТКИ]}…"))
            место += len(метка)
    return [строка for _, строка in sorted(найденные)]


def находки_по_весу(ссылки: list[dict], папка: Path | None, вес_html: int) -> list[dict]:
    """Тяжёлые картинки и общий вес страницы — по файлам папки."""
    if папка is None:
        return []
    тяжёлые, тяжеловатые = [], []
    всего = вес_html
    посчитанные = set()
    for ссылка in ссылки:
        if ссылка.get("тег") not in ГРУЗИТСЯ_СО_СТРАНИЦЕЙ:
            continue
        сырой = ссылка.get("сырой", "")
        вес = вес_ресурса(ссылка, папка)
        if вес is None:
            continue
        путь = локальный_путь(сырой, папка)
        # считаем по файлу, а не по ссылке: одна и та же картинка в <link> и в <img> — один вес
        ключ = str(путь.resolve()) if путь is not None else сырой
        if ключ in посчитанные:
            continue
        посчитанные.add(ключ)
        всего += вес
        if ссылка.get("тег") != "img":
            continue
        имя = "картинка в самой странице (data)" if сырой.startswith("data:") else f"«{сырой}»"
        if вес > КАРТИНКА_ТЯЖЁЛАЯ:
            тяжёлые.append(f"{имя} — {вес_словами(вес)}")
        elif вес > КАРТИНКА_ТЯЖЕЛОВАТА:
            тяжеловатые.append(f"{имя} — {вес_словами(вес)}")

    находки = []
    if тяжёлые:
        находки.append(находка(ЧИНИТЬ, "Тяжёлые картинки", тяжёлые,
                               "по мобильному интернету такая картинка грузится секундами — "
                               "человек уходит раньше, чем увидит её"))
    if тяжеловатые:
        находки.append(находка(ПОПРАВИТЬ, "Картинки, которые стоит сжать", тяжеловатые,
                               "страница грузится дольше, чем могла бы: на телефоне это заметно"))
    if всего > СТРАНИЦА_ТЯЖЁЛАЯ:
        находки.append(находка(
            ПОПРАВИТЬ, "Страница весит много",
            [f"вместе — {вес_словами(всего)} (считаем HTML, картинки, стили и скрипты "
             "из папки сайта)"],
            "на телефоне вдали от города страница откроется не сразу"))
    return находки


# ── Фон по пикселям снимка: последнее слово за экраном, а не за разметкой ────────────────
#
# Обход предков в браузере отвечает на вопрос «какой цвет ОБЪЯВЛЕН под элементом», а человек
# видит ПИКСЕЛИ. Расходятся они чаще, чем кажется, и всегда в одну сторону — в сторону ложной
# находки:
#   • фон, заданный сокращением `background: linear-gradient(…)`, оставляет `background-color`
#     прозрачным — обход проходит такого предка насквозь и приносит цвет `body`;
#   • полупрозрачная карточка («стекло») по той же причине пропускается;
#   • фотография первого экрана лежит соседом, а не предком, и в обход не попадает вовсе.
# Поэтому правило: по разметке вышло меньше нормы — перемеряем по снимку и верим снимку.
# Средний цвет экрана для этого не годится (им мерили раньше): кнопка стоит на своём островке —
# на тёмной карточке посреди светлой страницы или наоборот, — и среднее по экрану врёт так же
# уверенно, как разметка. Берём цвет РЯДОМ С САМИМ МЕСТОМ.
#
ОТСТУП_РАМКИ = 6        # px снимка: на столько отходим от края, чтобы не поймать кромку и тень
ТОЛЩИНА_РАМКИ = 14      # px снимка: ширина кольца, по которому берём цвет фона
ШАГ_ЦВЕТА = 16          # огрубление цвета перед подсчётом: тени и сжатие не должны дробить фон
ЦВЕТ_БУКВ_РЯДОМ = 40    # ближе этого по RGB — уже буква, а не фон под ней
РАЗНИЦА_РАСКЛАДКИ = 4   # px: настолько снимок и разбор могут разойтись по высоте страницы
БЕЗ_ЭКРАНА = ("экрана под рукой не было — числа посчитаны по разметке, "
              "а на фотографии и на градиенте она занижает контраст: проверьте глазами")


HEX_ЦВЕТ = re.compile(r"^#[0-9a-fA-F]{6}$")


def _разобрать_hex(цвет: str) -> tuple[int, int, int]:
    цвет = (цвет or "").lstrip("#")
    return tuple(int(цвет[и:и + 2], 16) for и in (0, 2, 4))


def _мода_цвета(пиксели: list[tuple[int, int, int]]) -> str | None:
    """Самый частый цвет пачки — и средний по всем, кто в него попал.

    Именно мода, а не среднее по всей пачке: в рамке вокруг кнопки попадаются буквы соседней
    строки и край фотографии, и среднее размазало бы фон вместе с ними. Мода отвечает на
    вопрос «какого цвета здесь БОЛЬШЕ ВСЕГО» — это и есть фон.
    """
    if not пиксели:
        return None

    def квант(п):
        return (п[0] // ШАГ_ЦВЕТА * ШАГ_ЦВЕТА, п[1] // ШАГ_ЦВЕТА * ШАГ_ЦВЕТА,
                п[2] // ШАГ_ЦВЕТА * ШАГ_ЦВЕТА)

    частый = Counter(квант(п) for п in пиксели).most_common(1)[0][0]
    ведро = [п for п in пиксели if квант(п) == частый]
    сред = [sum(п[и] for п in ведро) / len(ведро) for и in (0, 1, 2)]
    return "#%02x%02x%02x" % tuple(round(с) for с in сред)


def _кусок(картинка, левый, верхний, правый, нижний) -> list[tuple[int, int, int]]:
    """Пиксели прямоугольника снимка; за краем снимка ничего не берём."""
    ширина, высота = картинка.size
    левый, верхний = max(0, int(левый)), max(0, int(верхний))
    правый, нижний = min(ширина, int(round(правый))), min(высота, int(round(нижний)))
    if правый <= левый or нижний <= верхний:
        return []
    сырьё = картинка.crop((левый, верхний, правый, нижний)).tobytes()   # три байта на пиксель
    return [(сырьё[и], сырьё[и + 1], сырьё[и + 2]) for и in range(0, len(сырьё) - 2, 3)]


def фон_вокруг(картинка, коробка: dict, масштаб: float) -> str | None:
    """Цвет РАМКИ вокруг места — то, на чём кнопка стоит.

    Рамка, а не прямоугольник самого места: внутри кнопки лежит её заливка, её мерить незачем.
    Отходим на `ОТСТУП_РАМКИ`, чтобы не поймать скруглённую кромку, обводку и мягкую тень, и
    берём кольцо шириной `ТОЛЩИНА_РАМКИ` — четыре полосы: сверху, снизу, слева, справа.
    """
    x, y = коробка["x"] * масштаб, коробка["y"] * масштаб
    ш, в = коробка["ш"] * масштаб, коробка["в"] * масштаб
    о, т = ОТСТУП_РАМКИ, ТОЛЩИНА_РАМКИ
    полосы = [
        (x - о - т, y - о - т, x + ш + о + т, y - о),           # сверху
        (x - о - т, y + в + о, x + ш + о + т, y + в + о + т),   # снизу
        (x - о - т, y - о, x - о, y + в + о),                   # слева
        (x + ш + о, y - о, x + ш + о + т, y + в + о),           # справа
    ]
    пиксели: list[tuple[int, int, int]] = []
    for полоса in полосы:
        пиксели += _кусок(картинка, *полоса)
    return _мода_цвета(пиксели)


def фон_под_текстом(картинка, коробка: dict, масштаб: float, цвет_букв: str) -> str | None:
    """Цвет МЕЖДУ БУКВАМИ — то, на чём текст лежит.

    У текста, в отличие от кнопки, свой прямоугольник и есть фон: буквы занимают меньшую его
    часть. Выбрасываем пиксели, близкие к цвету самих букв, и берём самый частый из остальных.
    Букв оказалось столько, что фона не осталось (крупный жирный заголовок) — отходим на рамку
    вокруг, как у кнопки.
    """
    буквы = _разобрать_hex(цвет_букв)
    пиксели = _кусок(картинка, коробка["x"] * масштаб, коробка["y"] * масштаб,
                     (коробка["x"] + коробка["ш"]) * масштаб,
                     (коробка["y"] + коробка["в"]) * масштаб)
    фоновые = [п for п in пиксели
               if max(abs(п[и] - буквы[и]) for и in (0, 1, 2)) > ЦВЕТ_БУКВ_РЯДОМ]
    if len(фоновые) < max(16, len(пиксели) // 10):
        return фон_вокруг(картинка, коробка, масштаб)
    return _мода_цвета(фоновые)


def экран_страницы(замеры: dict, разметка: dict):
    """Снимок всей страницы на компьютере и во сколько раз его пиксели крупнее пикселей страницы.

    Разбор разметки снимается в том же размере («компьютер»), что и этот снимок, — значит
    координаты на странице и пиксели на снимке говорят об одном и том же месте. Масштаб считаем
    сами, делением ширин: у телефона снимок втрое крупнее страницы, и промах на этот множитель
    увёл бы рамку с фона на саму кнопку.

    Отдаём `None`, если снимка нет или он разошёлся с разбором по высоте страницы, — мерить по
    такому снимку нельзя, пусть лучше останется число по разметке и честная оговорка словами.
    """
    устройство = (замеры.get("устройства") or {}).get("компьютер") or {}
    путь = (устройство.get("скриншоты") or {}).get("вся_страница")
    окно = разметка.get("окно") or {}
    if not путь or not окно.get("ширина") or not Path(путь).is_file():
        return None
    try:
        from PIL import Image

        картинка = Image.open(путь).convert("RGB")
    except Exception:
        return None
    масштаб = картинка.width / окно["ширина"]
    if масштаб <= 0:
        return None
    if abs(картинка.height / масштаб - (окно.get("высота") or 0)) > РАЗНИЦА_РАСКЛАДКИ:
        return None
    return картинка, масштаб


def находки_по_контрасту(контраст: list[dict], экран=None) -> list[dict]:
    """Текст, который сливается с фоном.

    Число из браузера — предварительное: фон там взят по разметке, а под фотографией, под
    градиентом и на полупрозрачной карточке разметка врёт (см. блок выше). Поэтому каждое
    место, которое браузер счёл слабым, перемеряем по пикселям снимка — и находкой считаем
    результат пикселей. Нового места пиксели не добавляют: они только отменяют или оставляют
    то, что уже названо.
    """
    if not контраст:
        return []
    перемерить_по_экрану(контраст, экран)
    контраст = [м for м in контраст if м["коэффициент"] + 0.05 < м["порог"]]
    if not контраст:
        return []
    строки = []
    for место in контраст:
        коэф = f"{место['коэффициент']:.1f}".replace(".", ",")
        порог = str(место["порог"]).replace(".", ",")
        строки.append(f"«{место['текст']}» — {место['цвет']} на {место['фон']}: "
                      f"контраст {коэф} при норме {порог} (кегль {место['кегль']} px)"
                      + _откуда_фон(место))
    if not экран:
        строки.append(БЕЗ_ЭКРАНА)
    return [находка(ПОПРАВИТЬ, "Текст сливается с фоном", строки,
                    f"на телефоне на солнце такой текст не читается ({ПОДПИСЬ_КОНТРАСТА})")]


def перемерить_по_экрану(места: list[dict], экран) -> None:
    """Пересчитать фон и коэффициент по пикселям снимка — там, где снимок есть.

    Одна дорога для обеих текстовых проверок: и «текст сливается с фоном», и «тёплый цвет на
    светлом фоне» получают фон из разметки, а она врёт под градиентом, под фотографией и на
    полупрозрачной карточке. Пиксели ничего не добавляют, они только отменяют или оставляют
    то, что браузер уже счёл слабым. Снимка нет или место на нём не нашлось — остаётся число
    по разметке и оговорка словами.
    """
    for место in места:
        if not экран or not место.get("коробка") or not место.get("цвет"):
            continue
        картинка, масштаб = экран
        по_пикселям = фон_под_текстом(картинка, место["коробка"], масштаб, место["цвет"])
        if not по_пикселям:
            continue
        место["фон"] = по_пикселям
        место["коэффициент"] = round(контраст_hex(место["цвет"], по_пикселям), 1)
        место["фон_с_экрана"] = True


def _откуда_фон(место: dict) -> str:
    """Хвост строки: чем мерили фон — экраном или разметкой."""
    if место.get("фон_с_экрана"):
        return " · фон снят с экрана, вокруг самого места"
    if место.get("фон_картинка"):
        return " · здесь фон — картинка, смотрите глазами"
    return ""


def _яркость_hex(цвет: str) -> float:
    цвет = цвет.lstrip("#")
    каналы = [int(цвет[i:i + 2], 16) / 255 for i in (0, 2, 4)]
    к = [c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4 for c in каналы]
    return 0.2126 * к[0] + 0.7152 * к[1] + 0.0722 * к[2]


def контраст_hex(первый: str, второй: str) -> float:
    """Коэффициент контраста двух цветов по WCAG. Тот же расчёт, что и в браузере."""
    я1, я2 = _яркость_hex(первый), _яркость_hex(второй)
    ярче, темнее = max(я1, я2), min(я1, я2)
    return (ярче + 0.05) / (темнее + 0.05)


def находки_по_кнопкам(кнопки: list[dict], экран=None) -> list[dict]:
    """Кнопка целевого действия, которая не видна как кнопка.

    Правило владелицы, 11.09.2026: кнопка с целевым действием всегда акцентная и контрастная —
    спокойная ниша не повод для серой кнопки. Спокойной может быть вся страница, кнопка нет.
    Сторож на этом правиле должен молчать там, где кнопка честная: ученик, которого послали
    чинить исправную кнопку, второй раз проверке не поверит.

    Фон под кнопкой по разметке врёт (см. блок «Фон по пикселям снимка» выше). Поэтому: вышло
    меньше нормы — перемеряем по рамке вокруг кнопки на снимке и верим снимку. Раньше здесь
    брали средний цвет первого экрана — он врал и в другую сторону: светлая кнопка на нижнем
    экране получала в фон среднее тёмной шапки. Подпись НА кнопке перемерять незачем: она
    лежит на собственной заливке кнопки, а заливка в разметке названа честно.
    """
    if not кнопки:
        return []
    for к in кнопки:
        if not экран or not к.get("коробка") or к["к_фону"] + 0.05 >= 3:
            continue
        картинка, масштаб = экран
        по_пикселям = фон_вокруг(картинка, к["коробка"], масштаб)
        if not по_пикселям:
            continue
        к["фон"] = по_пикселям
        к["к_фону"] = round(контраст_hex(к["заливка"], по_пикселям), 2)
        к["фон_с_экрана"] = True
    кнопки = [к for к in кнопки if к["к_фону"] + 0.05 < 3 or к["к_подписи"] + 0.05 < 4.5]
    if not кнопки:
        return []
    строки = []
    for к in кнопки:
        беды = []
        if к["к_фону"] + 0.05 < 3:
            число = f"{к['к_фону']:.2f}".replace(".", ",")
            беды.append(f"к фону {к['фон']} — {число} при норме 3")
        if к["к_подписи"] + 0.05 < 4.5:
            число = f"{к['к_подписи']:.2f}".replace(".", ",")
            беды.append(f"подпись {к['подпись']} на заливке — {число} при норме 4,5")
        строки.append(f"«{к['текст']}» — заливка {к['заливка']}: " + "; ".join(беды)
                      + _откуда_фон(к))
    if not экран:
        строки.append(БЕЗ_ЭКРАНА)
    return [находка(ПОПРАВИТЬ, "Кнопка не видна как кнопка",
                    строки,
                    "кнопка целевого действия всегда акцентная и контрастная — спокойная ниша "
                    "не повод для серой кнопки; поднимите акцент в профиле или возьмите его "
                    "контрастную ступень")]


def находки_по_тёплому(тёплый: list[dict], экран=None) -> list[dict]:
    """Задача 13: тёплый цвет профиля как текст на фоне светлее нормы. Золото хорошо читается на
    тёмном (высокий контраст у него почти всегда сам собой), а на светлом фоне часто не дотягивает —
    для текста там есть отдельный, уже посчитанный под контраст 4,5 токен `--цвет-тёплый-тёмный`.

    Фон здесь перемеряется по пикселям снимка ровно так же, как у соседней проверки на слияние
    текста с фоном: золотая строка чаще всего лежит на тёмной плите, залитой градиентом, а
    градиент в разметке прозрачен — и по ней выходит белая страница и контраст вдвое ниже
    настоящего. Сторож, который шлёт чинить читаемую строку, второй раз не будет услышан.
    """
    if not тёплый:
        return []
    перемерить_по_экрану(тёплый, экран)
    тёплый = [м for м in тёплый if м["коэффициент"] + 0.05 < м["порог"]]
    if not тёплый:
        return []
    строки = []
    for м in тёплый:
        коэф = f"{м['коэффициент']:.1f}".replace(".", ",")
        порог = str(м["порог"]).replace(".", ",")
        строки.append(f"«{м['текст']}» тёплым цветом на {м['фон']}: "
                      f"контраст {коэф} при норме {порог}{_откуда_фон(м)}")
    if not экран:
        строки.append(БЕЗ_ЭКРАНА)
    return [находка(ПОПРАВИТЬ, "Тёплый цвет на светлом фоне не читается", строки,
                    "золото хорошо смотрится на тёмном фоне, а на светлом контраста часто не хватает — "
                    "для текста на светлом берите не --цвет-тёплый, а --цвет-тёплый-тёмный: он уже "
                    "посчитан под контраст 4,5")]


# ── Ритм страницы: светлота соседей, карточка против своего фона, одна главная кнопка ────
#
# Три беды, которых не видно по одному экрану: они про СОСЕДСТВО. Страница из одинаково
# светлых экранов читается как одна бесконечная простыня; карточка в тон своей секции
# не читается карточкой (диагноз 15.09: «экраны скучные, карточки на тёмном тоже тёмные»);
# две главные кнопки на экране — значит ни одной, человек не понимает, куда нажимать.
#
# Меряем по цвету фона из разбора, а не по классам рецепта: класс говорит, что задумано,
# цвет — что вышло. Светлота — та же линейка, что у контраста (`_яркость_hex`): одна
# формула на систему, второй не заводим.

РИТМ_СВЕТЛОТА = 0.06    # ближе — соседние экраны сливаются в один длинный
# Шаг карточки от фона своей секции считается по-разному на тёмном и на светлом, и это не
# послабление, а разная физика. На светлом карточку держит тень и кромка: белая карточка на
# кремовом фоне честно читается карточкой, хотя по светлоте отходит от него всего на сотые.
# На тёмном тени не видно вовсе — там карточку держит только собственная светлота, и шаг ей
# нужен крупный. Одним числом эти два случая не описать: от кремового фона (светлота 0,897)
# вверх есть всего 0,103 — порог 0,12 на светлом недостижим, и под него попала бы ЛЮБАЯ
# карточка на любой светлой секции.
РИТМ_КАРТОЧКА_НА_ТЁМНОМ = 0.12    # ближе — та самая «карточка на тёмном тоже тёмная»
РИТМ_КАРТОЧКА_НА_СВЕТЛОМ = 0.02   # ближе — карточка сливается с бумагой даже с тенью
ТЁМНАЯ_СЕКЦИЯ = 0.18              # светлота середины серого: ниже — фон тёмный
# Пара, где одинаковая светлота — норма: подвал по умолчанию берёт вторую ступень того же
# ключа, что и финал. Это одно решение, а не сбой ритма.
ПАРА_БЕЗ_РИТМА = ("финал", "подвал")


def _имя_экрана(номер: int, секция: dict) -> str:
    """«экран 4 („решение")» — номером по порядку, а тип подсказывает, какой это экран."""
    тип = (секция.get("тип") or "").strip()
    return f"экран {номер}" + (f" («{тип}»)" if тип else "")


def _фон_картинкой(*секции: dict) -> str:
    """Хвост строки: под градиентом и фотографией объявленный цвет — не тот, что видит человек."""
    return " · здесь фон — картинка, смотрите глазами" if any(
        с.get("фон_картинка") for с in секции) else ""


def находки_по_ритму(секции: list[dict]) -> list[dict]:
    """Ритм собранной страницы по замерам секций — без браузера, на одних числах.

    Приходит список секций из `РАЗБОР_JS`: `{"id", "тип", "фон", "фон_картинка", "карточки",
    "главных"}`. Цвета — `#rrggbb`, светлоту считаем здесь: числу из браузера верить нечего,
    а цвету есть.
    """
    if not секции:
        return []
    светлота = [_яркость_hex(с["фон"]) if HEX_ЦВЕТ.match(с.get("фон") or "") else None
                for с in секции]

    одинаковые = []
    for н in range(len(секции) - 1):
        свой, следом = светлота[н], светлота[н + 1]
        if свой is None or следом is None:
            continue
        типы = ((секции[н].get("тип") or ""), (секции[н + 1].get("тип") or ""))
        if типы == ПАРА_БЕЗ_РИТМА:
            continue
        if abs(свой - следом) >= РИТМ_СВЕТЛОТА:
            continue
        одинаковые.append(
            f"экраны {н + 1} и {н + 2} одной светлоты: {секции[н]['фон']} и {секции[н + 1]['фон']}"
            + _фон_картинкой(секции[н], секции[н + 1]))

    в_тон = []
    for н, (секция, своя) in enumerate(zip(секции, светлота), start=1):
        if своя is None:
            continue
        порог = (РИТМ_КАРТОЧКА_НА_ТЁМНОМ if своя < ТЁМНАЯ_СЕКЦИЯ
                 else РИТМ_КАРТОЧКА_НА_СВЕТЛОМ)
        for карточка in секция.get("карточки") or []:
            цвет = карточка.get("фон") or ""
            if not HEX_ЦВЕТ.match(цвет) or abs(_яркость_hex(цвет) - своя) >= порог:
                continue
            в_тон.append(f"{_имя_экрана(н, секция)}: «{карточка.get('класс') or 'карточка'}» "
                         f"{цвет} на фоне {секция['фон']}" + _фон_картинкой(секция))

    две_кнопки = [f"{_имя_экрана(н, секция)}: главных кнопок {секция.get('главных')}"
                  for н, секция in enumerate(секции, start=1)
                  if (секция.get("главных") or 0) >= 2]

    находки = []
    if одинаковые:
        находки.append(находка(
            ПОПРАВИТЬ, "Соседние экраны одной светлоты", одинаковые,
            "два экрана одного тона подряд читаются как один бесконечный — переверните роль "
            "одного из них на `ключ--наоборот` или уведите его на вторую ступень `ключ--глубже`"))
    if в_тон:
        находки.append(находка(
            ПОПРАВИТЬ, "Карточка в тон фона своей секции", в_тон,
            "карточка, совпавшая с фоном, перестаёт быть карточкой — на тёмной секции берите "
            "светлую подложку (или `карточка--стекло`), на светлой — глубокий тон акцента"))
    if две_кнопки:
        находки.append(находка(
            ЧИНИТЬ, "Две главные кнопки на одном экране", две_кнопки,
            "две главные — значит ни одной: человек не понимает, куда нажимать. "
            "Оставьте одну, вторую сделайте `кнопка кнопка--контур`"))
    return находки


# ── Контракт В: свободный экран ниже обложки ──────────────────────────────────────────────
#
# Обложку система собирает по рецепту, всё остальное нейросеть верстает свободно. Свобода
# держится ровно на одном: каждый экран обязан жить внутри своего `#экран-NN`, брать цвета,
# кегли, скругления и тени только из переменных и не заводить второй главной кнопки. Иначе
# «разные сборки» превращаются в разные сайты на одной странице.
#
# Проверяется дважды и одним кодом: сборка говорит сразу, `проверить.py` — ещё раз, уже по
# файлам работы. Сборка зовёт `места_контракта` на тех же экранах, которые сшивает в страницу,
# поэтому обратного импорта нет: этот модуль ниже по цепочке, `собрать.py` импортирует его.

СЕКЦИЯ_В = re.compile(
    r'^<section class="блок блок--([а-яё-]+) (ключ--(?:основной|глубже|наоборот))'
    r'( фон--(?:пятна|сетка|зерно))?"\s+id="экран-(\d{2})" data-тип="\1" data-вёрстка="своя">')
СВОЯ_ВЁРСТКА = 'data-вёрстка="своя"'
ОТКРЫВАЮЩИЙ_ТЕГ = re.compile(r"^<section\b[^>]*>", re.S)
СТИЛЬ_ЭКРАНА = re.compile(r"[ \t]*<style>(.*?)</style>[ \t]*\n?", re.S)
НОМЕР_ЭКРАНА = re.compile(r'id="экран-(\d+)"')
КОММЕНТАРИЙ_CSS = re.compile(r"/\*.*?\*/", re.S)
# Цвет числом: hex, rgb(), hsl(). `color-mix(…, transparent)` разрешён — он делает прозрачной
# ту же переменную профиля, а не заводит новый цвет. Кириллическое `#экран-02` под hex не подходит.
ЦВЕТ_ЧИСЛОМ = re.compile(r"#[0-9a-fA-F]{3,8}\b|\brgba?\(|\bhsla?\(")
ОБЪЯВЛЕНИЕ = re.compile(r"([a-z-]+)\s*:\s*([^;{}]+)")
# Какое слово обязано стоять в имени токена у каждого из трёх свойств. Само имя сверяется с
# каталогом переменных профиля: `--кнопка-радиус` — законное скругление, а `--кегль-заголовок`,
# которого в профиле нет, — находка, даже если написан он через `var()`.
КЛЮЧИ_ТОКЕНА = {"font-size": "кегль", "border-radius": "радиус", "box-shadow": "тень"}
ЗНАЧЕНИЕ_БЕЗ_ТОКЕНА = {"none", "0", "inherit", "unset", "initial", "revert"}
ВЛОЖЕННЫЕ_ПРАВИЛА = ("@media", "@supports", "@container", "@layer")
РОЛИ_КЛЮЧА = ("ключ--основной", "ключ--глубже", "ключ--наоборот")
ФАКТУРЫ = ("фон--пятна", "фон--сетка", "фон--зерно")
КЛАСС_СЕКЦИИ = re.compile(r'class="([^"]*)"')
ИД_СЕКЦИИ = re.compile(r'id="([^"]*)"')
ТИП_СЕКЦИИ = re.compile(r'data-тип="([^"]*)"')
ИД_ЭКРАНА_ДВЕ_ЦИФРЫ = re.compile(r"^экран-\d{2}$")
ОБЁРТКА_КАРТИНКИ = re.compile(
    r'<figure[^>]*class="[^"]*\b(?:фото|мокап|аватар)\b[^"]*"[^>]*>.*?</figure>', re.S)
ЗАГЛУШКА_КАРТИНКИ = re.compile(r'<div[^>]*class="[^"]*\bзаглушка-картинки\b[^"]*"[^>]*>.*?</div>', re.S)
КАРТИНКА_ЭКРАНА = re.compile(r"<(img|video|picture)\b")
СЛОТ_СВЯЗИ = re.compile(r"\{\{СВЯЗЬ:[^}]*\}\}")

