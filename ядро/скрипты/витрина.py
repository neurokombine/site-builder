"""Витрина: первый экран прототипа в каждом варианте дизайн-системы — рядом, в двух видах.

Человек выбирает вид глазами, а не по описанию словами: на скриншотах, на компьютере и на
телефоне сразу (🔴 одобрение = одобрение обоих, CLAUDE.md § 4). Скрипт берёт варианты из
`сайты/<имя>/дизайн.md` (контракт А), тексты экрана 1 — из `прототип.md`, а рецепт — по концепции
варианта из `ядро/блоки/<пресет>/01-первый-экран-<концепция>.html`: три варианта — три разные
композиции, а не один экран в трёх цветах. Свёрстанные экраны витрине не нужны: она идёт до них.

Запуск: .venv/bin/python ядро/скрипты/витрина.py сайты/<имя> [--без-показа]
На выходе: `витрина/вариант-N/` (index.html, style.css, компьютер.png, телефон.png) и
`витрина/витрина.html` — по строке на вариант. Выбор скрипт не делает и не записывает:
выбранный вариант человек называет, ты переписываешь его в `дизайн.md` → `## Решения` и в журнал.
"""
