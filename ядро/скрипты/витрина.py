def варианты_из(дизайн: dict) -> list[dict]:
    """Варианты, у которых есть css: без него показывать нечего. Пусто → []."""
    return [в for в in дизайн.get("варианты") or [] if (в.get("css") or "").strip()]


def перекрасить(html: str, css: str) -> str:
    """Та же страница в другом варианте: содержимое <style>…</style> каркаса → css варианта.
    Ссылка на шрифты — тоже под этот вариант: иначе свой шрифт не подгрузится, и человек выберет
    по системному, которого на сайте не будет."""
    страница = СТИЛЬ.sub(lambda _: f"<style>\n{css.strip()}\n</style>", html, count=1)
    страница = ШРИФТЫ_ИЗ_СЕТИ.sub("", страница)
    шрифты = собрать.ссылка_на_шрифты(css)
    if шрифты and ССЫЛКА_НА_СТИЛИ in страница:
        страница = страница.replace(ССЫЛКА_НА_СТИЛИ, шрифты + "\n" + ССЫЛКА_НА_СТИЛИ, 1)
    return страница


def _картинки(работа: Path) -> dict:
    """Что лежит у человека: первое фото (не `-telefon`), его телефонный кроп, первый ролик `.mp4` и постер."""
    img, video = Path(работа) / "img", Path(работа) / "video"
    фото = sorted(ф.name for ф in img.glob("*") if ф.suffix.lower() in КАРТИНКИ and "-telefon." not in ф.name) if img.is_dir() else []
    первое = фото[0] if фото else ""
    телефон = sorted(ф.name for ф in img.glob(Path(первое).stem + "-telefon.*")) if первое else []
    ролики = sorted((ф.stem for ф in video.glob("*.mp4") if not ф.stem.endswith("-telefon")), key=lambda с: (not с.startswith("zhivaya"), с)) if video.is_dir() else []   # петля zhivaya раньше речи golos
    ролик = ролики[0] if ролики else ""
    постеры = sorted(ф.name for ф in video.iterdir() if ф.name.startswith(ролик + "-poster.")) if ролик else []   # постер того же ролика, не первый по алфавиту
    return {"фото": первое, "фото_телефон": телефон[0] if телефон else "",
            "видео": ролик, "постер": постеры[0] if постеры else ""}


def тексты_первого_экрана(работа: Path) -> dict | None:
    """Экран 1 прототипа → тексты для рецепта первого экрана (контракт Е); нет прототипа/экрана — None."""
    файл = Path(работа) / "прототип.md"
    if not файл.is_file():
        return None
    прототипы = проверить_прототип.разобрать(файл.read_text(encoding="utf-8-sig"))
    if not прототипы or not прототипы[0]["экраны"]:
        return None
    шапка, экран = прототипы[0]["шапка"], прототипы[0]["экраны"][0]
    слоты = экран.get("слоты", {})

    def первый(имя: str) -> str:
        return (слоты.get(имя) or [""])[0].strip()

    цифры = []
    for кусок in РАЗДЕЛИТЕЛЬ.split(первый("Доказательство").split("источник:")[0]):
        м = ЧИСЛО.match(кусок)
        if м:
            цифры.append((м.group(1).strip(), м.group(2).strip()))
    слова = первый("Заголовок").split()
    # Задача 6: три новых слота контракта (задача 2) — верхняя строка, регалии, чипы; читаем через
    # тот же _подполя, что и проверить_прототип.py — тексты «знак: …» без ведущего «- » уже разобраны.
    верхняя_строка = проверить_прототип._подполя(слоты.get("Верхняя строка", []))
    регалии = проверить_прототип._подполя(слоты.get("Регалии", []))
    доверие_шапки = (верхняя_строка.get("доверие") or [""])[0].strip()
    доверие_кратко = (верхняя_строка.get("кратко") or [""])[0].strip()   # фикс-раунд 2, § 2: необязательная телефонная версия
    чипы = [с.strip() for с in слоты.get("Чипы", []) if с.strip() and с.strip().lower() != "нет"]
    # Задача 9, контракт § 6: подписи роликов мозаики — свой слот, раньше не читался вовсе (в
    # каждом кадре стояло заглушкой «Ролик N»); теперь строка берётся из прототипа, тем же приёмом,
    # что и чипы.
    подписи_роликов = [с.strip() for с in слоты.get("Подписи роликов", []) if с.strip() and с.strip().lower() != "нет"]
    кикер = первый("Кикер")
    # Задача 10: раньше кикер сочинялся из «Для кого» — «Кикер» давно свой обязательный слот
    # (`прототип-поля-первого-экрана.md` § 1), просто заполнить_первый_экран его не читал.
    # Нет слота или явное «нет» — честно пусто, элемент вырезается целиком (см. ВЫРЕЗАТЬ["кикер"]).
    вторая_ссылка = первый("Вторая ссылка")
    вторая_ссылка_текст, _, вторая_ссылка_цель = вторая_ссылка.partition("→")
    цель_число = re.search(r"\d+", вторая_ссылка_цель) if вторая_ссылка.strip().lower() != "нет" else None
    return {"пресет": (шапка.get("Пресет") or "визитка").strip().lower(),
            "кикер": "" if кикер.lower() == "нет" else кикер,
            "заголовок": " ".join(слова[:-1]) if len(слова) > 1 else " ".join(слова),
            "акцент": слова[-1] if len(слова) > 1 else "", "подзаголовок": первый("Подзаголовок"),
            "пункты": [с.strip() for с in слоты.get("Список", []) if с.strip()][:3],
            "кнопка": первый("Кнопка").split("→")[0].strip() or "Написать",
            "цифры": цифры[:3],
            "знак": (верхняя_строка.get("знак") or [""])[0].strip(),
            "доверие_шапка": "" if доверие_шапки.lower() == "нет" else доверие_шапки,
            "доверие_шапка_кратко": "" if доверие_кратко.lower() == "нет" else доверие_кратко,
            "когда": "" if первый("Когда").lower() == "нет" else первый("Когда"),
            "регалии_имя": (регалии.get("имя") or [""])[0].strip(),
            "регалии_роль": (регалии.get("роль") or [""])[0].strip(),
            "регалии_опоры": [о.strip() for о in регалии.get("опора", []) if о.strip()],
            # Задача 10: строка доверия под кнопками (не путать с «доверие_шапка» выше) больше не
            # сочиняется константой «Ваш вопрос — ответ в тот же день» — источник только сама
            # работа: настоящая лицензия из профиля (см. заполнить_первый_экран) или, если её нет,
            # собственный текст автора в необязательном слоте «Мелкая строка»; нет ни того, ни
            # другого — строка снимается вовсе, а не изображает обещание, которого не давали.
            "мелкая_строка": "" if первый("Мелкая строка").split("·")[0].strip().lower() == "нет"
                              else первый("Мелкая строка").split("·")[0].strip(),
            # «Вторая ссылка» — необязательный слот лендинга («Текст → экран N»); нет слота, «нет»
            # или числа цели — вторая кнопка снимается, вместо подмены на зашитое «Подробнее» → 2.
            "вторая_ссылка_текст": вторая_ссылка_текст.strip() if цель_число else "",
            "вторая_ссылка_экран": цель_число.group(0) if цель_число else "",
            "чипы": чипы, "подписи_роликов": подписи_роликов, **_картинки(работа)}


def ярлык(текст: str, предел: int = ПРЕДЕЛ_ЯРЛЫКА) -> str:
    """Длинную строку прототипа — в короткий ярлык: сперва по первому разделителю («Сценарий →
    кадр → герой → монтаж» → «Сценарий»), если и после этого длинно — по границе слова до предела.
    Короткая строка возвращается как есть, ничего не дописываем и многоточий не ставим: чип — это
    ярлык, а обрезок с «…» в пилюле читается хуже, чем два слова. Одно слово длиннее предела тоже
    отдаём целиком — слово посреди себя не рубим, это читается как опечатка; про ширину такой
    пилюли скажет флаг «Плашка на картинке во всю ширину» (`флаги_дизайна.py`)."""
    строка = " ".join(текст.split())
    if len(строка) <= предел:
        return строка
    места = [м for м in (строка.find(з) for з in РАЗДЕЛИТЕЛИ_ЯРЛЫКА) if м > 0]
    if места:
        строка = строка[:min(места)].strip(" " + РАЗДЕЛИТЕЛИ_ЯРЛЫКА)
    if len(строка) <= предел:
        return строка
    итог = ""
    for слово in строка.split():
        if итог and len(итог) + 1 + len(слово) > предел:
            break
        итог = f"{итог} {слово}".strip()
    return (итог or строка[:предел]).strip(" " + РАЗДЕЛИТЕЛИ_ЯРЛЫКА)


def заполнить_первый_экран(шаблон: str, т: dict, данные: dict | None, папка_профиля: Path | None) -> str:
    """Рецепт + тексты прототипа → кусок: нет фото — силуэт; цифр < 2 — без списка; спутники и бейджи — цифры и строка доверия."""
    html = шаблон.replace("{{НОМЕР}}", "1")
    if not т["акцент"]:   # заголовок из одного слова: пустой <em> не оставляем
        html = ВЫРЕЗАТЬ["акцент"].sub("", html)
    if not т["кикер"]:   # задача 10: нет слота/«нет» — элемента нет вовсе, заголовок без дырки над собой
        html = ВЫРЕЗАТЬ["кикер"].sub("", html)
    цифры = т["цифры"]
    if len(цифры) < 2:
        html = ВЫРЕЗАТЬ["цифры"].sub("", html)
    else:
        html = ВЫРЕЗАТЬ["цифра"].sub(lambda с: "" if int(с.group(1)) > len(цифры) else с.group(0), html)
    сайт = данные.get("сайт") if isinstance(данные, dict) else None
    юр_блок = сайт.get("юр_блок") if isinstance(сайт, dict) else None
    лицензия = str(юр_блок.get("лицензия") or "").strip() if isinstance(юр_блок, dict) else ""
    # Задача 10: строка доверия под кнопками больше не сочиняется константой — реальная лицензия
    # из профиля, иначе собственный текст автора («Мелкая строка» прототипа), иначе пусто, и
    # тогда строка снимается целиком (ВЫРЕЗАТЬ["доверие_низ"] ниже) — обещания без подписи не даём.
    доверие = лицензия or т.get("мелкая_строка") or ""
    пункты = т["пункты"] or [т["подзаголовок"]]
    пункты = [пункты[н % len(пункты)] for н in range(3)]   # по кругу: рецепт ждёт ровно три
    # Спутник орбиты и бейдж товара несут только короткое доказательство — цифру с подписью, лицензию; пункт списка целиком
    # туда не лезет (ревью T6: 14 слов вылезали за карточку). Нет доказательства — спутник или бейдж убирается.
    артефакты = (цифры + [(доверие, "")] + [("", "")] * 4)[:4]
    адрес = str(сайт.get("адрес") or "").strip() if isinstance(сайт, dict) else ""
    значения = {"КИКЕР": т["кикер"], "ЗАГОЛОВОК": т["заголовок"], "АКЦЕНТ": т["акцент"],
                "ПОДЗАГОЛОВОК": т["подзаголовок"], "ФОТО": т["фото"] or СИЛУЭТ, "ФОТО_ТЕЛЕФОН": т.get("фото_телефон") or т["фото"] or СИЛУЭТ,
                "ЛИЦО": т.get("лицо") or "50,22", "ВИДЕО": т.get("видео") or "", "ВИДЕО_ТЕЛЕФОН": т.get("видео_телефон") or т.get("видео") or "",
                "ПОСТЕР": т.get("постер") or КАДР, "ПОСТЕР_ТЕЛЕФОН": т.get("постер_телефон") or т.get("постер") or КАДР,
                # Задача 10: реального адреса до публикации нет (§ 7-bis) — честная пометка вместо
                # похожего на настоящий домена «ваш-сайт.ru»; уже опубликован — берём сайт.адрес.
                "АДРЕС_МОКАПА": re.sub(r"^https?://", "", адрес).strip("/") or АДРЕС_МОКАПА_ПРИМЕР,
                "ПОДПИСЬ_ФОТО": " ".join(filter(None, (т["заголовок"], т["акцент"]))), "ДОВЕРИЕ": доверие,
                # Задача 10: текст и цель — из слота «Вторая ссылка» прототипа, не зашитое
                # «Подробнее» → экран 2; нет слота/цели — ВЫРЕЗАТЬ["вторая_ссылка"] снимет кнопку.
                "ВТОРАЯ_ССЫЛКА_ТЕКСТ": т.get("вторая_ссылка_текст") or "",
                "ВТОРАЯ_ССЫЛКА_ЭКРАН": т.get("вторая_ссылка_экран") or "",
                # Задача 6: знак — короткое имя дела в шапке, не личный логотип (правило «ничего
                # личного в ядре»); правая часть строки доверия — своя, не путать с {{ДОВЕРИЕ}} лицензии.
                "ЗНАК": т.get("знак") or "Ваше дело", "ДОВЕРИЕ_ШАПКИ": т.get("доверие_шапка") or "",
                "ДОВЕРИЕ_ШАПКИ_КОРОТКО": т.get("доверие_шапка_кратко") or "",
                "КОГДА": т.get("когда") or ""}
    if not значения["КОГДА"]:   # поле необязательное (§ 3) — пусто или «нет» → строки нет вовсе
        html = ВЫРЕЗАТЬ["когда"].sub("", html)
        html = ВЫРЕЗАТЬ["когда_карточка"].sub("", html)
    if not значения["ДОВЕРИЕ"]:   # задача 10: ни лицензии, ни своего текста — строки под кнопками нет вовсе
        html = ВЫРЕЗАТЬ["доверие_низ"].sub("", html)
    if not значения["ВТОРАЯ_ССЫЛКА_ТЕКСТ"] or not значения["ВТОРАЯ_ССЫЛКА_ЭКРАН"]:   # задача 10: без честной цели — кнопки нет
        html = ВЫРЕЗАТЬ["вторая_ссылка"].sub("", html)
    ролики = list(т.get("ролики") or [(значения["ВИДЕО"], значения["ПОСТЕР"])])   # контракт З: пять роликов по кругу
    # Задача 9: подпись — из прототипа (контракт § 6), не заглушка «Ролик N»; нечего сказать —
    # пусто, и рецепт сам оставляет только слово «ролик» без уточнения (чем заменить, если пусто).
    подписи_роликов = т.get("подписи_роликов") or []
    for н in range(1, 6):
        значения[f"РОЛИК_{н}"], значения[f"ПОСТЕР_{н}"] = ролики[(н - 1) % len(ролики)]
        значения[f"ПОДПИСЬ_РОЛИКА_{н}"] = подписи_роликов[н - 1] if н <= len(подписи_роликов) else ""
    for н in range(1, 4):
        значения[f"ПУНКТ_{н}"] = пункты[н - 1]
        значения[f"ЦИФРА_{н}"], значения[f"ПОДПИСЬ_ЦИФРЫ_{н}"] = (цифры + [("", "")] * 3)[н - 1]
    for н in range(1, 5):
        значения[f"АРТЕФАКТ_{н}"], значения[f"АРТЕФАКТ_ПОДПИСЬ_{н}"] = артефакты[н - 1]
    # Регалии (задача 2 § 3): нет имени — карточки автора и её мобильной замены нет вовсе.
    регалии_опоры = (т.get("регалии_опоры") or []) + ["", "", ""]
    значения["РЕГАЛИИ_ИМЯ"], значения["РЕГАЛИИ_РОЛЬ"] = т.get("регалии_имя") or "", т.get("регалии_роль") or ""
    for н in range(1, 4):
        значения[f"РЕГАЛИИ_ОПОРА_{н}"] = регалии_опоры[н - 1]
    if not значения["РЕГАЛИИ_ИМЯ"]:
        html = ВЫРЕЗАТЬ["регалии"].sub("", html)
        html = ВЫРЕЗАТЬ["чип_автор"].sub("", html)
    # Чипы (задача 2 § 4): контракт режет строку «заголовок · пояснение»; разворот просит один.
    чипы = т.get("чипы") or []
    # Фикс-раунд А: у схем-ярлыков (товар крупно, разворот) чип парит над фото и рамкой телефона —
    # пункт прототипа целиком раздувал его в плашку шириной в полкадра и клал на плечо и на грудь
    # («на человека не кладём ничего»). Контракт § 5 назвал предел, здесь — страховка вёрстки для
    # старых прототипов, написанных до него. Схемы-карточки (орбита, центр, живой портрет) не
    # трогаем: у их спутника пояснение живёт отдельной второй строкой.
    схема_рецепта = собрать.СХЕМА_СЕКЦИИ.search(шаблон)
    ярлыком = bool(схема_рецепта) and схема_рецепта.group(1) in СХЕМЫ_ЯРЛЫКА
    for н in range(1, 5):
        заголовок, _, пояснение = (чипы[н - 1].partition("·") if н <= len(чипы) else ("", "", ""))
        заголовок, пояснение = заголовок.strip(" —"), пояснение.strip()
        if ярлыком:
            заголовок, пояснение = ярлык(заголовок), ярлык(пояснение, ПРЕДЕЛ_ПОЯСНЕНИЯ)
        значения[f"ЧИП_{н}"], значения[f"ЧИП_ПОДПИСЬ_{н}"] = заголовок, пояснение
    if not чипы:
        html = ВЫРЕЗАТЬ["чип_ролик"].sub("", html)
    if not значения["ДОВЕРИЕ_ШАПКИ"]:
        html = ВЫРЕЗАТЬ["шапка_лиц"].sub("", html)
    elif not значения["ДОВЕРИЕ_ШАПКИ_КОРОТКО"]:   # доверие есть, короткой телефонной версии нет — снимаем только «.кратко»
        html = ВЫРЕЗАТЬ["шапка_лиц_кратко"].sub("", html)

    def замена(с: re.Match) -> str:
        if с.group(1) == "СВЯЗЬ":
            return собрать.начинка_связи(т["кнопка"], данные, папка_профиля)[0]
        if с.group(1) == "ИКОНКА":
            return с.group(0)   # иконки подставляет страница_варианта — толщиной из полей варианта
        return escape(значения.get(с.group(1), ""))

    html = re.sub(r"<span>\{\{((?:АРТЕФАКТ|ЧИП)_ПОДПИСЬ_\d)\}\}</span>", lambda с: с.group(0) if значения.get(с.group(1)) else "", html)   # спутник без подписи
    html = re.sub(r"<small>\{\{(ПОДПИСЬ_РОЛИКА_\d)\}\}</small>", lambda с: с.group(0) if значения.get(с.group(1)) else "", html)   # кадр мозаики без подписи — остаётся только «ролик»
    html = ВЫРЕЗАТЬ["артефакт"].sub(lambda с: с.group(0) if значения.get(с.group("плейс")) else "", html)   # спутник или бейдж без доказательства/чипа
    html = ВЫРЕЗАТЬ["цифры"].sub("", html) if "орбита__спутник" in шаблон else html   # живой портрет: цифры уже в спутниках — список под текстом не дублируем; задача 7 — орбита теперь на классе «спутник», её цифры остаются отдельным рядом (макет вариант-2, строка 163)
    return собрать.ПЛЕЙСХОЛДЕР.sub(замена, html)


def набор(пресет: str) -> str:
    """Пресет как имя набора схем и папки рецептов; чужой или пустой — «визитка». Одна нормализация на витрину и обложки."""
    return пресет if пресет in собрать.НАБОРЫ_СХЕМ else "визитка"


def _схема(вариант: dict, пресет: str) -> str:
    """Схема варианта из набора пресета; пустая или чужая — «разворот» (об этом скажет 🟡 из _про_схемы)."""
    схема = вариант.get("схема")
    return схема if схема in собрать.НАБОРЫ_СХЕМ.get(пресет, собрать.СХЕМЫ) else "разворот"


def _композиция(в: dict, пресет: str = "визитка") -> str:
    """Строка витрины: поля после нормализации — что реально показано, а не что написано (схема — из набора пресета)."""
    def поле(ключ: str, можно, иначе: str) -> str:
        return в[ключ] if в.get(ключ) in можно else иначе
    return " · ".join((поле("схема", собрать.НАБОРЫ_СХЕМ.get(пресет, собрать.СХЕМЫ), "разворот (взят по умолчанию)"),
                       поле("доминанта", собрать.ДОМИНАНТЫ, "как в рецепте"), поле("атмосфера", собрать.АТМОСФЕРЫ, "как в рецепте"),
                       "иконки " + поле("иконки", собрать.ТОЛЩИНЫ_ИКОНОК, "обычные")))


def страница_варианта(работа: Path, вариант: dict, т: dict, поиск: dict) -> str:
    """Рецепт схемы варианта + тексты прототипа + поля варианта → страница одного варианта."""
    пресет = набор(т["пресет"])
    шаблон = (собрать.БЛОКИ / пресет / f"01-первый-экран-{_схема(вариант, пресет)}.html").read_text(encoding="utf-8")
    данные, папка_профиля, _ = собрать._профиль(работа)
    кусок = собрать.применить_вариант(заполнить_первый_экран(шаблон, т, данные, папка_профиля), вариант)
    кусок, _ = собрать.подставить_иконки(кусок, собрать.ТОЛЩИНЫ_ИКОНОК.get(вариант.get("иконки", ""), "1.75"))
    основа = собрать.собрать_страницу(собрать.КАРКАС.read_text(encoding="utf-8"), "", [кусок], поиск, "")
    м = собрать.ГЛАВНАЯ_КНОПКА.search(основа)
    return перекрасить(собрать.скрипт_обложки(собрать.липкая_кнопка(основа, м.group(0) if м else "")), вариант["css"])   # «открыть живьём» — с обложка.js и звук.js


def _про_схемы(варианты: list[dict], пресет: str) -> list[dict]:
    """Без схемы из набора вариант идёт разворотом (🟡); две одинаковые — ℹ️: разница сведётся к цвету."""
    схемы = [_схема(в, пресет) for в in варианты]
    без = [f"вариант {в['номер']} — «{в.get('схема') or 'пусто'}» не из набора {пресет}, взят разворот"
           for в in варианты if в.get("схема") not in собрать.НАБОРЫ_СХЕМ[пресет]]
    найденное = [находка(ПОПРАВИТЬ, "Вариант без схемы первого экрана", без,
                         "выбирать надо между композициями, а не между цветами одной — впиши «Схема первого экрана» "
                         f"по ядро/дизайн-система.md, раздел 6; схемы набора: {', '.join(собрать.НАБОРЫ_СХЕМ[пресет])}")] if без else []
    повторы = sorted({с for с in схемы if схемы.count(с) > 1}, key=схемы.index)
    if повторы:
        найденное.append(находка(
            К_СВЕДЕНИЮ, "Два варианта с одной схемой",
            [f"«{с}» — варианты {', '.join(str(в['номер']) for в, своя in zip(варианты, схемы) if своя == с)}"
             for с in повторы],
            "Разница между ними на витрине сведётся к цвету и шрифту; одному из них — другую схему."))
    return найденное


def _снять(варианты: list[dict], папка: Path, браузер) -> None:
    """Каждый вариант в обоих размерах, одним браузером; страница открывается через file://."""
    for в in варианты:
        индекс = папка / f"вариант-{в['номер']}" / "index.html"
        for размер in глаза.РАЗМЕРЫ:
            with глаза.контекст(браузер, размер) as контекст:
                страница = контекст.new_page()
                страница.goto(индекс.as_uri(), wait_until="load", timeout=глаза.ТАЙМАУТ_ЗАГРУЗКИ_МС)
                страница.wait_for_timeout(600)   # шрифтам и картинкам — встать на место
                страница.screenshot(path=str(индекс.parent / f"{размер}.png"))


