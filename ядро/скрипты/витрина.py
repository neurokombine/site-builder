def витрина(работа: Path, куда: Path | None = None, браузер=None) -> tuple[Path, list[dict]]:
    """Папка работы → `витрина/` с первым экраном в каждом варианте и `витрина.html`; находки.
    При 🔴 не собираем ничего: путь возвращается, но файла по нему нет."""
    работа = Path(работа)
    папка = Path(куда) if куда else работа / "витрина"
    итог = папка / "витрина.html"
    найденное: list[dict] = []
    варианты = варианты_из(собрать.прочитать_дизайн(работа / "дизайн.md"))
    if len(варианты) < 2:
        найденное.append(находка(
            ЧИНИТЬ, "В дизайн.md меньше двух вариантов",
            [f"вариантов с css в «{работа / 'дизайн.md'}»: {len(варианты)} — две-три на выбор, не одна"],
            "выбирать не из чего, а без выбора глазами вид не принят — "
            "добавь варианты по ядро/дизайн-система.md, раздел 4"))
    elif len(варианты) > 3:
        найденное.append(находка(
            К_СВЕДЕНИЮ, "Вариантов больше трёх", [f"в «{работа / 'дизайн.md'}» их {len(варианты)}"],
            "Из двух-трёх человек выбирает уверенно; из пяти — устаёт и берёт первый попавшийся."))
    т = тексты_первого_экрана(работа)
    if т is None:
        найденное.append(находка(
            ЧИНИТЬ, "Нет первого экрана в прототипе",
            [f"в «{работа / 'прототип.md'}» нет экрана 1 — или нет самого файла"],
            "витрина строит первый экран из прототипа и рецепта — сначала шаг 4"))
    if есть_красное(найденное):
        return итог, найденное

    пресет = набор(т["пресет"])
    найденное += _про_схемы(варианты, пресет)
    поиск = собрать.прочитать_поиск(работа / "поиск.md")
    # про связь и профиль говорит собрать.py — витрина только про вид, её находки не дублируем
    for в in варианты:
        своя = папка / f"вариант-{в['номер']}"
        своя.mkdir(parents=True, exist_ok=True)
        (своя / "index.html").write_text(страница_варианта(работа, в, т, поиск), encoding="utf-8")
        (своя / "style.css").write_text(собрать._склейка_стилей(), encoding="utf-8")
        if (работа / "img").is_dir():   # картинки рядом со страницей, как в собранном сайте
            shutil.copytree(работа / "img", своя / "img", dirs_exist_ok=True)
        if (работа / "video").is_dir():
            shutil.copytree(работа / "video", своя / "video", dirs_exist_ok=True)
        if not т["фото"]:   # без картинки — силуэт: схема видна целиком, а не с дырой
            (своя / "img").mkdir(exist_ok=True)
            shutil.copyfile(ЗАГЛУШКИ / СИЛУЭТ, своя / "img" / СИЛУЭТ)
        if not т["постер"]:
            (своя / "video").mkdir(exist_ok=True)
            shutil.copyfile(ЗАГЛУШКИ / КАДР, своя / "video" / КАДР)
    if браузер is not None:
        _снять(варианты, папка, браузер)
    else:
        from playwright.sync_api import sync_playwright
        with sync_playwright() as playwright, глаза.запустить_браузер(playwright) as свой:
            _снять(варианты, папка, свой)
    итог.write_text(_страница_витрины(работа.name, варианты, пресет), encoding="utf-8")
    return итог, найденное


def построить_парсер() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(description="Первый экран прототипа в каждом варианте — рядом, на компьютере и телефоне.")
    p.add_argument("работа", help="папка работы: сайты/<имя>")
    p.add_argument("--без-показа", action="store_true", help="собрать витрину, браузер не открывать")
    return p


def main_с_аргументами(argv) -> int:
    аргументы = построить_парсер().parse_args(argv)
    работа = Path(аргументы.работа).expanduser().resolve()   # относительный путь ронял as_uri()
    if not работа.is_dir():
        print(f"Не нашёл папку работы «{аргументы.работа}». Нужна папка сайта целиком "
              "(сайты/<имя>), а не файл внутри неё.")
        return 2
    путь, найденное = витрина(работа)
    print(f"# Витрина: {работа.name}")
    print("\n".join(строки_по_уровням(найденное, заголовки_уровней("показа"))))
    if есть_красное(найденное):
        print("\nВитрину пока не собираю: сначала красное выше.")
        return код_выхода(найденное)
    print(f"\nВитрина {'собрана' if аргументы.без_показа else 'открыта'}: {путь}. "
          f"Выбор делает человек глазами, в обоих видах. {ЧТО_ДАЛЬШЕ}")
    if not аргументы.без_показа:
        webbrowser.open(путь.as_uri())
    return 0


def main() -> int:
    вывод_в_utf8()
    return main_с_аргументами(sys.argv[1:])


if __name__ == "__main__":
    sys.exit(main())
