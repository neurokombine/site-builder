import sys
import webbrowser
from datetime import datetime
from html import escape
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import глаза  # noqa: E402
import проверить_прототип  # noqa: E402
import собрать  # noqa: E402
from находки import (ЧИНИТЬ, ПОПРАВИТЬ, К_СВЕДЕНИЮ, вывод_в_utf8, есть_красное,  # noqa: E402
                     заголовки_уровней, код_выхода, находка, строки_по_уровням)

СТИЛЬ = re.compile(r"<style>.*?</style>", re.S)   # первый <style> страницы — токены каркаса
ШРИФТЫ_ИЗ_СЕТИ = re.compile(r"^[ \t]*<link [^\n]*fonts\.g(?:oogleapis|static)\.com[^\n]*\n", re.M)
ССЫЛКА_НА_СТИЛИ = '<link rel="stylesheet" href="style.css">'
ПРАВИЛО = "Выбор — глазами, в обоих видах; нажали — тот же прототип стал другой страницей"
ЧТО_ДАЛЬШЕ = "Выбранный вариант перепиши в `дизайн.md` → `## Решения` и запиши в журнал, почему"
# Тексты первого экрана — из прототипа (контракт Е): «6 лет занятий» → цифра «6», подпись «лет занятий».
ЧИСЛО = re.compile(r"^\s*(\d[\d\s.,%+×x]*?)\s+(.+)$")
ВЫРЕЗАТЬ = {"фото": re.compile(r'\s*<figure class="фото[^"]*">.*?</figure>', re.S),
            "цифры": re.compile(r'\s*<ul class="цифры">.*?</ul>', re.S)}
КАРТИНКИ = (".jpg", ".jpeg", ".png", ".webp", ".svg")
ДОВЕРИЕ_ПО_УМОЛЧАНИЮ = "Ваш вопрос — ответ в тот же день"   # пока в профиле нет лицензии; на витрине, не на сайте


def варианты_из(дизайн: dict) -> list[dict]:
    """Варианты, у которых есть css: без него показывать нечего. Пусто → []."""
    return [в for в in дизайн.get("варианты") or [] if (в.get("css") or "").strip()]


def перекрасить(html: str, css: str) -> str:
    """Та же страница в другом варианте: содержимое <style>…</style> каркаса → css варианта.
    Ссылка на шрифты — тоже под этот вариант: иначе свой шрифт не подгрузится, и человек выберет
    по системному, которого на сайте не будет."""
    страница = СТИЛЬ.sub(lambda _: f"<style>\n{css.strip()}\n</style>", html, count=1)
    страница = ШРИФТЫ_ИЗ_СЕТИ.sub("", страница)
    шрифты = собрать.ссылка_на_шрифты(css)
    if шрифты and ССЫЛКА_НА_СТИЛИ in страница:
        страница = страница.replace(ССЫЛКА_НА_СТИЛИ, шрифты + "\n" + ССЫЛКА_НА_СТИЛИ, 1)
    return страница


def тексты_первого_экрана(работа: Path) -> dict | None:
    """Экран 1 прототипа → тексты для рецепта первого экрана (контракт Е); нет прототипа/экрана — None."""
    файл = Path(работа) / "прототип.md"
    if not файл.is_file():
        return None
    прототипы = проверить_прототип.разобрать(файл.read_text(encoding="utf-8-sig"))
    if not прототипы or not прототипы[0]["экраны"]:
        return None
    шапка, экран = прототипы[0]["шапка"], прототипы[0]["экраны"][0]
    слоты = экран.get("слоты", {})

    def первый(имя: str) -> str:
        return (слоты.get(имя) or [""])[0].strip()

    цифры = []
    for кусок in re.split(r"[,·]", первый("Доказательство").split("источник:")[0]):
        м = ЧИСЛО.match(кусок)
        if м:
            цифры.append((м.group(1).strip(), м.group(2).strip()))
    слова = первый("Заголовок").split()
    папка_картинок = Path(работа) / "img"
    картинки = sorted(ф.name for ф in папка_картинок.glob("*") if ф.suffix.lower() in КАРТИНКИ) \
        if папка_картинок.is_dir() else []
    return {"пресет": (шапка.get("Пресет") or "визитка").strip().lower(),
            "кикер": " ".join((шапка.get("Для кого") or "").split()[:6]),
            "заголовок": " ".join(слова[:-1]) if len(слова) > 1 else " ".join(слова),
            "акцент": слова[-1] if len(слова) > 1 else "", "подзаголовок": первый("Подзаголовок"),
            "пункты": [с.strip() for с in слоты.get("Список", []) if с.strip()][:3],
            "кнопка": первый("Кнопка").split("→")[0].strip() or "Написать",
            "цифры": цифры[:3], "фото": картинки[0] if картинки else ""}


def заполнить_первый_экран(шаблон: str, т: dict, данные: dict | None, папка_профиля: Path | None) -> str:
    """Рецепт первого экрана + тексты прототипа → кусок страницы. Нет фото — фигура вырезана, цифр
    меньше трёх — вырезан их список: пустой слот на витрине читался бы как дыра, а не как выбор."""
    html = шаблон.replace("{{НОМЕР}}", "1")
    if not т["фото"]:
        html = ВЫРЕЗАТЬ["фото"].sub("", html)
    if len(т["цифры"]) < 3:
        html = ВЫРЕЗАТЬ["цифры"].sub("", html)
    сайт = данные.get("сайт") if isinstance(данные, dict) else None
    юр_блок = сайт.get("юр_блок") if isinstance(сайт, dict) else None
    лицензия = str(юр_блок.get("лицензия") or "").strip() if isinstance(юр_блок, dict) else ""
    пункты = т["пункты"] or [т["подзаголовок"]]
    пункты = [пункты[н % len(пункты)] for н in range(3)]   # по кругу: рецепт ждёт ровно три
    артефакты = [(" ".join(п.split()[:3]), " ".join(п.split()[3:])) for п in пункты] + [(т["кнопка"], т["кикер"])]
    значения = {"КИКЕР": т["кикер"], "ЗАГОЛОВОК": т["заголовок"], "АКЦЕНТ": т["акцент"],
                "ПОДЗАГОЛОВОК": т["подзаголовок"], "ФОТО": т["фото"],
                "ПОДПИСЬ_ФОТО": " ".join(filter(None, (т["заголовок"], т["акцент"]))),
                "ДОВЕРИЕ": лицензия or ДОВЕРИЕ_ПО_УМОЛЧАНИЮ,
                "ВТОРАЯ_ССЫЛКА_ТЕКСТ": "Подробнее", "ВТОРАЯ_ССЫЛКА_ЭКРАН": "2"}
    for н in range(1, 4):
        значения[f"ПУНКТ_{н}"] = пункты[н - 1]
        значения[f"ЦИФРА_{н}"], значения[f"ПОДПИСЬ_ЦИФРЫ_{н}"] = (т["цифры"] + [("", "")] * 3)[н - 1]
    for н in range(1, 5):
        значения[f"АРТЕФАКТ_{н}"], значения[f"АРТЕФАКТ_ПОДПИСЬ_{н}"] = артефакты[н - 1]

    def замена(с: re.Match) -> str:
        if с.group(1) == "СВЯЗЬ":
            return собрать.начинка_связи(т["кнопка"], данные, папка_профиля)[0]
        if с.group(1) == "ИКОНКА":
            return с.group(0)   # иконки подставляет страница_варианта — толщиной из полей варианта
        return escape(значения.get(с.group(1), ""))

    return собрать.ПЛЕЙСХОЛДЕР.sub(замена, html)


def страница_варианта(работа: Path, вариант: dict, т: dict, поиск: dict) -> str:
    """Рецепт концепции варианта + тексты прототипа + поля варианта → страница одного варианта."""
    концепция = вариант.get("концепция") if вариант.get("концепция") in собрать.КОНЦЕПЦИИ else "разворот"
    пресет = т["пресет"] if (собрать.БЛОКИ / т["пресет"]).is_dir() else "визитка"
    шаблон = (собрать.БЛОКИ / пресет / f"01-первый-экран-{концепция}.html").read_text(encoding="utf-8")
    данные, папка_профиля, _ = собрать._профиль(работа)
    кусок = собрать.применить_вариант(заполнить_первый_экран(шаблон, т, данные, папка_профиля), вариант)
    кусок, _ = собрать.подставить_иконки(кусок, собрать.ТОЛЩИНЫ_ИКОНОК.get(вариант.get("иконки", ""), "1.75"))
    основа = собрать.собрать_страницу(собрать.КАРКАС.read_text(encoding="utf-8"), "", [кусок], поиск, "")
    м = собрать.ГЛАВНАЯ_КНОПКА.search(основа)
    return перекрасить(собрать.липкая_кнопка(основа, м.group(0) if м else ""), вариант["css"])


def _про_концепции(варианты: list[dict]) -> list[dict]:
    """Без концепции вариант идёт разворотом (🟡); две одинаковые — ℹ️: разница сведётся к цвету."""
    концепции = [в["концепция"] if в.get("концепция") in собрать.КОНЦЕПЦИИ else "разворот" for в in варианты]
    найденное = []
    без = [str(в["номер"]) for в in варианты if в.get("концепция") not in собрать.КОНЦЕПЦИИ]
    if без:
        найденное.append(находка(
            ПОПРАВИТЬ, "Вариант без концепции первого экрана", [f"вариант {н} — взят разворот" for н in без],
            "выбирать надо между композициями, а не между цветами одной — впиши «Концепция первого "
            "экрана» по ядро/дизайн-система.md, раздел 6"))
    повторы = sorted({к for к in концепции if концепции.count(к) > 1}, key=концепции.index)
    if повторы:
        найденное.append(находка(
            К_СВЕДЕНИЮ, "Два варианта с одной концепцией",
            [f"«{к}» — варианты {', '.join(str(в['номер']) for в, своя in zip(варианты, концепции) if своя == к)}"
             for к in повторы],
            "Разница между ними на витрине сведётся к цвету и шрифту; одному из них — другую концепцию."))
    return найденное


def _снять(варианты: list[dict], папка: Path, браузер) -> None:
    """Каждый вариант в обоих размерах, одним браузером; страница открывается через file://."""
    for в in варианты:
        индекс = папка / f"вариант-{в['номер']}" / "index.html"
        for размер in глаза.РАЗМЕРЫ:
            with глаза.контекст(браузер, размер) as контекст:
                страница = контекст.new_page()
                страница.goto(индекс.as_uri(), wait_until="load", timeout=глаза.ТАЙМАУТ_ЗАГРУЗКИ_МС)
                страница.wait_for_timeout(600)   # шрифтам и картинкам — встать на место
                страница.screenshot(path=str(индекс.parent / f"{размер}.png"))


def _страница_витрины(имя: str, варианты: list[dict]) -> str:
    """Самодостаточная страница: по строке на вариант — имя, чем отличается, композиция, оба вида рядом."""
    когда = datetime.now(глаза.МСК).strftime("%d.%m.%Y, %H:%M")
    ряды = []
    for в in варианты:
        папка = f"вариант-{в['номер']}"
        картинки = "".join(
            f'<figure class="{размер}"><figcaption>{размер.capitalize()} '
            f'{глаза.РАЗМЕРЫ[размер]["viewport"]["width"]}</figcaption>'
            f'<img src="{папка}/{размер}.png" alt="Вариант {в["номер"]}: {размер}"></figure>'
            for размер in глаза.РАЗМЕРЫ)
        чем = escape(в.get("чем_отличается") or "")
        композиция = " · ".join((в.get("концепция") or "разворот (поле пусто)", в.get("доминанта") or "как в рецепте",
                                 в.get("атмосфера") or "как в рецепте", "иконки " + (в.get("иконки") or "1.75")))
        ряды.append(
            f'<section class="вариант">\n<h2>Вариант {в["номер"]}'
            f'{" · " + escape(в["имя"]) if в.get("имя") else ""}</h2>\n'
            f'<p class="чем">{"Чем отличается: " + чем if чем else "Чем отличается — в дизайн.md не сказано"}'
            f' · <a href="{папка}/index.html">открыть страницу</a></p>\n'
            f'<p class="чем">Композиция: {escape(композиция)}</p>\n'
            f'<div class="рядом">{картинки}</div>\n</section>')
    return f"""<!DOCTYPE html>
<html lang="ru">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Витрина: {escape(имя)}</title>
<style>
body {{ margin: 0; padding: 24px; font-family: system-ui, sans-serif; line-height: 1.5; }}
h1 {{ font-size: 22px; margin: 0 0 4px; }}  h2 {{ font-size: 18px; margin: 0 0 4px; }}
.когда {{ color: rgb(90, 95, 102); margin: 0 0 4px; }}  .правило {{ font-weight: 600; margin: 0 0 24px; }}
.вариант {{ padding: 24px 0; border-top: 1px solid rgb(200, 200, 200); }}  .чем {{ margin: 0 0 16px; }}
.рядом {{ display: flex; flex-wrap: wrap; gap: 24px; align-items: flex-start; }}
figure {{ margin: 0; flex: 1 1 320px; }}  figure.телефон {{ flex: 0 1 390px; }}
figcaption {{ font-weight: 600; margin-bottom: 8px; }}
img {{ width: 100%; height: auto; border: 1px solid rgb(200, 200, 200); }}
.дальше {{ margin: 24px 0 0; }}
</style>
</head>
<body>
<h1>Витрина: {escape(имя)} — вариантов {len(варианты)}</h1>
<p class="когда">Снято {когда} МСК</p>
<p class="правило">{ПРАВИЛО}</p>
{chr(10).join(ряды)}
<p class="дальше">{escape(ЧТО_ДАЛЬШЕ)}</p>
</body>
</html>
"""


def витрина(работа: Path, куда: Path | None = None, браузер=None) -> tuple[Path, list[dict]]:
    """Папка работы → `витрина/` с первым экраном в каждом варианте и `витрина.html`; находки.
    При 🔴 не собираем ничего: путь возвращается, но файла по нему нет."""
    работа = Path(работа)
    папка = Path(куда) if куда else работа / "витрина"
    итог = папка / "витрина.html"
    найденное: list[dict] = []
    варианты = варианты_из(собрать.прочитать_дизайн(работа / "дизайн.md"))
    if len(варианты) < 2:
        найденное.append(находка(
            ЧИНИТЬ, "В дизайн.md меньше двух вариантов",
            [f"вариантов с css в «{работа / 'дизайн.md'}»: {len(варианты)} — две-три на выбор, не одна"],
            "выбирать не из чего, а без выбора глазами вид не принят — "
            "добавь варианты по ядро/дизайн-система.md, раздел 4"))
    elif len(варианты) > 3:
        найденное.append(находка(
            К_СВЕДЕНИЮ, "Вариантов больше трёх", [f"в «{работа / 'дизайн.md'}» их {len(варианты)}"],
            "Из двух-трёх человек выбирает уверенно; из пяти — устаёт и берёт первый попавшийся."))
    т = тексты_первого_экрана(работа)
    if т is None:
        найденное.append(находка(
            ЧИНИТЬ, "Нет первого экрана в прототипе",
            [f"в «{работа / 'прототип.md'}» нет экрана 1 — или нет самого файла"],
            "витрина строит первый экран из прототипа и рецепта — сначала шаг 4"))
    if есть_красное(найденное):
        return итог, найденное

    найденное += _про_концепции(варианты)
    поиск = собрать.прочитать_поиск(работа / "поиск.md")
    # про связь и профиль говорит собрать.py — витрина только про вид, её находки не дублируем
    for в in варианты:
        своя = папка / f"вариант-{в['номер']}"
        своя.mkdir(parents=True, exist_ok=True)
        (своя / "index.html").write_text(страница_варианта(работа, в, т, поиск), encoding="utf-8")
        shutil.copyfile(собрать.СТИЛИ, своя / "style.css")
        if (работа / "img").is_dir():   # картинки рядом со страницей, как в собранном сайте
            shutil.copytree(работа / "img", своя / "img", dirs_exist_ok=True)
    if браузер is not None:
        _снять(варианты, папка, браузер)
    else:
        from playwright.sync_api import sync_playwright
        with sync_playwright() as playwright, глаза.запустить_браузер(playwright) as свой:
            _снять(варианты, папка, свой)
    итог.write_text(_страница_витрины(работа.name, варианты), encoding="utf-8")
    return итог, найденное


def построить_парсер() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(description="Показать первый экран прототипа в каждом варианте "
                                            "дизайн-системы — рядом, на компьютере и на телефоне.")
    p.add_argument("работа", help="папка работы: сайты/<имя>")
    p.add_argument("--без-показа", action="store_true", help="собрать витрину, браузер не открывать")
    return p


def main_с_аргументами(argv) -> int:
    аргументы = построить_парсер().parse_args(argv)
    работа = Path(аргументы.работа).expanduser().resolve()   # относительный путь ронял as_uri()
    if not работа.is_dir():
        print(f"Не нашёл папку работы «{аргументы.работа}». Нужна папка сайта целиком "
              "(сайты/<имя>), а не файл внутри неё.")
        return 2
    путь, найденное = витрина(работа)
    print(f"# Витрина: {работа.name}")
    print("\n".join(строки_по_уровням(найденное, заголовки_уровней("показа"))))
    if есть_красное(найденное):
        print("\nВитрину пока не собираю: сначала красное выше.")
        return код_выхода(найденное)
    print(f"\nВитрина {'собрана' if аргументы.без_показа else 'открыта'}: {путь}. "
          f"Выбор делает человек глазами, в обоих видах. {ЧТО_ДАЛЬШЕ}")
    if not аргументы.без_показа:
        webbrowser.open(путь.as_uri())
    return 0


