        "   уже завёл на этом запуске; нет его — сначала опубликовать.py <папка сайта> --завести <имя>",
        "   --выкладываем, иначе origin ляжет на репозиторий самой системы.",
        "3. Запустите опубликовать.py <папка сайта> --выкладываем ещё раз, уже без --завести —",
