"""Публикация: папка собранного сайта → своя полка на GitHub и живая ссылка через Pages.

Берёт `сайты/<имя>/сайт/` (результат `собрать.py`) и превращает её в отдельный git-репозиторий
на GitHub Pages: заводит полку, включает Pages, закрывает или открывает сайт поиску, отправляет
обновления, умеет откатить последний коммит. По умолчанию — сухой прогон: без `--выкладываем`
наружу не уходит ничего, даже если полка уже заведена.

⛔ Публикация — «страшное место»: без сети наружу ничего не уходит, пока человек явно не сказал
«выкладываем». Перед отправкой список того, что поедет, проверяется на личное (`что_уедет.py`).

Запуск:
    .venv/bin/python ядро/скрипты/опубликовать.py сайты/моё-дело/сайт                     # сухой прогон
    .venv/bin/python ядро/скрипты/опубликовать.py сайты/моё-дело/сайт --завести moyo-delo --выкладываем
    .venv/bin/python ядро/скрипты/опубликовать.py сайты/моё-дело/сайт --закрыть-от-поиска --выкладываем
    .venv/bin/python ядро/скрипты/опубликовать.py сайты/моё-дело/сайт --откати --выкладываем
    .venv/bin/python ядро/скрипты/опубликовать.py сайты/моё-дело/сайт --статус
"""
from __future__ import annotations

import argparse
import re
import shutil
import subprocess
import sys
import time
from datetime import datetime
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import глаза  # noqa: E402
import что_уедет  # noqa: E402
from находки import ЧИНИТЬ, вывод_в_utf8  # noqa: E402

ИМЯ_ПОЛКИ = re.compile(r"^[a-z0-9-]+$")
ОСТАЛОСЬ_СЕКУНД = 90
ПАУЗА_СЕКУНД = 5
МЕТА_РОБОТЫ = re.compile(r'(<meta\s+name="robots"\s+content=")([^"]*)("\s*/?>)')


def запустить(команда: list[str], cwd: Path | None = None) -> tuple[int, str]:
    """Одна точка выхода наружу — всё, что зовёт git и gh, проходит через неё. Тесты подменяют
    именно эту функцию, чтобы ни разу не дёрнуть настоящий gh."""
    готово = subprocess.run(команда, cwd=cwd, capture_output=True, text=True)
    return готово.returncode, готово.stdout + готово.stderr


def gh_есть() -> bool:
    return shutil.which("gh") is not None


def gh_вошёл() -> bool:
    код, _ = запустить(["gh", "auth", "status"])
    return код == 0


def репозиторий_есть(папка: Path) -> bool:
    return (Path(папка) / ".git").exists()


def завести_репозиторий(папка: Path) -> None:
    """`git init -b main`; на старом git без флага `-b` — `init` + `checkout -b main`.
    `.gitignore` закрывает системный мусор, `git add -A` и первый коммит «Первый экран»."""
    папка = Path(папка)
    код, _ = запустить(["git", "init", "-b", "main"], cwd=папка)
    if код != 0:
        запустить(["git", "init"], cwd=папка)
        запустить(["git", "checkout", "-b", "main"], cwd=папка)
    гитигнор = папка / ".gitignore"
    если_было = гитигнор.read_text(encoding="utf-8") if гитигнор.exists() else ""
    for строка in (".DS_Store", "Thumbs.db"):
        if строка not in если_было.split("\n"):
            если_было = (если_было.rstrip("\n") + "\n" + строка + "\n") if если_было.strip() else строка + "\n"
    гитигнор.write_text(если_было, encoding="utf-8")
    запустить(["git", "add", "-A"], cwd=папка)
    запустить(["git", "commit", "-m", "Первый экран"], cwd=папка)


def что_поедет(папка: Path) -> list[tuple[Path, list[str]]]:
    """Что реально уедет на полку по `git ls-files` (сохранённое и новое, кроме закрытого
    в .gitignore) — и для каждого файла причины, по которым он подозрителен (`что_уедет.py`).

    ⚠️ Своего репозитория у папки ещё нет (первый сухой прогон, до `завести_репозиторий`) —
    и папка при этом лежит внутри системы, у которой `сайты/*` целиком закрыт в её же
    `.gitignore` (`CLAUDE.md`): `git ls-files` честно находит родительский репозиторий и
    отдаёт пустой список, будто в папке пусто, хотя личные файлы там есть. Точно тот же
    случай уже разобран в `что_уедет.файлы_под_git` — здесь то же лечение: список пуст,
    а на диске файлы есть → считаем сами."""
    папка = Path(папка)
    код, вывод = запустить(
        ["git", "-c", "core.quotepath=false", "ls-files", "-c", "-o", "--exclude-standard"],
        cwd=папка,
    )
    имена = [с for с in вывод.split("\n") if с.strip()] if код == 0 else []
    файлы = [папка / имя for имя in имена]
    если_пусто_и_есть_на_диске = not файлы and any(
        п.is_file() and ".git" not in п.parts for п in папка.rglob("*")
    )
    if если_пусто_и_есть_на_диске:
        файлы = [
            п for п in папка.rglob("*")
            if п.is_file() and ".git" not in п.parts and "__pycache__" not in п.parts
        ]
    return [(ф, что_уедет.чем_опасен(ф, папка)) for ф in файлы]


def закрыт_ли(папка: Path) -> bool:
    """По meta robots в index.html: «noindex» — закрыт, иначе — открыт. Нет файла — считаем
    закрытым: пока нечего показать, лучше молчать перед поиском, чем звать его раньше времени."""
    файл = Path(папка) / "index.html"
    if not файл.is_file():
        return True
    совпадение = МЕТА_РОБОТЫ.search(файл.read_text(encoding="utf-8"))
    return "noindex" in совпадение.group(2).lower() if совпадение else True


def _переписать_поиск_и_robots(папка: Path, содержимое_robots: str, содержимое_meta: str,
                               статус: str) -> None:
    папка = Path(папка)
    индекс = папка / "index.html"
    if индекс.is_file():
        текст = индекс.read_text(encoding="utf-8")
        текст = МЕТА_РОБОТЫ.sub(rf'\g<1>{содержимое_meta}\g<3>', текст)
        индекс.write_text(текст, encoding="utf-8")
    (папка / "robots.txt").write_text(f"User-agent: *\n{содержимое_robots}\n", encoding="utf-8")
    поиск_md = папка.parent / "поиск.md"
    if поиск_md.is_file():
        текст = поиск_md.read_text(encoding="utf-8")
        новый, сколько = re.subn(r"(?m)^(-\s*Статус:\s*)\S+\s*$", rf"\g<1>{статус}", текст)
        поиск_md.write_text(новый if сколько else текст.rstrip("\n") + f"\n- Статус: {статус}\n",
                            encoding="utf-8")


def закрыть_от_поиска(папка: Path) -> None:
    _переписать_поиск_и_robots(папка, "Disallow: /", "noindex, nofollow", "закрыт")


def открыть_поиску(папка: Path) -> None:
    _переписать_поиск_и_robots(папка, "Allow: /", "index, follow", "открыт")


def отправить(папка: Path, сообщение: str) -> tuple[int, str]:
    """`git add -A`; коммит, если реально что-то изменилось; `push -u origin main`."""
    папка = Path(папка)
    запустить(["git", "add", "-A"], cwd=папка)
    код_статуса, вывод_статуса = запустить(["git", "status", "--porcelain"], cwd=папка)
    if вывод_статуса.strip():
        код_коммита, вывод_коммита = запустить(["git", "commit", "-m", сообщение], cwd=папка)
        if код_коммита != 0:
            return код_коммита, вывод_коммита
    return запустить(["git", "push", "-u", "origin", "main"], cwd=папка)


def владелец_и_имя(папка: Path) -> tuple[str, str]:
    """`git remote get-url origin` → (владелец, имя) для GitHub; не-GitHub адрес (в тестах —
    локальный путь до bare-репозитория) → пустая пара, полки на GitHub у неё нет."""
    код, вывод = запустить(["git", "remote", "get-url", "origin"], cwd=Path(папка))
    if код != 0:
        return "", ""
    адрес = вывод.strip()
    for шаблон in (
        r"^https://github\.com/([^/]+)/([^/]+?)(?:\.git)?/?$",
        r"^git@github\.com:([^/]+)/([^/]+?)(?:\.git)?/?$",
    ):
        совпадение = re.match(шаблон, адрес)
        if совпадение:
            return совпадение.group(1), совпадение.group(2)
    return "", ""


def завести_полку(папка: Path, имя: str) -> str:
    """`gh repo create <имя> --public --source=<папка> --push` → адрес полки на GitHub."""
    запустить(["gh", "repo", "create", имя, "--public", f"--source={папка}", "--push"], cwd=Path(папка))
    владелец, имя_полки = владелец_и_имя(папка)
    return f"https://github.com/{владелец}/{имя_полки}" if владелец else ""


def включить_pages(владелец: str, имя: str) -> str:
    """Включает Pages от ветки main, корень «/»; полка уже опубликована (409 / already exists) —
    просто читаем её адрес. Возвращает `html_url`, а нет его в ответе — собираем сами."""
    код, вывод = запустить([
        "gh", "api", "-X", "POST", f"repos/{владелец}/{имя}/pages",
        "-f", "source[branch]=main", "-f", "source[path]=/",
    ])
    if код != 0 and ("409" in вывод or "already exists" in вывод.lower()):
        код, вывод = запустить(["gh", "api", f"repos/{владелец}/{имя}/pages"])
    try:
        адрес = __import__("json").loads(вывод).get("html_url")
    except ValueError:
        адрес = None
    return адрес or f"https://{владелец}.github.io/{имя}/"


def состояние_pages(владелец: str, имя: str) -> str:
    """Статус последней сборки Pages: `building` / `built` / `errored`; неудача запроса
    (полка ещё не проиндексирована, сеть моргнула) — «неизвестно», а не падение."""
    код, вывод = запустить(["gh", "api", f"repos/{владелец}/{имя}/pages/builds/latest"])
    if код != 0:
        return "неизвестно"
    try:
        return __import__("json").loads(вывод).get("status") or "неизвестно"
    except ValueError:
        return "неизвестно"


def откатить(папка: Path) -> tuple[int, str]:
    """Отменяет последний коммит новым коммитом (историю не переписываем — полка уже публичная)
    и сразу отправляет отмену на полку."""
    папка = Path(папка)
    код, вывод = запустить(["git", "revert", "--no-edit", "HEAD"], cwd=папка)
    if код != 0:
        return код, вывод
    return запустить(["git", "push", "origin", "main"], cwd=папка)


def ручной_путь(имя: str) -> str:
    return "\n".join([
        "Без `gh` то же самое можно сделать руками:",
        f"1. На github.com создайте публичный репозиторий с именем «{имя}».",
        "2. В папке сайта: git remote add origin <адрес репозитория>",
        "3. git push -u origin main",
        "4. В репозитории откройте Settings → Pages → Source: Deploy from a branch →",
        "   ветка main, папка / (root) → Save.",
        f"5. Через минуту-две адрес будет https://<ваш-логин>.github.io/{имя}/",
    ])


def записать_в_журнал(папка: Path, строка: str) -> None:
    журнал = Path(папка).parent / "журнал.md"
    если_было = журнал.read_text(encoding="utf-8") if журнал.exists() else "# Журнал\n"
    когда = datetime.now(глаза.МСК).strftime("%d.%m.%Y %H:%M")
    журнал.write_text(если_было.rstrip("\n") + f"\n\n## {когда} МСК — {строка}\n", encoding="utf-8")


def _сообщение_обновления() -> str:
    return f"Обновление {datetime.now(глаза.МСК).strftime('%d.%m %H:%M')} МСК"


def _напечатать_что_поедет(папка: Path) -> list[tuple[Path, list[str]]]:
    список = что_поедет(папка)
    подозрительные = [(п, причины) for п, причины in список if причины]
    print(f"Поедет файлов: {len(список)}")
    for путь, причины in список:
        относительный = путь.relative_to(папка)
        if причины:
            print(f"   ⚠️ {относительный} — {', '.join(причины)}")
        else:
            print(f"   {относительный}")
    return подозрительные


def _статус_поиска_строкой(папка: Path) -> str:
    return "закрыт от поиска" if закрыт_ли(папка) else "открыт поиску"


def _подождать_pages(владелец: str, имя: str) -> None:
    прошло = 0
    while прошло < ОСТАЛОСЬ_СЕКУНД:
        if состояние_pages(владелец, имя) == "built":
            print()
            print("Страница собрана.")
            return
        print(".", end="", flush=True)
        time.sleep(ПАУЗА_СЕКУНД)
        прошло += ПАУЗА_СЕКУНД
    print()
    print("Ещё собирается — обычно минута-две, откройте адрес позже.")


def main_с_аргументами(argv) -> int:
    ap = argparse.ArgumentParser(description="Публикация папки сайта на GitHub Pages")
    ap.add_argument("папка", help="папка собранного сайта, сайты/<имя>/сайт")
    ap.add_argument("--завести", metavar="ИМЯ", help="завести новую полку на GitHub с этим именем")
    ap.add_argument("--выкладываем", action="store_true", help="без этого флага наружу не уходит ничего")
    ap.add_argument("--открыть-поиску", action="store_true")
    ap.add_argument("--закрыть-от-поиска", action="store_true")
    ap.add_argument("--откати", action="store_true", help="отменить последний коммит и отправить отмену")
    ap.add_argument("--статус", action="store_true", help="показать адрес, состояние Pages и статус поиска")
    args = ap.parse_args(argv)

    папка = Path(args.папка).expanduser().resolve()
    if not папка.is_dir() or not (папка / "index.html").is_file():
        print(f"⛔ Нет папки сайта с index.html: {папка}")
        return 2

    if args.статус:
        владелец, имя = владелец_и_имя(папка)
        код, лог = запустить(["git", "log", "-1", "--oneline"], cwd=папка)
        print(f"Папка: {папка}")
        print(f"Адрес: https://github.com/{владелец}/{имя}" if владелец else "Адрес: полки на GitHub ещё нет")
        if владелец:
            print(f"Pages: {состояние_pages(владелец, имя)}")
        print(f"Поиск: {_статус_поиска_строкой(папка)}")
        print(f"Последний коммит: {лог.strip() if код == 0 else 'коммитов ещё нет'}")
        return 0

    if args.откати:
        if not args.выкладываем:
            print("Откат меняет живую полку — добавьте --выкладываем, чтобы его отправить.")
            return 0
        код, вывод = откатить(папка)
        if код != 0:
            print("⛔ Откат не прошёл:")
            print(вывод)
            return 1
        записать_в_журнал(папка, "откат последнего обновления")
        print("Откат отправлен на полку.")
        return 0

    if not args.выкладываем:
        print(f"Папка: {папка}")
        print(f"Статус поиска: {_статус_поиска_строкой(папка)}")
        владелец, имя = владелец_и_имя(папка)
        print(f"Адрес: https://github.com/{владелец}/{имя}" if владелец else "Адрес: полки на GitHub ещё нет")
        print()
        print("Сухой прогон — ничего никуда не отправлено. Что поедет:")
        подозрительные = _напечатать_что_поедет(папка)
        if подозрительные:
            print()
            print("⚠️ Среди этого есть подозрительное — закройте в .gitignore или уберите из папки.")
        if args.открыть_поиску or args.закрыть_от_поиска:
            print()
            print("Флаги поиска без --выкладываем применены только на месте (файлы переписаны), "
                  "но никуда не отправлены.")
            (открыть_поиску if args.открыть_поиску else закрыть_от_поиска)(папка)
            print(f"Теперь статус поиска: {_статус_поиска_строкой(папка)}")
        print()
        print("Отправить — добавьте --выкладываем. Открыть поиску — --открыть-поиску (тоже с --выкладываем).")
        return 0

    if args.завести:
        if not ИМЯ_ПОЛКИ.match(args.завести):
            print(f"⛔ Имя «{args.завести}» не годится: имя станет частью адреса, "
                  "разрешены только латинские буквы, цифры и дефис.")
            return 2

    if not репозиторий_есть(папка):
        завести_репозиторий(папка)

    подозрительные = [(п, причины) for п, причины in что_поедет(папка) if причины]
    if подозрительные:
        print("⛔ Среди того, что поедет, есть подозрительное — не отправляю:")
        for путь, причины in подозрительные:
            print(f"   {ЧИНИТЬ} {путь.relative_to(папка)} — {', '.join(причины)}")
        print("Закройте эти файлы в .gitignore или уберите из папки и попробуйте снова.")
        return 1

    if args.завести:
        if not gh_есть():
            print("⛔ Для новой полки нужен `gh`, а его не нашлось.")
            print()
            print(ручной_путь(args.завести))
            return 3
        if not gh_вошёл():
            print("Сначала войдите: `gh auth login` — покажет одноразовый код, как в Сборщике документов.")
            return 3

    if args.открыть_поиску:
        открыть_поиску(папка)
    elif args.закрыть_от_поиска:
        закрыть_от_поиска(папка)

    if args.завести:
        адрес = завести_полку(папка, args.завести)
        владелец, имя = владелец_и_имя(папка)
        if not владелец:
            print(f"⛔ Не удалось завести полку «{args.завести}» на GitHub — имя может быть занято "
                  "или GitHub сейчас недоступен. Попробуйте другое имя или руками:")
            print()
            print(ручной_путь(args.завести))
            return 1
        адрес = включить_pages(владелец, имя)
        print("Полка заведена, включаю Pages", end="", flush=True)
        _подождать_pages(владелец, имя)
        записать_в_журнал(папка, f"опубликовано: {адрес}")
    else:
        код, вывод = отправить(папка, _сообщение_обновления())
        if код != 0:
            print("⛔ Отправка не прошла:")
            print(вывод)
            return 1
        владелец, имя = владелец_и_имя(папка)
        адрес = f"https://github.com/{владелец}/{имя}" if владелец else ""
        записать_в_журнал(папка, "обновление отправлено на полку")

    if args.открыть_поиску:
        записать_в_журнал(папка, "открыт поиску")
    elif args.закрыть_от_поиска:
        записать_в_журнал(папка, "закрыт от поиска")

    print()
    print(f"Адрес: {адрес}" if адрес else "Адрес: полки на GitHub нет — публиковали без --завести")
    print(f"Статус поиска: {_статус_поиска_строкой(папка)}")
    print("Живой адрес обновляется не мгновенно — несколько секунд-минут, это нормально.")
    return 0


