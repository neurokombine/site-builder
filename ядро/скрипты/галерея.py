def страница_каталога() -> str:
    """Весь каталог одной самодостаточной страницей — открывается файлом, без сервера."""
    когда = datetime.now(глаза.МСК).strftime("%d.%m.%Y, %H:%M")
    полки = [("Экраны ниже обложки", "экраны", ряды_примеров()),
             ("Страница целиком: три цветовые партитуры", "страницы", ряды_страниц())]
    тело = "\n".join(f'<h2 id="{якорь}">{заголовок} — {len(ряды)}</h2>\n' + "\n".join(ряды)
                     for заголовок, якорь, ряды in полки if ряды)
    тело += "\n" + строка_бренда()
    ссылки = " ".join(f'<a href="#{якорь}">{заголовок}</a>' for заголовок, якорь, ряды in полки if ряды)
    ссылки += ' <a href="#бренд">Бренд</a>' 
    return f"""<!DOCTYPE html>
<html lang="ru">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Галерея примеров</title>
<style>{СТИЛЬ}</style>
</head>
<body>
<h1>Галерея примеров и референсов</h1>
<p class="когда">Собрано {когда} МСК · пересобирается командой <code>галерея.py --каталог</code></p>
<p class="правило">{ПРАВИЛО}</p>
<p class="полки">{ссылки}</p>
{тело}
</body>
</html>
"""


def каталог() -> Path:
    КАТАЛОГ.write_text(страница_каталога(), encoding="utf-8")
    return КАТАЛОГ


def построить_парсер() -> argparse.ArgumentParser:
    парсер = argparse.ArgumentParser(description="Галерея примеров: снять примеры и собрать каталог")
    парсер.add_argument("--снять", action="store_true", help="пересобрать и переснять примеры рецептов")
    парсер.add_argument("--каталог", action="store_true", help="собрать ядро/галерея/каталог.html")
    парсер.add_argument("--только", default="", help="один пример («боль/лендинг») или один тип («боль»)")
    return парсер


def main_с_аргументами(argv) -> int:
    доводы = построить_парсер().parse_args(argv)
    if not (доводы.снять or доводы.каталог):
        построить_парсер().print_help()
        return 2
    if доводы.снять:
        отчёт = снять(не_пусто(доводы.только))
        без_текста = [с["пример"] for с in отчёт if с["без_текста"]]
        print(f"Снято примеров: {len(отчёт)}"
              + (f"; без части текстов: {', '.join(без_текста)}" if без_текста else ""))
    if доводы.каталог:
        print(f"Каталог собран: {каталог()}")
    return 0


def main() -> int:
    вывод_в_utf8()
    return main_с_аргументами(sys.argv[1:])


if __name__ == "__main__":
    raise SystemExit(main())
