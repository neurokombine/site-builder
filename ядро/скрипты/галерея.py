ПРОФИЛЬ_ОБРАЗЕЦ = КОРЕНЬ / "ядро" / "скрипты" / "tests" / "фикстуры" / "профиль-образец"

# Обложка примера нужна сборке (без первого экрана страницы не бывает), но в снимок не попадает:
# снимаем ровно ту секцию, ради которой пример лежит на полке. Схема — «разворот»: она есть в
# обоих наборах и ничего не требует от картинки, кроме заглушки.
СХЕМА_ОБЛОЖКИ = "разворот"
НОМЕР_ПРИМЕРА = 2
СЕКЦИЯ_ПРИМЕРА = f"#экран-{НОМЕР_ПРИМЕРА}"
СЛОТ = re.compile(r"\{\{([^}]+)\}\}")
СЕКЦИЯ_С_КЛАССАМИ = re.compile(r'<section class="([^"]*)"[^>]*id="экран-%d"' % НОМЕР_ПРИМЕРА)
# Ширина телефонного снимка в точках страницы: браузер снимает его с тройной плотностью (так его
# видит глаз на телефоне), а на полку он кладётся уменьшенным до ширины 390 — иначе каталог из
