ПЛОТНОСТЬ_ТЕЛЕФОНА = глаза.РАЗМЕРЫ["телефон"]["device_scale_factor"]
ЦВЕТОВ_В_СНИМКЕ = 256
ПРАВИЛО = ("Галерея — для глаз, а не для копирования: берём приём и детали, а не HTML целиком. "
           "Чужая раскладка собрана под чужой текст и под ваш не встанет.")


def описание(папка: Path) -> dict[str, str]:
    """`о-примере.md` (или `о-референсе.md`) → {поле: значение}; нет файла — пустой словарь."""
    файл = next((папка / имя for имя in ("о-примере.md", "о-референсе.md") if (папка / имя).is_file()), None)
    if not файл:
        return {}
    итог, ключ = {}, None
    for строка in файл.read_text(encoding="utf-8").splitlines():
        начало = re.match(r"- ([^:]+):(.*)$", строка)
        if начало:
            ключ = начало.group(1).strip()
            итог[ключ] = начало.group(2).strip()
        elif ключ and строка.strip():
            итог[ключ] += " " + строка.strip()
        elif not строка.strip():
            ключ = None
    return итог


def примеры_рецептов() -> list[tuple[str, str]]:
    """Все примеры экранов ниже обложки парами «тип, набор» — в порядке состава наборов."""
    итог = []
    for набор, типы in собрать.ТИПЫ_НАБОРА.items():
        итог += [(тип, набор) for тип in типы if (ПРИМЕРЫ / тип / набор / "экран.html").is_file()]
    return итог


def тексты() -> dict[str, dict[str, str]]:
    """Образцовые тексты примеров: `ядро/галерея/образец/тексты.json`, ключ — «тип/набор».

    Это тексты образцовой работы `ядро/галерея/образец/` — выдуманное дело (те же, что в
    образцовой работе фикстур тестов), а не чьи-то настоящие: примеры лежат в ядре, и личного
    в них нет и быть не может."""
    return json.loads((ОБРАЗЕЦ / "тексты.json").read_text(encoding="utf-8"))


def заполнить(шаблон: str, значения: dict[str, str]) -> tuple[str, list[str]]:
    """Рецепт примера + образцовые тексты → готовый экран и список слотов, которых не хватило.

    Слоты `{{СВЯЗЬ:…}}` и `{{ИКОНКА:…}}` не трогаем: их ставит сама сборка — первый из профиля
    работы, второй из набора иконок ядра."""
    нет: list[str] = []

    def замена(м: re.Match) -> str:
        имя = м.group(1)
        if имя.startswith(("СВЯЗЬ:", "ИКОНКА:")):
            return м.group(0)
        if имя == "НОМЕР":
            return str(НОМЕР_ПРИМЕРА)
        if имя not in значения:
            нет.append(имя)
            return м.group(0)
        return значения[имя]

    return СЛОТ.sub(замена, шаблон), sorted(set(нет))


def подготовить(тип: str, набор: str, значения: dict[str, str]) -> tuple[Path, list[str]]:
    """Временная работа под один пример: образцовая обвязка плюс два экрана. Возвращает папку."""
    папка = РАБОТЫ / f"{тип}-{набор}"
    if папка.exists():
        shutil.rmtree(папка)
    (папка / "экраны").mkdir(parents=True)
    for имя in ("дизайн.md", "прототип.md", "поиск.md"):
        shutil.copyfile(ОБРАЗЕЦ / имя, папка / имя)
    for имя in ("img", "video"):
        shutil.copytree(ОБРАЗЕЦ / имя, папка / имя)
    # Профиль ищется по имени из шапки прототипа — рядом с работой или в `профили/`. Кладём копию
    # образцового профиля рядом: чужой профиль в галерею не попадает даже случайно.
    исходный = ПРОФИЛЬ_ОБРАЗЕЦ / "profile.json"
    if not исходный.is_file():
        raise SystemExit(f"нет образцового профиля «{исходный}» — без него пример не собрать. "
                         "Он приезжает вместе с системой; верни файл из хранилища версий "
                         "или положи рядом любой profile.json с именем папки «профиль-образец».")
    цель_профиля = папка.parent / ПРОФИЛЬ_ОБРАЗЕЦ.name
    цель_профиля.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(исходный, цель_профиля / "profile.json")

    т = витрина.тексты_первого_экрана(папка)
    if not т:
        raise SystemExit(f"не читается образцовый прототип: {ОБРАЗЕЦ / 'прототип.md'}")
    рецепт = собрать.БЛОКИ / набор / f"01-первый-экран-{СХЕМА_ОБЛОЖКИ}.html"
    обложка = витрина.заполнить_первый_экран(рецепт.read_text(encoding="utf-8"),
                                             {**т, "пресет": набор}, None, None)
    (папка / "экраны" / "01-первый-экран.html").write_text(обложка, encoding="utf-8")
    готово, нет = заполнить((ПРИМЕРЫ / тип / набор / "экран.html").read_text(encoding="utf-8"), значения)
    (папка / "экраны" / f"0{НОМЕР_ПРИМЕРА}-{тип}.html").write_text(готово, encoding="utf-8")
    return папка, нет


def ключ_секции(страница: str) -> str:
    """Какой светлотой встала секция примера на собранной странице — светлый или тёмный.

    Роль рецепта (`ключ--основной|глубже|наоборот`) сама по себе цвета не знает: цвет ей даёт
    ключ всей страницы. Поэтому ключ примера читаем с готовой страницы, а не из рецепта."""
    м = СЕКЦИЯ_С_КЛАССАМИ.search(страница)
    классы = м.group(1).split() if м else []
    return "тёмный" if "тёмный" in классы else "светлый"


def положить_снимок(файл: Path, уменьшить_в: float = 1) -> None:
    """Снимок → на полку: телефонный уменьшается до ширины страницы, и оба — палитрой в 256 цветов.

    Две правки одного файла, и обе про вес. Снимок телефона браузер делает с тройной плотностью
    (так его видит глаз на телефоне) — на полке он нужен шириной 390. И любой снимок
    интерфейса — это несколько десятков цветов, растянутых на полный канал: палитра в 256 цветов
    режет вес вдесятеро и на глаз не отличается, а полка из полусотни снимков иначе весит больше
    всей остальной системы. Это витрина для глаз, а не исходник для печати.
    """
    from PIL import Image   # Pillow уже стоит (им же меряет цвета `обложка.py`)

    with Image.open(файл) as кадр:
        кадр = кадр.convert("RGB")
        if уменьшить_в > 1:
            кадр = кадр.resize((max(1, round(кадр.width / уменьшить_в)),
                                max(1, round(кадр.height / уменьшить_в))), Image.LANCZOS)
        кадр.quantize(colors=ЦВЕТОВ_В_СНИМКЕ, method=Image.FASTOCTREE,
                      dither=Image.Dither.FLOYDSTEINBERG).save(файл, optimize=True)


def снять_пример(браузер, тип: str, набор: str, индекс: Path) -> None:
    """Секция примера в двух размерах → `компьютер.png` и `телефон.png` рядом с рецептом."""
    куда = ПРИМЕРЫ / тип / набор
    for размер in глаза.РАЗМЕРЫ:
        with глаза.контекст(браузер, размер) as контекст:
            страница = контекст.new_page()
            страница.goto(индекс.as_uri(), wait_until="load", timeout=глаза.ТАЙМАУТ_ЗАГРУЗКИ_МС)
            флаги_дизайна.дождаться_страницы(страница, кадр_ролика=True)
            файл = куда / f"{размер}.png"
            страница.locator(СЕКЦИЯ_ПРИМЕРА).screenshot(path=str(файл))
    положить_снимок(куда / "компьютер.png")
    положить_снимок(куда / "телефон.png", ПЛОТНОСТЬ_ТЕЛЕФОНА)


def снять(только: str | None = None) -> list[dict]:
    """Собрать и переснять примеры рецептов. Возвращает по строке отчёта на каждый."""
    значения = тексты()
    отчёт = []
    пары = [(т, н) for т, н in примеры_рецептов() if не_отсеян(т, н, только)]
    if not пары:
        raise SystemExit(f"под «{только}» не нашлось ни одного примера")
    from playwright.sync_api import sync_playwright   # тяжёлый импорт — только когда снимаем

    with sync_playwright() as playwright:
        браузер = глаза.запустить_браузер(playwright)
        try:
            for тип, набор in пары:
                папка, нет = подготовить(тип, набор, значения.get(f"{тип}/{набор}", {}))
                индекс, находки = собрать.собрать(папка)
                страница = индекс.read_text(encoding="utf-8")
                снять_пример(браузер, тип, набор, индекс)
                отчёт.append({"пример": f"{тип}/{набор}", "ключ": ключ_секции(страница),
                              "без_текста": нет, "находки": len(находки)})
                print(f"снят: {тип}/{набор} · ключ {отчёт[-1]['ключ']}"
                      + (f" · без текста: {', '.join(нет)}" if нет else ""))
        finally:
            браузер.close()
    return отчёт


def не_пусто(значение: str | None) -> str | None:
    """Пустая строка из командной строки — это «не задано», а не имя примера."""
    return значение or None


def не_отсеян(тип: str, набор: str, только: str | None) -> bool:
    """Отбор `--только`: имя примера целиком («боль/лендинг») или один тип («вопросы-ответы»)."""
    return не_пусто(только) is None or f"{тип}/{набор}" == только or тип == только


def карточка(заголовок: str, путь: str, снимки: list[str], строки: list[str]) -> str:
    """Один ряд каталога: снимки рядом, под ними — что хорошего и где это лежит."""
    картинки = "".join(
        f'<figure class="{"телефон" if "телефон" in снимок else "компьютер"}">'
        f'<a href="{снимок}" target="_blank" rel="noopener">'
        f'<img src="{снимок}" alt="{escape(заголовок)}" loading="lazy"></a></figure>'
        for снимок in снимки)
    текст = "".join(f"<p>{строка}</p>" for строка in строки)
    return (f'<article class="пример">\n<h3>{escape(заголовок)}</h3>\n'
            f'<div class="рядом">{картинки}</div>\n{текст}\n'
            f'<p class="путь"><code>{escape(путь)}</code></p>\n</article>')


def ряды_примеров() -> list[str]:
    """Полка рецептов по типам: снимок компьютера и телефона, «что хорошо», детали, путь."""
    ряды = []
    for тип, набор in примеры_рецептов():
        папка = ПРИМЕРЫ / тип / набор
        поля = описание(папка)
        путь = f"примеры/{тип}/{набор}"
        снимки = [f"{путь}/{имя}.png" for имя in ("компьютер", "телефон")
                  if (папка / f"{имя}.png").is_file()]
        строки = [f"<b>Что хорошо.</b> {escape(поля.get('Что хорошо', '—'))}",
                  f"<b>Детали.</b> <code>{escape(поля.get('Детали', '—'))}</code> · "
                  f"ключ {escape(поля.get('Ключ', '—'))} · {escape(поля.get('Откуда', '—'))}"]
        ряды.append(карточка(f"{тип} · {набор}", f"ядро/галерея/{путь}", снимки, строки))
    return ряды


def ряды_страниц() -> list[str]:
    """Полка страниц целиком: три цветовые партитуры, снимки по экранам."""
    ряды = []
    for папка in sorted(п for п in СТРАНИЦА_ЦЕЛИКОМ.iterdir() if п.is_dir()):
        поля = описание(папка)
        путь = f"примеры/страница-целиком/{папка.name}"
        снимки = [f"{путь}/{ф.name}" for ф in sorted(папка.glob("*.png"))]
        строки = [f"<b>Партитура.</b> {escape(поля.get('Партитура', '—'))}",
                  f"<b>Выбор владелицы.</b> {escape(поля.get('Выбор владелицы', '—'))}",
                  f'<a href="{путь}/страница.html" target="_blank" rel="noopener">открыть страницу целиком</a>']
        ряды.append(карточка(папка.name, f"ядро/галерея/{путь}", снимки, строки))
    return ряды


def строка_бренда() -> str:
    """Полка бренда одной строкой — без снимков и без имён.

    Единственное место галереи, которое каталог не раскрывает. Снимки там сняты с живых страниц
    настоящего дела, и уже адрес папки — это имя владельца: в каталоге, который лежит в ядре и
    уезжает с системой, такому имени места нет (`test_личное.py`). Полка от этого не пропадает —
    её открывают папкой, разбор лежит в `о-референсе.md` рядом со снимками.
    """
    сколько = len([п for п in БРЕНД.iterdir() if п.is_dir()]) if БРЕНД.is_dir() else 0
    return (f'<h2 id="бренд">Бренд: живые страницы — {сколько}</h2>\n'
            '<article class="пример"><p>Снимки живых страниц целиком, на компьютере и на телефоне, — '
            'планка, до которой доводится собранное. В каталоге их нет: это чужие страницы с именами '
            'и цифрами, а каталог уезжает вместе с системой. Открывайте папкой — рядом с каждым '
            'снимком лежит <code>о-референсе.md</code>: что это, что берём, чего не берём.</p>\n'
            '<p class="путь"><code>ядро/галерея/бренд/</code></p></article>')


