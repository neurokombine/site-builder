#!/usr/bin/env python3
"""Галерея: собрать пример экрана, снять его в двух видах и сложить каталог для глаз.

Зачем она есть. Экран ниже обложки система больше не собирает по рецепту — его верстает
нейросеть свободно, по инструкции `ядро/экраны/<тип>.md`. Инструкция говорит словами, а
вёрстку показывают глазами: галерея и есть эта витрина приёмов. На полке три вещи —
примеры экранов (по одному на тип и набор), три цветовые партитуры целой страницы и
референсы бренда; про каждую рядом лежит описание, что в ней хорошего.

⛔ Галерея — не ядро вёрстки: этот файл не импортируют ни `собрать.py`, ни `проверить.py`
(сторож — `tests/test_галерея.py`), и ни один пример в собранную страницу не уезжает: его
открывают, смотрят и берут ПРИЁМ, а не HTML целиком. Единственное, что сборка отсюда читает, —
замороженный `примеры/стили-раскладок.css` (склейка стилей, `собрать.СТИЛИ`).

Как собирается пример. В `сайты/_галерея/<тип>-<набор>/` (папка временная, `сайты/*` в git не
входит) кладётся образцовая работа из `ядро/галерея/образец/` — дизайн-система, прототип,
служебная голова, картинка и ролик-заглушки, — плюс два экрана: обложка (рецепт «разворот» на
текстах образца) и сам пример с подставленными текстами из `образец/тексты.json`. Дальше работу
собирает обычная `собрать.собрать` — тем же кодом, каким собирается настоящий сайт, чтобы
снимок показывал то, что человек увидит у себя. Снимается ТОЛЬКО секция примера
(`#экран-2`), в двух размерах: 1440 и 390.

Запуск:
    .venv/bin/python ядро/скрипты/галерея.py --снять            # пересобрать и переснять все примеры
    .venv/bin/python ядро/скрипты/галерея.py --снять --только боль/лендинг
    .venv/bin/python ядро/скрипты/галерея.py --каталог          # собрать ядро/галерея/каталог.html
"""
