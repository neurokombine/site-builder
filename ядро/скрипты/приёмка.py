def слово_принято(итог: dict, работа, ответ: str) -> dict:
    """Слово человека про показанный кадр. Единственная дверь из папки ожидания в `img/` работы.

    • «беру» — кадр (а для схем с вырезом ещё и сам вырез) переезжает в `img/` работы, а промт со
      всеми поправками уходит строкой в журнал (`заказ.в_журнал`);
    • «другой, <что не так>» — фраза человека дописывается в промт отдельной строкой, и заказ
      возвращается готовым к новому прогону; кадр остаётся ждать и никуда не едет;
    • всё остальное — «не понял»: ничего не двигаем и переспрашиваем.

    Пока «беру» не сказано, ни один путь не кладёт кадр в `img/`. Функция ничего не рисует сама:
    новый прогон делает тот, у кого есть канал, — так решение человека и генерация остаются
    разными шагами.
    """
    работа = Path(работа)
    слово = " ".join(str(ответ or "").split())
    низ = слово.lower()
    заказ = dict(итог.get("заказ") or {})
    if низ.startswith(СЛОВО_БЕРУ):
        img = работа / "img"
        img.mkdir(parents=True, exist_ok=True)
        файлы = [Path(итог["файл"])]
        вырез = Path(итог.get("замеры", {}).get("силуэт_файл") or "")
        if заказ.get("тип") in обложка.СХЕМЫ_ВЫРЕЗА and вырез.is_file() and вырез != файлы[0]:
            файлы.append(вырез)
        переехали = []
        for файл in файлы:
            куда = img / файл.name
            shutil.copyfile(файл, куда)
            переехали.append(куда)
        заказ_журнала = _заказ_с_поправками(итог, заказ)
        журнал = заказы.в_журнал(работа, заказ_журнала) if заказ_журнала.get("промт") else None
        return {"решение": СЛОВО_БЕРУ, "фраза": "", "файлы": переехали, "файл": переехали[0],
                "журнал": журнал, "заказ": заказ_журнала,
                "что_дальше": f"кадр в «{img}»; промт и поправки — строкой в журнал работы"}
    if низ.startswith(СЛОВО_ДРУГОЙ):
        фраза = слово[len(СЛОВО_ДРУГОЙ):].lstrip(" ,:—–-").strip()
        новый = _заказ_с_поправками(итог, заказ)
        if фраза:
            строка = f"Поправка от человека: {фраза.rstrip('.')}."
            новый["строки"] = list(новый.get("строки") or []) + [
                {"строка": строка, "откуда": "слово человека на показе кадра — он смотрел кадр в схеме"}]
            новый["промт"] = "\n".join(с["строка"] for с in новый["строки"])
        return {"решение": СЛОВО_ДРУГОЙ, "фраза": фраза, "файлы": [], "файл": None,
                "журнал": None, "заказ": новый,
                "что_дальше": ("рисуем ещё раз этим промтом" if фраза else
                               "скажите одной фразой, что именно не так — без неё промт не поправить")}
    return {"решение": "не понял", "фраза": слово, "файлы": [], "файл": None, "журнал": None,
            "заказ": заказ,
            "что_дальше": f"ответ — «{СЛОВО_БЕРУ}» или «{СЛОВО_ДРУГОЙ}, <что не так>»; "
                          f"пока слова нет, кадр ждёт и на страницу не идёт"}


def ставим_сами(заказ: dict, список: list[dict]) -> bool:
    """Ставит ли система этот кадр молча. Два условия сразу, и второго без первого не бывает:
    в кадре нет лица (фон, предмет, иллюстрация — их система ставит сама) И промахов не осталось.
    Лицо — всегда «нет»: его ставит только слово человека, и обойти это правило неоткуда."""
    if портрет.нужен_показ(заказ.get("схема", ""), заказ.get("тип", "")):
        return False
    return not список


def _заказ_с_поправками(итог: dict, заказ: dict) -> dict:
    """Заказ с тем промтом, которым кадр нарисован на самом деле: базовый плюс поправки приёмки.

    В журнал должно уехать то, что сработало, а не то, с чего начинали, — иначе следующий сайт
    начнётся с промта, который уже один раз промахнулся.
    """
    новый = dict(заказ)
    финальный = итог.get("промт") or заказ.get("промт", "")
    хвост = финальный[len(заказ.get("промт", "")):].strip()
    строки = list(заказ.get("строки") or [])
    if хвост:
        строки = строки + [{"строка": хвост,
                            "откуда": "поправка приёмки: замеры кадра против вилок заказа "
                                      "(`приёмка.поправка`)"}]
    новый["строки"] = строки
    новый["промт"] = финальный
    return новый


