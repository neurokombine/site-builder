def адрес(путь) -> str:
    """`file://…` для браузера — от АБСОЛЮТНОГО пути, всегда.

    Папку работы человек задаёт относительно («сайты/<имя>» — так во всей документации системы и
    так же зовут соседние скрипты), и относительный путь `Path.as_uri()` не переводит вовсе: он
    падает `ValueError` в лицо человеку ровно в тот момент, когда всё уже посчитано и витрина
    собрана. Одно место на все три открывания, чтобы это не вернулось.
    """
    return Path(путь).resolve().as_uri()


def _ссылка(файл: Path, откуда: Path) -> str:
    """Путь к файлу относительно страницы показа — чтобы витрина открывалась и без копий."""
    try:
        return os.path.relpath(Path(файл).resolve(), Path(откуда).resolve()).replace(os.sep, "/")
    except ValueError:   # разные диски на Windows: относительного пути между ними не бывает
        return адрес(файл)


