def _светлота_страницы(работа: Path | None, ключ: str) -> float | None:
    """Светлота фона той стороны страницы, куда ляжет кадр, — из палитры профиля работы."""
    if not работа:
        return None
    import собрать  # noqa: E402
    данные, _, _ = собрать._профиль(Path(работа))
    палитра = (данные or {}).get("палитра") if isinstance(данные, dict) else None
    return заказы.светлота_ключа(палитра, ключ)


def _заказ_для_кадра(работа: Path | None, схема: str, ключ: str) -> tuple[dict, list[dict]]:
    """Заказ, под который меряется кадр: из работы целиком или из схемы с ключом на голом месте."""
    if работа:
        return заказы.заказ_для_сайта(Path(работа), схема=схема, ключ=ключ)
    if not схема:
        return {}, [находка(ЧИНИТЬ, "Не сказано, под какую схему мерить",
                            ["нет ни --работа, ни --схема"],
                            "вилка крупности, пропорция и вид кадра — свойства схемы: без неё мерить не по чему")]
    return заказы.собрать_промт(схема, ключ or "тёмный", что_в_кадре="кадр на приёмку"), []


def нарисовать_и_принять(заказ: dict, куда, *, работа=None, попыток: int = ПОПЫТОК, имя: str = "kadr",
                         светлота_фона: float | None = None, без_показа: bool = False,
                         рисует=None, мерит=None, печатать=print) -> dict:
    """Весь путь одним вызовом: нарисовать с поправками → принять → показать или поставить.

    Один вход и для команды `приёмка.py --нарисуй`, и для `заказ.py --нарисуй`: путь после
    генерации обязан быть один, иначе кадр начнёт попадать на страницу мимо замеров — ровно то,
    ради чего задача и делалась.

    К итогу `добиться_кадра` добавляются два поля: `показ` — страница, которая ждёт слова человека
    (у портрета), и `поставлено` — файлы, которые система поставила сама (у фона, предмета и
    иллюстрации, и только когда промахов не осталось).
    """
    куда = Path(куда)
    итог = добиться_кадра(заказ, куда, попыток=попыток, рисует=рисует, мерит=мерит, имя=имя,
                          светлота_фона=светлота_фона)
    итог["показ"], итог["поставлено"] = None, []
    _записать_итог(куда / "итог.json", итог)
    if портрет.нужен_показ(заказ.get("схема", ""), заказ.get("тип", "")):
        итог["показ"] = витрина_портрета(итог, куда, работа=работа)
        печатать(f"\nКадр ждёт вашего слова: {итог['показ']}")
        печатать(f"Ответ: {портрет.СЛОВО_ЧЕЛОВЕКА}.")
        печатать(f"Сказать так: .venv/bin/python ядро/скрипты/приёмка.py "
                 f"--работа {работа or '<работа>'} --слово «беру»")
        if not без_показа:
            webbrowser.open(адрес(итог["показ"]))
    elif работа and ставим_сами(заказ, итог["промахи"]):
        ответ = слово_принято(итог, работа, СЛОВО_БЕРУ)
        итог["поставлено"] = ответ["файлы"]
        печатать(f"\nПромахов нет — ставлю сама: {', '.join(str(ф) for ф in ответ['файлы'])}")
    elif итог["промахи"]:
        печатать(f"\nСама не ставлю: промахи выше остались, кадр ждёт в «{куда}». "
                 "Скажите, рисовать ещё раз или брать как есть.")
    return итог


