def main_с_аргументами(argv) -> int:
    вывод_в_utf8()
    а = построить_парсер().parse_args(argv)
    работа = Path(а.работа) if а.работа else None
    if работа and not работа.is_dir():
        print(f"❌ нет папки работы «{работа}»")
        return 2
    # Папка ожидания: у работы — своя, рядом с витриной; без работы — рядом с самим кадром, чтобы
    # приёмка чужого файла не оставляла папок там, откуда её случайно запустили.
    куда = (Path(а.куда) if а.куда else
            работа / "витрина" / ЖДЁТ if работа else
            Path(а.кадр).resolve().parent / ЖДЁТ if а.кадр else Path.cwd() / ЖДЁТ)

    # Слово человека приходит следующей командой и заказа заново не просит: всё, что нужно, лежит
    # в итоге прошлого прогона. Собирать промт второй раз значило бы требовать прототип там, где
    # человек просто отвечает «беру».
    if а.слово:
        память = куда / "итог.json"
        if not память.is_file():
            print(f"❌ нечего принимать: не нашёл «{память}». Сперва нарисуйте кадр (--нарисуй).")
            return 2
        итог = _прочитать_итог(память)
        ответ = слово_принято(итог, работа or Path.cwd(), а.слово)
        print(f"Слово: {ответ['решение']} — {ответ['что_дальше']}")
        for файл in ответ["файлы"]:
            print(f"  • {файл}")
        if ответ["решение"] == СЛОВО_ДРУГОЙ and ответ["фраза"]:
            print("\nНовый промт:\n" + ответ["заказ"]["промт"])
        return 0 if ответ["решение"] == СЛОВО_БЕРУ else 1

    заказ, найденное = _заказ_для_кадра(работа, а.схема, а.ключ)
    if найденное:
        for строка in строки_по_уровням(найденное, заголовки_уровней("показа")):
            print(строка)
    if not заказ.get("промт"):
        print("\nМерить не по чему: заказ не собрался.")
        return 2
    светлота = _светлота_страницы(работа, заказ.get("ключ", "тёмный"))

    if а.нарисуй:
        # Что сказать про показ и постановку, копим и печатаем ПОСЛЕ замеров: человек сперва
        # должен увидеть числа, а потом — что с кадром стало.
        сказанное: list[str] = []
        try:
            итог = нарисовать_и_принять(заказ, куда, работа=работа, попыток=а.попыток, имя=а.имя,
                                        светлота_фона=светлота, без_показа=а.без_показа,
                                        печатать=сказанное.append)
        except кисть.БедаКисти as беда:
            print(f"❌ канал: {беда}")
            return 2
        except ЛицоБезСлова as беда:
            print(f"❌ {беда}")
            return 2
        _напечатать(итог, итог["промахи"])
        if итог.get("беда"):
            print(f"\n❌ канал: {итог['беда']}")
        for строка in сказанное:
            print(строка)
        return 2 if итог.get("беда") else (1 if итог["промахи"] else 0)
    else:
        if not а.кадр:
            print("❌ нечего мерить: дайте файл кадра или --нарисуй")
            return 2
        файл = Path(а.кадр)
        if not файл.is_file():
            print(f"❌ нет файла «{файл}»")
            return 2
        замеры = померить(файл, заказ, светлота_фона=светлота)
        итог = {"файл": файл, "замеры": замеры, "промахи": промахи(замеры, заказ), "попыток": 0,
                "попытки": [], "чем_нарисовано": {}, "промт": заказ.get("промт", ""),
                "заказ": заказ, "беда": ""}

    # Путь «померить чужой файл»: ничего не рисуем и никуда не кладём — только числа и слова.
    _напечатать(итог, итог["промахи"])
    if портрет.нужен_показ(заказ.get("схема", ""), заказ.get("тип", "")):
        путь = витрина_портрета(итог, куда, работа=работа)
        print(f"\nКадр ждёт вашего слова: {путь}")
        print(f"Ответ: {портрет.СЛОВО_ЧЕЛОВЕКА}.")
        if not а.без_показа:
            webbrowser.open(адрес(путь))
    return 1 if итог["промахи"] else 0


def _записать_итог(путь: Path, итог: dict) -> Path:
    """Итог прогона на диск, чтобы слово человека можно было сказать следующей командой.
    Пути — строками, попытки — без замеров: файл читает человек, а не только скрипт."""
    свой = {"файл": str(итог["файл"]), "промт": итог.get("промт", ""),
            "попыток": итог.get("попыток", 0), "беда": итог.get("беда", ""),
            "замеры": json.loads(json.dumps(итог.get("замеры", {}), default=str)),
            "промахи": итог.get("промахи", []),
            "чем_нарисовано": json.loads(json.dumps(итог.get("чем_нарисовано", {}), default=str)),
            "заказ": итог.get("заказ", {})}
    путь.write_text(json.dumps(свой, ensure_ascii=False, indent=2), encoding="utf-8")
    return путь


def _прочитать_итог(путь: Path) -> dict:
    свой = json.loads(Path(путь).read_text(encoding="utf-8"))
    свой["файл"] = Path(свой["файл"])
    return свой


