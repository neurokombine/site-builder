"""Приёмка кадра: годится ли нарисованное под этот заказ — и если нет, что сказать генератору.

Три задачи до этой научили систему **просить** кадр: канал до генератора (`кисть.py`), промт из
замеров схемы (`заказ.py`), каноны портрета из профиля (`портрет.py`). Два живых прогона показали
одно и то же: фон, формат и одежду генератор выполняет точно, а **композицию держит «около»** —
голова на 23 % при просимых 30–45 %, на 29 % при просимых 30–37 %, воздух над макушкой 5 % при
просимых 6 %. Кадр не той крупности молча ложился на страницу, и дальше под него чинилась вёрстка
— ровно та беда, из-за которой вся линия и затевалась.

Отсюда правило, которое исполняет этот модуль: **сгенерированный кадр проходит те же замеры, что
и принесённый.** Не попал в вилку — система переспрашивает генератор сама, с поправкой в числах и
в ту же сторону, а не ставит кадр молча и не просит «сделать лучше».

Второе правило — владелицы, от 13.09.2026: **портрет ставится только по слову человека.** Фон,
предмет и иллюстрацию система ставит сама; лицо — показывает и ждёт. Здесь это не напоминание в
комментарии, а устройство: кадр рисуется в отдельную папку ожидания, а в `img/` работы его
переносит ровно одна функция — `слово_принято`, и только по слову «беру». Попытка рисовать сразу
в `img/` под портретный заказ кончается отказом (`ЛицоБезСлова`), а не тихим файлом на странице.

**Замеры не переписаны заново.** Крупность, посадка, кайма, фон съёмки, светлота под текстом и вид
кадра меряются теми же функциями `обложка.py`, которыми система меряет кадр, принесённый человеком:
контракт один, просто читается он теперь с двух сторон — `заказ.py` им просит, `приёмка.py` им
принимает.

**Фотографию система режет сама, чтобы померить.** Генератор отдаёт снимок на ровном фоне, а не
PNG с прозрачностью: крупность головы, воздух над макушкой и кайму видно только по силуэту.
Поэтому под замер делается черновой вырез (`обложка.вырез`, папка `.замеры` рядом с кадром) — тот
же самый, который потом ляжет в схему с вырезом. Нечем резать (нет `rembg`) — говорим словами, что
крупность здесь не измерима, и не молчим.

Команды:

    .venv/bin/python ядро/скрипты/приёмка.py <кадр> --схема орбита --ключ светлый [--работа сайты/<имя>]
    .venv/bin/python ядро/скрипты/приёмка.py --работа сайты/<имя> --нарисуй [--попыток 3]
    .venv/bin/python ядро/скрипты/приёмка.py --работа сайты/<имя> --слово "беру"
    .venv/bin/python ядро/скрипты/приёмка.py --работа сайты/<имя> --слово "другой, лицо слишком крупно"

Коды возврата: 0 — кадр годится · 1 — есть промахи · 2 — беда канала (повторить или войти руками).
"""
