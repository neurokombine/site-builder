# Имя профиля становится именем папки внутри `профили/` — и потому его нельзя брать как есть.
СЛОВА_ОБ_ИМЕНИ = ("В имени профиля — только буквы, цифры, дефис и пробел; "
                  "без косых черт и без подчёркивания в начале.")


class ОшибкаПрофиля(Exception):
    """Профиль не читается или не проходит проверку — сообщение уже человеческое."""


def имя_допустимо(имя: str | None) -> str | None:
    """Годится ли это в имя профиля. Ничего не нашли — None; нашли — фраза человеку.

    ⛔ Имя профиля — это имя папки, а не подпись. Косая черта уводит профиль в подпапку,
    которой `--список` не покажет; две точки уводят его ВЫШЕ папки `профили/` — а туда не
    достаёт `.gitignore`, и контакты клиента уезжают наружу первым же сохранением версии.
    Подчёркивание и точка в начале заняты служебным (`_шаблон`, `_активный`, скрытые файлы).
    """
    имя = (имя or "").strip()
    if not имя:
        return "Имя профиля не названо. " + СЛОВА_ОБ_ИМЕНИ
    if имя == "_шаблон":
        return ("«_шаблон» — это образец, из которого заводятся все остальные; "
                "работать в нём нельзя. " + СЛОВА_ОБ_ИМЕНИ)
    if "/" in имя or "\\" in имя or ".." in имя or имя.startswith(("_", ".")):
        return СЛОВА_ОБ_ИМЕНИ
    if not all(знак.isalnum() or знак in "- ." for знак in имя):
        return СЛОВА_ОБ_ИМЕНИ
    return None


# ── Чтение и запись ──────────────────────────────────────────────────────────────────────

def прочитать_json(путь: Path) -> dict:
    try:
        текст = путь.read_text(encoding="utf-8")
    except OSError as ошибка:
        raise ОшибкаПрофиля(f"не получилось прочитать «{путь}»: {ошибка}") from ошибка
    try:
        return json.loads(текст)
    except json.JSONDecodeError as ошибка:
        raise ОшибкаПрофиля(
            f"файл «{путь.name}» повреждён — не читается как JSON ({ошибка})"
        ) from ошибка


def записать_json(путь: Path, данные: dict) -> None:
    путь.write_text(json.dumps(данные, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


# ── Список и активный профиль ────────────────────────────────────────────────────────────

def список_профилей(папка_профилей: Path | None = None) -> list[str]:
    """Имена профилей (без служебных `_*`), у которых на месте profile.json."""
    папка = папка_профилей or ПРОФИЛИ
    if not папка.exists():
        return []
    return sorted(
        д.name for д in папка.iterdir()
        if д.is_dir() and not д.name.startswith("_") and (д / "profile.json").exists()
    )


def прочитать_активного(папка_профилей: Path | None = None) -> str | None:
    """Имя активного профиля. Указатель ведёт в никуда — считаем, что активного нет.

    Папку профиля переименовывают и удаляют руками, а указатель об этом не знает. Падать из-за
    этого нельзя: работа встанет на ровном месте — говорим вслух и работаем дальше.
    """
    папка = папка_профилей or ПРОФИЛИ
    файл = папка / "_активный"
    if not файл.exists():
        return None
    имя = файл.read_text(encoding="utf-8").strip()
    if not имя:
        return None
    if not (папка / имя / "profile.json").exists():
        print(f"⚠️ Активным был профиль „{имя}“, но его папки больше нет — считаю, "
              "что активного профиля нет.")
        return None
    return имя


def записать_активного(имя: str, папка_профилей: Path | None = None) -> None:
    папка = папка_профилей or ПРОФИЛИ
    папка.mkdir(parents=True, exist_ok=True)
    (папка / "_активный").write_text(имя, encoding="utf-8")


def сделать_активным(имя: str, папка_профилей: Path | None = None) -> tuple[bool, str]:
    беда = имя_допустимо(имя)
    if беда:
        return False, беда
    имя = имя.strip()
    папка = папка_профилей or ПРОФИЛИ
    if имя not in список_профилей(папка):
        return False, f"Профиля „{имя}“ нет."
    записать_активного(имя, папка)
    return True, f"Работаем в профиле „{имя}“."


# ── Соседи ────────────────────────────────────────────────────────────────────────────────

def найти_соседей(корень: Path | None = None) -> list[dict]:
    """Ищет системы-соседи с профилями: папки-сёстры корня и их подпапки глубиной 1.

    Соседями считаем не по имени папки (у ученика Сборщик документов может называться как
    угодно), а по структуре: `<кандидат>/профили/<имя>/profile.json`.
    """
    свой_корень = корень or КОРЕНЬ
    родитель = свой_корень.parent
    находки: list[dict] = []
    if not родитель.exists():
        return находки

    try:
        сёстры = [
            п for п in родитель.iterdir()
            if п.is_dir() and п.name not in ПРОПУСКАЕМ and not п.name.startswith(".")
            and п.resolve() != свой_корень.resolve()
        ]
    except OSError:
        return находки

    кандидаты: list[Path] = []
    for сестра in сёстры:
        кандидаты.append(сестра)
        try:
            for вложенная in сестра.iterdir():
                if вложенная.is_dir() and вложенная.name not in ПРОПУСКАЕМ \
                        and not вложенная.name.startswith("."):
                    кандидаты.append(вложенная)
        except OSError:
            continue

    for кандидат in кандидаты:
        папка_профилей = кандидат / "профили"
        if not папка_профилей.is_dir():
            continue
        try:
            подпапки = sorted(папка_профилей.iterdir())
        except OSError:
            continue
        for подпапка in подпапки:
            if not подпапка.is_dir() or подпапка.name.startswith("_"):
                continue
            файл_профиля = подпапка / "profile.json"
            if not файл_профиля.exists():
                continue
            try:
                данные = прочитать_json(файл_профиля)
            except ОшибкаПрофиля:
                данные = {}
            автор = данные.get("автор") if isinstance(данные, dict) else None
            автор = автор if isinstance(автор, dict) else {}
            находки.append({
                "система": кандидат,
                "имя": подпапка.name,
                "путь": подпапка,
                "автор_имя": str(автор.get("имя") or "").strip(),
                "автор_роль": str(автор.get("роль") or "").strip(),
            })
    return находки


# ── Взять и завести ──────────────────────────────────────────────────────────────────────

def взять_профиль(
    источник: Path,
    имя: str | None = None,
    папка_профилей: Path | None = None,
    шаблон: Path | None = None,
) -> tuple[bool, str]:
    """Копирует profile.json (и активы/, если есть) из чужой папки профиля к нам.

    Отсутствующие ключи добираем из шаблона (секцию «сайт» и служебные подсказки) — старые
    поля источника не трогаем. `унаследован_из` всегда переписываем на реальный путь источника.
    """
    источник = Path(источник).expanduser().resolve()
    файл_источника = источник / "profile.json"
    if not файл_источника.exists():
        return False, f"В «{источник}» нет profile.json — это не папка профиля."

    имя = имя or источник.name
    беда = имя_допустимо(имя)
    if беда:
        return False, беда
    имя = имя.strip()
    папка = папка_профилей or ПРОФИЛИ
    целевая = папка / имя
    if целевая.exists():
        return False, (
            f"Профиль „{имя}“ уже есть — не перезаписываю его. "
            "Другое имя — флагом --как <имя>."
        )

    try:
        данные = прочитать_json(файл_источника)
    except ОшибкаПрофиля as ошибка:
        return False, f"Не получилось прочитать профиль-источник: {ошибка}"

    путь_шаблона = шаблон or ШАБЛОН
    if путь_шаблона.exists():
        try:
            шаблонные_данные = прочитать_json(путь_шаблона)
        except ОшибкаПрофиля:
            шаблонные_данные = {}
    else:
        шаблонные_данные = {}
    for ключ, значение in шаблонные_данные.items():
        данные.setdefault(ключ, значение)
    данные["унаследован_из"] = str(источник)

    целевая.mkdir(parents=True)
    записать_json(целевая / "profile.json", данные)

    активы_источника = источник / "активы"
    if активы_источника.is_dir():
        shutil.copytree(активы_источника, целевая / "активы")

    записать_активного(имя, папка)
    return True, (f"Взял профиль „{имя}“ из {источник} и сделал его активным; вернуть прежний — "
                  f"профиль.py <имя>. Запишите в журнал сайта, откуда он.")


def новый_профиль(
    имя: str,
    папка_профилей: Path | None = None,
    шаблон: Path | None = None,
) -> tuple[bool, str]:
    """Заводит пустой профиль из шаблона и делает его активным."""
    беда = имя_допустимо(имя)
    if беда:
        return False, беда
    имя = имя.strip()
    папка = папка_профилей or ПРОФИЛИ
    целевая = папка / имя
    if целевая.exists():
        return False, f"Профиль „{имя}“ уже есть — не перезаписываю его."

    путь_шаблона = шаблон or ШАБЛОН
    if not путь_шаблона.exists():
        return False, "Не нашёл шаблон профиля — профили/_шаблон/profile.json пропал."
    try:
        данные = прочитать_json(путь_шаблона)
    except ОшибкаПрофиля as ошибка:
        return False, f"Шаблон профиля повреждён: {ошибка}"
    данные["профиль"] = имя

    целевая.mkdir(parents=True)
    записать_json(целевая / "profile.json", данные)
    записать_активного(имя, папка)
    return True, f"Завёл новый профиль „{имя}“ — пустой, из шаблона. Теперь он активный."


