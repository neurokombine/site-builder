def _строка_соседа(находка: dict) -> str:
    детали = ", ".join(ч for ч in (находка["автор_имя"], находка["автор_роль"]) if ч)
    хвост = f" ({детали})" if детали else ""
    return f"Рядом нашёл: {находка['система'].name} — профиль „{находка['имя']}“{хвост}"


def _вывести_соседей() -> int:
    находки = найти_соседей()
