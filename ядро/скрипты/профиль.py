def _hls(hex_цвет: str) -> tuple[float, float, float]:
    r, g, b = (int(hex_цвет[i:i + 2], 16) / 255 for i in (1, 3, 5))
    return colorsys.rgb_to_hls(r, g, b)


def _из_hls(h: float, l: float, s: float) -> str:
    r, g, b = colorsys.hls_to_rgb(h % 1.0, min(max(l, 0.0), 1.0), min(max(s, 0.0), 1.0))
    return "#{:02X}{:02X}{:02X}".format(round(r * 255), round(g * 255), round(b * 255))


def _тёплая_кромка(градусов: float) -> float | None:
    """К какой кромке тёплого сектора поворачивать оттенок акцента — или `None`, если он уже внутри.

    Оттенки лежат на круге, поэтому «ближе» считаем по кратчайшей дуге, а не по разнице чисел:
    у красного акцента (352°) до 25° двадцать девять градусов, а не триста двадцать семь."""
    низ, верх = ТЁПЛЫЙ_СЕКТОР
    градусов %= 360
    def дуга(откуда: float, куда: float) -> float:
        д = (куда - откуда) % 360
        return д if д <= 180 else д - 360
    if низ <= градусов <= верх:
        return None
    return низ if abs(дуга(градусов, низ)) <= abs(дуга(градусов, верх)) else верх


def светимость(hex_цвет: str) -> float:
    """Относительная светимость по WCAG: линеаризуем sRGB-каналы и складываем с их весами.
    Формула — https://www.w3.org/TR/WCAG21/#dfn-relative-luminance."""
    r, g, b = (int(hex_цвет[i:i + 2], 16) / 255 for i in (1, 3, 5))

    def канал(c: float) -> float:
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4

    return 0.2126 * канал(r) + 0.7152 * канал(g) + 0.0722 * канал(b)


def контраст(цвет_1: str, цвет_2: str) -> float:
    """Контраст WCAG двух `#RRGGBB` — (светлее + .05) / (темнее + .05), от 1 до 21.

    Живёт здесь, а не в сборке: добор палитры сам меряет, видно ли посчитанный им цвет, а сборка
    зовёт профиль, не наоборот (обратный импорт замкнул бы круг)."""
    л1, л2 = светимость(цвет_1), светимость(цвет_2)
    л1, л2 = max(л1, л2), min(л1, л2)
    return (л1 + 0.05) / (л2 + 0.05)


def смесь(первый: str, доля: float, второй: str) -> str:
    """`color-mix(in srgb, первый <доля>%, второй)` — ровно то же число, что посчитал бы браузер.

    Роли палитры выводятся смесью, а не сдвигом светлоты: третья ступень тёмного — это первый
    тёмный, разведённый вторым, и её оттенок обязан лежать между ними, а не уехать в серое."""
    def канал(цвет: str, i: int) -> int:
        return int(цвет[1 + 2 * i:3 + 2 * i], 16)

    return "#" + "".join(
        f"{round(канал(первый, i) * доля + канал(второй, i) * (1 - доля)):02X}" for i in range(3))


def _сдвиг_светлоты(hex_цвет: str, дельта_процентов: float) -> str:
    """Тот же тон и та же насыщенность, светлота — на N процентных пунктов иначе.
    Механическая «ступень» — приём, которым уже считает тёплую тёмную ступень `собрать.py`."""
    h, l, s = _hls(hex_цвет)
    return _из_hls(h, l + дельта_процентов / 100, s)


def затемнить_до_контраста(цвет: str, фон: str, цель: float) -> str:
    """Тот же тон, темнее ровно настолько, чтобы цвет стало видно на этом фоне.

    Шаг — процент светлоты: мельче незачем, крупнее уводит цвет дальше нужного. Тем же приёмом
    сборка считает тёмную ступень тёплого цвета для текста на светлом фоне."""
    h, l, s = _hls(цвет)
    while l > 0:
        кандидат = _из_hls(h, l, s)
        if контраст(кандидат, фон) >= цель:
            return кандидат
        l -= 0.01
    return "#000000"   # предохранитель: при разумной палитре сюда не доходим


def добрать_палитру(палитра: dict | None) -> dict:
    """Семнадцать ролей полной палитры: что дано, что вывели (и из чего), что вывести не
    вышло — спросить у человека. Ничего не пишет на диск, только считает.

    Двенадцать ролей минимального комплекта человек даёт или система выводит ступенью светлоты;
    пять оставшихся (третий и четвёртый тёмный фон, два тона акцента, тихий текст) — смесь двух
    уже известных цветов. Останавливает по-прежнему только минимальный комплект: роль, которую
    не из чего смешать, молчит, потому что про её источник вопрос уже задан.

    Возврат: `{"полная": {...}, "выведено": [...], "не_вывелось": [...], "нужно_спросить": [...],
    "укомплектована": bool}`. Элемент «выведено» — `{"ключ", "из", "как"}`; «не_вывелось» —
    `{"ключ", "из"}` (роль, которую не из чего смешать: сам источник уже спрошен выше);
    «нужно_спросить» — `{"ключ", "почему"}`.
    """
    палитра = палитра if isinstance(палитра, dict) else {}
    полная = dict(палитра)
    выведено: list[dict] = []
    не_вывелось: list[dict] = []
    спросить: list[dict] = []

    def дано(ключ: str) -> bool:
        return bool(HEX.match(str(полная.get(ключ) or "")))

    def вывести(ключ: str, источник: str, дельта: float, как: str) -> None:
        if дано(ключ):
            return
        if not дано(источник):
            спросить.append({
                "ключ": ключ,
                "почему": f"обычно посчитал бы сам из «{источник}», а его тоже нет в палитре — "
                          f"впишите сначала его",
            })
            return
        полная[ключ] = _сдвиг_светлоты(полная[источник], дельта)
        выведено.append({"ключ": ключ, "из": источник, "как": как})

    # Опоры — спросить, если их нет; вывести их нельзя ни из чего.
    for опора, пояснение in ОПОРЫ_ПАЛИТРЫ.items():
        if not дано(опора):
            спросить.append({"ключ": опора, "почему": f"{пояснение} — это решение о бренде, "
                                                       "не арифметика, вывести не из чего"})

    # Второй фон — чуть иначе первого (светлый темнее, тёмный светлее: так во всех образцах).
    вывести("светлый_фон_2", "светлый_фон_1", -3.5,
            "чуть темнее «светлый_фон_1» (светлота −3.5%) — подложка карточки на общем фоне")
    вывести("тёмный_фон_2", "тёмный_фон_1", +3.5,
            "чуть светлее «тёмный_фон_1» (светлота +3.5%) — вторая точка градиента тёмного фона")

    # Ступени акцента — тон и насыщенность акцента, только светлее (задача 11: буквально
    # «ступени акцента — из основного»).
    вывести("акцент_средний", "акцент", +10,
            "тот же тон, что «акцент», но на 10% светлее — средняя ступень")
    вывести("акцент_яркий", "акцент", +20,
            "тот же тон, что «акцент», но на 20% светлее — яркая ступень")

    # Тёплый — из оттенка акцента: поворот к ближней кромке тёплого сектора (ТЁПЛЫЙ_СЕКТОР),
    # светлота 60 %, насыщенность акцента. Раньше оттенок был зашит числом, и зелёное дело
    # получало золотые галки и опоры — цвет чужого бренда в своей палитре. Теперь тёплый —
    # это родня акцента, повёрнутая в тёплую сторону ровно настолько, чтобы в неё попасть.
    if not дано("тёплый"):
        if not дано("акцент"):
            спросить.append({"ключ": "тёплый", "почему": "обычно посчитал бы сам из «акцент», "
                                                          "а его тоже нет в палитре — впишите сначала его"})
        else:
            h, _, s = _hls(полная["акцент"])
            кромка = _тёплая_кромка(h * 360)
            if кромка is None:
                спросить.append({
                    "ключ": "тёплый",
                    "почему": "акцент сам тёплого оттенка — выведенный «тёплый» вышел бы "
                              "почти таким же, а смысл тёплого в системе — отличаться от акцента; "
                              "выбор здесь не арифметика, а вкус — впишите его сами",
                })
            else:
                s = min(max(s, 0.20), 0.45)
                полная["тёплый"] = _из_hls(кромка / 360, ТЁПЛЫЙ_СВЕТЛОТА, s)
                выведено.append({
                    "ключ": "тёплый", "из": "акцент",
                    "как": f"оттенок «акцент» повёрнут к тёплому — до {кромка:g}° "
                           f"(ближняя кромка тёплого сектора {ТЁПЛЫЙ_СЕКТОР[0]:g}–{ТЁПЛЫЙ_СЕКТОР[1]:g}°); "
                           "светлота 60%, насыщенность взята у «акцент»",
                })

    вывести("тёплый_мягкий", "тёплый", +11,
            "тот же тон, что «тёплый», но на 11% светлее — смягчённый тёплый")

    # Мягкий текст — тот же приём смягчения, что и у тёплого: светлее в сторону фона.
    вывести("текст_мягкий", "текст", +19,
            "тот же тон, что «текст», но на 19% светлее — приглушённый текст")

    # Линия — из фона (задача 11 буквально); источник — светлый фон, второй, если первого нет.
    if not дано("линия"):
        источник_линии = "светлый_фон_1" if дано("светлый_фон_1") else (
            "светлый_фон_2" if дано("светлый_фон_2") else None)
        if источник_линии is None:
            спросить.append({"ключ": "линия", "почему": "обычно посчитал бы сам из «светлый_фон_1», "
                                                         "а фона в палитре нет вовсе — впишите сначала его"})
        else:
            полная["линия"] = _сдвиг_светлоты(полная[источник_линии], -10.5)
            выведено.append({
                "ключ": "линия", "из": источник_линии,
                "как": f"темнее «{источник_линии}» на 10.5% светлоты — едва заметная граница",
            })

    # ── Пять ролей сверх минимального комплекта (полная палитра — ПОЛНАЯ_ПАЛИТРА) ─────────
    # Каждая — смесь двух цветов, которые в палитре уже есть: своих или только что выведенных.
    # Нет одного из двух — роль не выводим и второй раз о том же не спрашиваем: про сам цвет
    # вопрос уже задан выше, а вердикт из пяти повторов человек читать не станет.
    def смешать(ключ: str, первый: str, доля: float, второй: str, как: str) -> None:
        if дано(ключ):
            return
        if not (дано(первый) and дано(второй)):
            нет = первый if not дано(первый) else второй
            не_вывелось.append({"ключ": ключ, "из": нет})
            return
        полная[ключ] = смесь(полная[первый], доля, полная[второй])
        выведено.append({"ключ": ключ, "из": первый, "как": как})

    смешать("тёмный_фон_3", "тёмный_фон_1", 0.60, "тёмный_фон_2",
            "смесь «тёмный_фон_1» 60% со вторым тёмным — ступень между ними: подвал, лента")
    смешать("тёмный_фон_4", "текст", 0.08, "тёмный_фон_1",
            "«тёмный_фон_1» с восемью процентами цвета текста — приглушённая тёмная плоскость: "
            "закрытые модули, низ градиента")

    # Две роли ложатся на светлый экран мелочью — кромкой, полосой, подписью под ценой, — и их
    # обязано быть видно. Бледную смесь система темнит до порога читаемости, а не отдаёт как есть.
    def смешать_читаемое(ключ: str, первый: str, доля: float, второй: str, как: str) -> None:
        if дано(ключ):
            return
        if not (дано(первый) and дано(второй)):
            не_вывелось.append({"ключ": ключ, "из": первый if not дано(первый) else второй})
            return
        цвет = смесь(полная[первый], доля, полная[второй])
        if дано("светлый_фон_1") and контраст(цвет, полная["светлый_фон_1"]) < ПОРОГ_ЧИТАЕМОСТИ:
            цвет = затемнить_до_контраста(цвет, полная["светлый_фон_1"], ПОРОГ_ЧИТАЕМОСТИ)
            как += ("; на светлом фоне эта смесь не читалась — дотемнил её до контраста "
                    + f"{ПОРОГ_ЧИТАЕМОСТИ}".replace(".", ","))
        полная[ключ] = цвет
        выведено.append({"ключ": ключ, "из": первый, "как": как})

    смешать_читаемое("акцент_глубже", "акцент", 0.55, "акцент_средний",
                     "смесь «акцент» 55% со средней ступенью — второй тон рядом с акцентом: "
                     "кромки, полосы, стекло")
    смешать("акцент_маркер", "акцент", 0.30, "акцент_средний",
            "смесь «акцент» 30% со средней ступенью — маркеры списков, номерки, узлы")
    смешать_читаемое("текст_тихий", "текст_мягкий", 0.55, "светлый_фон_1",
                     "смесь «текст_мягкий» 55% со светлым фоном профиля (не с белым — от белого "
                     "палитра розовеет) — мета, подписи, зачёркнутая цена")

    # Порядок для человека — как в полной палитре, не как посчиталось.
    выведено.sort(key=lambda з: ПОЛНАЯ_ПАЛИТРА.index(з["ключ"]))
    не_вывелось.sort(key=lambda з: ПОЛНАЯ_ПАЛИТРА.index(з["ключ"]))
    спросить.sort(key=lambda з: ПОЛНАЯ_ПАЛИТРА.index(з["ключ"])
                  if з["ключ"] in ПОЛНАЯ_ПАЛИТРА else 99)

    return {
        "полная": полная,
        "выведено": выведено,
        "не_вывелось": не_вывелось,
        "нужно_спросить": спросить,
        "укомплектована": not спросить,
    }


# ── Один и тот же вердикт о неполном профиле — всем шагам, а не только последнему ─────────
#
# Задача 4 (отчуждаемость). Вопрос «какой у вас тёмный фон» система задавала дважды: в
# `профиль.py --проверить` (куда заходят не все) и в `проверить.py` — на самом последнем шаге,
# когда сайт уже собран и показан. Между ними — `проверить_прототип.py`, `витрина.py`,
# `обложки.py` и `собрать.py`, которые молчали и собирали на бедной палитре: человек, дойдя до
# сборки, подставлял цвет наугад, и переделывать приходилось всё. Текст вердикта один на всю
# систему и живёт здесь, рядом с `добрать_палитру`, которая его и считает, — не четырьмя копиями
# по скриптам, каждая со своими словами.
#
# ⛔ Останавливаем только на «вывести не из чего»: то, что система считает сама (второй фон,
# ступени акцента, линия), она и посчитает — `добрать_палитру` возвращает это в «выведено», а не
# в «нужно_спросить», и находки здесь не будет.
# Те же пометки, что ловит проверка собранной страницы (`проверить.МЕТКИ_ПРОТОТИПА`).
# Список повторён, а не импортирован: `профиль.py` лежит ниже по цепочке и про проверку не знает.
МЕТКИ_В_ПРОФИЛЕ = ("[проверить]", "[пример]", "[ПРОПУСК", "[СВЕРИТЬ")

# Семья НБ-4: пометку себе ловят только в квадратных скобках, а у учебных профилей выдуман весь
# текст — и слово «пример» в подписи подвала сторож не поймает никогда. Поэтому учебный профиль
# объявляет себя сам, одним полем `"демо": true`, а не словом внутри текста, который уедет на
# страницу дословно. Тексты таких профилей менять не надо — надо знать, что они учебные.
ДЕМО_ПОЛЕ = "демо"


def это_демо(данные: dict | None) -> bool:
    """Учебный ли это профиль — по полю `демо` в корне profile.json."""
    return bool(данные.get(ДЕМО_ПОЛЕ)) if isinstance(данные, dict) else False


def автор_поле(данные: dict, имя: str) -> str:
    """Поле автора строкой — в валидации их читают до того, как разобран сам раздел."""
    автор = данные.get("автор")
    return str((автор or {}).get(имя) or "") if isinstance(автор, dict) else ""


СЛОВА_НЕУКОМПЛЕКТОВАН = "Профиль не укомплектован для показа"


def находки_по_комплекту(данные: dict | None, имя: str = "") -> list[dict]:
    """🔴 «чего не хватает и как вписать» — или пусто, если палитру удалось добрать самим.

    `данные` — прочитанный `profile.json` (None, если профиля нет: не у каждой работы он есть,
    и молчать здесь честнее, чем выдумывать вердикт); `имя` — имя папки профиля, оно попадает
    в слова находки, чтобы человек знал, какой файл открывать.
    """
    if not isinstance(данные, dict):
        return []
    палитра = данные.get("палитра")
    добор = добрать_палитру(палитра if isinstance(палитра, dict) else {})
    спросить = добор["нужно_спросить"]
    if not спросить:
        return []
    строки = [f"«{з['ключ']}»: {з['почему']}" for з in спросить]
    return [находка(
        ЧИНИТЬ, СЛОВА_НЕУКОМПЛЕКТОВАН,
        строки,
        f"в профиле „{имя}“ не хватает цветов, которые нельзя посчитать самим, — спросите "
        "человека и впишите их в profile.json → палитра, прежде чем показывать сайт людям "
        "(ядро/скрипты/профиль.py --проверить покажет то же самое подробнее)",
    )]


def находки_по_комплекту_папки(папка_профиля: Path | None, данные: dict | None) -> list[dict]:
    """То же самое, но имя берётся из папки профиля — так его знают все зовущие скрипты.

    `собрать._профиль`, а через него `витрина` и `обложки`, возвращают именно папку: она и есть
    `профили/<имя>` (или папка-заготовка рядом с работой), поэтому `имя` из неё честнее, чем
    повторный разбор шапки прототипа.
    """
    return находки_по_комплекту(данные, папка_профиля.name if папка_профиля is not None else "")


# ── Проверка ─────────────────────────────────────────────────────────────────────────────

def валидировать(данные: dict) -> tuple[list[str], list[str]]:
    """Возвращает (ошибки, предупреждения) — обе списками человеческих объяснений."""
    ошибки: list[str] = []
    предупреждения: list[str] = []

    for ключ in ОБЯЗАТЕЛЬНЫЕ_КЛЮЧИ:
        if ключ not in данные:
            ошибки.append(f"в profile.json нет ключа „{ключ}“ — он должен быть на месте, даже пустым")

    палитра = данные.get("палитра")
    if isinstance(палитра, dict):
        for цвет, значение in палитра.items():
            if not HEX.match(str(значение)):
                ошибки.append(
                    f"в палитре цвет „{цвет}“ записан как „{значение}“ — "
                    "нужен вид #RRGGBB, с решёткой"
                )

        # Задача 11: минимальный комплект — не двенадцать независимых полей, а четыре опоры
        # и восемь механических производных (добрать_палитру выше). Что вывели сами — говорим
        # человеку одной строкой; что вывести не из чего (или выбор неоднозначен) — не молчим,
        # а превращаем в ошибку: без этого дальше собирали бы сайт на бедной палитре молча.
        добор = добрать_палитру(палитра)
        for позиция in добор["выведено"]:
            предупреждения.append(
                f"цвет „{позиция['ключ']}“ в палитре не вписан — посчитал сам: {позиция['как']}; "
                "не понравится — впишите свой цвет в profile.json → палитра"
            )
        # Роль, которую не из чего смешать, раньше молчала совсем: про её источник вопрос уже
        # задан выше, и второй раз о том же не спрашивают. Но человек из-за этого не знал, что
        # вместе с одним неназванным цветом не вывелись и ещё две роли, — а сборка их ждёт и
        # ставит 🟡 «Имена переменных расходятся». Теперь называем их поимённо.
        for позиция in добор.get("не_вывелось", []):
            предупреждения.append(
                f"цвет „{позиция['ключ']}“ не вывелся: его смешивают из „{позиция['из']}“, а того "
                "в палитре нет — впишите источник, и эта роль посчитается сама"
            )
        for позиция in добор["нужно_спросить"]:
            хвост = ("" if "впишите" in позиция["почему"] else
                     " — впишите его в profile.json → палитра")
            ошибки.append(
                f"в палитре не хватает цвета „{позиция['ключ']}“, и вывести его самим не "
                f"получилось: {позиция['почему']}{хвост} "
                "(состав минимального комплекта — ядро/дизайн/палитра-и-токены.md § 1)"
            )

    сайт = данные.get("сайт")
    сайт = сайт if isinstance(сайт, dict) else {}

    тип_сайта = str(сайт.get("тип") or "")
    if тип_сайта not in ТИПЫ_САЙТА:
        ошибки.append(f"сайт.тип записан как „{тип_сайта}“ — нужно «визитка», «лендинг» или пусто")

    связь = сайт.get("связь")
    связь = связь if isinstance(связь, dict) else {}
    способ = str(связь.get("способ") or "")
    if способ not in СПОСОБЫ_СВЯЗИ:
        ошибки.append(
            f"сайт.связь.способ записан как „{способ}“ — нужно одно из: "
            "телеграм · max · вк · whatsapp · форма · виджет (или пусто)"
        )

    юр_блок = сайт.get("юр_блок")
    юр_блок = юр_блок if isinstance(юр_блок, dict) else {}
    статус = str(юр_блок.get("статус") or "")
    if статус not in СТАТУСЫ_ЮРЛИЦА:
        ошибки.append(
            f"сайт.юр_блок.статус записан как „{статус}“ — нужно одно из: "
            "физлицо · самозанятый · ИП (или пусто)"
        )

    # НБ-4: поля, которые уезжают на страницу ДОСЛОВНО. Пометка себе в квадратных скобках
    # («ИНН 000000000000 [пример]») попадала в подвал как есть, и на последнем шаге проверка
    # ставила за неё 🔴 «В тексте остались метки прототипа» — в экране, который собран правильно.
    # Два правила системы противоречили друг другу, и выполнить оба было нельзя. Спрашиваем там,
    # где пометку и писали, — в профиле.
    for путь, значение in (("сайт.юр_блок.реквизиты", юр_блок.get("реквизиты")),
                           ("сайт.юр_блок.оферта", юр_блок.get("оферта")),
                           ("подпись_в_подвале", данные.get("подпись_в_подвале")),
                           ("автор.роль", автор_поле(данные, "роль")),
                           ("автор.био", автор_поле(данные, "био"))):
        строка = str(значение or "")
        нашлись = [м for м in МЕТКИ_В_ПРОФИЛЕ if м.lower() in строка.lower()]
        if нашлись:
            предупреждения.append(
                f"{путь} — пометка {', '.join(нашлись)} внутри текста, а это поле уезжает "
                "на страницу дословно: уберите её здесь, иначе проверка собранного сайта "
                "поставит 🔴 за метку прототипа"
                + (" (профиль помечен «демо»: на учебной сборке это ожидаемо, на живой — нет)"
                   if это_демо(данные) else "")
            )

    if это_демо(данные):
        предупреждения.append(
            "профиль помечен «демо»: он учебный — имена, цифры и реквизиты в нём выдуманы. "
            "Собирать на нём можно что угодно, показывать людям — нельзя"
        )

    автор = данные.get("автор")
    автор = автор if isinstance(автор, dict) else {}
    if not str(автор.get("имя") or "").strip():
        предупреждения.append("автор.имя пустое — заполните, когда будет удобно")
    if not тип_сайта.strip():
        предупреждения.append("сайт.тип не выбран — визитка или лендинг")
    if not str(связь.get("адрес") or "").strip():
        предупреждения.append("сайт.связь.адрес пустой — куда будет падать заявка?")
    elif str(связь.get("адрес") or "").strip() in ЗАГЛУШКИ_ШАБЛОНА:
        предупреждения.append("сайт.связь.адрес — значение из шаблона: кнопка связи поведёт в никуда")
    контакты = данные.get("контакты")
    for контакт in контакты if isinstance(контакты, list) else []:
        адрес = str(контакт.get("адрес") or "").strip() if isinstance(контакт, dict) else ""
        if адрес in ЗАГЛУШКИ_ШАБЛОНА:
            предупреждения.append(
                f"контакты: «{контакт.get('название') or 'без названия'}» — адрес «{адрес}» остался "
                "из шаблона: на экран контактов он уедет дословно, мёртвой ссылкой"
            )

    # Задача 11, пункт «шире цвета»: нужной картинки нет — предложить, а не смолчать. Сайт
    # собирается и без неё (картинки.md § 9), но первый экран без лица теряет половину доверия —
    # значит, не ошибка, а предупреждение с прямой подсказкой, что сфотографировать.
    активы = данные.get("активы")
    активы = активы if isinstance(активы, dict) else {}
    for ключ, зачем in (
        ("фото_автора", "фото автора — самое сильное доказательство доверия на первом экране "
                        "и в карточке (ядро/картинки.md § 1); снимка нет — лицо рисуется "
                        "с трёх опорных снимков, раздел «внешность»"),
        ("логотип_на_светлом", "логотип для светлых участков страницы"),
        ("логотип_на_тёмном", "логотип для тёмных участков страницы"),
    ):
        if not str(активы.get(ключ) or "").strip():
            предупреждения.append(
                f"активы.{ключ} не заполнено — {зачем}; без него сайт соберётся, но обойдётся "
                "без этого доказательства"
            )

    # Задача 3: внешность — раздел про ЛИЦО владельца сайта. Он необязателен (сайт собирается и
    # без портрета), но пустым молча не проходит: лицо на первом экране рисуется только с трёх
    # опорных снимков, и узнать об этом человек должен здесь, а не в момент генерации кадра.
    ошибки_внешности, предупреждения_внешности = _проверить_внешность(данные)
    ошибки += ошибки_внешности
    предупреждения += предупреждения_внешности

    return ошибки, предупреждения


# Ровно три: с одного снимка генератор усредняет черты, с трёх лицо перестаёт плыть. Число живёт
# в `портрет.НОРМА_СЕЛФИ` — здесь оно только называется человеку, поэтому импортировать ради него
# весь модуль с картинками не нужно.
НОРМА_СЕЛФИ = 3
ПРО_СЕЛФИ = ("нужны, только если на первом экране будет ваше лицо: три ваших портрета рядом с "
             "profile.json — анфас, вполоборота и с обычной для вас улыбкой. Лицо система берёт "
             "только с них (ядро/профиль.md § 6)")


def _проверить_внешность(данные: dict) -> tuple[list[str], list[str]]:
    """Раздел «внешность»: форма полей и полнота набора снимков. Ошибка — только про форму."""
    ошибки: list[str] = []
    предупреждения: list[str] = []
    раздел = данные.get("внешность")
    if раздел is None:
        return ошибки, предупреждения
    if not isinstance(раздел, dict):
        ошибки.append("внешность записана не разделом — нужен объект с полями "
                      "селфи · телосложение · приметы · одежда · всегда · никогда")
        return ошибки, предупреждения
    for ключ in ("селфи", "всегда", "никогда"):
        if ключ in раздел and not isinstance(раздел[ключ], list):
            ошибки.append(f"внешность.{ключ} записано не списком — нужен список в квадратных скобках")
    снимки = раздел.get("селфи") if isinstance(раздел.get("селфи"), list) else []
    снимки = [str(с).strip() for с in снимки if str(с).strip()]
    if not снимки:
        предупреждения.append(f"внешность.селфи пусто — {ПРО_СЕЛФИ}")
    elif len(снимки) < НОРМА_СЕЛФИ:
        предупреждения.append(
            f"внешность.селфи — снимков {len(снимки)} из {НОРМА_СЕЛФИ}: с одного-двух генератор "
            "усредняет черты и рисует похожего человека, а не вас")
    elif len(снимки) > НОРМА_СЕЛФИ:
        предупреждения.append(
            f"внешность.селфи — снимков {len(снимки)}, в дело пойдут первые {НОРМА_СЕЛФИ}: "
            "остальные сходства не добавляют, а размывают его")
    if снимки and not str(раздел.get("телосложение") or "").strip():
        предупреждения.append(
            "внешность.телосложение пусто — снимки показывают лицо, а фигуру генератор придумает "
            "свою; хватит одной строки словами, ростовое фото образцом не прикладывают")
    return ошибки, предупреждения


def проверить_файл(путь: Path) -> tuple[list[str], list[str]]:
    """Читает profile.json и валидирует — для CLI и для тестов на уровне файла.
    Способ связи «виджет» обещает файл `виджет.html` рядом с профилем: без него `собрать.py`
    поставит на его место кнопку на экран контактов и 🟡. Видно это только с диска, не из данных."""
    путь = Path(путь)
    данные = прочитать_json(путь)
    ошибки, предупреждения = валидировать(данные)
    сайт = данные.get("сайт")
    связь = сайт.get("связь") if isinstance(сайт, dict) else None
    способ = str(связь.get("способ") or "").strip().lower() if isinstance(связь, dict) else ""
    if способ == "виджет" and not (путь.parent / "виджет.html").is_file():
        предупреждения.append(
            f"связь.способ = виджет, а файла профили/{путь.parent.name}/виджет.html нет — "
            "кнопка встанет на его место с 🟡"
        )

    # Путь на файл вписан — а файла на диске нет: узнать это можно только с диска, не из данных
    # (тот же приём, что и с виджетом выше).
    активы = данные.get("активы")
    активы = активы if isinstance(активы, dict) else {}
    for ключ, значение in активы.items():
        значение = str(значение or "").strip()
        if значение and "://" not in значение and not (путь.parent / значение).is_file():
            предупреждения.append(
                f"активы.{ключ} = «{значение}», а файла профили/{путь.parent.name}/{значение} "
                "нет на диске — на сайт он не попадёт"
            )

    # Снимки-образцы — тот же случай: путь вписан, а файла нет. Молча это значит «лицо взялось
    # не с ваших снимков», и увидеть подмену можно будет только на готовом кадре.
    раздел = данные.get("внешность")
    снимки = раздел.get("селфи") if isinstance(раздел, dict) else None
    for снимок in снимки if isinstance(снимки, list) else []:
        снимок = str(снимок or "").strip()
        if снимок and not (путь.parent / снимок).is_file():
            предупреждения.append(
                f"внешность.селфи = «{снимок}», а файла профили/{путь.parent.name}/{снимок} нет "
                "на диске — лицо на кадре получится не ваше"
            )
    return ошибки, предупреждения


# ── CLI ──────────────────────────────────────────────────────────────────────────────────

def _строка_соседа(находка: dict) -> str:
    детали = ", ".join(ч for ч in (находка["автор_имя"], находка["автор_роль"]) if ч)
    хвост = f" ({детали})" if детали else ""
    return f"Рядом нашёл: {находка['система'].name} — профиль „{находка['имя']}“{хвост}"


def _вывести_соседей() -> int:
    находки = найти_соседей()
    if not находки:
        print("Рядом никого не нашлось — соседних систем с профилем нет. Если система тут")
        print("одна, это нормально. Заведите профиль сами: /setup или --новый <имя>.")
        return 0
    for находка in находки:
        print(_строка_соседа(находка))
    print()
    for находка in находки:
        print(f"{находка['путь']}\t{находка['имя']}")
    return 0


def _вывести_список() -> int:
    профили = список_профилей()
    if not профили:
        print("Профилей пока нет. Скажите системе „настрой профиль“ или /setup.")
        return 0
    активный = прочитать_активного()
    print("Профили:")
    for имя in профили:
        пометка = "  ← активный" if имя == активный else ""
        print(f"  {имя}{пометка}")
    return 0


def _вывести_по_умолчанию() -> int:
    _вывести_список()
    профили = список_профилей()
    if not профили:
        return 0
    активный = прочитать_активного()
    print()
    if активный:
        print(f"Активный профиль: „{активный}“.")
    else:
        print("Активный профиль не выбран — переключитесь: профиль.py <имя>.")
    print("Профиль клиента или новая работа — профиль.py --новый <имя> или /setup.")
    return 0


def _выполнить_взять(путь_строка: str, как: str | None) -> int:
    успех, сообщение = взять_профиль(Path(путь_строка), как)
    print(сообщение)
    return 0 if успех else 1


def _выполнить_новый(имя: str) -> int:
    успех, сообщение = новый_профиль(имя)
    print(сообщение)
    return 0 if успех else 1


def _выполнить_активировать(имя: str) -> int:
    успех, сообщение = сделать_активным(имя)
    print(сообщение)
    if not успех:
        print()
        _вывести_список()
        return 1
    return 0


def _выполнить_проверить(имя: str | None) -> int:
    имя = имя or прочитать_активного()
    if not имя:
        # профиль один — молча работаем в нём; несколько — спрашиваем, гадать не будем
        профили = список_профилей()
        if len(профили) == 1:
            имя = профили[0]
            print(f"Профиль в системе один — проверяю его: „{имя}“.")
        else:
            print("Нет активного профиля и имя не названо. Сначала: --новый <имя> или /setup.")
            return 1
    путь = ПРОФИЛИ / имя / "profile.json"
    if not путь.exists():
        print(f"Профиля „{имя}“ нет. Список — профиль.py --список.")
        return 1

    try:
        ошибки, предупреждения = проверить_файл(путь)
    except ОшибкаПрофиля as ошибка:
        print(f"⛔ {ошибка}")
        return 1

    for предупреждение in предупреждения:
        print(f"⚠️ {предупреждение}")

    if ошибки:
        if предупреждения:
            print()
        print(f"⛔ В профиле „{имя}“ есть, что поправить:\n")
        for ошибка in ошибки:
            print(f"   - {ошибка}")
        print("\nПоправьте profile.json и запустите проверку снова.")
        return 1

    print(f"✅ Профиль „{имя}“ в порядке.")
    return 0


def построить_парсер() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(description="Профили: свой сайт или сайт клиента")
    p.add_argument("имя", nargs="?", default=None, help="сделать этот профиль активным")
    p.add_argument("--список", action="store_true", help="показать все профили")
    p.add_argument("--соседи", action="store_true", help="поискать профиль в системах рядом")
    p.add_argument("--взять", metavar="ПУТЬ",
                   help="скопировать профиль из указанной папки и сделать его активным")
    p.add_argument("--как", metavar="ИМЯ", help="имя для профиля из --взять")
    p.add_argument("--новый", metavar="ИМЯ", help="завести пустой профиль из шаблона")
    p.add_argument("--проверить", nargs="?", const="", default=None, metavar="ИМЯ",
                   help="проверить активный профиль (или названный по имени)")
    return p


def main() -> int:
    a = построить_парсер().parse_args()

    if a.соседи:
        return _вывести_соседей()
    if a.взять:
        return _выполнить_взять(a.взять, a.как)
    if a.новый:
        return _выполнить_новый(a.новый)
    if a.проверить is not None:
        return _выполнить_проверить(a.проверить or None)
    if a.список:
        return _вывести_список()
    if a.имя:
        return _выполнить_активировать(a.имя)
    return _вывести_по_умолчанию()


if __name__ == "__main__":
    sys.exit(main())
