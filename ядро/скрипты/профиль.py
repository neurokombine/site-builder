"""Профили: чей это сайт — свой или клиента, каким голосом, чем отвечаем по закону.

Профиль — это `профили/<имя>/profile.json`: имя, роль, цвета, шрифты, логотип, фото, контакты,
подпись в подвал, а с этой задачи ещё и секция «сайт» (тип, адрес, куда падает заявка,
юридический статус, чего говорить нельзя). Формат общий с Сборщиком документов — специально,
чтобы профиль можно было унаследовать, а не заводить заново.

Запуск:
    .venv/bin/python ядро/скрипты/профиль.py                       # список + кто активный
    .venv/bin/python ядро/скрипты/профиль.py --список
    .venv/bin/python ядро/скрипты/профиль.py --соседи               # поискать профиль рядом
    .venv/bin/python ядро/скрипты/профиль.py --взять <путь> [--как <имя>]
    .venv/bin/python ядро/скрипты/профиль.py --новый <имя>
    .venv/bin/python ядро/скрипты/профиль.py <имя>                  # сделать активным
    .venv/bin/python ядро/скрипты/профиль.py --проверить [имя]
"""
from __future__ import annotations

import argparse
import json
import re
import shutil
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent.parent
ПРОФИЛИ = КОРЕНЬ / "профили"
АКТИВНЫЙ = ПРОФИЛИ / "_активный"
ШАБЛОН = ПРОФИЛИ / "_шаблон" / "profile.json"

# Папки, в которые не заглядываем при поиске соседей: не профили, а мусор или чужой код —
# заглянуть внутрь них при поиске «профили/<имя>/profile.json» и долго, и без толку.
ПРОПУСКАЕМ = {".git", ".venv", "node_modules", "__pycache__", ".cache", ".DS_Store"}

HEX = re.compile(r"^#[0-9a-fA-F]{6}$")
ТИПЫ_САЙТА = {"", "визитка", "лендинг"}
СПОСОБЫ_СВЯЗИ = {"", "телеграм", "max", "вк", "whatsapp", "форма", "виджет"}
СТАТУСЫ_ЮРЛИЦА = {"", "физлицо", "самозанятый", "ИП"}
ОБЯЗАТЕЛЬНЫЕ_КЛЮЧИ = [
    "профиль", "название", "автор", "контакты", "палитра", "шрифты", "активы",
    "подпись_в_подвале", "сайт",
]


# Имя профиля становится именем папки внутри `профили/` — и потому его нельзя брать как есть.
СЛОВА_ОБ_ИМЕНИ = ("В имени профиля — только буквы, цифры, дефис и пробел; "
                  "без косых черт и без подчёркивания в начале.")


class ОшибкаПрофиля(Exception):
    """Профиль не читается или не проходит проверку — сообщение уже человеческое."""


def имя_допустимо(имя: str | None) -> str | None:
    """Годится ли это в имя профиля. Ничего не нашли — None; нашли — фраза человеку.

    ⛔ Имя профиля — это имя папки, а не подпись. Косая черта уводит профиль в подпапку,
    которой `--список` не покажет; две точки уводят его ВЫШЕ папки `профили/` — а туда не
    достаёт `.gitignore`, и контакты клиента уезжают наружу первым же сохранением версии.
    Подчёркивание и точка в начале заняты служебным (`_шаблон`, `_активный`, скрытые файлы).
    """
    имя = (имя or "").strip()
    if not имя:
        return "Имя профиля не названо. " + СЛОВА_ОБ_ИМЕНИ
    if имя == "_шаблон":
        return ("«_шаблон» — это образец, из которого заводятся все остальные; "
                "работать в нём нельзя. " + СЛОВА_ОБ_ИМЕНИ)
    if "/" in имя or "\\" in имя or ".." in имя or имя.startswith(("_", ".")):
        return СЛОВА_ОБ_ИМЕНИ
    if not all(знак.isalnum() or знак in "- ." for знак in имя):
        return СЛОВА_ОБ_ИМЕНИ
    return None


# ── Чтение и запись ──────────────────────────────────────────────────────────────────────

def прочитать_json(путь: Path) -> dict:
    try:
        текст = путь.read_text(encoding="utf-8")
    except OSError as ошибка:
        raise ОшибкаПрофиля(f"не получилось прочитать «{путь}»: {ошибка}") from ошибка
    try:
        return json.loads(текст)
    except json.JSONDecodeError as ошибка:
        raise ОшибкаПрофиля(
            f"файл «{путь.name}» повреждён — не читается как JSON ({ошибка})"
        ) from ошибка


def записать_json(путь: Path, данные: dict) -> None:
    путь.write_text(json.dumps(данные, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


# ── Список и активный профиль ────────────────────────────────────────────────────────────

def список_профилей(папка_профилей: Path | None = None) -> list[str]:
    """Имена профилей (без служебных `_*`), у которых на месте profile.json."""
    папка = папка_профилей or ПРОФИЛИ
    if not папка.exists():
        return []
    return sorted(
        д.name for д in папка.iterdir()
        if д.is_dir() and not д.name.startswith("_") and (д / "profile.json").exists()
    )


def прочитать_активного(папка_профилей: Path | None = None) -> str | None:
    """Имя активного профиля. Указатель ведёт в никуда — считаем, что активного нет.

    Папку профиля переименовывают и удаляют руками, а указатель об этом не знает. Падать из-за
    этого нельзя: работа встанет на ровном месте — говорим вслух и работаем дальше.
    """
    папка = папка_профилей or ПРОФИЛИ
    файл = папка / "_активный"
    if not файл.exists():
        return None
    имя = файл.read_text(encoding="utf-8").strip()
    if not имя:
        return None
    if not (папка / имя / "profile.json").exists():
        print(f"⚠️ Активным был профиль „{имя}“, но его папки больше нет — считаю, "
              "что активного профиля нет.")
        return None
    return имя


def записать_активного(имя: str, папка_профилей: Path | None = None) -> None:
    папка = папка_профилей or ПРОФИЛИ
    папка.mkdir(parents=True, exist_ok=True)
    (папка / "_активный").write_text(имя, encoding="utf-8")


def сделать_активным(имя: str, папка_профилей: Path | None = None) -> tuple[bool, str]:
    беда = имя_допустимо(имя)
    if беда:
        return False, беда
    имя = имя.strip()
    папка = папка_профилей or ПРОФИЛИ
    if имя not in список_профилей(папка):
        return False, f"Профиля „{имя}“ нет."
    записать_активного(имя, папка)
    return True, f"Работаем в профиле „{имя}“."


# ── Соседи ────────────────────────────────────────────────────────────────────────────────

def найти_соседей(корень: Path | None = None) -> list[dict]:
    """Ищет системы-соседи с профилями: папки-сёстры корня и их подпапки глубиной 1.

    Соседями считаем не по имени папки (у ученика Сборщик документов может называться как
    угодно), а по структуре: `<кандидат>/профили/<имя>/profile.json`.
    """
    свой_корень = корень or КОРЕНЬ
    родитель = свой_корень.parent
    находки: list[dict] = []
    if not родитель.exists():
        return находки

    try:
        сёстры = [
            п for п in родитель.iterdir()
            if п.is_dir() and п.name not in ПРОПУСКАЕМ and not п.name.startswith(".")
            and п.resolve() != свой_корень.resolve()
        ]
    except OSError:
        return находки

    кандидаты: list[Path] = []
    for сестра in сёстры:
        кандидаты.append(сестра)
        try:
            for вложенная in сестра.iterdir():
                if вложенная.is_dir() and вложенная.name not in ПРОПУСКАЕМ \
                        and not вложенная.name.startswith("."):
                    кандидаты.append(вложенная)
        except OSError:
            continue

    for кандидат in кандидаты:
        папка_профилей = кандидат / "профили"
        if not папка_профилей.is_dir():
            continue
        try:
            подпапки = sorted(папка_профилей.iterdir())
        except OSError:
            continue
        for подпапка in подпапки:
            if not подпапка.is_dir() or подпапка.name.startswith("_"):
                continue
            файл_профиля = подпапка / "profile.json"
            if not файл_профиля.exists():
                continue
            try:
                данные = прочитать_json(файл_профиля)
            except ОшибкаПрофиля:
                данные = {}
            автор = данные.get("автор") if isinstance(данные, dict) else None
            автор = автор if isinstance(автор, dict) else {}
            находки.append({
                "система": кандидат,
                "имя": подпапка.name,
                "путь": подпапка,
                "автор_имя": str(автор.get("имя") or "").strip(),
                "автор_роль": str(автор.get("роль") or "").strip(),
            })
    return находки


# ── Взять и завести ──────────────────────────────────────────────────────────────────────

def взять_профиль(
    источник: Path,
    имя: str | None = None,
    папка_профилей: Path | None = None,
    шаблон: Path | None = None,
) -> tuple[bool, str]:
    """Копирует profile.json (и активы/, если есть) из чужой папки профиля к нам.

    Отсутствующие ключи добираем из шаблона (секцию «сайт» и служебные подсказки) — старые
    поля источника не трогаем. `унаследован_из` всегда переписываем на реальный путь источника.
    """
    источник = Path(источник).expanduser().resolve()
    файл_источника = источник / "profile.json"
    if not файл_источника.exists():
        return False, f"В «{источник}» нет profile.json — это не папка профиля."

    имя = имя or источник.name
    беда = имя_допустимо(имя)
    if беда:
        return False, беда
    имя = имя.strip()
    папка = папка_профилей or ПРОФИЛИ
    целевая = папка / имя
    if целевая.exists():
        return False, (
            f"Профиль „{имя}“ уже есть — не перезаписываю его. "
            "Другое имя — флагом --как <имя>."
        )

    try:
        данные = прочитать_json(файл_источника)
    except ОшибкаПрофиля as ошибка:
        return False, f"Не получилось прочитать профиль-источник: {ошибка}"

    путь_шаблона = шаблон or ШАБЛОН
    if путь_шаблона.exists():
        try:
            шаблонные_данные = прочитать_json(путь_шаблона)
        except ОшибкаПрофиля:
            шаблонные_данные = {}
    else:
        шаблонные_данные = {}
    for ключ, значение in шаблонные_данные.items():
        данные.setdefault(ключ, значение)
    данные["унаследован_из"] = str(источник)

    целевая.mkdir(parents=True)
    записать_json(целевая / "profile.json", данные)

    активы_источника = источник / "активы"
    if активы_источника.is_dir():
        shutil.copytree(активы_источника, целевая / "активы")

    записать_активного(имя, папка)
    return True, f"Взял профиль „{имя}“ из {источник}. Запишите в журнал сайта, откуда он."


def новый_профиль(
    имя: str,
    папка_профилей: Path | None = None,
    шаблон: Path | None = None,
) -> tuple[bool, str]:
    """Заводит пустой профиль из шаблона и делает его активным."""
    беда = имя_допустимо(имя)
    if беда:
        return False, беда
    имя = имя.strip()
    папка = папка_профилей or ПРОФИЛИ
    целевая = папка / имя
    if целевая.exists():
        return False, f"Профиль „{имя}“ уже есть — не перезаписываю его."

    путь_шаблона = шаблон or ШАБЛОН
    if not путь_шаблона.exists():
        return False, "Не нашёл шаблон профиля — профили/_шаблон/profile.json пропал."
    try:
        данные = прочитать_json(путь_шаблона)
    except ОшибкаПрофиля as ошибка:
        return False, f"Шаблон профиля повреждён: {ошибка}"
    данные["профиль"] = имя

    целевая.mkdir(parents=True)
    записать_json(целевая / "profile.json", данные)
    записать_активного(имя, папка)
    return True, f"Завёл новый профиль „{имя}“ — пустой, из шаблона. Теперь он активный."


# ── Проверка ─────────────────────────────────────────────────────────────────────────────

def валидировать(данные: dict) -> tuple[list[str], list[str]]:
    """Возвращает (ошибки, предупреждения) — обе списками человеческих объяснений."""
    ошибки: list[str] = []
    предупреждения: list[str] = []

    for ключ in ОБЯЗАТЕЛЬНЫЕ_КЛЮЧИ:
        if ключ not in данные:
            ошибки.append(f"в profile.json нет ключа „{ключ}“ — он должен быть на месте, даже пустым")

    палитра = данные.get("палитра")
    if isinstance(палитра, dict):
        for цвет, значение in палитра.items():
            if not HEX.match(str(значение)):
                ошибки.append(
                    f"в палитре цвет „{цвет}“ записан как „{значение}“ — "
                    "нужен вид #RRGGBB, с решёткой"
                )

    сайт = данные.get("сайт")
    сайт = сайт if isinstance(сайт, dict) else {}

    тип_сайта = str(сайт.get("тип") or "")
    if тип_сайта not in ТИПЫ_САЙТА:
        ошибки.append(f"сайт.тип записан как „{тип_сайта}“ — нужно «визитка», «лендинг» или пусто")

    связь = сайт.get("связь")
    связь = связь if isinstance(связь, dict) else {}
    способ = str(связь.get("способ") or "")
    if способ not in СПОСОБЫ_СВЯЗИ:
        ошибки.append(
            f"сайт.связь.способ записан как „{способ}“ — нужно одно из: "
            "телеграм · max · вк · whatsapp · форма · виджет (или пусто)"
        )

    юр_блок = сайт.get("юр_блок")
    юр_блок = юр_блок if isinstance(юр_блок, dict) else {}
    статус = str(юр_блок.get("статус") or "")
    if статус not in СТАТУСЫ_ЮРЛИЦА:
        ошибки.append(
            f"сайт.юр_блок.статус записан как „{статус}“ — нужно одно из: "
            "физлицо · самозанятый · ИП (или пусто)"
        )

    автор = данные.get("автор")
    автор = автор if isinstance(автор, dict) else {}
    if not str(автор.get("имя") or "").strip():
        предупреждения.append("автор.имя пустое — заполните, когда будет удобно")
    if not тип_сайта.strip():
        предупреждения.append("сайт.тип не выбран — визитка или лендинг")
    if not str(связь.get("адрес") or "").strip():
        предупреждения.append("сайт.связь.адрес пустой — куда будет падать заявка?")

    return ошибки, предупреждения


def проверить_файл(путь: Path) -> tuple[list[str], list[str]]:
    """Читает profile.json и валидирует — для CLI и для тестов на уровне файла."""
    данные = прочитать_json(путь)
    return валидировать(данные)


# ── CLI ──────────────────────────────────────────────────────────────────────────────────

def _строка_соседа(находка: dict) -> str:
    детали = ", ".join(ч for ч in (находка["автор_имя"], находка["автор_роль"]) if ч)
    хвост = f" ({детали})" if детали else ""
    return f"Рядом нашёл: {находка['система'].name} — профиль „{находка['имя']}“{хвост}"


def _вывести_соседей() -> int:
    находки = найти_соседей()
    if not находки:
        print("Рядом никого не нашлось — соседних систем с профилем нет. Если система тут")
        print("одна, это нормально. Заведите профиль сами: /setup или --новый <имя>.")
        return 0
    for находка in находки:
        print(_строка_соседа(находка))
    print()
    for находка in находки:
        print(f"{находка['путь']}\t{находка['имя']}")
    return 0


def _вывести_список() -> int:
    профили = список_профилей()
    if not профили:
        print("Профилей пока нет. Скажите системе „настрой профиль“ или /setup.")
        return 0
    активный = прочитать_активного()
    print("Профили:")
    for имя in профили:
        пометка = "  ← активный" if имя == активный else ""
        print(f"  {имя}{пометка}")
    return 0


def _вывести_по_умолчанию() -> int:
    _вывести_список()
    профили = список_профилей()
    if not профили:
        return 0
    активный = прочитать_активного()
    print()
    if активный:
        print(f"Активный профиль: „{активный}“.")
    else:
        print("Активный профиль не выбран — переключитесь: профиль.py <имя>.")
    print("Профиль клиента или новая работа — профиль.py --новый <имя> или /setup.")
    return 0


def _выполнить_взять(путь_строка: str, как: str | None) -> int:
    успех, сообщение = взять_профиль(Path(путь_строка), как)
    print(сообщение)
    return 0 if успех else 1


def _выполнить_новый(имя: str) -> int:
    успех, сообщение = новый_профиль(имя)
    print(сообщение)
    return 0 if успех else 1


def _выполнить_активировать(имя: str) -> int:
    успех, сообщение = сделать_активным(имя)
    print(сообщение)
    if not успех:
        print()
        _вывести_список()
        return 1
    return 0


def _выполнить_проверить(имя: str | None) -> int:
    имя = имя or прочитать_активного()
    if not имя:
        # профиль один — молча работаем в нём; несколько — спрашиваем, гадать не будем
        профили = список_профилей()
        if len(профили) == 1:
            имя = профили[0]
            print(f"Профиль в системе один — проверяю его: „{имя}“.")
        else:
            print("Нет активного профиля и имя не названо. Сначала: --новый <имя> или /setup.")
            return 1
    путь = ПРОФИЛИ / имя / "profile.json"
    if not путь.exists():
        print(f"Профиля „{имя}“ нет. Список — профиль.py --список.")
        return 1

    try:
        ошибки, предупреждения = проверить_файл(путь)
    except ОшибкаПрофиля as ошибка:
        print(f"⛔ {ошибка}")
        return 1

    for предупреждение in предупреждения:
        print(f"⚠️ {предупреждение}")

    if ошибки:
        if предупреждения:
            print()
        print(f"⛔ В профиле „{имя}“ есть, что поправить:\n")
        for ошибка in ошибки:
            print(f"   - {ошибка}")
        print("\nПоправьте profile.json и запустите проверку снова.")
        return 1

    print(f"✅ Профиль „{имя}“ в порядке.")
    return 0


def построить_парсер() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(description="Профили: свой сайт или сайт клиента")
    p.add_argument("имя", nargs="?", default=None, help="сделать этот профиль активным")
    p.add_argument("--список", action="store_true", help="показать все профили")
    p.add_argument("--соседи", action="store_true", help="поискать профиль в системах рядом")
    p.add_argument("--взять", metavar="ПУТЬ",
                   help="скопировать профиль из указанной папки и сделать его активным")
    p.add_argument("--как", metavar="ИМЯ", help="имя для профиля из --взять")
    p.add_argument("--новый", metavar="ИМЯ", help="завести пустой профиль из шаблона")
    p.add_argument("--проверить", nargs="?", const="", default=None, metavar="ИМЯ",
                   help="проверить активный профиль (или названный по имени)")
    return p


def main() -> int:
    a = построить_парсер().parse_args()

    if a.соседи:
        return _вывести_соседей()
    if a.взять:
        return _выполнить_взять(a.взять, a.как)
    if a.новый:
        return _выполнить_новый(a.новый)
    if a.проверить is not None:
        return _выполнить_проверить(a.проверить or None)
    if a.список:
        return _вывести_список()
    if a.имя:
        return _выполнить_активировать(a.имя)
    return _вывести_по_умолчанию()


if __name__ == "__main__":
    sys.exit(main())
