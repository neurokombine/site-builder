def _выполнить_проверить(имя: str | None) -> int:
    имя = имя or прочитать_активного()
    if not имя:
        # профиль один — молча работаем в нём; несколько — спрашиваем, гадать не будем
        профили = список_профилей()
        if len(профили) == 1:
            имя = профили[0]
            print(f"Профиль в системе один — проверяю его: „{имя}“.")
        else:
            print("Нет активного профиля и имя не названо. Сначала: --новый <имя> или /setup.")
            return 1
    путь = ПРОФИЛИ / имя / "profile.json"
    if not путь.exists():
        print(f"Профиля „{имя}“ нет. Список — профиль.py --список.")
        return 1

    try:
        ошибки, предупреждения = проверить_файл(путь)
    except ОшибкаПрофиля as ошибка:
        print(f"⛔ {ошибка}")
        return 1

    for предупреждение in предупреждения:
        print(f"⚠️ {предупреждение}")

    if ошибки:
        if предупреждения:
            print()
        print(f"⛔ В профиле „{имя}“ есть, что поправить:\n")
        for ошибка in ошибки:
            print(f"   - {ошибка}")
        print("\nПоправьте profile.json и запустите проверку снова.")
        return 1

    print(f"✅ Профиль „{имя}“ в порядке.")
    return 0


