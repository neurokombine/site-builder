def папка_набора(пресет: str) -> Path:
    """Папка рецептов набора; чужой или пустой пресет — визитка (нормализация одна на витрину и обложки). Имя папки = пресет."""
    return собрать.БЛОКИ / витрина.набор(пресет)


def схемы_набора(пресет: str) -> list[str]:
    """Схемы, у которых в наборе есть рецепт, в порядке собрать.СХЕМЫ; чужой пресет — визитка.
    «Разворот-слева» — не отдельный рецепт (задача 6): вставляется сразу за «разворот», рендерится
    тем же файлом `01-первый-экран-разворот.html` с принудительной стороной, см. `_файл_рецепта`."""
    папка = папка_набора(пресет)
    схемы = [с for с in собрать.СХЕМЫ if (папка / f"01-первый-экран-{с}.html").is_file()]
    if "разворот" in схемы:
        схемы.insert(схемы.index("разворот") + 1, "разворот-слева")
    return схемы


def _файл_рецепта(папка: Path, схема: str) -> Path:
    """Путь к рецепту первого экрана; «разворот-слева» читает тот же файл, что и «разворот»."""
    return папка / f"01-первый-экран-{'разворот' if схема == 'разворот-слева' else схема}.html"


def _первый(файлы: list[Path], подсказки: tuple) -> Path | None:
    for подсказка in подсказки:
        for ф in файлы:
            if подсказка in ф.stem:
                return ф
    return None


def _лицо(файл: Path) -> str:
    """Точка лица строкой для data-лицо; svg и битый файл — умолчание (Pillow их не откроет)."""
    try:
        return "%d,%d" % обложка.фокус(файл)
    except (OSError, ValueError):
        return "%d,%d" % обложка.ФОКУС_ФОТО


def _рядом(папка: Path, основа: str, суффикс: str) -> str:
    """Имя файла `<основа><суффикс>.*` в папке, если есть (постер, телефонный кроп)."""
    найдено = sorted(папка.glob(основа + суффикс + ".*")) if папка.is_dir() else []
    return найдено[0].name if найдено else ""


