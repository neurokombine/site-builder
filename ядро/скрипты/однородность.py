def папка_сайта(аргумент: str) -> Path | None:
    """Папка работы (`сайты/моё-дело`) или сама папка сайта — берём ту, где лежит `index.html`."""
    путь = Path(аргумент).expanduser()
    for кандидат in (путь, путь / "сайт"):
        if (кандидат / "index.html").is_file():
            return кандидат
    return None


def посмотреть(папка: Path, браузер=None) -> tuple[list[dict], list[dict]]:
    """Собранная страница → находки и сводка. Папка отдаётся локальным сервером — так пути,
    шрифты и адреса ведут себя как на хостинге."""
    import проверить   # noqa: PLC0415 — `проверить.py` импортирует этот модуль, круг замкнулся бы

    if браузер is None:
        from playwright.sync_api import sync_playwright

        with sync_playwright() as движок:
            свой = глаза.запустить_браузер(движок)
            try:
                return посмотреть(папка, свой)
            finally:
                свой.close()
    with проверить.локальный_сервер(папка) as адрес:
        секции = снять(браузер, адрес)
    return находки(секции, палитра_страницы(папка)), сводка(секции)


def main() -> int:
    вывод_в_utf8()
    разбор = argparse.ArgumentParser(
        description="Однородность собранной страницы: читается ли она как одна вещь.")
    разбор.add_argument("сайт", help="папка работы (сайты/<имя>) или сама папка с index.html")
    аргументы = разбор.parse_args()

    папка = папка_сайта(аргументы.сайт)
    if папка is None:
        print(f"\n⛔ Не нашёл собранной страницы: жду папку с index.html или папку работы, "
              f"внутри которой лежит «сайт».\n   Дали: {аргументы.сайт}\n")
        return 2

    print(f"Смотрю однородность: {папка}")
    try:
        найденное, чем_держится = посмотреть(папка)
    except Exception as ошибка:                  # noqa: BLE001 — сказать словами, а не трассировкой
        print(f"\n⛔ Не удалось посмотреть страницу: {type(ошибка).__name__}: {ошибка}")
        print("   Проверьте установку: .venv/bin/python ядро/скрипты/selftest.py\n")
        return 1

    print("\n## Что держит страницу вместе\n")
    for строка in чем_держится:
        print(f"- {строка}")
    print("\n".join(строки_по_уровням(найденное, заголовки_уровней("показа"))))
    print("\nПоследнее слово — за глазами: откройте длинные снимки обоих размеров.\n")
    return код_выхода(найденное)


