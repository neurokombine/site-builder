def снять(браузер, адрес: str) -> list[dict]:
    """Вычисленные стили всех секций страницы — одним заходом. Свой контекст, «компьютер».

    Замер не имеет права уронить проверку: страница не открылась или JS не отработал — возвращаем
    пустой список, и критик молча ничего не говорит. Про саму неоткрывшуюся страницу скажет
    `проверить.py` — там это отдельная находка, и второй раз её повторять незачем.
    """
    контекст = глаза.контекст(браузер, "компьютер")
    страница = контекст.new_page()
    try:
        страница.goto(адрес, wait_until="load", timeout=глаза.ТАЙМАУТ_ЗАГРУЗКИ_МС)
        try:
            страница.evaluate("document.fonts.ready.then(() => true)")
        except Exception:        # noqa: BLE001 — шрифты не дождались: кегли и гарнитуры мерим как есть
            pass
        return страница.evaluate(ЗАМЕР_JS)
    except Exception:            # noqa: BLE001 — см. docstring
        return []
    finally:
        контекст.close()


