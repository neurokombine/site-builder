# ── Правила: чистые функции над замером ───────────────────────────────────────────────────

def _имя(номер: int, секция: dict) -> str:
    """«экран 4 («решение»)» — номером экрана из его `id` (это адрес, по которому чинят),
    а тип подсказывает, какой это экран. `id` не разобрался — считаем по порядку."""
    ид = (секция.get("id") or "").strip()
    цифры = re.search(r"(\d+)", ид)
    свой = int(цифры.group(1)) if цифры else номер
    тип = (секция.get("тип") or "").strip()
    return f"экран {свой}" + (f" («{тип}»)" if тип else "")


def _разобрать(цвет: str | None) -> tuple[int, int, int] | None:
    цвет = (цвет or "").strip()
    if not HEX_ЦВЕТ.match(цвет):
        return None
    return tuple(int(цвет[и:и + 2], 16) for и in (1, 3, 5))


def _расстояние(первый, второй) -> int:
    return sum(abs(а - б) for а, б in zip(первый, второй))


def _поверх(цвет, альфа: float, фон) -> tuple[float, float, float]:
    """Полупрозрачный цвет, легший на фон, — то, что в этом месте видит человек."""
    return tuple(с * альфа + ф * (1 - альфа) for с, ф in zip(цвет, фон))


def _ближайший(цвет, палитра: dict[str, str]) -> tuple[str, str, int] | None:
    """Ближайший токен палитры к этому цвету — чтобы находка говорила, чем его заменить."""
    рядом = None
    for имя, значение in палитра.items():
        цель = _разобрать(значение)
        if цель is None:
            continue
        расстояние = _расстояние(цвет, цель)
        if рядом is None or расстояние < рядом[2]:
            рядом = (имя, значение, расстояние)
    return рядом


def _в_палитре(запись: dict, фон_секции: str, палитра: dict[str, str]) -> bool:
    """Цвет считается «из палитры», если он сходится с каким-то токеном в пределах допуска.

    При альфе меньше единицы сравниваем не сам цвет, а то, что видно: цвет, легший на фон секции
    (и на общий `--цвет-фон`). Полупрозрачная плёнка чужого цвета в 5 % от глаза не отличается от
    такой же плёнки своего — и находкой быть не должна.
    """
    цвет = _разобрать(запись.get("цвет"))
    if цвет is None:
        return True
    цели = [ц for ц in (_разобрать(з) for з in палитра.values()) if ц is not None]
    if not цели:
        return True                       # палитры не добыли — находок про неё не выдумываем
    if any(_расстояние(цвет, цель) <= ДОПУСК_ЦВЕТА for цель in цели):
        return True
    альфа = float(запись.get("альфа") or 1)
    if альфа >= 1:
        return False
    фоны = [ф for ф in (_разобрать(фон_секции), _разобрать(палитра.get("--цвет-фон"))) if ф]
    свой_на = [_поверх(цвет, альфа, ф) for ф in фоны]
    return any(_расстояние(свой, _поверх(цель, альфа, ф)) <= ДОПУСК_ЦВЕТА
               for свой, ф in zip(свой_на, фоны) for цель in цели)


def _мода(значения) -> float | None:
    """Самое частое значение; при равенстве — то, что встретилось раньше."""
    значения = list(значения)
    return Counter(значения).most_common(1)[0][0] if значения else None


def _шрифты(секции: list[dict]) -> list[str]:
    семьи: list[str] = []
    for секция in секции:
        for имя in секция.get("шрифты") or []:
            if имя and имя not in семьи:
                семьи.append(имя)
    if len(семьи) <= ГАРНИТУР_НА_СТРАНИЦЕ:
        return []
    лишние = семьи[ГАРНИТУР_НА_СТРАНИЦЕ:]
    строки = [f"гарнитур на странице {len(семьи)}: " + ", ".join(семьи)]
    for номер, секция in enumerate(секции, start=1):
        свои = [имя for имя in секция.get("шрифты") or [] if имя in лишние]
        if свои:
            строки.append(f"{_имя(номер, секция)}: " + ", ".join(f"«{и}»" for и in свои))
    return строки


def _кегли(секции: list[dict]) -> list[str]:
    шкала = [(н, с) for н, с in enumerate(секции, start=1)
             if (с.get("тип") or "") not in ВНЕ_ШКАЛЫ]
    строки = []
    for тег, слово in (("h2", "заголовок"), ("p", "текст")):
        замеры = [(н, с, (с.get("кегли") or {}).get(тег)) for н, с in шкала]
        замеры = [(н, с, з) for н, с, з in замеры if isinstance(з, (int, float)) and з > 0]
        if len(замеры) < 2:
            continue
        мода = _мода(round(з) for _, _, з in замеры)
        строки += [f"{_имя(н, с)}: {слово} {з:g} px при {мода:g} на остальных"
                   for н, с, з in замеры if abs(з - мода) > ШАГ_КЕГЛЯ]
    return строки


def _радиусы(секции: list[dict]) -> list[str]:
    """Разнобой скруглений — внутри одного вида карточек, а не по странице разом.

    Разные виды карточек система нарочно скругляет по-разному: `--радиус-карточки` у карточки,
    `--радиус-плитки` у плитки, `--радиус-модуля` у модуля и работы. Страница, где карточки 18,
    а плитки 22, — замысел, и ругаться на неё нельзя. А вот две плитки с разным скруглением —
    разнобой, и находка называет вид словом: «скругление плиток 22 при 18 на остальных».
    Кнопка вида не имеет: она на странице одна и та же от первого экрана до последнего.
    """
    def перечень(места, порог: int, слово: str) -> list[str]:
        значения = {э["радиус"] for _, _, э in места}
        if len(значения) <= порог:
            return []
        мода = _мода(э["радиус"] for _, _, э in места)
        видели, строки = set(), []
        for н, с, э in места:
            if э["радиус"] == мода or (н, э["радиус"]) in видели:
                continue
            видели.add((н, э["радиус"]))
            строки.append(f"{_имя(н, с)}: скругление {слово} {э['радиус']:g} при {мода:g} на остальных")
        return строки

    def замеры(ключ: str):
        return [(н, с, э) for н, с in enumerate(секции, start=1)
                for э in (с.get(ключ) or []) if isinstance(э.get("радиус"), (int, float))]

    карточки = замеры("карточки")
    строки = []
    for вид in dict.fromkeys(э.get("вид") or "" for _, _, э in карточки):
        свои = [м for м in карточки if (м[2].get("вид") or "") == вид]
        строки += перечень(свои, РАЗНЫХ_РАДИУСОВ_ВИДА, СЛОВО_ВИДА.get(вид, "карточек"))
    return строки + перечень(замеры("кнопки"), РАЗНЫХ_РАДИУСОВ_КНОПОК, "кнопки")


def _тени(секции: list[dict]) -> list[str]:
    места = []
    for номер, секция in enumerate(секции, start=1):
        карточки = секция.get("карточки") or []
        светлота = (профиль.светимость(секция["фон"])
                    if HEX_ЦВЕТ.match(секция.get("фон") or "") else None)
        if not карточки or светлота is None:
            continue
        места.append((номер, секция, светлота,
                      any(к.get("тень") for к in карточки),
                      any(not к.get("тень") for к in карточки)))
    строки = []
    for и, (номер, секция, светлота, с_тенью, без_тени) in enumerate(места):
        for другой, соседняя, чужая_светлота, чужая_тень, чужое_без in места[и + 1:]:
            if abs(светлота - чужая_светлота) >= ШАГ_СВЕТЛОТЫ_ТЕНИ:
                continue
            if с_тенью and чужое_без:
                строки.append(f"{_имя(номер, секция)}: карточки с тенью, а на "
                              f"{_имя(другой, соседняя)} той же светлоты — без тени")
            elif без_тени and чужая_тень:
                строки.append(f"{_имя(номер, секция)}: карточки без тени, а на "
                              f"{_имя(другой, соседняя)} той же светлоты — с тенью")
    return строки


def _цвета(секции: list[dict], палитра: dict[str, str]) -> list[str]:
    if not палитра:
        return []
    строки, видели = [], set()
    for номер, секция in enumerate(секции, start=1):
        for запись in секция.get("цвета") or []:
            if _в_палитре(запись, секция.get("фон") or "", палитра):
                continue
            цвет = (запись.get("цвет") or "").lower()
            if (номер, цвет) in видели:
                continue
            видели.add((номер, цвет))
            рядом = _ближайший(_разобрать(цвет), палитра)
            чем = f" — ближе всего {рядом[0]} {рядом[1]}" if рядом else ""
            доля = "" if float(запись.get("альфа") or 1) >= 1 else f", прозрачность {запись['альфа']:g}"
            строки.append(f"{_имя(номер, секция)}: {цвет} — {запись.get('что') or 'цвет'} "
                          f"«{запись.get('класс') or ''}»{доля}{чем}")
    return строки


def _кнопки(секции: list[dict]) -> list[str]:
    главные = [(н, с, к) for н, с in enumerate(секции, start=1)
               for к in (с.get("кнопки") or []) if к.get("главная")]
    высоты = [к["высота"] for _, _, к in главные if isinstance(к.get("высота"), (int, float))]
    радиусы = {к["радиус"] for _, _, к in главные if isinstance(к.get("радиус"), (int, float))}
    разъехались = (len(высоты) > 1 and max(высоты) - min(высоты) > РАЗБРОС_ВЫСОТЫ_КНОПКИ) or len(радиусы) > 1
    if not разъехались:
        return []
    return [f"{_имя(н, с)}: главная кнопка {к.get('высота'):g} px высотой, "
            f"скругление {к.get('радиус'):g} px" for н, с, к in главные]


def места(секции: list[dict], палитра: dict[str, str]) -> dict[str, list[str]]:
    """Все шесть правил разом: код правила → места, где оно нарушено."""
    найдено = {
        "однородность-шрифт": _шрифты(секции),
        "однородность-кегль": _кегли(секции),
        "однородность-радиус": _радиусы(секции),
        "однородность-тень": _тени(секции),
        "однородность-цвет": _цвета(секции, палитра),
        "однородность-кнопка": _кнопки(секции),
    }
    return {код: строки for код, строки in найдено.items() if строки}


def находки(секции: list[dict], палитра: dict[str, str] | None = None) -> list[dict]:
    """Замер страницы → находки в одном и том же порядке, какой бы экран их ни принёс."""
    if not секции:
        return []
    найдено = места(секции, палитра or {})
    return [находка(уровень, что, найдено[код][:ПОТОЛОК_СТРОК], чем_грозит)
            for код, уровень, что, чем_грозит in ПРАВИЛА if найдено.get(код)]


def сводка(секции: list[dict]) -> list[str]:
    """Чем страница держится вместе — числами: это граница правки, а не вежливость.
    Верстальщик, которому сказали только про плохое, переделает и хорошее."""
    шрифты = {и for с in секции for и in (с.get("шрифты") or [])}
    заголовки = {(с.get("кегли") or {}).get("h2") for с in секции} - {None}
    карточки = [к for с in секции for к in (с.get("карточки") or [])]
    радиусы = {к.get("радиус") for к in карточки} - {None}
    главных = sum(1 for с in секции for к in (с.get("кнопки") or []) if к.get("главная"))
    своих = sum(1 for с in секции if с.get("своя"))
    return [
        f"экранов на странице {len(секции)}, из них свободной вёрстки {своих}",
        f"гарнитур {len(шрифты)}: " + ", ".join(sorted(шрифты)) if шрифты else "гарнитур не видно",
        f"кеглей заголовка {len(заголовки)}: " + ", ".join(f"{з:g} px" for з in sorted(заголовки))
        if заголовки else "заголовков экранов не видно",
        f"карточек {len(карточки)}, скруглений {len(радиусы)}: "
        + ", ".join(f"{р:g} px" for р in sorted(радиусы)) if карточки else "карточек на странице нет",
        f"главных кнопок {главных}",
    ]


