// Липкая панель телефона дублирует главную кнопку первого экрана. Пока сама кнопка на виду,
// дублировать нечего — панель только режет пополам нижнюю строку в ПЕРВОМ ЖЕ кадре, до всякой
// прокрутки, и это читается как брак (фикс М намерил такое у девяти видов каталога из двадцати
// четырёх). Значит панель спит, пока главная кнопка в окне, и просыпается, когда та ушла из виду.
// ⚠️ Это НЕ «появление при скролле», которое запрещено. Запрет владелицы — про СОДЕРЖАНИЕ страницы:
// текст и блоки не выплывают по мере прокрутки. Здесь не двигается ни одна строка: место под панель
// держит отступ, он стоит ВСЕГДА и от сна панели не меняется, а сама панель прибита к окну, а не к
// потоку. Двигается служебная плашка, подменяющая ушедшую кнопку, — и только она.
// ⛔ Прятать умеет только этот скрипт, а показывать — CSS по умолчанию. Нет JS, нет
// IntersectionObserver, нет главной кнопки на экране — панель видна всегда, ровно как была: на
// телефоне это единственный путь к действию, и потерять его нельзя ни при каких условиях. Это
// жёстче, чем у `очко.js`, где отсутствие JS просто возвращало прежний вид.
(function () {
  var СПИТ = "главная-на-виду";                       // класс на body; правило сна — в стилях
  var кнопка = document.querySelector(".первый-экран__действие .кнопка--главная");
  if (!кнопка || !window.IntersectionObserver) { return; }

  function пометить(на_виду) { document.body.classList.toggle(СПИТ, !!на_виду); }

  // Первый ответ наблюдателя приходит следующим кадром — этого хватило бы на вспышку панели поверх
  // первого экрана. Поэтому начальное состояние ставим сразу, ещё до первой отрисовки.
  var б = кнопка.getBoundingClientRect();
  пометить(б.bottom > 0 && б.top < (window.innerHeight || 0));

  // ⚡ И только СЛЕДУЮЩИМ кадром разрешаем стилям анимировать панель. Без этого переход честно
  // проигрывал уезд при каждой загрузке: по умолчанию панель видна (иначе без JS её было бы не
  // вернуть), а класс сна ложится уже после разбора страницы — зритель успевал увидеть её целиком.
  // Два кадра, а не один: первый отдаёт браузеру начальное положение на отрисовку, второй включает
  // переход, когда «до» и «после» уже совпали. Дальше панель ездит плавно, как и задумано.
  requestAnimationFrame(function () {
    requestAnimationFrame(function () { document.body.classList.add("панель-с-переходом"); });
  });

  new IntersectionObserver(function (записи) {
    пометить(записи[записи.length - 1].isIntersecting);
  }, { threshold: 0 }).observe(кнопка);
})();
