// Кегль — это число, а читается высота строчной буквы («очко»). У гарнитур она расходится в полтора
// раза: те же 17px геометрическим гротеском (Jost, очко .46) выглядят заметно мельче, чем
// гуманистическим (Open Sans, .535), — и человек говорит «на компьютере нечитаемо», хотя вилка
// кеглей у него ровно макетная. Поэтому меряем очко той гарнитуры, которая РЕАЛЬНО применилась в
// браузере зрителя (не той, что заказана: Google Fonts мог не доехать и подставиться системный), и
// поднимаем текстовые кегли до макетной видимой высоты. Гарнитура с крупным очком остаётся на
// макетных числах — вниз не двигаем никогда.
// ⛔ Заголовок, подзаголовок и цифру не трогаем: их кегль держит РАСКЛАДКУ — число строк заголовка и
// долю первого экрана, — а в цифрах строчных букв нет вовсе, очко про них ничего не говорит.
// ⛔ И трогаем только ВЕРХНИЙ конец вилки — компьютер. На телефоне те же 16–17px занимают вчетверо
// большую долю ширины и экран держат в руке, а не на вытянутой: там мелко не было и запаса ширины
// нет — поднимешь кегль, и лид вытолкнет строку доверия из первого окна. Беда живёт на компьютере,
// там поправка и работает; граница — та же, на которой у системы расходятся телефон и компьютер.
// Нет JS — страница остаётся ровно такой, какой была до этой поправки: хуже не делаем.
(function () {
  var ЭТАЛОН = 0.535;                  // очко Open Sans — текстовой гарнитуры утверждённых макетов
  var ПОТОЛОК = 1.2, МЁРТВАЯ = 0.02;   // выше потолка расползается раскладка; ближе к единице не трогаем вовсе
  var КОМПЬЮТЕР = "(min-width: 900px)";
  var ТОКЕНЫ = ["--кегль-текст", "--кегль-лид", "--кегль-мелкий", "--кегль-кикер"];
  var корень = document.documentElement;
  var холст = document.createElement("canvas").getContext("2d");
  var ждём = 0;

  // Ink-высота буквы в сотых долях кегля: не метрика из файла шрифта, а то, что браузер нарисует.
  function мера(буква) { var м = холст.measureText(буква); return (м && м.actualBoundingBoxAscent) || 0; }

  function применить() {
    ждём = 0;
    if (!холст) { return; }
    // Сперва снимаем прошлую поправку — иначе прочитаем её же и умножим второй раз.
    for (var i = 0; i < ТОКЕНЫ.length; i++) { корень.style.removeProperty(ТОКЕНЫ[i]); }
    var стиль = getComputedStyle(корень), стек = стиль.getPropertyValue("--шрифт-текста").trim();
    if (!стек) { return; }
    холст.font = "400 100px " + стек;
    // Кириллическая «х» и латинская «x»: у гарнитуры без кириллицы первая дала бы ноль.
    var очко = Math.max(мера("х"), мера("x")) / 100;
    if (!(очко > 0)) { return; }
    var k = Math.round(Math.min(ПОТОЛОК, Math.max(1, ЭТАЛОН / очко)) * 1000) / 1000;
    if (k - 1 < МЁРТВАЯ || !matchMedia(КОМПЬЮТЕР).matches) { k = 1; }
    корень.setAttribute("data-очко", очко.toFixed(3));      // чтобы проверка могла сказать числа вслух
    корень.setAttribute("data-поправка", k.toFixed(3));
    if (k === 1) { return; }
    for (i = 0; i < ТОКЕНЫ.length; i++) {
      var было = стиль.getPropertyValue(ТОКЕНЫ[i]).trim();
      if (было) { корень.style.setProperty(ТОКЕНЫ[i], "calc((" + было + ") * " + k + ")"); }
    }
  }

  применить();
  // Свой шрифт доехал — меряем уже его, а не системную подмену, которой браузер рисовал до этого.
  if (document.fonts && document.fonts.ready) { document.fonts.ready.then(применить); }
  // Кегли человек вправе переопределить в медиазапросе — после смены ширины перечитываем их заново.
  addEventListener("resize", function () { ждём = ждём || requestAnimationFrame(применить); });
})();
